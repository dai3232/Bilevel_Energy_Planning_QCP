function tests = test_stage_b2c_365day_resume
%TEST_STAGE_B2C_365DAY_RESUME Fast tests for explicit same-run recovery.
tests = functiontests(localfunctions);
end

function setup(testCase)
root = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));
addpath(genpath(fullfile(root,"src")));
temporary = string(tempname);
project = fullfile(temporary,"project");
runRoot = fullfile(project,"runs","B2C_365_RESUME_TEST");
for directory = ["iterations","indices","matrices","checkpoints", ...
        "tests","issues","acceptance","reports"]
    mkdir(fullfile(runRoot,directory));
end
context = make_context(project,runRoot,"B2C_365_RESUME_TEST");
rkkt.artifacts.write_text_utf8(context.effective_config_path, ...
    "stage_id: ""stage_B"""+newline);
manifest = struct("run_id",context.run_id,"stage_id","stage_B", ...
    "status","RUNNING");
rkkt.artifacts.write_json_file(context.run_manifest_path,manifest);
testCase.TestData.temporary = temporary;
testCase.TestData.project = project;
testCase.TestData.context = context;
testCase.TestData.repository = root;
end

function teardown(testCase)
if isfolder(testCase.TestData.temporary)
    rmdir(testCase.TestData.temporary,"s");
end
end

function testExplicitExistingRunDirectoryKeepsIdentity(testCase)
[actual,manifest] = rkkt.artifacts.open_existing_run_context( ...
    testCase.TestData.project,testCase.TestData.context.root,"stage_B");
verifyEqual(testCase,string(actual.run_id),"B2C_365_RESUME_TEST");
verifyEqual(testCase,string(actual.root), ...
    string(testCase.TestData.context.root));
verifyEqual(testCase,string(manifest.status),"RUNNING");
end

function testRunIdOrNestedDirectoryCannotImpersonateExplicitRun(testCase)
verifyError(testCase,@()rkkt.artifacts.open_existing_run_context( ...
    testCase.TestData.project,"B2C_365_RESUME_TEST","stage_B"), ...
    "rkkt:runs:ResumeDirectoryMissing");
nested = fullfile(testCase.TestData.context.root,"checkpoints");
verifyError(testCase,@()rkkt.artifacts.open_existing_run_context( ...
    testCase.TestData.project,nested,"stage_B"), ...
    "rkkt:runs:ResumeDirectoryScope");
end

