    TextType="string",VariableNamingRule="preserve");
manifest.sha256(1) = string(repmat('0',1,64));
rkkt.artifacts.write_table_csv_17g_atomic( ...
    context.checkpoint_manifest_path,manifest);
verifyError(testCase,@()rkkt.artifacts.load_stage_b2c_checkpoint(context), ...
    "stageB2C:checkpoint:Hash");
end

function testB2CCheckpointWriterRejectsTerminalRun(testCase)
