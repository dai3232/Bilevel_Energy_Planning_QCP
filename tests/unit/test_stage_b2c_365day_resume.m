function testResumePreparationBindsConfigInputAndCode(testCase)
context = testCase.TestData.context;
sourceConfig = fullfile(testCase.TestData.project,"config", ...
    "stage_B_2C_365_day_serial_experiment.yaml");
mkdir(fileparts(sourceConfig));
rkkt.artifacts.write_text_utf8(sourceConfig, ...
    "stage_id: ""stage_B"""+newline);
copyfile(sourceConfig,context.effective_config_path,"f");
baseHash = string(repmat('1',1,64));
seriesHash = string(repmat('2',1,64));
inputHashes = table(["基础参数.xlsx";"输入数据.xlsx"], ...
    [baseHash;seriesHash], ...
    'VariableNames',{'fileName','actualSHA256'});
signature = string(repmat('3',1,64));
manifest = jsondecode(fileread(context.run_manifest_path));
manifest.run_purpose = "stage_B_2C_365_day_serial_recursive_ipm_experiment";
manifest.milestone = "B-2C-365-DAY-SERIAL-SUPPLEMENT";
manifest.checkpoint_solver_code_signature = signature;
manifest.time_scope = "days_1_to_365_full_24_hours";
manifest.full_kkt_role = "not_executed_365_day_serial_experiment";
manifest.resume_supported = true;
manifest.experiment_mode = "convergence_run";
manifest.convergence_required = true;
manifest.input_hashes = struct("base_parameters",char(baseHash), ...
    "timeseries",char(seriesHash));
rkkt.artifacts.write_json_file(context.run_manifest_path,manifest);
rkkt.artifacts.write_text_utf8(context.checkpoint_manifest_path,"iteration"+newline);
config = struct("run_purpose",string(manifest.run_purpose), ...
    "full_kkt_role",string(manifest.full_kkt_role));
[actual,~,resumed] = rkkt.artifacts.prepare_stage_b2c_365day_run( ...
    testCase.TestData.project,config,inputHashes,signature, ...
    ResumeRunDirectory=context.root);
verifyTrue(testCase,resumed);
verifyEqual(testCase,string(actual.run_id),string(context.run_id));
verifyError(testCase,@()rkkt.artifacts.prepare_stage_b2c_365day_run( ...
    testCase.TestData.project,config,inputHashes,string(repmat('4',1,64)), ...
    ResumeRunDirectory=context.root), ...
    "stageB2C:day365:ResumeIdentity");
end

function testCheckpointChainMetadataAndRebuiltFingerprint(testCase)
context = testCase.TestData.context;
state0 = make_state(0);
linearization0 = make_linearization(state0,"L0");
metadata0 = make_metadata(0);
record0 = rkkt.artifacts.write_stage_b2c_checkpoint( ...
    context,state0,linearization0,metadata0);
state1 = make_state(1);
linearization1 = make_linearization(state1,"L1");
metadata1 = make_metadata(1);
record1 = rkkt.artifacts.write_stage_b2c_checkpoint( ...
    context,state1,linearization1,metadata1);
verifyEqual(testCase,string(record1.previous_checkpoint_sha256), ...
    string(record0.sha256));
expected = rmfield(metadata1,"iteration");
rebuilt = rkkt.diagnostics.compute_stage_a4_rns1_fingerprint( ...
    linearization1,"linearization");
[checkpoint,selected] = rkkt.artifacts.load_stage_b2c_checkpoint( ...
    context,NaN,ExpectedMetadata=expected, ...
    RebuiltLinearizationFingerprint=rebuilt);
verifyEqual(testCase,double(selected.iteration),1);
verifyEqual(testCase,checkpoint.state,state1);

wrong = expected; wrong.solver_code_signature = repmat('0',1,64);
verifyError(testCase,@()rkkt.artifacts.load_stage_b2c_checkpoint( ...
    context,NaN,ExpectedMetadata=wrong), ...
    "stageB2C:checkpoint:ExpectedMetadata");
verifyError(testCase,@()rkkt.artifacts.load_stage_b2c_checkpoint( ...
    context,NaN,RebuiltLinearizationFingerprint=string(repmat('f',1,64))), ...
    "stageB2C:checkpoint:RebuiltLinearization");
end

function testCheckpointManifestTamperBreaksWholeChain(testCase)
context = testCase.TestData.context;
state = make_state(0);
rkkt.artifacts.write_stage_b2c_checkpoint( ...
    context,state,make_linearization(state,"L0"),make_metadata(0));
