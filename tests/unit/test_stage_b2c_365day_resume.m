function testMatchingOrphanCheckpointIsAdoptedWithoutOverwrite(testCase)
context = testCase.TestData.context;
state = make_state(0);
linearization = make_linearization(state,"L0");
metadata = make_metadata(0);
record = rkkt.artifacts.write_stage_b2c_checkpoint( ...
    context,state,linearization,metadata);
pathValue = fullfile(context.checkpoints_dir,"iteration_000.mat");
before = rkkt.data.compute_sha256_file(pathValue);
delete(context.checkpoint_manifest_path);
adopted = rkkt.artifacts.write_stage_b2c_checkpoint( ...
    context,state,linearization,metadata);
after = rkkt.data.compute_sha256_file(pathValue);
verifyEqual(testCase,after,before);
verifyEqual(testCase,string(adopted.sha256),string(record.sha256));
end

function context = make_context(projectRoot,runRoot,runId)
context = struct("project_root",char(projectRoot), ...
    "runs_root",char(fullfile(projectRoot,"runs")), ...
    "root",char(runRoot),"run_dir",char(runRoot), ...
    "run_id",char(runId),"stage_id","stage_B", ...
    "iterations_dir",char(fullfile(runRoot,"iterations")), ...
    "indices_dir",char(fullfile(runRoot,"indices")), ...
    "matrices_dir",char(fullfile(runRoot,"matrices")), ...
    "checkpoints_dir",char(fullfile(runRoot,"checkpoints")), ...
    "tests_dir",char(fullfile(runRoot,"tests")), ...
    "issues_dir",char(fullfile(runRoot,"issues")), ...
    "acceptance_dir",char(fullfile(runRoot,"acceptance")), ...
    "reports_dir",char(fullfile(runRoot,"reports")), ...
    "run_manifest_path",char(fullfile(runRoot,"run_manifest.json")), ...
    "effective_config_path",char(fullfile(runRoot,"effective_config.yaml")), ...
    "checkpoint_manifest_path",char(fullfile(runRoot,"checkpoints", ...
        "checkpoint_manifest.csv")));
end

function value = make_state(revision)
value = struct("xi",[1;2]+revision,"y",[3;4]+revision, ...
    "l",[5;6]+revision,"z",[7;8]+revision, ...
    "iteration_index",double(revision), ...
    "state_revision",double(revision), ...
    "newton_direction_number",double(revision+1), ...
    "completed_newton_direction_count",double(revision));
end

function value = make_linearization(state,identity)
value = struct("identity",string(identity),"H",sparse(eye(2)), ...
    "A",sparse([1,0]),"G",sparse([0,1]), ...
    "r_eq",0,"r_ineq",0,"r_dual",[0;0],"r_comp",0, ...
    "l",state.l(1),"z",state.z(1),"mu",state.l(1)*state.z(1), ...
    "state",state,"objective",struct("gradient",[1;1]), ...
    "constraints",struct("eq_offset",0,"ineq_offset",0));
end

function value = make_metadata(iteration)
value = struct("iteration",double(iteration), ...
    "git_commit",repmat('a',1,40), ...
    "config_sha256",repmat('b',1,64), ...
    "input_hash_fingerprint",repmat('c',1,64), ...
    "solver_code_signature",repmat('d',1,64), ...
    "recursive_route","all_inequality_daily_joint_final_kkt_residual_gate", ...
    "full_kkt_role","not_executed_365_day_serial_experiment", ...
    "time_scope_type","supplemental_365_day_serial_scope");
end
