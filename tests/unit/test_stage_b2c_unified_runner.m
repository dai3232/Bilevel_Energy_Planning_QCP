function testAcceptedHistoryResumesWithLogicalColumns(testCase)
root = testCase.TestData.root;
temporary = string(tempname);
guard = onCleanup(@()remove_temporary_directory(temporary));
context = make_temporary_context(temporary,root);
settings = rkkt.config.build_stage_b2c_run_settings(root, ...
    DayStart=14,DayEnd=20,MaxIterations=2, ...
    RequireConvergence=false,AuditMode="recursive_only", ...
    ConfigPath=fullfile(root,"config","RUN_PROJECT.yaml"));
config = rkkt.model.build_stage_b2c_runtime_configuration( ...
    root,settings,testCase.TestData.data);
[index,~] = rkkt.cache.load_or_build_stage_b2c_index( ...
    root,testCase.TestData.data,config);
signature = rkkt.artifacts.compute_package_code_signature(root);
first = rkkt.solver.run_stage_b2c_365day_serial_ipm( ...
    testCase.TestData.data,index,config,context, ...
    MaxIterations=1,SolverCodeSignature=signature);
verifyEqual(testCase,first.accepted_iteration_count,1);
resumed = rkkt.solver.run_stage_b2c_365day_serial_ipm( ...
    testCase.TestData.data,index,config,context, ...
    MaxIterations=2,Resume=true,SolverCodeSignature=signature);
verifyEqual(testCase,resumed.accepted_iteration_count,2);
verifyTrue(testCase,islogical(resumed.iteration_history.converged));
verifyTrue(testCase,islogical( ...
    resumed.factorization_history.solution_finite));
verifyTrue(testCase,islogical( ...
    resumed.water_correction_history.strictly_positive));
verifyTrue(testCase,all( ...
    resumed.water_correction_history.strictly_positive));
clear guard
remove_temporary_directory(temporary);
end

