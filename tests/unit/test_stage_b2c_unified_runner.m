function testDailyJointStructureTemplateIsReusedWithScanDisabled(testCase)
root = testCase.TestData.root;
settings = make_settings(root,14,20,"recursive_only");
config = rkkt.model.build_stage_b2c_runtime_configuration( ...
    root,settings,testCase.TestData.data);
[index,~] = rkkt.cache.load_or_build_stage_b2c_index( ...
    root,testCase.TestData.data,config);
state = rkkt.model.initialize_stage_b2c_state( ...
    testCase.TestData.data,index,config);
lin = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
    state,testCase.TestData.data,index,config,"B-2C-STRUCTURE-UNIT-TEST");
template = rkkt.solver.build_stage_b2c_daily_joint_structure_template(lin);
direction = rkkt.solver.solve_stage_b2c_daily_joint_direction(lin, ...
    SymmetryTolerance=config.reduced_symmetry_tolerance, ...
    LocalResidualTolerance=config.local_linear_solve_residual_tolerance, ...
    ReconstructedKktResidualTolerance= ...
        config.recursive_full_kkt_residual_tolerance, ...
    CoreConsistencyMaximumPasses=config.core_consistency_max_passes, ...
    CompensatedCoreAccumulation=config.compensated_core_accumulation, ...
    DailyJointStructureTemplate=template,JointMicroborderEnabled=false);
verifyTrue(testCase,direction.partition.structure_template_reused);
verifyEqual(testCase,direction.partition.cross_day_nnz,0);
verifyFalse(testCase,direction.diagnostics.joint_microborder_scan_executed);
verifyEqual(testCase,direction.timing.joint_microborder_detection_seconds,0);
verifyEqual(testCase,direction.diagnostics.joint_microborder_detection. ...
    stop_reason,"scan_disabled");
verifyEqual(testCase, ...
    direction.recovery.diagnostics.certified_residual_day_count,7);
verifyEqual(testCase, ...
    direction.recovery.diagnostics.extended_residual_fallback_day_count,0);
verifyTrue(testCase,all( ...
    [direction.recovery.daily_direct_backsolve.certified_residual_used]));
verifyLessThanOrEqual(testCase, ...
    direction.diagnostics.candidate_kkt_relative_residual, ...
    config.recursive_full_kkt_residual_tolerance);
end

