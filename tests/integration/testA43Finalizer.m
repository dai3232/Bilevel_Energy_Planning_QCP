function testPreparedEvidenceIsReusedForUniquePassTerminalization(testCase)
fixture = make_fixture(testCase,"CONVERGED");
stageHash = compute_sha256_file(fullfile(fixture.project,"CURRENT_STAGE.md"));
prepared = finalize_stage_a4_3_run( ...
    fixture.project,fixture.run_id,"FinalizeManifest",false);
verifyFalse(testCase,prepared.manifest_finalized);
verifyEqual(testCase,prepared.manifest_status,"RUNNING");
verifyEqual(testCase,prepared.candidate_terminal_status,"PASS");
verifyFalse(testCase,prepared.evidence_inventory_reused);
inventoryHash = compute_sha256_file(prepared.evidence_hashes_path);

finalized = finalize_stage_a4_3_run(fixture.project,fixture.run_id);
verifyTrue(testCase,finalized.manifest_finalized);
verifyEqual(testCase,finalized.manifest_status,"PASS");
verifyEqual(testCase,finalized.candidate_terminal_status,"PASS");
verifyTrue(testCase,finalized.evidence_inventory_reused);
verifyEqual(testCase,compute_sha256_file( ...
    finalized.evidence_hashes_path),inventoryHash);
verifyEqual(testCase,compute_sha256_file(fullfile( ...
    fixture.project,"CURRENT_STAGE.md")),stageHash);
verifyTrue(testCase,isfile(fullfile(fixture.run_root,"acceptance", ...
    "acceptance_results.pre_finalization.csv")));
verifyTrue(testCase,isfile(fullfile(fixture.run_root,"issues", ...
    "issue_log.pre_finalization.csv")));
verifyTrue(testCase,isfile(fullfile(fixture.run_root,"issues", ...
    "decision_log.pre_finalization.csv")));

manifest = jsondecode(fileread(fullfile( ...
    fixture.run_root,"run_manifest.json")));
verifyEqual(testCase,string(manifest.status),"PASS");
verifyFalse(testCase,manifest.stage_b_entered);
verifyTrue(testCase,manifest.current_stage_preserved);
acceptance = readtable(fullfile(fixture.run_root,"acceptance", ...
    "acceptance_results.csv"),"TextType","string","Delimiter",",");
verifyEqual(testCase,height(acceptance),7);
verifyTrue(testCase,all(acceptance.status=="PASS"));
hashes = readtable(finalized.evidence_hashes_path,"TextType","string", ...
    "Delimiter",",");
verifyFalse(testCase,any(hashes.relative_path=="run_manifest.json"));
verifyFalse(testCase,any(hashes.relative_path== ...
    "acceptance/evidence_hashes.csv"));
verifyTrue(testCase,any(hashes.relative_path== ...
    "reports/report_visual_qa.csv"));
verifyTrue(testCase,any(hashes.relative_path== ...
    "tests/static_check_summary.csv"));
end

