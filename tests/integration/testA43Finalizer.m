function counts = make_suite_counts(expected)
counts = repmat(struct( ...
    "suite_label","", ...
    "test_total",0, ...
    "test_passed",0, ...
    "test_failed",0, ...
    "test_incomplete",0, ...
    "duration_seconds",0),size(expected,1),1);
for row = 1:size(expected,1)
    n = str2double(expected(row,2));
    counts(row).suite_label = char(expected(row,1));
    counts(row).test_total = n;
    counts(row).test_passed = n;
    counts(row).duration_seconds = 0.01*n;
end
end

