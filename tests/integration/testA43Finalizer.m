function advisories = fixture_analyzer(project,dependency,scope)
file = strings(0,1); line = zeros(0,1); column = zeros(0,1);
identifier = strings(0,1); message = strings(0,1);
scopeNames = string(scope.relative_path);
nonblockingIds = ["MSNU","SPRIX"];
for k = 1:height(dependency)
    relative = string(dependency.relative_path(k));
    if endsWith(relative,".m","IgnoreCase",true)
        findings = checkcode(fullfile(project,replace(relative,"/",filesep)), ...
            "-id");
        for j = 1:numel(findings)
            identifierValue = string(findings(j).id);
            if ismember(relative,scopeNames) && ...
                    ~ismember(identifierValue,nonblockingIds)
                continue
            end
            file(end+1,1)=relative; %#ok<AGROW>
            line(end+1,1)=double(findings(j).line); %#ok<AGROW>
            if isempty(findings(j).column)
                column(end+1,1)=NaN; %#ok<AGROW>
            else
                column(end+1,1)=double(findings(j).column(1)); %#ok<AGROW>
            end
            identifier(end+1,1)=identifierValue; %#ok<AGROW>
            message(end+1,1)=string(findings(j).message); %#ok<AGROW>
        end
    end
end
advisories = table(file,line,column,identifier,message);
end

