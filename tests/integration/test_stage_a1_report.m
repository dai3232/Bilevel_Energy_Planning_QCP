function tests = test_stage_a1_report
%TEST_STAGE_A1_REPORT Verify artifact-backed A1 DOCX generation and guards.
tests = functiontests(localfunctions);
end

function setup(testCase)
repositoryRoot = string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
originalPath = path;
addpath(genpath(fullfile(repositoryRoot,'src')));
testCase.addTeardown(@() path(originalPath));

runRoot = string(tempname(tempdir));
[created,message] = mkdir(runRoot);
testCase.assertTrue(created,message);
testCase.addTeardown(@() remove_test_tree(runRoot));
write_synthetic_run(runRoot);

testCase.TestData.repositoryRoot = repositoryRoot;
testCase.TestData.runRoot = runRoot;
testCase.TestData.context = struct('root',char(runRoot), ...
    'project_root',char(repositoryRoot));
end

function testGeneratesThreeValidatedArtifactBackedReports(testCase)
outputDirectory = fullfile(testCase.TestData.runRoot,'staged_reports');
paths = generate_stage_a1_reports(testCase.TestData.context, ...
    'OutputDirectory',outputDirectory,'FinalStatusCandidate','PASS');

verifyEqual(testCase,string_filename(paths.model_report), ...
    "阶段A1_完整KKT与递推方向等价验收报告.docx");
verifyEqual(testCase,string_filename(paths.issue_report), ...
    "阶段A1_问题修复与验收报告.docx");
verifyEqual(testCase,string_filename(paths.run_summary), ...
    "运行_synthetic_stage_A1_report_结果摘要.docx");

reportFiles = string(struct2cell(paths));
verifyEqual(testCase,numel(reportFiles),3);
verifyTrue(testCase,all(isfile(reportFiles)));
for reportFile = reshape(reportFiles,1,[])
    [valid,validation] = validate_docx_package(reportFile);
    verifyTrue(testCase,valid,strjoin(string(validation.errors),'; '));
end

modelXml = read_document_xml(paths.model_report);
verifyTrue(testCase,contains(modelXml,'依据全部阻断项计算的终态'));
verifyTrue(testCase,contains(modelXml,'PASS'));
verifyTrue(testCase,contains(modelXml,'471 × 471'));
verifyTrue(testCase,contains(modelXml,'27'));
verifyTrue(testCase,contains(modelXml,'29'));
verifyTrue(testCase,contains(modelXml,'16 × 16'));
verifyTrue(testCase,contains(modelXml,'不连接第 7 小时'));
verifyTrue(testCase,contains(modelXml,'不是正式物理日'));

issueXml = read_document_xml(paths.issue_report);
expectedAcceptanceIds = stage_a1_acceptance_ids();
for acceptanceId = reshape(expectedAcceptanceIds,1,[])
    verifyEqual(testCase,count(issueXml,acceptanceId),1, ...
        sprintf('Acceptance row %s was dropped or duplicated.',acceptanceId));
end

summaryXml = read_document_xml(paths.run_summary);
verifyTrue(testCase,contains(summaryXml,'不能解释为正式 24 小时运行'));
manifest = jsondecode(fileread(fullfile(testCase.TestData.runRoot, ...
    'run_manifest.json')));
verifyEqual(testCase,string(manifest.status),"RUNNING");
end

function testExistingReportsAreNeverOverwritten(testCase)
outputDirectory = fullfile(testCase.TestData.runRoot,'staged_reports');
paths = generate_stage_a1_reports(testCase.TestData.context, ...
    'OutputDirectory',outputDirectory,'FinalStatusCandidate','PASS');
beforeHash = compute_sha256_file(string(paths.model_report));

verifyError(testCase,@() generate_stage_a1_reports( ...
    testCase.TestData.context,'OutputDirectory',outputDirectory, ...
    'FinalStatusCandidate','PASS'),'stageA1:report:ArtifactExists');
verifyEqual(testCase,compute_sha256_file(string(paths.model_report)),beforeHash);
end

function testFalsePassCandidateIsRejectedAndFailureCanBeReported(testCase)
acceptancePath = fullfile(testCase.TestData.runRoot,'acceptance', ...
    'acceptance_results.csv');
acceptance = readtable(acceptancePath,'TextType','string', ...
    'VariableNamingRule','preserve');
acceptance.status(1) = "FAIL";
acceptance.actual_value(1) = "synthetic failure";
write_table_csv_17g(acceptancePath,acceptance);

manifestPath = fullfile(testCase.TestData.runRoot,'run_manifest.json');
manifest = jsondecode(fileread(manifestPath));
manifest.newton_direction_count = 0;
manifest.a1_solver_executed = false;
write_json_file(manifestPath,manifest);

outputDirectory = fullfile(testCase.TestData.runRoot,'failure_reports');
verifyError(testCase,@() generate_stage_a1_reports( ...
    testCase.TestData.context,'OutputDirectory',outputDirectory, ...
    'FinalStatusCandidate','PASS'), ...
    'stageA1:report:FinalStatusCandidateMismatch');

paths = generate_stage_a1_reports(testCase.TestData.context, ...
    'OutputDirectory',outputDirectory, ...
    'FinalStatusCandidate','FAIL_RETRYABLE');
verifyTrue(testCase,all(isfile(string(struct2cell(paths)))));
issueXml = read_document_xml(paths.issue_report);
verifyTrue(testCase,contains(issueXml,'FAIL_RETRYABLE'));
end

