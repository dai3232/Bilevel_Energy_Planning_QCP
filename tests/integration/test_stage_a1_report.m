function testMinimalFailureReportNeedsNoNumericalArtifacts(testCase)
issues = new_stage_a1_issue_log();
issues(1,:) = {"SA1-ISSUE-001","synthetic_stage_A1_report", ...
    "stage_A1","SA1-EQ-002","inequality_elimination", ...
    "inequality row 17","synthetic injected failure", ...
    "stageA1:test:Injected: synthetic injected failure", ...
    "synthetic root cause","inspect persisted issue evidence", ...
    "0123456789abcdef","","OPEN", ...
    "issues/issue_log.csv","synthetic-time"};
acceptance = readtable(fullfile(testCase.TestData.runRoot,'acceptance', ...
    'acceptance_results.csv'),'TextType','string', ...
    'VariableNamingRule','preserve');
acceptance.status(:) = "NOT_RUN";
acceptance.status(9) = "FAIL";
acceptance.actual_value(:) = "";
acceptance.actual_value(9) = "synthetic injected failure";

try
    error('stageA1:test:Injected','synthetic injected failure');
catch exception
end
reportPath = generate_stage_a1_failure_report( ...
    testCase.TestData.context,exception,issues,acceptance);
verifyEqual(testCase,string_filename(reportPath), ...
    "阶段A1_失败与首层定位报告.docx");
[valid,validation] = validate_docx_package(reportPath);
verifyTrue(testCase,valid,strjoin(string(validation.errors),'; '));
xml = read_document_xml(reportPath);
verifyTrue(testCase,contains(xml,'stageA1:test:Injected'));
verifyTrue(testCase,contains(xml,'inequality_elimination'));
verifyTrue(testCase,contains(xml,'inequality row 17'));
verifyTrue(testCase,contains(xml,'SA1-EQ-002'));
verifyTrue(testCase,contains(xml,'不推断未运行的矩阵维数'));
verifyFalse(testCase,contains(xml,'471'));
verifyError(testCase,@() generate_stage_a1_failure_report( ...
    testCase.TestData.context,exception,issues,acceptance), ...
    'stageA1:failureReport:ArtifactExists');
end

