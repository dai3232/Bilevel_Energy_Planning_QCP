function xml = read_document_xml(docxPath)
extractRoot = string(tempname(tempdir));
[created,message] = mkdir(extractRoot);
assert(created,message);
cleanup = onCleanup(@() remove_test_tree(extractRoot));
unzip(docxPath,extractRoot);
xml = string(fileread(fullfile(extractRoot,'word','document.xml')));
end

