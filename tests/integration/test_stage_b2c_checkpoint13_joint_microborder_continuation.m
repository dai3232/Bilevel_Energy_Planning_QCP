function tests = test_stage_b2c_checkpoint13_joint_microborder_continuation
% Continue the historical 90-day checkpoint through directions 14--18.
tests = functiontests(localfunctions);
end

function setupOnce(testCase)
root = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));
addpath(genpath(fullfile(root,"src")));
sourceRoot = fullfile(root,"runs", ...
    "B2C_90DAY_ADAPTIVE_DELAYED_INEQ_FORMAL_20260820_112344");
required = [ ...
    fullfile(sourceRoot,"diagnostics","resolved_runtime_configuration.mat")
    fullfile(sourceRoot,"diagnostics","cache_summary.csv")
    fullfile(sourceRoot,"checkpoints","checkpoint_manifest.csv")];
assumeTrue(testCase,all(isfile(required)), ...
    "The checkpoint13 continuation artifacts are unavailable.");
runtime = load(required(1),"config");
config = runtime.config;
cacheSummary = readtable(required(2),"TextType","string", ...
    "VariableNamingRule","preserve","Delimiter",",");
dataPath = unique(cacheSummary.path(cacheSummary.cache_type=="annual_data"));
indexPath = unique(cacheSummary.path( ...
    cacheSummary.cache_type=="canonical_index"));
assumeTrue(testCase,isscalar(dataPath) && isfile(dataPath) && ...
    isscalar(indexPath) && isfile(indexPath), ...
    "The checkpoint13 continuation caches are unavailable.");
dataPayload = load(dataPath,"data");
indexPayload = load(indexPath,"index");
data = dataPayload.data;
index = indexPayload.index;
context = struct( ...
    "checkpoints_dir",fullfile(sourceRoot,"checkpoints"), ...
    "checkpoint_manifest_path",required(3));
checkpoint = rkkt.artifacts.load_stage_b2c_checkpoint(context,13);
state = checkpoint.state;
linearization = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
    state,data,index,config,"CP13-JOINT-MICROBORDER-CONTINUATION");
linearizationTemplate = rkkt.model.build_stage_b2c_linearization_template( ...
    linearization,data,index,config);

directionNumbers = (14:18).';
nDirections = numel(directionNumbers);
history = table('Size',[nDirections,18], ...
    'VariableTypes',[repmat("double",1,15),repmat("logical",1,3)], ...
    'VariableNames',{'direction_number','revision_before', ...
    'revision_after','core_dimension','microborder_day', ...
    'kkt_relative','daily_relative','alpha_primal','alpha_dual', ...
    'primal_equality_inf','primal_inequality_inf','dual_inf', ...
    'mean_lz','water_violation','total_seconds', ...
    'joint_microborder_used','high_low_update_used', ...
    'water_accepted_displacement_used'});
previousIdentity = "";
lastStep = struct();
for k = 1:nDirections
    step = rkkt.diagnostics.execute_stage_b2c_iteration( ...
        state,data,index,config, ...
        PreviousLinearizationIdentity=previousIdentity, ...
        FullKktAuditEnabled=false, ...
        PrecomputedLinearization=linearization, ...
        LinearizationTemplate=linearizationTemplate, ...
        LinearizationUpdateMode="cached_numeric");
    jointUsed = step.recursive.diagnostics.joint_microborder_used;
    microborderDay = NaN;
    if jointUsed
        microborderDay = step.recursive.diagnostics. ...
            joint_microborder_day_ids(1);
    end
    history(k,:) = {directionNumbers(k),state.state_revision, ...
        step.state_after.state_revision,step.recursive.core.dimension, ...
        microborderDay, ...
        step.recursive.diagnostics.candidate_kkt_relative_residual, ...
        step.recursive.diagnostics. ...
            daily_recovery_maximum_relative_residual, ...
        step.primal_step.alpha,step.dual_step.alpha, ...
        step.metrics_after.primal_equality_inf, ...
        step.metrics_after.primal_inequality_inf, ...
        step.metrics_after.dual_scaled_inf, ...
        step.metrics_after.mean_lz_scaled, ...
        step.metrics_after.maximum_water_violation, ...
        step.timing.total_seconds, ...
        jointUsed,step.high_low_state_update_used, ...
        step.water_slack_second_order_correction. ...
            accepted_primal_displacement_used};
    fprintf(['DIR=%d CORE=%d DAY=%g KKT=%.17g DAILY=%.17g ', ...
        'AP=%.17g AD=%.17g EQ=%.17g INEQ=%.17g DUAL=%.17g ', ...
        'GAP=%.17g WATER=%.17g SEC=%.6f\n'], ...
        history.direction_number(k),history.core_dimension(k), ...
        history.microborder_day(k),history.kkt_relative(k), ...
        history.daily_relative(k),history.alpha_primal(k), ...
        history.alpha_dual(k),history.primal_equality_inf(k), ...
        history.primal_inequality_inf(k),history.dual_inf(k), ...
        history.mean_lz(k),history.water_violation(k), ...
        history.total_seconds(k));
    previousIdentity = step.linearization_before.identity;
    state = step.state_after;
    linearization = step.linearization_after;
    lastStep = step;
    if k==1
        rkkt.artifacts.save_mat_artifact(fullfile(root,".matlab_temp", ...
            "checkpoint14_joint_microborder_diagnostic.mat"), ...
            "state",state,"linearization",linearization, ...
            "previousIdentity",previousIdentity);
    end
end
testCase.TestData.history = history;
testCase.TestData.last_step = lastStep;
testCase.TestData.config = config;
end

function testFiveDirectionsAreAcceptedInSequence(testCase)
history = testCase.TestData.history;
verifyEqual(testCase,history.direction_number,(14:18).');
verifyEqual(testCase,history.revision_before,(13:17).');
verifyEqual(testCase,history.revision_after,(14:18).');
verifyTrue(testCase,all(history.core_dimension==16 | ...
    history.core_dimension==17));
verifyLessThanOrEqual(testCase,max(history.kkt_relative), ...
    testCase.TestData.config.recursive_full_kkt_residual_tolerance);
verifyLessThanOrEqual(testCase,max(history.daily_relative), ...
    testCase.TestData.config.local_linear_solve_residual_tolerance);
verifyTrue(testCase,all(history.alpha_primal>0 & history.alpha_primal<=1));
verifyTrue(testCase,all(history.alpha_dual>0 & history.alpha_dual<=1));
end

function testEveryMicroborderDirectionConsumesHighLowState(testCase)
history = testCase.TestData.history;
micro = history.joint_microborder_used;
verifyTrue(testCase,any(micro));
verifyTrue(testCase,all(history.core_dimension(micro)==17));
verifyTrue(testCase,all(history.high_low_update_used(micro)));
verifyTrue(testCase,all( ...
    history.water_accepted_displacement_used(micro)));
verifyTrue(testCase,all(history.core_dimension(~micro)==16));
verifyFalse(testCase,any(history.high_low_update_used(~micro)));
verifyFalse(testCase,any( ...
    history.water_accepted_displacement_used(~micro)));
verifyEqual(testCase,testCase.TestData.last_step.state_after.state_revision,18);
verifyGreaterThan(testCase,min(testCase.TestData.last_step.state_after.l),0);
verifyGreaterThan(testCase,min(testCase.TestData.last_step.state_after.z),0);
end
