function result = main_stage_0_test_evidence_addendum()
%MAIN_STAGE_0_TEST_EVIDENCE_ADDENDUM Persist a truthful 14-test addendum run.
%
% This entry point does not execute optimization, KKT assembly, a recursive
% solver, or any stage_A1 direction calculation. It only reruns the frozen
% Stage 0 MATLAB test inventory and persists its evidence in a new run.

projectRoot = fileparts(mfilename('fullpath'));
addpath(genpath(fullfile(projectRoot,'src')));
addpath(fullfile(projectRoot,'tests'));

parentRunId = '20260718_163832_stage_0_9e12222e';
historicalBaseline = 'b74a2ac';
testCommand = [ ...
    'matlab -batch "result=main_stage_0_test_evidence_addendum(); ', ...
    'assert(strcmp(char(result.status),''PASS''))"'];

assert_formal_addendum_preconditions(projectRoot,parentRunId, ...
    historicalBaseline);
metadata = struct( ...
    'run_purpose','stage_0_test_evidence_addendum', ...
    'parent_run_id',parentRunId, ...
    'historical_baseline_commit',historicalBaseline, ...
    'actual_test_command',testCommand, ...
    'optimization_executed',false, ...
    'a1_solver_executed',false);

runContext = create_run_context(projectRoot,'stage_0', ...
    'ModelContractVersion','1.0', ...
    'EffectiveConfigPath',fullfile(projectRoot,'config','stage_0.yaml'), ...
    'ManifestMetadata',metadata);
try
    result = run_stage0_test_evidence_addendum(runContext,testCommand);
catch exception
    preserve_addendum_catastrophe(runContext,exception);
    rethrow(exception);
end
end

function assert_formal_addendum_preconditions(projectRoot,parentRunId, ...
        historicalBaseline)
stateText = string(fileread(fullfile(projectRoot,'CURRENT_STAGE.md')));
if ~contains(stateText,'`stage_id`: `stage_A1`') || ...
        ~contains(stateText,'`status`: `READY`')
    error('stage0:addendum:StageGate', ...
        'CURRENT_STAGE.md must identify stage_A1 / READY.');
end

branch = strip(string(run_git(projectRoot,'rev-parse --abbrev-ref HEAD')));
if branch ~= "stage_A1"
    error('stage0:addendum:WrongBranch', ...
        'Formal addendum execution requires branch stage_A1 (actual: %s).',branch);
end
headCommit = lower(strip(string(run_git(projectRoot,'rev-parse HEAD'))));
if startsWith(headCommit,lower(string(historicalBaseline)))
    error('stage0:addendum:FrameworkCommitMissing', ...
        ['Formal execution must run the committed evidence framework, not ' ...
        'the historical baseline commit %s.'],historicalBaseline);
end
assert_git_ancestor(projectRoot,historicalBaseline);
fullStatus = strip(string(run_git(projectRoot, ...
    '-c core.quotePath=false status --porcelain=v1')));
expectedStatus = "?? runs/"+string(parentRunId)+".zip";
if fullStatus ~= expectedStatus
    error('stage0:addendum:WorkingTreeNotIsolated', ...
        ['Before the formal run, the only uncommitted item must be the ' ...
        'preserved parent-run ZIP. Actual status: %s'],fullStatus);
end

parentRoot = fullfile(projectRoot,'runs',parentRunId);
parentManifestPath = fullfile(parentRoot,'run_manifest.json');
if ~isfolder(parentRoot) || ~isfile(parentManifestPath)
    error('stage0:addendum:ParentRunMissing', ...
        'The immutable parent run is unavailable: %s',parentRoot);
end
parentManifest = jsondecode(fileread(parentManifestPath));
if ~isfield(parentManifest,'run_id') || ...
        ~strcmp(char(string(parentManifest.run_id)),parentRunId)
    error('stage0:addendum:ParentRunIdentity', ...
        'The parent run manifest identity does not match %s.',parentRunId);
end
if ~isfield(parentManifest,'status') || ...
        ~strcmp(char(string(parentManifest.status)),'PASS') || ...
        ~isfield(parentManifest,'blocking_acceptance_total') || ...
        ~isfield(parentManifest,'blocking_acceptance_pass') || ...
        double(parentManifest.blocking_acceptance_total) ~= 10 || ...
        double(parentManifest.blocking_acceptance_pass) ~= 10
    error('stage0:addendum:ParentRunNotAccepted', ...
        'The parent run must remain PASS with 10 of 10 blocking items.');
end

zipPath = fullfile(projectRoot,'runs',[parentRunId,'.zip']);
expectedZipSha = "b44576fd8f20c94f79e631a8d286d709ce4c9d41feafb724fa7dd01010fe78d7";
if ~isfile(zipPath)
    error('stage0:addendum:PreservedZipMissing', ...
        'The preserved untracked parent-run ZIP is missing: %s',zipPath);
end
actualZipSha = compute_sha256_file(string(zipPath));
if actualZipSha ~= expectedZipSha
    error('stage0:addendum:PreservedZipHashMismatch', ...
        'The preserved ZIP SHA256 changed (actual: %s).',actualZipSha);
end
end

function assert_git_ancestor(projectRoot,ancestorCommit)
safePath = strrep(projectRoot,'\','/');
command = sprintf([ ...
    'git -c safe.directory="%s" -C "%s" merge-base ' ...
    '--is-ancestor "%s" HEAD 2>&1'], ...
    safePath,projectRoot,ancestorCommit);
[exitCode,output] = system(command);
if exitCode == 1
    error('stage0:addendum:UnexpectedCommitAncestry', ...
        'Historical baseline %s is not an ancestor of HEAD.',ancestorCommit);
elseif exitCode ~= 0
    error('stage0:addendum:GitInspectionFailed', ...
        'Could not verify commit ancestry: %s',strtrim(output));
end
end

function output = run_git(projectRoot,arguments)
safePath = strrep(projectRoot,'\','/');
command = sprintf('git -c safe.directory="%s" -C "%s" %s', ...
    safePath,projectRoot,arguments);
[exitCode,output] = system(command);
if exitCode ~= 0
    error('stage0:addendum:GitInspectionFailed', ...
        'Git inspection failed for "%s": %s',arguments,strtrim(output));
end
end

function preserve_addendum_catastrophe(runContext,exception)
externalFailure = is_external_catastrophe(exception);
if externalFailure
    rowStatus = 'BLOCKED';
    terminalStatus = 'BLOCKED_EXTERNAL';
    issueStatus = 'BLOCKED';
    rootCause = 'MATLAB、许可证、工具箱或文件权限不可用';
else
    rowStatus = 'FAIL';
    terminalStatus = 'FAIL_RETRYABLE';
    issueStatus = 'OPEN';
    rootCause = '执行器或证据框架发生未捕获错误';
end
try
    acceptance = addendum_acceptance_row(rowStatus, ...
        "The addendum runner raised an unhandled exception", ...
        'unexpected runner failure','run_manifest.json');
    write_table_csv_17g(runContext.acceptance_results_path,acceptance);
catch
end
try
    issues = new_stage0_issue_log();
    issues = append_stage0_issue(issues,runContext, ...
        'S0-TEST-EVIDENCE-001','补充测试证据执行器发生未捕获异常', ...
        exception.message,rootCause, ...
        '恢复外部条件或修复后创建新的不可覆盖 run 并重新执行', ...
        issueStatus, ...
        'run_manifest.json');
    write_table_csv_17g(runContext.issue_log_path,issues);
catch
end
try
    manifest = jsondecode(fileread(runContext.run_manifest_path));
    if isfield(manifest,'status') && strcmp(manifest.status,'RUNNING')
        finalize_run_manifest(runContext,terminalStatus,struct( ...
            'fatal_error',exception.message, ...
            'candidate_terminal_status',terminalStatus));
    end
catch
end
end

function external = is_external_catastrophe(exception)
diagnostic = lower(string(exception.identifier)+" "+ ...
    string(exception.message));
markers = ["license", "permission denied", "access is denied", ...
    "parallel computing toolbox", "license manager", ...
    "许可证", "权限", "无法访问matlab", "无法访问 matlab"];
external = any(contains(diagnostic,markers));
end

function acceptance = addendum_acceptance_row(status,actual,comparison,evidence)
acceptance = table("S0-TEST-EVIDENCE-001", ...
    "原有14项Stage 0测试补充重跑证据完整且全部通过", ...
    "total=14; passed=14; failed=0; incomplete=0; 输入哈希、六类测试证据、证据SHA256及中文报告均有效", ...
    string(actual),string(comparison),string(status),true,string(evidence), ...
    string(datetime('now','TimeZone','Asia/Shanghai', ...
    'Format','yyyy-MM-dd''T''HH:mm:ssXXX')), ...
    'VariableNames',{'test_id','requirement','threshold','actual_value', ...
    'comparison','status','blocking','evidence_path','checked_at'});
end
