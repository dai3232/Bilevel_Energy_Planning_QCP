function raise_first_acceptance_failure(acceptance,verification)
row = find(acceptance.status~="PASS" & ...
    acceptance.test_id~="SA1-ART-001",1,"first");
assert(~isempty(row),"stageA1:acceptance:MissingFailure", ...
    "A non-PASS acceptance row was expected.");
testId = acceptance.test_id(row);
switch testId
    case "SA1-EQ-001"
        layer = "direction_equivalence_comparison";
        object = location_text( ...
            verification.audit.maximum_direction_difference.location);
    case "SA1-EQ-002"
        layer = "full_kkt_reinsertion";
        object = location_text( ...
            verification.audit.maximum_recursive_residual.location);
    case "SA1-EQ-003"
        layer = "full_kkt_direct_solve";
        object = location_text(verification.audit.maximum_full_residual.location);
    case {"SA1-MAT-001","SA1-MAT-002","SA1-BLK-001"}
        layer = "matrix_dimension_audit";
        object = acceptance.actual_value(row);
    case "SA1-LIN-001"
        layer = "shared_linearization_identity";
        object = acceptance.actual_value(row);
    case "SA1-BND-001"
        layer = "soc_window_boundary_assembly";
        object = "day1 hours8-10 SOC equations";
    case {"SA1-IDX-001","SA1-IDX-002"}
        layer = "canonical_index_or_fixed_zero_recovery";
        object = acceptance.actual_value(row);
    case "SA1-NUM-001"
        layer = "numerical_safeguard_audit";
        object = acceptance.actual_value(row);
    otherwise
        layer = "acceptance_evaluation";
        object = acceptance.actual_value(row);
end
error("stageA1:acceptance:BlockingFailure", ...
    "test_id '%s'; layer '%s'; object '%s'; actual '%s'", ...
    testId,layer,replace(string(object),"'",""),acceptance.actual_value(row));
end

function value = location_text(location)
try
    value = string(jsonencode(location));
catch
    value = string(location);
end
end

function installed = install_staged_reports(context,staged)
installed = struct();
names = fieldnames(staged);
for k = 1:numel(names)
    source = string(staged.(names{k}));
    sourceHash = lower(string(compute_sha256_file(source)));
    [~,base,extension] = fileparts(source);
    target = string(fullfile(context.reports_dir,base+extension));
    if isfile(target) || isfolder(target)
        error("stageA1:report:TargetExists", ...
            "Refusing to overwrite report %s.",target);
    end
    [moved,message] = movefile(source,target);
    assert(moved,"stageA1:report:InstallFailed","%s",message);
    assert(lower(string(compute_sha256_file(target)))==sourceHash, ...
        "stageA1:report:InstalledHash", ...
        "Installed report hash differs for reports/%s%s.",base,extension);
    installed.(names{k}) = char(target);
end
end

function value = relative_report_paths(paths)
value = struct();
names = fieldnames(paths);
for k = 1:numel(names)
    [~,base,extension] = fileparts(paths.(names{k}));
    value.(names{k}) = char("reports/"+string(base)+string(extension));
end
end

function write_new_table(pathValue,value)
if isfile(pathValue) || isfolder(pathValue)
    error("stageA1:artifacts:TargetExists", ...
        "Refusing to overwrite %s.",pathValue);
end
write_table_csv_17g(pathValue,value);
end

function [acceptance,issues] = persist_external_block(projectRoot,context, ...
        environment,hashes,issues)
acceptance = initialize_stage_a1_acceptance(projectRoot);
envPass = all(string(environment.status(logical(environment.blocking)))=="PASS");
hashPass = height(hashes)==2 && all(string(hashes.status)=="PASS");
acceptance = set_stage_a1_acceptance_result(acceptance,"SA1-ENV-001", ...
    blocked_or_pass(envPass),"environment preflight", ...
    "blocking environment checks","environment.csv");
acceptance = set_stage_a1_acceptance_result(acceptance,"SA1-DATA-001", ...
    blocked_or_pass(hashPass),"controlled input hash preflight", ...
    "two SHA256 comparisons","input_hashes.csv");
for row = 1:height(acceptance)
    if acceptance.status(row)=="NOT_RUN"
        acceptance = set_stage_a1_acceptance_result(acceptance, ...
            acceptance.test_id(row),"BLOCKED", ...
            "not run because external preflight did not pass", ...
            "dependency blocked","environment.csv; input_hashes.csv");
    end
end
issues = append_stage_a1_issue(issues,context,"SA1-ENV-001", ...
    "external_preflight","MATLAB environment or controlled input", ...
    "A1 execution was not started","Environment or input SHA256 unavailable", ...
    "external environment or controlled input mismatch", ...
    "Restore the required environment or controlled input and create a new run", ...
    "BLOCKED","environment.csv; input_hashes.csv");
write_new_table(context.issue_log_path,issues);
write_new_table(context.acceptance_results_path,acceptance);
end

function value = blocked_or_pass(passed)
if passed, value="PASS"; else, value="BLOCKED"; end
end

function preserve_stage_a1_failure(context,acceptance,issues,exception)
hashPath = fullfile(context.acceptance_dir,"evidence_hashes.csv");
if isfile(hashPath)
    priorPath = fullfile(context.acceptance_dir, ...
        "evidence_hashes.pre_failure_candidate.csv");
    try
        if ~isfile(priorPath) && ~isfolder(priorPath)
            movefile(hashPath,priorPath);
        end
    catch
    end
end
try
    if isempty(acceptance)
        acceptance = initialize_stage_a1_acceptance(string(context.project_root));
    end
    failureId = first_failure_test_id(exception);
    if nnz(acceptance.test_id==failureId)~=1
        failureId = "SA1-ART-001";
    end
    acceptance = set_stage_a1_acceptance_result(acceptance, ...
        failureId,"FAIL",exception.message, ...
        "first failing Stage A1 layer","run_manifest.json");
    artifactRow = acceptance.test_id=="SA1-ART-001";
    if failureId~="SA1-ART-001" && acceptance.status(artifactRow)~="FAIL"
        acceptance = set_stage_a1_acceptance_result(acceptance, ...
            "SA1-ART-001","BLOCKED", ...
            "not completed after "+failureId, ...
            "dependency blocked by first failure","run_manifest.json");
    end
    for row = 1:height(acceptance)
        if acceptance.status(row)=="NOT_RUN"
            acceptance = set_stage_a1_acceptance_result(acceptance, ...
                acceptance.test_id(row),"BLOCKED", ...
                "not completed after "+failureId, ...
                "dependency blocked by first failure","run_manifest.json");
        end
    end
    write_table_csv_17g(context.acceptance_results_path,acceptance);
catch
end
try
    issues = append_stage_a1_issue(issues,context, ...
        first_failure_test_id(exception), ...
        first_failure_layer(exception),first_failure_object(exception), ...
        "Stage A1 formal run failed",exception.message, ...
        "See exception cause and persisted evidence", ...
        "Fix the first failing layer and create a new unique run", ...
        "OPEN","run_manifest.json");
    write_table_csv_17g(context.issue_log_path,issues);
catch
end
try
    generate_stage_a1_failure_report(context,exception,issues,acceptance);
catch
end
try
    if ~isfile(hashPath)
        write_stage_a1_evidence_hashes(context,struct());
    end
catch
end
try
    manifest = jsondecode(fileread(context.run_manifest_path));
    if string(manifest.status)=="RUNNING"
        updates = struct( ...
            "fatal_error_identifier",exception.identifier, ...
            "fatal_error_message",exception.message, ...
            "first_failed_layer",first_failure_layer(exception), ...
            "first_failed_object",first_failure_object(exception));
        if isfile(hashPath)
            updates.evidence_hashes = "acceptance/evidence_hashes.csv";
            updates.evidence_hashes_sha256 = compute_sha256_file(hashPath);
        end
        failureReportPath = fullfile(context.reports_dir, ...
            "阶段A1_失败与首层定位报告.docx");
        if isfile(failureReportPath)
            updates.reports = struct("failure", ...
                relative_run_path(failureReportPath,context.root));
        end
        finalize_run_manifest(context,"FAIL_RETRYABLE",updates);
    end
catch
end
end

function value = first_failure_layer(exception)
token = regexp(exception.message,"layer '([^']+)'",'tokens','once');
if isempty(token), value="execution_or_artifact"; else, value=string(token{1}); end
end

function value = first_failure_object(exception)
token = regexp(exception.message,"object '([^']*)'",'tokens','once');
if isempty(token)
    message = string(exception.message);
    hourMatch = regexp(message, ...
        "Hour \d+ failed at [^;]+; xi indices=\[[^\]]*\]; equality indices=\[[^\]]*\]; block dimension=\d+", ...
        'match','once');
    coreMatch = regexp(message, ...
        "16-by-16 core failed for q indices 1:14 and duration multiplier indices 1:2", ...
        'match','once');
    inequalityMatch = regexp(message, ...
        "Inequality elimination failed at row \d+",'match','once');
    if ~isempty(hourMatch)
        value = string(hourMatch);
    elseif ~isempty(coreMatch)
        value = string(coreMatch);
    elseif ~isempty(inequalityMatch)
        value = string(inequalityMatch);
    else
        value = string(exception.identifier);
    end
else
    value = string(token{1});
end
if ~isempty(exception.cause)
    value = value+"; cause="+string(exception.cause{1}.identifier);
end
end

function value = first_failure_test_id(exception)
token = regexp(exception.message,"test_id '([^']+)'",'tokens','once');
if isempty(token)
    if contains(string(exception.identifier),"Recursive")
        value = "SA1-EQ-002";
    elseif contains(string(exception.identifier),"FullKkt")
        value = "SA1-EQ-003";
    elseif contains(string(exception.identifier),"tests")
        value = "SA1-ART-001";
    else
        value = "SA1-ART-001";
    end
else
    value = string(token{1});
end
end

function value = relative_run_path(pathValue,runRoot)
value = char(replace(extractAfter(string(pathValue), ...
    strlength(string(runRoot))+1),'\','/'));
end

function cleanup_staging(pathValue)
if strlength(string(pathValue))>0 && isfolder(pathValue)
    try
        rmdir(pathValue,'s');
    catch
        % Temporary cleanup must never hide the original execution result.
    end
end
end
