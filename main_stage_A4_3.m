function write_initial_identity_artifacts( ...
        context,environment,inputHashes,historical)
environment = addvars(environment, ...
    repmat(string(context.run_id),height(environment),1), ...
    'Before',1,'NewVariableNames','run_id');
write_table_csv_17g_atomic(context.environment_csv_path,environment);
write_table_csv_17g_atomic(context.input_hashes_csv_path, ...
    input_hash_table(inputHashes,context.run_id));
write_table_csv_17g_atomic( ...
    fullfile(context.root,"historical_runs_before.csv"),historical);
end

function recover_initial_identity_artifacts( ...
        context,environment,inputHashes,historical)
environmentPath = string(context.environment_csv_path);
inputPath = string(context.input_hashes_csv_path);
historyPath = fullfile(context.root,"historical_runs_before.csv");
if isfile(environmentPath)
    observed = readtable(environmentPath,"TextType","string", ...
        "VariableNamingRule","preserve");
    assert(height(observed)==height(environment) && ...
        all(string(observed.run_id)==string(context.run_id)) && ...
        all(ismember(string(observed.status), ...
        ["PASS","NOT_APPLICABLE"])) && ...
        all(string(observed.status(logical(observed.blocking)))=="PASS"), ...
        "stageA4:a43:ResumeEnvironment", ...
        "Persisted environment evidence is inconsistent.");
else
    environment = addvars(environment, ...
        repmat(string(context.run_id),height(environment),1), ...
        'Before',1,'NewVariableNames','run_id');
    write_table_csv_17g_atomic(environmentPath,environment);
end
expectedHashes = input_hash_table(inputHashes,context.run_id);
if isfile(inputPath)
    observed = readtable(inputPath,"TextType","string", ...
        "VariableNamingRule","preserve");
    assert(height(observed)==2 && ...
        all(lower(string(observed.actualSHA256))== ...
        lower(string(expectedHashes.actualSHA256))) && ...
        all(string(observed.status)=="PASS"), ...
        "stageA4:a43:ResumeInputHashes", ...
        "Persisted controlled input hashes are inconsistent.");
else
    write_table_csv_17g_atomic(inputPath,expectedHashes);
end
if ~isfile(historyPath)
    write_table_csv_17g_atomic(historyPath,historical);
    update_running_run_manifest(context,struct( ...
        "historical_before_reconstructed_on_resume",true));
end
end

