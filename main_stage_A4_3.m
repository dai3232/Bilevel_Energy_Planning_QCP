function persisted = load_persisted_postprocess_result(context)
%LOAD_PERSISTED_POSTPROCESS_RESULT Read the immutable numerical result used
% to resume an interrupted postprocess phase.  No solver call is made here.
persisted = struct("available",false,"reason","", ...
    "summary",struct(),"final_state",struct());
pathValue = fullfile(context.root,"a4_3_solver_result.mat");
if ~isfile(pathValue)
    persisted.reason = "a4_3_solver_result.mat is missing";
    return
end
try
    payload = load(pathValue,"summary","final_state");
    required = ["summary","final_state"];
    if ~all(isfield(payload,cellstr(required))) || ...
            ~isstruct(payload.summary) || ~isscalar(payload.summary) || ...
            ~isstruct(payload.final_state) || ~isscalar(payload.final_state)
        persisted.reason = "persisted solver result is incomplete";
        return
    end
    terminal = string(payload.summary.run_terminal_state);
    if ~ismember(terminal,["CONVERGED","MAX_ITERATIONS", ...
            "NUMERICAL_FAILURE"])
        persisted.reason = "persisted numerical terminal state is not complete";
        return
    end
    if ~isfield(payload.final_state,"xi") || ...
            ~isnumeric(payload.final_state.xi) || ...
            ~iscolumn(payload.final_state.xi) || ...
            any(~isfinite(payload.final_state.xi))
        persisted.reason = "persisted final state is missing finite xi";
        return
    end
    persisted.summary = payload.summary;
    persisted.final_state = payload.final_state;
    persisted.available = true;
catch cause
    persisted.reason = "could not load persisted solver result: "+ ...
        string(cause.identifier)+": "+string(cause.message);
end
end

function result = rebuild_persisted_postprocess_result( ...
        persisted,data,index,config)
%REBUILD_PERSISTED_POSTPROCESS_RESULT Recreate only deterministic derived
%objects from the accepted state; never solve or advance a direction.
result = persisted.summary;
result.final_state = persisted.final_state;
result.final_linearization = ...
    build_stage_a4_scaled_objective_linearization( ...
        result.final_state,data,index,config,"A4-3-FORMAL-CANDIDATE");
assert(isfield(result.final_state,"state_revision") && ...
        isfield(result.final_linearization,"diagnostic_objective_chain_id") && ...
        string(result.final_linearization.diagnostic_objective_chain_id)== ...
        "A4-3-FORMAL-CANDIDATE" && ...
        double(result.final_linearization.state.state_revision)== ...
        double(result.final_state.state_revision), ...
    "stageA4:a43:PostprocessRebuildIdentity", ...
    "Rebuilt postprocess linearization does not match the persisted state.");
end

