function verify_resume_identity(context,preflight,inputHashes,config)
manifest = jsondecode(fileread(context.run_manifest_path));
assert(string(manifest.status)=="RUNNING" && ...
    string(manifest.stage_id)=="stage_A4" && ...
    string(manifest.run_purpose)==config.a4_3.run_purpose && ...
    lower(string(manifest.git_commit))==lower(preflight.git_commit) && ...
    lower(string(manifest.input_hashes.base_parameters))== ...
        lower(string(inputHashes.actualSHA256(1))) && ...
    lower(string(manifest.input_hashes.timeseries))== ...
        lower(string(inputHashes.actualSHA256(2))) && ...
    lower(string(compute_sha256_file(context.effective_config_path)))== ...
        lower(string(compute_sha256_file(config.source_paths.a4_3))), ...
    "stageA4:a43:ResumeIdentity", ...
    "Resume requires identical code, input hashes, and effective config.");
end

function [issues,decisions] = make_logs(context,result,acceptance)
if result.run_terminal_state=="CONVERGED" && ...
        all(acceptance.status(1:6)=="PASS")
    issues = empty_issue_log();
else
    failureId = "A43-"+result.run_terminal_state;
    failedRows = acceptance(acceptance.status=="FAIL",:);
    if isempty(failedRows)
        failedIds = "none";
    else
        failedIds = strjoin(failedRows.test_id,",");
    end
    issues = table(string(context.run_id),failureId,failedIds, ...
        result.run_terminal_state, ...
        "Formal A4-3 candidate did not satisfy every numerical gate.", ...
        "Persisted trajectory, checkpoint, direction and physical evidence retained.", ...
        "No algorithm factor was changed; user decision is required.", ...
        "OPEN","iterations/iteration_summary.csv; acceptance/acceptance_results.csv", ...
        'VariableNames',{'run_id','issue_id','test_id','layer', ...
        'symptom','evidence_preserved','next_action','status', ...
        'evidence_path'});
end
decisions = table(string(context.run_id),"A4-3", ...
    result.run_terminal_state, ...
    "CURRENT_STAGE remains stage_A4 / READY; no Stage B transition.", ...
    result.iteration_count, ...
    "positive_scalar_unitized_kkt", ...
    "independent alpha_primal/alpha_dual; stable-v2 MaxPasses=3", ...
    "issues/issue_log.csv; iterations/iteration_summary.csv", ...
    'VariableNames',{'run_id','milestone','numerical_terminal_state', ...
    'stage_decision','accepted_iteration_count', ...
    'convergence_coordinate','algorithm_contract','evidence_path'});
end

function value = empty_issue_log()
value = table(strings(0,1),strings(0,1),strings(0,1), ...
    strings(0,1),strings(0,1),strings(0,1),strings(0,1), ...
    strings(0,1),strings(0,1), ...
    'VariableNames',{'run_id','issue_id','test_id','layer', ...
    'symptom','evidence_preserved','next_action','status', ...
    'evidence_path'});
end

function updates = manifest_observations( ...
        result,structural,physicalResults,physicalAudit, ...
        forbiddenCode,forbiddenExecution,historical)
% Numerical/structural postprocessing has completed, but reports, external
% tests, static evidence and final hashing are still pending.  Keep the
% phase recoverable until the finalizer performs the single terminal
% transition.
direction = result.direction_audit;
if isempty(direction)
    worstDirection = Inf;
    worstRecursiveResidual = Inf;
    worstDirectResidual = Inf;
else
    worstDirection = max([direction.direction_relative_error; ...
        direction.xi_relative_error;direction.y_relative_error; ...
        direction.l_relative_error;direction.z_relative_error],[],"all");
    worstRecursiveResidual = max( ...
        direction.recursive_full_kkt_relative_residual);
    worstDirectResidual = max(direction.full_kkt_relative_residual);
end
updates = struct( ...
    "a4_3_run_terminal_state",char(result.run_terminal_state), ...
    "convergence_achieved",result.convergence_achieved, ...
    "newton_direction_count",result.iteration_count, ...
    "accepted_state_update_count",result.iteration_count, ...
    "last_attempted_iteration",result.last_attempted_iteration, ...
    "attempted_iteration_count_current_invocation", ...
        result.attempted_iteration_count_current_invocation, ...
    "full_kkt_audit_count",result.full_kkt_audit_count, ...
    "accepted_iteration_full_kkt_audit_count", ...
        result.accepted_iteration_full_kkt_audit_count, ...
    "resume_replay_full_kkt_audit_count", ...
        result.resume_replay_full_kkt_audit_count, ...
    "completed_iteration_evaluation_count_current_invocation", ...
        result.completed_iteration_evaluation_count_current_invocation, ...
    "objective_scale_factor",result.objective_scale_factor, ...
    "final_scaled_metrics",result.final_metrics, ...
    "worst_direction_metric",worstDirection, ...
    "worst_recursive_full_kkt_residual",worstRecursiveResidual, ...
    "worst_complete_kkt_audit_residual",worstDirectResidual, ...
    "strict_positivity_all_accepted", ...
        result.execution_audit.strict_positivity_pass, ...
    "no_full_direction_fallback", ...
        result.execution_audit.no_full_direction_fallback, ...
    "forbidden_execution_pass", ...
        all(forbiddenCode.status=="PASS") && ...
        all(forbiddenExecution.status=="PASS") && ...
        result.execution_audit.forbidden_execution_pass, ...
    "structural_kkt_dimension",structural.kkt_dimension, ...
    "structural_kkt_nnz",structural.kkt_nnz, ...
    "structural_export_direction_solve_count", ...
        structural.additional_direction_solve_count, ...
    "capacity_result_count",height(physicalResults.capacity_results), ...
    "hourly_result_count",height(physicalResults.hourly_dispatch_results), ...
    "physical_audit_pass",all(physicalAudit.status=="PASS"), ...
    "physical_dispatch_interpretation",result.convergence_achieved, ...
    "capacity_planning_interpretation",result.convergence_achieved, ...
    "historical_runs_unchanged",historical.passed, ...
    "reports_generated",false, ...
    "tests_executed",false, ...
    "postprocess_phase","IN_PROGRESS", ...
    "postprocessing_executed",false, ...
    "postprocess_completed_at","", ...
    "finalization_pending",true);
end

function phase = read_postprocess_phase(manifest)
if isfield(manifest,"postprocess_phase")
    phase = string(manifest.postprocess_phase);
else
    phase = "NOT_STARTED";
end
assert(ismember(phase,["NOT_STARTED","IN_PROGRESS","COMPLETE"]), ...
    "stageA4:a43:PostprocessPhase", ...
    "Invalid persisted A4-3 postprocess phase: %s.",phase);
end

function result = completed_postprocess_result(context,manifest)
solverPath = fullfile(context.root,"a4_3_solver_result.mat");
assert(isfile(solverPath),"stageA4:a43:CompletedPostprocessEvidence", ...
    "A COMPLETE postprocess phase requires a4_3_solver_result.mat.");
loaded = load(solverPath,"summary");
assert(isfield(loaded,"summary") && isstruct(loaded.summary), ...
    "stageA4:a43:CompletedPostprocessEvidence", ...
    "The persisted A4-3 solver summary is missing.");
summary = loaded.summary;
acceptance = readtable(context.acceptance_results_path, ...
