    "rhs",fullAudit.kkt.rhs,"direction",fullAudit.direction, ...
    "slices",fullAudit.kkt.slices,"symmetry",fullAudit.kkt.symmetry, ...
    "linearization_identity",fullAudit.linearization_identity);
end

