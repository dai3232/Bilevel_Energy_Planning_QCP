function value=write_evidence_hashes(runRoot,pathValue)
assert(~isfile(pathValue)&&~isfolder(pathValue), ...
    "stageB2B:EvidenceHashExists","Refusing to overwrite hash evidence.");
listing=dir(fullfile(runRoot,"**","*")); listing=listing(~[listing.isdir]);
relative_path=strings(0,1); sha256=strings(0,1); bytes=zeros(0,1);
for k=1:numel(listing)
    absolute=string(fullfile(listing(k).folder,listing(k).name));
    relative=replace(extractAfter(absolute,string(runRoot)+filesep),filesep,"/");
    if relative=="acceptance/evidence_hashes.csv" || relative=="run_manifest.json", continue; end
    relative_path(end+1,1)=relative; sha256(end+1,1)=compute_sha256_file(absolute); ...
        bytes(end+1,1)=listing(k).bytes; %#ok<AGROW>
end
[relative_path,order]=sort(relative_path); sha256=sha256(order); bytes=bytes(order);
value=table(relative_path,sha256,bytes,repmat("PASS",numel(bytes),1), ...
    'VariableNames',{'relative_path','sha256','bytes','status'});
write_new_table(pathValue,value);
end

function value=input_hash_object(hashes)
