assert(nnz(base)==1&&nnz(series)==1,"stageB2B:InputHashRows", ...
    "Both controlled input rows are required.");
value=struct("base_parameters",char(hashes.actualSHA256(base)), ...
    "timeseries",char(hashes.actualSHA256(series)));
end
