    double(hashes.actualBytes),string(hashes.expectedSHA256), ...
    string(hashes.actualSHA256),string(hashes.status), ...
    'VariableNames',{'run_id','file_name','relative_path','expected_bytes', ...
    'actual_bytes','expectedSHA256','actualSHA256','status'});
end
function assert_clean_implementation_commit(root)
[code,branch]=system(git_command(root,"rev-parse --abbrev-ref HEAD"));
assert(code==0&&strip(string(branch))=="stage_B","stageB2B:GitBranch", ...
    "Formal B-2B must run on branch stage_B.");
[code,changes]=system(git_command(root,"status --porcelain --untracked-files=no"));
assert(code==0&&strlength(strip(string(changes)))==0,"stageB2B:GitDirty", ...
    "Formal B-2B requires a clean tracked worktree.");
end
function value=git_commit(root)
[code,output]=system(git_command(root,"rev-parse HEAD")); value=lower(strip(string(output)));
assert(code==0&&~isempty(regexp(value,"^[0-9a-f]{40}$","once")), ...
    "stageB2B:GitCommit","Could not resolve implementation commit.");
end
function value=git_command(root,arguments)
safe=replace(char(root),'\','/');
value=string(sprintf('git -c safe.directory=%s %s',safe,char(arguments)));
end
function runId=choose_run_id(root,requested,shortCommit)
if strlength(strtrim(requested))>0
    runId=requested; assert(~contains(runId,["/","\"]),"stageB2B:RunId", ...
        "Run id must be a leaf name.");
else
    timestamp=string(datetime("now","TimeZone","UTC","Format","yyyyMMdd_HHmmss"));
    runId=timestamp+"_stage_B_2B_"+shortCommit;
end
assert(~isfile(fullfile(root,"runs",runId))&&~isfolder(fullfile(root,"runs",runId)), ...
    "stageB2B:RunExists","Run path already exists: %s",runId);
end
function ensure_directory(pathValue)
if isfolder(pathValue), return; end
[created,message]=mkdir(pathValue); assert(created,"stageB2B:Directory","%s",message);
end
function write_new_table(pathValue,value)
assert(~isfile(pathValue)&&~isfolder(pathValue),"stageB2B:ArtifactExists", ...
    "Refusing to overwrite %s.",pathValue);
write_table_csv_17g(pathValue,value);
end
function value=conditional_status(passed)
if passed, value="PASS"; else, value="FAIL"; end
end
