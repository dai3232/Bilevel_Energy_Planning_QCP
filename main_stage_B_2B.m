    "global_core_16";"full_KKT_audit"];
matrices={lin.H;lin.A;lin.G;recursive.reduced.W; ...
    recursive.reduced.saddle;recursive.core.matrix;fullAudit.kkt.matrix};
row_count=zeros(7,1); column_count=zeros(7,1); nonzero_count=zeros(7,1);
for k=1:7
    [row_count(k),column_count(k)]=size(matrices{k});
    nonzero_count(k)=nnz(matrices{k});
end
artifact_path=[repmat("matrices/stage_b2b_linearization.mat",3,1); ...
    repmat("matrices/stage_b2b_recursive_direction.mat",3,1); ...
    "matrices/stage_b2b_full_kkt_audit.mat"];
sha256=[repmat(compute_sha256_file(paths.linearization),3,1); ...
    repmat(compute_sha256_file(paths.recursive),3,1); ...
    compute_sha256_file(paths.full)];
role=["shared_lagrangian_hessian";"shared_equality_jacobian"; ...
    "shared_inequality_jacobian";"algebraic_audit"; ...
    "algebraic_audit";"recursive_formal";"independent_audit_only"];
solved=[false;false;false;false;false;true;true];
value=table(repmat(string(context.run_id),7,1),matrix_name,role, ...
    row_count,column_count,nonzero_count,true(7,1),artifact_path,sha256, ...
    repmat(string(lin.identity),7,1),solved,repmat("PASS",7,1), ...
    'VariableNames',{'run_id','matrix_name','role','row_count', ...
    'column_count','nonzero_count','is_sparse','artifact_path','sha256', ...
    'linearization_identity','solved','status'});
end

