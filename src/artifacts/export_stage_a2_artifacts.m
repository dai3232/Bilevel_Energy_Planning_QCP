function exported = export_stage_a2_artifacts(runContext,data,index,config, ...
        linearization,fullResult,recursiveResult,audit,options)
%EXPORT_STAGE_A2_ARTIFACTS Persist one formal-day A2 direction comparison.
% Complete KKT and 589-dimensional chain matrices remain sparse MAT data.

arguments
    runContext (1,1) struct
    data (1,1) struct
    index (1,1) struct
    config (1,1) struct
    linearization (1,1) struct
    fullResult (1,1) struct
    recursiveResult (1,1) struct
    audit (1,1) struct
    options.Environment = struct()
    options.Tests = struct()
    options.A1Regression = struct()
    options.CodeScan table = table()
end
validate_inputs(runContext,index,config,linearization,fullResult, ...
    recursiveResult,audit);
paths = artifact_paths(runContext,config.hours);
targets = output_targets(paths);
assert_targets_absent(targets);
ensure_directory(paths.diagnostics_dir);

save_mat_artifact(paths.linearization_mat,"linearization",linearization);
save_mat_artifact(paths.full_kkt_mat,"kkt",fullResult.kkt, ...
    "diagnostics",fullResult.diagnostics, ...
    "linearization_identity",fullResult.linearization_identity);
save_mat_artifact(paths.recursive_blocks_mat, ...
    "reduced",recursiveResult.reduced,"partition",recursiveResult.partition, ...
    "thomas",recursiveResult.thomas,"day_response",recursiveResult.day_response, ...
    "core",recursiveResult.core,"recovery",recursiveResult.recovery, ...
    "linearization_identity",recursiveResult.linearization_identity);
save_mat_artifact(paths.directions_mat, ...
    "full_direction",fullResult.direction, ...
    "recursive_direction",recursiveResult.direction, ...
    "full_components",fullResult.components, ...
    "recursive_components",recursiveResult.components, ...
    "fixed_zero",recursiveResult.fixed_zero);
fullResidual = fullResult.kkt.matrix*fullResult.direction-fullResult.kkt.rhs;
recursiveResidual = fullResult.kkt.matrix*recursiveResult.direction- ...
    fullResult.kkt.rhs;
save_mat_artifact(paths.residuals_mat,"audit",audit, ...
    "full_kkt_residual",fullResidual, ...
    "recursive_full_kkt_residual",recursiveResidual, ...
    "recursive_reinsertion",recursiveResult.full_kkt_reinsertion, ...
    "chain_diagnostics",recursiveResult.thomas.diagnostics, ...
    "core_diagnostics",recursiveResult.core.diagnostics);
save_mat_artifact(paths.index_mapping_mat,"index",index);
save_mat_artifact(paths.configuration_mat,"config",config, ...
    "data_metadata",data.meta,"input_hashes",data.hashes, ...
    "environment",options.Environment,"tests",options.Tests, ...
    "a1_regression",options.A1Regression);

write_table_csv_17g(paths.variable_index,index.variable_index);
write_table_csv_17g(paths.constraint_index,index.constraint_index);
write_table_csv_17g(paths.block_index,index.block_index);
write_table_csv_17g(paths.fixed_zero_map,index.fixed_zero_map);
write_table_csv_17g(paths.permutation_map,index.permutation_map);
write_table_csv_17g(paths.soc_link_map,index.soc_link_map);
indexAudit = validate_canonical_index_framework(index);
write_table_csv_17g(paths.index_audit,indexAudit);

blockDimensions = make_block_dimensions(recursiveResult,config);
blockDiagnostics = make_block_diagnostics(recursiveResult,config);
comparison = make_direction_comparison(audit,recursiveResult,config, ...
    linearization,fullResult);
residualSummary = make_residual_summary(fullResult,recursiveResult,config);
socAudit = make_soc_boundary_audit(index,linearization,config);
fixedAudit = make_fixed_zero_recovery_audit(index,recursiveResult);
activity = make_renewable_activity(data,index,config);
write_table_csv_17g(paths.block_dimensions,blockDimensions);
write_table_csv_17g(paths.block_diagnostics,blockDiagnostics);
write_table_csv_17g(paths.direction_comparison,comparison);
write_table_csv_17g(paths.residual_summary,residualSummary);
write_table_csv_17g(paths.soc_boundary_audit,socAudit);
write_table_csv_17g(paths.fixed_zero_recovery_audit,fixedAudit);
write_table_csv_17g(paths.renewable_activity,activity);

if isempty(options.CodeScan)
    codeScan = scan_stage_a2_forbidden_code(string(runContext.project_root),config);
else
    codeScan = options.CodeScan;
end
write_table_csv_17g(paths.code_scan,codeScan);
identityEvidence = make_identity_evidence(linearization,fullResult, ...
    recursiveResult,index,config);
write_json_file(paths.linearization_identity,identityEvidence);

write_sparse_triplets(paths.core_triplets,recursiveResult.core.matrix);
write_sparse_triplets(paths.day_response_triplets,recursiveResult.day_response.S);
for position = 1:numel(config.hours)
    write_sparse_triplets(paths.hour_D_triplets(position), ...
        recursiveResult.partition.hour(position).D);
end
matrixManifest = make_matrix_manifest(paths,linearization,fullResult, ...
    recursiveResult,config.hours);
write_table_csv_17g(paths.matrix_manifest,matrixManifest);

hashTargets = targets(targets~=string(paths.artifact_hashes));
artifactHashes = make_artifact_hashes(runContext.root,hashTargets);
write_table_csv_17g(paths.artifact_hashes,artifactHashes);
exported = struct("paths",paths,"matrix_manifest",matrixManifest, ...
    "block_dimensions",blockDimensions,"block_diagnostics",blockDiagnostics, ...
    "direction_comparison",comparison,"residual_summary",residualSummary, ...
    "soc_boundary_audit",socAudit,"fixed_zero_recovery_audit",fixedAudit, ...
    "renewable_activity",activity,"code_scan",codeScan, ...
    "artifact_hashes",artifactHashes, ...
    "linearization_identity",identityEvidence);
end

function validate_inputs(context,index,config,lin,fullResult,recursive,audit)
requiredContext = ["root","run_id","stage_id","matrices_dir", ...
    "indices_dir","iterations_dir","project_root"];
assert(all(isfield(context,cellstr(requiredContext))) && isfolder(context.root), ...
    "stageA2:artifacts:InvalidRunContext","Invalid A2 run context.");
assert(string(context.stage_id)=="stage_A2", ...
    "stageA2:artifacts:StageMismatch","A2 exporter requires stage_A2.");
manifest = jsondecode(fileread(context.run_manifest_path));
assert(string(manifest.run_id)==string(context.run_id) && ...
    string(manifest.stage_id)=="stage_A2" && string(manifest.status)=="RUNNING", ...
    "stageA2:artifacts:ManifestIdentity", ...
    "A2 export requires the matching RUNNING manifest.");
requiredIndex = ["variable_index","constraint_index","block_index", ...
    "fixed_zero_map","permutation_map","soc_link_map"];
assert(all(isfield(index,cellstr(requiredIndex))) && ...
    all(cellfun(@istable,struct2cell(rmfield(index, ...
    setdiff(fieldnames(index),cellstr(requiredIndex)))))), ...
    "stageA2:artifacts:IndexContract","Six canonical index tables are required.");
assert(lin.counts.full_kkt==2749 && fullResult.kkt.dimension==2749 && ...
    isequal(size(fullResult.kkt.matrix),[2749 2749]) && ...
    issparse(fullResult.kkt.matrix), ...
    "stageA2:artifacts:FullKktDimension", ...
    "The complete A2 KKT must be sparse and 2749-by-2749.");
blocks = [recursive.partition.hour.dimension];
assert(numel(blocks)==24 && ...
    isequal(blocks,config.expected_hourly_kkt_block_dimensions) && ...
    sum(blocks)==589 && size(recursive.partition.M,1)==589 && ...
    issparse(recursive.partition.M), ...
    "stageA2:artifacts:HourBlockDimension", ...
    "A2 requires the natural 24-block, 589-dimensional sparse chain.");
assert(isequal(size(recursive.day_response.S),[14 14]) && ...
    isequal(size(recursive.core.matrix),[16 16]), ...
    "stageA2:artifacts:CoreDimension", ...
    "A2 day response/core must be 14-by-14 and 16-by-16.");
assert(height(index.fixed_zero_map)==61 && recursive.fixed_zero.count==61, ...
    "stageA2:artifacts:FixedZeroCount", ...
    "A2 fixed-zero mapping must contain the 61 data-derived rows.");
identities = string([lin.identity,fullResult.linearization_identity, ...
    recursive.linearization_identity,audit.linearization_identity]);
assert(isscalar(unique(identities)), ...
    "stageA2:artifacts:LinearizationIdentity", ...
    "Full, recursive, and audit routes must share one linearization identity.");
assert(recursive.no_full_direction_fallback, ...
    "stageA2:artifacts:RecursiveFallback", ...
    "Recursive evidence that permits a full-KKT fallback cannot be exported.");
end

