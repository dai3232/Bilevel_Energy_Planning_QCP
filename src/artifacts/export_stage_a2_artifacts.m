function targets = output_targets(paths)
names=fieldnames(paths); targets=strings(0,1);
for k=1:numel(names)
    if names{k}=="diagnostics_dir", continue; end
    targets=[targets;reshape(string(paths.(names{k})),[],1)]; %#ok<AGROW>
end
assert(numel(unique(lower(targets)))==numel(targets), ...
    "stageA2:artifacts:DuplicateTarget","A2 artifact targets are not unique.");
end

function assert_targets_absent(targets)
for target=targets.'
    if isfile(target) || isfolder(target)
        error("stageA2:artifacts:TargetExists", ...
            "A2 artifact target exists and will not be overwritten: %s",target);
    end
end
end

function ensure_directory(pathValue)
if isfolder(pathValue), return; end
if exist(pathValue,'file'), error("stageA2:artifacts:PathConflict", ...
        "A file exists where a directory is required: %s",pathValue); end
[created,message]=mkdir(pathValue);
assert(created,"stageA2:artifacts:CreateDirectory","%s",message);
end

function output = make_block_dimensions(recursive,config)
blocks=recursive.partition.hour; n=numel(blocks);
hour=reshape([blocks.hour],[],1); n_primal=reshape([blocks.n_primal],[],1);
n_equalities=reshape([blocks.n_equalities],[],1);
kkt_dimension=reshape([blocks.dimension],[],1);
expected_dimension=reshape(config.expected_hourly_kkt_block_dimensions,[],1);
status=repmat("PASS",n,1); status(kkt_dimension~=expected_dimension)="FAIL";
output=table(hour,n_primal,n_equalities,kkt_dimension,expected_dimension,status);
end

function output = make_block_diagnostics(recursive,config)
assert(isfield(recursive.thomas.diagnostics,"hour_block"), ...
    "stageA2:artifacts:HourDiagnosticsMissing", ...
    "The recursive solve did not return 24 hourly block diagnostics.");
value=recursive.thomas.diagnostics.hour_block;
assert(isstruct(value) && numel(value)==24, ...
    "stageA2:artifacts:HourDiagnosticsCount", ...
    "Exactly 24 hourly block diagnostics are required.");
output=struct2table(value(:));
required=["hour","dimension","D_numeric_rank","D_condition_2", ...
    "D_symmetry_relative","schur_numeric_rank","schur_condition_2", ...
    "schur_inertia_positive","schur_inertia_negative", ...
    "schur_inertia_zero","schur_factor_relative_residual","rhs_count"];
assert(all(ismember(required,string(output.Properties.VariableNames))), ...
    "stageA2:artifacts:HourDiagnosticsSchema", ...
    "Hourly diagnostic schema is incomplete.");
passed=output.dimension==reshape(config.expected_hourly_kkt_block_dimensions,[],1) & ...
    output.D_numeric_rank==output.dimension & isfinite(output.D_condition_2) & ...
    output.D_symmetry_relative<=config.tolerances.symmetry_relative & ...
    output.schur_numeric_rank==output.dimension & ...
    isfinite(output.schur_condition_2) & output.schur_inertia_zero==0 & ...
    output.schur_factor_relative_residual<= ...
        config.tolerances.recursive_full_kkt_relative_residual & ...
    output.rhs_count==15;
output.status=repmat("PASS",24,1); output.status(~passed)="FAIL";
end

function output = make_direction_comparison(audit,recursive,config,lin,fullResult)
identityMismatch=double(~(string(lin.identity)== ...
    string(fullResult.linearization_identity) && string(lin.identity)== ...
    string(recursive.linearization_identity)));
fixedValue=max([0;abs(recursive.fixed_zero.value(:))]);
fixedDirection=max([0;abs(recursive.fixed_zero.direction(:))]);
metric_id=["overall_direction_relative_2norm";"xi_direction_relative_2norm"; ...
    "y_direction_relative_2norm";"l_direction_relative_2norm"; ...
    "z_direction_relative_2norm";"fixed_zero_maximum_absolute_value"; ...
    "fixed_zero_maximum_absolute_direction";"linearization_identity_mismatch"; ...
    "recursive_full_direction_fallback_used";"reduced_assembly_relative_error"; ...
    "hour_chain_relative_residual";"global_core_relative_residual"];
actual_value=[audit.direction_relative_error;audit.component_relative_errors.xi; ...
    audit.component_relative_errors.y;audit.component_relative_errors.l; ...
    audit.component_relative_errors.z;fixedValue;fixedDirection;identityMismatch; ...
    double(~recursive.no_full_direction_fallback); ...
    recursive.partition.assembly_audit.matrix_relative_error; ...
    recursive.thomas.diagnostics.chain_relative_residual; ...
    recursive.core.diagnostics.relative_residual];
threshold=[repmat(config.tolerances.direction_relative_2norm,5,1);0;0;0;0; ...
    config.tolerances.symmetry_relative; ...
    config.tolerances.recursive_full_kkt_relative_residual; ...
    config.tolerances.recursive_full_kkt_relative_residual];
status=repmat("PASS",numel(actual_value),1);
status(~isfinite(actual_value) | actual_value>threshold)="FAIL";
output=table(metric_id,actual_value,threshold,status);
end

function output = make_residual_summary(fullResult,recursive,config)
K=fullResult.kkt.matrix; b=fullResult.kkt.rhs;
fullResidual=K*fullResult.direction-b; recursiveResidual=K*recursive.direction-b;
chainRhs=[recursive.partition.r_v,recursive.partition.B];
chainResidual=recursive.partition.M*recursive.thomas.stacked_solution-chainRhs;
coreResidual=recursive.core.matrix*recursive.core.solution-recursive.core.rhs;
route=["full_kkt_direct_preferred";"full_kkt_direct_hard_limit"; ...
    "recursive_direction_reinserted_in_full_kkt"; ...
    "recursive_hour_chain_15_rhs";"global_core_16"];
absolute_residual_2norm=[norm(fullResidual,2);norm(fullResidual,2); ...
    norm(recursiveResidual,2);norm(chainResidual,'fro');norm(coreResidual,2)];
rhs_2norm=[norm(b,2);norm(b,2);norm(b,2);norm(chainRhs,'fro'); ...
    norm(recursive.core.rhs,2)];
relative_residual_2norm=absolute_residual_2norm./max(1,rhs_2norm);
threshold=[config.tolerances.direct_preferred;config.tolerances.direct_maximum; ...
    repmat(config.tolerances.recursive_full_kkt_relative_residual,3,1)];
status=repmat("PASS",5,1);
status(~isfinite(relative_residual_2norm) | relative_residual_2norm>threshold)="FAIL";
output=table(route,absolute_residual_2norm,rhs_2norm, ...
    relative_residual_2norm,threshold,status);
end

function output = make_soc_boundary_audit(index,lin,config)
links=index.soc_link_map; constraints=index.constraint_index;
check_id=strings(0,1); hour=zeros(0,1); storage=zeros(0,1);
equation_id=strings(0,1); boundary_role=strings(0,1);
predecessor_hour=zeros(0,1); predecessor_soc_index=zeros(0,1);
current_soc_index=zeros(0,1); expected=strings(0,1); actual=strings(0,1);
status=strings(0,1);
for h=config.hours
    for s=1:2
        link=links(links.day==config.days(1) & links.hour==h & ...
            links.storage_id==s,:);
        equation=constraints(constraints.day==config.days(1) & ...
            constraints.hour==h & string(constraints.constraint_type)=="equality" & ...
            string(constraints.constraint_name)=="soc_dynamics" & ...
            constraints.asset_id==s,:);
        passed=height(link)==1 && height(equation)==1;
        if passed
            passed=lin.A(equation.global_row,link.current_soc_global_index)==1;
        end
        if h==config.start_hour
            role="initial_fixed_half_energy";
            if height(link)==1 && height(equation)==1
                passed=passed && isnan(link.predecessor_hour) && ...
                    link.predecessor_soc_global_index==0 && ...
                    link.initial_energy_fraction==0.5 && ...
                    lin.A(equation.global_row,lin.maps.q_day(12+s))==-0.5;
                expectedText="SOC(14,s,1)-0.5E(s); no previous-day link";
            else
                expectedText="one initial SOC equation";
            end
        else
            role="same_day_predecessor";
            if height(link)==1 && height(equation)==1
                passed=passed && link.predecessor_hour==h-1 && ...
                    link.predecessor_soc_global_index>0 && ...
                    lin.A(equation.global_row,link.predecessor_soc_global_index)==-1 && ...
                    lin.A(equation.global_row,lin.maps.q_day(12+s))==0;
            end
            expectedText=sprintf("same-day predecessor hour %d",h-1);
        end
        if height(link)==1
            pred=link.predecessor_hour; predIndex=link.predecessor_soc_global_index;
            current=link.current_soc_global_index;
            actualText=sprintf("source=%s; predecessor=%s; predecessor_index=%d", ...
                string(link.boundary_source),number_or_na(pred),predIndex);
        else
            pred=NaN; predIndex=0; current=0; actualText="MISSING_OR_DUPLICATE";
        end
        if height(equation)==1, eqId=string(equation.constraint_id); else, eqId="MISSING_OR_DUPLICATE"; end
        check_id(end+1,1)=sprintf("SOC-DYN-H%02d-S%02d",h,s); %#ok<AGROW>
        hour(end+1,1)=h; storage(end+1,1)=s; equation_id(end+1,1)=eqId;
        boundary_role(end+1,1)=role; predecessor_hour(end+1,1)=pred;
        predecessor_soc_index(end+1,1)=predIndex; current_soc_index(end+1,1)=current;
        expected(end+1,1)=expectedText; actual(end+1,1)=actualText;
        status(end+1,1)=pass_text(passed);
    end
end
for s=1:2
    link=links(links.day==config.days(1) & links.hour==config.terminal_hour & ...
        links.storage_id==s,:);
    equation=constraints(constraints.day==config.days(1) & ...
        constraints.hour==config.terminal_hour & ...
        string(constraints.constraint_type)=="equality" & ...
        string(constraints.constraint_name)=="terminal_soc" & ...
        constraints.asset_id==s,:);
    passed=height(link)==1 && height(equation)==1 && ...
        link.terminal_equality && link.terminal_energy_fraction==0.5;
    if passed
        passed=lin.A(equation.global_row,link.current_soc_global_index)==1 && ...
            lin.A(equation.global_row,lin.maps.q_day(12+s))==-0.5;
        eqId=string(equation.constraint_id); current=link.current_soc_global_index;
        actualText="hour=24; fraction="+compose("%.17g",link.terminal_energy_fraction);
    else
        eqId="MISSING_OR_DUPLICATE"; current=0; actualText="MISSING_OR_DUPLICATE";
    end
    check_id(end+1,1)=sprintf("SOC-END-H24-S%02d",s); hour(end+1,1)=24;
    storage(end+1,1)=s; equation_id(end+1,1)=eqId;
    boundary_role(end+1,1)="terminal_fixed_half_energy";
    predecessor_hour(end+1,1)=24; predecessor_soc_index(end+1,1)=current;
    current_soc_index(end+1,1)=current;
    expected(end+1,1)="SOC(14,s,24)-0.5E(s)=0 in final hour block";
    actual(end+1,1)=actualText; status(end+1,1)=pass_text(passed);
end
output=table(check_id,hour,storage,equation_id,boundary_role, ...
    predecessor_hour,predecessor_soc_index,current_soc_index, ...
    expected,actual,status);
end

function output = make_fixed_zero_recovery_audit(index,recursive)
map=index.fixed_zero_map; count=height(map);
assert(count==recursive.fixed_zero.count && count==61, ...
    "stageA2:artifacts:FixedZeroCount", ...
    "Canonical and recovered A2 fixed-zero counts must both equal 61.");
recovered_value=reshape(double(recursive.fixed_zero.value),[],1);
recovered_direction=reshape(double(recursive.fixed_zero.direction),[],1);
assert(numel(recovered_value)==count && numel(recovered_direction)==count, ...
    "stageA2:artifacts:FixedZeroShape","Fixed-zero recovery shape is invalid.");
status=repmat("PASS",count,1);
passed=map.fixed_value==0 & map.fixed_direction_value==0 & ...
    recovered_value==0 & recovered_direction==0 & ...
    string(map.inequality_status)=="NOT_APPLICABLE_BOTH_BOUNDS";
status(~passed)="FAIL";
output=addvars(map,recovered_value,recovered_direction,status, ...
    'NewVariableNames',{'recovered_value','recovered_direction','status'});
end

function output = make_renewable_activity(data,index,config)
n=numel(config.hours)*10;
day=repmat(config.days(1),n,1); hour=zeros(n,1); asset_type=strings(n,1);
asset_id=zeros(n,1); variable_name=strings(n,1); kappa=zeros(n,1);
exact_zero=false(n,1); active_variable_present=false(n,1);
active_global_index=zeros(n,1); fixed_zero_map_present=false(n,1);
lower_bound_removed=false(n,1); upper_bound_removed=false(n,1);
status=strings(n,1); row=0;
for h=config.hours
    for kind=["wind","solar"]
        for asset=1:5
            row=row+1; hour(row)=h; asset_type(row)=kind; asset_id(row)=asset;
            if kind=="wind"
                variable_name(row)="PW";
                kappa(row)=data.timeseries.windAvailability(config.days(1),h,asset);
            else
                variable_name(row)="PP";
                kappa(row)=data.timeseries.solarAvailability(config.days(1),h,asset);
            end
            exact_zero(row)=kappa(row)==0;
            variable=index.variable_index(index.variable_index.day==config.days(1) & ...
                index.variable_index.hour==h & ...
                string(index.variable_index.asset_type)==kind & ...
                index.variable_index.asset_id==asset & ...
                string(index.variable_index.variable_name)==variable_name(row),:);
            fixed=index.fixed_zero_map(index.fixed_zero_map.day==config.days(1) & ...
                index.fixed_zero_map.hour==h & ...
                string(index.fixed_zero_map.asset_type)==kind & ...
                index.fixed_zero_map.asset_id==asset & ...
                string(index.fixed_zero_map.variable_name)==variable_name(row),:);
            active_variable_present(row)=height(variable)==1;
            if height(variable)==1, active_global_index(row)=variable.global_index_start; end
            fixed_zero_map_present(row)=height(fixed)==1;
            if height(fixed)==1
                both=string(fixed.inequality_status)=="NOT_APPLICABLE_BOTH_BOUNDS";
                lower_bound_removed(row)=both; upper_bound_removed(row)=both;
            end
            passed=(exact_zero(row) && ~active_variable_present(row) && ...
                fixed_zero_map_present(row) && lower_bound_removed(row) && ...
                upper_bound_removed(row)) || (~exact_zero(row) && ...
                active_variable_present(row) && ~fixed_zero_map_present(row));
            status(row)=pass_text(passed);
        end
    end
end
output=table(day,hour,asset_type,asset_id,variable_name,kappa,exact_zero, ...
    active_variable_present,active_global_index,fixed_zero_map_present, ...
    lower_bound_removed,upper_bound_removed,status);
end

