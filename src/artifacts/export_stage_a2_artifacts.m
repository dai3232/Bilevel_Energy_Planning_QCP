function output = make_matrix_manifest(paths,lin,fullResult,recursive,hours)
names=["linearization_H";"linearization_A";"linearization_G"; ...
    "full_kkt";"reduced_W";"reduced_saddle"];
values={lin.H;lin.A;lin.G;fullResult.kkt.matrix;recursive.reduced.W; ...
    recursive.reduced.saddle};
artifactPaths=[repmat(string(paths.linearization_mat),3,1); ...
    string(paths.full_kkt_mat);repmat(string(paths.recursive_blocks_mat),2,1)];
for k=1:numel(hours)
    names=[names;sprintf("hour_%02d_D",hours(k)); ...
        sprintf("hour_%02d_E",hours(k));sprintf("hour_%02d_B",hours(k))]; %#ok<AGROW>
    values=[values;{recursive.partition.hour(k).D; ...
        recursive.partition.hour(k).E;recursive.partition.hour(k).B}]; %#ok<AGROW>
    artifactPaths=[artifactPaths;repmat(string(paths.recursive_blocks_mat),3,1)]; %#ok<AGROW>
end
names=[names;"hour_chain_M";"day_response_S";"global_core"];
values=[values;{recursive.partition.M;recursive.day_response.S;recursive.core.matrix}];
artifactPaths=[artifactPaths;repmat(string(paths.recursive_blocks_mat),3,1)];
n=numel(values); rows=zeros(n,1); columns=zeros(n,1); nonzero=zeros(n,1);
is_sparse=false(n,1); sha256=strings(n,1); path=strings(n,1);
for k=1:n
    [rows(k),columns(k)]=size(values{k}); nonzero(k)=nnz(values{k});
    is_sparse(k)=issparse(values{k}); sha256(k)=compute_sha256_file(artifactPaths(k));
    path(k)=relative_path(fileparts(fileparts(paths.linearization_mat)),artifactPaths(k));
end
matrix_name=string(names);
output=table(matrix_name,rows,columns,nonzero,is_sparse,sha256,path, ...
    'VariableNames',{'matrix_name','rows','columns','nnz','is_sparse','sha256','path'});
end

function output = make_artifact_hashes(runRoot,targets)
n=numel(targets); relative_path_value=strings(n,1); sha256=strings(n,1);
bytes=zeros(n,1); artifact_type=strings(n,1);
for k=1:n
    assert(isfile(targets(k)),"stageA2:artifacts:MissingWrittenTarget", ...
        "Expected A2 artifact was not written: %s",targets(k));
    relative_path_value(k)=relative_path(runRoot,targets(k));
    sha256(k)=compute_sha256_file(targets(k)); info=dir(targets(k)); bytes(k)=info.bytes;
    [~,~,extension]=fileparts(targets(k)); artifact_type(k)=erase(lower(string(extension)),".");
end
scope=repmat("numerical_export",n,1); status=repmat("PASS",n,1);
output=table(relative_path_value,sha256,bytes,artifact_type,scope,status, ...
    'VariableNames',{'relative_path','sha256','bytes','artifact_type','scope','status'});
end

function value = relative_path(root,pathValue)
root=string(char(java.io.File(char(root)).getCanonicalPath()));
pathValue=string(char(java.io.File(char(pathValue)).getCanonicalPath()));
prefix=root+filesep;
assert(startsWith(lower(pathValue),lower(prefix)), ...
    "stageA2:artifacts:PathOutsideRun","Artifact path is outside run root.");
value=replace(extractAfter(pathValue,strlength(prefix)),string(filesep),"/");
end

function value = pass_text(condition)
if condition, value="PASS"; else, value="FAIL"; end
end

function value = number_or_na(number)
if isfinite(number), value=sprintf("%d",number); else, value="NA"; end
end
