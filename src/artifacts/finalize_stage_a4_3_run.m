function passed = validate_converged_aggregate_campaign( ...
        projectRoot,results,summary,expectedSuites,a43Expected)
passed = false;
requiredSummary = ["execution_status","campaign_mode", ...
    "stage_pass_eligible","test_total","test_passed","test_failed", ...
    "test_incomplete","test_names_unique_within_suite", ...
    "suite_label_test_name_unique","suite_counts"];
if ~all(isfield(summary,cellstr(requiredSummary))) || ...
        string(summary.execution_status)~="COMPLETE" || ...
        string(summary.campaign_mode)~="converged_full_validation" || ...
        ~logical(summary.stage_pass_eligible) || ...
        double(summary.test_total)~=257 || ...
        double(summary.test_passed)~=257 || ...
        double(summary.test_failed)~=0 || ...
        double(summary.test_incomplete)~=0 || ...
        ~logical(summary.test_names_unique_within_suite) || ...
        ~logical(summary.suite_label_test_name_unique)
    return
end
labels = string(results.suite_label);
if height(results)~=257 || ...
        ~isequal(unique(labels,"stable"),expectedSuites(:,1))
    return
end
for row = 1:size(expectedSuites,1)
    label = expectedSuites(row,1);
    expectedCount = str2double(expectedSuites(row,2));
    subset = results(labels==label,:);
    if height(subset)~=expectedCount || ...
            numel(unique(string(subset.test_name)))~=expectedCount
        return
    end
end
if ~aggregate_suite_names_match_inventory(results, ...
        "stage_A4_3",a43Expected) || ...
        ~aggregate_suite_names_match_inventory(results, ...
        "stage_A4_RNS_1",read_csv(fullfile(projectRoot,"tests", ...
        "stage_A4_RNS_1_expected_test_inventory.csv"))) || ...
        ~aggregate_suite_names_match_inventory(results, ...
        "stage_A4_2D_2A_R1",read_csv(fullfile(projectRoot,"tests", ...
        "stage_A4_2D_2A_R1_expected_test_inventory.csv")))
    return
end
passed = validate_suite_count_summary(summary.suite_counts, ...
    expectedSuites);
end

function passed = validate_nonconverged_aggregate_campaign(results,summary)
passed = false;
requiredSummary = ["execution_status","campaign_mode", ...
    "stage_pass_eligible","test_total","test_passed","test_failed", ...
    "test_incomplete","test_names_unique_within_suite", ...
    "suite_label_test_name_unique","suite_counts"];
if ~all(isfield(summary,cellstr(requiredSummary))) || ...
        string(summary.execution_status)~="COMPLETE" || ...
        string(summary.campaign_mode)~="nonconverged_direct_validation" || ...
        logical(summary.stage_pass_eligible) || ...
        ~logical(summary.test_names_unique_within_suite) || ...
        ~logical(summary.suite_label_test_name_unique)
    return
end
labels = unique(string(results.suite_label),"stable");
% A failed numerical candidate runs only the direct A4-3/finalizer checks;
% it must never masquerade as the 257-test Stage-PASS campaign.
expected = ["stage_A4_3","27";"stage_A4_3_finalizer","5"];
if ~isequal(labels,expected(:,1)) || height(results)~=32
    return
end
forbidden = ["stage_A4_RNS_1","stage_A4_2D_2A_R1", ...
    "stage_A4_regression_195"];
if any(ismember(labels,forbidden))
    return
end
for row = 1:numel(labels)
    if nnz(string(results.suite_label)==labels(row))~= ...
            str2double(expected(row,2))
        return
    end
end
passed = validate_suite_count_summary(summary.suite_counts,expected);
end

function passed = aggregate_suite_names_match_inventory( ...
        results,suiteLabel,inventory)
required = "test_name";
passed = all(ismember(required,string(inventory.Properties.VariableNames)));
if ~passed
    return
end
observed = string(results.test_name( ...
    string(results.suite_label)==suiteLabel));
expected = string(inventory.test_name);
passed = isequal(observed,expected);
end

function passed = validate_suite_count_summary(suiteCounts,expected)
passed = false;
if ~isstruct(suiteCounts) || numel(suiteCounts)~=size(expected,1)
    return
end
required = ["suite_label","test_total","test_passed", ...
    "test_failed","test_incomplete","duration_seconds"];
if ~all(isfield(suiteCounts,cellstr(required)))
    return
end
for row = 1:size(expected,1)
    count = str2double(expected(row,2));
    item = suiteCounts(row);
    if string(item.suite_label)~=expected(row,1) || ...
            double(item.test_total)~=count || ...
            double(item.test_passed)~=count || ...
            double(item.test_failed)~=0 || ...
            double(item.test_incomplete)~=0 || ...
            ~isscalar(item.duration_seconds) || ...
            ~isfinite(double(item.duration_seconds)) || ...
            double(item.duration_seconds)<0
        return
    end
end
passed = true;
end

function passed = validate_junit(pathValue,expectedCount)
passed = false;
try
    document = xmlread(pathValue);
    passed = double(document.getElementsByTagName( ...
        "testcase").getLength())==expectedCount;
catch
end
end

function passed = validate_fixed_test_hash_manifest(pathValue,directory)
hashes = read_csv(pathValue);
required = ["names","sha256","bytes","status"];
expectedNames = ["test_inventory.csv";"test_results.csv"; ...
    "test_results.xml";"matlab_test_console.log"; ...
    "test_command.txt";"test_summary.json"];
passed = all(ismember(required,string(hashes.Properties.VariableNames))) && ...
    height(hashes)==6 && ...
    isequal(string(hashes.names),expectedNames) && ...
    all(string(hashes.status)=="PASS");
if ~passed
    return
end
for row = 1:height(hashes)
    target = fullfile(directory,string(hashes.names(row)));
    info = dir(target);
    if ~isfile(target) || ~isscalar(info) || ...
            double(hashes.bytes(row))~=info.bytes || ...
            lower(string(hashes.sha256(row)))~= ...
            lower(string(compute_sha256_file(target)))
        passed = false;
        return
    end
end
end

