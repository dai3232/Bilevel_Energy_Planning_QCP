function value = logical_column(input)
if islogical(input)
    value = input;
elseif isnumeric(input)
    value = input~=0;
else
    text = lower(strip(string(input)));
    assert(all(ismember(text,["true","false","1","0"])), ...
        "stageA4:a43:finalizer:LogicalColumn", ...
        "A persisted logical column contains an invalid value.");
    value = text=="true" | text=="1";
end
value = value(:);
end

function passed = tables_equivalent(left,right)
passed = istable(left) && istable(right) && ...
    height(left)==height(right) && ...
    isequal(string(left.Properties.VariableNames), ...
    string(right.Properties.VariableNames));
if ~passed
    return
end
for name = string(left.Properties.VariableNames)
    a = left.(name); b = right.(name);
    if (isnumeric(a)||islogical(a)) && (isnumeric(b)||islogical(b))
        equal = isequaln(double(a),double(b));
    else
        aText = string(a);
        bText = string(b);
        aText(ismissing(aText)) = "";
        bText(ismissing(bText)) = "";
        equal = isequal(aText,bText);
    end
    if ~equal
        passed = false;
        return
    end
end
end

function passed = advisory_tables_equivalent(left,right)
% Historical A4-3 static evidence used UNKNOWN when localized checkcode
% messages omitted a trailing "(ID)" token.  Accept that representation
% only when every other field is exact and the independently rebuilt ID is
% one of the two explicitly nonblocking advisory IDs.
if tables_equivalent(left,right)
    passed = true;
    return
end
passed = istable(left) && istable(right) && ...
    height(left)==height(right) && ...
    isequal(string(left.Properties.VariableNames), ...
        string(right.Properties.VariableNames)) && ...
    ismember("identifier",string(left.Properties.VariableNames));
if ~passed
    return
end
leftId = string(left.identifier);
rightId = string(right.identifier);
legacy = leftId=="UNKNOWN" & ismember(rightId,["MSNU","SPRIX"]);
if ~all(leftId==rightId | legacy)
    passed = false;
    return
end
left.identifier = right.identifier;
passed = tables_equivalent(left,right);
end

function value = read_csv(pathValue)
value = readtable(pathValue,"TextType","string", ...
    "VariableNamingRule","preserve","Delimiter",",");
end

function value = read_json(pathValue)
try
    value = jsondecode(fileread(pathValue));
catch exception
    error("stageA4:a43:finalizer:JsonRead", ...
        "Could not decode %s: %s",pathValue,exception.message);
end
end

function value = canonical_directory(pathValue,errorId)
assert(isfolder(pathValue),errorId, ...
    "Required directory does not exist: %s",pathValue);
value = string(char(java.io.File(char(pathValue)).getCanonicalPath()));
end

function value = canonical_file(pathValue,errorId)
assert(isfile(pathValue),errorId, ...
    "Required file does not exist: %s",pathValue);
value = string(char(java.io.File(char(pathValue)).getCanonicalPath()));
end

function passed = path_is_inside(pathValue,root)
pathValue = string(char(java.io.File(char(pathValue)).getCanonicalPath()));
root = string(char(java.io.File(char(root)).getCanonicalPath()));
passed = startsWith(lower(pathValue),lower(root+filesep));
end

function value = relative_path(pathValue,root)
pathValue = string(char(java.io.File(char(pathValue)).getCanonicalPath()));
root = string(char(java.io.File(char(root)).getCanonicalPath()));
assert(startsWith(lower(pathValue),lower(root+filesep)), ...
    "stageA4:a43:finalizer:RelativePath", ...
    "Evidence path is outside the current run: %s",pathValue);
value = replace(extractAfter(pathValue,strlength(root)+1),"\","/");
end

