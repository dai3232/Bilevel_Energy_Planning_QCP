function validate_environment_and_inputs(context,paths,manifest)
environment = read_csv(paths.environment);
inputs = read_csv(paths.input_hashes);
assert(all(ismember(["blocking","status"], ...
    string(environment.Properties.VariableNames))) && ...
    all(ismember(["expectedSHA256","actualSHA256","status"], ...
    string(inputs.Properties.VariableNames))), ...
    "stageA4:a43:finalizer:EnvironmentSchema", ...
    "Environment or input-hash evidence has an invalid schema.");
blocking = logical_column(environment.blocking);
assert(all(string(environment.status(blocking))=="PASS"), ...
    "stageA4:a43:finalizer:EnvironmentFailed", ...
    "A blocking environment check did not pass.");
assert(height(inputs)==2 && all(string(inputs.status)=="PASS") && ...
    all(lower(string(inputs.expectedSHA256))== ...
    lower(string(inputs.actualSHA256))) && ...
    all(strlength(string(inputs.actualSHA256))==64), ...
    "stageA4:a43:finalizer:InputHashFailed", ...
    "Controlled input SHA256 evidence did not pass.");
assert(isfield(manifest,"input_hashes") && ...
    isfield(manifest.input_hashes,"base_parameters") && ...
    isfield(manifest.input_hashes,"timeseries") && ...
    lower(string(manifest.input_hashes.base_parameters))== ...
        lower(string(inputs.actualSHA256(1))) && ...
    lower(string(manifest.input_hashes.timeseries))== ...
        lower(string(inputs.actualSHA256(2))), ...
    "stageA4:a43:finalizer:InputManifestIdentity", ...
    "run_manifest.json and input_hashes.csv disagree.");
for candidate = [string(paths.environment),string(paths.input_hashes)]
    assert(path_is_inside(canonical_file(candidate, ...
        "stageA4:a43:finalizer:EnvironmentEvidenceScope"), ...
        string(context.root)), ...
        "stageA4:a43:finalizer:EnvironmentEvidenceScope", ...
        "Environment/input evidence must be inside the current run.");
end
end

function findings = run_code_analyzer_records(root,closure)
file = strings(0,1);
line = zeros(0,1);
column = zeros(0,1);
identifier = strings(0,1);
message = strings(0,1);
for k = 1:height(closure)
    relative = string(closure.relative_path(k));
    if ~endsWith(relative,".m","IgnoreCase",true)
        continue
    end
    absolute = fullfile(root,replace(relative,"/",filesep));
    observed = checkcode(absolute,"-id");
    for j = 1:numel(observed)
        file(end+1,1) = relative; %#ok<AGROW>
        line(end+1,1) = double(observed(j).line); %#ok<AGROW>
        currentColumn = observed(j).column;
        if isempty(currentColumn)
            column(end+1,1) = NaN; %#ok<AGROW>
        else
            column(end+1,1) = double(currentColumn(1)); %#ok<AGROW>
        end
        text = string(observed(j).message);
        token = regexp(char(text),"\(([A-Za-z0-9_]+)\)[ \t]*$", ...
            "tokens","once");
        if isempty(token)
            identifier(end+1,1) = string(observed(j).id); %#ok<AGROW>
        else
            identifier(end+1,1) = string(token{1}); %#ok<AGROW>
        end
        message(end+1,1) = text; %#ok<AGROW>
    end
end
findings = table(file,line,column,identifier,message);
end

