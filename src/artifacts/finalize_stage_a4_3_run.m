function outcome = finalize_stage_a4_3_run(projectRoot,runId,options)
%FINALIZE_STAGE_A4_3_RUN Deterministically terminalize one completed A4-3 run.
%
% This function never solves a Newton system, advances an iterate, changes
% CURRENT_STAGE.md, or enters Stage B.  It consumes only persisted run
% evidence.  The manifest must still be RUNNING and the numerical terminal
% state must already be CONVERGED, MAX_ITERATIONS, or NUMERICAL_FAILURE.
%
% By default the function performs the unique RUNNING -> PASS or
% RUNNING -> FAIL_RETRYABLE transition.  FinalizeManifest=false writes and
% freezes the derived acceptance/log/hash package but deliberately leaves
% the manifest RUNNING for an external review.  A later default call must
% reproduce that package byte-for-byte before terminalization.
%
% Required externally persisted finalization evidence:
%   reports/report_structure_validation.csv
%   reports/report_visual_qa.csv
%   reports/report_sha256.csv
%   tests/test_results.csv
%   tests/test_summary.json
%   tests/static_check_summary.csv
%   tests/a4_3_specialty/{suite_identity.json,test_inventory.csv,
%     test_results.csv,test_results.xml,matlab_test_console.log,
%     test_command.txt,test_summary.json,test_evidence_sha256.csv}

arguments
    projectRoot (1,1) string
    runId (1,1) string
    options.FinalizeManifest (1,1) logical = true
    options.ReportStructureValidationPath (1,1) string = ""
    options.ReportVisualValidationPath (1,1) string = ""
    options.ReportHashManifestPath (1,1) string = ""
    options.TestResultsPath (1,1) string = ""
    options.TestSummaryPath (1,1) string = ""
    options.StaticCheckSummaryPath (1,1) string = ""
    options.A43SpecialtyEvidenceDirectory (1,1) string = ""
end

projectRoot = canonical_directory(projectRoot, ...
    "stageA4:a43:finalizer:ProjectRoot");
assert(~isempty(regexp(char(runId), ...
    "^[A-Za-z0-9][A-Za-z0-9._-]*$","once")), ...
    "stageA4:a43:finalizer:RunId", ...
    "runId contains characters that are unsafe in a run path.");
runRoot = canonical_directory(fullfile(projectRoot,"runs",runId), ...
    "stageA4:a43:finalizer:RunRoot");
context = make_context(projectRoot,runRoot,runId);
manifest = read_json(context.run_manifest_path);
validate_running_manifest(manifest,context);

currentStagePath = fullfile(projectRoot,"CURRENT_STAGE.md");
currentStageHashBefore = compute_sha256_file(currentStagePath);
assert_current_stage_ready(currentStagePath);

paths = resolve_paths(context,options);
assert_all_paths_inside_current_run(paths,context.root);
require_finalization_inputs(paths);
[runResult,iterationEvidence,directionEvidence] = ...
    load_numeric_evidence(context,manifest);
physicalAudit = read_csv(paths.physical_audit);
validate_environment_and_inputs(context,paths,manifest);
historicalAudit = read_json(paths.historical_audit);
historicalPassed = scalar_logical_field( ...
    historicalAudit,"passed","historical_runs_audit.json");
assert(historicalPassed, ...
    "stageA4:a43:finalizer:HistoricalRunsChanged", ...
    "The persisted historical-run preservation audit did not pass.");

reportEvidence = load_report_evidence(context,paths);
acceptance = evaluate_stage_a4_3_acceptance( ...
    projectRoot,runResult,physicalAudit, ...
    "ReportEvidence",reportEvidence);
testAudit = validate_test_evidence( ...
    projectRoot,context,manifest,runResult,paths);
staticAudit = validate_static_evidence( ...
    projectRoot,context,manifest,runResult,paths.static_summary, ...
    paths.forbidden_code,paths.forbidden_execution, ...
    paths.dependency_closure,paths.code_analyzer_results, ...
    paths.git_diff_check,paths.effective_config,paths.stage_snapshot, ...
    paths.code_analyzer_scope,paths.code_analyzer_advisories);
identityAudit = validate_manifest_numeric_identity( ...
    manifest,runResult,iterationEvidence,directionEvidence);

numericalTerminal = string(runResult.run_terminal_state);
assert(ismember(numericalTerminal, ...
    ["CONVERGED","MAX_ITERATIONS","NUMERICAL_FAILURE"]), ...
    "stageA4:a43:finalizer:NumericalState", ...
    "Only a completed A4-3 numerical terminal state can be finalized.");
if numericalTerminal=="MAX_ITERATIONS"
    assert(runResult.iteration_count==100, ...
        "stageA4:a43:finalizer:MaxIterationIdentity", ...
        "MAX_ITERATIONS requires exactly 100 accepted updates.");
end

acceptancePassed = height(acceptance)==7 && ...
    all(string(acceptance.status)=="PASS");
candidatePass = numericalTerminal=="CONVERGED" && ...
    logical(runResult.convergence_achieved) && acceptancePassed && ...
    testAudit.passed && staticAudit.passed && identityAudit.passed && ...
    historicalPassed;
if candidatePass
    finalStatus = "PASS";
else
    finalStatus = "FAIL_RETRYABLE";
end
% Reaching 100 iterations is never success, even if a malformed caller
% supplied superficially small final metrics.
assert(numericalTerminal~="MAX_ITERATIONS" || finalStatus~="PASS", ...
    "stageA4:a43:finalizer:MaxIterationsCannotPass", ...
    "MAX_ITERATIONS must never be terminalized as PASS.");

[issues,decisions] = make_final_logs( ...
    context,runResult,acceptance,testAudit,staticAudit, ...
    identityAudit,historicalPassed,finalStatus);
preserve_pre_finalization_tables(context);
write_derived_table(context.acceptance_results_path,acceptance);
write_derived_table(context.issue_log_path,issues);
write_derived_table(context.decision_log_path,decisions);

evidencePath = fullfile(context.acceptance_dir,"evidence_hashes.csv");
[evidence,reusedEvidence] = materialize_complete_hash_inventory( ...
    context,manifest,evidencePath);
assert(height(evidence)>0 && all(string(evidence.status)=="PASS"), ...
    "stageA4:a43:finalizer:EvidenceInventory", ...
    "The complete A4-3 SHA256 inventory is not valid.");

assert_current_stage_ready(currentStagePath);
currentStageHashAfter = compute_sha256_file(currentStagePath);
assert(lower(string(currentStageHashAfter))== ...
    lower(string(currentStageHashBefore)), ...
    "stageA4:a43:finalizer:CurrentStageChanged", ...
    "CURRENT_STAGE.md changed during finalization.");

updates = make_manifest_updates( ...
    context,runResult,acceptance,issues,testAudit,staticAudit, ...
    reportEvidence,evidence,evidencePath,finalStatus, ...
    currentStageHashAfter,reusedEvidence);
if options.FinalizeManifest
    finalManifest = finalize_run_manifest(context,finalStatus,updates);
    assert_current_stage_ready(currentStagePath);
    assert(lower(string(compute_sha256_file(currentStagePath)))== ...
        lower(string(currentStageHashBefore)), ...
        "stageA4:a43:finalizer:CurrentStageChanged", ...
        "CURRENT_STAGE.md changed during manifest terminalization.");
else
    finalManifest = update_running_run_manifest(context,updates);
end

outcome = struct( ...
    "run_id",string(context.run_id), ...
    "run_root",string(context.root), ...
    "numerical_terminal_state",numericalTerminal, ...
    "candidate_terminal_status",finalStatus, ...
    "manifest_status",string(finalManifest.status), ...
    "manifest_finalized",logical(options.FinalizeManifest), ...
    "acceptance",acceptance, ...
    "issues",issues, ...
    "decisions",decisions, ...
    "test_audit",testAudit, ...
    "static_audit",staticAudit, ...
    "identity_audit",identityAudit, ...
    "evidence_hashes",evidence, ...
    "evidence_hashes_path",string(evidencePath), ...
    "evidence_inventory_reused",reusedEvidence, ...
    "current_stage","stage_A4 / READY", ...
    "stage_b_entered",false);
end

