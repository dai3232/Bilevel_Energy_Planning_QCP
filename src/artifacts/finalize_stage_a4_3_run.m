function value = choose_path(configured,defaultValue)
if strlength(strip(configured))==0
    value = string(defaultValue);
else
    value = string(configured);
end
end

function require_finalization_inputs(paths)
names = string(fieldnames(paths));
for k = 1:numel(names)
    value = string(paths.(names(k)));
    assert(isfile(value), ...
        "stageA4:a43:finalizer:EvidenceMissing", ...
        "Required A4-3 finalization evidence is missing: %s",value);
end
end

function validate_running_manifest(manifest,context)
required = ["run_id","stage_id","status","started_at","git_commit", ...
    "input_hashes","a4_3_run_terminal_state", ...
    "convergence_achieved","historical_runs_unchanged", ...
    "stage_b_entered"];
assert(all(isfield(manifest,cellstr(required))), ...
    "stageA4:a43:finalizer:ManifestSchema", ...
    "run_manifest.json is missing required A4-3 fields.");
assert(string(manifest.run_id)==string(context.run_id) && ...
    string(manifest.stage_id)=="stage_A4", ...
    "stageA4:a43:finalizer:ManifestIdentity", ...
    "Run context and manifest identity differ.");
assert(string(manifest.status)=="RUNNING", ...
    "stageA4:a43:finalizer:ManifestAlreadyFinal", ...
    "Only a RUNNING A4-3 manifest can be finalized.");
assert(~logical(manifest.stage_b_entered), ...
    "stageA4:a43:finalizer:StageBoundary", ...
    "The A4-3 run must not enter Stage B.");
assert(logical(manifest.historical_runs_unchanged), ...
    "stageA4:a43:finalizer:HistoricalManifest", ...
    "The manifest does not record an unchanged historical-run boundary.");
end

function [runResult,iterationEvidence,directionEvidence] = ...
        load_numeric_evidence(context,manifest)
payload = load(fullfile(context.root,"a4_3_solver_result.mat"));
assert(isfield(payload,"summary") && isstruct(payload.summary) && ...
    isscalar(payload.summary), ...
    "stageA4:a43:finalizer:SolverResult", ...
    "a4_3_solver_result.mat does not contain scalar summary evidence.");
runResult = payload.summary;
required = ["run_terminal_state","convergence_achieved", ...
    "iteration_count","final_metrics","direction_audit", ...
    "iteration_summary","execution_audit","full_kkt_audit_count"];
assert(all(isfield(runResult,cellstr(required))), ...
    "stageA4:a43:finalizer:SolverResult", ...
    "The persisted solver summary is incomplete.");
iterationEvidence = read_csv(fullfile(context.root,"iterations", ...
    "iteration_summary.csv"));
directionEvidence = read_csv(fullfile(context.root,"iterations", ...
    "direction_audit.csv"));
assert(tables_equivalent(runResult.iteration_summary,iterationEvidence), ...
    "stageA4:a43:finalizer:IterationMismatch", ...
    "Persisted iteration CSV differs from the solver MAT summary.");
assert(tables_equivalent(runResult.direction_audit,directionEvidence), ...
    "stageA4:a43:finalizer:DirectionMismatch", ...
    "Persisted direction CSV differs from the solver MAT summary.");
assert(string(manifest.a4_3_run_terminal_state)== ...
    string(runResult.run_terminal_state) && ...
    logical(manifest.convergence_achieved)== ...
    logical(runResult.convergence_achieved), ...
    "stageA4:a43:finalizer:ManifestNumericalMismatch", ...
    "Manifest and solver MAT numerical terminal facts differ.");
end

function reportEvidence = load_report_evidence(context,paths)
reportPaths = struct( ...
    "model_report",char(paths.model_report), ...
    "issue_report",char(paths.issue_report), ...
    "run_summary",char(paths.run_summary_report));
[packagePassed,recomputed] = validate_stage_a4_report_set( ...
    reportPaths,string(context.run_id));
persistedStructure = read_csv(paths.report_structure);
assert(structure_audits_equivalent(persistedStructure,recomputed), ...
    "stageA4:a43:finalizer:ReportStructureMismatch", ...
    "Persisted report structure QA differs from independent validation.");

visual = read_csv(paths.report_visual);
validate_visual_inventory(context,reportPaths,visual);
reportHashes = read_csv(paths.report_hashes);
validate_report_hashes(context,reportPaths,reportHashes);
% A structurally invalid package is a truthful FAIL_RETRYABLE fact rather
% than a reason to fabricate PASS.  Hash/path inconsistency above remains
% a hard evidence error and leaves the manifest RUNNING.
if ~packagePassed
    recomputed.status(:) = "FAIL";
end
reportEvidence = struct( ...
    "run_root",string(context.root), ...
    "report_paths",reportPaths, ...
    "structure_validation",recomputed, ...
    "visual_validation",visual, ...
    "hash_manifest",reportHashes, ...
    "package_passed",packagePassed);
end

function passed = structure_audits_equivalent(left,right)
passed = false;
required = ["report_key","path","sha256","status"];
if ~all(ismember(required,string(left.Properties.VariableNames))) || ...
        height(left)~=3 || height(right)~=3
    return
end
[~,leftOrder] = sort(string(left.report_key));
[~,rightOrder] = sort(string(right.report_key));
left = left(leftOrder,:); right = right(rightOrder,:);
if ~isequal(string(left.report_key),string(right.report_key))
    return
end
for k = 1:height(left)
    if canonical_file(left.path(k), ...
            "stageA4:a43:finalizer:ReportStructurePath")~= ...
            canonical_file(right.path(k), ...
            "stageA4:a43:finalizer:ReportStructurePath") || ...
            lower(string(left.sha256(k)))~=lower(string(right.sha256(k))) || ...
            string(left.status(k))~=string(right.status(k))
        return
    end
end
passed = true;
end

function validate_visual_inventory(context,reportPaths,visual)
required = ["report_path","page_number","page_count","image_path", ...
    "image_sha256","status"];
assert(all(ismember(required,string(visual.Properties.VariableNames))) && ...
    height(visual)>=3, ...
    "stageA4:a43:finalizer:VisualSchema", ...
    "Report visual QA evidence has an invalid schema.");
expected = string(struct2cell(reportPaths));
observedReports = strings(height(visual),1);
for row = 1:height(visual)
    observedReports(row) = canonical_file(visual.report_path(row), ...
        "stageA4:a43:finalizer:VisualReportPath");
    imagePath = canonical_file(visual.image_path(row), ...
        "stageA4:a43:finalizer:VisualImagePath");
    assert(path_is_inside(imagePath,string(context.root)), ...
        "stageA4:a43:finalizer:VisualImageScope", ...
        "Rendered page evidence must be inside the current run.");
    assert(lower(string(compute_sha256_file(imagePath)))== ...
        lower(string(visual.image_sha256(row))), ...
        "stageA4:a43:finalizer:VisualImageHash", ...
        "Rendered page image hash mismatch: %s",imagePath);
    try
        information = imfinfo(imagePath);
    catch exception
        error("stageA4:a43:finalizer:VisualImageFormat", ...
            "Rendered page evidence is not a readable image: %s (%s)", ...
            imagePath,exception.message);
    end
    assert(~isempty(information), ...
        "stageA4:a43:finalizer:VisualImageFormat", ...
        "Rendered page evidence is empty: %s",imagePath);
end
expected = arrayfun(@(value)canonical_file(value, ...
    "stageA4:a43:finalizer:VisualReportPath"),expected);
assert(isequal(sort(unique(observedReports)),sort(expected)), ...
    "stageA4:a43:finalizer:VisualReportSet", ...
    "Visual QA must cover exactly the three required reports.");
for reportPath = expected.'
    rows = visual(observedReports==reportPath,:);
    pageCount = double(rows.page_count);
    pageNumber = double(rows.page_number);
    assert(~isempty(rows) && isscalar(unique(pageCount)) && ...
        unique(pageCount)==height(rows) && ...
        isequal(sort(pageNumber),(1:height(rows)).'), ...
        "stageA4:a43:finalizer:VisualPages", ...
        "Visual QA pages are incomplete for %s.",reportPath);
end
end

function validate_report_hashes(context,reportPaths,hashes)
required = ["relative_path","sha256","status"];
assert(all(ismember(required,string(hashes.Properties.VariableNames))) && ...
    height(hashes)==3 && ...
    numel(unique(string(hashes.relative_path)))==3, ...
    "stageA4:a43:finalizer:ReportHashSchema", ...
    "Report SHA256 manifest must contain exactly three unique rows.");
expected = string(struct2cell(reportPaths));
for pathValue = expected.'
    canonical = canonical_file(pathValue, ...
        "stageA4:a43:finalizer:ReportHashPath");
    assert(path_is_inside(canonical,string(context.root)), ...
        "stageA4:a43:finalizer:ReportScope", ...
        "A report is outside the current run.");
    relative = relative_path(canonical,string(context.root));
    row = hashes(string(hashes.relative_path)==relative,:);
    assert(height(row)==1 && ...
        lower(string(row.sha256))== ...
        lower(string(compute_sha256_file(canonical))), ...
        "stageA4:a43:finalizer:ReportHash", ...
        "Report SHA256 evidence is inconsistent: %s",canonical);
end
end

function audit = validate_test_evidence( ...
        projectRoot,context,manifest,runResult,paths)
results = read_csv(paths.test_results);
summary = read_json(paths.test_summary);
requiredColumns = ["suite_label","test_name","passed","failed","incomplete", ...
    "duration_seconds","details"];
assert(all(ismember(requiredColumns, ...
    string(results.Properties.VariableNames))), ...
    "stageA4:a43:finalizer:TestSchema", ...
    "tests/test_results.csv has an invalid schema.");
requiredSummary = ["test_total","test_passed","test_failed", ...
    "test_incomplete"];
assert(all(isfield(summary,cellstr(requiredSummary))), ...
    "stageA4:a43:finalizer:TestSummary", ...
    "tests/test_summary.json is incomplete.");
passed = logical_column(results.passed);
failed = logical_column(results.failed);
incomplete = logical_column(results.incomplete);
count = height(results);
suiteLabels = string(results.suite_label);
testNames = string(results.test_name);
pairIdentity = suiteLabels+"|"+testNames;
identityPass = count>0 && all(strlength(suiteLabels)>0) && ...
    all(strlength(testNames)>0) && ...
    numel(unique(pairIdentity))==count;
countPass = double(summary.test_total)==count && ...
    double(summary.test_passed)==nnz(passed) && ...
    double(summary.test_failed)==nnz(failed) && ...
    double(summary.test_incomplete)==nnz(incomplete);
executionComplete = true;
if isfield(summary,"execution_status")
    executionComplete = string(summary.execution_status)=="COMPLETE";
end
aggregateOutcomePass = identityPass && countPass && executionComplete && ...
    all(passed) && ~any(failed) && ~any(incomplete);
audit = struct( ...
    "aggregate_passed",aggregateOutcomePass, ...
    "identity_passed",identityPass, ...
    "summary_matches_results",countPass, ...
    "execution_complete",executionComplete, ...
    "test_total",count, ...
    "test_passed",nnz(passed), ...
    "test_failed",nnz(failed), ...
    "test_incomplete",nnz(incomplete), ...
    "results_path",string(paths.test_results), ...
    "summary_path",string(paths.test_summary));

expectedPath = fullfile(projectRoot,"tests", ...
    "stage_A4_3_expected_test_inventory.csv");
expected = read_csv(expectedPath);
inventory = read_csv(paths.a43_inventory);
requiredInventory = ["test_order","test_name","source_file"];
assert(all(ismember(requiredInventory, ...
    string(expected.Properties.VariableNames))) && ...
    all(ismember(requiredInventory, ...
    string(inventory.Properties.VariableNames))), ...
    "stageA4:a43:finalizer:A43InventorySchema", ...
    "The A4-3 specialty inventory schema is invalid.");
expected = expected(:,cellstr(requiredInventory));
inventory = inventory(:,cellstr(requiredInventory));
inventoryIdentity = height(expected)==27 && ...
    tables_equivalent(expected,inventory) && ...
    isequal(double(inventory.test_order),(1:27).') && ...
    numel(unique(string(inventory.test_name)))==27;

specialtyResults = read_csv(paths.a43_results);
specialtySummary = read_json(paths.a43_summary);
requiredResultColumns = ["test_name","passed","failed","incomplete", ...
    "duration_seconds","details"];
assert(all(ismember(requiredResultColumns, ...
    string(specialtyResults.Properties.VariableNames))), ...
    "stageA4:a43:finalizer:A43ResultSchema", ...
    "The A4-3 specialty result schema is invalid.");
specialtyPassed = logical_column(specialtyResults.passed);
specialtyFailed = logical_column(specialtyResults.failed);
specialtyIncomplete = logical_column(specialtyResults.incomplete);
summaryFields = ["execution_status","suite_label","test_total", ...
    "test_passed","test_failed","test_incomplete", ...
    "test_names_unique","expected_inventory_sha256"];
assert(all(isfield(specialtySummary,cellstr(summaryFields))), ...
    "stageA4:a43:finalizer:A43SummarySchema", ...
    "The A4-3 specialty summary is missing identity fields.");
expectedSha = lower(string(compute_sha256_file(expectedPath)));
resultIdentity = inventoryIdentity && ...
