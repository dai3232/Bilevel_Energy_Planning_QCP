function preserve_pre_finalization_tables(context)
pairs = [ ...
    string(context.acceptance_results_path), ...
        fullfile(context.acceptance_dir, ...
        "acceptance_results.pre_finalization.csv"); ...
    string(context.issue_log_path), ...
        fullfile(context.issues_dir,"issue_log.pre_finalization.csv"); ...
    string(context.decision_log_path), ...
        fullfile(context.issues_dir,"decision_log.pre_finalization.csv")];
for row = 1:size(pairs,1)
    source = pairs(row,1); target = pairs(row,2);
    assert(isfile(source), ...
        "stageA4:a43:finalizer:PreFinalizationEvidence", ...
        "Pre-finalization source is missing: %s",source);
    if isfile(target)
        continue
    end
    temporary = string(tempname(fileparts(target)))+".csv";
    guard = onCleanup(@()delete_if_exists(temporary));
    [copied,message] = copyfile(source,temporary);
    assert(copied,"stageA4:a43:finalizer:PreserveCopy","%s",message);
    sourceHash = compute_sha256_file(source);
    assert(lower(string(compute_sha256_file(temporary)))== ...
        lower(string(sourceHash)), ...
        "stageA4:a43:finalizer:PreserveHash", ...
        "Pre-finalization copy hash mismatch.");
    [moved,message] = movefile(temporary,target);
    assert(moved,"stageA4:a43:finalizer:PreserveMove","%s",message);
    clear guard
end
end

function write_derived_table(pathValue,value)
if isfile(pathValue)
    try
        existing = read_csv(pathValue);
        if tables_equivalent(existing,value)
            return
        end
    catch
        % A malformed mutable pre-finalization table is replaced only after
        % its original bytes have been preserved by the caller.
    end
end
write_table_csv_17g_atomic(pathValue,value);
end

function [evidence,reused] = materialize_complete_hash_inventory( ...
        context,manifest,target)
candidate = build_hash_inventory(context,manifest,target);
if isfile(target)
    existing = read_csv(target);
    assert(hash_inventories_equivalent(existing,candidate), ...
        "stageA4:a43:finalizer:EvidenceInventoryChanged", ...
        "A pre-existing final evidence inventory no longer matches the "+ ...
        "current run.  It is preserved and will not be overwritten.");
    evidence = existing;
    reused = true;
else
    write_table_csv_17g_atomic(target,candidate);
    evidence = read_csv(target);
    if ~hash_inventories_equivalent(evidence,candidate)
        error("stageA4:a43:finalizer:EvidenceInventoryWrite", ...
            "The persisted complete evidence inventory failed read-back: %s", ...
            hash_inventory_difference(evidence,candidate));
    end
    reused = false;
end

function value = hash_inventory_difference(left,right)
value = "left_height="+height(left)+"; right_height="+height(right);
required = ["relative_path","scope","bytes","sha256","status","checked_at"];
if ~all(ismember(required,string(left.Properties.VariableNames)))
    value = value+"; left_columns="+ ...
        strjoin(string(left.Properties.VariableNames),",");
    return
end
if height(left)~=height(right)
    return
end
[~,leftOrder] = sort(string(left.relative_path));
[~,rightOrder] = sort(string(right.relative_path));
left = left(leftOrder,:); right = right(rightOrder,:);
checks = [ ...
    isequal(string(left.relative_path),string(right.relative_path))
    isequal(string(left.scope),string(right.scope))
    isequal(double(left.bytes),double(right.bytes))
    isequal(lower(string(left.sha256)),lower(string(right.sha256)))
    isequal(string(left.status),string(right.status))
    isequal(string(left.checked_at),string(right.checked_at))];
value = value+"; path/scope/bytes/sha/status/time="+ ...
    strjoin(string(double(checks.')),",");
end
end

function evidence = build_hash_inventory(context,manifest,target)
listing = dir(fullfile(context.root,"**","*"));
relative = strings(0,1);
absolute = strings(0,1);
scope = strings(0,1);
targetRelative = relative_path(target,string(context.root));
for k = 1:numel(listing)
    if listing(k).isdir
        continue
    end
    pathValue = string(fullfile(listing(k).folder,listing(k).name));
    currentRelative = relative_path(pathValue,string(context.root));
    if ismember(currentRelative, ...
            ["run_manifest.json",targetRelative,".initializing"])
        continue
    end
    relative(end+1,1) = currentRelative; %#ok<AGROW>
    absolute(end+1,1) = pathValue; %#ok<AGROW>
    first = extractBefore(currentRelative,"/");
    if ismissing(first) || strlength(first)==0
        first = "run_root";
    end
    scope(end+1,1) = first; %#ok<AGROW>
end
[relative,order] = sort(relative);
absolute = absolute(order);
scope = scope(order);
assert(~isempty(relative) && ...
    numel(unique(relative))==numel(relative), ...
    "stageA4:a43:finalizer:EvidenceInventory", ...
    "Complete evidence paths must be nonempty and unique.");
n = numel(relative);
bytes = zeros(n,1);
sha256 = strings(n,1);
status = repmat("PASS",n,1);
checked_at = repmat("manifest_started_at:"+string(manifest.started_at),n,1);
for k = 1:n
    info = dir(absolute(k));
    assert(isscalar(info) && ~info.isdir, ...
        "stageA4:a43:finalizer:EvidenceMissing", ...
        "Evidence disappeared during hashing: %s",absolute(k));
    bytes(k) = info.bytes;
    sha256(k) = lower(string(compute_sha256_file(absolute(k))));
    if strlength(sha256(k))~=64
        status(k) = "FAIL";
    end
end
evidence = table(relative,scope,bytes,sha256,status,checked_at, ...
    'VariableNames',{'relative_path','scope','bytes','sha256', ...
    'status','checked_at'});
end

function passed = hash_inventories_equivalent(left,right)
required = ["relative_path","scope","bytes","sha256","status","checked_at"];
passed = all(ismember(required,string(left.Properties.VariableNames))) && ...
    height(left)==height(right);
if ~passed
    return
end
[~,leftOrder] = sort(string(left.relative_path));
[~,rightOrder] = sort(string(right.relative_path));
left = left(leftOrder,:); right = right(rightOrder,:);
passed = isequal(string(left.relative_path),string(right.relative_path)) && ...
    isequal(string(left.scope),string(right.scope)) && ...
    isequal(double(left.bytes),double(right.bytes)) && ...
    isequal(lower(string(left.sha256)),lower(string(right.sha256))) && ...
    isequal(string(left.status),string(right.status)) && ...
    isequal(string(left.checked_at),string(right.checked_at));
end

