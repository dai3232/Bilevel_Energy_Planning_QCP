    issues = append_issue(issues,context, ...
        "A43-NUMERICAL-"+numericalTerminal,"A4-3-TERMINAL", ...
        numericalTerminal, ...
        "The formal candidate did not reach CONVERGED.", ...
        "The complete trajectory and accepted checkpoints were preserved.", ...
        "Keep stage_A4 / READY and review the persisted trajectory.", ...
        "iterations/iteration_summary.csv");
end
failed = acceptance(string(acceptance.status)~="PASS",:);
for row = 1:height(failed)
    issues = append_issue(issues,context, ...
        "A43-ACCEPTANCE-"+failed.test_id(row),failed.test_id(row), ...
        "acceptance", ...
        "A blocking Stage A4 acceptance item did not pass.", ...
        "The observed value and threshold remain unchanged.", ...
        "Resolve the failed gate without changing the frozen threshold.", ...
        "acceptance/acceptance_results.csv");
end
if ~testAudit.passed
    issues = append_issue(issues,context,"A43-TEST-EVIDENCE", ...
        "A4-3-TESTS","tests", ...
        "The persisted test set is failed, incomplete, or inconsistent.", ...
        "The original test result and summary files were retained.", ...
        "Repair the implementation/evidence and create a new formal run.", ...
        "tests/test_results.csv; tests/test_summary.json");
end
if ~staticAudit.passed
    issues = append_issue(issues,context,"A43-STATIC-EVIDENCE", ...
        "A4-3-STATIC","static", ...
        "One or more persisted static/forbidden checks did not pass.", ...
        "The static summary and dependency closure were retained.", ...
        "Resolve the failed check without changing the algorithm contract.", ...
        "tests/static_check_summary.csv; diagnostics");
end
if ~identityAudit.passed
    issues = append_issue(issues,context,"A43-EVIDENCE-IDENTITY", ...
        "A4-3-IDENTITY","identity", ...
        "Manifest, iteration, direction, or Git identity is inconsistent.", ...
        "Conflicting evidence was retained.", ...
        "Do not interpret or promote this run.", ...
        "run_manifest.json; a4_3_solver_result.mat");
end
if ~historicalPassed
    issues = append_issue(issues,context,"A43-HISTORICAL-RUNS", ...
        "A4-3-HISTORY","history", ...
        "Historical run preservation did not pass.", ...
        "The historical audit was retained.", ...
        "Stop and restore the historical evidence boundary.", ...
        "historical_runs_audit.json");
end
if finalStatus=="PASS"
    assert(isempty(issues), ...
        "stageA4:a43:finalizer:PassWithIssues", ...
        "A PASS candidate cannot contain an open issue.");
end
decisions = table(string(context.run_id),"A4-3", ...
    numericalTerminal,finalStatus, ...
    "CURRENT_STAGE remains stage_A4 / READY; no Stage B transition.", ...
    double(result.iteration_count), ...
    "positive_scalar_unitized_kkt", ...
    "independent alpha_primal/alpha_dual; stable-v2 MaxPasses=3", ...
    "complete persisted evidence; full KKT audit only", ...
    'VariableNames',{'run_id','milestone','numerical_terminal_state', ...
    'manifest_terminal_status','stage_decision', ...
    'accepted_iteration_count','convergence_coordinate', ...
    'algorithm_contract','evidence_basis'});
end

