function assert_run_evidence_references(runRoot,references,errorId)
for value = references(:).'
    tokens = strip(split(string(value),";"));
    tokens = tokens(strlength(tokens)>0);
    assert(~isempty(tokens),errorId, ...
        "An evidence_path field is empty.");
    for token = tokens(:).'
        assert(~contains(replace(token,"\","/"),"../") && ...
            ~startsWith(replace(token,"\","/"),"/"), ...
            errorId,"Evidence reference escapes the current run: %s",token);
        if is_absolute_path(token)
            candidate = token;
        else
            candidate = fullfile(runRoot,replace(token,"/",filesep));
        end
        canonical = string(char(java.io.File( ...
            char(candidate)).getCanonicalPath()));
        assert(path_is_inside(canonical,string(runRoot)) && ...
            (isfile(canonical)||isfolder(canonical)), ...
            errorId, ...
            "Evidence reference must resolve inside the current run: %s", ...
            token);
    end
end
end

function passed = is_absolute_path(pathValue)
text = char(pathValue);
passed = (~isempty(regexp(text,"^[A-Za-z]:[\\/]","once"))) || ...
    startsWith(string(pathValue),"\\");
end

