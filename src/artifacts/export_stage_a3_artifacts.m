    "soc_boundary_audit",socAudit, ...
    "fixed_zero_recovery_audit",fixedAudit, ...
    "renewable_activity",activity,"code_scan",codeScan, ...
    "artifact_hashes",artifactHashes, ...
    "linearization_identity",identityEvidence);
end

function validate_inputs(context,index,config,lin,fullResult,recursive,audit)
requiredContext=["root","run_id","stage_id","matrices_dir", ...
    "indices_dir","iterations_dir","project_root"];
assert(all(isfield(context,cellstr(requiredContext)))&&isfolder(context.root), ...
    "stageA3:artifacts:InvalidRunContext","Invalid A3 run context.");
assert(string(context.stage_id)=="stage_A3", ...
    "stageA3:artifacts:StageMismatch","A3 exporter requires stage_A3.");
manifest=jsondecode(fileread(context.run_manifest_path));
assert(string(manifest.run_id)==string(context.run_id)&& ...
    string(manifest.stage_id)=="stage_A3"&&string(manifest.status)=="RUNNING", ...
    "stageA3:artifacts:ManifestIdentity", ...
    "A3 export requires the matching RUNNING manifest.");
requiredIndex=["variable_index","constraint_index","block_index", ...
    "fixed_zero_map","permutation_map","soc_link_map"];
assert(all(isfield(index,cellstr(requiredIndex))), ...
    "stageA3:artifacts:IndexContract", ...
    "Six canonical index tables are required.");
for name=requiredIndex
    assert(istable(index.(name)),"stageA3:artifacts:IndexContract", ...
        "Canonical index field %s must be a table.",name);
end
assert(lin.counts.full_kkt==18836&&fullResult.kkt.dimension==18836&& ...
    isequal(size(fullResult.kkt.matrix),[18836 18836])&& ...
    issparse(fullResult.kkt.matrix), ...
    "stageA3:artifacts:FullKktDimension", ...
    "The complete A3 KKT must be sparse and 18836-by-18836.");
assert(isequal(size(recursive.reduced.W),[3722 3722])&& ...
    isequal(size(recursive.reduced.saddle),[4340 4340])&& ...
    issparse(recursive.reduced.W)&&issparse(recursive.reduced.saddle), ...
    "stageA3:artifacts:ReducedSystemDimension", ...
    "A3 reduced W/saddle must be sparse 3722 and 4340 systems.");
assert(numel(recursive.daily_partitions)==7&& ...
    numel(recursive.daily_thomas)==7&&numel(recursive.daily_responses)==7, ...
    "stageA3:artifacts:DailyCount", ...
    "A3 requires seven partitions, Thomas solves, and day responses.");
for k=1:7
    partition=recursive.daily_partitions(k);
    response=recursive.daily_responses(k);
    assert(double(partition.day_id)==config.days(k)&& ...
        double(response.day_id)==config.days(k)&&numel(partition.hour)==24&& ...
        issparse(partition.M)&&isequal(size(response.S),[14 14])&& ...
        isequal(size(response.c),[14 1])&& ...
        isequal(size(response.beta),[14 1])&& ...
        isequal(size(response.gamma),[14 1]), ...
        "stageA3:artifacts:DailyContract", ...
        "Day %d partition/response contract is invalid.",config.days(k));
end
assert(isequal(double(recursive.aggregation.day_ids_sorted(:).'),config.days)&& ...
    isequal(size(recursive.aggregation.S_sum),[14 14])&& ...
    isequal(size(recursive.aggregation.gamma_sum),[14 1])&& ...
    isequal(size(recursive.core.matrix),[16 16]), ...
    "stageA3:artifacts:CoreDimension", ...
    "A3 aggregation/core dimensions are invalid.");
assert(height(index.fixed_zero_map)==recursive.fixed_zero.count, ...
    "stageA3:artifacts:FixedZeroCount", ...
    "Canonical and recovered fixed-zero counts differ.");
identities=string([lin.identity,fullResult.linearization_identity, ...
    recursive.linearization_identity,audit.linearization_identity]);
assert(isscalar(unique(identities)), ...
    "stageA3:artifacts:LinearizationIdentity", ...
    "Full, recursive, and audit routes must share one identity.");
assert(recursive.no_full_direction_fallback, ...
    "stageA3:artifacts:RecursiveFallback", ...
    "Recursive evidence permits a full-KKT direction fallback.");
assemblyAudit=recursive.partition.assembly_audit;
assert(logical(assemblyAudit.no_cross_day_soc_coupling)&& ...
    double(assemblyAudit.cross_day_hourly_equality_nnz)==0, ...
    "stageA3:artifacts:CrossDaySocCoupling", ...
    "A3 recursive partition contains cross-day hourly/SOC coupling.");
end

function output=make_daily_response_summary(recursive,config)
n=numel(recursive.daily_responses); day=zeros(n,1);
S_rows=zeros(n,1); S_columns=zeros(n,1); c_length=zeros(n,1);
beta_length=zeros(n,1); gamma_length=zeros(n,1); S_nnz=zeros(n,1);
S_norm_fro=zeros(n,1); c_norm_2=zeros(n,1); beta_norm_2=zeros(n,1);
gamma_norm_2=zeros(n,1); gamma_identity_relative_residual=zeros(n,1);
status=strings(n,1);
for k=1:n
    response=recursive.daily_responses(k); day(k)=double(response.day_id);
    [S_rows(k),S_columns(k)]=size(response.S); S_nnz(k)=nnz(response.S);
    c_length(k)=numel(response.c); beta_length(k)=numel(response.beta);
    gamma_length(k)=numel(response.gamma); S_norm_fro(k)=norm(response.S,'fro');
    c_norm_2(k)=norm(response.c,2); beta_norm_2(k)=norm(response.beta,2);
    gamma_norm_2(k)=norm(response.gamma,2);
    identityResidual=response.gamma-(response.c-response.S*response.beta);
    gamma_identity_relative_residual(k)=norm(identityResidual,2)/ ...
        max(1,norm(response.gamma,2));
    passed=day(k)==config.days(k)&&S_rows(k)==14&&S_columns(k)==14&& ...
        c_length(k)==14&&beta_length(k)==14&&gamma_length(k)==14&& ...
        gamma_identity_relative_residual(k)<=config.tolerances.symmetry_relative;
    status(k)=pass_text(passed);
end
output=table(day,S_rows,S_columns,c_length,beta_length,gamma_length, ...
    S_nnz,S_norm_fro,c_norm_2,beta_norm_2,gamma_norm_2, ...
    gamma_identity_relative_residual,status);
end

function output=make_aggregation_audit(recursive,config)
aggregation=recursive.aggregation;
input_order=string(mat2str(double(aggregation.input_order(:).')));
sort_order=string(mat2str(double(aggregation.sort_order(:).')));
day_ids_sorted=string(mat2str(double(aggregation.day_ids_sorted(:).')));
S_rows=size(aggregation.S_sum,1); S_columns=size(aggregation.S_sum,2);
gamma_length=numel(aggregation.gamma_sum);
S_sum_norm_fro=norm(aggregation.S_sum,'fro');
gamma_sum_norm_2=norm(aggregation.gamma_sum,2);
S_order_invariance_relative_error= ...
    double(aggregation.order_invariant_S_relative_error);
gamma_order_invariance_relative_error= ...
    double(aggregation.order_invariant_gamma_relative_error);
sorted_contract=isequal(double(aggregation.day_ids_sorted(:).'),config.days);
status=pass_text(sorted_contract&&logical(aggregation.order_invariant_passed)&& ...
    S_order_invariance_relative_error<=config.tolerances.symmetry_relative&& ...
    gamma_order_invariance_relative_error<=config.tolerances.symmetry_relative);
output=table(input_order,sort_order,day_ids_sorted,S_rows,S_columns, ...
    gamma_length,S_sum_norm_fro,gamma_sum_norm_2, ...
    S_order_invariance_relative_error, ...
    gamma_order_invariance_relative_error,sorted_contract,status);
end

function output=make_direction_comparison(audit,recursive,config,lin,fullResult)
identityMismatch=double(~(string(lin.identity)== ...
    string(fullResult.linearization_identity)&&string(lin.identity)== ...
    string(recursive.linearization_identity)));
fixedValue=max([0;abs(recursive.fixed_zero.value(:))]);
fixedDirection=max([0;abs(recursive.fixed_zero.direction(:))]);
dayChainResiduals=zeros(numel(recursive.daily_thomas),1);
for k=1:numel(recursive.daily_thomas)
    dayChainResiduals(k)=recursive.daily_thomas(k).diagnostics.chain_relative_residual;
end
metric_id=["overall_direction_relative_2norm"; ...
    "xi_direction_relative_2norm";"y_direction_relative_2norm"; ...
    "l_direction_relative_2norm";"z_direction_relative_2norm"; ...
    "fixed_zero_maximum_absolute_value"; ...
    "fixed_zero_maximum_absolute_direction"; ...
    "linearization_identity_mismatch"; ...
    "recursive_full_direction_fallback_used"; ...
    "daily_aggregation_S_order_relative_error"; ...
    "daily_aggregation_gamma_order_relative_error"; ...
    "maximum_daily_chain_relative_residual"; ...
    "global_core_relative_residual"];
actual_value=[audit.direction_relative_error; ...
    audit.component_relative_errors.xi;audit.component_relative_errors.y; ...
    audit.component_relative_errors.l;audit.component_relative_errors.z; ...
