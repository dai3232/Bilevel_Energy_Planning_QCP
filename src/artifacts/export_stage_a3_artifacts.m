function output=make_residual_summary(fullResult,recursive,config)
K=fullResult.kkt.matrix; b=fullResult.kkt.rhs;
fullResidual=K*fullResult.direction-b;
recursiveResidual=K*recursive.direction-b;
route=["full_kkt_direct_preferred";"full_kkt_direct_hard_limit"; ...
    "recursive_direction_reinserted_in_full_kkt"];
day_id=[NaN;NaN;NaN];
absolute_residual_2norm=[norm(fullResidual,2);norm(fullResidual,2); ...
    norm(recursiveResidual,2)];
rhs_2norm=[norm(b,2);norm(b,2);norm(b,2)];
threshold=[config.tolerances.direct_preferred;config.tolerances.direct_maximum; ...
    config.tolerances.recursive_full_kkt_relative_residual];
for k=1:numel(recursive.daily_partitions)
    partition=recursive.daily_partitions(k); thomas=recursive.daily_thomas(k);
    chainRhs=[partition.r_v,partition.B];
    chainResidual=partition.M*thomas.stacked_solution-chainRhs;
    route(end+1,1)="recursive_day_chain_15_rhs"; %#ok<AGROW>
    day_id(end+1,1)=double(partition.day_id); %#ok<AGROW>
    absolute_residual_2norm(end+1,1)=norm(chainResidual,'fro'); %#ok<AGROW>
    rhs_2norm(end+1,1)=norm(chainRhs,'fro'); %#ok<AGROW>
    threshold(end+1,1)=config.tolerances.recursive_full_kkt_relative_residual; %#ok<AGROW>
end
coreResidual=recursive.core.matrix*recursive.core.solution-recursive.core.rhs;
route(end+1,1)="global_core_16"; day_id(end+1,1)=NaN;
absolute_residual_2norm(end+1,1)=norm(coreResidual,2);
rhs_2norm(end+1,1)=norm(recursive.core.rhs,2);
threshold(end+1,1)=config.tolerances.recursive_full_kkt_relative_residual;
relative_residual_2norm=absolute_residual_2norm./max(1,rhs_2norm);
status=repmat("PASS",numel(route),1);
status(~isfinite(relative_residual_2norm)|relative_residual_2norm>threshold)="FAIL";
output=table(route,day_id,absolute_residual_2norm,rhs_2norm, ...
    relative_residual_2norm,threshold,status);
end

function output=make_soc_boundary_audit(index,lin,config)
links=index.soc_link_map; constraints=index.constraint_index;
check_id=strings(0,1); day=zeros(0,1); hour=zeros(0,1); storage=zeros(0,1);
equation_id=strings(0,1); boundary_role=strings(0,1);
predecessor_day=zeros(0,1); predecessor_hour=zeros(0,1);
predecessor_soc_index=zeros(0,1); current_soc_index=zeros(0,1);
expected=strings(0,1); actual=strings(0,1); status=strings(0,1);
for d=1:numel(config.days)
    dayId=config.days(d);
    for h=config.hours
        for s=1:2
            link=links(links.day==dayId&links.hour==h&links.storage_id==s,:);
            equation=constraints(constraints.day==dayId&constraints.hour==h& ...
                string(constraints.constraint_type)=="equality"& ...
                string(constraints.constraint_name)=="soc_dynamics"& ...
                constraints.asset_id==s,:);
            passed=height(link)==1&&height(equation)==1;
            if passed
                passed=lin.A(equation.global_row, ...
                    link.current_soc_global_index)==1;
            end
            predDay=NaN;
            if ismember("predecessor_day",string(link.Properties.VariableNames))&& ...
                    height(link)==1
                predDay=link.predecessor_day;
            end
            if h==config.hours(1)
                role="initial_fixed_half_energy_no_interday_link";
                if height(link)==1&&height(equation)==1
                    passed=passed&&isnan(link.predecessor_hour)&& ...
                        link.predecessor_soc_global_index==0&& ...
                        link.initial_energy_fraction==0.5&& ...
                        (isnan(predDay)||predDay==0)&& ...
                        lin.A(equation.global_row, ...
                        q_day_index(lin,d,12+s))==-0.5;
                end
                expectedText="fixed 0.5E; no prior day/hour-0 SOC link";
            else
                role="same_day_predecessor";
                if height(link)==1&&height(equation)==1
                    passed=passed&&link.predecessor_hour==h-1&& ...
                        link.predecessor_soc_global_index>0&& ...
                        (isnan(predDay)||predDay==dayId)&& ...
                        predecessor_is_same_day(index.variable_index, ...
                        link.predecessor_soc_global_index,dayId,h-1,s)&& ...
                        lin.A(equation.global_row, ...
                        link.predecessor_soc_global_index)==-1&& ...
                        lin.A(equation.global_row,q_day_index(lin,d,12+s))==0;
                end
                expectedText=sprintf("same-day %d hour predecessor %d",dayId,h-1);
            end
            if height(link)==1
                pred=link.predecessor_hour;
                predIndex=link.predecessor_soc_global_index;
                current=link.current_soc_global_index;
                actualText=sprintf("source=%s; predecessor_hour=%s; predecessor_index=%d", ...
                    string(link.boundary_source),number_or_na(pred),predIndex);
            else
                pred=NaN; predIndex=0; current=0; actualText="MISSING_OR_DUPLICATE";
            end
            if height(equation)==1
                eqId=string(equation.constraint_id);
            else
                eqId="MISSING_OR_DUPLICATE";
            end
            check_id(end+1,1)=sprintf("SOC-D%02d-H%02d-S%02d",dayId,h,s); %#ok<AGROW>
            day(end+1,1)=dayId; hour(end+1,1)=h; storage(end+1,1)=s; %#ok<AGROW>
            equation_id(end+1,1)=eqId; boundary_role(end+1,1)=role; %#ok<AGROW>
            predecessor_day(end+1,1)=predDay; predecessor_hour(end+1,1)=pred; %#ok<AGROW>
            predecessor_soc_index(end+1,1)=predIndex; current_soc_index(end+1,1)=current; %#ok<AGROW>
            expected(end+1,1)=expectedText; actual(end+1,1)=actualText; %#ok<AGROW>
            status(end+1,1)=pass_text(passed); %#ok<AGROW>
        end
    end
    for s=1:2
        h=config.hours(end);
        link=links(links.day==dayId&links.hour==h&links.storage_id==s,:);
        equation=constraints(constraints.day==dayId&constraints.hour==h& ...
            string(constraints.constraint_type)=="equality"& ...
            string(constraints.constraint_name)=="terminal_soc"& ...
            constraints.asset_id==s,:);
        passed=height(link)==1&&height(equation)==1&& ...
            link.terminal_equality&&link.terminal_energy_fraction==0.5;
        if passed
            passed=lin.A(equation.global_row,link.current_soc_global_index)==1&& ...
                lin.A(equation.global_row,q_day_index(lin,d,12+s))==-0.5;
            eqId=string(equation.constraint_id); current=link.current_soc_global_index;
            actualText="hour=24; fraction="+compose("%.17g", ...
                link.terminal_energy_fraction);
        else
            eqId="MISSING_OR_DUPLICATE"; current=0; actualText="MISSING_OR_DUPLICATE";
        end
        check_id(end+1,1)=sprintf("SOC-END-D%02d-H24-S%02d",dayId,s); %#ok<AGROW>
        day(end+1,1)=dayId; hour(end+1,1)=24; storage(end+1,1)=s; %#ok<AGROW>
        equation_id(end+1,1)=eqId; boundary_role(end+1,1)="terminal_fixed_half_energy"; %#ok<AGROW>
        predecessor_day(end+1,1)=dayId; predecessor_hour(end+1,1)=24; %#ok<AGROW>
        predecessor_soc_index(end+1,1)=current; current_soc_index(end+1,1)=current; %#ok<AGROW>
        expected(end+1,1)="SOC(d,s,24)-0.5E(s)=0 in final hour block"; %#ok<AGROW>
        actual(end+1,1)=actualText; status(end+1,1)=pass_text(passed); %#ok<AGROW>
    end
end
output=table(check_id,day,hour,storage,equation_id,boundary_role, ...
    predecessor_day,predecessor_hour,predecessor_soc_index, ...
    current_soc_index,expected,actual,status);
end

