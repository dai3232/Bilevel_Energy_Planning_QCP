function output=make_fixed_zero_recovery_audit(index,recursive,physical)
map=index.fixed_zero_map; count=height(map);
assert(count==recursive.fixed_zero.count, ...
    "stageA3:artifacts:FixedZeroCount", ...
    "Canonical and recovered A3 fixed-zero counts differ.");
assert(recursive.fixed_zero.count==count&&recursive.fixed_zero.all_exact_zero, ...
    "stageA3:artifacts:FixedZeroShape", ...
    "Recursive recovery did not report the canonical fixed-zero count.");
assert(physical.fixed_zero_audit.count==count&& ...
    physical.fixed_zero_audit.values_exact_zero&& ...
    physical.fixed_zero_audit.directions_exact_zero&& ...
    physical.fixed_zero_audit.maximum_absolute_value==0&& ...
    physical.fixed_zero_audit.maximum_absolute_direction==0, ...
    "stageA3:artifacts:PhysicalFixedZero", ...
    "Actual physical recovery did not preserve exact fixed zeros.");
recovered_value=zeros(count,1); recovered_direction=zeros(count,1);
recovery_source=strings(count,1);
for row=1:count
    dayPosition=find(double(physical.days)==double(map.day(row)),1);
    hourPosition=find(double(physical.hours)==double(map.hour(row)),1);
    assert(~isempty(dayPosition)&&~isempty(hourPosition), ...
        "stageA3:artifacts:PhysicalFixedZeroLocation", ...
        "Fixed-zero row %d is outside physical recovery arrays.",row);
    if string(map.asset_type(row))=="wind"&& ...
            string(map.variable_name(row))=="PW"
        field="wind";
    elseif string(map.asset_type(row))=="solar"&& ...
            string(map.variable_name(row))=="PP"
        field="solar";
    else
        error("stageA3:artifacts:PhysicalFixedZeroType", ...
            "Unsupported fixed-zero row %d: %s/%s.",row, ...
            map.asset_type(row),map.variable_name(row));
    end
    recovered_value(row)=physical.value.(field)(dayPosition,hourPosition, ...
        map.asset_id(row));
    recovered_direction(row)=physical.direction.(field)(dayPosition,hourPosition, ...
        map.asset_id(row));
    recovery_source(row)="physical."+field+"[day,hour,asset]";
end
status=repmat("PASS",count,1);
passed=map.fixed_value==0&map.fixed_direction_value==0& ...
    recovered_value==0&recovered_direction==0& ...
    string(map.inequality_status)=="NOT_APPLICABLE_BOTH_BOUNDS";
status(~passed)="FAIL";
output=addvars(map,recovered_value,recovered_direction,recovery_source,status, ...
    'NewVariableNames',{'recovered_value','recovered_direction', ...
    'recovery_source','status'});
end

function output=make_renewable_activity(data,index,config)
n=numel(config.days)*numel(config.hours)*10;
day=zeros(n,1); hour=zeros(n,1); asset_type=strings(n,1);
asset_id=zeros(n,1); variable_name=strings(n,1); kappa=zeros(n,1);
