function targets=output_targets(paths)
names=fieldnames(paths); targets=strings(0,1);
for k=1:numel(names)
    if names{k}=="diagnostics_dir", continue; end
    targets=[targets;reshape(string(paths.(names{k})),[],1)]; %#ok<AGROW>
end
assert(numel(unique(lower(targets)))==numel(targets), ...
    "stageA3:artifacts:DuplicateTarget","A3 artifact targets are not unique.");
end
function assert_targets_absent(targets)
for target=targets.'
    if isfile(target)||isfolder(target)
        error("stageA3:artifacts:TargetExists", ...
            "A3 artifact target exists and will not be overwritten: %s",target);
    end
end
end
function ensure_directory(pathValue)
if isfolder(pathValue), return; end
if exist(pathValue,'file')
    error("stageA3:artifacts:PathConflict", ...
        "A file exists where a directory is required: %s",pathValue);
end
[created,message]=mkdir(pathValue);
assert(created,"stageA3:artifacts:CreateDirectory","%s",message);
end

function output=make_block_dimensions(recursive)
day=zeros(0,1); hour=zeros(0,1); n_primal=zeros(0,1);
n_equalities=zeros(0,1); kkt_dimension=zeros(0,1);
day_chain_offset_start=zeros(0,1); day_chain_offset_end=zeros(0,1);
status=strings(0,1);
for d=1:numel(recursive.daily_partitions)
    partition=recursive.daily_partitions(d); offset=0;
    for h=1:numel(partition.hour)
        block=partition.hour(h); dimension=double(block.dimension);
        day(end+1,1)=double(partition.day_id); %#ok<AGROW>
        hour(end+1,1)=double(block.hour); %#ok<AGROW>
        n_primal(end+1,1)=double(block.n_primal); %#ok<AGROW>
        n_equalities(end+1,1)=double(block.n_equalities); %#ok<AGROW>
        kkt_dimension(end+1,1)=dimension; %#ok<AGROW>
        day_chain_offset_start(end+1,1)=offset+1; %#ok<AGROW>
        day_chain_offset_end(end+1,1)=offset+dimension; %#ok<AGROW>
        passed=dimension==double(block.n_primal)+double(block.n_equalities)&& ...
            dimension>0;
        status(end+1,1)=pass_text(passed); %#ok<AGROW>
        offset=offset+dimension;
    end
end
output=table(day,hour,n_primal,n_equalities,kkt_dimension, ...
    day_chain_offset_start,day_chain_offset_end,status);
end

function output=make_daily_chain_dimensions(recursive)
n=numel(recursive.daily_partitions); day=zeros(n,1); block_count=zeros(n,1);
sum_block_dimensions=zeros(n,1); chain_rows=zeros(n,1); chain_columns=zeros(n,1);
chain_nnz=zeros(n,1); rhs_count=zeros(n,1); status=strings(n,1);
for k=1:n
    partition=recursive.daily_partitions(k);
    day(k)=double(partition.day_id); block_count(k)=numel(partition.hour);
    sum_block_dimensions(k)=sum([partition.hour.dimension]);
    [chain_rows(k),chain_columns(k)]=size(partition.M);
    chain_nnz(k)=nnz(partition.M); rhs_count(k)=size(partition.B,2)+1;
    status(k)=pass_text(block_count(k)==24&& ...
        sum_block_dimensions(k)==chain_rows(k)&& ...
        chain_rows(k)==chain_columns(k)&&issparse(partition.M)&&rhs_count(k)==15);
end
output=table(day,block_count,sum_block_dimensions,chain_rows,chain_columns, ...
    chain_nnz,rhs_count,status);
end

function output=make_block_diagnostics(recursive,config)
rows=table();
for k=1:numel(recursive.daily_thomas)
    value=recursive.daily_thomas(k).diagnostics.hour_block;
    assert(isstruct(value)&&numel(value)==24, ...
        "stageA3:artifacts:HourDiagnosticsCount", ...
        "Each day requires exactly 24 hourly block diagnostics.");
    current=struct2table(value(:));
    current=addvars(current,repmat(double(recursive.daily_partitions(k).day_id), ...
        height(current),1),'Before',1,'NewVariableNames','day');
    if isempty(rows), rows=current; else, rows=[rows;current]; end %#ok<AGROW>
end
required=["day","hour","dimension","D_numeric_rank", ...
    "D_condition_2","D_symmetry_relative","schur_numeric_rank", ...
    "schur_condition_2","schur_inertia_positive", ...
    "schur_inertia_negative","schur_inertia_zero", ...
    "schur_factor_relative_residual","rhs_count"];
assert(all(ismember(required,string(rows.Properties.VariableNames))), ...
    "stageA3:artifacts:HourDiagnosticsSchema", ...
    "Hourly diagnostic schema is incomplete.");
passed=rows.D_numeric_rank==rows.dimension&isfinite(rows.D_condition_2)& ...
    rows.D_symmetry_relative<=config.tolerances.symmetry_relative& ...
    rows.schur_numeric_rank==rows.dimension& ...
    isfinite(rows.schur_condition_2)&rows.schur_inertia_zero==0& ...
    rows.schur_factor_relative_residual<= ...
        config.tolerances.recursive_full_kkt_relative_residual& ...
    rows.rhs_count==15;
rows.status=repmat("PASS",height(rows),1); rows.status(~passed)="FAIL";
output=rows;
end

