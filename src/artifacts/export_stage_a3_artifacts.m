function exported = export_stage_a3_artifacts(runContext,data,index,config, ...
        linearization,fullResult,recursiveResult,audit,options)
%EXPORT_STAGE_A3_ARTIFACTS Persist the seven-day Stage A3 direction audit.
% The complete 18836 KKT and all day chains remain sparse MAT data.

arguments
    runContext (1,1) struct
    data (1,1) struct
    index (1,1) struct
    config (1,1) struct
    linearization (1,1) struct
    fullResult (1,1) struct
    recursiveResult (1,1) struct
    audit (1,1) struct
    options.Environment = struct()
    options.Tests = struct()
    options.A2Regression = struct()
    options.A1Regression = struct()
    options.CodeScan table = table()
    options.Physical = struct()
end
exported=export_impl(runContext,data,index,config,linearization, ...
    fullResult,recursiveResult,audit,options);
end

