    "W",recursiveResult.reduced.W,"A",recursiveResult.reduced.A, ...
    "saddle",recursiveResult.reduced.saddle, ...
    "rhs",recursiveResult.reduced.rhs, ...
    "theta",recursiveResult.reduced.theta, ...
    "phi",recursiveResult.reduced.phi, ...
    "linearization_identity",recursiveResult.reduced.linearization_identity);
