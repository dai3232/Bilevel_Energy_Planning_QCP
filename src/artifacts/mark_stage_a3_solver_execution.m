function manifest = mark_stage_a3_solver_execution(runContext)
%MARK_STAGE_A3_SOLVER_EXECUTION Record the sole permitted A3 direction.

arguments
    runContext (1,1) struct
end
pathValue=runContext.run_manifest_path;
assert(isfile(pathValue),"stageA3:artifacts:ManifestMissing", ...
    "Run manifest is missing.");
manifest=jsondecode(fileread(pathValue));
assert(string(manifest.run_id)==string(runContext.run_id) && ...
    string(manifest.stage_id)=="stage_A3" && string(manifest.status)=="RUNNING", ...
    "stageA3:artifacts:ManifestIdentity", ...
    "Only the matching RUNNING A3 manifest can record execution.");
assert(isfield(manifest,"a3_solver_executed") && ...
    ~logical(manifest.a3_solver_executed), ...
    "stageA3:artifacts:SolverExecutionAlreadyMarked", ...
    "A3 solver execution was already recorded.");
assert(double(manifest.newton_direction_count)==1 && ...
    ~logical(manifest.full_ipm_executed) && ...
    ~logical(manifest.parallel_executed) && ...
    ~logical(manifest.optimization_executed), ...
    "stageA3:artifacts:ExecutionScope", ...
    "Manifest scope must permit one serial direction and no optimization/IPM.");
manifest.a3_solver_executed=true;
manifest.solver_execution_started_at=char(datetime('now', ...
    'TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSSXXX'));
write_json_file(pathValue,manifest);
end
