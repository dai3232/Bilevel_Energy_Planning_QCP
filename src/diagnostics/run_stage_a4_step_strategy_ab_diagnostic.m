function equal = canonical_state_vectors_equal(left,right)
equal = isequal(left.xi,right.xi) && isequal(left.y,right.y) && ...
    isequal(left.l,right.l) && isequal(left.z,right.z) && ...
    left.iteration_index==right.iteration_index && ...
    left.state_revision==right.state_revision;
end

function equal = canonical_state_equal(left,right)
equal = canonical_state_vectors_equal(left,right) && ...
    left.newton_direction_number==right.newton_direction_number && ...
    left.completed_newton_direction_count== ...
        right.completed_newton_direction_count && ...
    string(left.diagnostic_chain_id)==string(right.diagnostic_chain_id);
end
