chainBToARatio = nan(n,1);
chainBToARatioDefined = false(n,1);
chainAScaledChange = zeros(n,1);
chainBScaledChange = zeros(n,1);
betweenScaledDifference = zeros(n,1);
position = 0;
for k = 1:5
    for metricName = metrics
        position = position+1;
        initial = metric_value(chainA.iterations(1),metricName,"before");
        aValue = metric_value(chainA.iterations(k),metricName,"after");
        bValue = metric_value(chainB.iterations(k),metricName,"after");
        [aRatio,aDefined] = safe_ratio(aValue,initial);
        [bRatio,bDefined] = safe_ratio(bValue,initial);
        [betweenRatio,betweenDefined] = safe_ratio(bValue,aValue);
        iteration(position) = k;
        metric(position) = metricName;
        initialValue(position) = initial;
        chainAValue(position) = aValue;
        chainBValue(position) = bValue;
        chainADelta(position) = aValue-initial;
        chainBDelta(position) = bValue-initial;
        chainARatio(position) = aRatio;
        chainBRatio(position) = bRatio;
        chainARatioDefined(position) = aDefined;
        chainBRatioDefined(position) = bDefined;
        chainBToARatio(position) = betweenRatio;
        chainBToARatioDefined(position) = betweenDefined;
        chainAScaledChange(position) = ...
            (aValue-initial)/max(1,abs(initial));
        chainBScaledChange(position) = ...
            (bValue-initial)/max(1,abs(initial));
        betweenScaledDifference(position) = ...
            (bValue-aValue)/max([1,abs(aValue),abs(bValue)]);
    end
end
output = table(iteration,metric,initialValue,chainAValue,chainBValue, ...
    chainADelta,chainBDelta,chainARatio,chainBRatio, ...
    chainARatioDefined,chainBRatioDefined,chainBToARatio, ...
    chainBToARatioDefined,chainAScaledChange,chainBScaledChange, ...
    betweenScaledDifference, ...
    'VariableNames',{'iteration','metric','initial_value','chain_a_value', ...
    'chain_b_value','chain_a_delta_from_initial', ...
    'chain_b_delta_from_initial','chain_a_ratio_to_initial', ...
    'chain_b_ratio_to_initial','chain_a_ratio_defined', ...
    'chain_b_ratio_defined','chain_b_to_chain_a_ratio', ...
    'chain_b_to_chain_a_ratio_defined','chain_a_scaled_change', ...
    'chain_b_scaled_change','between_chain_scaled_difference'});
end

function value = metric_value(item,metric,state)
if metric=="investment_objective"
    value = item.("objective_value_"+state);
else
    snapshot = item.("residuals_"+state);
    value = snapshot.(metric);
end
end

function [ratio,defined] = safe_ratio(value,reference)
defined = reference~=0;
if defined
    ratio = value/reference;
else
    ratio = NaN;
end
end

function output = combine_audit_table(chainA,chainB,fieldName)
chains = {chainA,chainB};
output = table();
for c = 1:2
    for k = 1:5
        rows = chains{c}.complementarity_audits(k).(fieldName);
        rows = addvars(rows, ...
            repmat(chains{c}.diagnostic_chain_id,height(rows),1), ...
            repmat(chains{c}.step_strategy,height(rows),1), ...
            'Before',1,'NewVariableNames',{'chain_id','strategy'});
        output = [output;rows]; %#ok<AGROW>
    end
end
end

