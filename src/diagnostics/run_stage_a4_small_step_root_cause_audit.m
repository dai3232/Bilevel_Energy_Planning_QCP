end

function [closureTable,qp5Table] = build_direction_closure_evidence( ...
        abResult,indexA,indexB,config,tolerance)
chains = {abResult.chain_a,abResult.chain_b};
indices = {indexA,indexB};
closureRecords = repmat(empty_direction_closure_record(),10,1);
qp5Records = repmat(empty_qp5_causal_record(),20,1);
closurePosition = 0;
qp5Position = 0;
for c = 1:2
    variables = indices{c}.variable_index;
    qMask = variables.day==0 & variables.hour==0 & ...
        string(variables.variable_name)=="QP5";
    qIndex = variables.global_index_start(qMask);
    inequalities = inequalities_from_index(indices{c});
    lower = find(string(inequalities.constraint_id)=="INEQ-Q-LOWER-QP5");
    upper = find(string(inequalities.constraint_id)=="INEQ-Q-UPPER-QP5");
    for k = 1:5
        item = chains{c}.iterations(k);
        snapshot = item.root_cause_linearization_before;
        direction = item.recursive_direction_components;
        eqTerm = snapshot.A*direction.xi;
        eqClosure = eqTerm+snapshot.r_eq;
        ineqGTerm = snapshot.G*direction.xi;
        ineqClosure = ineqGTerm+direction.l+snapshot.r_ineq;
        compSlackTerm = snapshot.z.*direction.l;
        compMultiplierTerm = snapshot.l.*direction.z;
        compClosure = compSlackTerm+compMultiplierTerm+snapshot.r_comp;
        dualHTerm = snapshot.H*direction.xi;
        dualATerm = snapshot.A.'*direction.y;
        dualGTerm = snapshot.G.'*direction.z;
        dualClosure = dualHTerm+dualATerm+dualGTerm+snapshot.r_dual;
        eqDenominator = max(ones(numel(eqClosure),1), ...
            abs(snapshot.A)*abs(direction.xi)+abs(snapshot.r_eq));
        ineqDenominator = max(ones(numel(ineqClosure),1), ...
            abs(snapshot.G)*abs(direction.xi)+abs(direction.l)+ ...
            abs(snapshot.r_ineq));
        compDenominator = max(ones(numel(compClosure),1), ...
            abs(compSlackTerm)+abs(compMultiplierTerm)+ ...
            abs(snapshot.r_comp));
        dualDenominator = max(ones(numel(dualClosure),1), ...
            abs(snapshot.H)*abs(direction.xi)+ ...
            abs(snapshot.A).'*abs(direction.y)+ ...
            abs(snapshot.G).'*abs(direction.z)+abs(snapshot.r_dual));
        eqScaled = max(abs(eqClosure)./eqDenominator);
        ineqScaled = max(abs(ineqClosure)./ineqDenominator);
        compScaled = max(abs(compClosure)./compDenominator);
        dualScaled = max(abs(dualClosure)./dualDenominator);
        closurePosition = closurePosition+1;
        record = empty_direction_closure_record();
        record.chain_id = char(chains{c}.diagnostic_chain_id);
        record.strategy = char(chains{c}.step_strategy);
        record.iteration = k;
        record.linearization_identity = char(snapshot.identity);
        record.hessian_nnz = nnz(snapshot.H);
        record.equality_scaled_closure = eqScaled;
        record.inequality_scaled_closure = ineqScaled;
        record.complementarity_scaled_closure = compScaled;
        record.dual_scaled_closure = dualScaled;
        record.maximum_scaled_closure = max([eqScaled,ineqScaled, ...
            compScaled,dualScaled]);
        record.direction_relative_error = item.direction_relative_error;
        record.recursive_kkt_relative_residual = ...
            item.recursive_kkt_relative_residual;
        record.full_kkt_relative_residual = ...
            item.full_kkt_relative_residual;
        record.no_full_direction_fallback = ...
            item.no_full_direction_fallback;
        record.passed = record.hessian_nnz==0 && ...
            record.maximum_scaled_closure<=tolerance && ...
            item.direction_relative_error<= ...
                config.tolerances.direction_relative_2norm && ...
            item.recursive_kkt_relative_residual<= ...
                config.tolerances.recursive_full_kkt_relative_residual && ...
            item.full_kkt_relative_residual<= ...
                config.tolerances.direct_maximum && ...
            item.no_full_direction_fallback;
        closureRecords(closurePosition) = record;

        for row = [lower,upper]
            qp5Position = qp5Position+1;
            qp5Records(qp5Position) = qp5_causal_record( ...
                chains{c},item,snapshot,direction,inequalities,row, ...
                qIndex,config.fraction_to_boundary,tolerance);
        end
    end
end
closureTable = struct2table(closureRecords);
closureTable.chain_id = string(closureTable.chain_id);
closureTable.strategy = string(closureTable.strategy);
closureTable.linearization_identity = ...
    string(closureTable.linearization_identity);
qp5Table = struct2table(qp5Records);
for name = ["chain_id","strategy","bound_side","constraint_id"]
    qp5Table.(name) = string(qp5Table.(name));
end
end

function record = qp5_causal_record(chain,item,snapshot,direction, ...
        inequalities,row,qIndex,tau,tolerance)
constraintId = string(inequalities.constraint_id(row));
if contains(constraintId,"LOWER")
    side = "lower";
else
    side = "upper";
end
gDirection = snapshot.G(row,:)*direction.xi;
qContribution = snapshot.G(row,qIndex)*direction.xi(qIndex);
otherGContribution = gDirection-qContribution;
ineqClosure = gDirection+direction.l(row)+snapshot.r_ineq(row);
ineqScale = max(1,abs(snapshot.G(row,:))*abs(direction.xi)+ ...
    abs(direction.l(row))+abs(snapshot.r_ineq(row)));
slackCompTerm = snapshot.z(row)*direction.l(row);
multiplierCompTerm = snapshot.l(row)*direction.z(row);
compClosure = slackCompTerm+multiplierCompTerm+snapshot.r_comp(row);
compScale = max(1,abs(slackCompTerm)+abs(multiplierCompTerm)+ ...
    abs(snapshot.r_comp(row)));
dualATerm = snapshot.A(:,qIndex).'*direction.y;
dualGTerm = snapshot.G(:,qIndex).'*direction.z;
dualHTerm = snapshot.H(qIndex,:)*direction.xi;
dualClosure = dualHTerm+dualATerm+dualGTerm+snapshot.r_dual(qIndex);
dualScale = max(1,abs(snapshot.H(qIndex,:))*abs(direction.xi)+ ...
    abs(snapshot.A(:,qIndex)).'*abs(direction.y)+ ...
    abs(snapshot.G(:,qIndex)).'*abs(direction.z)+ ...
    abs(snapshot.r_dual(qIndex)));
slackRaw = boundary_ratio(snapshot.l(row),direction.l(row));
multiplierRaw = boundary_ratio(snapshot.z(row),direction.z(row));
slackCandidate = capped_candidate(slackRaw,tau);
multiplierCandidate = capped_candidate(multiplierRaw,tau);

record = empty_qp5_causal_record();
record.chain_id = char(chain.diagnostic_chain_id);
record.strategy = char(chain.step_strategy);
record.iteration = item.iteration;
record.bound_side = char(side);
record.inequality_index = row;
record.constraint_global_row = inequalities.global_row(row);
record.constraint_id = char(constraintId);
record.qp5_variable_global_index = qIndex;
record.qp5_value = item.canonical_state_before.xi(qIndex);
record.delta_qp5 = direction.xi(qIndex);
record.g_qp5_coefficient = snapshot.G(row,qIndex);
record.g_delta_xi = gDirection;
record.g_delta_qp5_contribution = qContribution;
record.g_other_variable_contribution = otherGContribution;
record.r_ineq = snapshot.r_ineq(row);
record.l = snapshot.l(row);
record.delta_l = direction.l(row);
record.inequality_direction_closure = ineqClosure;
record.inequality_direction_scaled_closure = abs(ineqClosure)/ineqScale;
record.z = snapshot.z(row);
record.delta_z = direction.z(row);
record.r_comp = snapshot.r_comp(row);
record.z_times_delta_l = slackCompTerm;
record.l_times_delta_z = multiplierCompTerm;
record.complementarity_direction_closure = compClosure;
record.complementarity_direction_scaled_closure = ...
    abs(compClosure)/compScale;
record.slack_raw_boundary_ratio = slackRaw;
record.multiplier_raw_boundary_ratio = multiplierRaw;
record.slack_candidate_alpha = slackCandidate;
record.multiplier_candidate_alpha = multiplierCandidate;
record.official_candidate_alpha_primal = item.candidate_alpha_primal;
record.official_candidate_alpha_dual = item.candidate_alpha_dual;
record.is_primal_limiter = item.primal_step.limiting_index==row;
record.is_dual_limiter = item.dual_step.limiting_index==row;
record.qp5_dual_h_delta_xi = dualHTerm;
record.qp5_dual_a_transpose_delta_y = dualATerm;
record.qp5_dual_g_transpose_delta_z = dualGTerm;
record.qp5_r_dual = snapshot.r_dual(qIndex);
record.qp5_dual_direction_closure = dualClosure;
record.qp5_dual_direction_scaled_closure = abs(dualClosure)/dualScale;
record.maximum_scaled_closure = max([ ...
    record.inequality_direction_scaled_closure, ...
    record.complementarity_direction_scaled_closure, ...
    record.qp5_dual_direction_scaled_closure]);
record.passed = record.maximum_scaled_closure<=tolerance;
end

