directionErrors = reshape([items.direction_relative_error],[],1);
recursiveResiduals = reshape( ...
    [items.recursive_kkt_relative_residual],[],1);
directResiduals = reshape([items.full_kkt_relative_residual],[],1);
noFallback = reshape([items.no_full_direction_fallback],[],1);
audit = struct( ...
    "maximum_direction_relative_error",max(directionErrors), ...
    "maximum_recursive_complete_kkt_relative_residual", ...
        max(recursiveResiduals), ...
    "maximum_direct_complete_kkt_relative_residual", ...
        max(directResiduals), ...
    "all_no_full_direction_fallback",all(noFallback), ...
    "passed",all(directionErrors<=directionTolerance) && ...
        all(recursiveResiduals<=recursiveTolerance) && ...
        all(directResiduals<=directTolerance) && all(noFallback));
end

function conclusion = build_root_cause_conclusion( ...
        decomposition,qp5Metadata,qp5CausalChain,directionClosure,abResult)
