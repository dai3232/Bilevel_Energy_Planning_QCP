record = struct("chain_id","","strategy","","iteration",0, ...
    "step_kind","","candidate_count",0, ...
    "minimum_candidate_alpha",NaN,"median_candidate_alpha",NaN, ...
    "p95_candidate_alpha",NaN,"maximum_candidate_alpha",NaN, ...
    "minimum_raw_boundary_ratio",NaN, ...
    "median_raw_boundary_ratio",NaN,"p95_raw_boundary_ratio",NaN, ...
    "maximum_raw_boundary_ratio",NaN, ...
    "within_2x_minimum_count",0,"within_10x_minimum_count",0, ...
    "within_100x_minimum_count",0, ...
    "concentration_basis","", ...
    "reconstructed_global_alpha",NaN, ...
    "official_candidate_alpha",NaN, ...
    "alpha_closure_scaled_error",NaN, ...
    "negative_direction_count",0,"global_limiter_count",0, ...
    "limiter_traceable",false);
end

function output = group_candidate_inventory(inventory)
records = repmat(empty_candidate_group_record(),0,1);
for groupKind = ["constraint_name","asset_type"]
    groupValues = string(inventory.(groupKind));
    keys = unique(inventory(:,{'chain_id','strategy','iteration', ...
        'step_kind'}),'rows','stable');
    for keyIndex = 1:height(keys)
        key = keys(keyIndex,:);
        keyMask = inventory.chain_id==key.chain_id & ...
            inventory.strategy==key.strategy & ...
            inventory.iteration==key.iteration & ...
            inventory.step_kind==key.step_kind;
        names = sort(unique(groupValues(keyMask)));
        for groupName = names.'
            mask = keyMask & groupValues==groupName;
            values = inventory.reconstructed_candidate_alpha(mask);
            raw = inventory.raw_boundary_ratio(mask);
            record = empty_candidate_group_record();
            record.chain_id = char(key.chain_id);
            record.strategy = char(key.strategy);
            record.iteration = key.iteration;
            record.step_kind = char(key.step_kind);
            record.group_kind = char(groupKind);
            record.group_name = char(groupName);
            record.candidate_count = nnz(mask);
            record.minimum_candidate_alpha = min(values);
            record.minimum_raw_boundary_ratio = min(raw);
            record.global_limiter_count = ...
                nnz(inventory.is_global_limiter(mask));
            records(end+1,1) = record; %#ok<AGROW>
        end
    end
end
output = struct2table(records);
for name = ["chain_id","strategy","step_kind","group_kind","group_name"]
    output.(name) = string(output.(name));
end
end

function record = empty_candidate_group_record()
record = struct("chain_id","","strategy","","iteration",0, ...
    "step_kind","","group_kind","","group_name","", ...
    "candidate_count",0,"minimum_candidate_alpha",NaN, ...
    "minimum_raw_boundary_ratio",NaN,"global_limiter_count",0);
end

function passed = candidate_group_evidence_closed(summary,grouped,tolerance)
passed = true;
for rowNumber = 1:height(summary)
    source = summary(rowNumber,:);
    for groupKind = ["constraint_name","asset_type"]
        mask = grouped.chain_id==source.chain_id & ...
            grouped.strategy==source.strategy & ...
            grouped.iteration==source.iteration & ...
            grouped.step_kind==source.step_kind & ...
            grouped.group_kind==groupKind;
        rows = grouped(mask,:);
        if isempty(rows)
            passed = false;
            return
        end
        rawMinimum = min(rows.minimum_raw_boundary_ratio);
        scale = max([1,abs(rawMinimum), ...
            abs(source.minimum_raw_boundary_ratio)]);
        passed = passed && ...
            sum(rows.candidate_count)==source.candidate_count && ...
            abs(rawMinimum-source.minimum_raw_boundary_ratio)/scale<= ...
                tolerance && ...
            sum(rows.global_limiter_count)==1;
        if ~passed
            return
        end
    end
end
end

function [decomposition,qp5Metadata,audit] = ...
        build_initial_dual_decomposition(abResult,indexA,indexB,tolerance)
itemA = abResult.chain_a.iterations(1);
itemB = abResult.chain_b.iterations(1);
snapshotA = itemA.root_cause_linearization_before;
snapshotB = itemB.root_cause_linearization_before;
stateA = itemA.canonical_state_before;
stateB = itemB.canonical_state_before;
assert(isequal(stateA.xi,stateB.xi) && isequal(stateA.y,stateB.y) && ...
    isequal(stateA.l,stateB.l) && isequal(stateA.z,stateB.z), ...
    "stageA4:a42d1:InitialChainState", ...
    "A4-2C chains must start from the same canonical state.");

variables = indexA.variable_index;
variables = sortrows(variables,"global_index_start");
objectiveGradient = snapshotA.objective_gradient(:);
aTransposeY = snapshotA.A.'*stateA.y;
gTransposeZ = snapshotA.G.'*stateA.z;
reconstructed = objectiveGradient+aTransposeY+gTransposeZ;
actual = snapshotA.r_dual(:);
closure = reconstructed-actual;
closureDenominator = max(ones(numel(closure),1), ...
    abs(objectiveGradient)+abs(snapshotA.A).'*abs(stateA.y)+ ...
    abs(snapshotA.G).'*abs(stateA.z)+abs(actual));
scaledClosure = abs(closure)./closureDenominator;
groups = primal_variable_groups(variables);
variableId = string(variables.block_id)+"|"+ ...
    string(variables.variable_name)+"|"+ ...
    string(variables.global_index_start);
decomposition = table(variables.global_index_start,variableId, ...
    string(variables.block_id),variables.day,variables.hour, ...
    string(variables.asset_type),variables.asset_id, ...
    string(variables.variable_name),string(variables.unit),groups, ...
    objectiveGradient,aTransposeY,gTransposeZ,reconstructed,actual, ...
    closure,scaledClosure, ...
    'VariableNames',{'variable_global_index','variable_id','block_id', ...
