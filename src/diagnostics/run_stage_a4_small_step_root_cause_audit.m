function groups = primal_variable_groups(variables)
groups = strings(height(variables),1);
for k = 1:height(variables)
    assetType = string(variables.asset_type(k));
    variableName = string(variables.variable_name(k));
    if variables.day(k)==0 && variables.hour(k)==0
        groups(k) = "global_capacity";
    elseif variables.day(k)>0 && variables.hour(k)==0
        groups(k) = "daily_capacity_copy";
    elseif assetType=="wind"
        groups(k) = "wind";
    elseif assetType=="solar"
        groups(k) = "solar";
    elseif assetType=="hydro"
        groups(k) = "hydro";
    elseif assetType=="thermal"
        groups(k) = "thermal";
    elseif variableName=="Pch"
        groups(k) = "pch";
    elseif variableName=="Pdis"
        groups(k) = "pdis";
    elseif variableName=="SOC"
        groups(k) = "soc";
    else
        error("stageA4:a42d1:VariableGroup", ...
            "Canonical variable %d cannot be assigned to a user group.",k);
    end
end
end

function statistics = scale_statistics(values)
values = values(:);
absoluteValues = abs(values);
nonzeroValues = absoluteValues(absoluteValues>0);
if isempty(nonzeroValues)
    minimumAbsoluteNonzero = NaN;
    minimumOrder = NaN;
    maximumOrder = NaN;
    orderSpan = NaN;
else
    minimumAbsoluteNonzero = min(nonzeroValues);
    minimumOrder = floor(log10(minimumAbsoluteNonzero));
    maximumOrder = floor(log10(max(nonzeroValues)));
    orderSpan = maximumOrder-minimumOrder;
end
statistics = struct( ...
    "count",numel(values), ...
    "nonzero_count",numel(nonzeroValues), ...
    "negative_count",nnz(values<0), ...
    "zero_count",nnz(values==0), ...
    "positive_count",nnz(values>0), ...
    "minimum_value",min(values), ...
    "maximum_value",max(values), ...
    "minimum_absolute_nonzero",minimumAbsoluteNonzero, ...
    "median_absolute",median(absoluteValues), ...
    "p95_absolute",percentile95(absoluteValues), ...
    "maximum_absolute",max(absoluteValues), ...
    "minimum_order_of_magnitude",minimumOrder, ...
    "maximum_order_of_magnitude",maximumOrder, ...
    "order_of_magnitude_span",orderSpan);
end

function value = percentile95(values)
values = sort(values(:));
position = 1+0.95*(numel(values)-1);
lowerPosition = floor(position);
upperPosition = ceil(position);
if lowerPosition==upperPosition
    value = values(lowerPosition);
else
    weight = position-lowerPosition;
    value = (1-weight)*values(lowerPosition)+weight*values(upperPosition);
end
end

function ratio = boundary_ratio(value,direction)
if direction<0
    ratio = -value/direction;
else
    ratio = Inf;
end
end

function value = capped_candidate(rawRatio,tau)
if isinf(rawRatio)
    value = 1;
else
    value = min(1,tau*rawRatio);
end
end

