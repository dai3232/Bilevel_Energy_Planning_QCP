function result = run_stage_a4_small_step_root_cause_audit( ...
        abResult,indexA,indexB,config,projectRoot)
%RUN_STAGE_A4_SMALL_STEP_ROOT_CAUSE_AUDIT Read-only A4-2D-1 audit.
%
% The caller supplies the already executed A4-2C A/B result.  This
% function only evaluates retained states, recursive directions, and
% sparse pre-update linearization snapshots.  It performs no Newton solve,
% state update, artifact write, or stage transition.

arguments
    abResult (1,1) struct
    indexA (1,1) struct
    indexB (1,1) struct
    config (1,1) struct
    projectRoot (1,1) string
end

validate_scope(abResult,indexA,indexB,config,projectRoot);
numericTolerance = 2048*eps;
directionTolerance = config.tolerances.direction_relative_2norm;
recursiveResidualTolerance = ...
    config.tolerances.recursive_full_kkt_relative_residual;
directResidualTolerance = config.tolerances.direct_maximum;
protectedBefore = capture_protected_objects(abResult);

fixtureAudit = audit_frozen_fixtures(abResult,projectRoot);
[candidateInventory,candidateSummary,candidateGroupSummary] = ...
    build_step_candidate_evidence(abResult,indexA,indexB,config, ...
        numericTolerance);
top20Candidates = candidateInventory(candidateInventory.rank<=20,:);

[dualDecomposition,qp5Metadata,dualDecompositionAudit] = ...
    build_initial_dual_decomposition(abResult,indexA,indexB, ...
        numericTolerance);
[directionClosure,qp5CausalChain] = build_direction_closure_evidence( ...
    abResult,indexA,indexB,config,numericTolerance);
[initialStateScales,initialGroupScales, ...
    initialResidualGroupScales,initialCentrality,scaleAudit] = ...
    build_initialization_and_scale_evidence(abResult,indexA,indexB);

protectedAfter = capture_protected_objects(abResult);
readOnlyAudit = compare_protected_objects(protectedBefore,protectedAfter);
directionAudit = audit_existing_direction_evidence(abResult, ...
    directionTolerance,recursiveResidualTolerance,directResidualTolerance);
rootCauseConclusion = build_root_cause_conclusion( ...
    dualDecomposition,qp5Metadata,qp5CausalChain, ...
    directionClosure,abResult);

checks = struct( ...
    "frozen_a4_2a_baseline_fixture_reproduced_field_by_field", ...
        fixtureAudit.passed, ...
    "all_step_candidates_reconstructed_and_traceable", ...
        all(candidateSummary.alpha_closure_scaled_error<= ...
            numericTolerance) && ...
        all(candidateSummary.limiter_traceable) && ...
        height(candidateSummary)==20 && ...
        candidate_group_evidence_closed(candidateSummary, ...
            candidateGroupSummary,numericTolerance), ...
    "initial_dual_residual_decomposition_closed", ...
        dualDecompositionAudit.passed, ...
    "all_four_direction_equations_closed", ...
        all(directionClosure.maximum_scaled_closure<=numericTolerance), ...
    "qp5_bound_causal_chain_closed", ...
        height(qp5CausalChain)==20 && ...
        all(qp5CausalChain.maximum_scaled_closure<=numericTolerance), ...
    "initialization_and_scale_coverage_complete",scaleAudit.passed, ...
    "audit_objects_and_fingerprints_unchanged",readOnlyAudit.passed, ...
    "existing_recursive_and_complete_kkt_audits_passed", ...
        directionAudit.passed, ...
    "single_factor_recommendation_only", ...
        rootCauseConclusion.next_single_factor_experiment== ...
            "dual_initialization");
checkValues = struct2cell(checks);
allPass = all(cellfun(@(value)isequal(value,true),checkValues));
if ~allPass
    names = string(fieldnames(checks));
    names = names(~cellfun(@(value)isequal(value,true),checkValues));
    error("stageA4:a42d1:AuditFailed", ...
        "A4-2D-1 checks failed: %s.",strjoin(names,", "));
end

result = struct();
result.stage_id = "stage_A4";
result.stage_status = "READY";
result.milestone = "A4-2D-1_small_step_root_cause_read_only_audit";
result.milestone_status = "PASS";
result.ab_result = abResult;
result.index_a = indexA;
result.index_b = indexB;
result.fixture_audit = fixtureAudit;
result.step_candidate_inventory = candidateInventory;
result.top20_step_candidates = top20Candidates;
result.step_candidate_summary = candidateSummary;
result.step_candidate_group_summary = candidateGroupSummary;
result.initial_dual_decomposition = dualDecomposition;
result.qp5_metadata = qp5Metadata;
result.dual_decomposition_audit = dualDecompositionAudit;
result.direction_equation_closure = directionClosure;
result.qp5_causal_chain = qp5CausalChain;
result.initial_state_scale_statistics = initialStateScales;
result.initial_user_group_scale_statistics = initialGroupScales;
result.initial_residual_group_scale_statistics = ...
    initialResidualGroupScales;
result.initial_centrality_statistics = initialCentrality;
result.scale_audit = scaleAudit;
result.read_only_audit = readOnlyAudit;
result.existing_direction_audit = directionAudit;
result.root_cause_conclusion = rootCauseConclusion;
result.checks = checks;
result.all_pass = allPass;
result.execution = struct( ...
    "baseline_chain_count",2, ...
    "baseline_iterations_per_chain",5, ...
    "baseline_newton_direction_count",10, ...
    "baseline_complete_kkt_audit_count",10, ...
    "baseline_state_update_count",10, ...
    "additional_audit_newton_direction_count",0, ...
    "additional_audit_complete_kkt_solve_count",0, ...
    "additional_audit_state_update_count",0, ...
    "formal_a4_run_created",false, ...
    "full_ipm_executed",false, ...
    "optimization_executed",false, ...
    "parallel_executed",false, ...
    "formal_step_rule_modified",false, ...
    "initialization_modified",false, ...
    "objective_or_model_scale_modified",false, ...
    "stage_b_entered",false);
end

function validate_scope(abResult,indexA,indexB,config,projectRoot)
assert(isfolder(projectRoot) && config.stage_id=="stage_A4" && ...
    config.status=="READY" && abResult.stage_id=="stage_A4" && ...
    abResult.stage_status=="READY" && abResult.all_pass, ...
    "stageA4:a42d1:Scope", ...
    "A4-2D-1 requires a passing A4-2C result under stage_A4 / READY.");
assert(abResult.execution.chain_count==2 && ...
    abResult.execution.iterations_per_chain==5 && ...
    abResult.execution.newton_direction_count==10 && ...
    abResult.execution.full_kkt_audit_count==10 && ...
    abResult.execution.state_update_count==10, ...
    "stageA4:a42d1:BaselineExecution", ...
    "The retained A4-2C baseline must contain both complete five-round chains.");
assert(abResult.chain_a.diagnostic_chain_id=="A4-2C-A" && ...
    abResult.chain_b.diagnostic_chain_id=="A4-2C-B" && ...
    abResult.chain_a.step_strategy=="independent" && ...
    abResult.chain_b.step_strategy=="common_min" && ...
    numel(abResult.chain_a.iterations)==5 && ...
    numel(abResult.chain_b.iterations)==5, ...
    "stageA4:a42d1:ChainIdentity", ...
    "A4-2D-1 must reuse the isolated A4-2C A and B chains.");
assert(indexA.scope.stage_id=="stage_A4" && ...
    indexB.scope.stage_id=="stage_A4", ...
    "stageA4:a42d1:IndexIdentity", ...
    "Both supplied canonical indices must identify stage_A4.");

chains = {abResult.chain_a,abResult.chain_b};
indices = {indexA,indexB};
requiredSnapshot = ["identity","H","A","G","objective_gradient", ...
    "r_dual","r_eq","r_ineq","r_comp","l","z","mu", ...
    "eq_offset","ineq_offset"];
for c = 1:2
    variables = indices{c}.variable_index;
    constraints = indices{c}.constraint_index;
    nPrimal = height(variables);
    nEquality = nnz(string(constraints.constraint_type)=="equality");
    nInequality = nnz(string(constraints.constraint_type)=="inequality");
    for k = 1:5
        item = chains{c}.iterations(k);
        assert(isfield(item,"root_cause_linearization_before") && ...
            isfield(item,"canonical_state_before") && ...
            isfield(item,"canonical_state_after") && ...
            isfield(item,"recursive_direction_components"), ...
            "stageA4:a42d1:RetainedEvidence", ...
            "Chain %d iteration %d lacks retained root-cause evidence.",c,k);
        snapshot = item.root_cause_linearization_before;
        for name = requiredSnapshot
            assert(isfield(snapshot,name), ...
                "stageA4:a42d1:SnapshotField", ...
                "Retained linearization field %s is missing.",name);
        end
        state = item.canonical_state_before;
        direction = item.recursive_direction_components;
        assert(snapshot.identity==item.linearization_identity_before && ...
            isequal(snapshot.l(:),state.l(:)) && ...
            isequal(snapshot.z(:),state.z(:)) && ...
            isequal(size(snapshot.A),[nEquality,nPrimal]) && ...
            isequal(size(snapshot.G),[nInequality,nPrimal]) && ...
            numel(snapshot.r_eq)==nEquality && ...
            numel(snapshot.r_dual)==nPrimal && ...
            numel(snapshot.r_ineq)==nInequality && ...
            numel(snapshot.r_comp)==nInequality && ...
            numel(direction.xi)==nPrimal && ...
            numel(direction.y)==nEquality && ...
            numel(direction.l)==nInequality && ...
            numel(direction.z)==nInequality && nnz(snapshot.H)==0, ...
            "stageA4:a42d1:SnapshotDimension", ...
            "Retained root-cause evidence has inconsistent dimensions.");
    end
end
end

function audit = audit_frozen_fixtures(abResult,projectRoot)
fixtureAPath = fullfile(projectRoot,"tests","fixtures", ...
    "stage_A4_2A_five_round_baseline.csv");
assert(isfile(fixtureAPath), ...
    "stageA4:a42d1:FrozenFixtureMissing", ...
    "The frozen A4-2A baseline fixture is required.");

actualA = make_baseline_table(abResult.chain_a.iterations);
expectedA = readtable(fixtureAPath,'Delimiter',',', ...
    'ReadVariableNames',true,'TextType','string', ...
    'VariableNamingRule','preserve');
[passedA,detailsA] = fixture_matches(actualA,expectedA);
chainB = abResult.chain_b;
chainBInternalContract = chainB.all_pass && ...
    chainB.iteration_count==5 && chainB.step_strategy=="common_min" && ...
    all([chainB.iterations.all_pass]) && ...
    numel(unique(string( ...
        {chainB.iterations.direction_solve_invocation_id})))==5 && ...
    all([chainB.iterations.no_full_direction_fallback]);
audit = struct( ...
    "chain_a_fixture_path",string(fixtureAPath), ...
    "chain_a_fixture_sha256",string(compute_sha256_file(fixtureAPath)), ...
    "chain_a_field_count",width(expectedA), ...
    "chain_a_row_count",height(expectedA), ...
    "chain_a_details",detailsA, ...
    "chain_a_passed",passedA, ...
    "chain_b_internal_five_round_contract_passed", ...
        chainBInternalContract, ...
    "passed",passedA && chainBInternalContract);
end

function [passed,details] = fixture_matches(actual,expected)
expectedNames = string(expected.Properties.VariableNames).';
actualNames = string(actual.Properties.VariableNames).';
sameNames = isequal(actualNames,expectedNames);
sameHeight = height(actual)==height(expected);
fieldPassed = false(numel(expectedNames),1);
if sameNames && sameHeight
    for k = 1:numel(expectedNames)
        name = expectedNames(k);
        left = actual.(name);
        right = expected.(name);
        if isnumeric(left) && isnumeric(right)
            fieldPassed(k) = isequaln(double(left),double(right));
        else
            fieldPassed(k) = isequaln(string(left),string(right));
        end
    end
end
details = table(expectedNames,fieldPassed, ...
    'VariableNames',{'field_name','passed'});
passed = sameNames && sameHeight && all(fieldPassed);
end

function baseline = make_baseline_table(iterations)
n = numel(iterations);
iteration = reshape([iterations.iteration],[],1);
alphaPrimal = reshape([iterations.alpha_primal],[],1);
alphaDual = reshape([iterations.alpha_dual],[],1);
primalLimiter = strings(n,1);
dualLimiter = strings(n,1);
numericNames = ["equality_before","equality_after", ...
    "slack_equality_before","slack_equality_after","dual_before", ...
    "dual_after","complementarity_inf_before", ...
    "complementarity_inf_after","gap_before","gap_after", ...
    "minimum_l_after","minimum_z_after","direction_relative_error", ...
    "xi_relative_error","y_relative_error","l_relative_error", ...
    "z_relative_error","recursive_kkt_relative_residual", ...
    "full_kkt_relative_residual"];
values = zeros(n,numel(numericNames));
for k = 1:n
    item = iterations(k);
    primalLimiter(k) = item.primal_step.limiting_constraint_id;
    dualLimiter(k) = item.dual_step.limiting_constraint_id;
    before = item.residuals_before;
    after = item.residuals_after;
    values(k,:) = [before.equality_inf,after.equality_inf, ...
        before.slack_equality_inf,after.slack_equality_inf, ...
        before.dual_inf,after.dual_inf, ...
        before.complementarity_inf,after.complementarity_inf, ...
        before.complementarity_gap,after.complementarity_gap, ...
        after.minimum_l,after.minimum_z,item.direction_relative_error, ...
        item.component_relative_errors.xi, ...
        item.component_relative_errors.y, ...
        item.component_relative_errors.l, ...
        item.component_relative_errors.z, ...
        item.recursive_kkt_relative_residual, ...
        item.full_kkt_relative_residual];
end
baseline = table(iteration,alphaPrimal,alphaDual,primalLimiter, ...
    dualLimiter,values(:,1),values(:,2),values(:,3),values(:,4), ...
    values(:,5),values(:,6),values(:,7),values(:,8),values(:,9), ...
    values(:,10),values(:,11),values(:,12),values(:,13),values(:,14), ...
    values(:,15),values(:,16),values(:,17),values(:,18),values(:,19), ...
    'VariableNames',[{'iteration','alpha_primal','alpha_dual', ...
    'primal_limiter','dual_limiter'},cellstr(numericNames)]);
end

function [inventory,summary,groupSummary] = ...
        build_step_candidate_evidence(abResult,indexA,indexB,config,tolerance)
chains = {abResult.chain_a,abResult.chain_b};
indices = {indexA,indexB};
inventory = table();
summaryRecords = repmat(empty_candidate_summary(),20,1);
summaryPosition = 0;
for c = 1:2
    inequalities = inequalities_from_index(indices{c});
    for k = 1:5
        item = chains{c}.iterations(k);
        state = item.canonical_state_before;
        direction = item.recursive_direction_components;
        for stepKind = ["primal","dual"]
            if stepKind=="primal"
                values = state.l(:);
                delta = direction.l(:);
                officialStep = item.primal_step;
            else
                values = state.z(:);
                delta = direction.z(:);
                officialStep = item.dual_step;
            end
            [rows,record] = candidate_rows(chains{c},k,stepKind, ...
                values,delta,officialStep,inequalities, ...
                config.fraction_to_boundary,tolerance);
            inventory = append_table(inventory,rows);
            summaryPosition = summaryPosition+1;
            summaryRecords(summaryPosition) = record;
        end
    end
end
summary = struct2table(summaryRecords);
summary.chain_id = string(summary.chain_id);
summary.strategy = string(summary.strategy);
summary.step_kind = string(summary.step_kind);
summary.concentration_basis = string(summary.concentration_basis);
groupSummary = group_candidate_inventory(inventory);
end

function [rows,record] = candidate_rows(chain,iteration,stepKind, ...
        values,direction,officialStep,inequalities,tau,tolerance)
negative = find(direction<0);
rawRatio = -values(negative)./direction(negative);
candidateAlpha = min(ones(numel(negative),1),tau*rawRatio);
if isempty(negative)
    reconstructedAlpha = 1;
else
    [~,order] = sortrows([candidateAlpha,negative],[1,2]);
    negative = negative(order);
    rawRatio = rawRatio(order);
    candidateAlpha = candidateAlpha(order);
    reconstructedAlpha = min(candidateAlpha);
end
metadata = inequalities(negative,:);
n = numel(negative);
rank = (1:n).';
isLimiter = negative==officialStep.limiting_index;
rows = table( ...
    repmat(chain.diagnostic_chain_id,n,1), ...
    repmat(chain.step_strategy,n,1),repmat(iteration,n,1), ...
    repmat(stepKind,n,1),negative,metadata.global_row, ...
    string(metadata.constraint_id),string(metadata.constraint_name), ...
    metadata.day,metadata.hour,string(metadata.asset_type), ...
    metadata.asset_id,string(metadata.unit),values(negative), ...
    direction(negative),rawRatio,repmat(tau,n,1),candidateAlpha, ...
    rank,isLimiter, ...
    'VariableNames',{'chain_id','strategy','iteration','step_kind', ...
    'inequality_index','constraint_global_row','constraint_id', ...
    'constraint_name','day','hour','asset_type','asset_id','unit', ...
    'state_value','direction_value','raw_boundary_ratio','tau', ...
    'reconstructed_candidate_alpha','rank','is_global_limiter'});

if isempty(candidateAlpha)
    minimumValue = NaN; medianValue = NaN; p95Value = NaN;
    maximumValue = NaN; rawMinimum = NaN; rawMedian = NaN;
    rawP95 = NaN; rawMaximum = NaN;
    within2 = 0; within10 = 0; within100 = 0;
else
    minimumValue = min(candidateAlpha);
    medianValue = median(candidateAlpha);
    p95Value = percentile95(candidateAlpha);
    maximumValue = max(candidateAlpha);
    rawMinimum = min(rawRatio);
    rawMedian = median(rawRatio);
    rawP95 = percentile95(rawRatio);
    rawMaximum = max(rawRatio);
    within2 = nnz(rawRatio<=2*rawMinimum);
    within10 = nnz(rawRatio<=10*rawMinimum);
    within100 = nnz(rawRatio<=100*rawMinimum);
end
scale = max([1,abs(reconstructedAlpha),abs(officialStep.alpha)]);
record = empty_candidate_summary();
record.chain_id = char(chain.diagnostic_chain_id);
record.strategy = char(chain.step_strategy);
record.iteration = iteration;
record.step_kind = char(stepKind);
record.candidate_count = n;
record.minimum_candidate_alpha = minimumValue;
record.median_candidate_alpha = medianValue;
record.p95_candidate_alpha = p95Value;
record.maximum_candidate_alpha = maximumValue;
record.minimum_raw_boundary_ratio = rawMinimum;
record.median_raw_boundary_ratio = rawMedian;
record.p95_raw_boundary_ratio = rawP95;
record.maximum_raw_boundary_ratio = rawMaximum;
record.within_2x_minimum_count = within2;
record.within_10x_minimum_count = within10;
record.within_100x_minimum_count = within100;
record.concentration_basis = 'raw_boundary_ratio';
record.reconstructed_global_alpha = reconstructedAlpha;
record.official_candidate_alpha = officialStep.alpha;
record.alpha_closure_scaled_error = ...
    abs(reconstructedAlpha-officialStep.alpha)/scale;
record.negative_direction_count = nnz(direction<0);
record.global_limiter_count = nnz(isLimiter);
record.limiter_traceable = n>0 && nnz(isLimiter)==1 && ...
    record.alpha_closure_scaled_error<=tolerance;
end

