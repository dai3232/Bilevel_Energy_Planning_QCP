function passed = scale_source_counts_closed(rows,primalGroups,state)
passed = true;
for quantity = ["objective_gradient","a_transpose_y", ...
        "g_transpose_z","r_dual"]
    selected = rows(rows.scope=="primal_variable" & ...
        rows.quantity==quantity,:);
    passed = passed && sum(selected.count)==numel(primalGroups);
end
passed = passed && rows.count(rows.group_name=="equality_multiplier")== ...
    numel(state.y);
passed = passed && rows.count(rows.group_name=="inequality_multiplier" & ...
    rows.quantity=="z")==numel(state.z) && ...
    rows.count(rows.group_name=="inequality_multiplier" & ...
    rows.quantity=="delta_z")==numel(state.z) && ...
    rows.count(rows.group_name=="slack" & rows.quantity=="l")== ...
        numel(state.l) && ...
    rows.count(rows.group_name=="slack" & rows.quantity=="delta_l")== ...
        numel(state.l);
end

function passed = residual_group_counts_closed( ...
        rows,equalities,inequalities,snapshot)
equalityGroups = unique(string(equalities.constraint_name));
inequalityGroups = unique(string(inequalities.constraint_name));
equalityRows = rows(rows.scope=="equality_constraint" & ...
    rows.quantity=="r_eq",:);
passed = height(equalityRows)==numel(equalityGroups) && ...
    isequal(sort(equalityRows.group_name),sort(equalityGroups)) && ...
    sum(equalityRows.count)==numel(snapshot.r_eq);
if ~passed
    return
end
for quantity = ["r_ineq","r_comp","delta_l","delta_z"]
    selected = rows(rows.scope=="inequality_constraint" & ...
        rows.quantity==quantity,:);
    passed = passed && height(selected)==numel(inequalityGroups) && ...
        isequal(sort(selected.group_name),sort(inequalityGroups)) && ...
        sum(selected.count)==numel(snapshot.r_ineq);
    if ~passed
        return
    end
end
expectedHeight = numel(equalityGroups)+4*numel(inequalityGroups);
passed = passed && height(rows)==expectedHeight;
end

function exact = initial_chain_state_exact(left,right)
exact = isequal(left.xi,right.xi) && isequal(left.y,right.y) && ...
    isequal(left.l,right.l) && isequal(left.z,right.z);
end

