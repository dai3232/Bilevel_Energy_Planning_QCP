    'variable_group','objective_gradient','a_transpose_y', ...
    'g_transpose_z','reconstructed_r_dual','actual_r_dual', ...
    'closure_error','scaled_closure_error'});

qp5Mask = variables.day==0 & variables.hour==0 & ...
    string(variables.variable_name)=="QP5";
assert(nnz(qp5Mask)==1,"stageA4:a42d1:QP5Variable", ...
