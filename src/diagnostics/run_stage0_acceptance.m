function result = run_stage0_acceptance(runContext)
%RUN_STAGE0_ACCEPTANCE Execute every blocking stage-0 acceptance item.
% No optimization model, KKT system, recursive solver, or IPM iteration is
% assembled or executed here.

projectRoot = runContext.project_root;
acceptance = initialize_stage0_acceptance(projectRoot);
issues = new_stage0_issue_log();
data = [];
index = [];
hashes = table();
hashesMatch = false;
normalizedMatPath = fullfile(runContext.checkpoints_dir, ...
    'stage0_normalized_data.mat');

% Persist controlled empty evidence immediately; later writes contain only
% facts observed during this run.
write_table_csv_17g(runContext.acceptance_results_path,acceptance);
write_table_csv_17g(runContext.issue_log_path,issues);
dataAuditPath = fullfile(runContext.root,'数据审计.csv');
write_table_csv_17g(dataAuditPath,empty_data_audit());

%% S0-ENV-001 / S0-ENV-002
try
    environment = inspect_stage0_environment();
    environment = addvars(environment,repmat(string(runContext.run_id), ...
        height(environment),1),'Before',1,'NewVariableNames','run_id');
    write_table_csv_17g(runContext.environment_csv_path,environment);
    environmentStatus = string(environment.status);
    env1Mask = ismember(string(environment.check_id), ...
        ["MATLAB_RELEASE","SPARSE_MLDIVIDE","SPARSE_LDL"]);
    env2Mask = startsWith(string(environment.check_id),"PCT_");
    if all(environmentStatus(env1Mask)=="PASS")
        actual = strjoin(string(environment.actual(env1Mask)),'; ');
        acceptance = set_stage0_acceptance_result(acceptance,'S0-ENV-001', ...
            'PASS',actual,'R2024a and deterministic sparse checks passed', ...
            'environment.csv');
    else
        acceptance = set_stage0_acceptance_result(acceptance,'S0-ENV-001', ...
            'BLOCKED',strjoin(string(environment.details(env1Mask & ...
            environmentStatus~="PASS")),'; '),'environment unavailable', ...
            'environment.csv');
        issues = append_stage0_issue(issues,runContext,'S0-ENV-001', ...
            'MATLAB R2024a 或稀疏线性代数检查失败','见 environment.csv', ...
            '外部 MATLAB 环境不可用','恢复指定 MATLAB 环境后重新运行', ...
            'BLOCKED','environment.csv');
    end
    if all(environmentStatus(env2Mask)=="PASS")
        acceptance = set_stage0_acceptance_result(acceptance,'S0-ENV-002', ...
            'PASS',strjoin(string(environment.actual(env2Mask)),'; '), ...
            'installed + license test + real worker execution', ...
            'environment.csv');
    else
        acceptance = set_stage0_acceptance_result(acceptance,'S0-ENV-002', ...
            'BLOCKED',strjoin(string(environment.details(env2Mask & ...
            environmentStatus~="PASS")),'; '),'PCT unavailable', ...
            'environment.csv');
        issues = append_stage0_issue(issues,runContext,'S0-ENV-002', ...
            'Parallel Computing Toolbox 实测失败','见 environment.csv', ...
            '外部工具箱、许可证或 worker 环境不可用', ...
            '恢复工具箱与许可证后重新运行','BLOCKED','environment.csv');
    end
catch ME
    acceptance = set_stage0_acceptance_result(acceptance,'S0-ENV-001', ...
        'BLOCKED',ME.message,'environment inspection raised an error', ...
        'environment.csv');
    acceptance = set_stage0_acceptance_result(acceptance,'S0-ENV-002', ...
        'BLOCKED',ME.message,'environment inspection raised an error', ...
        'environment.csv');
    issues = append_stage0_issue(issues,runContext,'S0-ENV-001', ...
        '环境检查器无法完成',ME.message,'外部环境或检查器异常', ...
        '定位环境错误后重新运行','BLOCKED','environment.csv');
end

%% S0-DATA-001
try
    [hashes,hashesMatch] = verify_input_hashes(projectRoot);
    hashEvidence = hash_artifact_table(hashes,runContext.run_id);
    write_table_csv_17g(runContext.input_hashes_csv_path,hashEvidence);
    if hashesMatch
        actual = strjoin(string(hashEvidence.file_name)+"="+ ...
            string(hashEvidence.actual_sha256),'; ');
        acceptance = set_stage0_acceptance_result(acceptance,'S0-DATA-001', ...
            'PASS',actual,'actual SHA256 equals controlled manifest', ...
            'input_hashes.csv');
    else
        acceptance = set_stage0_acceptance_result(acceptance,'S0-DATA-001', ...
            'BLOCKED','one or more hashes differ','SHA256 equality failed', ...
            'input_hashes.csv');
        issues = append_stage0_issue(issues,runContext,'S0-DATA-001', ...
            '受控输入哈希不一致','见 input_hashes.csv','受控文件缺失或被修改', ...
            '停止并恢复受控输入，不得自动修改','BLOCKED','input_hashes.csv');
    end
catch ME
    acceptance = set_stage0_acceptance_result(acceptance,'S0-DATA-001', ...
        'BLOCKED',ME.message,'SHA256 verification raised an error', ...
        'input_hashes.csv');
    issues = append_stage0_issue(issues,runContext,'S0-DATA-001', ...
        '输入哈希无法校验',ME.message,'外部文件、权限或清单异常', ...
        '恢复受控输入与权限后重新运行','BLOCKED','input_hashes.csv');
end

%% S0-DATA-002 through S0-DATA-005
if hashesMatch
    try
        data = load_project_data(projectRoot);
        write_table_csv_17g(dataAuditPath,data.audit);
        rangeActual = sprintf('%s/%s %s; %s/%s %s', ...
            '基础参数.xlsx',data.sources.baseSheet,data.sources.baseEffectiveRange, ...
            '输入数据.xlsx',data.sources.timeSeriesSheet, ...
            data.sources.timeSeriesEffectiveRange);
        acceptance = set_stage0_acceptance_result(acceptance,'S0-DATA-002', ...
            'PASS',rangeActual,'sheet + semantic range + label/header audit', ...
            '数据审计.csv');
        countActual = sprintf('%d/%d/%d/%d/%d',data.meta.nThermal, ...
            data.meta.nHydro,data.meta.nWind,data.meta.nSolar,data.meta.nStorage);
        acceptance = set_stage0_acceptance_result(acceptance,'S0-DATA-003', ...
            'PASS',countActual,'equals 4/4/5/5/2','数据审计.csv');
        timeActual = sprintf('%dx%d; %g min; dt=%.17g h',data.meta.nDays, ...
            data.meta.nHours,data.meta.stepMinutes,data.meta.dtHours);
        acceptance = set_stage0_acceptance_result(acceptance,'S0-DATA-004', ...
            'PASS',timeActual,'equals 365x24; 60 min; dt=1 h','数据审计.csv');
        planActual = sprintf('base=%.17g MW; converted range=[%.17g, %.17g] MW', ...
            data.meta.planBaseMW,min(data.timeseries.planMW(:)), ...
            max(data.timeseries.planMW(:)));
        acceptance = set_stage0_acceptance_result(acceptance,'S0-DATA-005', ...
            'PASS',planActual,'Pplan = 10000 * Pplan_hat; range 2070..9860 MW', ...
            '数据审计.csv');
    catch ME
        dependentIds = ["S0-DATA-002","S0-DATA-003","S0-DATA-004","S0-DATA-005"];
        for id = dependentIds
            acceptance = set_stage0_acceptance_result(acceptance,id,'FAIL', ...
                ME.message,'label-driven data load failed','数据审计.csv');
        end
        issues = append_stage0_issue(issues,runContext,'S0-DATA-002', ...
            '标签式 Excel 读取或数据合同校验失败',ME.message, ...
            '读取器或受控数据合同实现问题','最小修复后重跑数据及索引回归', ...
            'OPEN','数据审计.csv');
    end
else
    dependentIds = ["S0-DATA-002","S0-DATA-003","S0-DATA-004","S0-DATA-005"];
    for id = dependentIds
        acceptance = set_stage0_acceptance_result(acceptance,id,'BLOCKED', ...
            'not run because input hash verification did not pass', ...
            'dependency blocked','input_hashes.csv');
    end
end

%% S0-IDX-001 and the MAT framework
indexPassed = false;
matPassed = false;
if ~isempty(data)
    try
        index = build_canonical_index_framework(data,1,1:24,[],runContext.run_id);
        indexAudit = validate_canonical_index_framework(index);
        write_table_csv_17g(fullfile(runContext.indices_dir,'variable_index.csv'), ...
            index.variable_index);
        write_table_csv_17g(fullfile(runContext.indices_dir,'constraint_index.csv'), ...
            index.constraint_index);
        write_table_csv_17g(fullfile(runContext.indices_dir,'block_index.csv'), ...
            index.block_index);
        write_table_csv_17g(fullfile(runContext.indices_dir,'fixed_zero_map.csv'), ...
            index.fixed_zero_map);
        write_table_csv_17g(fullfile(runContext.indices_dir,'permutation_map.csv'), ...
            index.permutation_map);
        write_table_csv_17g(fullfile(runContext.indices_dir,'index_audit.csv'), ...
            indexAudit);
        indexPassed = all(indexAudit.passed);
        if indexPassed
            indexActual = sprintf(['variables=%d; constraints=%d; fixed_zero=%d; ' ...
                'all gap/overlap/permutation audits PASS'],index.counts.variables, ...
                index.counts.constraints,index.counts.fixed_zero);
            acceptance = set_stage0_acceptance_result(acceptance,'S0-IDX-001', ...
                'PASS',indexActual,'canonical framework audit', ...
                'indices/index_audit.csv');
        else
            error('stage0:index:AuditFailed','One or more index audits failed.');
        end

        artifactData = sanitize_data_for_artifact(data);
        save_mat_artifact(normalizedMatPath,'data',artifactData,'index',index);
        matSha = compute_sha256_file(normalizedMatPath);
        checkpoint = checkpoint_artifact_table(runContext,index,hashes, ...
            normalizedMatPath,matSha);
        write_table_csv_17g(runContext.checkpoint_manifest_path,checkpoint);
        matPassed = isfile(normalizedMatPath) && strlength(matSha)==64;
    catch ME
        if string(acceptance.status(string(acceptance.test_id)=="S0-IDX-001")) ~= "PASS"
            acceptance = set_stage0_acceptance_result(acceptance,'S0-IDX-001', ...
                'FAIL',ME.message,'index framework generation/audit failed', ...
                'indices/index_audit.csv');
        end
        issues = append_stage0_issue(issues,runContext,'S0-IDX-001', ...
            '索引、固定零映射或 MAT 工件生成失败',ME.message, ...
            '阶段0基础设施实现问题','修复后重跑索引与工件回归', ...
            'OPEN','indices');
    end
else
    acceptance = set_stage0_acceptance_result(acceptance,'S0-IDX-001', ...
        'BLOCKED','not run because normalized data is unavailable', ...
        'dependency blocked','数据审计.csv');
end

%% S0-ART-001
duplicateGuard = duplicate_run_guard_passes(runContext);
artifactPassed = duplicateGuard && matPassed && ...
    isfile(runContext.run_manifest_path) && isfile(runContext.acceptance_results_path);
if artifactPassed
    acceptance = set_stage0_acceptance_result(acceptance,'S0-ART-001', ...
        'PASS',sprintf('run_id=%s; duplicate guard=PASS; JSON/CSV/MAT present', ...
        runContext.run_id),'explicit duplicate run_id rejected without overwrite', ...
        'run_manifest.json; checkpoints/checkpoint_manifest.csv');
else
    acceptance = set_stage0_acceptance_result(acceptance,'S0-ART-001', ...
        'FAIL',sprintf('duplicate_guard=%d; mat=%d',duplicateGuard,matPassed), ...
        'artifact infrastructure incomplete','run_manifest.json');
    issues = append_stage0_issue(issues,runContext,'S0-ART-001', ...
        '不可覆盖 run 或 CSV/MAT/JSON 工件框架不完整','见验收实际值', ...
        '阶段0工件基础设施问题','修复后重跑工件集成测试', ...
        'OPEN','run_manifest.json');
end

% Persist all facts needed by the report smoke test.
write_table_csv_17g(runContext.acceptance_results_path,acceptance);
write_table_csv_17g(runContext.issue_log_path,issues);

%% S0-RPT-001: render a disposable report package from this run's real facts.
try
    smoke_report_generation(runContext);
    acceptance = set_stage0_acceptance_result(acceptance,'S0-RPT-001', ...
        'PASS','three Chinese DOCX packages generated and structurally validated', ...
        'real current-run evidence clone; no optimization values fabricated', ...
        ['reports/阶段0_环境数据与基础设施验收报告.docx; ' ...
        'reports/阶段0_问题修复与验收报告.docx']);
catch ME
    acceptance = set_stage0_acceptance_result(acceptance,'S0-RPT-001', ...
        'FAIL',ME.message,'DOCX smoke test failed','reports');
    issues = append_stage0_issue(issues,runContext,'S0-RPT-001', ...
        '中文 Word 报告烟雾测试失败',ME.message,'报告基础设施实现问题', ...
        '修复并重跑报告集成测试','OPEN','reports');
end

write_table_csv_17g(runContext.acceptance_results_path,acceptance);
write_table_csv_17g(runContext.issue_log_path,issues);

terminalStatus = aggregate_stage_status(acceptance);
hashObject = hash_manifest_object(hashes);
reportRelativePaths = struct( ...
    'environment_data','reports/阶段0_环境数据与基础设施验收报告.docx', ...
    'issue_acceptance','reports/阶段0_问题修复与验收报告.docx', ...
    'run_summary',sprintf('reports/运行_%s_结果摘要.docx',runContext.run_id));
updates = struct('input_hashes',hashObject, ...
    'index_contract_version','1.0-stage0-framework', ...
    'normalized_data_artifact','checkpoints/stage0_normalized_data.mat', ...
    'reports',reportRelativePaths, ...
    'blocking_acceptance_total',sum(acceptance.blocking), ...
    'blocking_acceptance_pass',sum(acceptance.blocking & ...
    string(acceptance.status)=="PASS"));
finalize_run_manifest(runContext,terminalStatus,updates);

% Generate the final immutable reports once, now that acceptance and the
% terminal manifest are both authoritative.
reportPaths = generate_stage0_reports(runContext);
reportNames = fieldnames(reportPaths);
for k = 1:numel(reportNames)
    [valid,validation] = validate_docx_package(reportPaths.(reportNames{k}));
    if ~valid
        error('stage0:report:FinalValidationFailed','%s', ...
            strjoin(validation.errors,'; '));
    end
end

result = struct('run_id',string(runContext.run_id), ...
    'status',string(terminalStatus),'run_context',runContext, ...
    'acceptance',acceptance,'issues',issues,'reports',reportPaths, ...
    'index_passed',indexPassed,'mat_passed',matPassed);
end

function artifact = hash_artifact_table(hashes,runId)
n = height(hashes);
artifact = table(repmat(string(runId),n,1),string(hashes.fileName), ...
    "inputs/raw/"+string(hashes.fileName),double(hashes.expectedBytes), ...
    double(hashes.actualBytes),string(hashes.expectedSHA256), ...
    string(hashes.actualSHA256),string(hashes.status), ...
    repmat(string(datetime('now','TimeZone','Asia/Shanghai', ...
    'Format','yyyy-MM-dd''T''HH:mm:ssXXX')),n,1), ...
    'VariableNames',{'run_id','file_name','relative_path','expected_bytes', ...
    'actual_bytes','expected_sha256','actual_sha256','status','checked_at'});
end

function tableValue = empty_data_audit()
names = {'checkId','item','sourceFile','sheet','sectionLabel','locator', ...
    'expectedShape','actualShape','headerRow','dataStartRow','dataEndRow', ...
    'minValue','maxValue','status','details','unit'};
types = [repmat({'string'},1,8),repmat({'double'},1,5), ...
    repmat({'string'},1,3)];
tableValue = table('Size',[0,numel(names)],'VariableTypes',types, ...
    'VariableNames',names);
end

function sanitized = sanitize_data_for_artifact(data)
sanitized = data;
sanitized.projectRoot = ".";
sanitized.sources.baseFile = "inputs/raw/基础参数.xlsx";
sanitized.sources.timeSeriesFile = "inputs/raw/输入数据.xlsx";
if ismember('filePath',sanitized.hashes.Properties.VariableNames)
    sanitized.hashes.filePath = "inputs/raw/"+string(sanitized.hashes.fileName);
end
end

function checkpoint = checkpoint_artifact_table(runContext,index,hashes,pathValue,sha)
hashText = string(jsonencode(hash_manifest_object(hashes)));
checkpoint = table(string(runContext.run_id),string(runContext.stage_id), ...
    "none",0,"1.0",hashText,string(index.version),"NOT_APPLICABLE", ...
    "checkpoints/"+string(extractAfter(string(pathValue), ...
    string(runContext.checkpoints_dir)+filesep)), ...
    string(sha),string(datetime('now','TimeZone','Asia/Shanghai', ...
    'Format','yyyy-MM-dd''T''HH:mm:ssXXX')), ...
    'VariableNames',{'run_id','stage_id','solve_pass','iteration', ...
    'model_contract_version','input_hashes','index_contract_version', ...
    'solver_version','path','sha256','created_at'});
end

function value = hash_manifest_object(hashes)
value = struct();
if isempty(hashes)
    return
end
for k = 1:height(hashes)
    name = string(hashes.fileName(k));
    if name == "基础参数.xlsx"
        field = 'base_parameters';
    elseif name == "输入数据.xlsx"
        field = 'timeseries';
    else
        field = matlab.lang.makeValidName(char(name));
    end
    value.(field) = char(string(hashes.actualSHA256(k)));
end
end

function passed = duplicate_run_guard_passes(runContext)
passed = false;
try
    create_run_context(runContext.project_root,runContext.stage_id, ...
        'RunId',runContext.run_id);
catch ME
    passed = strcmp(ME.identifier,'stage0:artifacts:RunExists');
end
end

function smoke_report_generation(runContext)
smokeRoot = tempname;
mkdir(smokeRoot);
cleanup = onCleanup(@() remove_smoke_root(smokeRoot)); %#ok<NASGU>
copyfile(runContext.run_manifest_path,fullfile(smokeRoot,'run_manifest.json'));
copyfile(runContext.environment_csv_path,fullfile(smokeRoot,'environment.csv'));
copyfile(runContext.input_hashes_csv_path,fullfile(smokeRoot,'input_hashes.csv'));
copyfile(fullfile(runContext.root,'数据审计.csv'),fullfile(smokeRoot,'数据审计.csv'));
mkdir(fullfile(smokeRoot,'acceptance'));
copyfile(runContext.acceptance_results_path, ...
    fullfile(smokeRoot,'acceptance','acceptance_results.csv'));
mkdir(fullfile(smokeRoot,'issues'));
copyfile(runContext.issue_log_path,fullfile(smokeRoot,'issues','issue_log.csv'));
copyfile(runContext.indices_dir,fullfile(smokeRoot,'indices'));
smokeContext = struct('root',smokeRoot,'project_root',runContext.project_root);
paths = generate_stage0_reports(smokeContext);
names = fieldnames(paths);
for k = 1:numel(names)
    [valid,details] = validate_docx_package(paths.(names{k}));
    if ~valid
        error('stage0:report:SmokeValidationFailed','%s', ...
            strjoin(details.errors,'; '));
    end
end
end

function remove_smoke_root(pathValue)
if isfolder(pathValue)
    rmdir(pathValue,'s');
end
end
