function result = run_stage_a4_single_iteration(data,index,config)
%RUN_STAGE_A4_SINGLE_ITERATION Execute exactly one A4 primal-dual update.
%
% This milestone entry is deliberately not a complete IPM loop and does
% not create a run directory.  The recursive direction is computed first;
% the complete sparse KKT direction is computed afterwards for audit only.

arguments
    data (1,1) struct
    index (1,1) struct
    config (1,1) struct
end

assert(string(config.stage_id)=="stage_A4" && ...
    string(config.status)=="READY", ...
    "stageA4:singleIteration:StageStatus", ...
    "A4-1 requires stage_A4 / READY.");
assert(config.fraction_to_boundary==0.9995 && ...
    config.initialization.centering_sigma==0.1, ...
    "stageA4:singleIteration:FrozenStepParameters", ...
    "A4-1 requires sigma=0.1 and tau=0.9995 from solver.yaml.");

totalTimer = tic;
stateBefore = initialize_stage_a4_state(data,index,config);
linearizationBefore = build_stage_a4_linearization( ...
    stateBefore,data,index,config);

recursiveTimer = tic;
recursive = solve_stage_a_multiday_recursive_direction( ...
    linearizationBefore, ...
    AssemblyTolerance=config.tolerances.symmetry_relative, ...
    SymmetryTolerance=config.tolerances.symmetry_relative);
timing.recursive_seconds = toc(recursiveTimer);

directTimer = tic;
direct = solve_stage_a_multiday_full_kkt_direction(linearizationBefore);
timing.full_kkt_audit_seconds = toc(directTimer);

audit = verify_stage_a_multiday_direction_equivalence( ...
    direct,recursive,linearizationBefore, ...
    DirectionRelative=config.tolerances.direction_relative_2norm, ...
    RecursiveResidual= ...
        config.tolerances.recursive_full_kkt_relative_residual, ...
    FullResidualPreferred=config.tolerances.direct_preferred, ...
    FullResidualMaximum=config.tolerances.direct_maximum);

primalStep = compute_fraction_to_boundary_step( ...
    linearizationBefore.l,recursive.components.l, ...
    config.fraction_to_boundary);
dualStep = compute_fraction_to_boundary_step( ...
    linearizationBefore.z,recursive.components.z, ...
    config.fraction_to_boundary);

stateAfter = update_primal_dual_state( ...
    linearizationBefore.state,recursive.components, ...
    primalStep.alpha,dualStep.alpha);
stateAfter.iteration_index = linearizationBefore.state.iteration_index+1;
stateAfter.state_revision = linearizationBefore.state.state_revision+1;
linearizationAfter = build_stage_a4_linearization( ...
    stateAfter,data,index,config);

before = residual_snapshot( ...
    linearizationBefore,config.initialization.centering_sigma);
after = residual_snapshot( ...
    linearizationAfter,config.initialization.centering_sigma);
closure = audit_linear_update(linearizationBefore,linearizationAfter, ...
    recursive.components,primalStep.alpha,dualStep.alpha);

physicalBefore = recover_stage_a_physical_arrays( ...
    linearizationBefore.state.xi,recursive.components.xi,index,data);
physicalAfter = recover_stage_a_physical_arrays( ...
    linearizationAfter.state.xi,recursive.components.xi,index,data);
fixedZero = struct( ...
    "count",physicalAfter.fixed_zero_audit.count, ...
    "values_exact_zero_before", ...
        physicalBefore.fixed_zero_audit.values_exact_zero, ...
    "values_exact_zero_after", ...
        physicalAfter.fixed_zero_audit.values_exact_zero, ...
    "directions_exact_zero", ...
        physicalAfter.fixed_zero_audit.directions_exact_zero, ...
    "maximum_absolute_value_after", ...
        physicalAfter.fixed_zero_audit.maximum_absolute_value, ...
    "maximum_absolute_direction", ...
        physicalAfter.fixed_zero_audit.maximum_absolute_direction);
soc = audit_formal_soc_links(index,config);
permutation = recursive.partition.permutation;
permutationAudit = struct( ...
    "dimension",permutation.dimension, ...
    "is_bijection",permutation.is_bijection, ...
    "is_nonidentity",permutation.is_nonidentity, ...
    "forward_inverse_composition_exact", ...
        permutation.forward_inverse_composition_exact, ...
    "inverse_forward_composition_exact", ...
        permutation.inverse_forward_composition_exact);

allStatesFinite = all(isfinite([linearizationAfter.state.xi; ...
    linearizationAfter.state.y;linearizationAfter.state.l; ...
    linearizationAfter.state.z]));
identitySeparated = linearizationBefore.identity~=linearizationAfter.identity;
fixedZeroPassed = fixedZero.count==config.expected_fixed_zero_count && ...
    fixedZero.values_exact_zero_before && ...
    fixedZero.values_exact_zero_after && ...
    fixedZero.directions_exact_zero && ...
    fixedZero.maximum_absolute_value_after==0 && ...
    fixedZero.maximum_absolute_direction==0;
stepPassed = primalStep.alpha>0 && primalStep.alpha<=1 && ...
    dualStep.alpha>0 && dualStep.alpha<=1 && ...
    min(linearizationAfter.l)>0 && min(linearizationAfter.z)>0;
closurePassed = closure.slack_residual_scaled<=256*eps && ...
    closure.equality_linear_update_relative_error<=256*eps && ...
    closure.dual_linear_update_relative_error<=256*eps && ...
    closure.slack_linear_update_relative_error<=2048*eps && ...
    closure.equality_contraction_relative_error<=256*eps && ...
    closure.dual_contraction_relative_error<=256*eps && ...
    closure.slack_state_consistency_inf<=16*eps && ...
    after.complementarity_gap>0 && isfinite(after.complementarity_gap);
structurePassed = soc.passed && permutationAudit.dimension==4340 && ...
    permutationAudit.is_bijection && permutationAudit.is_nonidentity && ...
    permutationAudit.forward_inverse_composition_exact && ...
    permutationAudit.inverse_forward_composition_exact && ...
    closure.model_matrices_unchanged && identitySeparated;
directionPassed = audit.direction_relative_error<= ...
    config.tolerances.direction_relative_2norm && ...
    audit.recursive_kkt_relative_residual<= ...
    config.tolerances.recursive_full_kkt_relative_residual && ...
    audit.full_kkt_relative_residual<= ...
    config.tolerances.direct_maximum && ...
    audit.passed.full_residual_hard && ...
    audit.passed.no_full_direction_fallback;

checks = struct( ...
    "direction_equivalence",directionPassed, ...
    "positive_fraction_to_boundary",stepPassed, ...
    "updated_state_finite",allStatesFinite, ...
    "linear_update_closure",closurePassed, ...
    "formal_soc_and_permutation",structurePassed, ...
    "fixed_zero_exact",fixedZeroPassed, ...
    "recursive_no_full_direction_fallback", ...
        recursive.no_full_direction_fallback && ...
        ~recursive.full_direction_consumed);
checkValues = struct2cell(checks);
allPassed = all(cellfun(@(value)isequal(value,true),checkValues));
if ~allPassed
    failedNames = string(fieldnames(checks));
    failedNames = failedNames(~cellfun( ...
        @(value)isequal(value,true),checkValues));
    error("stageA4:singleIteration:ClosureFailed", ...
        "A4-1 single-iteration checks failed: %s.", ...
        strjoin(failedNames,", "));
end

timing.total_seconds = toc(totalTimer);
result = struct();
result.stage_id = "stage_A4";
result.stage_status = "READY";
result.milestone = "A4-1_single_primal_dual_iteration";
result.milestone_status = "PASS";
result.config = config;
result.state_before = linearizationBefore.state;
result.state_after = linearizationAfter.state;
result.linearization_before = linearizationBefore;
result.linearization_after = linearizationAfter;
result.recursive = recursive;
result.direct_audit = direct;
result.direction_audit = audit;
result.primal_step = primalStep;
result.dual_step = dualStep;
result.residuals = struct("before",before,"after",after, ...
    "closure",closure);
result.fixed_zero = fixedZero;
result.soc = soc;
result.permutation = permutationAudit;
result.checks = checks;
result.all_pass = allPassed;
result.timing = timing;
result.execution = struct( ...
    "newton_direction_count",1, ...
    "state_update_count",1, ...
    "full_kkt_audit_count",1, ...
    "recursive_direction_is_official",true, ...
    "full_kkt_direction_consumed_by_recursive",false, ...
    "full_ipm_executed",false, ...
    "optimization_executed",false, ...
    "parallel_executed",false, ...
    "formal_a4_run_created",false, ...
    "stage_b_entered",false);
end

function snapshot = residual_snapshot(lin,sigma)
inequalityFunction = lin.G*lin.state.xi+lin.constraints.ineq_offset;
physicalViolation = max(max(inequalityFunction,0));
gap = mean(lin.l.*lin.z);
raw = lin.l.'*lin.z;
snapshot = struct( ...
    "equality_inf",norm(lin.r_eq,inf), ...
    "slack_equality_inf",norm(lin.r_ineq,inf), ...
    "physical_inequality_violation",physicalViolation, ...
    "physical_inequality_scale",max(1,norm(inequalityFunction,inf)), ...
    "dual_inf",norm(lin.r_dual,inf), ...
    "complementarity_gap",gap, ...
    "raw_complementarity",raw, ...
    "mu",lin.mu, ...
    "minimum_l",min(lin.l), ...
    "minimum_z",min(lin.z));
assert(isfinite(gap) && gap>0 && isfinite(raw) && raw>0 && ...
    lin.mu==sigma*gap, ...
    "stageA4:singleIteration:ComplementarityDefinition", ...
    "The normalized/raw complementarity or mu definition is inconsistent.");
end

function closure = audit_linear_update(before,after,direction,alphaP,alphaD)
assert(nnz(after.H-before.H)==0 && nnz(after.A-before.A)==0 && ...
    nnz(after.G-before.G)==0 && ...
    isequal(after.objective.gradient,before.objective.gradient), ...
    "stageA4:singleIteration:ModelChanged", ...
    "The model matrices or objective gradient changed during one update.");

expectedEq = before.r_eq+alphaP*(before.A*direction.xi);
expectedSlack = before.r_ineq+alphaP*( ...
    before.G*direction.xi+direction.l);
expectedDual = before.r_dual+alphaD*( ...
    before.A.'*direction.y+before.G.'*direction.z);
eqScale = max([1,norm(after.r_eq,inf),norm(expectedEq,inf)]);
slackScale = max([1,norm(after.r_ineq,inf),norm(expectedSlack,inf)]);
dualScale = max([1,norm(after.r_dual,inf),norm(expectedDual,inf)]);
constraintScale = max(1,norm(after.G*after.state.xi+ ...
    after.constraints.ineq_offset,inf)+norm(after.state.l,inf));

impliedSlack = -(after.G*after.state.xi+ ...
    after.constraints.ineq_offset);
consistencyDifference = after.state.l-impliedSlack-after.r_ineq;
closure = struct( ...
    "equality_linear_update_relative_error", ...
        norm(after.r_eq-expectedEq,inf)/eqScale, ...
    "slack_linear_update_relative_error", ...
        norm(after.r_ineq-expectedSlack,inf)/slackScale, ...
    "dual_linear_update_relative_error", ...
        norm(after.r_dual-expectedDual,inf)/dualScale, ...
    "equality_contraction_relative_error", ...
        norm(after.r_eq-(1-alphaP)*before.r_eq,inf)/eqScale, ...
    "dual_contraction_relative_error", ...
        norm(after.r_dual-(1-alphaD)*before.r_dual,inf)/dualScale, ...
    "slack_residual_scaled",norm(after.r_ineq,inf)/constraintScale, ...
    "slack_state_consistency_inf",norm(consistencyDifference,inf), ...
    "model_matrices_unchanged",true);
end

function audit = audit_formal_soc_links(index,config)
links = index.soc_link_map;
variables = index.variable_index;
initialCount = 0;
terminalCount = 0;
crossDayCount = 0;
for day = config.days
    for storage = 1:2
        first = links(links.day==day & links.hour==1 & ...
            links.storage_id==storage,:);
        initialCount = initialCount+height(first);
        if height(first)~=1 || ~isnan(first.predecessor_hour) || ...
                first.predecessor_soc_global_index~=0 || ...
                first.initial_energy_fraction~=0.5
            crossDayCount = crossDayCount+1;
        end
        last = links(links.day==day & links.hour==24 & ...
            links.storage_id==storage & links.terminal_equality,:);
        terminalCount = terminalCount+height(last);
        if height(last)~=1 || last.terminal_energy_fraction~=0.5
            crossDayCount = crossDayCount+1;
        end
    end
    internal = links(links.day==day & links.hour>1,:);
    predecessors = variables(internal.predecessor_soc_global_index,:);
    crossDayCount = crossDayCount+nnz(predecessors.day~=day | ...
        predecessors.hour~=internal.hour-1);
end
audit = struct( ...
    "initial_half_energy_link_count",initialCount, ...
    "terminal_half_energy_link_count",terminalCount, ...
    "cross_day_or_nonadjacent_link_count",crossDayCount, ...
    "passed",initialCount==14 && terminalCount==14 && ...
        crossDayCount==0);
end
