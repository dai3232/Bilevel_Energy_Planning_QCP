function audit = verify_final(outputDirectory,expectedManifest)
paths = evidence_paths(outputDirectory);
assert(isfile(paths.manifest), ...
    "stageA4:r1:EvidenceManifestMissing", ...
    "Final R1 evidence manifest is missing.");
actualManifest = readtable(paths.manifest,Delimiter=',', ...
    ReadVariableNames=true,TextType="string", ...
    VariableNamingRule="preserve");
schemaExact = isequal(string(actualManifest.Properties.VariableNames), ...
    ["artifact_path","sha256"]);
rowsExact = schemaExact && ...
    isequal(string(actualManifest.artifact_path), ...
        expectedManifest.artifact_path) && ...
    isequal(string(actualManifest.sha256),expectedManifest.sha256);
hashesExact = rowsExact;
if rowsExact
    for k = 1:height(actualManifest)
        pathValue = fullfile(outputDirectory, ...
            actualManifest.artifact_path(k));
        hashesExact = hashesExact && isfile(pathValue) && ...
            compute_sha256_file(pathValue)==actualManifest.sha256(k);
    end
end
matSchema = false;
if isfile(paths.mat)
    variablesInfo = whos("-file",paths.mat);
    variables = string({variablesInfo.name});
    matSchema = all(ismember( ...
        ["r1Result","r1TestSummary","r1TestInventory","r1TestResults"], ...
        variables));
end
audit = struct( ...
    "schema_exact",schemaExact, ...
    "rows_exact",rowsExact, ...
    "hashes_exact",hashesExact, ...
    "mat_schema_exact",matSchema, ...
    "all_pass",schemaExact && rowsExact && hashesExact && matSchema);
assert(audit.all_pass,"stageA4:r1:EvidenceFinalAudit", ...
    "Final R1 stable-v2 evidence failed its hash or schema audit.");
end

function write_text(pathValue,textValue)
fileId = fopen(pathValue,"wb","n","UTF-8");
assert(fileId>=0,"stageA4:r1:EvidenceTextOpen", ...
    "Unable to open R1 evidence text file: %s",pathValue);
cleanup = onCleanup(@()close_file_if_open(fileId));
fprintf(fileId,"%s",textValue);
status = fclose(fileId);
clear cleanup
assert(status==0,"stageA4:r1:EvidenceTextClose", ...
    "Unable to close R1 evidence text file: %s",pathValue);
end

function close_file_if_open(fileId)
if any(fopen("all")==fileId)
    fclose(fileId);
end
end

function cleanup_staging(stagingDirectory,outputDirectory)
if ~isfolder(stagingDirectory) || isfolder(outputDirectory)
    return
end
fixtureParent = canonical_folder(fileparts(outputDirectory));
stagingCanonical = canonical_candidate(stagingDirectory);
requiredPrefix = lower(fixtureParent+filesep);
assert(startsWith(lower(stagingCanonical),requiredPrefix) && ...
    endsWith(stagingCanonical,".building"), ...
    "stageA4:r1:UnsafeStagingCleanup", ...
    "Refusing to clean an unsafe R1 staging path: %s",stagingCanonical);
rmdir(stagingCanonical,"s");
end

function value = leaf(pathValue)
[~,name,extension] = fileparts(pathValue);
value = string(name)+string(extension);
end

function value = canonical_folder(pathValue)
assert(isfolder(pathValue),"stageA4:r1:CanonicalFolder", ...
    "Expected an existing folder: %s",pathValue);
value = string(char(java.io.File(char(pathValue)).getCanonicalPath()));
end

function value = canonical_candidate(pathValue)
value = string(char(java.io.File(char(pathValue)).getCanonicalPath()));
end
