audit = struct( ...
    "dimension",permutation.dimension, ...
    "is_bijection",permutation.is_bijection, ...
    "is_nonidentity",permutation.is_nonidentity, ...
    "forward_inverse_composition_exact", ...
        permutation.forward_inverse_composition_exact, ...
    "inverse_forward_composition_exact", ...
        permutation.inverse_forward_composition_exact);
end

function audit = audit_formal_soc_boundaries(index,config,before,after, ...
        direction,alphaPrimal,relativeToleranceMultiplier)
links = index.soc_link_map;
variables = index.variable_index;
equalities = index.constraint_index( ...
    string(index.constraint_index.constraint_type)=="equality",:);
initialCount = 0;
terminalCount = 0;
crossDayCount = 0;
initialCoefficientFailures = 0;
terminalCoefficientFailures = 0;
initialRows = zeros(0,1);
terminalRows = zeros(0,1);
terminalLocalScales = zeros(0,1);
for day = config.days
    dayPosition = find(before.maps.days==day,1,"first");
    for storage = 1:2
        first = links(links.day==day & links.hour==1 & ...
            links.storage_id==storage,:);
        initialCount = initialCount+height(first);
        firstRow = find(equalities.day==day & equalities.hour==1 & ...
            string(equalities.constraint_name)=="soc_dynamics" & ...
            equalities.asset_id==storage);
        qEnergy = before.maps.q_day(12+storage,dayPosition);
        if isscalar(firstRow)
            initialRows(end+1,1) = firstRow; %#ok<AGROW>
        end
        if height(first)~=1 || ~isscalar(firstRow) || ...
                ~isnan(first.predecessor_hour) || ...
                first.predecessor_soc_global_index~=0 || ...
                first.initial_energy_fraction~=0.5 || ...
                before.A(firstRow,qEnergy)~=-0.5 || ...
                before.A(firstRow,first.current_soc_global_index)~=1
            initialCoefficientFailures = initialCoefficientFailures+1;
        end
        last = links(links.day==day & links.hour==24 & ...
            links.storage_id==storage & links.terminal_equality,:);
        terminalCount = terminalCount+height(last);
        lastRow = find(equalities.day==day & equalities.hour==24 & ...
            string(equalities.constraint_name)=="terminal_soc" & ...
            equalities.asset_id==storage);
        if isscalar(lastRow)
            terminalRows(end+1,1) = lastRow; %#ok<AGROW>
            terminalLocalScales(end+1,1) = max([1, ...
                abs(after.state.xi(last.current_soc_global_index)), ...
                0.5*abs(after.state.xi(qEnergy))]); %#ok<AGROW>
        end
        if height(last)~=1 || ~isscalar(lastRow) || ...
                last.terminal_energy_fraction~=0.5 || ...
                before.A(lastRow,qEnergy)~=-0.5 || ...
                before.A(lastRow,last.current_soc_global_index)~=1
            terminalCoefficientFailures = terminalCoefficientFailures+1;
        end
    end
    internal = links(links.day==day & links.hour>1,:);
    predecessors = variables(internal.predecessor_soc_global_index,:);
    crossDayCount = crossDayCount+nnz(predecessors.day~=day | ...
        predecessors.hour~=internal.hour-1);
end
expectedInitial = before.r_eq(initialRows)+alphaPrimal*( ...
    before.A(initialRows,:)*direction.xi);
initialScale = max([1,norm(after.r_eq(initialRows),inf), ...
    norm(expectedInitial,inf)]);
initialUpdateError = norm(after.r_eq(initialRows)-expectedInitial,inf)/ ...
    initialScale;
expectedTerminal = before.r_eq(terminalRows)+alphaPrimal*( ...
    before.A(terminalRows,:)*direction.xi);
terminalScale = max([1,norm(after.r_eq(terminalRows),inf), ...
    norm(expectedTerminal,inf)]);
terminalUpdateError = norm(after.r_eq(terminalRows)-expectedTerminal,inf)/ ...
    terminalScale;
terminalScaledResiduals = abs(after.r_eq(terminalRows))./ ...
    terminalLocalScales;
terminalMaximumScaledResidual = max(terminalScaledResiduals);
audit = struct( ...
    "day_ids",config.days, ...
    "initial_half_energy_link_count",initialCount, ...
    "terminal_half_energy_link_count",terminalCount, ...
    "cross_day_or_nonadjacent_link_count",crossDayCount, ...
    "initial_boundary_coefficient_failure_count", ...
        initialCoefficientFailures, ...
    "terminal_boundary_coefficient_failure_count", ...
        terminalCoefficientFailures, ...
    "initial_residual_inf_before",norm(before.r_eq(initialRows),inf), ...
    "initial_residual_inf_after",norm(after.r_eq(initialRows),inf), ...
    "initial_linear_update_relative_error",initialUpdateError, ...
    "terminal_residual_inf_before",norm(before.r_eq(terminalRows),inf), ...
    "terminal_residual_inf_after",norm(after.r_eq(terminalRows),inf), ...
    "terminal_maximum_locally_scaled_residual_after", ...
        terminalMaximumScaledResidual, ...
    "relative_tolerance_multiplier",relativeToleranceMultiplier, ...
    "terminal_linear_update_relative_error",terminalUpdateError, ...
    "passed",initialCount==14 && terminalCount==14 && ...
        crossDayCount==0 && initialCoefficientFailures==0 && ...
        terminalCoefficientFailures==0 && ...
        initialUpdateError<=relativeToleranceMultiplier*eps && ...
        terminalUpdateError<=relativeToleranceMultiplier*eps && ...
        terminalMaximumScaledResidual<= ...
            max(512,relativeToleranceMultiplier)*eps);
end

function audit = audit_qp5_bounds(index,before,after,direction)
variables = index.variable_index;
qMask = variables.day==0 & variables.hour==0 & ...
    string(variables.variable_name)=="QP5";
assert(nnz(qMask)==1,"stageA4:iteration:QP5Variable", ...
    "The global QP5 variable must occur exactly once.");
qIndex = variables.global_index_start(qMask);
qPosition = find(before.maps.q_global==qIndex,1,"first");
assert(isscalar(qPosition),"stageA4:iteration:QP5Map", ...
    "The global QP5 variable is missing from maps.q_global.");

inequalities = index.constraint_index( ...
    string(index.constraint_index.constraint_type)=="inequality",:);
lower = find(string(inequalities.constraint_id)=="INEQ-Q-LOWER-QP5");
upper = find(string(inequalities.constraint_id)=="INEQ-Q-UPPER-QP5");
assert(isscalar(lower) && isscalar(upper), ...
    "stageA4:iteration:QP5BoundRows", ...
    "QP5 must have exactly one semantic lower and upper inequality row.");

lowerAudit = make_qp5_side(inequalities,lower,before,after,direction);
upperAudit = make_qp5_side(inequalities,upper,before,after,direction);
lowerBound = before.capacity_parameters.lower(qPosition);
upperBound = before.capacity_parameters.upper(qPosition);
audit = struct( ...
    "capacity_name","QP5", ...
    "capacity_position",qPosition, ...
    "capacity_variable_global_index",qIndex, ...
    "capacity_lower_bound",lowerBound, ...
    "capacity_upper_bound",upperBound, ...
    "capacity_value_before",before.state.xi(qIndex), ...
    "capacity_value_after",after.state.xi(qIndex), ...
    "capacity_direction",direction.xi(qIndex), ...
    "distance_to_lower_before",before.state.xi(qIndex)-lowerBound, ...
    "distance_to_lower_after",after.state.xi(qIndex)-lowerBound, ...
    "distance_to_upper_before",upperBound-before.state.xi(qIndex), ...
    "distance_to_upper_after",upperBound-after.state.xi(qIndex), ...
    "lower",lowerAudit,"upper",upperAudit, ...
    "passed",lowerAudit.constraint_id=="INEQ-Q-LOWER-QP5" && ...
        upperAudit.constraint_id=="INEQ-Q-UPPER-QP5" && ...
        lowerAudit.physical_function_before== ...
            lowerBound-before.state.xi(qIndex) && ...
        lowerAudit.physical_function_after== ...
            lowerBound-after.state.xi(qIndex) && ...
        upperAudit.physical_function_before== ...
            before.state.xi(qIndex)-upperBound && ...
        upperAudit.physical_function_after== ...
            after.state.xi(qIndex)-upperBound && ...
        lowerAudit.physical_function_direction== -direction.xi(qIndex) && ...
        upperAudit.physical_function_direction== direction.xi(qIndex) && ...
        all(isfinite([before.state.xi(qIndex),after.state.xi(qIndex), ...
            direction.xi(qIndex)])));
end

function side = make_qp5_side(inequalities,row,before,after,direction)
slackRatio = boundary_ratio(before.l(row),direction.l(row));
multiplierRatio = boundary_ratio(before.z(row),direction.z(row));
side = struct( ...
    "constraint_id",string(inequalities.constraint_id(row)), ...
    "inequality_index",row, ...
    "constraint_global_row",inequalities.global_row(row), ...
    "physical_function_before",before.constraints.ineq(row), ...
    "physical_function_after",after.constraints.ineq(row), ...
    "physical_function_direction",before.G(row,:)*direction.xi, ...
    "slack_before",before.l(row), ...
    "slack_after",after.l(row), ...
    "slack_direction",direction.l(row), ...
    "slack_boundary_ratio",slackRatio, ...
    "multiplier_before",before.z(row), ...
    "multiplier_after",after.z(row), ...
    "multiplier_direction",direction.z(row), ...
    "multiplier_boundary_ratio",multiplierRatio);
end

function ratio = boundary_ratio(value,direction)
if direction<0
    ratio = -value/direction;
else
    ratio = Inf;
end
end

function step = annotate_limiting_inequality(step,index)
inequalities = index.constraint_index( ...
    string(index.constraint_index.constraint_type)=="inequality",:);
if step.limiting_index==0
    step.limiting_constraint_id = "";
    step.limiting_constraint_global_row = 0;
    step.limiting_day = NaN;
    step.limiting_hour = NaN;
    step.limiting_asset_type = "";
    step.limiting_asset_id = NaN;
    return
end
row = inequalities(step.limiting_index,:);
step.limiting_constraint_id = string(row.constraint_id);
step.limiting_constraint_global_row = row.global_row;
step.limiting_day = row.day;
step.limiting_hour = row.hour;
step.limiting_asset_type = string(row.asset_type);
step.limiting_asset_id = row.asset_id;
end
