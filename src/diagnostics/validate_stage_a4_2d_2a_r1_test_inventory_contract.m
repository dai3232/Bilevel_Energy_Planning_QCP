function audit = validate_stage_a4_2d_2a_r1_test_inventory_contract( ...
        actual,projectRoot)
%VALIDATE_STAGE_A4_2D_2A_R1_TEST_INVENTORY_CONTRACT Fix the 18 R1 tests.

arguments
    actual table
    projectRoot (1,1) string
end
relativePath = "tests/stage_A4_2D_2A_R1_expected_test_inventory.csv";
expectedPath = fullfile(projectRoot,strrep(relativePath,'/',filesep));
assert(isfile(expectedPath), ...
    "stageA4:tests:R1ExpectedInventoryMissing", ...
    "The controlled R1 inventory is missing: %s",expectedPath);
expected = readtable(expectedPath,Delimiter=',', ...
    ReadVariableNames=true,TextType="string", ...
    VariableNamingRule="preserve");
required = ["test_order","test_name","source_file"];
assert(all(ismember(required,string(expected.Properties.VariableNames))) && ...
    all(ismember(required,string(actual.Properties.VariableNames))), ...
    "stageA4:tests:R1InventorySchema", ...
    "R1 inventories require order, name and source.");
expected = expected(:,cellstr(required));
actual = actual(:,cellstr(required));
expected.test_name = strip(string(expected.test_name));
actual.test_name = strip(string(actual.test_name));
expected.source_file = replace(strip(string(expected.source_file)),'\','/');
actual.source_file = replace(strip(string(actual.source_file)),'\','/');
expectedOrder = double(expected.test_order);
actualOrder = double(actual.test_order);
allowedSource = ...
    "tests/integration/test_stage_a4_objective_unitization_stable_rerun.m";
assert(height(expected)==18 && isequal(expectedOrder,(1:18).') && ...
    numel(unique(expected.test_name))==18 && ...
    all(expected.source_file==allowedSource), ...
    "stageA4:tests:R1ExpectedInventoryInvalid", ...
    "The controlled expected R1 inventory is invalid.");
assert(height(actual)==18 && isequal(actualOrder,(1:18).') && ...
    numel(unique(actual.test_name))==18 && ...
    all(actual.source_file==allowedSource), ...
    "stageA4:tests:R1ActualInventoryInvalid", ...
    "The discovered R1 inventory is invalid.");
assert(isequal(actual.test_name,expected.test_name) && ...
    isequal(actual.source_file,expected.source_file), ...
    "stageA4:tests:R1ExpectedInventoryMismatch", ...
    "Discovered R1 tests differ from the controlled inventory.");
audit = struct( ...
    "matches_expected",true, ...
    "expected_count",18, ...
    "actual_count",height(actual), ...
    "expected_inventory_relative_path",relativePath, ...
    "expected_inventory_sha256", ...
        lower(string(compute_sha256_file(expectedPath))), ...
    "test_names_unique",true, ...
    "order_matches",true, ...
    "source_files_match",true);
end
