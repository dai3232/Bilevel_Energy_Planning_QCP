function audit = verify_current_input_hashes(projectRoot,frozen)
[current,allMatch] = verify_input_hashes(projectRoot);
currentNames = string(current.fileName);
frozenNames = string(frozen.file_name);
[sortedCurrent,currentOrder] = sort(currentNames);
[sortedFrozen,frozenOrder] = sort(frozenNames);
namesExact = isequal(sortedCurrent,sortedFrozen);
hashesExact = namesExact && isequal( ...
    lower(string(current.actualSHA256(currentOrder))), ...
    lower(string(frozen.actual_sha256(frozenOrder))));
audit = struct( ...
    "manifest_pass",allMatch, ...
    "names_exact",namesExact, ...
    "hashes_exact",hashesExact, ...
    "all_pass",allMatch && namesExact && hashesExact);
end

function tableValue = make_refinement_table(recursive)
dayCount = numel(recursive.daily_thomas);
objectType = [repmat("day_chain",dayCount,1);"global_core"];
dayId = [reshape([recursive.daily_responses.day_id],[],1);0];
selectedPass = zeros(dayCount+1,1);
passesAttempted = zeros(dayCount+1,1);
initialResidual = zeros(dayCount+1,1);
finalResidual = zeros(dayCount+1,1);
reductionRatio = zeros(dayCount+1,1);
stopReason = strings(dayCount+1,1);
targetMet = false(dayCount+1,1);
additionalFactorizationCount = zeros(dayCount+1,1);
for d = 1:dayCount
    item = recursive.daily_thomas(d).diagnostics.residual_refinement;
    selectedPass(d) = item.selected_pass;
    passesAttempted(d) = item.passes_attempted;
    initialResidual(d) = item.initial_maximum_column_relative;
    finalResidual(d) = item.final_maximum_column_relative;
    reductionRatio(d) = item.residual_reduction_ratio;
    stopReason(d) = item.stop_reason;
    targetMet(d) = item.target_met;
    additionalFactorizationCount(d) = ...
        item.additional_factorization_count;
end
item = recursive.core.diagnostics.residual_refinement;
selectedPass(end) = item.selected_pass;
passesAttempted(end) = item.passes_attempted;
initialResidual(end) = item.initial_maximum_column_relative;
finalResidual(end) = item.final_maximum_column_relative;
reductionRatio(end) = item.residual_reduction_ratio;
stopReason(end) = item.stop_reason;
targetMet(end) = item.target_met;
additionalFactorizationCount(end) = ...
    item.additional_factorization_count;
tableValue = table(objectType,dayId,selectedPass,passesAttempted, ...
    initialResidual,finalResidual,reductionRatio,stopReason,targetMet, ...
    additionalFactorizationCount, ...
    'VariableNames',{'object_type','day_id','selected_pass', ...
    'passes_attempted','initial_maximum_column_relative', ...
    'final_maximum_column_relative','residual_reduction_ratio', ...
    'stop_reason','target_met','additional_factorization_count'});
end

function audit = audit_factorized_operators(recursive)
factorCount = 0;
reconstructionExact = true;
available = true;
rawMismatchMaximum = 0;
rawResidualRebuildExact = true;
retainedContextExact = true;
factorizedSolveResiduals = zeros(0,1);
factorizedSolveAuditCount = 0;
for d = 1:numel(recursive.daily_thomas)
    factors = recursive.daily_thomas(d).factors;
    schurBlocks = recursive.daily_thomas(d).schur_blocks;
    factorCount = factorCount+numel(factors);
    for k = 1:numel(factors)
        factor = factors{k};
        reconstructedPermuted = factor.L*factor.D*factor.L.';
        permutationMatrix = sparse(factor.permutation, ...
            1:factor.dimension,1,factor.dimension,factor.dimension);
        reconstructed = permutationMatrix*reconstructedPermuted* ...
            permutationMatrix.';
        reconstructionExact = reconstructionExact && ...
            isequal(reconstructed,factor.factorized_operator);
        retainedContextExact = retainedContextExact && ...
            isequal(factor.matrix,schurBlocks{k});
        available = available && ...
            factor.actual_factorized_operator_available_for_residual_audit;
        rawMismatchMaximum = max(rawMismatchMaximum, ...
            factor.raw_to_factorized_operator_relative);
    end
    refinement = recursive.daily_thomas(d).diagnostics. ...
        residual_refinement;
    rhs = [recursive.partition.day(d).r_v, ...
        recursive.partition.day(d).B];
    rawMetric = maximum_column_relative( ...
        rhs-recursive.partition.day(d).M* ...
        recursive.daily_thomas(d).stacked_solution,rhs);
    rawResidualRebuildExact = rawResidualRebuildExact && ...
        rawMetric==refinement.final_maximum_column_relative;
    reconstructionExact = reconstructionExact && ...
        refinement.residual_operator_exact_original && ...
        refinement.factor_context_unchanged;
    [values,count,availableValues] = collect_factorized_residuals( ...
        recursive.daily_thomas(d).diagnostics.multiplier_solve);
    factorizedSolveResiduals = [ ...
        factorizedSolveResiduals;values]; %#ok<AGROW>
    factorizedSolveAuditCount = factorizedSolveAuditCount+count;
    available = available && availableValues;
    [values,count,availableValues] = collect_factorized_residuals( ...
        recursive.daily_thomas(d).diagnostics.back_solve);
    factorizedSolveResiduals = [ ...
        factorizedSolveResiduals;values]; %#ok<AGROW>
    factorizedSolveAuditCount = factorizedSolveAuditCount+count;
    available = available && availableValues;
    [values,count,availableValues] = collect_factorized_residuals( ...
        refinement.correction_solve);
    factorizedSolveResiduals = [ ...
        factorizedSolveResiduals;values]; %#ok<AGROW>
    factorizedSolveAuditCount = factorizedSolveAuditCount+count;
    available = available && availableValues;
end
factor = recursive.core.factor;
factorCount = factorCount+1;
reconstructedPermuted = factor.L*factor.D*factor.L.';
permutationMatrix = sparse(factor.permutation, ...
    1:factor.dimension,1,factor.dimension,factor.dimension);
reconstructed = permutationMatrix*reconstructedPermuted* ...
    permutationMatrix.';
reconstructionExact = reconstructionExact && ...
    isequal(reconstructed,factor.factorized_operator) && ...
    isequal(recursive.core.matrix,factor.matrix) && ...
    recursive.core.diagnostics.residual_refinement. ...
        residual_operator_exact_original && ...
    recursive.core.diagnostics.residual_refinement. ...
        factor_context_unchanged;
retainedContextExact = retainedContextExact && ...
    isequal(recursive.core.matrix,factor.matrix);
available = available && ...
    factor.actual_factorized_operator_available_for_residual_audit;
rawMismatchMaximum = max(rawMismatchMaximum, ...
    factor.raw_to_factorized_operator_relative);
coreRawMetric = maximum_column_relative( ...
    recursive.core.rhs-recursive.core.matrix* ...
    recursive.core.solution,recursive.core.rhs);
rawResidualRebuildExact = rawResidualRebuildExact && ...
    coreRawMetric==recursive.core.diagnostics.residual_refinement. ...
        final_maximum_column_relative;
[values,count,availableValues] = collect_factorized_residuals( ...
    recursive.core.diagnostics.solve);
factorizedSolveResiduals = [ ...
    factorizedSolveResiduals;values];
factorizedSolveAuditCount = factorizedSolveAuditCount+count;
available = available && availableValues;
