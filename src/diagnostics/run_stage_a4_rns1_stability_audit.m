function [values,count,allAvailable] = collect_factorized_residuals(value)
values = zeros(0,1);
count = 0;
allAvailable = true;
if isempty(value)
    return
end
if iscell(value)
    for k = 1:numel(value)
        [childValues,childCount,childAvailable] = ...
            collect_factorized_residuals(value{k});
        values = [values;childValues]; %#ok<AGROW>
        count = count+childCount;
        allAvailable = allAvailable && childAvailable;
    end
    return
end
if ~isstruct(value)
    return
end
for itemIndex = 1:numel(value)
    item = value(itemIndex);
    if isfield(item,"factorized_operator_relative_residual")
        values = [values; ...
            item.factorized_operator_relative_residual]; %#ok<AGROW>
        count = count+1;
        allAvailable = allAvailable && ...
            isfield(item,"actual_factorized_operator_available") && ...
            item.actual_factorized_operator_available && ...
            isfield(item,"actual_factorized_operator_used_for_audit") && ...
            item.actual_factorized_operator_used_for_audit;
    end
    fields = string(fieldnames(item));
    for fieldIndex = 1:numel(fields)
        fieldName = fields(fieldIndex);
        if fieldName=="factorized_operator_relative_residual" || ...
                fieldName=="actual_factorized_operator_available" || ...
                fieldName=="actual_factorized_operator_used_for_audit"
            continue
        end
        child = item.(fieldName);
        if isstruct(child) || iscell(child)
            [childValues,childCount,childAvailable] = ...
                collect_factorized_residuals(child);
            values = [values;childValues]; %#ok<AGROW>
            count = count+childCount;
            allAvailable = allAvailable && childAvailable;
        end
    end
end
end

function value = maximum_column_relative(residual,rhs)
rhsNorm = full(sqrt(sum(abs(rhs).^2,1)));
residualNorm = full(sqrt(sum(abs(residual).^2,1)));
value = full(max(residualNorm./max(1,rhsNorm)));
end

function audit = audit_determinism(first,second)
directionExact = isequal(first.direction,second.direction);
refinementExact = isequaln(first.residual_refinement, ...
    second.residual_refinement);
responseExact = isequaln(first.daily_responses,second.daily_responses);
coreExact = isequaln(first.core.solution,second.core.solution);
audit = struct( ...
    "direction_exact",directionExact, ...
    "refinement_diagnostics_exact",refinementExact, ...
    "daily_responses_exact",responseExact, ...
    "core_solution_exact",coreExact, ...
    "all_pass",directionExact && refinementExact && ...
        responseExact && coreExact);
end

