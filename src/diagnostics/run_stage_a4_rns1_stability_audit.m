function result = run_stage_a4_rns1_stability_audit(projectRoot)
%RUN_STAGE_A4_RNS1_STABILITY_AUDIT Audit the frozen round-19 stress input.
%
% This milestone performs one recursive Newton direction twice for
% determinism.  It does not update the primal-dual state, rerun D2A, create
% a formal run, or consume the complete-KKT direction as a fallback.

arguments
    projectRoot (1,1) string
end

fixtureRoot = fullfile(projectRoot,"tests","fixtures", ...
    "stage_A4_RNS_1_authority_v1");
metadataPath = fullfile(fixtureRoot, ...
    "stage_A4_RNS_1_round19_authority_v1.metadata.json");
manifestPath = fullfile(fixtureRoot, ...
    "stage_A4_RNS_1_authority_artifact_sha256.csv");
matPath = fullfile(fixtureRoot, ...
    "stage_A4_RNS_1_round19_authority_v1.mat");
require_file(metadataPath);
require_file(manifestPath);
require_file(matPath);

metadata = jsondecode(fileread(metadataPath));
artifactAudit = verify_artifact_hashes( ...
    fixtureRoot,manifestPath,metadata);
fixture = load(matPath);
config = load_stage_a4_configuration(projectRoot);
assert(string(config.stage_id)=="stage_A4" && ...
    string(config.status)=="READY" && ...
    config.symmetry_relative_tolerance==1e-12 && ...
    config.direction_relative_tolerance==1e-10 && ...
    config.recursive_full_kkt_residual_tolerance==1e-10, ...
    "stageA4:rns1:FrozenGovernance", ...
    "A4-RNS-1 requires stage_A4 / READY and frozen 1e-12/1e-10 audits.");

stateFingerprint = compute_stage_a4_rns1_fingerprint( ...
    fixture.stateAfterRound18,"state");
linearizationFingerprint = compute_stage_a4_rns1_fingerprint( ...
    fixture.linearizationRound19,"linearization");
inputHashAudit = verify_current_input_hashes( ...
    projectRoot,fixture.inputHashes);
authorityAudit = verify_authority_failure_evidence( ...
    projectRoot,fixture,metadata,matPath);
fixtureAudit = struct( ...
    "source_commit",string(metadata.source_commit), ...
    "source_commit_exact",string(metadata.source_commit)== ...
        "58b2b3645b79c71460ff0de1a03033c319829cd6", ...
    "state_fingerprint",stateFingerprint, ...
    "state_fingerprint_exact",stateFingerprint== ...
        string(metadata.state_after_round18_fingerprint), ...
    "linearization_fingerprint",linearizationFingerprint, ...
    "linearization_fingerprint_exact",linearizationFingerprint== ...
        string(metadata.linearization_round19_fingerprint), ...
    "artifact_hashes",artifactAudit, ...
    "input_hashes",inputHashAudit, ...
    "authority_failure",authorityAudit, ...
    "day17_authority_symmetry_relative", ...
        fixture.day17Response.diagnostics.symmetry_relative, ...
    "authority_loose_direction_relative_error", ...
        fixture.looseAudit.direction_relative_error, ...
    "authority_loose_recursive_kkt_relative_residual", ...
        fixture.looseAudit.recursive_kkt_relative_residual);
fixtureAudit.all_pass = fixtureAudit.source_commit_exact && ...
    fixtureAudit.state_fingerprint_exact && ...
    fixtureAudit.linearization_fingerprint_exact && ...
    artifactAudit.all_pass && inputHashAudit.all_pass && ...
    authorityAudit.all_pass;

try
    first = solve_stage_a_multiday_recursive_direction( ...
        fixture.linearizationRound19, ...
        AssemblyTolerance=1e-12,SymmetryTolerance=1e-12, ...
        ResidualRefinementMaxPasses=3);
    second = solve_stage_a_multiday_recursive_direction( ...
        fixture.linearizationRound19, ...
        AssemblyTolerance=1e-12,SymmetryTolerance=1e-12, ...
        ResidualRefinementMaxPasses=3);
catch cause
    result = failed_result(fixtureAudit,cause);
    return
end

fullAudit = fixture.fullAuditRound19;
directionAudit = verify_stage_a_multiday_direction_equivalence( ...
    fullAudit,first,fixture.linearizationRound19, ...
    DirectionRelative=1e-10,RecursiveResidual=1e-10, ...
    FullResidualPreferred=1e-12,FullResidualMaximum=1e-10);
directResidual = directionAudit.full_kkt_relative_residual;
dayIds = reshape([first.daily_responses.day_id],[],1);
day17Position = find(dayIds==17);
assert(isscalar(day17Position), ...
    "stageA4:rns1:StableDay17", ...
    "The stable result must contain exactly one day-17 response.");
day17 = first.daily_responses(day17Position);
refinementTable = make_refinement_table(first);
operatorAudit = audit_factorized_operators(first);
determinism = audit_determinism(first,second);

componentErrors = directionAudit.component_relative_errors;
componentVector = [componentErrors.xi;componentErrors.y; ...
    componentErrors.l;componentErrors.z];
recursiveResidual = directionAudit.recursive_kkt_relative_residual;
engineeringTarget = 5e-11;
if recursiveResidual<=engineeringTarget
    marginStatus = "SUFFICIENT";
else
    marginStatus = "INSUFFICIENT";
end
blocking = struct( ...
    "day17_response_symmetry", ...
        day17.diagnostics.symmetry_relative<=1e-12, ...
    "overall_direction", ...
        directionAudit.direction_relative_error<=1e-10, ...
    "component_directions",all(componentVector<=1e-10), ...
    "recursive_full_kkt_residual",recursiveResidual<=1e-10, ...
    "direct_full_kkt_residual",directResidual<=1e-10, ...
    "fixed_zero_exact",directionAudit.passed.fixed_zero_exact, ...
    "day_sort_invariant",directionAudit.passed.day_sort_invariant, ...
    "no_full_direction_fallback", ...
        first.no_full_direction_fallback && ...
        ~first.full_direction_consumed, ...
    "positive_input_state", ...
        min(fixture.linearizationRound19.l)>0 && ...
        min(fixture.linearizationRound19.z)>0, ...
    "operator_identity_audit",operatorAudit.all_pass, ...
    "bounded_refinement", ...
        all(refinementTable.selected_pass<=3) && ...
        all(refinementTable.passes_attempted<=3) && ...
        all(refinementTable.additional_factorization_count==0), ...
    "deterministic_repeat",determinism.all_pass, ...
    "fixture_evidence",fixtureAudit.all_pass);
blockingValues = struct2cell(blocking);
allBlockingPass = all(cellfun(@(value)isequal(value,true), ...
    blockingValues));

result = struct();
result.stage_id = "stage_A4";
result.stage_status = "READY";
result.milestone = "A4-RNS-1";
if allBlockingPass
    result.milestone_status = "PASS";
else
    result.milestone_status = "FAIL_RETRYABLE";
end
result.fixture = fixtureAudit;
result.first = first;
result.second = second;
result.refinement = refinementTable;
result.operator_audit = operatorAudit;
result.determinism = determinism;
result.direction_audit = directionAudit;
result.actual = struct( ...
    "day17_response_symmetry_relative", ...
        day17.diagnostics.symmetry_relative, ...
    "direction_relative_error", ...
        directionAudit.direction_relative_error, ...
    "xi_relative_error",componentErrors.xi, ...
    "y_relative_error",componentErrors.y, ...
    "l_relative_error",componentErrors.l, ...
    "z_relative_error",componentErrors.z, ...
    "recursive_full_kkt_relative_residual",recursiveResidual, ...
    "direct_full_kkt_relative_residual",directResidual, ...
    "minimum_l",min(fixture.linearizationRound19.l), ...
    "minimum_z",min(fixture.linearizationRound19.z), ...
    "engineering_target",engineeringTarget, ...
    "numerical_margin_status",marginStatus, ...
    "engineering_margin_is_nonblocking",true);
result.blocking = blocking;
result.all_blocking_pass = allBlockingPass;
result.failure = struct("present",false,"identifier","","message","");
if fixtureAudit.authority_failure.all_pass
    result.d2a_original_status_preserved = "FAIL_RETRYABLE";
else
    result.d2a_original_status_preserved = "UNVERIFIED";
end
result.stage_a4_pass_claimed = false;
result.execution = struct( ...
    "recursive_newton_direction_count",2, ...
    "state_update_count",0, ...
    "full_kkt_direction_solve_count",0, ...
    "full_kkt_audit_matvec_count",2, ...
    "complete_kkt_direction_fallback_used",false, ...
    "hundred_round_run_executed",false, ...
    "full_ipm_executed",false, ...
    "optimization_executed",false, ...
    "parallel_executed",false, ...
    "formal_a4_run_created",false, ...
    "d2a_rerun_executed",false, ...
    "stage_b_entered",false);
end

function audit = verify_artifact_hashes(root,manifestPath,metadata)
expectedManifestSha256 = ...
    "391517925f12d5654d2cc46de187e8807420e5761a8bba203e2010686e076fd5";
manifestSha256 = compute_sha256_file(manifestPath);
manifest = readtable(manifestPath,Delimiter=',', ...
    ReadVariableNames=true,TextType="string", ...
    VariableNamingRule="preserve");
required = ["artifact_path","sha256"];
assert(all(ismember(required,string(manifest.Properties.VariableNames))), ...
    "stageA4:rns1:ArtifactManifestSchema", ...
    "The RNS authority artifact manifest schema is invalid.");
expectedNames = [ ...
    "stage_A4_RNS_1_round19_authority_v1.mat"
    "stage_A4_RNS_1_authority_round_prefix.csv"
    "stage_A4_RNS_1_authority_input_hashes.csv"
    "stage_A4_RNS_1_authority_generation_command.txt"
    "stage_A4_RNS_1_round19_authority_v1.metadata.json"];
names = string(manifest.artifact_path);
namesAreUnique = numel(unique(names))==numel(names);
namesExact = isequal(names,expectedNames);
safeLeafNames = all(arrayfun(@is_safe_leaf,names));
hashShapeExact = all(~cellfun("isempty", ...
    regexp(cellstr(lower(string(manifest.sha256))), ...
    '^[0-9a-f]{64}$','once')));
actual = strings(height(manifest),1);
exists = false(height(manifest),1);
for k = 1:height(manifest)
    pathValue = fullfile(root,names(k));
    exists(k) = isfile(pathValue);
    if exists(k)
        actual(k) = compute_sha256_file(pathValue);
    end
end
expected = lower(string(manifest.sha256));
matches = exists & actual==expected;
metadataNames = [string(metadata.mat_file); ...
    string(metadata.prefix_file);string(metadata.input_hash_file); ...
    string(metadata.command_file);expectedNames(5)];
metadataHashes = lower([string(metadata.mat_sha256); ...
    string(metadata.prefix_sha256);string(metadata.input_hash_sha256); ...
    string(metadata.command_sha256);expected(5)]);
metadataCrossExact = isequal(metadataNames,expectedNames) && ...
    isequal(metadataHashes,expected);
audit = struct( ...
    "count",height(manifest), ...
    "manifest_sha256",manifestSha256, ...
    "manifest_root_exact",manifestSha256==expectedManifestSha256, ...
    "names_unique",namesAreUnique, ...
    "names_exact",namesExact, ...
    "safe_leaf_names",safeLeafNames, ...
    "hash_shape_exact",hashShapeExact, ...
    "metadata_cross_reference_exact",metadataCrossExact, ...
    "all_exist",all(exists), ...
    "all_match",all(matches), ...
    "actual_sha256",actual, ...
    "expected_sha256",expected, ...
    "all_pass",height(manifest)==5 && ...
        manifestSha256==expectedManifestSha256 && ...
        namesAreUnique && namesExact && safeLeafNames && ...
        hashShapeExact && metadataCrossExact && all(matches));
end

function value = is_safe_leaf(pathValue)
pathValue = string(pathValue);
[folder,name,extension] = fileparts(pathValue);
value = strlength(folder)==0 && ...
    pathValue==string(name)+string(extension) && ...
    ~contains(pathValue,["..","/","\"]) && strlength(pathValue)>0;
end

