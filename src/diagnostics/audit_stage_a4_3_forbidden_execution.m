function audit = audit_stage_a4_3_forbidden_execution( ...
        runResult,config,codeAudit,dependencyClosure)
%AUDIT_STAGE_A4_3_FORBIDDEN_EXECUTION Audit actual persisted route facts.

arguments
    runResult (1,1) struct
    config (1,1) struct
    codeAudit table
    dependencyClosure table
end
iterations = runResult.iteration_summary;
directions = runResult.direction_audit;
complete = height(iterations)==runResult.iteration_count && ...
    height(directions)==runResult.iteration_count && ...
    all(codeAudit.status=="PASS") && ...
    height(dependencyClosure)>0 && all(dependencyClosure.status=="PASS");
tracePresent = runResult.iteration_count>0;

check_id = [ ...
    "A43-RUNTIME-NO-COMMON-MIN"
    "A43-RUNTIME-FIXED-SIGMA"
    "A43-RUNTIME-NO-PREDICTOR-CORRECTOR"
    "A43-RUNTIME-NO-LINE-SEARCH"
    "A43-RUNTIME-NO-REGULARIZATION"
    "A43-RUNTIME-NO-AUTOMATIC-SYMMETRIZATION"
    "A43-RUNTIME-NO-PARALLEL"
    "A43-RUNTIME-NO-FULL-DIRECTION-FALLBACK"];
requirement = [ ...
    "all accepted xi/l/y/z updates use independent primal/dual steps"
    "every accepted iteration uses frozen sigma=0.1"
    "predictor-corrector is absent from runtime trace and closure"
    "line search is absent from runtime trace and closure"
    "regularization is absent from runtime trace and closure"
    "automatic symmetrization is absent from runtime trace and closure"
    "parallel execution is absent from runtime trace and closure"
    "recursive direction never consumes or falls back to complete KKT"];
used = [ ...
    any(iterations.common_step_used) || ...
        any(iterations.step_strategy~="independent") || ...
        config.a4_3.common_step_enabled
    any(iterations.dynamic_sigma_used) || ...
        any(iterations.centering_sigma~=0.1) || ...
        config.a4_3.dynamic_sigma_enabled
    any(iterations.predictor_corrector_used) || ...
        config.a4_3.predictor_corrector_enabled
    any(iterations.line_search_used) || config.a4_3.line_search_enabled
    any(iterations.regularization_used) || ...
        config.a4_3.regularization_enabled
    any(iterations.automatic_symmetrization_used) || ...
        config.a4_3.automatic_symmetrization_enabled
    any(iterations.parallel_used) || config.a4_3.parallel_mode~="off"
    any(iterations.full_kkt_direction_fallback_used) || ...
        any(~directions.no_full_direction_fallback) || ...
        any(~directions.full_kkt_audit_only) || ...
        config.a4_3.full_kkt_direction_fallback_enabled];
actual_value = compose("used=%d; accepted_iterations=%d", ...
    used,repmat(runResult.iteration_count,8,1));
evidence_path = repmat( ...
    "iterations/iteration_summary.csv; diagnostics/forbidden_code_audit.csv; diagnostics/dependency_closure_sha256.csv", ...
    8,1);
status = repmat("FAIL",8,1);
status(~used & complete & tracePresent) = "PASS";
status(~used & complete & ~tracePresent) = "NOT_RUN";
audit = table(check_id,requirement,actual_value,evidence_path,status);
assert(isequal(audit.check_id,check_id) && ...
    numel(unique(audit.check_id))==8, ...
    "stageA4:a43:RuntimeForbiddenIdentity", ...
    "The A4-3 runtime forbidden-factor audit identity changed.");
end
