function reportPaths = generate_stage_a3_reports(runContext,varargin)
%GENERATE_STAGE_A3_REPORTS Build three Chinese reports from persisted facts.

parser=inputParser; parser.FunctionName=mfilename;
addParameter(parser,'OutputDirectory',"",@is_text_scalar);
addParameter(parser,'FinalStatusCandidate',"",@is_text_scalar);
parse(parser,varargin{:});
assert(isstruct(runContext)&&isscalar(runContext)&&isfield(runContext,'root'), ...
    'stageA3:report:InvalidRunContext','runContext.root is required.');
runRoot=string(char(java.io.File(char(string(runContext.root))).getCanonicalPath()));
assert(isfolder(runRoot),'stageA3:report:MissingRunRoot','Run root is missing.');
facts=load_facts(runRoot); candidate=upper(strip(string( ...
    parser.Results.FinalStatusCandidate)));
if strlength(candidate)==0, candidate="PASS"; end
validate_facts(facts,candidate); facts.candidateStatus=candidate;
outputDirectory=strip(string(parser.Results.OutputDirectory));
if strlength(outputDirectory)==0, outputDirectory=fullfile(runRoot,'reports'); end
ensure_directory(outputDirectory);
reportPaths=struct( ...
    'model_report',fullfile(outputDirectory, ...
        '阶段A3_7日日响应汇总与方向等价报告.docx'), ...
    'issue_report',fullfile(outputDirectory,'阶段A3_问题修复与验收报告.docx'), ...
    'run_summary',fullfile(outputDirectory, ...
        "运行_"+safe_filename(facts.runId)+"_结果摘要.docx"));
targets=string(struct2cell(reportPaths)); assert_targets_absent(targets);
staging=string(tempname(tempdir)); mkdir(staging); guard=onCleanup(@()remove_tree(staging));
staged=[fullfile(staging,"model.docx");fullfile(staging,"issues.docx"); ...
    fullfile(staging,"summary.docx")];
metadata=struct("run_id",facts.runId,"stage_id",facts.stageId, ...
    "git_commit",facts.gitCommit,"manifest_status",facts.manifestStatus, ...
    "candidate_status",facts.candidateStatus);
write_stage_a3_docx(staged(1),'阶段A3_7日日响应汇总与方向等价报告', ...
    '第14—20日真实数据 · 7个独立正式日 · 单次 Newton 方向算法验收', ...
    metadata,build_model_blocks(facts));
write_stage_a3_docx(staged(2),'阶段A3_问题修复与验收报告', ...
    '六项阻断门禁、自动测试、问题证据与范围边界', ...
    metadata,build_issue_blocks(facts));
write_stage_a3_docx(staged(3),'阶段 A3 单次运行结果摘要', ...
    '7日日响应串行汇总证据（不构成优化、调度或经济结论）', ...
    metadata,build_summary_blocks(facts));
for k=1:numel(staged)
    [valid,details]=validate_docx_package(staged(k));
    assert(valid,'stageA3:report:InvalidDocxPackage','%s', ...
        strjoin(string(details.errors),'; '));
end
assert_targets_absent(targets);
names=fieldnames(reportPaths);
for k=1:numel(targets)
    [moved,message]=movefile(staged(k),targets(k));
    assert(moved,'stageA3:report:PublishFailed','%s',message);
    reportPaths.(names{k})=char(targets(k));
end
clear guard;
end

