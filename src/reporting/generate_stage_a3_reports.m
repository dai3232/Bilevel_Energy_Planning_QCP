function blocks=empty_blocks()
blocks=repmat(block_template(),0,1);
end
function value=block_template()
value=struct("type","","level",0,"title","","text","", ...
    "headers",strings(1,0),"rows",strings(0,0),"widths",zeros(1,0));
end
function block=heading_block(textValue,level)
block=block_template(); block.type="heading"; block.text=string(textValue);
block.level=level;
end
function block=paragraph_block(textValue)
block=block_template(); block.type="paragraph"; block.text=string(textValue);
end
function block=callout_block(titleText,textValue)
block=block_template(); block.type="callout"; block.title=string(titleText);
block.text=string(textValue);
end
function block=table_block(headers,rows,widths)
block=block_template(); block.type="table"; block.headers=string(headers);
block.rows=string(rows); block.widths=double(widths);
end
function block=selected_table_block(tableValue,columns,widths)
assert(all(ismember(columns,string(tableValue.Properties.VariableNames))), ...
    'stageA3:report:MissingColumn','Report evidence table is missing a column.');
rows=strings(height(tableValue),numel(columns));
for c=1:numel(columns)
    raw=tableValue.(columns(c));
    for r=1:height(tableValue), rows(r,c)=display_text(raw(r,:)); end
end
block=table_block(display_headers(columns),rows,widths);
end
function headers=display_headers(columns)
headers=replace(columns,"_"," ");
end
function value=matrix_dimension(matrix,name)
row=matrix(string(matrix.matrix_name)==string(name),:);
assert(height(row)==1,'stageA3:report:MatrixIdentity', ...
    'Missing or duplicate matrix evidence %s.',name);
value=string(row.rows)+"x"+string(row.columns);
end
function value=metric_value(tableValue,id)
row=tableValue(string(tableValue.metric_id)==string(id),:);
assert(height(row)==1,'stageA3:report:MetricIdentity','Missing metric %s.',id);
value=format_number(double(row.actual_value));
end
function value=residual_value(tableValue,route,dayId)
mask=string(tableValue.route)==string(route);
if isnan(dayId), mask=mask&isnan(double(tableValue.day_id)); ...
else, mask=mask&double(tableValue.day_id)==dayId; end
row=tableValue(mask,:);
assert(height(row)==1,'stageA3:report:ResidualIdentity', ...
    'Missing residual route %s.',route);
value=format_number(double(row.relative_residual_2norm));
end
function value=scope_text(facts)
value="实际启用：全局14维容量q、两个储能时长约束、一次容量投资目标与全局容量界；"+ ...
    "每日14维q_d及绑定、24小时自然变维块、日内SOC链和日末闭合。"+ ...
    "未启用：日用水、第二次火电、完整IPM、优化和并行。";
if isfield(facts.manifest,"enabled_components")
    value=value+" Manifest启用组件="+display_text(facts.manifest.enabled_components)+"。";
end
end
function pathValue=required(root,relative)
pathValue=fullfile(root,relative);
assert(isfile(pathValue),'stageA3:report:MissingArtifact', ...
    'Required persisted artifact is missing: %s',pathValue);
end
function value=read_json(pathValue)
try
    value=jsondecode(fileread(pathValue));
catch exception
    error('stageA3:report:InvalidJson','%s: %s',pathValue,exception.message);
end
end
function value=read_csv(pathValue)
try
    options=detectImportOptions(pathValue,'Encoding','UTF-8','Delimiter',',', ...
        'VariableNamingRule','preserve');
    options.VariableNamesLine=1; options.DataLines=[2 Inf];
    value=readtable(pathValue,options);
catch exception
    error('stageA3:report:InvalidCsv','%s: %s',pathValue,exception.message);
end
end
function value=required_manifest_text(manifest,name)
assert(isfield(manifest,name),'stageA3:report:ManifestField', ...
    'Manifest field %s is missing.',name);
value=string(manifest.(name));
assert(isscalar(value)&&strlength(strip(value))>0, ...
    'stageA3:report:ManifestField','Manifest field %s is invalid.',name);
end
function values=to_logical(raw)
if islogical(raw), values=raw; return; end
if isnumeric(raw), values=raw~=0; return; end
values=lower(strip(string(raw)))=="true"|strip(string(raw))=="1";
end
function textValue=display_text(value)
if iscell(value), value=value{1}; end
if isstring(value)||ischar(value)
    textValue=strjoin(string(value(:).'),", ");
elseif islogical(value)
    textValue=string(value);
elseif isnumeric(value)
    if isscalar(value), textValue=format_number(double(value)); ...
    else, textValue=string(mat2str(double(value))); end
else
    try
        textValue=string(jsonencode(value));
    catch
        textValue=string(value);
    end
end
end
function value=format_number(number)
if isnan(number), value="NaN"; elseif isinf(number), value=string(number); ...
else, value=compose("%.17g",number); end
end
function ensure_directory(pathValue)
if isfolder(pathValue), return; end
if isfile(pathValue), error('stageA3:report:PathConflict', ...
        'A file exists where reports/ is required: %s',pathValue); end
[created,message]=mkdir(pathValue);
assert(created,'stageA3:report:CreateDirectoryFailed','%s',message);
end
function assert_targets_absent(targets)
for target=targets.'
    if isfile(target)||isfolder(target)
        error('stageA3:report:ArtifactExists', ...
            'Refusing to overwrite existing report: %s',target);
    end
end
end
function name=safe_filename(value)
name=regexprep(string(value),'[^A-Za-z0-9._-]','_');
assert(strlength(name)>0,'stageA3:report:UnsafeFilename','Invalid run id.');
end
function remove_tree(pathValue)
if isfolder(pathValue), rmdir(pathValue,'s'); end
end
function tf=is_text_scalar(value)
tf=ischar(value)||(isstring(value)&&isscalar(value));
end
