function validate_facts(facts,candidate)
assert(facts.stageId=="stage_A3"&&facts.manifestStatus=="RUNNING", ...
    'stageA3:report:ManifestIdentity', ...
    'Reports require the matching RUNNING stage_A3 manifest.');
assert(candidate=="PASS",'stageA3:report:CandidateStatus', ...
    'Formal three-report generation requires PASS as the fact-derived candidate.');
blocking=to_logical(facts.environment.blocking);
assert(any(blocking)&&all(string(facts.environment.status(blocking))=="PASS"), ...
    'stageA3:report:EnvironmentEvidence', ...
    'Blocking environment evidence must be persisted PASS.');
assert(height(facts.inputHashes)==2&&all(string(facts.inputHashes.status)=="PASS")&& ...
    all(lower(string(facts.inputHashes.expectedSHA256))== ...
    lower(string(facts.inputHashes.actualSHA256))), ...
    'stageA3:report:InputHashEvidence', ...
    'Both controlled input SHA256 comparisons must be persisted PASS.');
expected=["SA3-MAT-001";"SA3-DAY-001";"SA3-CORE-001"; ...
    "SA3-EQ-001";"SA3-EQ-002";"SA3-SUM-001"];
acceptancePassed=height(facts.acceptance)==6&& ...
    isequal(string(facts.acceptance.test_id),expected)&& ...
    all(string(facts.acceptance.status)=="PASS");
if ~acceptancePassed
    error('stageA3:report:AcceptanceMismatch', ...
        'Expected six PASS rows; ids=%s; status=%s.', ...
        strjoin(string(facts.acceptance.test_id),','), ...
        strjoin(string(facts.acceptance.status),','));
end
assert(height(facts.issues)==0,'stageA3:report:UnresolvedIssues', ...
    'Formal PASS reports require an empty persisted issue_log.csv.');
assert(all_tests_pass(facts.a3Inventory,facts.a3Results,facts.a3Summary), ...
    'stageA3:report:A3Tests','Persisted A3 test evidence is inconsistent.');
assert(all_tests_pass(facts.a2Inventory,facts.a2Results,facts.a2Summary), ...
    'stageA3:report:A2Regression','Persisted A2 regression is inconsistent.');
assert(height(facts.a1Inventory)==37&& ...
    all_tests_pass(facts.a1Inventory,facts.a1Results,facts.a1Summary), ...
    'stageA3:report:A1Regression','All 37 A1 regression tests must pass.');
assert(height(facts.blocks)==168&&all(string(facts.blocks.status)=="PASS")&& ...
    height(facts.chains)==7&&all(string(facts.chains.status)=="PASS")&& ...
    height(facts.responses)==7&&all(string(facts.responses.status)=="PASS")&& ...
    height(facts.aggregation)==1&&string(facts.aggregation.status)=="PASS", ...
    'stageA3:report:DailyEvidence','Daily block/response evidence is invalid.');
assert(height(facts.soc)==350&&all(string(facts.soc.status)=="PASS"), ...
    'stageA3:report:SocEvidence','Seven-day SOC evidence is invalid.');
assert(all(double(facts.fixed.fixed_value)==0)&& ...
    all(double(facts.fixed.fixed_direction_value)==0)&& ...
    all(double(facts.fixedRecovery.recovered_value)==0)&& ...
    all(double(facts.fixedRecovery.recovered_direction)==0), ...
    'stageA3:report:FixedZeroEvidence','Fixed-zero evidence is invalid.');
assert(all(string(facts.codeScan.status)=="PASS")&& ...
    logical(facts.identity.all_identities_equal)&& ...
    logical(facts.identity.no_full_kkt_direction_fallback), ...
    'stageA3:report:ImplementationEvidence', ...
    'Code scan or shared-linearization identity evidence did not pass.');
assert(~logical(facts.manifest.parallel_executed)&& ...
    ~logical(facts.manifest.full_ipm_executed)&& ...
    ~logical(facts.manifest.optimization_executed)&& ...
    double(facts.manifest.newton_direction_count)==1&& ...
    logical(facts.manifest.a3_solver_executed), ...
    'stageA3:report:ScopeMismatch','Manifest execution scope is invalid.');
end

function passed=all_tests_pass(inventory,results,summary)
passed=height(inventory)==height(results)&&height(results)>0&& ...
    isequal(string(inventory.test_name),string(results.test_name))&& ...
    all(to_logical(results.passed))&&~any(to_logical(results.failed))&& ...
    ~any(to_logical(results.incomplete))&& ...
    double(summary.test_total)==height(results)&& ...
    double(summary.test_passed)==height(results)&& ...
    double(summary.test_failed)==0&&double(summary.test_incomplete)==0;
end

