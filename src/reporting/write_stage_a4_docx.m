function xml = style_xml( ...
        id,name,basedOn,sizeValue,color,bold,before,after,line)
base = "";
if strlength(basedOn)>0
    base = "<w:basedOn w:val="""+basedOn+"""/>";
end
boldXml = "";
if bold, boldXml="<w:b/><w:bCs/>"; end
xml = "<w:style w:type=""paragraph"" w:styleId="""+id+ ...
    """><w:name w:val="""+name+"""/>"+base+ ...
    "<w:qFormat/><w:pPr><w:spacing w:before="""+before+ ...
    """ w:after="""+after+""" w:line="""+line+ ...
    """ w:lineRule=""auto""/></w:pPr><w:rPr>"+ ...
    "<w:rFonts w:ascii=""Calibri"" w:hAnsi=""Calibri"" "+ ...
    "w:eastAsia=""Microsoft YaHei""/>"+boldXml+ ...
    "<w:color w:val="""+color+"""/><w:sz w:val="""+ ...
    sizeValue+"""/><w:szCs w:val="""+sizeValue+ ...
    """/></w:rPr></w:style>";
end

