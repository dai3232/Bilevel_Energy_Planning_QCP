    "</w:pPr><w:r><w:rPr><w:b/><w:bCs/></w:rPr>"+ ...
    "<w:t xml:space=""preserve"">"+xml_escape(label)+ ...
    "： </w:t></w:r><w:r><w:t xml:space=""preserve"">"+ ...
    xml_escape(value)+"</w:t></w:r></w:p>";
end

