function write_stage_a4_docx(outputPath,titleText,subtitleText,metadata,blocks)
%WRITE_STAGE_A4_DOCX Write a standard-business-brief A4 OOXML report.
% Design preset: standard_business_brief. Header: memo_masthead.

arguments
    outputPath (1,1) string
    titleText (1,1) string
    subtitleText (1,1) string
    metadata (1,1) struct
    blocks (:,1) struct
end
assert(~isfile(outputPath)&&~isfolder(outputPath), ...
    "stageA4:report:ArtifactExists","Refusing to overwrite %s.",outputPath);
requiredMetadata = ["run_id","stage_id","git_commit", ...
    "manifest_status","candidate_status"];
assert(all(isfield(metadata,cellstr(requiredMetadata))), ...
    "stageA4:report:MetadataSchema", ...
    "A4 report metadata is incomplete.");

root = string(tempname(tempdir)); mkdir(root);
guard = onCleanup(@()remove_tree(root));
mkdir(fullfile(root,'_rels')); mkdir(fullfile(root,'docProps'));
mkdir(fullfile(root,'word')); mkdir(fullfile(root,'word','_rels'));
write_utf8(fullfile(root,'[Content_Types].xml'),content_types_xml());
write_utf8(fullfile(root,'_rels','.rels'),root_relationships_xml());
write_utf8(fullfile(root,'docProps','core.xml'), ...
    core_properties_xml(titleText));
write_utf8(fullfile(root,'docProps','app.xml'),app_properties_xml());
write_utf8(fullfile(root,'word','styles.xml'),styles_xml());
write_utf8(fullfile(root,'word','settings.xml'),settings_xml());
write_utf8(fullfile(root,'word','header1.xml'), ...
    header_xml(metadata.run_id));
write_utf8(fullfile(root,'word','footer1.xml'), ...
    footer_xml(metadata.run_id));
write_utf8(fullfile(root,'word','_rels','document.xml.rels'), ...
    document_relationships_xml());

body = paragraph_xml('STAGE A4 · 完整内点迭代结果备忘','MastheadKicker')+ ...
    paragraph_xml(titleText,'Title')+paragraph_xml(subtitleText,'Subtitle');
labels = ["运行标识","阶段","Git 提交","报告生成时 manifest", ...
    "事实推导候选终态"];
values = [string(metadata.run_id),string(metadata.stage_id), ...
    string(metadata.git_commit),string(metadata.manifest_status), ...
    string(metadata.candidate_status)];
for k = 1:numel(labels)
    body = body+metadata_xml(labels(k),values(k));
end
body = body+paragraph_xml('','MastheadSpacer');
for k = 1:numel(blocks)
    body = body+block_xml(blocks(k));
end
write_utf8(fullfile(root,'word','document.xml'),document_xml(body));

files = {'[Content_Types].xml',fullfile('_rels','.rels'), ...
    fullfile('docProps','core.xml'),fullfile('docProps','app.xml'), ...
    fullfile('word','document.xml'),fullfile('word','styles.xml'), ...
    fullfile('word','settings.xml'),fullfile('word','header1.xml'), ...
    fullfile('word','footer1.xml'), ...
    fullfile('word','_rels','document.xml.rels')};
zipPath = string(tempname(fileparts(outputPath)))+".zip";
zipGuard = onCleanup(@()delete_if_exists(zipPath));
zip(zipPath,files,root);
[moved,message] = movefile(zipPath,outputPath);
assert(moved,"stageA4:report:PackageWriteFailed","%s",message);
clear zipGuard guard;
end

function xml = block_xml(block)
type = string(block.type);
switch type
    case "heading"
        level = double(block.level); style = "Heading1";
        if level==2, style="Heading2"; end
        xml = paragraph_xml(string(block.text),style);
    case "paragraph"
        xml = paragraph_xml(string(block.text),'Normal');
    case "callout"
        cellBody = paragraph_xml(string(block.title),'CalloutTitle')+ ...
            paragraph_xml(string(block.text),'CalloutText');
        xml = one_cell_callout(cellBody);
    case "table"
        xml = table_xml(string(block.headers),string(block.rows), ...
            double(block.widths));
    otherwise
        error("stageA4:report:UnknownBlockType", ...
            "Unknown report block %s.",type);
end
end

function xml = one_cell_callout(cellBody)
xml = ['<w:tbl><w:tblPr><w:tblW w:w="9360" w:type="dxa"/>' ...
    '<w:tblLayout w:type="fixed"/><w:tblInd w:w="120" w:type="dxa"/>' ...
    '<w:tblBorders><w:top w:val="single" w:sz="4" w:color="D8DEE8"/>' ...
    '<w:left w:val="single" w:sz="4" w:color="D8DEE8"/>' ...
    '<w:bottom w:val="single" w:sz="4" w:color="D8DEE8"/>' ...
    '<w:right w:val="single" w:sz="4" w:color="D8DEE8"/>' ...
    '<w:insideH w:val="nil"/><w:insideV w:val="nil"/></w:tblBorders>' ...
    '<w:tblCellMar><w:top w:w="120" w:type="dxa"/>' ...
    '<w:left w:w="120" w:type="dxa"/>' ...
    '<w:bottom w:w="120" w:type="dxa"/>' ...
    '<w:right w:w="120" w:type="dxa"/></w:tblCellMar></w:tblPr>' ...
    '<w:tblGrid><w:gridCol w:w="9360"/></w:tblGrid>' ...
    '<w:tr><w:trPr><w:cantSplit/></w:trPr><w:tc><w:tcPr>' ...
    '<w:tcW w:w="9360" w:type="dxa"/>' ...
    '<w:shd w:fill="F4F6F9"/><w:vAlign w:val="center"/></w:tcPr>' ...
    char(cellBody) '</w:tc></w:tr></w:tbl>' ...
    char(paragraph_xml('','TableSpacer'))];
xml = string(xml);
end

function xml = table_xml(headers,rows,widths)
assert(sum(widths)==9360&&size(rows,2)==numel(headers)&& ...
    numel(widths)==numel(headers), ...
    "stageA4:report:TableGeometry", ...
    "Every A4 report table must use exact 9360-DXA geometry.");
grid = "";
for width = widths
    grid = grid+"<w:gridCol w:w="""+width+"""/>";
end
xml = "<w:tbl><w:tblPr><w:tblW w:w=""9360"" w:type=""dxa""/>"+ ...
    "<w:tblLayout w:type=""fixed""/>"+ ...
    "<w:tblInd w:w=""120"" w:type=""dxa""/>"+ ...
    "<w:tblBorders><w:top w:val=""single"" w:sz=""4"" "+ ...
    "w:color=""D9DEE7""/><w:left w:val=""single"" w:sz=""4"" "+ ...
    "w:color=""D9DEE7""/><w:bottom w:val=""single"" w:sz=""4"" "+ ...
    "w:color=""D9DEE7""/><w:right w:val=""single"" w:sz=""4"" "+ ...
    "w:color=""D9DEE7""/><w:insideH w:val=""single"" w:sz=""3"" "+ ...
    "w:color=""D9DEE7""/><w:insideV w:val=""single"" w:sz=""3"" "+ ...
    "w:color=""D9DEE7""/></w:tblBorders>"+ ...
    "<w:tblCellMar><w:top w:w=""80"" w:type=""dxa""/>"+ ...
    "<w:left w:w=""120"" w:type=""dxa""/>"+ ...
    "<w:bottom w:w=""80"" w:type=""dxa""/>"+ ...
    "<w:right w:w=""120"" w:type=""dxa""/></w:tblCellMar>"+ ...
    "</w:tblPr><w:tblGrid>"+grid+"</w:tblGrid>"+ ...
    table_row_xml(headers,widths,true);
for r = 1:size(rows,1)
    xml = xml+table_row_xml(rows(r,:),widths,false);
end
xml = xml+"</w:tbl>"+paragraph_xml('','TableSpacer');
end

function xml = table_row_xml(values,widths,isHeader)
if isHeader
    rowProperties = "<w:trPr><w:tblHeader/><w:cantSplit/></w:trPr>";
else
    rowProperties = "<w:trPr><w:cantSplit/></w:trPr>";
end
xml = "<w:tr>"+rowProperties;
for k = 1:numel(values)
    fill = ""; style = "TableText";
    if isHeader
        fill = "<w:shd w:fill=""F2F4F7""/>";
        style = "TableHeader";
    end
    xml = xml+"<w:tc><w:tcPr><w:tcW w:w="""+widths(k)+ ...
        """ w:type=""dxa""/>"+fill+ ...
        "<w:vAlign w:val=""center""/></w:tcPr>"+ ...
        paragraph_xml(values(k),style)+"</w:tc>";
end
xml = xml+"</w:tr>";
end

function xml = paragraph_xml(textValue,styleName)
xml = "<w:p><w:pPr><w:pStyle w:val="""+styleName+ ...
    """/></w:pPr><w:r><w:t xml:space=""preserve"">"+ ...
    xml_escape(textValue)+"</w:t></w:r></w:p>";
end

function xml = metadata_xml(label,value)
