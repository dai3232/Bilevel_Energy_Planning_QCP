function output = daily_dispatch_summary(hourly)
days = unique(numeric_column(hourly,"day"),'stable');
n = numel(days);
day = days; wind_mwh = zeros(n,1); solar_mwh = zeros(n,1);
hydro_mwh = zeros(n,1); thermal_mwh = zeros(n,1);
charge_mwh = zeros(n,1); discharge_mwh = zeros(n,1);
names = ["PW","PP","PH","PF","Pch","Pdis"];
targets = {wind_mwh,solar_mwh,hydro_mwh,thermal_mwh, ...
    charge_mwh,discharge_mwh};
variable = string(column(hourly,"variable_name"));
energy = numeric_column(hourly,"energy_mwh");
allDays = numeric_column(hourly,"day");
for k = 1:numel(names)
    values = zeros(n,1);
    for d = 1:n
        mask = allDays==days(d)&variable==names(k);
        values(d) = sum(energy(mask));
    end
    targets{k} = values;
end
wind_mwh = targets{1}; solar_mwh = targets{2};
hydro_mwh = targets{3}; thermal_mwh = targets{4};
charge_mwh = targets{5}; discharge_mwh = targets{6};
output = table(day,wind_mwh,solar_mwh,hydro_mwh,thermal_mwh, ...
    charge_mwh,discharge_mwh);
end

function output = daily_soc_summary(hourly)
days = unique(numeric_column(hourly,"day"),'stable');
day = days; soc_min_mwh = zeros(numel(days),1);
soc_max_mwh = zeros(numel(days),1);
allDays = numeric_column(hourly,"day");
variable = string(column(hourly,"variable_name"));
values = numeric_column(hourly,"value");
for d = 1:numel(days)
    mask = allDays==days(d)&variable=="SOC";
    soc_min_mwh(d) = min(values(mask));
    soc_max_mwh(d) = max(values(mask));
end
output = table(day,soc_min_mwh,soc_max_mwh);
end

