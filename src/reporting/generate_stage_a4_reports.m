end

function value = numeric_column(tableValue,name)
raw = column(tableValue,name);
if isnumeric(raw)
    value=double(raw);
else
    tokens = strip(string(raw));
    value=str2double(tokens);
    invalid = isnan(value)&~strcmpi(tokens,"NaN");
    assert(~any(invalid), ...
        "stageA4:report:InvalidNumericEvidence", ...
        "Persisted numeric column %s contains a nonnumeric token.",name);
end
value = reshape(value,[],1);
end

function value = numeric_at(tableValue,name,row)
values = numeric_column(tableValue,name); value=values(row);
end

function values = to_logical(raw)
if islogical(raw), values=raw; return; end
if isnumeric(raw), values=raw~=0; return; end
values = lower(strip(string(raw)))=="true"|strip(string(raw))=="1";
end

function textValue = display_text(value)
tokens = display_tokens(value);
textValue = strjoin(tokens.',", ");
end

function tokens = display_tokens(value)
if iscell(value)
    if isempty(value), tokens="[]"; return; end
    tokens = strings(0,1);
    for k = 1:numel(value)
        tokens = [tokens;display_tokens(value{k})]; %#ok<AGROW>
    end
elseif isstring(value)
    if isempty(value), tokens="[]"; return; end
    tokens = value(:); tokens(ismissing(tokens))="<missing>";
elseif ischar(value)
    if isempty(value)
        tokens = "[]";
    elseif isrow(value)
        tokens = string(value);
    else
        tokens = string(cellstr(value));
    end
elseif islogical(value)
    tokens = repmat("false",numel(value),1); tokens(value(:))="true";
elseif isnumeric(value)
    tokens = strings(numel(value),1);
    for k = 1:numel(value), tokens(k)=format_number(double(value(k))); end
else
    try
        tokens = string(jsonencode(value));
    catch
        tokens = string(value);
    end
end
end

function value = format_number(number)
if isnan(number), value="NaN";
elseif isinf(number), value=string(number);
else, value=compose("%.17g",number);
end
end

