    isequal(unique(day,'stable'),(14:20).')&& ...
    isequal(unique(hour,'stable'),(1:24).')&& ...
    complete_day_hour_coverage(day,hour,24), ...
    "stageA4:report:HourlyEvidence", ...
    "hourly_dispatch_results.csv must contain exactly one complete 7x24 result scope.");
