function [reportPaths,validation] = generate_stage_a4_reports( ...
        runContext,options)
%GENERATE_STAGE_A4_REPORTS Build three Chinese reports from persisted facts.
%
% No solver result is accepted as a direct function argument.  Every number
% displayed in the reports is re-read from the current run's CSV/JSON
% evidence.  ReportGateMode="preflight" supports the first half of the
% circular SA4-RPT-001 gate.  A PASS candidate is gated strictly; a failed
% run is still reportable and its failed evidence remains visible.

arguments
    runContext (1,1) struct
    options.OutputDirectory (1,1) string = ""
    options.FinalStatusCandidate (1,1) string = "PASS"
    options.ReportGateMode (1,1) string {mustBeMember( ...
        options.ReportGateMode,["preflight","final"])} = "final"
end
assert(isfield(runContext,"root")&&isfield(runContext,"project_root"), ...
    "stageA4:report:InvalidRunContext", ...
    "runContext.root and runContext.project_root are required.");
runRoot = canonical_path(runContext.root);
assert(isfolder(runRoot),"stageA4:report:MissingRunRoot", ...
    "Run root is missing.");
facts = load_facts(runRoot);
facts.projectRoot = string(runContext.project_root);
facts.gateMode = options.ReportGateMode;
facts.candidateStatus = upper(strip(options.FinalStatusCandidate));
validate_facts(facts);

outputDirectory = strip(options.OutputDirectory);
if strlength(outputDirectory)==0
    outputDirectory = fullfile(runRoot,"reports");
end
ensure_directory(outputDirectory);
reportPaths = struct( ...
    "model_report",fullfile(outputDirectory, ...
        "阶段A4_模型与优化结果报告.docx"), ...
    "issue_report",fullfile(outputDirectory, ...
        "阶段A4_问题修复与验收报告.docx"), ...
    "run_summary",fullfile(outputDirectory, ...
        "运行_"+safe_filename(facts.runId)+"_结果摘要.docx"));
targets = string(struct2cell(reportPaths));
assert_targets_absent(targets);

staging = string(tempname(tempdir)); mkdir(staging);
guard = onCleanup(@()remove_tree(staging));
staged = [fullfile(staging,"model.docx"); ...
    fullfile(staging,"issues.docx");fullfile(staging,"summary.docx")];
metadata = struct( ...
    "run_id",facts.runId,"stage_id",facts.stageId, ...
    "git_commit",facts.gitCommit, ...
    "manifest_status",facts.manifestStatus, ...
    "candidate_status",metadata_candidate(facts));
write_stage_a4_docx(staged(1), ...
    "阶段A4 模型与优化结果报告", ...
    "第14—20日真实数据 · 7个独立正式日 · 完整原始—对偶内点迭代", ...
    metadata,build_model_blocks(facts));
write_stage_a4_docx(staged(2), ...
    "阶段A4 问题修复与验收报告", ...
    "收敛、逐轮方向审计、物理验收、测试与报告门禁", ...
    metadata,build_issue_blocks(facts));
write_stage_a4_docx(staged(3), ...
    "阶段 A4 单次运行结果摘要", ...
    "真实工件驱动的容量与小时运行结果", ...
    metadata,build_summary_blocks(facts));

stagedPaths = struct("model_report",char(staged(1)), ...
    "issue_report",char(staged(2)),"run_summary",char(staged(3)));
[valid,validation] = validate_stage_a4_report_set(stagedPaths,facts.runId);
assert(valid,"stageA4:report:InvalidDocxSet", ...
    "A4 report structural validation failed: %s", ...
    failed_validation_text(validation));

assert_targets_absent(targets);
names = fieldnames(reportPaths);
for k = 1:numel(targets)
    sourceHash = compute_sha256_file(staged(k));
    [moved,message] = movefile(staged(k),targets(k));
    assert(moved,"stageA4:report:PublishFailed","%s",message);
    assert(lower(string(compute_sha256_file(targets(k))))== ...
        lower(string(sourceHash)), ...
        "stageA4:report:PublishedHash", ...
        "Published A4 report hash changed.");
    reportPaths.(names{k}) = char(targets(k));
end
[valid,validation] = validate_stage_a4_report_set(reportPaths,facts.runId);
assert(valid,"stageA4:report:InstalledDocxSet", ...
    "Installed A4 report validation failed: %s", ...
    failed_validation_text(validation));
clear guard;
end

function facts = load_facts(root)
facts = struct(); facts.root = root;
facts.manifest = read_json(required(root,"run_manifest.json"));
facts.environment = read_csv(required(root,"environment.csv"));
facts.inputHashes = read_csv(required(root,"input_hashes.csv"));
facts.acceptance = read_csv(required(root, ...
    fullfile("acceptance","acceptance_results.csv")));
facts.physicalAudit = read_csv(required(root, ...
    fullfile("acceptance","physical_audit.csv")));
facts.issues = read_csv(required(root,fullfile("issues","issue_log.csv")));
facts.iterations = read_csv(required(root, ...
    fullfile("iterations","iteration_summary.csv")));
facts.direction = read_csv(required(root, ...
    fullfile("iterations","direction_audit.csv")));
facts.capacity = read_csv(required(root, ...
    fullfile("results","capacity_results.csv")));
facts.hourly = read_csv(required(root, ...
    fullfile("results","hourly_dispatch_results.csv")));
facts.resultHashes = read_csv(required(root, ...
    fullfile("results","result_artifact_hashes.csv")));
facts.matrices = read_csv(required(root, ...
    fullfile("matrices","matrix_manifest.csv")));
facts.checkpoints = read_csv(required(root, ...
    fullfile("checkpoints","checkpoint_manifest.csv")));
facts.testSummary = read_json(required(root, ...
    fullfile("tests","test_summary.json")));
facts.runId = required_manifest_text(facts.manifest,"run_id");
facts.stageId = required_manifest_text(facts.manifest,"stage_id");
facts.gitCommit = required_manifest_text(facts.manifest,"git_commit");
facts.manifestStatus = required_manifest_text(facts.manifest,"status");
end

function validate_facts(facts)
assert(facts.stageId=="stage_A4"&&facts.manifestStatus=="RUNNING", ...
    "stageA4:report:ManifestIdentity", ...
    "Reports require the matching RUNNING stage_A4 manifest.");
allowedCandidates = ["PASS","FAIL_RETRYABLE","BLOCKED_EXTERNAL", ...
    "NEEDS_MODEL_DECISION","MAX_ITERATIONS","NUMERICAL_FAILURE"];
assert(ismember(facts.candidateStatus,allowedCandidates), ...
    "stageA4:report:CandidateStatus", ...
    "Unsupported A4 report status candidate: %s.",facts.candidateStatus);
strictPass = facts.candidateStatus=="PASS";
validate_environment_and_inputs(facts,strictPass);
validate_acceptance(facts);
validate_execution_scope(facts.manifest,strictPass);
validate_iteration_evidence(facts.iterations,strictPass);
validate_direction_evidence(facts.direction,strictPass);
validate_result_evidence(facts,strictPass);
validate_issue_and_test_evidence(facts,strictPass);
if strictPass
    assert(height(facts.matrices)>0&&height(facts.checkpoints)>0, ...
        "stageA4:report:MatrixCheckpointEvidence", ...
        "PASS requires nonempty matrix and checkpoint manifests.");
end
end

function validate_environment_and_inputs(facts,strictPass)
requiredEnvironment = ["blocking","status"];
requiredInputs = ["file_name","expectedSHA256","actualSHA256","status"];
assert(all(ismember(requiredEnvironment, ...
    string(facts.environment.Properties.VariableNames)))&& ...
    all(ismember(requiredInputs, ...
    string(facts.inputHashes.Properties.VariableNames)))&& ...
    height(facts.inputHashes)==2, ...
    "stageA4:report:EnvironmentInputSchema", ...
    "Environment or controlled-input evidence is incomplete.");
blocking = to_logical(column(facts.environment,"blocking"));
status = upper(strip(string(column(facts.environment,"status"))));
inputStatus = upper(strip(string(column(facts.inputHashes,"status"))));
expected = lower(string(column(facts.inputHashes,"expectedSHA256")));
actual = lower(string(column(facts.inputHashes,"actualSHA256")));
assert(all(ismember(status,reportable_gate_statuses()))&& ...
    all(ismember(inputStatus,reportable_gate_statuses())), ...
    "stageA4:report:EnvironmentInputStatus", ...
    "Environment or input evidence contains an unsupported status.");
if strictPass
    assert(any(blocking)&&all(status(blocking)=="PASS"), ...
        "stageA4:report:EnvironmentEvidence", ...
        "Blocking environment evidence must be persisted PASS.");
    assert(all(inputStatus=="PASS")&&all(expected==actual), ...
        "stageA4:report:InputHashEvidence", ...
        "Both controlled input SHA256 comparisons must be persisted PASS.");
end
end

function validate_acceptance(facts)
expected = ["SA4-CONV-001";"SA4-CONV-002";"SA4-CONV-003"; ...
    "SA4-CONV-004";"SA4-EQ-001";"SA4-PHY-001";"SA4-RPT-001"];
ids = string(column(facts.acceptance,"test_id"));
status = upper(string(column(facts.acceptance,"status")));
assert(height(facts.acceptance)==7&&isequal(ids,expected)&& ...
    all(ismember(status,reportable_gate_statuses())), ...
    "stageA4:report:AcceptanceMismatch", ...
    "A4 acceptance rows must use canonical IDs and reportable statuses.");
if facts.candidateStatus=="PASS"
    assert(all(status(1:6)=="PASS"), ...
        "stageA4:report:AcceptanceMismatch", ...
        "A PASS candidate requires the six numerical A4 gates PASS.");
    if facts.gateMode=="final"
        assert(status(7)=="PASS", ...
            "stageA4:report:ReportGateNotPassed", ...
            "Final PASS reports require SA4-RPT-001=PASS.");
    else
        assert(ismember(status(7),["NOT_RUN","PASS"]), ...
            "stageA4:report:ReportGatePreflight", ...
            "PASS preflight requires SA4-RPT-001=NOT_RUN or PASS.");
    end
else
    assert(any(status~="PASS"), ...
        "stageA4:report:FailedCandidateWithoutFailedGate", ...
        "A non-PASS candidate must retain at least one failed or unrun gate.");
end
end

function validate_execution_scope(manifest,strictPass)
required = ["optimization_executed","full_ipm_executed", ...
    "physical_dispatch_interpretation","capacity_planning_interpretation", ...
    "parallel_executed","newton_direction_count", ...
    "enabled_components","disabled_components"];
assert(all(isfield(manifest,cellstr(required))), ...
    "stageA4:report:ExecutionScope", ...
    "Manifest execution scope is incomplete.");
assert(~logical(manifest.parallel_executed)&& ...
    double(manifest.newton_direction_count)>=0, ...
    "stageA4:report:ExecutionScope", ...
    "A4-3 reports require serial scope and a nonnegative direction count.");
if strictPass
    assert(logical(manifest.optimization_executed)&& ...
        logical(manifest.full_ipm_executed)&& ...
        logical(manifest.physical_dispatch_interpretation)&& ...
        logical(manifest.capacity_planning_interpretation)&& ...
        double(manifest.newton_direction_count)>0, ...
        "stageA4:report:ExecutionScope", ...
        "PASS requires a completed serial A4 optimization.");
end
end

function validate_iteration_evidence(value,strictPass)
requiredColumns = ["iteration","state_revision","objective_scaled", ...
    "objective_original","r_eq_inf","r_ineq_inf", ...
    "physical_inequality_violation","r_dual_scaled_inf", ...
    "r_dual_original_mapped_inf","r_comp_scaled_inf", ...
    "mean_lz_scaled","ltz_scaled","gap_original_mapped", ...
    "eta_eq","eta_dual","eta_gap","candidate_alpha_primal", ...
    "applied_alpha_primal","candidate_alpha_dual", ...
    "applied_alpha_dual","min_l","min_z","convergence_passed"];
assert(height(value)>0&& ...
    all(ismember(requiredColumns,string(value.Properties.VariableNames))), ...
    "stageA4:report:IterationSchema", ...
    "iteration_summary.csv is incomplete.");
iteration = numeric_column(value,"iteration");
assert(all(isfinite(iteration))&&all(diff(iteration)>0), ...
    "stageA4:report:IterationOrder", ...
    "Iteration identifiers must be finite and strictly increasing.");
if strictPass
    final = height(value);
    threshold = 1.0e-8;
    assert(numeric_at(value,"r_eq_inf",final)<=threshold&& ...
        numeric_at(value,"r_ineq_inf",final)<=threshold&& ...
        numeric_at(value,"r_dual_scaled_inf",final)<=threshold&& ...
        numeric_at(value,"mean_lz_scaled",final)<=threshold&& ...
        numeric_at(value,"physical_inequality_violation",final)<=threshold&& ...
        to_logical(column(value,"convergence_passed",final))&& ...
        isfinite(numeric_at(value,"objective_original",final)), ...
        "stageA4:report:ConvergenceEvidence", ...
        "The final persisted iteration does not meet all frozen thresholds.");
end
end

function validate_direction_evidence(value,strictPass)
requiredColumns = ["iteration","direction_relative_error", ...
    "xi_relative_error","y_relative_error", ...
    "l_relative_error","z_relative_error", ...
    "recursive_full_kkt_relative_residual", ...
    "full_kkt_relative_residual","no_full_direction_fallback", ...
    "full_kkt_audit_only","recursive_direction_is_official"];
assert(height(value)>0&& ...
    all(ismember(requiredColumns,string(value.Properties.VariableNames))), ...
    "stageA4:report:DirectionSchema", ...
    "direction_audit.csv is incomplete.");
metrics = requiredColumns(2:8);
for name = metrics
    numbers = numeric_column(value,name);
    if strictPass
        assert(all(isfinite(numbers))&&all(numbers<=1.0e-10), ...
            "stageA4:report:DirectionThreshold", ...
            "Persisted direction metric %s exceeds 1e-10.",name);
    end
end
if strictPass
    assert(all(to_logical(column(value,"no_full_direction_fallback")))&& ...
        all(to_logical(column(value,"full_kkt_audit_only")))&& ...
        all(to_logical(column(value,"recursive_direction_is_official"))), ...
        "stageA4:report:DirectionRole", ...
        "Every accepted direction must be recursive and independently audited.");
end
end

