assert(height(facts.physicalAudit)>0&& ...
    all(ismember(physicalStatus,reportable_gate_statuses())), ...
    "stageA4:report:PhysicalEvidence", ...
    "Physical evidence is empty or contains an unsupported status.");
assert(height(facts.resultHashes)>=4&& ...
    all(upper(string(column(facts.resultHashes,"status")))=="PASS"), ...
    "stageA4:report:ResultHashes", ...
    "Final result artifact hashes are missing or failed.");
if strictPass
    assert(all(capacityStatus=="PASS"), ...
        "stageA4:report:CapacityEvidence", ...
        "PASS requires 14 canonical capacity rows PASS.");
    assert(all(hourlyStatus=="PASS"), ...
        "stageA4:report:HourlyEvidence", ...
        "PASS requires every hourly result row PASS.");
    assert(all(physicalStatus=="PASS"), ...
        "stageA4:report:PhysicalEvidence", ...
        "PASS requires every physical audit row PASS.");
end

function passed = complete_day_hour_coverage(day,hour,rowsPerHour)
%COMPLETE_DAY_HOUR_COVERAGE Ensure every modeled day/hour appears exactly
% once per physical variable row; unique day/hour sets alone are insufficient.
if numel(day)~=numel(hour) || any(~isfinite(day)) || any(~isfinite(hour)) || ...
        any(day~=fix(day)) || any(hour~=fix(hour))
    passed = false;
    return
end
[dayGrid,hourGrid] = ndgrid(14:20,1:24);
expected = string(dayGrid(:))+"|"+string(hourGrid(:));
observed = string(day)+"|"+string(hour);
[expectedUnique,~,~] = unique(expected);
[observedUnique,~,observedGroup] = unique(observed);
if ~isequal(sort(expectedUnique),sort(observedUnique))
    passed = false;
    return
end
observedCounts = accumarray(observedGroup,1);
passed = all(observedCounts==rowsPerHour);
end
end

function validate_issue_and_test_evidence(facts,strictPass)
if strictPass&&height(facts.issues)>0
    issueStatus = upper(string(column(facts.issues,"status")));
    assert(~any(ismember(issueStatus,["OPEN","BLOCKED"])), ...
        "stageA4:report:UnresolvedIssues", ...
        "Final PASS reports cannot contain OPEN or BLOCKED issues.");
end
summary = facts.testSummary;
required = ["test_total","test_passed","test_failed","test_incomplete"];
assert(all(isfield(summary,cellstr(required)))&& ...
    all(isfinite(double([summary.test_total,summary.test_passed, ...
    summary.test_failed,summary.test_incomplete])))&& ...
    all(double([summary.test_total,summary.test_passed, ...
    summary.test_failed,summary.test_incomplete])>=0), ...
    "stageA4:report:TestEvidence", ...
    "Persisted A4 test summary is incomplete or invalid.");
if strictPass
    assert(double(summary.test_total)>0&& ...
        double(summary.test_passed)==double(summary.test_total)&& ...
        double(summary.test_failed)==0&&double(summary.test_incomplete)==0, ...
    "stageA4:report:TestEvidence", ...
    "Persisted A4 test summary is incomplete or not all PASS.");
end
end

