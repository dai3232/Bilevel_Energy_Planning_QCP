    assert(~isfile(targets{k})&&~isfolder(targets{k}), ...
        'stageA2:report:ArtifactExists','Refusing to overwrite %s.',targets{k});
end
end
function name = string_filename(pathValue)
[~,base,extension]=fileparts(pathValue); name=[base,extension];
end
function name = safe_filename(value)
name=regexprep(char(string(value)),'[^A-Za-z0-9._-]','_');
end
function remove_tree(pathValue)
if isfolder(pathValue)
    try
        rmdir(pathValue,'s');
    catch
    end
end
end
function delete_if_exists(pathValue)
if isfile(pathValue)
    try
        delete(pathValue);
    catch
    end
end
end
