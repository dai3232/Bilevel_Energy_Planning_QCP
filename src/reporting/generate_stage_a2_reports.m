function values = to_logical(raw)
if islogical(raw)
    values=raw;
    return
end
if isnumeric(raw)
    values=raw~=0;
    return
end
values=lower(strip(string(raw)))=="true" | strip(string(raw))=="1";
end
function textValue = display_text(value)
if isstring(value)
    value(ismissing(value))="";
    if isempty(value)
        textValue="";
    else
        textValue=strjoin(value(:)',', ');
    end
elseif ischar(value)
    textValue=string(value);
elseif isnumeric(value)||islogical(value)
    if isscalar(value)
        textValue=format_number(double(value));
    else
        textValue=string(jsonencode(value));
    end
elseif isempty(value)
    textValue="";
else
    try
        textValue=string(jsonencode(value));
    catch
        textValue=string(value);
    end
end
end
function value = format_number(number)
if isfinite(number)
    value=string(sprintf('%.17g',number));
else
    value=string(number);
end
end
function value = xml_escape(value)
value=display_text(value); value=replace(value,'&','&amp;');
value=replace(value,'<','&lt;'); value=replace(value,'>','&gt;');
value=replace(value,'"','&quot;'); value=replace(value,'''','&apos;');
end
function write_utf8(pathValue,content)
[fileId,message]=fopen(pathValue,'wb','n','UTF-8');
assert(fileId>=0,'stageA2:report:WriteFailed','%s',message);
guard=onCleanup(@()close_file(fileId)); bytes=unicode2native(char(content),'UTF-8');
count=fwrite(fileId,bytes,'uint8');
assert(count==numel(bytes),'stageA2:report:WriteFailed','Short write for %s.',pathValue);
status=fclose(fileId); clear guard;
assert(status==0,'stageA2:report:WriteFailed','Could not close %s.',pathValue);
end
function close_file(fileId)
try
    if ischar(fopen(fileId))
        fclose(fileId);
    end
catch
end
end
function ensure_directory(pathValue)
if isfolder(pathValue), return; end
[created,message]=mkdir(pathValue);
assert(created,'stageA2:report:DirectoryCreateFailed','%s',message);
end
function assert_targets_absent(targets)
