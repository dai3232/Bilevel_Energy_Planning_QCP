function reportPaths = generate_stage_a2_reports(runContext,varargin)
%GENERATE_STAGE_A2_REPORTS Build three Chinese reports from persisted A2 facts.

parser=inputParser; parser.FunctionName=mfilename;
addParameter(parser,'OutputDirectory','',@is_text_scalar);
addParameter(parser,'FinalStatusCandidate','',@is_text_scalar);
parse(parser,varargin{:});
assert(isstruct(runContext)&&isscalar(runContext)&&isfield(runContext,'root'), ...
    'stageA2:report:InvalidRunContext','runContext.root is required.');
runRoot=char(java.io.File(char(string(runContext.root))).getCanonicalPath());
assert(isfolder(runRoot),'stageA2:report:MissingRunRoot','Run root is missing.');
facts=load_facts(runRoot,runContext);
candidate=upper(strip(string(parser.Results.FinalStatusCandidate)));
if strlength(candidate)==0, candidate="PASS"; end
validate_facts(facts,candidate);
facts.candidateStatus=candidate;
outputDirectory=char(string(parser.Results.OutputDirectory));
if isempty(outputDirectory), outputDirectory=fullfile(runRoot,'reports'); end
ensure_directory(outputDirectory);
reportPaths=struct( ...
    'model_report',fullfile(outputDirectory, ...
        '阶段A2_完整24小时方向等价与变维结构报告.docx'), ...
    'issue_report',fullfile(outputDirectory,'阶段A2_问题修复与验收报告.docx'), ...
    'run_summary',fullfile(outputDirectory,sprintf('运行_%s_结果摘要.docx', ...
        safe_filename(facts.runId))));
targets=struct2cell(reportPaths); assert_targets_absent(targets);
staging=tempname; mkdir(staging); guard=onCleanup(@()remove_tree(staging));
staged=cellfun(@(p)fullfile(staging,string_filename(p)),targets, ...
    'UniformOutput',false);
write_docx(staged{1},'阶段A2_完整24小时方向等价与变维结构报告', ...
    '第14日1—24小时真实数据 · 单次 Newton 方向算法验收',facts, ...
    build_model_body(facts));
write_docx(staged{2},'阶段A2_问题修复与验收报告', ...
    '六项阻断门禁、自动测试、问题证据与范围边界',facts, ...
    build_issue_body(facts));
write_docx(staged{3},'Stage A2 单次运行结果摘要', ...
    '完整物理日算法验证证据摘要（不构成优化或经济结论）',facts, ...
    build_summary_body(facts));
for k=1:numel(staged)
    [valid,details]=validate_docx_package(staged{k});
    assert(valid,'stageA2:report:InvalidDocxPackage','%s', ...
        strjoin(string(details.errors),'; '));
end
assert_targets_absent(targets);
for k=1:numel(targets)
    [moved,message]=movefile(staged{k},targets{k});
    assert(moved,'stageA2:report:PublishFailed','%s',message);
end
clear guard;
end

