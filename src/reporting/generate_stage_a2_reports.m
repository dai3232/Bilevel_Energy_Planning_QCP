function value = matrix_dimension(matrix,name)
row=matrix(string(matrix.matrix_name)==name,:);
assert(height(row)==1,'stageA2:report:MatrixManifest', ...
    'Expected one matrix_manifest row for %s.',name);
value=string(row.rows)+" × "+string(row.columns);
end

function value = metric_value(tableValue,id)
row=tableValue(string(tableValue.metric_id)==id,:);
assert(height(row)==1,'stageA2:report:MetricMissing','Missing metric %s.',id);
value=format_number(double(row.actual_value));
end

function value = residual_value(tableValue,id)
row=tableValue(string(tableValue.route)==id,:);
assert(height(row)==1,'stageA2:report:ResidualMissing','Missing residual %s.',id);
value=format_number(double(row.relative_residual_2norm));
end

function xml = definition_table(rows)
xml=table_xml(["项目","真实记录"],string(rows),[2800 6560]);
end

function xml = selected_table(tableValue,columns,widths)
actual=string(tableValue.Properties.VariableNames);
assert(all(ismember(columns,actual)),'stageA2:report:MissingColumn', ...
    'A report source is missing required columns.');
rows=strings(height(tableValue),numel(columns));
for column=1:numel(columns)
    values=tableValue.(columns(column));
    for row=1:height(tableValue)
        if iscell(values), value=values{row}; else, value=values(row); end
        rows(row,column)=display_text(value);
    end
end
xml=table_xml(display_headers(columns),rows,widths);
end

