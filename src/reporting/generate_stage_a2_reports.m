function validate_facts(facts,candidate)
assert(facts.stageId=="stage_A2" && facts.manifestStatus=="RUNNING", ...
    'stageA2:report:ManifestIdentity', ...
    'Reports require the matching RUNNING stage_A2 manifest.');
assert(candidate=="PASS",'stageA2:report:CandidateStatus', ...
    'Formal three-report generation requires PASS as the fact-derived candidate.');
blockingEnvironment=to_logical(facts.environment.blocking);
assert(any(blockingEnvironment) && ...
    all(string(facts.environment.status(blockingEnvironment))=="PASS"), ...
    'stageA2:report:EnvironmentEvidence', ...
    'Blocking environment evidence must be persisted PASS.');
assert(height(facts.inputHashes)==2 && ...
    all(string(facts.inputHashes.status)=="PASS") && ...
    all(lower(string(facts.inputHashes.expectedSHA256))== ...
        lower(string(facts.inputHashes.actualSHA256))), ...
    'stageA2:report:InputHashEvidence', ...
    'Both controlled input SHA256 comparisons must be persisted PASS.');
expected=["SA2-MAT-001";"SA2-ZERO-001";"SA2-ZERO-002"; ...
    "SA2-EQ-001";"SA2-EQ-002";"SA2-PHY-001"];
assert(height(facts.acceptance)==6 && ...
    isequal(string(facts.acceptance.test_id),expected) && ...
    all(string(facts.acceptance.status)=="PASS"), ...
    'stageA2:report:AcceptanceMismatch', ...
    'All six frozen A2 acceptance facts must be persisted PASS.');
assert(all_tests_pass(facts.a2Inventory,facts.a2Results,facts.a2Summary), ...
    'stageA2:report:A2Tests','Persisted A2 test evidence is inconsistent.');
assert(height(facts.a1Inventory)==37 && ...
    all_tests_pass(facts.a1Inventory,facts.a1Results,facts.a1Summary), ...
    'stageA2:report:A1Regression', ...
    'All 37 persisted A1 regression tests must pass.');
assert(height(facts.blocks)==24 && sum(double(facts.blocks.kkt_dimension))==589 && ...
    all(string(facts.blocks.status)=="PASS"), ...
    'stageA2:report:BlockEvidence','24-block dimension evidence is invalid.');
assert(height(facts.fixed)==61 && ...
    nnz(string(facts.fixed.asset_type)=="solar")==60 && ...
    nnz(string(facts.fixed.asset_type)=="wind")==1 && ...
    all(double(facts.fixed.fixed_value)==0) && ...
    all(double(facts.fixed.fixed_direction_value)==0), ...
    'stageA2:report:FixedZeroEvidence','Fixed-zero evidence is invalid.');
assert(height(facts.soc)==50 && all(string(facts.soc.status)=="PASS"), ...
    'stageA2:report:SocEvidence','SOC audit evidence is invalid.');
assert(all(string(facts.codeScan.status)=="PASS") && ...
    logical(facts.identity.all_identities_equal), ...
    'stageA2:report:ImplementationEvidence', ...
    'Code scan or shared-linearization identity evidence did not pass.');
assert(~logical(facts.manifest.parallel_executed) && ...
    ~logical(facts.manifest.full_ipm_executed) && ...
    ~logical(facts.manifest.optimization_executed) && ...
    double(facts.manifest.newton_direction_count)==1 && ...
    logical(facts.manifest.a2_solver_executed), ...
    'stageA2:report:ScopeMismatch','Manifest execution scope is invalid.');
end

function passed = all_tests_pass(inventory,results,summary)
passed=height(inventory)==height(results) && ...
    isequal(string(inventory.test_name),string(results.test_name)) && ...
    all(to_logical(results.passed)) && ~any(to_logical(results.failed)) && ...
    ~any(to_logical(results.incomplete)) && ...
    double(summary.test_total)==height(results) && ...
    double(summary.test_passed)==height(results) && ...
    double(summary.test_failed)==0 && double(summary.test_incomplete)==0;
end

