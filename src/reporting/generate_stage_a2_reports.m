function xml = table_row_xml(values,widths,isHeader)
if isHeader
    rowPr='<w:trPr><w:tblHeader/><w:cantSplit/></w:trPr>';
    style='TableHeader'; shade='<w:shd w:val="clear" w:fill="F2F4F7"/>';
else
    rowPr='<w:trPr><w:cantSplit/></w:trPr>'; style='TableText'; shade='';
end
xml="<w:tr>"+string(rowPr);
for k=1:numel(widths)
    xml=xml+sprintf('<w:tc><w:tcPr><w:tcW w:w="%d" w:type="dxa"/>%s<w:vAlign w:val="center"/></w:tcPr>',widths(k),shade)+ ...
        paragraph_xml(values(k),style,'keepNext',isHeader)+"</w:tc>";
end
xml=xml+"</w:tr>";
end

function xml = paragraph_xml(textValue,styleName,varargin)
parser=inputParser; addParameter(parser,'keepNext',false,@islogical); parse(parser,varargin{:});
properties="<w:pPr><w:pStyle w:val="""+xml_escape(styleName)+"""/>";
if parser.Results.keepNext, properties=properties+"<w:keepNext/>"; end
properties=properties+"</w:pPr>";
xml="<w:p>"+properties+"<w:r><w:t xml:space=""preserve"">"+ ...
    xml_escape(textValue)+"</w:t></w:r></w:p>";
end

function write_docx(outputPath,titleText,subtitleText,facts,bodyXml)
assert(~isfile(outputPath)&&~isfolder(outputPath), ...
    'stageA2:report:ArtifactExists','Refusing to overwrite %s.',outputPath);
root=tempname; mkdir(root); guard=onCleanup(@()remove_tree(root));
mkdir(fullfile(root,'_rels')); mkdir(fullfile(root,'docProps'));
mkdir(fullfile(root,'word')); mkdir(fullfile(root,'word','_rels'));
write_utf8(fullfile(root,'[Content_Types].xml'),content_types_xml());
write_utf8(fullfile(root,'_rels','.rels'),root_relationships_xml());
write_utf8(fullfile(root,'docProps','core.xml'),core_properties_xml(titleText));
write_utf8(fullfile(root,'docProps','app.xml'),app_properties_xml());
write_utf8(fullfile(root,'word','styles.xml'),styles_xml());
write_utf8(fullfile(root,'word','settings.xml'),settings_xml());
write_utf8(fullfile(root,'word','header1.xml'),header_xml(facts.runId));
write_utf8(fullfile(root,'word','footer1.xml'),footer_xml(facts.runId));
write_utf8(fullfile(root,'word','_rels','document.xml.rels'), ...
    document_relationships_xml());
titleBlock=paragraph_xml('STAGE A2 · 算法验收备忘','MastheadKicker')+ ...
    paragraph_xml(titleText,'Title')+paragraph_xml(subtitleText,'Subtitle')+ ...
    metadata_xml('运行标识',facts.runId)+metadata_xml('阶段',facts.stageId)+ ...
    metadata_xml('Git 提交',facts.gitCommit)+ ...
    metadata_xml('报告生成时 manifest',facts.manifestStatus)+ ...
    metadata_xml('事实推导候选终态',facts.candidateStatus)+ ...
    paragraph_xml('','MastheadSpacer');
write_utf8(fullfile(root,'word','document.xml'),document_xml(titleBlock+bodyXml));
files={'[Content_Types].xml',fullfile('_rels','.rels'), ...
    fullfile('docProps','core.xml'),fullfile('docProps','app.xml'), ...
    fullfile('word','document.xml'),fullfile('word','styles.xml'), ...
    fullfile('word','settings.xml'),fullfile('word','header1.xml'), ...
    fullfile('word','footer1.xml'),fullfile('word','_rels','document.xml.rels')};
zipPath=[tempname(fileparts(outputPath)),'.zip'];
zipGuard=onCleanup(@()delete_if_exists(zipPath)); zip(zipPath,files,root);
[moved,message]=movefile(zipPath,outputPath);
assert(moved,'stageA2:report:PackageWriteFailed','%s',message);
clear zipGuard guard;
end

