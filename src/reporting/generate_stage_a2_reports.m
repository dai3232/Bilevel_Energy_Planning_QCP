    paragraph_xml(detailText,'CalloutText');
xml="<w:tbl>"+table_properties_xml()+ ...
    "<w:tblGrid><w:gridCol w:w=""9360""/></w:tblGrid>"+ ...
    "<w:tr><w:trPr><w:cantSplit/></w:trPr><w:tc><w:tcPr>"+ ...
    "<w:tcW w:w=""9360"" w:type=""dxa""/>"+ ...
    "<w:shd w:val=""clear"" w:fill=""E8EEF5""/>"+ ...
    "<w:vAlign w:val=""center""/></w:tcPr>"+body+ ...
    "</w:tc></w:tr></w:tbl>"+paragraph_xml('','TableSpacer');
end

function xml = table_xml(headers,rows,widths)
headers=string(headers(:)'); rows=string(rows);
if isempty(rows), rows=strings(0,numel(headers)); end
assert(size(rows,2)==numel(headers) && numel(widths)==numel(headers) && ...
    sum(widths)==9360,'stageA2:report:TableGeometry', ...
    'Table geometry must sum to 9360 DXA.');
grid=strings(1,numel(widths));
for k=1:numel(widths), grid(k)=sprintf('<w:gridCol w:w="%d"/>',widths(k)); end
xml="<w:tbl>"+table_properties_xml()+"<w:tblGrid>"+strjoin(grid,'')+ ...
    "</w:tblGrid>"+table_row_xml(headers,widths,true);
for row=1:size(rows,1), xml=xml+table_row_xml(rows(row,:),widths,false); end
xml=xml+"</w:tbl>"+paragraph_xml('','TableSpacer');
end

