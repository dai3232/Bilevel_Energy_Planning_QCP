function [reportPath,validation] = ...
        generate_stage_a4_iteration24_rank_report(runContext)
%GENERATE_STAGE_A4_ITERATION24_RANK_REPORT Build artifact-backed Chinese DOCX.
%
% Every numerical value is read back from the current diagnostic run.  The
% report explicitly distinguishes a successful root-cause replay from a
% Stage-A4 pass or a solver repair.

arguments
    runContext (1,1) struct
end
root = string(runContext.root);
diagnostics = fullfile(root,"diagnostics");
manifest = read_json(fullfile(root,"run_manifest.json"));
summary = read_json(fullfile(diagnostics,"diagnostic_summary.json"));
identity = read_json(fullfile(diagnostics,"replay_identity.json"));
blocksTable = read_csv(fullfile(diagnostics,"block_summary.csv"));
nearNull = read_csv(fullfile(diagnostics,"near_null_components.csv"));
curvature = read_csv(fullfile(diagnostics,"curvature_sources.csv"));
scale = read_csv(fullfile(diagnostics,"scaling_trace.csv"));
factor = read_csv(fullfile(diagnostics,"factor_solve_comparison.csv"));
acceptance = read_csv(fullfile(root,"acceptance","acceptance_results.csv"));
issues = read_csv(fullfile(root,"issues","issue_log.csv"));
inputHashes = read_csv(fullfile(root,"input_hashes.csv"));
testSummary = read_json(fullfile(root,"tests","test_summary.json"));

assert(string(manifest.status)=="RUNNING" && ...
    string(manifest.stage_id)=="stage_A4" && ...
    string(summary.diagnostic_status)=="PASS" && ...
    ~logical(summary.stage_a4_pass_claimed), ...
    "stageA4:iter24:ReportFacts", ...
    "The persisted iteration-24 diagnostic facts are inconsistent.");

reportPath = fullfile(root,"reports", ...
    "阶段A4_第24轮病态矩阵受控重放与根因判定报告.docx");
assert(~isfile(reportPath)&&~isfolder(reportPath), ...
    "stageA4:iter24:ReportExists", ...
    "Refusing to overwrite %s.",reportPath);
metadata = struct( ...
    "run_id",string(runContext.run_id), ...
    "stage_id","stage_A4", ...
    "git_commit",string(manifest.git_commit), ...
    "manifest_status","RUNNING", ...
    "candidate_status","诊断PASS；Stage A4仍被阻断", ...
    "report_kicker","STAGE A4 · 第24轮数值秩根因审计", ...
    "header_label","STAGE A4 · 第24轮病态矩阵受控重放");
blocks = build_blocks(summary,identity,blocksTable,nearNull, ...
    curvature,scale,factor,acceptance,issues,inputHashes,testSummary);
write_stage_a4_docx(reportPath, ...
    "阶段A4 第24轮病态矩阵受控重放与根因判定报告", ...
    "第23轮已接受状态 · day 14 / hour 3 · 只读线性代数诊断", ...
    metadata,blocks);
[valid,validation] = validate_docx_package(reportPath);
requiredText = [ ...
    "结构真奇异"; ...
    "数值秩"; ...
    "没有更新任何状态"; ...
    "Stage A4 仍为 READY"; ...
    "未实施修复"];
for k=1:numel(requiredText)
    valid = valid && contains(validation.document_text,requiredText(k));
    if ~contains(validation.document_text,requiredText(k))
        validation.errors(end+1) = ...
            "Missing required report statement: "+requiredText(k);
    end
end
assert(valid,"stageA4:iter24:ReportValidation", ...
    "Iteration-24 diagnostic DOCX structural/content validation failed: %s", ...
    strjoin(validation.errors,"; "));
end

function blocks = build_blocks(summary,identity,blockTable,nearNull, ...
        curvature,scale,factor,acceptance,issues,inputHashes,testSummary)
blocks = empty_blocks();
blocks(end+1) = callout_block("根因判定", ...
    "冻结的双精度系数在80位重算中仍为满秩，因此不是模型结构真奇异。"+ ...
    "Thomas前向消元把SOC等式乘子方向放大到约1e7，而无目标二阶曲率的"+ ...
    "小时原变量仅保留约1e-8至1e-7的障碍曲率；默认数值秩和零主元阈值"+ ...
    "遂把非零方向判为零。");

blocks(end+1) = heading_block("一、权威状态与执行边界",1);
blocks(end+1) = table_block(["项目","持久化事实"],[ ...
    "父运行",string(identity.authority_run_id); ...
    "父状态修订 / 尝试轮次", ...
        string(identity.state_revision)+" / "+ ...
        string(identity.attempted_iteration); ...
    "状态指纹",string(identity.state_fingerprint); ...
    "线性化指纹",string(identity.linearization_fingerprint); ...
    "失败证据SHA256",string(identity.failure_evidence_sha256); ...
    "诊断代码提交",string(identity.current_commit); ...
    "状态更新 / 完成方向","0 / 0"; ...
    "完整KKT用途","仅独立审计，未被递推路线消费"],[3000 6360]);
blocks(end+1) = paragraph_block( ...
    "本次只重放第24轮方向形成过程，没有更新任何状态，没有执行完整IPM、"+ ...
    "优化、并行或Stage B；诊断性未门禁LDL和合同尺度化均未进入正式方向。");
blocks(end+1) = heading_block("受控输入哈希",2);
inputRows = strings(height(inputHashes),3);
for k=1:height(inputHashes)
    inputRows(k,:) = [string(inputHashes.fileName(k)), ...
        string(inputHashes.actualSHA256(k)),string(inputHashes.status(k))];
end
blocks(end+1) = table_block(["文件","实际SHA256","状态"], ...
    inputRows,[2200 5500 1660]);

blocks(end+1) = heading_block("二、失败层级与谱演化",1);
rows = strings(height(blockTable),7);
for k=1:height(blockTable)
    rows(k,:) = [ ...
        string(blockTable.hour(k)), ...
        string(blockTable.raw_rank(k)), ...
        string(blockTable.schur_rank(k)), ...
        f(blockTable.schur_condition_2(k)), ...
        f(blockTable.schur_smin(k)), ...
        f(blockTable.rank_tolerance(k)), ...
        string(blockTable.singular_values_below_rank_tolerance(k))];
end
blocks(end+1) = table_block( ...
    ["小时","原块秩","主元秩","主元cond2","最小奇异值","rank阈值","阈值下数量"], ...
    rows,[700 900 900 1750 1700 1700 1710]);
h2 = blockTable(blockTable.hour==2,:);
h3 = blockTable(blockTable.hour==3,:);
blocks(end+1) = paragraph_block( ...
    "第2小时已经处在门槛边缘：最小奇异值/rank阈值="+ ...
    f(h2.schur_smin/h2.rank_tolerance)+"。第3小时最大奇异值增至"+ ...
    f(h3.schur_smax)+"，rank阈值随之升至"+f(h3.rank_tolerance)+ ...
    "，超过5个仍非零的小奇异值，生产门禁因此报告17/22。");

blocks(end+1) = heading_block("三、主导坐标与曲率来源",1);
leaders = nearNull(nearNull.loading_order<=2,:);
leaderRows = strings(height(leaders),6);
for k=1:height(leaders)
    leaderRows(k,:) = [string(leaders.mode(k)), ...
        f(leaders.singular_value(k)), ...
        string(leaders.loading_order(k)), ...
        string(leaders.identifier(k))+" / "+ ...
            string(leaders.asset_type(k))+ ...
            string(leaders.asset_id(k)), ...
        f(leaders.coefficient(k)), ...
        f(leaders.equality_energy(k))];
end
blocks(end+1) = table_block( ...
    ["模态","奇异值","次序","坐标","载荷","等式乘子能量"], ...
    leaderRows,[700 1500 700 2600 1500 2360]);
blocks(end+1) = paragraph_block( ...
    "5个门槛下模态的能量几乎全部位于小时原变量，不是3条等式乘子方向；"+ ...
    "最小模态主要是两台同参数火电出力的相反方向。");
blocks(end+1) = table_block(["曲率审计","实际范围"],[ ...
    "小时变量目标Hessian对角","全部为0"; ...
    "障碍约化W对角", ...
        f(min(curvature.w_diagonal))+" ～ "+ ...
        f(max(curvature.w_diagonal)); ...
    "第3小时主元最大奇异值",f(summary.hour3_smax)], ...
    [3600 5760]);

blocks(end+1) = heading_block("四、80位重算与尺度反事实",1);
lastScale = scale(end,:);
blocks(end+1) = table_block(["证据","未尺度化","8遍合同尺度反事实"],[ ...
    "数值秩",string(summary.hour3_numeric_rank), ...
        string(lastScale.numeric_rank); ...
    "cond2",f(summary.hour3_condition_2), ...
        f(lastScale.condition_2); ...
    "最大奇异值",f(summary.hour3_smax),f(lastScale.smax); ...
    "最小奇异值",f(summary.hour3_smin),f(lastScale.smin); ...
    "rank阈值下奇异值数量", ...
        string(summary.hour3_singular_values_below_rank_tolerance), ...
        string(lastScale.below_rank_tolerance)], ...
    [3000 3180 3180]);
blocks(end+1) = paragraph_block( ...
    "80位重算的最小绝对特征值为"+ ...
    f(summary.high_precision_s3_smin)+"，明确非零；其cond2仍约"+ ...
    f(summary.high_precision_s3_condition_2)+"，说明病态谱宽来自冻结系数"+ ...
    "和消元结构，而不是双精度形成Schur矩阵时的偶然舍入。只读合同尺度"+ ...
    "反事实把cond2降低约"+f(summary.condition_reduction_factor)+ ...
    "倍并恢复22维数值秩；这只是根因证据，未实施修复。");

blocks(end+1) = heading_block("五、求解与完整KKT独立审计",1);
factorRows = strings(height(factor),4);
for k=1:height(factor)
    factorRows(k,:) = [string(factor.route(k)), ...
        f(factor.original_operator_relative_residual(k)), ...
        f(factor.relative_error_to_high_precision(k)), ...
        string(factor.used_for_formal_direction(k))];
end
blocks(end+1) = table_block( ...
    ["诊断路线","原算子残差","对80位参考误差","进入正式方向"], ...
    factorRows,[2800 2300 2300 1960]);
blocks(end+1) = paragraph_block( ...
    "未门禁双精度LDL在本组15个右端上仍给出约机器精度的原算子残差，"+ ...
    "所以本次停止点首先是保守的rank/零主元判据被尺度触发；这不等于可"+ ...
    "直接删除门禁。完整18836维稀疏KKT仅独立审计，残差="+ ...
    f(summary.full_kkt_relative_residual)+"，方向未被递推路线消费。");

blocks(end+1) = heading_block("六、测试、问题与下一步",1);
blocks(end+1) = table_block(["项目","结果"],[ ...
    "专项测试",string(testSummary.test_passed)+"/"+ ...
        string(testSummary.test_total)+" PASS"; ...
    "诊断验收",string(nnz(string(acceptance.status)=="PASS"))+"/"+ ...
        string(height(acceptance))+" PASS"; ...
    "未解决问题",string(height(issues))+ ...
        "项，继续阻断Stage A4"; ...
    "阶段状态","stage_A4 / READY"],[3300 6060]);
blocks(end+1) = callout_block("停止边界与建议", ...
    "本报告完成的是根因判定，不是数值修复。Stage A4 仍为 READY，"+ ...
    "不得把诊断PASS写成阶段PASS。下一独立里程碑应在不改模型、sigma、"+ ...
    "tau、初始化和步长的条件下，对局部对称对角合同尺度化做统一实现与"+ ...
    "冻结压力测试，并继续用原始未尺度化算子审计残差；不得正则化、自动"+ ...
    "对称化或完整KKT方向回退。");
end

function blocks = empty_blocks()
blocks = repmat(block_template(),0,1);
end
function value = block_template()
value = struct("type","","level",0,"title","","text","", ...
    "headers",strings(1,0),"rows",strings(0,0), ...
    "widths",zeros(1,0));
end
function block = heading_block(textValue,level)
block=block_template(); block.type="heading";
block.text=string(textValue); block.level=level;
end
function block = paragraph_block(textValue)
block=block_template(); block.type="paragraph"; block.text=string(textValue);
end
function block = callout_block(titleText,textValue)
block=block_template(); block.type="callout";
block.title=string(titleText); block.text=string(textValue);
end
function block = table_block(headers,rows,widths)
block=block_template(); block.type="table";
block.headers=string(headers); block.rows=string(rows);
block.widths=double(widths);
assert(sum(block.widths)==9360, ...
    "stageA4:iter24:ReportTableWidth", ...
    "Diagnostic report tables must total 9360 DXA.");
end

function value = f(number)
if isnan(double(number))
    value="不适用";
else
    value=string(sprintf("%.17g",double(number)));
end
end
function value = read_json(pathValue)
assert(isfile(pathValue),"stageA4:iter24:ReportInput", ...
    "Missing report input %s.",pathValue);
value=jsondecode(fileread(pathValue));
end
function value = read_csv(pathValue)
assert(isfile(pathValue),"stageA4:iter24:ReportInput", ...
    "Missing report input %s.",pathValue);
opts=detectImportOptions(pathValue,"TextType","string", ...
    "VariableNamingRule","preserve");
value=readtable(pathValue,opts);
end
