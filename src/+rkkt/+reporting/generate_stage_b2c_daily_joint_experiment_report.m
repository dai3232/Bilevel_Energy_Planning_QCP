function report = generate_stage_b2c_daily_joint_experiment_report(runRoot)
%GENERATE_STAGE_B2C_DAILY_JOINT_EXPERIMENT_REPORT Build the Chinese report.

arguments
    runRoot (1,1) string
end

manifest = jsondecode(fileread(fullfile(runRoot,"run_manifest.json")));
identity = read_csv(fullfile(runRoot,"diagnostics", ...
    "checkpoint_identity.csv"));
gate = read_csv(fullfile(runRoot,"diagnostics","single_day_gate.csv"));
days = read_csv(fullfile(runRoot,"diagnostics", ...
    "daily_joint_block_diagnostics.csv"));
directions = read_csv(fullfile(runRoot,"diagnostics", ...
    "direction_equivalence.csv"));
timing = read_csv(fullfile(runRoot,"diagnostics","solver_timing.csv"));
acceptance = read_csv(fullfile(runRoot,"acceptance", ...
    "acceptance_results.csv"));
tests = jsondecode(fileread(fullfile(runRoot,"tests","test_summary.json")));
analyzer = read_csv(fullfile(runRoot,"tests","code_analyzer.csv"));

passed = ~isempty(acceptance) && all(string(acceptance.status)=="PASS");
if passed
    conclusion = "冻结点实验通过：完全消去全部不等式方向后，最差单日日内联合块可用一次稀疏LDL完成15列右端求解；七天均形成14维响应并汇总到16维核心，恢复后的完整方向在控制点和压力点均满足既有方向与完整KKT残差阈值。";
    candidateStatus = "PASS（仅冻结方向实验）";
else
    conclusion = "冻结点实验未通过。运行已在首个阻断位置停止，未使用正则化、伪逆、完整方向回退或状态更新；具体阻断项见验收表和问题日志。";
    candidateStatus = "未通过（以run_manifest终态为准）";
end

metadata = struct("run_id",string(manifest.run_id), ...
    "stage_id","stage_B / B-2C", ...
    "git_commit",string(manifest.git_commit), ...
    "manifest_status",string(manifest.status), ...
    "candidate_status",candidateStatus, ...
    "report_kicker","STAGE B-2C · 冻结Newton方向实验", ...
    "header_label","STAGE B-2C · 日内联合与16维核心");

blocks = repmat(block_template(),0,1);
blocks(end+1) = callout_block("实验结论",conclusion);
blocks(end+1) = heading_block(1,"1. 输入冻结与执行边界");
blocks(end+1) = table_block( ...
    ["点位","检查点修订","方向编号","状态指纹","线性化指纹一致"], ...
    select_rows(identity,["point","checkpoint_revision", ...
        "direction_number","state_fingerprint","fingerprint_match"]), ...
    [1000,1300,1100,4560,1400]);
blocks(end+1) = paragraph_block( ...
    "控制点使用iteration_033状态计算第34次方向；压力点使用iteration_034状态计算第35次方向。数据来自既有PKG数据模块MAT，索引和配置来自历史门禁MAT；未重新读取Excel，未执行IPM状态更新。" );

blocks(end+1) = heading_block(1,"2. 最差单日日块门禁");
blocks(end+1) = table_block( ...
    ["点位","日","维数","nnz","结构秩","15列最大残差","最小主元","状态"], ...
    select_rows(gate,["point","day_id","dimension","nnz", ...
        "structural_rank","maximum_rhs_relative_residual", ...
        "minimum_absolute_pivot","status"]), ...
    [800,650,800,900,900,1900,1600,1810]);
blocks(end+1) = paragraph_block( ...
    "单日日块由q_day、pi_day及24小时原始变量/等式乘子联合组成；水量Δl、Δz已完全消元，显式水量eta维数为0。" );

blocks(end+1) = heading_block(1,"3. 七日日块与16维核心");
blocks(end+1) = table_block( ...
    ["点位","日","日块维数","nnz","结构秩","最大右端残差","水量eta维数"], ...
    select_rows(days,["point","day_id","dimension","nnz", ...
        "structural_rank","maximum_rhs_relative_residual", ...
        "water_eta_dimension"]), ...
    [900,650,1150,1100,1100,2500,1960]);

blocks(end+1) = heading_block(1,"4. 完整方向等价性");
blocks(end+1) = table_block( ...
    ["点位","路线","方向误差","候选KKT残差","完整KKT残差","状态"], ...
    select_rows(directions,["point","route", ...
        "direction_relative_error","candidate_kkt_relative_residual", ...
        "full_kkt_relative_residual","status"]), ...
    [950,1800,1700,1900,1700,1310]);
blocks(end+1) = paragraph_block( ...
    "完整KKT仅在计时区间之外生成独立参考方向。压力点旧递推方向若未通过审计，其耗时只作为被拒绝方向耗时，不作为有效求解速度。" );

blocks(end+1) = heading_block(1,"5. 单次求解速度");
blocks(end+1) = table_block( ...
    ["点位","路线","预热次数","正式次数","正式求解秒数","方向有效"], ...
    select_rows(timing,["point","route","warmup_count", ...
        "timed_count","formal_seconds","direction_accepted"]), ...
    [900,1900,1100,1100,2000,2360]);
blocks(end+1) = paragraph_block( ...
    "每条路线在每个冻结点预热1次且不计时，随后正式计时1次。计时从已有linearization开始，到完整Δxi/Δy/Δl/Δz组装结束；MAT读取、完整KKT审计、误差比较、写盘和报告均不计入。" );

blocks(end+1) = heading_block(1,"6. 定向测试、Code Analyzer与阶段边界");
summaryRows = ["定向测试总数",number_text(tests.test_total); ...
    "定向测试通过",number_text(tests.test_passed); ...
    "Code Analyzer文件数",number_text(height(analyzer)); ...
    "Code Analyzer问题数", ...
        number_text(sum(double(analyzer.finding_count))); ...
    "完整IPM","未执行";"状态更新","未执行"; ...
    "Stage C1","未进入"];
blocks(end+1) = table_block(["项目","实际值"],summaryRows,[4300,5060]);
blocks(end+1) = table_block(["验收项","实际值","门槛","状态"], ...
    select_rows(acceptance,["check_id","actual_value","threshold","status"]), ...
    [2300,3300,2200,1560]);

outputPath = fullfile(runRoot,"reports", ...
    "阶段B-2C_日内联合方向冻结点实验报告.docx");
rkkt.reporting.write_stage_b2c_docx(outputPath, ...
    "阶段B-2C：日内联合方向冻结点实验报告", ...
    "第34次方向控制点 · 第35次方向压力点 · 完整方向与单次速度", ...
    metadata,blocks);
report = struct("path",string(outputPath), ...
    "run_id",string(manifest.run_id),"status","GENERATED", ...
    "design_preset","standard_business_brief", ...
    "header_pattern","memo_masthead");
end

function value = read_csv(pathValue)
value = readtable(pathValue,detectImportOptions(pathValue, ...
    "Delimiter",",","TextType","string", ...
    "VariableNamingRule","preserve"));
end

function rows = select_rows(source,names)
rows = strings(height(source),numel(names));
for column = 1:numel(names)
    value = source.(names(column));
    if isnumeric(value) || islogical(value)
        rows(:,column) = compose("%.17g",double(value));
    else
        rows(:,column) = string(value);
    end
end
end

function value = number_text(number)
value = compose("%.17g",double(number));
end

function value = block_template()
value = struct("type","","level",0,"text","","title","", ...
    "headers",strings(1,0),"rows",strings(0,0),"widths",zeros(1,0));
end

function value = heading_block(level,textValue)
value = block_template();
value.type = "heading";
value.level = level;
value.text = string(textValue);
end

function value = paragraph_block(textValue)
value = block_template();
value.type = "paragraph";
value.text = string(textValue);
end

function value = callout_block(titleValue,textValue)
value = block_template();
value.type = "callout";
value.title = string(titleValue);
value.text = string(textValue);
end

function value = table_block(headers,rows,widths)
value = block_template();
value.type = "table";
value.headers = reshape(string(headers),1,[]);
value.rows = string(rows);
value.widths = reshape(double(widths),1,[]);
assert(size(value.rows,2)==numel(value.headers) && ...
    numel(value.widths)==numel(value.headers) && ...
    sum(value.widths)==9360, ...
    "stageB2C:dailyJoint:ReportTable", ...
    "Report table geometry must total 9360 DXA.");
end
