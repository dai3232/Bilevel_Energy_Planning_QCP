function report = generate_stage_b2c_water_correction_experiment_report(runRoot)
%GENERATE_STAGE_B2C_WATER_CORRECTION_EXPERIMENT_REPORT Build Chinese report.

arguments
    runRoot (1,1) string
end

manifest = jsondecode(fileread(fullfile(runRoot,"run_manifest.json")));
initial = read_csv(fullfile(runRoot,"diagnostics","initial_metrics.csv"));
iterations = read_csv(fullfile(runRoot,"diagnostics","iteration_history.csv"));
factors = read_csv(fullfile(runRoot,"diagnostics", ...
    "daily_joint_factorization_history.csv"));
acceptance = read_csv(fullfile(runRoot,"acceptance", ...
    "acceptance_results.csv"));
analyzer = read_csv(fullfile(runRoot,"tests","code_analyzer.csv"));
terminal = string(manifest.experimental_solver_terminal_state);
physicalPass = logical(manifest.experimental_physical_audit_passed);
if terminal=="CONVERGED" && physicalPass
    conclusion = "实验成功：从权威运行第27次检查点续算时，精确水量二阶松弛校正使四项冻结收敛判据在第17日日块出现数值零主元之前全部通过。该结论只针对隔离实验；正式B-2C入口、模型、阈值和生产状态均未改变。";
else
    conclusion = "实验未形成可接受收敛结果。水量二阶松弛校正未被写入正式B-2C入口，现有正式求解状态保持不变。";
end

metadata = struct("run_id",string(manifest.run_id), ...
    "stage_id","stage_B / B-2C isolated experiment", ...
    "git_commit",string(manifest.git_commit), ...
    "manifest_status",string(manifest.milestone_status), ...
    "candidate_status",terminal, ...
    "report_kicker","STAGE B-2C · 水量二阶松弛校正", ...
    "header_label","STAGE B-2C · 隔离续算实验");

blocks = repmat(block_template(),0,1);
blocks(end+1) = callout_block("实验结论",conclusion);

blocks(end+1) = heading_block(1,"1. 实验边界");
blocks(end+1) = paragraph_block( ...
    "实验从既有权威运行的已接受检查点出发，继续使用同一数据、同一模型、同一四项停止阈值、同一递推方向和同一独立完整KKT审计。唯一新增操作发生在一次普通Newton更新之后：只校正56条二次日水量约束的松弛变量。" );
blocks(end+1) = table_block(["项目","实际值"],[ ...
    "源run",string(manifest.source_run_id); ...
    "源检查点",string(manifest.source_checkpoint_revision); ...
    "源等价首轮",string(double(manifest.source_checkpoint_revision)+1); ...
    "正式求解器修改","否";"正式入口修改","否"; ...
    "目标函数/模型口径修改","否";"步长修改","否"; ...
    "生产fallback新增","否"],[3000,6360]);

blocks(end+1) = heading_block(1,"2. 校正公式与作用范围");
blocks(end+1) = paragraph_block( ...
    "对每条二次水量不等式g(x)≤0，普通更新先得到x⁺=x+αΔx和l_trial=l+αΔl。随后精确计算二阶余项q=g(x⁺)-g(x)-αGΔx，并令l_corrected=l_trial-q。因此校正后的水量残差严格回到(1-α)(g(x)+l)，只消除非线性Taylor余项，不删除物理约束，也不把l直接重置为-g(x)。" );
blocks(end+1) = paragraph_block( ...
    "未改变的量包括：全部原变量xi、等式乘子y、不等式乘子z、7248条非水量松弛、递推Newton方向、完整KKT审计方向以及原fraction-to-boundary步长。若任一校正水量松弛不再严格为正，实验直接失败，不使用兼容或兜底分支。" );

blocks(end+1) = heading_block(1,"3. 起点与首轮直接对比");
blocks(end+1) = table_block(["点位","等式残差","不等式残差", ...
    "对偶残差","平均l·z","水量越界"], ...
    select_rows(initial,["point","primal_equality_inf", ...
    "primal_inequality_inf","dual_scaled_inf", ...
    "mean_lz_scaled","maximum_water_violation"]), ...
    [1500,1550,1650,1550,1550,1560]);
if ~isempty(iterations)
    first = iterations(1,:);
    firstRows = [ ...
        "普通更新后的不等式残差",first.uncorrected_primal_inequality_inf; ...
        "二阶校正后的不等式残差",first.primal_inequality_inf; ...
        "最大水量二阶余项",first.maximum_absolute_water_remainder; ...
        "最大校正闭合误差",first.maximum_water_closure_error; ...
        "校正后最小水量松弛",first.minimum_corrected_water_l];
    blocks(end+1) = table_block(["首轮指标","实际值"], ...
        string(firstRows),[4400,4960]);
end

blocks(end+1) = heading_block(1,"4. 连续续算与第17日主元");
outcomeRows = [ ...
    "实验终态",terminal; ...
    "已接受实验更新",string(manifest.accepted_iteration_count); ...
    "对应源累计更新数",string(manifest.final_source_equivalent_revision); ...
    "最终等式残差",number_field(manifest,"final_primal_equality_inf"); ...
    "最终不等式残差",number_field(manifest,"final_primal_inequality_inf"); ...
    "最终对偶残差",number_field(manifest,"final_dual_scaled_inf"); ...
    "最终平均l·z",number_field(manifest,"final_mean_lz_scaled"); ...
    "最终水量物理越界",number_field(manifest,"final_maximum_water_violation"); ...
    "最终第17日零主元数",number_field(manifest, ...
        "final_day17_numerical_zero_pivot_count")];
blocks(end+1) = table_block(["指标","实际值"],outcomeRows,[3900,5460]);
if ~isempty(iterations)
    blocks(end+1) = table_block(["实验轮次","源等价轮次","校正前残差", ...
        "校正后残差","平均l·z","第17日最小主元","零主元数"], ...
        select_rows(iterations,["experiment_iteration", ...
        "source_equivalent_revision","uncorrected_primal_inequality_inf", ...
        "primal_inequality_inf","mean_lz_scaled", ...
        "day17_minimum_absolute_pivot", ...
        "day17_numerical_zero_pivot_count"]), ...
        [750,900,1500,1500,1300,2210,1200]);
end
day17 = factors(double(factors.day_id)==17,:);
if ~isempty(day17)
    blocks(end+1) = paragraph_block( ...
        "第17日主元表记录的是每轮方向求解时、尚未施加该轮松弛校正前的联合日块LDL结果。因此它直接回答校正轨迹是否在零主元阻断之前达到收敛。" );
end

blocks(end+1) = heading_block(1,"5. 实际启用与未启用内容");
blocks(end+1) = paragraph_block( ...
    "实际启用：第14—20日统一容量投资目标、小时功率平衡、SOC日内递推与每日0.5E闭合、储能时长等式、风光水火储小时边界、四座水电每日水量上下限、全不等式消元、七个日内联合块、16维全局核心、逐轮独立完整KKT审计，以及本实验的56条水量松弛精确二阶校正。" );
blocks(end+1) = paragraph_block( ...
    "明确未启用：改变目标函数、改变水量口径、动态sigma、预测—校正方向、非线性线搜索、正则化、伪逆、完整KKT方向回退、前一日结果替代、并行、Stage C1，以及对正式B-2C入口的任何集成。" );

blocks(end+1) = heading_block(1,"6. 验收与验证范围");
blocks(end+1) = table_block(["验收项","实际值","门限","状态"], ...
    select_rows(acceptance,["check_id","actual_value", ...
    "threshold","status"]),[1900,3300,2500,1660]);
blocks(end+1) = table_block(["文件","Code Analyzer问题数","状态"], ...
    select_rows(analyzer,["file","finding_count","status"]), ...
    [6100,1800,1460]);
blocks(end+1) = paragraph_block( ...
    "本次为隔离数值实验，执行了新增核心函数定向单测、源检查点哈希复核、逐轮递推/完整KKT方向等价审计、56行校正闭合与正值审计、最终四项停止判据和物理可行性审计。未运行全量测试、完整构建、全量lint或E2E。" );

blocks(end+1) = heading_block(1,"7. 结论边界与下一步");
if terminal=="CONVERGED" && physicalPass
    blocks(end+1) = paragraph_block( ...
        "实验结果支持的结论是：当前慢残差主要由二次水量约束的Taylor余项反复注入；精确校正该余项可以让算法在第17日储能交换零模态数值显化之前满足原冻结停止判据。它不证明零模态从数学上消失，也不自动授权写入正式求解器。下一步如决定采用，应将同一校正以显式配置和正式验收集成，再从第0次状态运行全新B-2C。" );
else
    blocks(end+1) = paragraph_block( ...
        "实验未证明该方法足以通过现有阻断。正式代码保持不变，后续需要依据失败迭代、闭合或正值证据重新讨论算法选择。" );
end

outputPath = fullfile(runRoot,"reports", ...
    "阶段B-2C_水量二阶松弛校正实验报告.docx");
rkkt.reporting.write_stage_b2c_docx(outputPath, ...
    "阶段B-2C：水量二阶松弛校正实验报告", ...
    "从权威检查点续算 · 保持正式模型与停止阈值不变 · 隔离算法实验", ...
    metadata,blocks);
report = struct("path",string(outputPath), ...
    "run_id",string(manifest.run_id),"status","GENERATED", ...
    "design_preset","standard_business_brief", ...
    "header_pattern","memo_masthead");
end

function value = read_csv(pathValue)
options = detectImportOptions(pathValue,"Delimiter",",", ...
    "TextType","string","VariableNamingRule","preserve");
options.VariableNamesLine = 1;
options.VariableUnitsLine = 0;
options.VariableDescriptionsLine = 0;
options.DataLines = [2,Inf];
options = setvartype(options,options.VariableNames,"string");
value = readtable(pathValue,options);
end

function rows = select_rows(source,names)
rows = strings(height(source),numel(names));
for column = 1:numel(names)
    rows(:,column) = string(source.(names(column)));
end
end

function value = number_field(manifest,name)
if isfield(manifest,name)
    value = compose("%.17g",double(manifest.(name)));
else
    value = "未记录";
end
end

function value = block_template()
value = struct("type","","level",0,"text","","title","", ...
    "headers",strings(1,0),"rows",strings(0,0),"widths",zeros(1,0));
end

function value = heading_block(level,textValue)
value = block_template(); value.type = "heading";
value.level = level; value.text = string(textValue);
end

function value = paragraph_block(textValue)
value = block_template(); value.type = "paragraph";
value.text = string(textValue);
end

function value = callout_block(titleValue,textValue)
value = block_template(); value.type = "callout";
value.title = string(titleValue); value.text = string(textValue);
end

function value = table_block(headers,rows,widths)
value = block_template(); value.type = "table";
value.headers = reshape(string(headers),1,[]);
value.rows = string(rows); value.widths = reshape(double(widths),1,[]);
assert(size(value.rows,2)==numel(value.headers) && ...
    numel(value.widths)==numel(value.headers) && ...
    sum(value.widths)==9360, ...
    "stageB2C:waterCorrection:ReportTable", ...
    "Report table geometry must total 9360 DXA.");
end
