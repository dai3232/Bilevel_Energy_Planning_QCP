function value = logical_text(input)
if input
    value = "true";
else
    value = "false";
end
end

function value = numeric_text(input)
value = string(compose("%.17g",input));
end

function fig = trajectory_figure(trajectory,interactive)
fig = rkkt.ipm.validation.ValidationSupport.newFigure( ...
    "IPM受控轨迹",interactive);
layout = tiledlayout(fig,1,2,"TileSpacing","compact", ...
    "Padding","compact");
nexttile(layout);
semilogy(trajectory.previewIteration,trajectory.alphaPrimal, ...
    "-o","LineWidth",1.2);
hold on;
semilogy(trajectory.previewIteration,trajectory.alphaDual, ...
    "-s","LineWidth",1.2);
hold off;
xticks(trajectory.previewIteration);
xlabel("受控预览轮次");
ylabel("步长（对数轴）");
title("独立原始与对偶步长");
legend(["alphaPrimal","alphaDual"],"Location","best");
