function value = state_change_summary(step)
names = ["xi";"y";"l";"z"];
before = {step.state_before.xi;step.state_before.y; ...
    step.state_before.l;step.state_before.z};
after = {step.state_after.xi;step.state_after.y; ...
    step.state_after.l;step.state_after.z};
direction = {step.recursive.components.xi; ...
    step.recursive.components.y;step.recursive.components.l; ...
    step.recursive.components.z};
alpha = [ ...
    step.applied_step.applied_alpha_primal; ...
    step.applied_step.applied_alpha_dual; ...
    step.applied_step.applied_alpha_primal; ...
    step.applied_step.applied_alpha_dual];
dimension = reshape(cellfun(@numel,before),[],1);
normBefore = reshape(cellfun(@(item)norm(item,2),before),[],1);
normAfter = reshape(cellfun(@(item)norm(item,2),after),[],1);
deltaNorm = reshape(cellfun(@(left,right) ...
    norm(right-left,2),before,after),[],1);
maximumAbsoluteDelta = reshape(cellfun(@(left,right) ...
    max(abs(right-left)),before,after),[],1);
updateExact = false(4,1);
for k = 1:4
    updateExact(k) = isequaln(after{k}, ...
        before{k}+alpha(k)*direction{k});
end
value = table(names,dimension,normBefore,normAfter,deltaNorm, ...
    maximumAbsoluteDelta,alpha,updateExact, ...
    'VariableNames',{'component','dimension','normBefore', ...
    'normAfter','deltaNorm','maximumAbsoluteDelta','alpha', ...
    'updateExact'});
end

function value = residual_step_summary(step)
phase = ["before";"after"];
before = step.residuals.before;
after = step.residuals.after;
equalityInf = [before.equality_inf;after.equality_inf];
slackEqualityInf = [ ...
    before.slack_equality_inf;after.slack_equality_inf];
dualInf = [before.dual_inf;after.dual_inf];
complementarityInf = [ ...
    before.complementarity_inf;after.complementarity_inf];
complementarityGap = [ ...
    before.complementarity_gap;after.complementarity_gap];
minimumL = [before.minimum_l;after.minimum_l];
minimumZ = [before.minimum_z;after.minimum_z];
alphaPrimal = repmat( ...
    step.applied_step.applied_alpha_primal,2,1);
alphaDual = repmat( ...
    step.applied_step.applied_alpha_dual,2,1);
directionRelativeError = repmat( ...
    step.direction_audit.direction_relative_error,2,1);
recursiveKktRelativeResidual = repmat( ...
    step.direction_audit.recursive_kkt_relative_residual,2,1);
allPass = repmat(step.all_pass,2,1);
value = table(phase,equalityInf,slackEqualityInf,dualInf, ...
    complementarityInf,complementarityGap,minimumL,minimumZ, ...
    alphaPrimal,alphaDual,directionRelativeError, ...
    recursiveKktRelativeResidual,allPass);
end

function fig = step_figure(stateSummary,residualSummary,interactive)
fig = rkkt.validation.newFigure( ...
    "IPM单步状态更新",interactive);
layout = tiledlayout(fig,1,2,"TileSpacing","compact", ...
    "Padding","compact");
nexttile(layout);
semilogy(1:height(stateSummary), ...
    max(stateSummary.deltaNorm,realmin),"-o","LineWidth",1.4);
xticks(1:height(stateSummary));
xticklabels(stateSummary.component);
ylabel("状态变化二范数");
title("独立原始/对偶步长更新");
grid on;
nexttile(layout);
metrics = [residualSummary.equalityInf, ...
    residualSummary.dualInf, ...
    residualSummary.complementarityInf, ...
    residualSummary.complementarityGap];
semilogy(1:2,max(metrics,realmin),"-o","LineWidth",1.2);
xticks(1:2);
xticklabels(residualSummary.phase);
ylabel("残差或间隙");
title("单步前后残差摘要");
legend(["r_{eq}","r_{dual}","r_{comp}","mean(lz)"], ...
    "Location","best");
grid on;
end
