function [data,correction] = apply_stage_b2c_load_corrections( ...
        data,correctionPath)
%APPLY_STAGE_B2C_LOAD_CORRECTIONS Apply the reviewed load overlay.

arguments
    data (1,1) struct
    correctionPath (1,1) string
end
correctionPath = string(java.io.File(char(correctionPath)).getCanonicalPath());
assert(isfile(correctionPath),"rkkt:data:LoadCorrectionMissing", ...
    "The load-correction table is missing: %s",correctionPath);
rows = readtable(correctionPath,"TextType","string", ...
    "VariableNamingRule","preserve","Encoding","UTF-8");
required = ["day","hour","original_load_mw","corrected_load_mw", ...
    "reduction_mw","reason","margin_fraction", ...
    "estimated_boundary_load_mw", ...
    "requires_water_coupled_validation"];
assert(isequal(string(rows.Properties.VariableNames),required), ...
    "rkkt:data:LoadCorrectionSchema", ...
    "The load-correction table does not match the frozen column schema.");

day = double(rows.day);
hour = double(rows.hour);
original = double(rows.original_load_mw);
corrected = double(rows.corrected_load_mw);
reduction = double(rows.reduction_mw);
assert(~isempty(day) && all(isfinite([day;hour;original;corrected;reduction])) && ...
    all(day==fix(day) & day>=1 & day<=data.meta.nDays) && ...
    all(hour==fix(hour) & hour>=1 & hour<=data.meta.nHours) && ...
    numel(unique(day+hour/(data.meta.nHours+1)))==numel(day) && ...
    all(corrected>0 & corrected<original) && ...
    all(abs(corrected/10-round(corrected/10))<=1e-12) && ...
    all(abs(reduction-(original-corrected))<=1e-9), ...
    "rkkt:data:LoadCorrectionValues", ...
    "The load-correction table contains invalid or duplicate edits.");

linear = sub2ind(size(data.timeseries.planMW),day,hour);
actualOriginal = double(data.timeseries.planMW(linear));
assert(all(abs(actualOriginal-original)<=1e-9), ...
    "rkkt:data:LoadCorrectionOriginalMismatch", ...
    "A declared original load does not match the controlled annual input.");
data.timeseries.planMW(linear) = corrected;
data.timeseries.planPerUnit(linear) = corrected/data.meta.planBaseMW;

correction = struct( ...
    "version","stage-B2C-reviewed-load-correction-v1.0", ...
    "enabled",true, ...
    "path",correctionPath, ...
    "sha256",rkkt.data.compute_sha256_file(correctionPath), ...
    "row_count",height(rows), ...
    "days",reshape(unique(day,"stable"),1,[]), ...
    "day_count",numel(unique(day)), ...
    "total_reduction_mwh",sum(reduction), ...
    "maximum_single_hour_reduction_mw",max(reduction), ...
    "rounding_mw",10, ...
    "water_coupled_feasibility_certified",false);
data.load_correction = correction;
end
