function template = build_stage_b2c_linearization_template( ...
        reference,data,index,config)
%BUILD_STAGE_B2C_LINEARIZATION_TEMPLATE Freeze invariant B-2C structure.

arguments
    reference (1,1) struct
    data (1,1) struct
    index (1,1) struct
    config (1,1) struct
end
assert(string(reference.stage_id)=="stage_B" && ...
    string(reference.milestone_id)=="B-2C" && ...
    string(index.scope.milestone_id)=="B-2C" && ...
    string(config.milestone_id)=="B-2C", ...
    "stageB2C:template:Identity", ...
    "The fixed template requires one B-2C reference linearization.");
nPrimal = index.counts.variables;
nEquality = index.counts.equalities;
nBaseInequality = index.stage_a_base_index.counts.inequalities;
waterIndex = index.water_constraint_index;
nWater = height(waterIndex);
waterRows = waterIndex.inequality_position(:);
assert(isequal(size(reference.A),[nEquality,nPrimal]) && ...
    isequal(size(reference.G),[nBaseInequality+nWater,nPrimal]) && ...
    isequal(waterRows,nBaseInequality+(1:nWater).') && ...
    nWater==config.expected_water_inequality_count, ...
    "stageB2C:template:Dimensions", ...
    "The reference matrices and canonical water suffix are inconsistent.");

columns = zeros(nWater,24);
records = reference.constraints.water.constraint_hessians;
assert(numel(records)==nWater, ...
    "stageB2C:template:WaterRecords", ...
    "The reference water-Hessian inventory is incomplete.");
for row = 1:nWater
    value = records(row).variable_indices(:).';
    assert(numel(value)==24 && all(value>=1) && all(value<=nPrimal), ...
        "stageB2C:template:WaterSupport", ...
        "Every water row must retain exactly 24 primal columns.");
    columns(row,:) = value;
end
hydro = waterIndex.hydro_id(:);
signValue = double(reference.constraints.water.sign(:));
waterA = double(data.base.hydro.waterA(hydro));
waterB = double(data.base.hydro.waterB(hydro));
waterC = double(data.base.hydro.waterC(hydro));
hessianCoefficient = signValue.*(2.*waterA);
hessianNnz = 24.*double(hessianCoefficient~=0);
hessianFrobenius = sqrt(24).*abs(hessianCoefficient);
assert(all(ismember(signValue,[-1,1])) && ...
    all(isfinite([waterA;waterB;waterC])) && ...
    all(isfinite(reference.constraints.water.bound_value)), ...
    "stageB2C:template:WaterParameters", ...
    "The fixed water coefficients, signs, or bounds are invalid.");

stageABaseIdentity = string(reference.base_linearization_identity);
marker = "|iteration";
if contains(stageABaseIdentity,marker)
    stageABaseIdentityPrefix = extractBefore(stageABaseIdentity,marker);
else
    stageABaseIdentityPrefix = "";
end
template = struct( ...
    "version","stage-B2C-linearization-template-v1.0", ...
    "stage_id","stage_B","milestone_id","B-2C", ...
    "index_version",string(index.version), ...
    "days",reshape(double(config.days),1,[]), ...
    "hours",reshape(double(config.hours),1,[]), ...
    "n_primal",nPrimal,"n_equalities",nEquality, ...
    "n_base_inequalities",nBaseInequality, ...
    "n_water_inequalities",nWater, ...
    "n_inequalities",nBaseInequality+nWater, ...
    "A",reference.A, ...
    "equality_offset",reference.constraints.eq_offset, ...
    "base_G",reference.G(1:nBaseInequality,:), ...
    "base_inequality_offset", ...
        reference.constraints.ineq_offset(1:nBaseInequality), ...
    "objective_hessian",reference.objective.hessian, ...
    "original_objective_gradient", ...
        reference.objective.original_gradient, ...
    "scaled_objective_gradient",reference.objective.gradient, ...
    "objective_scale_factor",reference.objective_scale.factor, ...
    "index",index,"maps",reference.maps,"layout",reference.layout, ...
    "fixed_zero_map",index.fixed_zero_map, ...
    "permutation",index.permutation_map, ...
    "capacity_parameters",reference.capacity_parameters, ...
    "counts",reference.counts,"config",config, ...
    "model_contract_version",reference.model_contract_version, ...
    "input_hashes",lower(string(data.hashes.actualSHA256)), ...
    "stage_a_base_identity",stageABaseIdentity, ...
    "stage_a_base_identity_prefix",stageABaseIdentityPrefix);
template.water = struct( ...
    "rows",waterRows,"columns",columns, ...
    "row_numbers",repmat((1:nWater).',1,24), ...
    "sign",signValue, ...
    "bound_value",double(reference.constraints.water.bound_value(:)), ...
    "water_a",waterA,"water_b",waterB,"water_c",waterC, ...
    "hessian_coefficient",hessianCoefficient, ...
    "hessian_nnz",hessianNnz, ...
    "hessian_frobenius",hessianFrobenius, ...
    "constraint_hessians",records, ...
    "hessian_triplets",reference.constraints.water.hessian_triplets, ...
    "row_audit",reference.constraints.water.row_audit, ...
    "counts",reference.constraints.water.counts, ...
    "maximum_hessian_symmetry_relative", ...
        reference.constraints.water.maximum_hessian_symmetry_relative);
end
