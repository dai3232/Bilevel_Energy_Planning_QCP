function parameters = stage_a_capacity_parameters(data)
%STAGE_A_CAPACITY_PARAMETERS Return the canonical 14-dimensional data view.

assert(data.meta.nWind == 5 && data.meta.nSolar == 5 && ...
    data.meta.nStorage == 2,"stageA:capacity:DeviceCounts", ...
    "Stage A requires 5 wind, 5 solar, and 2 storage assets.");

parameters = struct();
parameters.names = ["QW1","QW2","QW3","QW4","QW5", ...
    "QP1","QP2","QP3","QP4","QP5","QS1","QS2","ES1","ES2"];
parameters.lower = [data.base.wind.capacityLowerMW; ...
    data.base.solar.capacityLowerMW; ...
    data.base.storage.powerLowerMW; ...
    data.base.storage.energyLowerMWh];
parameters.upper = [data.base.wind.capacityUpperMW; ...
    data.base.solar.capacityUpperMW; ...
    data.base.storage.powerUpperMW; ...
    data.base.storage.energyUpperMWh];
parameters.cost = [data.base.wind.investmentYuanPerMW; ...
    data.base.solar.investmentYuanPerMW; ...
    data.base.storage.investmentPowerYuanPerMW; ...
    data.base.storage.investmentEnergyYuanPerMWh];
parameters.storage_power_indices = (11:12).';
parameters.storage_energy_indices = (13:14).';
parameters.storage_duration_hours = data.base.storage.durationHours;
parameters.charge_efficiency = data.base.storage.chargeEfficiency;
parameters.discharge_efficiency = data.base.storage.dischargeEfficiency;
parameters.initial_soc_fraction = data.base.storage.initialSocFraction;
parameters.soc_upper_fraction = data.base.storage.socUpperFraction;
parameters.soc_lower_fraction = data.base.storage.socLowerFraction;

assert(isequal(size(parameters.lower),[14,1]) && ...
    isequal(size(parameters.upper),[14,1]) && ...
    isequal(size(parameters.cost),[14,1]), ...
    "stageA:capacity:CanonicalDimension", ...
    "The canonical capacity vectors must be 14-by-1.");
assert(all(isfinite(parameters.lower)) && ...
    all(isfinite(parameters.upper)) && all(isfinite(parameters.cost)) && ...
    all(parameters.lower < parameters.upper), ...
    "stageA:capacity:InvalidBounds", ...
    "Capacity data must be finite with strict lower bounds below upper bounds.");
end
