function scope = resolve_stage_b2c_day_scope(dayScope,dayStart,dayEnd)
%RESOLVE_STAGE_B2C_DAY_SCOPE Resolve a continuous range or frozen 307-day set.

arguments
    dayScope (1,1) string {mustBeMember(dayScope, ...
        ["continuous","screened_307"])}
    dayStart (1,1) double {mustBeInteger,mustBePositive}
    dayEnd (1,1) double {mustBeInteger,mustBePositive}
end

assert(dayStart<=dayEnd && dayEnd<=365, ...
    "rkkt:runConfig:Days", ...
    "DayStart/DayEnd must define one ascending interval inside 1:365.");
physicalInfeasible = zeros(1,0);
numericallyPathological = zeros(1,0);
excluded = zeros(1,0);
explicitDaySet = false;

if dayScope=="screened_307"
    assert(dayStart==1 && dayEnd==365, ...
        "rkkt:runConfig:Screened307Bounds", ...
        "screened_307 requires day_start=1 and day_end=365.");
    physicalInfeasible = [61,62,66,96,99,119,126,131,137,140,144, ...
        150,152,156,161,166,172,183,199,203,206,209,212,216,218, ...
        231,238,244,245,248,251,252,261,263,266,271,272,277,280, ...
        285,298];
    numericallyPathological = [65,109,112,118,124,127,154,197,215, ...
        222,223,235,236,247,260,264,297];
    excluded = sort([physicalInfeasible,numericallyPathological]);
    explicitDaySet = true;
end

days = setdiff(dayStart:dayEnd,excluded,"stable");
scope = struct("day_scope",dayScope,"day_start",dayStart, ...
    "day_end",dayEnd,"days",days,"explicit_day_set",explicitDaySet, ...
    "excluded_days",excluded, ...
    "physical_infeasible_days",physicalInfeasible, ...
    "numerically_pathological_days",numericallyPathological);
end
