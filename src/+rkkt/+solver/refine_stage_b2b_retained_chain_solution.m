function [solution,diagnostics] = ...
        refine_stage_b2b_retained_chain_solution( ...
        partition,factors,multipliers,rhs,initialSolution,options)
%REFINE_STAGE_B2B_RETAINED_CHAIN_SOLUTION Refine arbitrary retained RHS.

arguments
    partition (1,1) struct
    factors (:,1) cell
    multipliers (:,1) cell
    rhs {mustBeNumeric,mustBeReal}
    initialSolution {mustBeNumeric,mustBeReal}
    options.MaxPasses (1,1) double {mustBeInteger,mustBeNonnegative} = 0
    options.TargetRelative (1,1) double ...
        {mustBePositive,mustBeFinite} = 64*eps
    options.Label (1,1) string = "stageB2B_retained_chain"
    options.UseExtendedResidual (1,1) logical = false
end
assert(options.MaxPasses<=3 && ...
    isequal(size(initialSolution),size(rhs)) && ...
    size(rhs,1)==size(partition.M,1), ...
    "stageB2B:refinement:Contract", ...
    "Retained water-border refinement shape or pass limit is invalid.");
factorsBefore = factors;
multipliersBefore = multipliers;
current = initialSolution;
metrics = rkkt.solver.compute_retained_residual_metrics( ...
    partition.M,current,rhs, ...
    UseExtendedResidual=options.UseExtendedResidual);
initialMetric = metrics.maximum_column_relative;
selectedPass = 0;
attemptedPasses = 0;
history = repmat(history_row(0,metrics,true),options.MaxPasses+1,1);
corrections = cell(options.MaxPasses,1);
if options.MaxPasses==0
    stopReason = "disabled";
elseif initialMetric<=options.TargetRelative
    stopReason = "target_met_initial";
else
    stopReason = "maximum_passes_reached";
    for pass = 1:options.MaxPasses
        attemptedPasses = pass;
        [correction,~,corrections{pass}] = ...
            rkkt.solver.apply_retained_block_thomas_once( ...
            partition,factors,multipliers,metrics.residual, ...
            options.Label+"_correction_"+string(pass));
        candidate = current+correction;
        candidateMetrics = rkkt.solver.compute_retained_residual_metrics( ...
            partition.M,candidate,rhs, ...
            UseExtendedResidual=options.UseExtendedResidual);
        improved = candidateMetrics.maximum_column_relative < ...
            metrics.maximum_column_relative || ...
            (candidateMetrics.maximum_column_relative== ...
            metrics.maximum_column_relative && ...
            candidateMetrics.frobenius_relative<metrics.frobenius_relative);
        history(pass+1) = history_row(pass,candidateMetrics,improved);
        if ~improved
            stopReason = "residual_no_longer_decreased";
            break
        end
        current = candidate;
        metrics = candidateMetrics;
        selectedPass = pass;
        if metrics.maximum_column_relative<=options.TargetRelative
            stopReason = "target_met";
            break
        end
    end
end
history = history(1:attemptedPasses+1);
solution = current;
assert(isequaln(factors,factorsBefore) && ...
    isequaln(multipliers,multipliersBefore), ...
    "stageB2B:refinement:FactorMutation", ...
    "Retained water-border refinement changed the factor context.");
finalMetrics = rkkt.solver.compute_retained_residual_metrics( ...
    partition.M,solution,rhs, ...
    UseExtendedResidual=options.UseExtendedResidual);
if initialMetric==0
    reductionRatio = 0;
else
    reductionRatio = finalMetrics.maximum_column_relative/initialMetric;
end
diagnostics = struct("enabled",options.MaxPasses>0, ...
    "triggered",options.MaxPasses>0 && initialMetric>options.TargetRelative, ...
    "maximum_passes",options.MaxPasses, ...
    "target_relative",options.TargetRelative, ...
    "passes_attempted",attemptedPasses,"correction_count",selectedPass, ...
    "selected_pass",selectedPass,"stop_reason",stopReason, ...
    "target_met",finalMetrics.maximum_column_relative<=options.TargetRelative, ...
    "initial_maximum_column_relative",initialMetric, ...
    "final_maximum_column_relative",finalMetrics.maximum_column_relative, ...
    "residual_reduction_ratio",reductionRatio,"history",history, ...
    "correction_solve",{corrections(1:attemptedPasses)}, ...
    "rhs_count",size(rhs,2),"all_rhs_share_selected_pass",true, ...
    "residual_operator","original_partition_M", ...
    "extended_residual_used",options.UseExtendedResidual, ...
    "residual_operator_exact_original",true, ...
    "correction_operator","retained_thomas_inverse_map", ...
    "factor_context_unchanged",true,"additional_factorization_count",0, ...
    "direct_chain_backslash_used",false, ...
    "full_kkt_direction_consumed",false);
end

function value = history_row(pass,metrics,accepted)
value = struct("pass",pass, ...
    "maximum_column_relative",metrics.maximum_column_relative, ...
    "column_relative",metrics.column_relative, ...
    "frobenius_relative",metrics.frobenius_relative, ...
    "componentwise_backward_error",metrics.componentwise_backward_error, ...
    "maximum_absolute",metrics.maximum_absolute,"accepted",accepted);
end
