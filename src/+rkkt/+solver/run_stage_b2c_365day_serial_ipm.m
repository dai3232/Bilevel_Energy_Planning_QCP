function result = run_stage_b2c_365day_serial_ipm( ...
        data,modelIndex,config,context,options)
%RUN_STAGE_B2C_365DAY_SERIAL_IPM Run/resume a configured serial IPM.

arguments
    data (1,1) struct
    modelIndex (1,1) struct
    config (1,1) struct
    context (1,1) struct
    options.MaxIterations (1,1) double {mustBeInteger,mustBePositive} = 100
    options.Resume (1,1) logical = false
    options.SolverCodeSignature (1,1) string = ""
    options.DayResponseExecutionMode (1,1) string {mustBeMember( ...
        options.DayResponseExecutionMode,["serial","parallel_processes"])} = ...
        "serial"
    options.ParallelWorkerCount (1,1) double ...
        {mustBeInteger,mustBeNonnegative} = 0
    options.JointMicroborderScanEnabled (1,1) logical = false
    options.CheckpointEnabled (1,1) logical = true
    options.RecursiveBlockTemplate (1,1) struct = struct()
end
parallelRequested = options.DayResponseExecutionMode=="parallel_processes";
assert(~parallelRequested || options.ParallelWorkerCount>0, ...
    "stageB2C:parallel:WorkerCount", ...
    "A positive worker count is required for parallel day responses.");
assert(options.CheckpointEnabled || ~options.Resume, ...
    "stageB2C:lightweight:Resume", ...
    "Checkpoint-free lightweight runs cannot resume an interrupted solve.");

assert(ismember(config.time_scope_type,[ ...
    "supplemental_365_day_serial_scope", ...
    "configured_contiguous_day_scope", ...
    "configured_explicit_day_scope"]) && ...
    ~isempty(config.days) && ...
    (config.time_scope_type=="configured_explicit_day_scope" || ...
        isequal(config.days,config.days(1):config.days(end))) && ...
    numel(unique(config.days))==numel(config.days) && ...
    issorted(config.days,"strictascend") && ...
    config.parallel_enabled==parallelRequested && ...
    ((parallelRequested && options.ParallelWorkerCount== ...
        config.parallel_worker_count) || ...
        (~parallelRequested && options.ParallelWorkerCount==0)) && ...
    ~config.annual_scope_enabled && ~config.full_kkt_audit_enabled && ...
    ~config.full_kkt_enabled && ~config.full_kkt_solve_enabled, ...
    "stageB2C:serial:Contract", ...
    "The serial runner requires an ascending recursive-only day profile.");
runtimeRoute = isfield(modelIndex,"version") && ...
    ismember(string(modelIndex.version),[ ...
        "stage-B2C-recursive-runtime-package-v1.0", ...
        "stage-B2C-recursive-numerical-payload-v1.0"]);
invocationTimer = tic;
setupTimer = tic;
limit = min(options.MaxIterations,config.max_iterations);
diagnosticsDir = fullfile(context.root,"diagnostics");
ensure_directory(diagnosticsDir);
paths = history_paths(diagnosticsDir);

manifest = jsondecode(fileread(context.run_manifest_path));
gitCommit = string(manifest.git_commit);
configSha = rkkt.data.compute_sha256_file(context.effective_config_path);
[inputFingerprint,~] = ...
    rkkt.artifacts.compute_stage_a4_checkpoint_input_fingerprint( ...
    manifest.input_hashes);
codeSignature = options.SolverCodeSignature;
if strlength(codeSignature)==0
    codeSignature = rkkt.artifacts.compute_package_code_signature( ...
        string(context.project_root));
end
expected = checkpoint_identity(gitCommit,configSha,inputFingerprint, ...
    codeSignature,config,options.JointMicroborderScanEnabled);

if options.Resume
    [state,iterationHistory,timingHistory, ...
        factorizationHistory,waterCorrectionHistory,resumeRecord, ...
        resumeMetadata] = ...
        restore_accepted_state(context,paths,expected,config);
    startRevision = double(state.state_revision);
    cumulativeOffset = resume_wall_offset(manifest,timingHistory);
    append_resume_event(diagnosticsDir,context,resumeRecord, ...
        codeSignature,cumulativeOffset);
    linearizationTemplate = options.RecursiveBlockTemplate;
    if runtimeRoute
        linearizationTemplate = modelIndex.template;
    end
    if isempty(fieldnames(linearizationTemplate))
        linearizationTemplate = ...
            rkkt.model.build_stage_b2c_recursive_block_template( ...
                data,modelIndex,config);
    end
    linearization = ...
        rkkt.model.update_stage_b2c_recursive_block_linearization( ...
            state,linearizationTemplate,ChainId="B-2C-FORMAL-IPM");
    rebuilt = rkkt.diagnostics.compute_stage_a4_rns1_fingerprint( ...
        linearization,"linearization");
    assert(lower(string(resumeRecord.linearization_fingerprint))== ...
        lower(rebuilt) && ...
        lower(string(resumeMetadata.linearization_fingerprint))== ...
        lower(rebuilt),"stageB2C:day365:ResumeLinearization", ...
        "The latest accepted checkpoint does not match the rebuilt linearization.");
else
    assert(~isfile(context.checkpoint_manifest_path) && ...
        ~any(structfun(@isfile,paths)), ...
        "stageB2C:day365:FreshArtifactsExist", ...
        "A fresh 365-day solve cannot overwrite histories or checkpoints.");
    if runtimeRoute
        linearizationTemplate = modelIndex.template;
        state = rkkt.model.initialize_stage_b2c_runtime_state( ...
            data,modelIndex,config);
    else
        [state,linearizationTemplate] = ...
            rkkt.model.initialize_stage_b2c_state(data,modelIndex,config, ...
                RecursiveBlockTemplate=options.RecursiveBlockTemplate);
    end
    linearization = ...
        rkkt.model.update_stage_b2c_recursive_block_linearization( ...
            state,linearizationTemplate,ChainId="B-2C-FORMAL-IPM");
    iterationHistory = empty_iteration_history();
    timingHistory = empty_timing_history();
    factorizationHistory = empty_factorization_history();
    waterCorrectionHistory = empty_water_correction_history();
    if options.CheckpointEnabled
        initialMetricsPath = fullfile(diagnosticsDir,"initial_metrics.json");
        assert(~isfile(initialMetricsPath), ...
            "stageB2C:day365:FreshArtifactsExist", ...
            "The fresh-run initial metrics already exist.");
        rkkt.artifacts.write_json_file(initialMetricsPath, ...
            rkkt.diagnostics.compute_stage_b2c_unitized_metrics(linearization));
        persist_histories(paths,iterationHistory,timingHistory, ...
            factorizationHistory,waterCorrectionHistory);
        metadata = checkpoint_metadata(0,expected,config,false, ...
            options.DayResponseExecutionMode,options.ParallelWorkerCount, ...
            options.JointMicroborderScanEnabled);
        rkkt.artifacts.write_stage_b2c_checkpoint( ...
            context,state,linearization,metadata);
    end
    startRevision = 0;
    cumulativeOffset = 0;
end
dailyJointStructureTemplate = struct();
assert(startRevision<=limit,"stageB2C:day365:ResumeIterationLimit", ...
    "MaxIterations must be at least the resumed accepted revision %d.", ...
    startRevision);
setupSeconds = toc(setupTimer);

terminalState = "ITERATION_LIMIT_REACHED";
if rkkt.diagnostics.stage_b2c_convergence_passed( ...
        rkkt.diagnostics.compute_stage_b2c_unitized_metrics(linearization),config)
    terminalState = "CONVERGED";
end
previousIdentity = "";
lastDirection = struct();
lastCore = struct();
lastRecursiveDiagnostics = struct();
parallelExecuted = false;
dailyResponseSeconds = 0;
runTimer = tic;
rkkt.artifacts.update_running_run_manifest(context,struct( ...
    "iteration_loop_wall_seconds",cumulativeOffset, ...
    "recursive_ipm_compute_seconds",sum(timingHistory.total_seconds), ...
    "accepted_iteration_count",startRevision, ...
    "parallel_executed",false, ...
    "day_response_execution_mode",char(options.DayResponseExecutionMode), ...
    "parallel_worker_count",options.ParallelWorkerCount, ...
    "joint_microborder_scan_enabled",options.JointMicroborderScanEnabled, ...
    "b2c_serial_solver_terminal_state","RUNNING"));

for iteration = startRevision+1:limit
    if terminalState=="CONVERGED"
        break
    end
    step = rkkt.diagnostics.execute_stage_b2c_iteration( ...
        state,data,modelIndex,config, ...
        PreviousLinearizationIdentity=previousIdentity, ...
        FullKktAuditEnabled=false, ...
        PrecomputedLinearization=linearization, ...
        LinearizationTemplate=linearizationTemplate, ...
        DailyJointStructureTemplate=dailyJointStructureTemplate, ...
        LinearizationUpdateMode="recursive_blocks", ...
        DayResponseExecutionMode=options.DayResponseExecutionMode, ...
        ParallelWorkerCount=options.ParallelWorkerCount, ...
        JointMicroborderScanEnabled=options.JointMicroborderScanEnabled);
    assert_iteration_route(step,config);
    parallelExecuted = parallelExecuted || step.recursive.diagnostics. ...
        parallel_day_responses_executed;
    dailyResponseSeconds = dailyResponseSeconds+ ...
        step.recursive.timing.daily_response_seconds;
    converged = rkkt.diagnostics.stage_b2c_convergence_passed( ...
        step.metrics_after,config);
    acceptedWall = cumulativeOffset+toc(runTimer);
    iterationRow = make_iteration_row( ...
        step,iteration,acceptedWall,converged);
    timingRow = make_timing_row(step,iteration,acceptedWall);
    if options.CheckpointEnabled
        pending = struct("iteration",iteration, ...
            "iteration_row",iterationRow,"timing_row",timingRow, ...
            "factorization_rows",make_factorization_rows(step,iteration), ...
            "water_correction_rows", ...
                make_water_correction_rows(step,iteration));
        rkkt.artifacts.save_mat_artifact(fullfile(diagnosticsDir, ...
            "pending_accepted_history.mat"),"pending",pending);
        checkpointTimer = tic;
        checkpointRecord = rkkt.artifacts.write_stage_b2c_checkpoint( ...
            context,step.state_after,step.linearization_after, ...
            checkpoint_metadata(iteration,expected,config,parallelExecuted, ...
                options.DayResponseExecutionMode, ...
                options.ParallelWorkerCount, ...
                options.JointMicroborderScanEnabled));
        checkpointSeconds = toc(checkpointTimer);
        factorizationHistory = [factorizationHistory; ...
            pending.factorization_rows]; %#ok<AGROW>
        waterCorrectionHistory = [waterCorrectionHistory; ...
            pending.water_correction_rows]; %#ok<AGROW>
    end
    iterationHistory = [iterationHistory;iterationRow]; %#ok<AGROW>
    timingHistory = [timingHistory;timingRow]; %#ok<AGROW>
    if options.CheckpointEnabled
        persist_histories(paths,iterationHistory,timingHistory, ...
            factorizationHistory,waterCorrectionHistory);
    end
    cumulativeCompute = sum(timingHistory.total_seconds);

    state = step.state_after;
    linearization = step.linearization_after;
    previousIdentity = step.linearization_before.identity;
    lastDirection = step.recursive.components;
    lastCore = step.recursive.core;
    lastRecursiveDiagnostics = step.recursive.diagnostics;
    wallSeconds = cumulativeOffset+toc(runTimer);
    if options.CheckpointEnabled
        rkkt.artifacts.update_running_run_manifest(context,struct( ...
            "b2c_serial_solver_terminal_state","RUNNING", ...
            "accepted_iteration_count",iteration, ...
            "state_update_count",iteration,"convergence_achieved",converged, ...
            "recursive_ipm_compute_seconds",cumulativeCompute, ...
            "iteration_loop_wall_seconds",wallSeconds, ...
            "accepted_state_wall_seconds",acceptedWall, ...
            "last_checkpoint_write_seconds",checkpointSeconds, ...
            "last_checkpoint_sha256",char(checkpointRecord.sha256), ...
            "full_kkt_audit_executed",false,"full_kkt_assembled",false, ...
            "full_kkt_solved",false,"parallel_executed",parallelExecuted, ...
            "parallel_worker_count",options.ParallelWorkerCount, ...
            "joint_microborder_scan_enabled", ...
                options.JointMicroborderScanEnabled, ...
            "recursive_final_kkt_relative_residual", ...
                step.recursive.diagnostics.candidate_kkt_relative_residual, ...
            "core_consistency_correction_passes_applied", ...
                step.recursive.core.direct_daily_correction.passes_applied, ...
            "core_consistency_final_relative_residual", ...
                step.recursive.core.direct_daily_correction. ...
                    final_relative_residual, ...
            "last_linearization_identity",char(linearization.identity)));
    end
    clear step
    if converged
        terminalState = "CONVERGED";
    end
end

if ~options.CheckpointEnabled
    persist_lightweight_histories(paths,iterationHistory,timingHistory);
end

finalMetrics = rkkt.diagnostics.compute_stage_b2c_unitized_metrics(linearization);
elapsedSeconds = cumulativeOffset+toc(runTimer);
invocationTotalSeconds = toc(invocationTimer);
result = struct("final_state",state,"final_linearization",linearization, ...
    "final_metrics",finalMetrics,"last_direction",lastDirection, ...
    "last_core",lastCore, ...
    "last_recursive_diagnostics",lastRecursiveDiagnostics, ...
    "iteration_history",iterationHistory,"timing_history",timingHistory, ...
    "factorization_history",factorizationHistory, ...
    "water_correction_history",waterCorrectionHistory, ...
    "accepted_iteration_count",double(state.state_revision), ...
    "convergence_achieved",terminalState=="CONVERGED", ...
    "run_terminal_state",terminalState,"elapsed_seconds",elapsedSeconds, ...
    "invocation_setup_seconds",setupSeconds, ...
    "invocation_total_wall_seconds",invocationTotalSeconds, ...
    "invocation_elapsed_seconds",toc(runTimer), ...
    "resume_from_iteration",startRevision,"resumed",options.Resume, ...
    "full_kkt_audit_executed",false,"full_kkt_assembled",false, ...
    "full_kkt_solved",false,"parallel_executed",parallelExecuted, ...
    "day_response_execution_mode",options.DayResponseExecutionMode, ...
    "parallel_worker_count",options.ParallelWorkerCount, ...
    "joint_microborder_scan_enabled",options.JointMicroborderScanEnabled, ...
    "checkpoint_enabled",options.CheckpointEnabled, ...
    "daily_response_compute_seconds",dailyResponseSeconds);
end

function [state,iterations,timing,factors,correction,record,metadata] = ...
        restore_accepted_state(context,paths,expected,config)
[checkpoint,record] = rkkt.artifacts.load_stage_b2c_checkpoint( ...
    context,NaN,ExpectedMetadata=expected);
state = checkpoint.state;
metadata = checkpoint.metadata;
revision = double(state.state_revision);
[iterations,timing,factors,correction] = read_and_trim_histories( ...
    paths,revision,config);
persist_histories(paths,iterations,timing,factors,correction);
end

function [iterations,timing,factors,correction] = read_and_trim_histories( ...
        paths,revision,config)
iterations = read_typed_table(paths.iteration,empty_iteration_history());
timing = read_typed_table(paths.timing,empty_timing_history());
factors = read_typed_table(paths.factorization,empty_factorization_history());
correction = read_typed_table(paths.water_correction, ...
    empty_water_correction_history());
iterations = iterations(iterations.iteration<=revision,:);
timing = timing(timing.iteration<=revision,:);
factors = factors(factors.iteration<=revision,:);
correction = correction(correction.iteration<=revision,:);
expectedIterations = (1:revision).';
if revision>0 && (height(iterations)<revision || height(timing)<revision || ...
        height(factors)<revision*(numel(config.days)+1) || ...
        height(correction)<revision*config.expected_water_inequality_count)
    [iterations,timing,factors,correction] = ...
        recover_missing_accepted_history(paths,revision,config, ...
        iterations,timing,factors,correction);
end
assert(isequal(iterations.iteration,expectedIterations) && ...
    isequal(timing.iteration,expectedIterations) && ...
    height(factors)==revision*(numel(config.days)+1) && ...
    height(correction)==revision*config.expected_water_inequality_count, ...
    "stageB2C:day365:ResumeHistory", ...
    "Accepted histories are not contiguous through revision %d.",revision);
end

function [iterations,timing,factors,correction] = ...
        recover_missing_accepted_history(paths,revision,config, ...
        iterations,timing,factors,correction)
pendingPath = fullfile(fileparts(paths.iteration),"pending_accepted_history.mat");
assert(isfile(pendingPath),"stageB2C:day365:ResumeHistory", ...
    "Checkpoint revision %d is ahead of cumulative histories and no pending accepted history exists.", ...
    revision);
loaded = load(pendingPath,"pending");
assert(isfield(loaded,"pending") && ...
    double(loaded.pending.iteration)==revision, ...
    "stageB2C:day365:ResumeHistory", ...
    "The pending accepted history does not match checkpoint revision %d.",revision);
pending = loaded.pending;
baseRevision = revision-1;
iterations = iterations(iterations.iteration<=baseRevision,:);
timing = timing(timing.iteration<=baseRevision,:);
factors = factors(factors.iteration<=baseRevision,:);
correction = correction(correction.iteration<=baseRevision,:);
assert(isequal(iterations.iteration,(1:baseRevision).') && ...
    isequal(timing.iteration,(1:baseRevision).') && ...
    height(factors)==baseRevision*(numel(config.days)+1) && ...
    height(correction)==baseRevision*config.expected_water_inequality_count, ...
    "stageB2C:day365:ResumeHistory", ...
    "Histories before the pending accepted revision are incomplete.");
iterations = [iterations;pending.iteration_row];
timing = [timing;pending.timing_row];
factors = [factors;pending.factorization_rows];
correction = [correction;pending.water_correction_rows];
end

function value = read_typed_table(pathValue,template)
assert(isfile(pathValue),"stageB2C:day365:ResumeHistory", ...
    "A cumulative history file is missing: %s",pathValue);
opts = detectImportOptions(pathValue,"Delimiter",",", ...
    "VariableNamingRule","preserve");
assert(isequal(string(opts.VariableNames), ...
    string(template.Properties.VariableNames)), ...
    "stageB2C:day365:ResumeHistory", ...
    "A cumulative history file has an unexpected schema: %s",pathValue);
for name = string(template.Properties.VariableNames)
    source = template.(name);
    if isstring(source)
        opts = setvartype(opts,name,"string");
    elseif islogical(source)
        opts = setvartype(opts,name,"logical");
    else
        opts = setvartype(opts,name,"double");
    end
end
value = readtable(pathValue,opts);
end

function append_resume_event(diagnosticsDir,context,record,signature,offset)
pathValue = fullfile(diagnosticsDir,"resume_events.csv");
if isfile(pathValue)
    events = readtable(pathValue,"TextType","string", ...
        "VariableNamingRule","preserve");
else
    events = table(zeros(0,1),strings(0,1),zeros(0,1),strings(0,1), ...
        strings(0,1),strings(0,1),zeros(0,1), ...
        'VariableNames',{'invocation','run_id','resumed_iteration', ...
        'checkpoint_sha256','solver_code_signature','resumed_at_utc', ...
        'prior_iteration_loop_wall_seconds'});
end
event = table(height(events)+1,string(context.run_id), ...
    double(record.iteration),string(record.sha256),string(signature), ...
    string(datetime("now","TimeZone","UTC", ...
        "Format","yyyy-MM-dd'T'HH:mm:ss.SSSXXX")),offset, ...
    'VariableNames',events.Properties.VariableNames);
events = [events;event];
rkkt.artifacts.write_table_csv_17g_atomic(pathValue,events);
rkkt.artifacts.update_running_run_manifest(context,struct( ...
    "resume_count",height(events), ...
    "last_resume_from_iteration",double(record.iteration), ...
    "last_resume_checkpoint_sha256",char(string(record.sha256))));
end

function value = resume_wall_offset(manifest,timing)
historyOffset = 0;
if ~isempty(timing)
    historyOffset = double(timing.cumulative_seconds(end));
end
if isfield(manifest,"iteration_loop_wall_seconds")
    value = max(double(manifest.iteration_loop_wall_seconds),historyOffset);
else
    value = historyOffset;
end
assert(isfinite(value) && value>=0,"stageB2C:day365:ResumeTiming", ...
    "The persisted iteration-loop timing offset is invalid.");
end

function assert_iteration_route(step,config)
responses = step.recursive.responses;
adaptiveDelayed = step.recursive.diagnostics. ...
    adaptive_delayed_inequality_elimination_used;
jointMicroborder = step.recursive.diagnostics.joint_microborder_used;
dailyRecoveryPass = ...
    step.recursive.diagnostics.daily_direct_factor_backsolve_used || ...
    step.recursive.diagnostics.daily_affine_response_recovery_used || ...
    adaptiveDelayed;
retainedDailyPass = step.recursive.core.direct_daily_correction. ...
    retained_daily_factors_reused || adaptiveDelayed;
rhsPass = arrayfun(@(value)value.rhs_count==config.expected_rhs_per_day || ...
    (jointMicroborder && value.day_id== ...
        step.recursive.diagnostics.joint_microborder_day_ids && ...
        value.rhs_count==config.expected_rhs_per_day+1),responses);
factorsPass = numel(responses)==numel(config.days) && all(rhsPass) && ...
    all(arrayfun(@(value) ...
        value.factor.factorization_count==1 && ...
        value.factor.refinement_additional_factorization_count==0 && ...
        ~value.factor.blocking_warning_present && ...
        (~value.factor.warning_present || ...
            (value.factor.warning_continued && value.factor.inertia_zero>0)) && ...
        value.factor.solution_finite,responses));
assert(factorsPass && ismember(step.recursive.core.dimension,[16,17]) && ...
    (step.recursive.core.dimension==17)==jointMicroborder && ...
    (~jointMicroborder || step.high_low_state_update_used) && ...
    step.recursive.core.factor.factorization_count==1 && ...
    step.recursive.core.factor.refinement_additional_factorization_count==0 && ...
    ~step.recursive.core.factor.warning_present && ...
    step.recursive.core.factor.solution_finite && ...
    step.recursive.partition.full_inequality_elimination && ...
    step.recursive.partition.cross_day_nnz==0 && ...
    step.recursive.diagnostics.final_kkt_residual_gate_passed && ...
    step.recursive.diagnostics.candidate_kkt_relative_residual<= ...
        config.recursive_full_kkt_residual_tolerance && ...
    dailyRecoveryPass && ...
    step.recursive.diagnostics. ...
        daily_recovery_additional_factorization_count==0 && ...
    step.recursive.core.direct_daily_correction. ...
        daily_additional_factorization_count==0 && ...
    step.recursive.core.direct_daily_correction. ...
        core_additional_factorization_count==0 && ...
    retainedDailyPass && ...
    step.recursive.core.direct_daily_correction. ...
        retained_core_factor_reused && ...
    (jointMicroborder || ...
        step.recursive.core.direct_daily_correction.maximum_passes== ...
            config.core_consistency_max_passes) && ...
    step.recursive.core.direct_daily_correction. ...
        compensated_accumulation_used== ...
        config.compensated_core_accumulation && ...
    ~step.full_kkt_audit_executed && ~step.direction_audit.executed && ...
    step.water_slack_second_order_correction_scope_count== ...
        config.expected_water_inequality_count && ...
    step.water_slack_second_order_correction.all_strictly_positive && ...
    step.fixed_zero.count==config.expected_stage_a_fixed_zero_count && ...
    step.fixed_zero.all_exact_zero && step.no_full_direction_fallback && ...
    ~step.full_direction_consumed_by_recursive, ...
    "stageB2C:serial:IterationRoute", ...
    "A serial recursive iteration violated its configured route.");
end

function row = make_iteration_row(step,iteration,cumulative,converged)
m = step.metrics_after; d = step.recursive.diagnostics;
c = step.water_slack_second_order_correction;
row = table(iteration,m.objective_raw,m.objective_scaled, ...
    m.primal_equality_inf,m.primal_inequality_inf,m.dual_scaled_inf, ...
    m.mean_lz_scaled,step.primal_step.alpha,step.dual_step.alpha, ...
    m.min_l,m.min_z,d.candidate_kkt_relative_residual, ...
    d.core_direct_daily_correction_passes, ...
    d.core_direct_daily_correction_final_relative_residual, ...
    d.core_compensated_accumulation_used, ...
    max(d.daily_local_maximum_relative_residuals), ...
    numel(d.near_zero_pivot_day_ids), ...
    string(strjoin(string(d.near_zero_pivot_day_ids),"|")), ...
    sum(d.daily_factorization_counts)+ ...
        step.recursive.core.factor.factorization_count, ...
    false,m.maximum_water_violation,c.correction_fraction, ...
    c.correction_fraction_limited,c.minimum_corrected_l, ...
    step.fixed_zero.count,step.fixed_zero.maximum_absolute_value, ...
    step.fixed_zero.maximum_absolute_direction,step.fixed_zero.all_exact_zero, ...
    step.timing.total_seconds,cumulative,converged, ...
    'VariableNames',empty_iteration_history().Properties.VariableNames);
end

function row = make_timing_row(step,iteration,cumulative)
t = step.timing;
row = table(iteration,t.linearization_before_seconds,t.recursive_seconds, ...
    t.full_kkt_audit_seconds,t.step_and_state_update_seconds, ...
    t.linearization_after_seconds,t.total_seconds,cumulative, ...
    'VariableNames',empty_timing_history().Properties.VariableNames);
end

function rows = make_factorization_rows(step,iteration)
n = numel(step.recursive.responses);
rows = empty_factorization_history();
for position = 1:n
    response = step.recursive.responses(position);
    rows = [rows;factorization_row(iteration,response.day_id, ...
        "daily_joint",response.factor)]; %#ok<AGROW>
end
coreFactor = step.recursive.core.factor;
coreObjectType = "global_core_16";
if isfield(coreFactor,"object_type")
    coreObjectType = string(coreFactor.object_type);
end
