function audit = build_execution_audit(iterations,directions,factorization, ...
        waterCorrection,config,accepted,formalExecution)
if accepted==0
    directionPass=false; positivity=false; noFallback=false;
    correctionPass=false; maximumCorrectionClosure=NaN;
    minimumCorrectedWaterSlack=NaN; minimumCorrectionFraction=NaN;
    finalCorrectionFraction=NaN; limitedCorrectionCount=0;
    fullCorrectionCount=0;
else
    directionPass = all(directions.direction_relative_error<=1e-10) && ...
        all(directions.xi_relative_error<=1e-10) && ...
        all(directions.y_relative_error<=1e-10) && ...
        all(directions.l_relative_error<=1e-10) && ...
        all(directions.z_relative_error<=1e-10) && ...
        all(directions.recursive_full_kkt_relative_residual<=1e-10) && ...
        all(directions.full_kkt_relative_residual<=1e-10);
    positivity=all(iterations.min_l_after>0) && ...
        all(iterations.min_z_after>0);
    noFallback=all(directions.no_full_direction_fallback) && ...
        ~any(directions.full_direction_consumed_by_recursive);
    correctionMechanicsPass = height(waterCorrection)==56*accepted && ...
        isequal(waterCorrection.iteration, ...
            repelem((1:accepted).',56,1)) && ...
        all(waterCorrection.correction_fraction>0) && ...
        all(waterCorrection.correction_fraction<=1) && ...
        all((waterCorrection.correction_fraction==1)== ...
            waterCorrection.full_correction_centrality_safe) && ...
        all(waterCorrection.strictly_positive) && ...
        all(waterCorrection.l_corrected>= ...
            config.centering_sigma*waterCorrection.l_trial) && ...
        all(abs(waterCorrection.closure_error)<= ...
            waterCorrection.closure_tolerance) && ...
        all(iterations.water_slack_second_order_correction_applied) && ...
        all(iterations.water_slack_second_order_correction_scope_count==56);
    maximumCorrectionClosure = max(abs(waterCorrection.closure_error));
    minimumCorrectedWaterSlack = min(waterCorrection.l_corrected);
    minimumCorrectionFraction = min(iterations.water_correction_fraction);
    finalCorrectionFraction = iterations.water_correction_fraction(end);
    limitedCorrectionCount = sum( ...
        iterations.water_correction_fraction_limited);
    fullCorrectionCount = sum(iterations.water_correction_fraction==1);
    correctionPass = correctionMechanicsPass && ...
        (~formalExecution || finalCorrectionFraction==1);
end
% The persisted step table is the execution source of truth for forbidden
% factors; iteration rows intentionally remain limited to the user contract.
forbidden = config.step_strategy=="independent" && ...
    ~config.common_step_enabled && ~config.dynamic_sigma_enabled && ...
    ~config.predictor_corrector_enabled && ~config.line_search_enabled && ...
    ~config.regularization_enabled && ...
    ~config.automatic_symmetrization_enabled && ...
    ~config.parallel_enabled && ...
    ~config.full_kkt_direction_fallback_enabled;
factorizationPass = height(factorization)==8*accepted && ...
    all(factorization.factorization_count==1) && ...
    ~any(factorization.blocking_warning_present) && ...
    all(~factorization.warning_present | factorization.warning_continued) && ...
    all(factorization.solution_finite) && ...
    all(factorization.final_kkt_gate_applies) && ...
    ~any(factorization.full_kkt_direction_consumed);
audit = struct("accepted_iteration_count",accepted, ...
    "formal_execution",formalExecution, ...
    "one_full_kkt_audit_per_accepted_iteration", ...
        height(directions)==accepted, ...
    "direction_audits_pass",directionPass, ...
    "strict_positivity_pass",positivity, ...
    "no_full_direction_fallback",noFallback, ...
    "forbidden_execution_pass",forbidden, ...
    "daily_joint_factorization_pass",factorizationPass, ...
    "water_slack_second_order_correction_pass",correctionPass, ...
    "maximum_water_slack_correction_closure_error", ...
        maximumCorrectionClosure, ...
    "minimum_corrected_water_slack",minimumCorrectedWaterSlack, ...
    "minimum_water_slack_correction_fraction",minimumCorrectionFraction, ...
    "final_water_slack_correction_fraction",finalCorrectionFraction, ...
    "centrality_limited_water_correction_iteration_count", ...
        limitedCorrectionCount, ...
    "full_water_correction_iteration_count",fullCorrectionCount, ...
    "final_full_water_correction_pass",finalCorrectionFraction==1, ...
    "all_accepted_iterations_pass",accepted>0 && ...
        height(directions)==accepted && directionPass && positivity && ...
        noFallback && forbidden && factorizationPass && correctionPass);
end

