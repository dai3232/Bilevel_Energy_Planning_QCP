function row = make_direction_row(step,iteration)
a = step.direction_audit; c = a.component_relative_errors;
delta = abs(step.recursive.direction-step.full_audit.direction);
[maximumDirection,maximumDirectionIndex] = max(delta);
recursiveResidual = step.full_audit.kkt.matrix* ...
    step.recursive.direction-step.full_audit.kkt.rhs;
[maximumRecursive,maximumRecursiveRow] = max(abs(recursiveResidual));
fullResidual = step.full_audit.kkt.matrix* ...
    step.full_audit.direction-step.full_audit.kkt.rhs;
[maximumFull,maximumFullRow] = max(abs(fullResidual));
row = table(iteration,a.direction_relative_error,c.xi,c.y,c.l,c.z, ...
    a.recursive_kkt_relative_residual,a.full_kkt_relative_residual, ...
    maximumDirection,maximumDirectionIndex, ...
    maximumRecursive,maximumRecursiveRow,maximumFull,maximumFullRow, ...
    true,true,true,false,string(a.linearization_identity), ...
    'VariableNames',{'iteration','direction_relative_error', ...
    'xi_relative_error','y_relative_error','l_relative_error', ...
    'z_relative_error','recursive_full_kkt_relative_residual', ...
    'full_kkt_relative_residual','maximum_direction_difference', ...
    'maximum_direction_index','maximum_recursive_residual', ...
    'maximum_recursive_residual_row','maximum_full_residual', ...
    'maximum_full_residual_row','no_full_direction_fallback', ...
    'full_kkt_audit_only','recursive_direction_is_formal', ...
    'full_direction_consumed_by_recursive','linearization_identity'});
end

function row = make_water_hessian_row(step,iteration,index)
rows = index.water_constraint_index.inequality_position;
upper = string(index.water_constraint_index.bound_type)=="upper";
z = step.state_before.z(rows);
row = table(iteration,step.state_before.state_revision, ...
    step.water_hessian_nnz,step.water_hessian_fro_norm, ...
    step.water_hessian_symmetry_relative,min(z(upper)),max(z(upper)), ...
    min(z(~upper)),max(z(~upper)), ...
    string(step.linearization_before.identity), ...
    'VariableNames',{'iteration','state_revision_before','nnz', ...
    'frobenius_norm','symmetry_relative','upper_z_min','upper_z_max', ...
    'lower_z_min','lower_z_max','linearization_identity'});
end

function row = make_objective_row(step,iteration)
q = step.state_after.xi(step.linearization_after.maps.q_global);
names = matlab.lang.makeUniqueStrings(matlab.lang.makeValidName( ...
    cellstr(step.linearization_after.capacity_parameters.names(:))));
value = struct("iteration",iteration, ...
    "objective_raw",step.metrics_after.objective_raw, ...
    "objective_scaled",step.metrics_after.objective_scaled, ...
    "objective_scale_factor",step.metrics_after.objective_scale_factor);
for k = 1:14
    value.(names{k}) = q(k);
end
row = struct2table(value,"AsArray",true);
end

