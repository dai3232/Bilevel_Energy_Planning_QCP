function result = run_stage_b2c_full_ipm( ...
        data,index,config,context,options)
%RUN_STAGE_B2C_FULL_IPM Run the formal seven-day daily-joint recursive IPM.
%
% Every accepted iteration rebuilds the nonlinear water rows, their
% multiplier-weighted Lagrangian Hessian, seven fully eliminated daily
% joint systems, and the 16-dimensional core. The recursive direction is
% accepted only by its final KKT residual; a raw
% sparse full-KKT solve is performed independently once per attempted
% iteration and is consumed only by the audit.

arguments
    data (1,1) struct
    index (1,1) struct
    config (1,1) struct
    context (1,1) struct
    options.IterationLimit (1,1) double = NaN
end
validate_contract(config,context);
limit = config.max_iterations;
if ~isnan(options.IterationLimit)
    assert(options.IterationLimit>=1 && ...
        options.IterationLimit<=config.max_iterations && ...
        options.IterationLimit==fix(options.IterationLimit), ...
        "stageB2C:ipm:IterationLimit", ...
        "A diagnostic iteration limit must be an integer in [1,100].");
    limit = options.IterationLimit;
end
formalExecution = limit==config.max_iterations;
diagnosticsDir = fullfile(context.root,"diagnostics");
ensure_directory(diagnosticsDir);
paths = history_paths(diagnosticsDir);
assert(~any(isfile(string(struct2cell(paths)))) && ...
    ~isfile(context.checkpoint_manifest_path), ...
    "stageB2C:ipm:EvidenceExists", ...
    "A fresh B-2C IPM invocation refuses to overwrite evidence.");

manifest = jsondecode(fileread(context.run_manifest_path));
gitCommit = string(manifest.git_commit);
configSha = rkkt.data.compute_sha256_file(context.effective_config_path);
inputFingerprint = hash_text(jsonencode(manifest.input_hashes));
state = rkkt.model.initialize_stage_b2c_state(data,index,config);
linearization = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
    state,data,index,config,"B-2C-FORMAL-IPM");
initialMetrics = rkkt.diagnostics.compute_stage_b2c_unitized_metrics(linearization);
rkkt.artifacts.write_json_file(fullfile(diagnosticsDir,"initial_metrics.json"), ...
    initialMetrics);
metadata = checkpoint_metadata(0,gitCommit,configSha,inputFingerprint);
rkkt.artifacts.write_stage_b2c_checkpoint(context,state,linearization,metadata);

iterationHistory = empty_iteration_history();
residualHistory = empty_residual_history();
stepHistory = empty_step_history();
directionHistory = empty_direction_history();
waterHessianHistory = empty_water_hessian_history();
objectiveHistory = empty_objective_history(linearization);
timingHistory = empty_timing_history();
factorizationHistory = empty_factorization_history();
waterCorrectionHistory = empty_water_correction_history();
persist_histories(paths,iterationHistory,residualHistory,stepHistory, ...
    directionHistory,waterHessianHistory,objectiveHistory, ...
    timingHistory,factorizationHistory,waterCorrectionHistory);
terminalState = "MAX_ITERATIONS";
failure = struct("present",false,"iteration",0,"identifier","", ...
    "message","","evidence_path","");
previousIdentity = "";
runTimer = tic;
lastStep = struct();

for iteration = 1:limit
    checkpointCommitted = false;
    try
        step = rkkt.diagnostics.execute_stage_b2c_iteration(state,data,index,config, ...
            PreviousLinearizationIdentity=previousIdentity);
        assert_iteration_route(step,config);
        elapsed = toc(runTimer);
        convergenceCandidate = rkkt.diagnostics.stage_b2c_convergence_passed( ...
            step.metrics_after,config);
        candidateIteration = [iterationHistory; ...
            make_iteration_row(step,iteration,elapsed, ...
                convergenceCandidate,config)];
        candidateResidual = [residualHistory; ...
            make_residual_row(step,iteration)];
        candidateStep = [stepHistory;make_step_row(step,iteration)];
        candidateDirection = [directionHistory; ...
            make_direction_row(step,iteration)];
        candidateWater = [waterHessianHistory; ...
            make_water_hessian_row(step,iteration,index)];
        candidateObjective = [objectiveHistory; ...
            make_objective_row(step,iteration)];
        candidateTiming = [timingHistory; ...
            make_timing_row(step,iteration,elapsed)];
        candidateFactorization = [factorizationHistory; ...
            make_factorization_rows(step,iteration)];
        candidateWaterCorrection = [waterCorrectionHistory; ...
            make_water_correction_rows(step,iteration)];
        persist_histories(paths,candidateIteration,candidateResidual, ...
            candidateStep,candidateDirection,candidateWater, ...
            candidateObjective,candidateTiming,candidateFactorization, ...
            candidateWaterCorrection);
        metadata = checkpoint_metadata(iteration,gitCommit,configSha, ...
            inputFingerprint);
        metadata.iteration_history_sha256 = char( ...
            rkkt.data.compute_sha256_file(paths.iteration));
        metadata.direction_history_sha256 = char( ...
            rkkt.data.compute_sha256_file(paths.direction));
        metadata.water_correction_history_sha256 = char( ...
            rkkt.data.compute_sha256_file(paths.water_correction));
        rkkt.artifacts.write_stage_b2c_checkpoint(context,step.state_after, ...
            step.linearization_after,metadata);
        checkpointCommitted = true;
        iterationHistory = candidateIteration;
        residualHistory = candidateResidual;
        stepHistory = candidateStep;
        directionHistory = candidateDirection;
        waterHessianHistory = candidateWater;
        objectiveHistory = candidateObjective;
        timingHistory = candidateTiming;
        factorizationHistory = candidateFactorization;
        waterCorrectionHistory = candidateWaterCorrection;
        state = step.state_after;
        linearization = step.linearization_after;
        previousIdentity = step.linearization_before.identity;
        lastStep = step;
        rkkt.artifacts.update_running_run_manifest(context,struct( ...
            "b2c_solver_terminal_state","RUNNING", ...
            "accepted_iteration_count",iteration, ...
            "state_update_count",iteration, ...
            "convergence_achieved",convergenceCandidate, ...
            "last_state_fingerprint",char( ...
                rkkt.artifacts.compute_stage_a4_checkpoint_state_fingerprint( ...
                    step.state_after)), ...
            "last_linearization_identity",char( ...
                step.linearization_after.identity), ...
            "full_kkt_role","audit_only", ...
            "recursive_direction_is_formal",true, ...
            "water_slack_second_order_correction_enabled",true, ...
            "water_slack_second_order_correction_scope_count",56, ...
            "no_full_direction_fallback",true, ...
            "full_direction_consumed_by_recursive",false));
        if convergenceCandidate
            terminalState = "CONVERGED";
            break
        end
        clear step
    catch cause
        if ~checkpointCommitted
            persist_histories(paths,iterationHistory,residualHistory, ...
                stepHistory,directionHistory,waterHessianHistory, ...
                objectiveHistory,timingHistory,factorizationHistory, ...
                waterCorrectionHistory);
        end
        terminalState = "NUMERICAL_FAILURE";
        failure = persist_failure(context,cause,iteration,state);
        break
    end
end

accepted = height(iterationHistory);
if accepted==limit && terminalState~="CONVERGED" && ...
        terminalState~="NUMERICAL_FAILURE"
    terminalState = "MAX_ITERATIONS";
end
if accepted==0
    finalMetrics = initialMetrics;
else
    finalMetrics = rkkt.diagnostics.compute_stage_b2c_unitized_metrics(linearization);
end
executionAudit = build_execution_audit(iterationHistory, ...
    directionHistory,factorizationHistory,waterCorrectionHistory, ...
    config,accepted,formalExecution);
if terminalState~="NUMERICAL_FAILURE" && accepted>0 && ...
        ~executionAudit.all_accepted_iterations_pass
    terminalState = "NUMERICAL_FAILURE";
    cause = MException("stageB2C:ipm:ExecutionAudit", ...
        "A persisted B-2C per-iteration execution audit failed.");
    failure = persist_failure(context,cause,accepted,state);
end
rkkt.artifacts.update_running_run_manifest(context,struct( ...
    "b2c_solver_terminal_state",char(terminalState), ...
    "convergence_evaluated",true, ...
    "convergence_achieved",terminalState=="CONVERGED", ...
    "accepted_iteration_count",accepted, ...
    "state_update_count",accepted, ...
    "full_ipm_executed",formalExecution, ...
    "recursive_direction_executed",accepted>0, ...
    "recursive_direction_is_formal",true, ...
    "water_slack_second_order_correction_enabled",true, ...
    "water_slack_second_order_correction_scope_count",56, ...
    "minimum_water_slack_correction_fraction", ...
        executionAudit.minimum_water_slack_correction_fraction, ...
    "final_water_slack_correction_fraction", ...
        executionAudit.final_water_slack_correction_fraction, ...
    "centrality_limited_water_correction_iteration_count", ...
        executionAudit.centrality_limited_water_correction_iteration_count, ...
    "water_slack_second_order_correction_passed", ...
        executionAudit.water_slack_second_order_correction_pass, ...
    "maximum_water_slack_correction_closure_error", ...
        executionAudit.maximum_water_slack_correction_closure_error, ...
    "minimum_corrected_water_slack", ...
        executionAudit.minimum_corrected_water_slack, ...
    "full_kkt_role","audit_only", ...
    "no_full_direction_fallback",executionAudit.no_full_direction_fallback, ...
    "full_direction_consumed_by_recursive",false, ...
    "final_primal_equality_inf",finalMetrics.primal_equality_inf, ...
    "final_primal_inequality_inf",finalMetrics.primal_inequality_inf, ...
    "final_dual_scaled_inf",finalMetrics.dual_scaled_inf, ...
    "final_mean_lz_scaled",finalMetrics.mean_lz_scaled, ...
    "final_maximum_water_violation", ...
        finalMetrics.maximum_water_violation));

result = struct("stage_id","stage_B","milestone","B-2C", ...
    "run_id",string(context.run_id),"run_path",string(context.root), ...
    "run_terminal_state",terminalState, ...
    "convergence_achieved",terminalState=="CONVERGED", ...
    "accepted_iteration_count",accepted, ...
    "state_update_count",accepted,"iteration_limit",limit, ...
    "formal_execution",formalExecution, ...
    "initial_metrics",initialMetrics,"final_metrics",finalMetrics, ...
    "final_state",state,"final_linearization",linearization, ...
    "iteration_history",iterationHistory, ...
    "residual_history",residualHistory,"step_history",stepHistory, ...
    "direction_audit_history",directionHistory, ...
    "water_hessian_history",waterHessianHistory, ...
    "objective_history",objectiveHistory,"timing_history",timingHistory, ...
    "daily_joint_factorization_history",factorizationHistory, ...
    "water_slack_second_order_correction_history", ...
        waterCorrectionHistory, ...
    "execution_audit",executionAudit,"failure",failure, ...
    "last_step",lastStep,"solver_seconds",toc(runTimer), ...
    "full_kkt_role","audit_only", ...
    "recursive_direction_is_formal",true, ...
    "water_slack_second_order_correction_enabled",true, ...
    "no_full_direction_fallback", ...
        executionAudit.no_full_direction_fallback, ...
    "full_direction_consumed_by_recursive",false);
end

function validate_contract(config,context)
manifest = jsondecode(fileread(context.run_manifest_path));
assert(string(manifest.stage_id)=="stage_B" && ...
    string(manifest.status)=="RUNNING" && ...
    config.milestone_id=="B-2C" && config.max_iterations==100 && ...
    config.recursive_route== ...
        "all_inequality_daily_joint_final_kkt_residual_gate" && ...
    config.recursive_refinement_max_passes==0 && ...
    config.recursive_congruence_scaling_enabled && ...
    config.equilibration_passes==0 && ...
    config.step_strategy=="independent" && ...
    config.centering_sigma==0.1 && ...
    config.fraction_to_boundary==0.9995, ...
    "stageB2C:ipm:Contract", ...
    "The formal B-2C run context or frozen algorithm contract changed.");
end

function assert_iteration_route(step,config)
responses = step.recursive.responses;
assert(numel(responses)==7 && all(arrayfun( ...
    @(x)x.rhs_count==15 && x.factor.factorization_count==1 && ...
    ~x.factor.blocking_warning_present && ...
    (~x.factor.warning_present || ...
        (x.factor.warning_continued && x.factor.inertia_zero>0)) && ...
    x.factor.solution_finite,responses)) && ...
    step.recursive.core.dimension==16 && ...
    step.recursive.core.factor.factorization_count==1 && ...
    ~step.recursive.core.factor.warning_present && ...
    step.recursive.core.factor.solution_finite && ...
    step.recursive.partition.full_inequality_elimination && ...
    step.recursive.partition.water_eta_dimension==0 && ...
    step.recursive.diagnostics.final_kkt_residual_gate_passed && ...
    step.recursive.diagnostics.candidate_kkt_relative_residual<= ...
        config.recursive_full_kkt_residual_tolerance && ...
    ~step.recursive.diagnostics.local_response_residual_is_blocking && ...
    step.direction_audit.all_pass && ...
    step.direction_audit.direction_relative_error<= ...
        config.direction_relative_error_tolerance && ...
    step.direction_audit.recursive_kkt_relative_residual<= ...
        config.recursive_full_kkt_residual_tolerance && ...
    step.direction_audit.full_kkt_relative_residual<= ...
        config.full_kkt_residual_tolerance && ...
    step.water_slack_second_order_correction_applied && ...
    step.water_slack_second_order_correction_scope_count==56 && ...
    step.only_water_slacks_corrected && ...
    step.water_slack_second_order_correction.correction_fraction>0 && ...
    step.water_slack_second_order_correction.correction_fraction<=1 && ...
    step.water_slack_second_order_correction.all_strictly_positive && ...
    step.water_residual_rebuild_closure<=max( ...
        step.water_slack_second_order_correction.audit.closure_tolerance) && ...
    step.no_full_direction_fallback && ...
    ~step.full_direction_consumed_by_recursive && ...
    ~step.factor_reused_across_iterations, ...
    "stageB2C:ipm:IterationRoute", ...
    "A B-2C iteration violated the daily-joint final-KKT audit contract.");
end

