function [resultHigh,resultLow] = sparse_matvec_high_low( ...
        matrix,xHigh,xLow)
pattern = sparse_row_pattern_mixed(matrix);
resultHigh = zeros(size(matrix,1),size(xHigh,2));
resultLow = zeros(size(resultHigh));
for row = 1:pattern.dimension
    count = pattern.counts(row);
    positions = pattern.starts(row):(pattern.starts(row)+count-1);
    columns = pattern.column(positions);
    entries = pattern.value(positions);
    for rhsColumn = 1:size(xHigh,2)
        accumulatorHigh = 0;
        accumulatorLow = 0;
        for k = 1:count
            [productHigh,productLow] = multiply_double_high_low( ...
                entries(k),xHigh(columns(k),rhsColumn), ...
                xLow(columns(k),rhsColumn));
            [accumulatorHigh,accumulatorLow] = add_high_low_mixed( ...
                accumulatorHigh,accumulatorLow,productHigh,productLow);
        end
        [resultHigh(row,rhsColumn),resultLow(row,rhsColumn)] = ...
            two_sum_mixed(accumulatorHigh,accumulatorLow);
    end
end
end

function result = vpa_sparse_matvec( ...
        matrix,xHigh,xLow,vpaDigits)
pattern = sparse_row_pattern_mixed(matrix);
xVpa = double_pair_to_vpa(xHigh,xLow,vpaDigits);
result = vpa(zeros(size(matrix,1),size(xHigh,2)),vpaDigits);
for row = 1:pattern.dimension
    count = pattern.counts(row);
    if count==0
        continue
    end
    positions = pattern.starts(row):(pattern.starts(row)+count-1);
    columns = pattern.column(positions);
    entriesVpa = exact_double_to_vpa(pattern.value(positions),vpaDigits);
    result(row,:) = sum(entriesVpa.*xVpa(columns,:),1);
end
end

function [productHigh,productLow] = multiply_double_high_low( ...
        coefficient,xHigh,xLow)
[firstHigh,firstLow] = two_product_mixed(coefficient,xHigh);
[secondHigh,secondLow] = two_product_mixed(coefficient,xLow);
[productHigh,productLow] = add_high_low_mixed( ...
    firstHigh,firstLow,secondHigh,secondLow);
end

function [quotientHigh,quotientLow] = divide_high_low_by_double( ...
        numeratorHigh,numeratorLow,denominator)
assert(all(isfinite(denominator)) && all(denominator~=0), ...
    "mixedDirection:DivisionDenominator", ...
    "A high/low division denominator is zero or nonfinite.");
quotientHigh = numeratorHigh./denominator;
quotientLow = zeros(size(quotientHigh));
for pass = 1:2
    [productHigh,productLow] = multiply_double_high_low( ...
        denominator,quotientHigh,quotientLow);
    [remainderHigh,remainderLow] = add_high_low_mixed( ...
        numeratorHigh,numeratorLow,-productHigh,-productLow);
    correction = (remainderHigh+remainderLow)./denominator;
    [quotientHigh,quotientLow] = add_double_to_high_low_mixed( ...
        quotientHigh,quotientLow,correction);
end
end

