function value = norm_high_low_mixed(high,low)
sumHigh = 0;
sumLow = 0;
for k = 1:numel(high)
    [squareHigh,squareLow] = two_product_mixed(high(k),high(k));
    [crossHigh,crossLow] = two_product_mixed(2*high(k),low(k));
    [lowSquareHigh,lowSquareLow] = two_product_mixed(low(k),low(k));
    [termHigh,termLow] = add_high_low_mixed( ...
        squareHigh,squareLow,crossHigh,crossLow);
    [termHigh,termLow] = add_high_low_mixed( ...
        termHigh,termLow,lowSquareHigh,lowSquareLow);
    [sumHigh,sumLow] = add_high_low_mixed( ...
        sumHigh,sumLow,termHigh,termLow);
end
value = sqrt(sumHigh+sumLow);
end

