for pass = 0:maximumPasses
    residualTimer = tic;
    [actionHigh,actionLow] = factor_reduced_target_action_high_low( ...
        retained,target,kept,delayed,solutionHigh,solutionLow);
    [residualHigh,residualLow] = add_high_low_mixed( ...
        rhsHigh,rhsLow,-actionHigh,-actionLow);
    residualSeconds = toc(residualTimer);
    residualNorm = vecnorm(residualHigh+residualLow,2,1);
    rhsNorm = max(ones(1,size(rhsHigh,2)), ...
