    end
    if pass>0
        if currentMaximum>=previousMaximum
            nonShrinkCount = nonShrinkCount+1;
        else
            nonShrinkCount = 0;
        end
        if nonShrinkCount>=2
            stopReason = "two_consecutive_nonshrinking_passes";
            break
        end
    end
    previousMaximum = currentMaximum;
    correctionTimer = tic;
    correction = apply_retained_d_kept_inverse( ...
        retained.D,kept,residualHigh+residualLow);
    timingRows(pass+1).correction_wall_seconds = toc(correctionTimer);
    [solutionHigh,solutionLow] = add_double_to_high_low_mixed( ...
        solutionHigh,solutionLow,correction);
    correctionsApplied = correctionsApplied+1;
end
solutionHigh = bestHigh;
solutionLow = bestLow;
history.selected_solution = history.pass==bestPass;
timing = struct2table(timingRows(1:lastPass+1));
selectedRows = history(history.pass==bestPass,:);
diagnostics = struct( ...
    "passes_evaluated",lastPass, ...
    "corrections_applied",correctionsApplied, ...
    "maximum_passes",maximumPasses,"first_gate_pass",firstGatePass, ...
    "selected_pass",bestPass,"stop_reason",string(stopReason), ...
    "initial_maximum_relative_residual", ...
        max(history.relative_residual(history.pass==0)), ...
    "selected_maximum_relative_residual", ...
        max(selectedRows.relative_residual), ...
    "selected_maximum_componentwise_backward_error",NaN, ...
    "elapsed_seconds",toc(timer),"factorization_count",1, ...
    "additional_factorization_count",0, ...
    "delayed_coordinate_count",numel(delayed),"label",label);
end

