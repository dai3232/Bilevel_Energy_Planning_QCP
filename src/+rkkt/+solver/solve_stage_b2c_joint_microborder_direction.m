function responses = formal_response_array( ...
        responseCells,problemPosition,micro,problemResponse, ...
        problemFactor,affineRefinement,coreDimension)
a = problemResponse.a_high+problemResponse.a_low;
U = problemResponse.U_high(:,1:16)+problemResponse.U_low(:,1:16);
borderHigh = problemResponse.U_high(:,17);
borderLow = problemResponse.U_low(:,17);
promotedHigh = problemResponse.U_high(:,18:end);
promotedLow = problemResponse.U_low(:,18:end);
problemFactor.maximum_column_relative_residual = ...
    affineRefinement.selected_maximum_relative_residual;
problemFactor.initial_maximum_column_relative_residual = ...
    affineRefinement.initial_maximum_relative_residual;
problemFactor.refinement_enabled = affineRefinement.maximum_passes>0;
problemFactor.refinement_triggered = ...
    affineRefinement.corrections_applied>0;
problemFactor.refinement_maximum_passes = affineRefinement.maximum_passes;
