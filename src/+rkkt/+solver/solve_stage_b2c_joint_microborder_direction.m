function [solutionHigh,solutionLow,history,timing,diagnostics] = ...
        refine_factor_promoted_final_solution( ...
        retained,target,promotion,rhsHigh,rhsLow, ...
        solutionHigh,solutionLow,rhsLabels,tolerance,maximumPasses,label)
assert(target.enabled && promotion.enabled && numel(rhsLabels)==1, ...
    "mixedDirection:PromotedFinalContract", ...
    "The promoted final recovery contract is invalid.");
pattern = sparse_row_pattern_mixed(target.base_matrix);
history = table();
timingRows = repmat(struct("pass",NaN, ...
    "accurate_residual_seconds",NaN,"correction_wall_seconds",NaN, ...
    "maximum_relative_residual",NaN,"all_columns_pass",false, ...
    "factorization_count",1,"additional_factorization_count",0), ...
    maximumPasses+1,1);
bestNorm = Inf;
bestPass = NaN;
bestHigh = solutionHigh;
bestLow = solutionLow;
firstGatePass = NaN;
previousNorm = Inf;
nonShrinkCount = 0;
correctionsApplied = 0;
stopReason = "maximum_passes";
lastPass = 0;
timer = tic;
for pass = 0:maximumPasses
    residualTimer = tic;
    [residualHigh,residualLow] = ...
        accurate_target_operator_residual_high_low( ...
            pattern,target,solutionHigh,solutionLow,rhsHigh,rhsLow);
    residualSeconds = toc(residualTimer);
    residualNorm = norm_high_low_mixed(residualHigh,residualLow);
    rhsNorm = max(1,norm_high_low_mixed(rhsHigh,rhsLow));
    relativeResidual = residualNorm/rhsNorm;
    maximumAbsolute = max(abs(residualHigh)+abs(residualLow));
    history = [history;table(pass,string(rhsLabels),relativeResidual, ...
        residualNorm,maximumAbsolute, ...
        'VariableNames',{'pass','rhs_label','relative_residual', ...
        'residual_norm','maximum_absolute_residual'})]; %#ok<AGROW>
    timingRows(pass+1).pass = pass;
    timingRows(pass+1).accurate_residual_seconds = residualSeconds;
    timingRows(pass+1).maximum_relative_residual = relativeResidual;
    timingRows(pass+1).all_columns_pass = relativeResidual<=tolerance;
    lastPass = pass;
    if residualNorm<bestNorm
        bestNorm = residualNorm;
        bestPass = pass;
        bestHigh = solutionHigh;
        bestLow = solutionLow;
    end
    if isnan(firstGatePass) && relativeResidual<=tolerance
        firstGatePass = pass;
    end
    if pass==maximumPasses
        stopReason = "maximum_passes_after_gate";
        break
    end
    if pass>0
        if residualNorm>=previousNorm
            nonShrinkCount = nonShrinkCount+1;
        else
            nonShrinkCount = 0;
        end
        if nonShrinkCount>=2
            stopReason = "two_consecutive_nonshrinking_passes";
            break
        end
    end
    previousNorm = residualNorm;
    correctionTimer = tic;
    [factorResidualHigh,factorResidualLow] = ...
        factor_rhs_transform_high_low( ...
            retained,residualHigh,residualLow);
    correctionR = apply_retained_d_kept_inverse( ...
        retained.D,promotion.kept_indices, ...
        factorResidualHigh(promotion.kept_indices)+ ...
        factorResidualLow(promotion.kept_indices));
    [correctionHigh,correctionLow] = ...
        embed_and_map_factor_coordinates( ...
            retained,promotion.kept_indices,correctionR, ...
            zeros(size(correctionR)));
    [solutionHigh,solutionLow] = add_high_low_mixed( ...
        solutionHigh,solutionLow,correctionHigh,correctionLow);
    timingRows(pass+1).correction_wall_seconds = toc(correctionTimer);
    correctionsApplied = correctionsApplied+1;
end
solutionHigh = bestHigh;
solutionLow = bestLow;
history.selected_solution = history.pass==bestPass;
timing = struct2table(timingRows(1:lastPass+1));
selected = history(history.selected_solution,:);
diagnostics = struct( ...
    "passes_evaluated",lastPass, ...
    "corrections_applied",correctionsApplied, ...
    "maximum_passes",maximumPasses,"first_gate_pass",firstGatePass, ...
    "selected_pass",bestPass,"stop_reason",string(stopReason), ...
    "initial_maximum_relative_residual", ...
        history.relative_residual(1), ...
    "selected_maximum_relative_residual",selected.relative_residual, ...
    "selected_maximum_componentwise_backward_error",NaN, ...
    "elapsed_seconds",toc(timer),"factorization_count",1, ...
    "additional_factorization_count",0,"label",label);
end

