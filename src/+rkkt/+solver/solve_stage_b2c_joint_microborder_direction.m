    exact_double_to_vpa(low,vpaDigits);
end

function [high,low] = vpa_to_high_low(value,vpaDigits)
high = double(value);
low = double(value-exact_double_to_vpa(high,vpaDigits));
[high,low] = add_high_low_mixed( ...
    high,zeros(size(high)),low,zeros(size(low)));
end

function pattern = sparse_row_pattern_mixed(matrix)
[row,column,value] = find(sparse(matrix));
[~,order] = sortrows([row,column],[1,2]);
row = row(order);
column = column(order);
value = value(order);
counts = accumarray(row,1,[size(matrix,1),1]);
starts = cumsum([1;counts(1:end-1)]);
pattern = struct("dimension",size(matrix,1),"row",row, ...
    "column",column,"value",value,"counts",counts,"starts",starts);
end

function [residualHigh,residualLow] = accurate_sparse_residual_high_low( ...
        pattern,solutionHigh,solutionLow,rhsHigh,rhsLow)
residualHigh = zeros(size(rhsHigh));
residualLow = zeros(size(rhsLow));
for row = 1:pattern.dimension
    count = pattern.counts(row);
    positions = pattern.starts(row):(pattern.starts(row)+count-1);
    columns = pattern.column(positions);
    entries = pattern.value(positions);
    for rhsColumn = 1:size(solutionHigh,2)
        accumulatorHigh = rhsHigh(row,rhsColumn);
        accumulatorLow = rhsLow(row,rhsColumn);
        for k = 1:count
            [productHigh,productLow] = two_product_mixed( ...
                entries(k),solutionHigh(columns(k),rhsColumn));
            [accumulatorHigh,accumulatorLow] = add_high_low_mixed( ...
                accumulatorHigh,accumulatorLow, ...
                -productHigh,-productLow);
            [productHigh,productLow] = two_product_mixed( ...
                entries(k),solutionLow(columns(k),rhsColumn));
            [accumulatorHigh,accumulatorLow] = add_high_low_mixed( ...
                accumulatorHigh,accumulatorLow, ...
                -productHigh,-productLow);
        end
        [residualHigh(row,rhsColumn),residualLow(row,rhsColumn)] = ...
            two_sum_mixed(accumulatorHigh,accumulatorLow);
    end
end
assert(all(isfinite(residualHigh),"all") && ...
    all(isfinite(residualLow),"all"), ...
    "mixedDirection:ResidualFinite", ...
    "Double-double residual reconstruction produced NaN or Inf.");
end

function [residualHigh,residualLow] = ...
        accurate_target_operator_residual_high_low( ...
        operatorPattern,target,solutionHigh,solutionLow,rhsHigh,rhsLow)
[residualHigh,residualLow] = accurate_sparse_residual_high_low( ...
    operatorPattern,solutionHigh,solutionLow,rhsHigh,rhsLow);
if target.physical_operator
    [jacobianXHigh,jacobianXLow] = sparse_matvec_high_low( ...
        target.selected_jacobian,solutionHigh,solutionLow);
    [weightedHigh,weightedLow] = multiply_high_low_pair_mixed( ...
        target.theta_high,target.theta_low,jacobianXHigh,jacobianXLow);
    [selectedActionHigh,selectedActionLow] = sparse_matvec_high_low( ...
        target.selected_jacobian.',weightedHigh,weightedLow);
    [residualHigh,residualLow] = add_high_low_mixed( ...
        residualHigh,residualLow,-selectedActionHigh,-selectedActionLow);
end
[dotHigh,dotLow] = dot_high_low_columns( ...
    target.c_high,target.c_low,solutionHigh,solutionLow);
[quotientHigh,quotientLow] = divide_high_low_by_high_low_mixed( ...
    dotHigh,dotLow,target.d_high,target.d_low);
[rankHigh,rankLow] = multiply_high_low_pair_mixed( ...
    full(target.c_high),full(target.c_low),quotientHigh,quotientLow);
[residualHigh,residualLow] = add_high_low_mixed( ...
    residualHigh,residualLow,rankHigh,rankLow);
assert(all(isfinite(residualHigh),"all") && ...
    all(isfinite(residualLow),"all"), ...
    "mixedDirection:TargetResidualFinite", ...
    "The target-operator high/low residual is nonfinite.");
end

function denominator = target_operator_componentwise_denominator( ...
        target,solutionHigh,solutionLow,rhsHigh,rhsLow)
solutionMagnitude = abs(solutionHigh)+abs(solutionLow);
cMagnitude = abs(full(target.c_high))+abs(full(target.c_low));
dMagnitude = abs(target.d_high)+abs(target.d_low);
rankMagnitude = cMagnitude*((cMagnitude.'*solutionMagnitude)./dMagnitude);
if target.physical_operator
    jacobianMagnitude = abs(target.selected_jacobian)*solutionMagnitude;
    thetaMagnitude = abs(target.theta_high)+abs(target.theta_low);
    selectedMagnitude = abs(target.selected_jacobian).'*( ...
        thetaMagnitude.*jacobianMagnitude);
    operatorMagnitude = abs(target.base_matrix)*solutionMagnitude+ ...
        selectedMagnitude;
else
    operatorMagnitude = abs(target.canonical_matrix)*solutionMagnitude;
end
denominator = operatorMagnitude+rankMagnitude+abs(rhsHigh)+abs(rhsLow);
end

function [dotHigh,dotLow] = dot_high_low_columns( ...
        coefficientHigh,coefficientLow,xHigh,xLow)
coefficientHigh = full(coefficientHigh);
coefficientLow = full(coefficientLow);
active = find(coefficientHigh~=0 | coefficientLow~=0);
dotHigh = zeros(1,size(xHigh,2));
dotLow = zeros(size(dotHigh));
for k = 1:numel(active)
    row = active(k);
    [productHigh,productLow] = multiply_high_low_pair_mixed( ...
        coefficientHigh(row),coefficientLow(row), ...
        xHigh(row,:),xLow(row,:));
    [dotHigh,dotLow] = add_high_low_mixed( ...
        dotHigh,dotLow,productHigh,productLow);
end
end

function [quotientHigh,quotientLow] = ...
        divide_high_low_by_high_low_mixed( ...
        numeratorHigh,numeratorLow,denominatorHigh,denominatorLow)
denominator = denominatorHigh+denominatorLow;
assert(isscalar(denominator) && isfinite(denominator) && denominator~=0, ...
    "mixedDirection:TargetDivisionDenominator", ...
    "The target-operator high/low denominator is invalid.");
quotientHigh = (numeratorHigh+numeratorLow)./denominator;
quotientLow = zeros(size(quotientHigh));
for pass = 1:2
    [productHigh,productLow] = multiply_high_low_pair_mixed( ...
        denominatorHigh,denominatorLow,quotientHigh,quotientLow);
    [remainderHigh,remainderLow] = add_high_low_mixed( ...
        numeratorHigh,numeratorLow,-productHigh,-productLow);
    correction = (remainderHigh+remainderLow)./denominator;
    [quotientHigh,quotientLow] = add_high_low_mixed( ...
        quotientHigh,quotientLow,correction,zeros(size(correction)));
end
end

function [productHigh,productLow] = multiply_high_low_pair_mixed( ...
        leftHigh,leftLow,rightHigh,rightLow)
[firstHigh,firstLow] = two_product_mixed(leftHigh,rightHigh);
[secondHigh,secondLow] = two_product_mixed(leftHigh,rightLow);
[thirdHigh,thirdLow] = two_product_mixed(leftLow,rightHigh);
[fourthHigh,fourthLow] = two_product_mixed(leftLow,rightLow);
[productHigh,productLow] = add_high_low_mixed( ...
    firstHigh,firstLow,secondHigh,secondLow);
[productHigh,productLow] = add_high_low_mixed( ...
    productHigh,productLow,thirdHigh,thirdLow);
[productHigh,productLow] = add_high_low_mixed( ...
    productHigh,productLow,fourthHigh,fourthLow);
end

function [high,low] = add_double_to_high_low_mixed(high,low,value)
[high,low] = add_high_low_mixed( ...
    high,low,value,zeros(size(value)));
end

function [high,low] = add_high_low_mixed(aHigh,aLow,bHigh,bLow)
[sumHigh,sumError] = two_sum_mixed(aHigh,bHigh);
[lowHigh,lowError] = two_sum_mixed(aLow,bLow);
[middleHigh,middleError] = two_sum_mixed(sumError,lowHigh);
[sumHigh,sumError] = two_sum_mixed(sumHigh,middleHigh);
[lowHigh,lowError2] = two_sum_mixed(sumError,lowError);
[lowHigh,lowError3] = two_sum_mixed(lowHigh,middleError);
[lowError,lowTail] = two_sum_mixed(lowError2,lowError3);
[sumHigh,sumError] = two_sum_mixed(sumHigh,lowHigh);
[sumError,lowHigh] = two_sum_mixed(sumError,lowError);
[lowHigh,lowError] = two_sum_mixed(lowHigh,lowTail);
[sumError,lowHigh] = two_sum_mixed(sumError,lowHigh);
[lowHigh,lowError] = two_sum_mixed(lowHigh,lowError);
[high,low] = two_sum_mixed(sumHigh,sumError);
[low,lowTail] = two_sum_mixed(low,lowHigh);
[lowError,~] = two_sum_mixed(lowError,lowTail);
[low,~] = two_sum_mixed(low,lowError);
[high,low] = two_sum_mixed(high,low);
end

function [product,errorValue] = two_product_mixed(left,right)
splitter = 134217729;
product = left.*right;
leftSplit = splitter.*left;
leftHigh = leftSplit-(leftSplit-left);
leftLow = left-leftHigh;
rightSplit = splitter.*right;
rightHigh = rightSplit-(rightSplit-right);
rightLow = right-rightHigh;
errorValue = ((leftHigh.*rightHigh-product)+ ...
    leftHigh.*rightLow+leftLow.*rightHigh)+leftLow.*rightLow;
end

function [sumValue,errorValue] = two_sum_mixed(left,right)
sumValue = left+right;
rightVirtual = sumValue-left;
errorValue = (left-(sumValue-rightVirtual))+(right-rightVirtual);
end

