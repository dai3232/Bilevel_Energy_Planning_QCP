    affineRefinement.corrections_applied;
problemFactor.refinement_additional_factorization_count = 0;
problemFactor.local_residual_target_met = ...
    affineRefinement.selected_maximum_relative_residual<= ...
        problemFactor.local_residual_tolerance;
templatePosition = find((1:numel(responseCells)).'~=problemPosition,1);
assert(isscalar(templatePosition), ...
    "stageB2C:jointMicroborder:ResponseTemplate", ...
    "The micro-border response array requires at least one ordinary day.");
problem = responseCells{templatePosition};
problem.stage_id = "stage_B";
problem.milestone_id = "B-2C";
problem.linearization_identity = micro.linearization_identity;
problem.day_id = micro.day_id;
problem.a = a;
problem.U = U;
problem.p = a(micro.pi_day_local_positions);
problem.S = -U(micro.pi_day_local_positions,1:14);
problem.schur_matrix_contribution = micro.coupling.'*U;
problem.schur_rhs_contribution = micro.coupling.'*a;
problem.factor = problemFactor;
problem.dimension = micro.dimension;
problem.rhs_count = 16;
problem.water_eta_dimension = 0;
responseCells{problemPosition} = problem;

recoveryContract = ...
    "u_day=a-U*core_solution(1:16)-border_response*core_solution(17)" + ...
    "-factor_promoted_response*core_solution(18:end); " + ...
    "retained_LDL_preconditions_only_if_residual_fails";
for d = 1:numel(responseCells)
    response = responseCells{d};
    response.a_high = response.a;
    response.a_low = zeros(size(response.a));
    response.U_high = response.U;
    response.U_low = sparse(size(response.U,1),size(response.U,2));
    response.border_response_high = zeros(response.dimension,1);
    response.border_response_low = zeros(response.dimension,1);
    response.factor_promoted_response_high = ...
        zeros(response.dimension,max(0,coreDimension-17));
    response.factor_promoted_response_low = ...
        zeros(response.dimension,max(0,coreDimension-17));
    if d==problemPosition
        response.a_high = problemResponse.a_high;
        response.a_low = problemResponse.a_low;
        response.U_high = problemResponse.U_high(:,1:16);
        response.U_low = problemResponse.U_low(:,1:16);
        response.border_response_high = borderHigh;
        response.border_response_low = borderLow;
        response.factor_promoted_response_high = promotedHigh;
        response.factor_promoted_response_low = promotedLow;
    end
    response.border_response = response.border_response_high+ ...
        response.border_response_low;
    response.factor_promoted_response = ...
        response.factor_promoted_response_high+ ...
        response.factor_promoted_response_low;
    response.core_solution_dimension = coreDimension;
    response.response_contract = recoveryContract;
    response.recovery_contract = recoveryContract;
    response.augmented_schur_matrix_contribution = ...
        zeros(coreDimension,coreDimension);
    response.augmented_schur_rhs_contribution = zeros(coreDimension,1);
    if d==problemPosition
        borderC = micro.target_operator.border_c_high+ ...
            micro.target_operator.border_c_low;
        augmentedCoupling = [micro.coupling,borderC];
        augmentedResponse = [response.U,response.border_response, ...
            response.factor_promoted_response];
        response.augmented_schur_matrix_contribution(1:17,:) = ...
            augmentedCoupling.'*augmentedResponse;
        response.augmented_schur_rhs_contribution(1:17) = ...
            augmentedCoupling.'*response.a;
    else
        response.augmented_schur_matrix_contribution(1:16,1:16) = ...
            response.schur_matrix_contribution;
        response.augmented_schur_rhs_contribution(1:16) = ...
            response.schur_rhs_contribution;
    end
    responseCells{d} = response;
end
responses = vertcat(responseCells{:});
end

