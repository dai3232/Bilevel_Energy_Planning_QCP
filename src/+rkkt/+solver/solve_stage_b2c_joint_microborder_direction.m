function [delayed,kept,blockTable] = ...
        select_delayed_factor_blocks(D,pivotTolerance)
n = size(D,1);
delayed = zeros(0,1);
rows = struct("first_index",{},"last_index",{}, ...
    "block_dimension",{},"minimum_absolute_eigenvalue",{}, ...
    "delayed",{});
cursor = 1;
blockNumber = 0;
while cursor<=n
    if cursor<n && D(cursor+1,cursor)~=0
        indices = (cursor:cursor+1).';
    else
        indices = cursor;
    end
    eigenvalues = eig(full(D(indices,indices)));
    isDelayed = any(abs(eigenvalues)<=pivotTolerance);
    if isDelayed
        delayed = [delayed;indices]; %#ok<AGROW>
    end
    blockNumber = blockNumber+1;
    rows(blockNumber) = struct( ... %#ok<AGROW>
        "first_index",indices(1),"last_index",indices(end), ...
        "block_dimension",numel(indices), ...
        "minimum_absolute_eigenvalue",min(abs(eigenvalues)), ...
        "delayed",isDelayed);
    cursor = indices(end)+1;
end
kept = setdiff((1:n).',delayed,"stable");
blockTable = struct2table(rows);
end

function [solutionHigh,solutionLow,history,timing,diagnostics] = ...
        refine_factor_reduced_target_responses( ...
        retained,target,kept,delayed,rhsHigh,rhsLow,rhsLabels, ...
        tolerance,maximumPasses,label)
initial = apply_retained_d_kept_inverse( ...
    retained.D,kept,rhsHigh+rhsLow);
solutionHigh = initial;
solutionLow = zeros(size(initial));
history = table();
timingRows = repmat(struct("pass",NaN, ...
    "accurate_residual_seconds",NaN,"correction_wall_seconds",NaN, ...
