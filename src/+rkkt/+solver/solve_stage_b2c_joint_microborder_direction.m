function target = build_global_base_high_low( ...
        lin,contract,partition,enabled,vpaDigits)
canonicalMatrix = full(partition.global.matrix);
canonicalRhs = full(partition.global.rhs);
if ~enabled
    matrixHigh = canonicalMatrix;
    matrixLow = zeros(size(canonicalMatrix));
    rhsHigh = canonicalRhs;
    rhsLow = zeros(size(canonicalRhs));
    target = struct( ...
        "enabled",false,"matrix_high",matrixHigh, ...
        "matrix_low",matrixLow,"rhs_high",rhsHigh, ...
        "rhs_low",rhsLow, ...
        "matrix_vpa",exact_double_to_vpa(matrixHigh,vpaDigits), ...
        "rhs_vpa",exact_double_to_vpa(rhsHigh,vpaDigits), ...
        "canonical_matrix_relative_difference",0, ...
        "canonical_rhs_relative_difference",0, ...
        "touching_inequality_rows",zeros(0,1));
    return
end

previousDigits = digits(vpaDigits);
restoreDigits = onCleanup(@() digits(previousDigits));
q = contract.q_global;
yDuration = contract.y_duration;
gGlobal = sparse(lin.G(:,q));
touchingRows = find(any(gGlobal,2));
gVpa = exact_double_to_vpa(full(gGlobal(touchingRows,:)),vpaDigits);
lVpa = exact_double_to_vpa(contract.l(touchingRows),vpaDigits);
zVpa = exact_double_to_vpa(contract.z(touchingRows),vpaDigits);
rCompVpa = exact_double_to_vpa( ...
    contract.r_comp(touchingRows),vpaDigits);
rIneqVpa = exact_double_to_vpa( ...
    contract.r_ineq(touchingRows),vpaDigits);
thetaSourceVpa = zVpa./lVpa;
phiSourceVpa = (rCompVpa-zVpa.*rIneqVpa)./lVpa;
[thetaHigh,thetaLow] = vpa_to_high_low(thetaSourceVpa,vpaDigits);
[phiHigh,phiLow] = vpa_to_high_low(phiSourceVpa,vpaDigits);
thetaPairVpa = double_pair_to_vpa(thetaHigh,thetaLow,vpaDigits);
phiPairVpa = double_pair_to_vpa(phiHigh,phiLow,vpaDigits);

hVpa = exact_double_to_vpa(full(lin.H(q,q)),vpaDigits);
weightedGVpa = repmat(thetaPairVpa,1,numel(q)).*gVpa;
wVpa = hVpa+gVpa.'*weightedGVpa;
aDurationVpa = exact_double_to_vpa( ...
    full(lin.A(yDuration,q)),vpaDigits);
matrixSourceVpa = [wVpa,aDurationVpa.'; ...
    aDurationVpa,vpa(zeros(numel(yDuration),numel(yDuration)),vpaDigits)];
rhsQSourceVpa = -exact_double_to_vpa(contract.r_dual(q),vpaDigits)+ ...
    gVpa.'*phiPairVpa;
rhsSourceVpa = [rhsQSourceVpa; ...
    -exact_double_to_vpa(contract.r_eq(yDuration),vpaDigits)];
[matrixHigh,matrixLow] = vpa_to_high_low(matrixSourceVpa,vpaDigits);
[rhsHigh,rhsLow] = vpa_to_high_low(rhsSourceVpa,vpaDigits);
matrixPairVpa = double_pair_to_vpa(matrixHigh,matrixLow,vpaDigits);
rhsPairVpa = double_pair_to_vpa(rhsHigh,rhsLow,vpaDigits);
canonicalMatrixVpa = exact_double_to_vpa(canonicalMatrix,vpaDigits);
canonicalRhsVpa = exact_double_to_vpa(canonicalRhs,vpaDigits);
matrixDifference = norm(matrixPairVpa-canonicalMatrixVpa,'fro')/ ...
    max(vpa(1,vpaDigits),norm(canonicalMatrixVpa,'fro'));
rhsDifference = norm(rhsPairVpa-canonicalRhsVpa,2)/ ...
    max(vpa(1,vpaDigits),norm(canonicalRhsVpa,2));
target = struct( ...
    "enabled",true,"matrix_high",matrixHigh, ...
    "matrix_low",matrixLow,"rhs_high",rhsHigh,"rhs_low",rhsLow, ...
    "matrix_vpa",matrixPairVpa,"rhs_vpa",rhsPairVpa, ...
    "theta_high",thetaHigh,"theta_low",thetaLow, ...
    "phi_high",phiHigh,"phi_low",phiLow, ...
    "touching_inequality_rows",touchingRows, ...
    "canonical_matrix_relative_difference",double(matrixDifference), ...
    "canonical_rhs_relative_difference",double(rhsDifference));
clear restoreDigits
end

function micro = build_joint_microborder_day( ...
        lin,index,contract,partition,position,problemDayId,relationHours, ...
        symmetryTolerance,targetOperatorEnabled,physicalOperatorEnabled, ...
        scaledGammaCoordinate,vpaDigits)
day = partition.day(position);
rows = [vertcat(contract.ineq_by_day_hour{position,:}); ...
    contract.water_by_day{position}];
rows = rows(:);
assert(numel(unique(rows))==numel(rows), ...
    "jointMicroborder:InequalityRows", ...
    "The problem-day inequality rows are not unique.");

[equalityMeta,inequalityMeta] = canonical_constraint_metadata( ...
    index,contract);
dayInequalityMeta = inequalityMeta(rows,:);
assert(all(dayInequalityMeta.day==problemDayId), ...
    "jointMicroborder:InequalityMetadata", ...
    "The contract day rows disagree with constraint metadata.");

localCanonical = day.canonical_reduced_indices;
localPrimalPositions = find(localCanonical<=contract.nx);
localPrimalCanonical = localCanonical(localPrimalPositions);
dayJacobianAll = sparse(lin.G(rows,:));
outside = true(contract.nx,1);
outside(localPrimalCanonical) = false;
assert(nnz(dayJacobianAll(:,outside))==0, ...
    "jointMicroborder:ExternalInequalityCoupling", ...
    "The problem-day inequalities couple outside the local primal slice.");
dayJacobian = dayJacobianAll(:,localPrimalCanonical);
embeddedJacobian = sparse(numel(rows),day.dimension);
embeddedJacobian(:,localPrimalPositions) = dayJacobian;

[a,b,relationTable] = build_relation_coefficients( ...
    lin,contract,equalityMeta,inequalityMeta,rows,localPrimalCanonical, ...
    problemDayId,relationHours);
jointColumn = embeddedJacobian.'*b;
jointGradient = sparse(lin.A).'*a+sparse(lin.G).'* ...
    embed_rows(b,rows,contract.nineq);
localGradient = jointGradient(localPrimalCanonical);
localScale = max(1,norm(sparse(lin.A(:,localPrimalCanonical)),"fro")* ...
    norm(a,2)+norm(dayJacobian,"fro")*norm(b,2));
localGradientRelative = norm(localGradient,2)/localScale;
assert(localGradientRelative<=1024*eps, ...
    "jointMicroborder:RelationResidual", ...
    "The label-derived joint relation residual %.17g is not exact.", ...
    localGradientRelative);

touchingRows = find(any(sparse(lin.G(:,localPrimalCanonical)),2));
otherRows = setdiff(touchingRows,rows,"stable");
otherJacobian = sparse(lin.G(otherRows,localPrimalCanonical));
otherTheta = contract.z(otherRows)./contract.l(otherRows);
otherPhi = (contract.r_comp(otherRows)- ...
    contract.z(otherRows).*contract.r_ineq(otherRows))./ ...
    contract.l(otherRows);
directW = sparse(lin.H(localPrimalCanonical,localPrimalCanonical))+ ...
    otherJacobian.'*(spdiags(otherTheta,0,numel(otherRows), ...
    numel(otherRows))*otherJacobian);
directRhs = -contract.r_dual(localPrimalCanonical)+ ...
    otherJacobian.'*otherPhi;
baseMatrix = day.matrix;
baseRhs = day.rhs;
baseMatrix(localPrimalPositions,localPrimalPositions) = directW;
baseRhs(localPrimalPositions) = directRhs;

theta = contract.z(rows)./contract.l(rows);
inverseTheta = 1./theta;
rNu = contract.r_comp(rows)./contract.z(rows)-contract.r_ineq(rows);
d = full(b.'*(inverseTheta.*b));
rho = full(b.'*rNu);
assert(isfinite(d) && d>0 && isfinite(rho), ...
    "jointMicroborder:FiniteCoordinate", ...
    "The joint micro-border diagonal or right-hand side is invalid.");
sqrtTheta = sqrt(theta);
unit = (b./sqrtTheta)/sqrt(d);
unitNormError = abs(norm(unit,2)-1);
scaledJacobian = spdiags(sqrtTheta,0,numel(rows),numel(rows))* ...
    embeddedJacobian;
scaledRhs = sqrtTheta.*rNu;
projectedJacobian = scaledJacobian-unit*(unit.'*scaledJacobian);
projectedRhs = scaledRhs-unit*(unit.'*scaledRhs);
safeMatrix = baseMatrix+projectedJacobian.'*projectedJacobian;
safeRhs = baseRhs+projectedJacobian.'*projectedRhs;

if targetOperatorEnabled
    [matrixError,rhsError] = matrix_free_safe_equivalence_errors( ...
        safeMatrix,safeRhs,day.matrix,day.rhs,jointColumn,d,rho);
    equivalenceAuditMethod = "matrix_free_column_audit";
else
    rebuiltMatrix = safeMatrix+jointColumn*jointColumn.'/d;
    rebuiltRhs = safeRhs+jointColumn*rho/d;
    matrixError = norm(rebuiltMatrix-day.matrix,"fro")/ ...
        max(1,norm(day.matrix,"fro"));
    rhsError = norm(rebuiltRhs-day.rhs,2)/max(1,norm(day.rhs,2));
    equivalenceAuditMethod = "legacy_explicit_rebuild";
end
safeSymmetry = norm(safeMatrix-safeMatrix.',"fro")/ ...
    max(1,norm(safeMatrix,"fro"));
equivalenceTolerance = max(4096*eps,symmetryTolerance);
assert(unitNormError<=4096*eps && matrixError<=equivalenceTolerance && ...
    rhsError<=equivalenceTolerance && safeSymmetry<=symmetryTolerance, ...
    "jointMicroborder:ProjectionEquivalence", ...
    "The projected same-size daily block is not equivalent to the original.");

outsideLocal = true(contract.nx,1);
outsideLocal(localPrimalCanonical) = false;
externalGradient = jointGradient(outsideLocal);
targetOperator = struct("enabled",false);
if targetOperatorEnabled
    targetOperator = build_target_operator_high_low( ...
        day,baseMatrix,baseRhs,embeddedJacobian,b,contract,rows, ...
        physicalOperatorEnabled,scaledGammaCoordinate,vpaDigits);
end
factorMatrix = sparse(safeMatrix);
factorMatrixMethod = "projected_binary64_safe_matrix";
micro = struct( ...
    "day_id",problemDayId,"dimension",day.dimension, ...
    "linearization_identity",lin.identity, ...
    "safe_matrix",sparse(safeMatrix),"safe_rhs",safeRhs, ...
    "factor_matrix",sparse(factorMatrix), ...
    "factor_matrix_method",factorMatrixMethod, ...
    "coupling",sparse(day.coupling),"joint_column",jointColumn, ...
    "d",d,"rho",rho,"unit",unit,"r_nu",rNu, ...
    "sqrt_theta",sqrtTheta,"projected_jacobian",projectedJacobian, ...
    "inequality_rows",rows,"inequality_coefficients",b, ...
    "equality_coefficients",a,"relation_table",relationTable, ...
    "canonical_reduced_indices",day.canonical_reduced_indices, ...
    "q_day_local_positions",day.q_day_local_positions, ...
    "pi_day_local_positions",day.pi_day_local_positions, ...
    "local_primal_positions",localPrimalPositions, ...
    "local_primal_canonical",localPrimalCanonical, ...
    "unit_norm_error",unitNormError, ...
    "local_gradient_relative_residual",localGradientRelative, ...
    "external_gradient_nonzero_count",nnz(externalGradient), ...
    "matrix_equivalence_error",matrixError, ...
    "rhs_equivalence_error",rhsError, ...
    "equivalence_audit_method",equivalenceAuditMethod, ...
    "safe_symmetry_relative",safeSymmetry, ...
    "target_operator",targetOperator);
end

function [matrixError,rhsError] = matrix_free_safe_equivalence_errors( ...
        safeMatrix,safeRhs,canonicalMatrix,canonicalRhs,c,d,rho)
difference = safeMatrix-canonicalMatrix;
matrixResidualSquared = 0;
for column = 1:size(canonicalMatrix,2)
    residualColumn = difference(:,column)+c*(c(column)/d);
    matrixResidualSquared = matrixResidualSquared+ ...
        norm(residualColumn,2)^2;
end
matrixError = sqrt(matrixResidualSquared)/ ...
    max(1,norm(canonicalMatrix,"fro"));
rhsResidual = safeRhs-canonicalRhs+c*(rho/d);
rhsError = norm(rhsResidual,2)/max(1,norm(canonicalRhs,2));
end

function target = build_target_operator_high_low( ...
        day,baseMatrix,baseRhs,embeddedJacobian,b,contract,rows, ...
        physicalOperatorEnabled,scaledGammaCoordinate,vpaDigits)
previousDigits = digits(vpaDigits);
restoreDigits = onCleanup(@() digits(previousDigits));
bVpa = exact_double_to_vpa(full(b),vpaDigits);
lVpa = exact_double_to_vpa(contract.l(rows),vpaDigits);
zVpa = exact_double_to_vpa(contract.z(rows),vpaDigits);
rCompVpa = exact_double_to_vpa(contract.r_comp(rows),vpaDigits);
rIneqVpa = exact_double_to_vpa(contract.r_ineq(rows),vpaDigits);
inverseThetaSourceVpa = lVpa./zVpa;
thetaSourceVpa = zVpa./lVpa;
rNuSourceVpa = rCompVpa./zVpa-rIneqVpa;
[thetaHigh,thetaLow] = vpa_to_high_low(thetaSourceVpa,vpaDigits);
[inverseThetaHigh,inverseThetaLow] = vpa_to_high_low( ...
    inverseThetaSourceVpa,vpaDigits);
[rNuHigh,rNuLow] = vpa_to_high_low(rNuSourceVpa,vpaDigits);
thetaPairVpa = double_pair_to_vpa(thetaHigh,thetaLow,vpaDigits);
inverseThetaPairVpa = double_pair_to_vpa( ...
    inverseThetaHigh,inverseThetaLow,vpaDigits);
rNuPairVpa = double_pair_to_vpa(rNuHigh,rNuLow,vpaDigits);
cVpa = vpa_sparse_transpose_product( ...
    embeddedJacobian,full(b),zeros(numel(b),1),vpaDigits);
if physicalOperatorEnabled
    dVpa = sum(bVpa.*inverseThetaPairVpa.*bVpa);
    rhoVpa = sum(bVpa.*rNuPairVpa);
    thetaForUseVpa = thetaPairVpa;
    rNuForUseVpa = rNuPairVpa;
else
    dVpa = sum(bVpa.*inverseThetaSourceVpa.*bVpa);
    rhoVpa = sum(bVpa.*rNuSourceVpa);
    thetaForUseVpa = thetaSourceVpa;
    rNuForUseVpa = rNuSourceVpa;
end
dDiagnostic = double(dVpa);
rhoDiagnostic = double(rhoVpa);
assert(isfinite(dDiagnostic) && dDiagnostic>0 && ...
    isfinite(rhoDiagnostic), ...
    "mixedDirection:TargetCoordinate", ...
    "The high-precision target coordinate is nonfinite or nonpositive.");
[cHigh,cLow] = vpa_to_high_low(cVpa,vpaDigits);
[dHigh,dLow] = vpa_to_high_low(dVpa,vpaDigits);
[rhoHigh,rhoLow] = vpa_to_high_low(rhoVpa,vpaDigits);
cPairVpa = double_pair_to_vpa(cHigh,cLow,vpaDigits);
dPairVpa = double_pair_to_vpa(dHigh,dLow,vpaDigits);
rhoPairVpa = double_pair_to_vpa(rhoHigh,rhoLow,vpaDigits);
sqrtDPairVpa = sqrt(dPairVpa);
if scaledGammaCoordinate
    borderCVpa = cPairVpa/sqrtDPairVpa;
    borderDVpa = vpa(1,vpaDigits);
    borderRhsVpa = rhoPairVpa/sqrtDPairVpa;
else
    borderCVpa = cPairVpa;
    borderDVpa = dPairVpa;
    borderRhsVpa = rhoPairVpa;
end
[sqrtDHigh,sqrtDLow] = vpa_to_high_low(sqrtDPairVpa,vpaDigits);
[borderCHigh,borderCLow] = vpa_to_high_low(borderCVpa,vpaDigits);
[borderDHigh,borderDLow] = vpa_to_high_low(borderDVpa,vpaDigits);
[borderRhsHigh,borderRhsLow] = vpa_to_high_low( ...
    borderRhsVpa,vpaDigits);
if physicalOperatorEnabled
    [thetaRNuHigh,thetaRNuLow] = multiply_high_low_pair_mixed( ...
        thetaHigh,thetaLow,rNuHigh,rNuLow);
    selectedRhsVpa = vpa_sparse_transpose_product( ...
        embeddedJacobian,thetaRNuHigh,thetaRNuLow,vpaDigits);
    unprojectedRhsVpa = exact_double_to_vpa(baseRhs,vpaDigits)+ ...
        selectedRhsVpa;
    targetRhsVpa = unprojectedRhsVpa- ...
        cPairVpa*(rhoPairVpa/dPairVpa);
    coordinateDefinition = ...
        "M_base+J'*theta*J-c*(c'*x)/d; " + ...
        "r_base+J'*(theta.*r_nu)-c*rho/d";
else
    unprojectedRhsVpa = exact_double_to_vpa(day.rhs,vpaDigits);
    targetRhsVpa = unprojectedRhsVpa- ...
        cPairVpa*(rhoPairVpa/dPairVpa);
    coordinateDefinition = "M_day-c*(c'*x)/d; r_day-c*rho/d";
end
[unprojectedRhsHigh,unprojectedRhsLow] = vpa_to_high_low( ...
    unprojectedRhsVpa,vpaDigits);
[rhsHigh,rhsLow] = vpa_to_high_low(targetRhsVpa,vpaDigits);
preconditionerMatrixHigh = sparse(day.matrix);
preconditionerMatrixLow = sparse(size(day.matrix,1),size(day.matrix,2));
preconditionerLowRelative = 0;
if physicalOperatorEnabled
    inverseDPairVpa = 1/dPairVpa;
    [inverseDHigh,inverseDLow] = ...
        vpa_to_high_low(inverseDPairVpa,vpaDigits);
    [preconditionerMatrixHigh,preconditionerMatrixLow] = ...
        assemble_physical_target_matrix_high_low( ...
        baseMatrix,embeddedJacobian,thetaHigh,thetaLow, ...
        cHigh,cLow,inverseDHigh,inverseDLow);
    preconditionerLowRelative = norm(preconditionerMatrixLow,"fro")/ ...
        max(1,norm(preconditionerMatrixHigh,"fro"));
end
target = struct( ...
    "enabled",true,"physical_operator",physicalOperatorEnabled, ...
    "scaled_gamma_coordinate",scaledGammaCoordinate, ...
    "canonical_matrix",sparse(day.matrix), ...
    "canonical_rhs",day.rhs, ...
    "base_matrix",sparse(baseMatrix),"base_rhs",baseRhs, ...
    "selected_jacobian",sparse(embeddedJacobian), ...
    "c_high",sparse(cHigh),"c_low",sparse(cLow), ...
    "d_high",dHigh,"d_low",dLow, ...
    "rho_high",rhoHigh,"rho_low",rhoLow, ...
    "sqrt_d_high",sqrtDHigh,"sqrt_d_low",sqrtDLow, ...
    "border_c_high",sparse(borderCHigh), ...
    "border_c_low",sparse(borderCLow), ...
    "border_d_high",borderDHigh,"border_d_low",borderDLow, ...
    "border_rhs_high",borderRhsHigh, ...
    "border_rhs_low",borderRhsLow, ...
    "rhs_high",rhsHigh,"rhs_low",rhsLow, ...
    "preconditioner_matrix_high",preconditionerMatrixHigh, ...
    "preconditioner_matrix_low",preconditionerMatrixLow, ...
    "preconditioner_low_relative",preconditionerLowRelative, ...
    "unprojected_rhs_high",unprojectedRhsHigh, ...
    "unprojected_rhs_low",unprojectedRhsLow, ...
    "theta_high",thetaHigh,"theta_low",thetaLow, ...
    "r_nu_high",rNuHigh,"r_nu_low",rNuLow, ...
    "c_vpa",cVpa,"d_vpa",dVpa,"rho_vpa",rhoVpa, ...
    "c_pair_vpa",cPairVpa,"d_pair_vpa",dPairVpa, ...
    "rho_pair_vpa",rhoPairVpa, ...
    "sqrt_d_pair_vpa",sqrtDPairVpa, ...
    "border_c_vpa",borderCVpa,"border_d_vpa",borderDVpa, ...
    "border_rhs_vpa",borderRhsVpa, ...
    "theta_vpa",thetaForUseVpa,"r_nu_vpa",rNuForUseVpa, ...
    "coordinate_definition",coordinateDefinition);
clear restoreDigits
end

function [matrixHigh,matrixLow] = ...
        assemble_physical_target_matrix_high_low( ...
        baseMatrix,jacobian,thetaHigh,thetaLow,cHigh,cLow, ...
        inverseDHigh,inverseDLow)
% Assemble the upper triangle of Mbase+J'*theta*J-c*c'/d in twofold form.
n = size(baseMatrix,1);
assert(size(baseMatrix,2)==n && size(jacobian,2)==n, ...
    "mixedDirection:PhysicalPreconditionerShape", ...
    "The physical target preconditioner dimensions are inconsistent.");
[baseRow,baseColumn,baseValue] = find(triu(sparse(baseMatrix)));
[jacobianRow,jacobianColumn,jacobianValue] = find(sparse(jacobian));
[~,order] = sortrows([jacobianRow,jacobianColumn],[1,2]);
jacobianRow = jacobianRow(order);
jacobianColumn = jacobianColumn(order);
jacobianValue = jacobianValue(order);
rowCounts = accumarray(jacobianRow,1,[size(jacobian,1),1]);
rowStarts = cumsum([1;rowCounts(1:end-1)]);
cHigh = full(cHigh(:));
cLow = full(cLow(:));
cSupport = find(cHigh~=0 | cLow~=0);
gramEntryCount = sum(rowCounts.*(rowCounts+1)/2);
rankEntryCount = numel(cSupport)*(numel(cSupport)+1)/2;
entryCount = numel(baseValue)+gramEntryCount+rankEntryCount;
keys = zeros(entryCount,1);
valuesHigh = zeros(entryCount,1);
valuesLow = zeros(entryCount,1);
cursor = 0;

for k = 1:numel(baseValue)
    cursor = cursor+1;
    keys(cursor) = baseRow(k)+(baseColumn(k)-1)*n;
    valuesHigh(cursor) = baseValue(k);
end
for row = 1:size(jacobian,1)
    count = rowCounts(row);
    if count==0
        continue
    end
    positions = rowStarts(row):(rowStarts(row)+count-1);
    columns = jacobianColumn(positions);
    coefficients = jacobianValue(positions);
    for left = 1:count
        for right = left:count
            [coefficientHigh,coefficientLow] = two_product_mixed( ...
                coefficients(left),coefficients(right));
            [termHigh,termLow] = multiply_high_low_pair_mixed( ...
                thetaHigh(row),thetaLow(row), ...
                coefficientHigh,coefficientLow);
            cursor = cursor+1;
            keys(cursor) = columns(left)+(columns(right)-1)*n;
            valuesHigh(cursor) = termHigh;
            valuesLow(cursor) = termLow;
        end
    end
end
for left = 1:numel(cSupport)
    leftPosition = cSupport(left);
    for right = left:numel(cSupport)
        rightPosition = cSupport(right);
        [productHigh,productLow] = multiply_high_low_pair_mixed( ...
            cHigh(leftPosition),cLow(leftPosition), ...
            cHigh(rightPosition),cLow(rightPosition));
        [rankHigh,rankLow] = multiply_high_low_pair_mixed( ...
            productHigh,productLow,inverseDHigh,inverseDLow);
        cursor = cursor+1;
        keys(cursor) = leftPosition+(rightPosition-1)*n;
        valuesHigh(cursor) = -rankHigh;
        valuesLow(cursor) = -rankLow;
    end
end
assert(cursor==entryCount, ...
    "mixedDirection:PhysicalPreconditionerEntries", ...
    "The physical target preconditioner entry count is inconsistent.");

[keys,order] = sort(keys);
valuesHigh = valuesHigh(order);
valuesLow = valuesLow(order);
resultKeys = zeros(entryCount,1);
resultHigh = zeros(entryCount,1);
resultLow = zeros(entryCount,1);
source = 1;
resultCount = 0;
while source<=entryCount
    key = keys(source);
    accumulatorHigh = 0;
    accumulatorLow = 0;
    while source<=entryCount && keys(source)==key
        [accumulatorHigh,accumulatorLow] = add_high_low_mixed( ...
            accumulatorHigh,accumulatorLow, ...
            valuesHigh(source),valuesLow(source));
        source = source+1;
    end
    [accumulatorHigh,accumulatorLow] = ...
        two_sum_mixed(accumulatorHigh,accumulatorLow);
    resultCount = resultCount+1;
    resultKeys(resultCount) = key;
    resultHigh(resultCount) = accumulatorHigh;
    resultLow(resultCount) = accumulatorLow;
end
resultKeys = resultKeys(1:resultCount);
resultHigh = resultHigh(1:resultCount);
resultLow = resultLow(1:resultCount);
resultRow = mod(resultKeys-1,n)+1;
resultColumn = floor((resultKeys-1)/n)+1;
upperHigh = sparse(resultRow,resultColumn,resultHigh,n,n);
upperLow = sparse(resultRow,resultColumn,resultLow,n,n);
matrixHigh = upperHigh+triu(upperHigh,1).';
matrixLow = upperLow+triu(upperLow,1).';
assert(all(isfinite(nonzeros(matrixHigh))) && ...
    all(isfinite(nonzeros(matrixLow))) && ...
    nnz(matrixHigh-matrixHigh.')==0 && nnz(matrixLow-matrixLow.')==0, ...
    "mixedDirection:PhysicalPreconditionerFinite", ...
    "The physical target preconditioner pair is nonfinite or asymmetric.");
end

function [a,b,tableOut] = build_relation_coefficients( ...
        lin,contract,equalityMeta,inequalityMeta,rows,localPrimalCanonical, ...
        problemDayId,relationHours)
a = zeros(contract.neq,1);
bGlobal = sparse(contract.nineq,1);
inWindow = ismember(equalityMeta.hour,relationHours);
balanceMask = equalityMeta.day==problemDayId & inWindow & ...
    equalityMeta.constraint_name=="hourly_power_balance";
socMask = equalityMeta.day==problemDayId & inWindow & ...
    equalityMeta.constraint_name=="soc_dynamics";
a(equalityMeta.global_row(balanceMask)) = -1;
a(equalityMeta.global_row(socMask)) = 0.9;

upperNames = ["pw_upper_bound","ph_upper_bound","pf_upper_bound"];
upperMask = inequalityMeta.day==problemDayId & ...
    ismember(inequalityMeta.hour,relationHours) & ...
    ismember(inequalityMeta.constraint_name,upperNames);
pchMask = inequalityMeta.day==problemDayId & ...
    ismember(inequalityMeta.hour,relationHours) & ...
    inequalityMeta.constraint_name=="pch_lower_bound";
socLowerMask = inequalityMeta.day==problemDayId & ...
    inequalityMeta.hour==relationHours(end) & ...
    inequalityMeta.constraint_name=="soc_lower_bound";
bGlobal(inequalityMeta.global_row(upperMask)) = 1;
bGlobal(inequalityMeta.global_row(pchMask)) = 0.19;
bGlobal(inequalityMeta.global_row(socLowerMask)) = 0.9;

qbindMask = equalityMeta.day==problemDayId & ...
    equalityMeta.constraint_name=="daily_capacity_binding" & ...
    ismember(equalityMeta.asset_type, ...
        ["wind_capacity","storage_energy_capacity"]);
qbindRows = equalityMeta.global_row(qbindMask);
assert(nnz(balanceMask)==numel(relationHours) && ...
    nnz(socMask)==2*numel(relationHours) && ...
    nnz(qbindMask)==7 && nnz(pchMask)==2*numel(relationHours) && ...
    nnz(socLowerMask)==2, ...
    "jointMicroborder:RelationCardinality", ...
    "The expected label-derived equality/inequality relation changed.");

gradient = sparse(lin.A(:,localPrimalCanonical)).'*a+ ...
    sparse(lin.G(:,localPrimalCanonical)).'*bGlobal;
usedColumns = zeros(numel(qbindRows),1);
for k = 1:numel(qbindRows)
    row = qbindRows(k);
    coefficients = sparse(lin.A(row,localPrimalCanonical));
    column = find(coefficients,1);
    assert(nnz(coefficients)==1 && ~ismember(column,usedColumns(1:k-1)), ...
        "jointMicroborder:BindingColumn", ...
        "A target daily binding does not have one unique local capacity column.");
    a(row) = -gradient(column)/coefficients(column);
    gradient = gradient+coefficients.'*a(row);
    usedColumns(k) = column;
end

[present,locations] = ismember(rows,(1:contract.nineq).');
assert(all(present),"jointMicroborder:RowMap", ...
    "The problem-day inequality row map is incomplete.");
b = bGlobal(locations);
selectedEquality = find(a);
selectedInequality = find(bGlobal);
eqTable = table(repmat("equality",numel(selectedEquality),1), ...
    equalityMeta.constraint_id(selectedEquality), ...
    equalityMeta.constraint_name(selectedEquality), ...
    equalityMeta.day(selectedEquality),equalityMeta.hour(selectedEquality), ...
    equalityMeta.asset_type(selectedEquality), ...
    equalityMeta.asset_id(selectedEquality),full(a(selectedEquality)), ...
    'VariableNames',{'constraint_type','constraint_id','constraint_name', ...
    'day','hour','asset_type','asset_id','coefficient'});
ineqTable = table(repmat("inequality",numel(selectedInequality),1), ...
    inequalityMeta.constraint_id(selectedInequality), ...
    inequalityMeta.constraint_name(selectedInequality), ...
    inequalityMeta.day(selectedInequality), ...
    inequalityMeta.hour(selectedInequality), ...
    inequalityMeta.asset_type(selectedInequality), ...
    inequalityMeta.asset_id(selectedInequality), ...
    full(bGlobal(selectedInequality)), ...
    'VariableNames',eqTable.Properties.VariableNames);
tableOut = [eqTable;ineqTable];
end

function [solutionHigh,solutionLow,history,timing,diagnostics] = ...
        refine_high_low_with_retained_factor( ...
        matrix,rhsHigh,rhsLow,solutionHigh,solutionLow,retained, ...
        rhsLabels,tolerance,maximumPasses,continueAfterGate,label, ...
        targetOperator)
useTargetOperator = isstruct(targetOperator) && ...
    isfield(targetOperator,"enabled") && targetOperator.enabled;
if useTargetOperator
    if targetOperator.physical_operator
        pattern = sparse_row_pattern_mixed(targetOperator.base_matrix);
    else
        pattern = sparse_row_pattern_mixed(targetOperator.canonical_matrix);
    end
else
    pattern = sparse_row_pattern_mixed(matrix);
end

history = table();
timingRows = repmat(struct( ...
    "pass",NaN,"accurate_residual_seconds",NaN, ...
    "correction_wall_seconds",NaN, ...
    "reported_factor_solve_seconds",NaN, ...
    "high_low_accumulation_seconds",NaN, ...
    "maximum_relative_residual",NaN, ...
    "maximum_componentwise_backward_error",NaN, ...
    "all_columns_pass",false,"factorization_count",1, ...
    "additional_factorization_count",0),maximumPasses+1,1);
refinementTimer = tic;
bestMaximum = Inf;
bestPass = NaN;
bestHigh = solutionHigh;
bestLow = solutionLow;
firstGatePass = NaN;
previousMaximum = Inf;
nonShrinkCount = 0;
correctionsApplied = 0;
stopReason = "maximum_passes";
lastPass = 0;

for pass = 0:maximumPasses
    residualTimer = tic;
    if useTargetOperator
        [residualHigh,residualLow] = ...
            accurate_target_operator_residual_high_low( ...
            pattern,targetOperator,solutionHigh,solutionLow, ...
            rhsHigh,rhsLow);
    else
        [residualHigh,residualLow] = ...
            accurate_sparse_residual_high_low( ...
            pattern,solutionHigh,solutionLow,rhsHigh,rhsLow);
    end
    residualSeconds = toc(residualTimer);
    roundedResidual = residualHigh+residualLow;
    rhsNorm = max(ones(1,size(rhsHigh,2)), ...
        vecnorm(rhsHigh+rhsLow,2,1));
    residualNorm = vecnorm(roundedResidual,2,1);
    relativeResidual = residualNorm./rhsNorm;
    absoluteResidual = max(abs(residualHigh)+abs(residualLow),[],1);
    if useTargetOperator
        denominator = target_operator_componentwise_denominator( ...
            targetOperator,solutionHigh,solutionLow,rhsHigh,rhsLow);
    else
        denominator = abs(matrix)*(abs(solutionHigh)+abs(solutionLow))+ ...
            abs(rhsHigh)+abs(rhsLow);
    end
    zeroDenominator = denominator==0;
    componentwiseRatio = zeros(size(roundedResidual));
    componentwiseRatio(~zeroDenominator) = ...
        (abs(residualHigh(~zeroDenominator))+ ...
        abs(residualLow(~zeroDenominator)))./ ...
        denominator(~zeroDenominator);
    componentwiseRatio(zeroDenominator & ...
        (residualHigh~=0 | residualLow~=0)) = Inf;
    backwardError = max(componentwiseRatio,[],1);
    zeroDenominatorCount = sum(zeroDenominator,1);
    inconsistentZeroCount = sum(zeroDenominator & ...
        (residualHigh~=0 | residualLow~=0),1);
    currentMaximum = max(relativeResidual);
    currentBackward = max(backwardError);
    history = [history;table(repmat(pass,numel(rhsLabels),1), ...
        rhsLabels,relativeResidual.',residualNorm.',absoluteResidual.', ...
        backwardError.',vecnorm(solutionHigh,2,1).', ...
        vecnorm(solutionLow,2,1).',zeroDenominatorCount.', ...
        inconsistentZeroCount.', ...
        'VariableNames',{'pass','rhs_label','relative_residual', ...
        'residual_norm','maximum_absolute_residual', ...
        'componentwise_backward_error','solution_high_norm', ...
        'solution_low_norm','zero_componentwise_denominator_count', ...
        'nonzero_residual_at_zero_denominator_count'})]; %#ok<AGROW>
    timingRows(pass+1).pass = pass;
    timingRows(pass+1).accurate_residual_seconds = residualSeconds;
    timingRows(pass+1).maximum_relative_residual = currentMaximum;
    timingRows(pass+1).maximum_componentwise_backward_error = ...
        currentBackward;
    timingRows(pass+1).all_columns_pass = ...
        all(relativeResidual<=tolerance);
    lastPass = pass;
    if currentMaximum<bestMaximum
        bestMaximum = currentMaximum;
        bestPass = pass;
        bestHigh = solutionHigh;
        bestLow = solutionLow;
    end
    if isnan(firstGatePass) && all(relativeResidual<=tolerance)
        firstGatePass = pass;
    end
    if pass==maximumPasses
        stopReason = conditional(isfinite(firstGatePass), ...
            "maximum_passes_after_gate","maximum_passes_without_gate");
        break
    end
    if pass>0
        if currentMaximum>=previousMaximum
            nonShrinkCount = nonShrinkCount+1;
        else
            nonShrinkCount = 0;
        end
        if nonShrinkCount>=2
            stopReason = "two_consecutive_nonshrinking_passes";
            break
        end
    end
    if isfinite(firstGatePass) && ~continueAfterGate
        stopReason = "gate_pass";
        break
    end
    previousMaximum = currentMaximum;
    correctionTimer = tic;
    [correction,correctionDiagnostics] = ...
        rkkt.solver.apply_stage_b2c_daily_joint_factor( ...
        retained,matrix,roundedResidual,label+"_pass_"+string(pass+1), ...
        ResidualTolerance=tolerance,RefinementPasses=0, ...
        ContinueNumericalPivotWarning=true);
    timingRows(pass+1).correction_wall_seconds = toc(correctionTimer);
    timingRows(pass+1).reported_factor_solve_seconds = ...
        correctionDiagnostics.solve_seconds;
    accumulationTimer = tic;
    [solutionHigh,solutionLow] = add_double_to_high_low_mixed( ...
        solutionHigh,solutionLow,correction);
    timingRows(pass+1).high_low_accumulation_seconds = ...
        toc(accumulationTimer);
    correctionsApplied = correctionsApplied+1;
end

solutionHigh = bestHigh;
solutionLow = bestLow;
history.selected_solution = history.pass==bestPass;
