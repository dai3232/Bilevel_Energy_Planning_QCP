function result = vpa_sparse_transpose_product_pairs( ...
        matrixHigh,matrixLow,solutionHigh,solutionLow,vpaDigits)
matrixHigh = sparse(matrixHigh);
matrixLow = sparse(matrixLow);
assert(isequal(size(matrixHigh),size(matrixLow)), ...
    "mixedDirection:CoefficientPairShape", ...
    "High/low coefficient matrices have different shapes.");
result = vpa(zeros(size(matrixHigh,2),size(solutionHigh,2)),vpaDigits);
for column = 1:size(matrixHigh,2)
    rows = find(matrixHigh(:,column)~=0 | matrixLow(:,column)~=0);
    if isempty(rows)
        continue
    end
    coefficientVpa = double_pair_to_vpa( ...
        full(matrixHigh(rows,column)),full(matrixLow(rows,column)), ...
        vpaDigits);
    solutionVpa = double_pair_to_vpa( ...
        solutionHigh(rows,:),solutionLow(rows,:),vpaDigits);
    result(column,:) = sum(coefficientVpa.*solutionVpa,1);
end
end

function result = vpa_sparse_transpose_product( ...
        matrix,solutionHigh,solutionLow,vpaDigits)
matrix = sparse(matrix);
result = vpa(zeros(size(matrix,2),size(solutionHigh,2)),vpaDigits);
for column = 1:size(matrix,2)
    rows = find(matrix(:,column));
    if isempty(rows)
        continue
    end
    coefficients = full(matrix(rows,column));
    coefficientVpa = exact_double_to_vpa(coefficients,vpaDigits);
    solutionVpa = double_pair_to_vpa( ...
        solutionHigh(rows,:),solutionLow(rows,:),vpaDigits);
    result(column,:) = sum(coefficientVpa.*solutionVpa,1);
end
end

function value = exact_double_to_vpa(value,vpaDigits)
