function solution = apply_retained_d_kept_inverse(D,kept,rhs)
n = size(D,1);
assert(size(rhs,1)==numel(kept), ...
    "mixedDirection:KeptDShape", ...
    "The retained-D reduced right-hand side has an invalid shape.");
isKept = false(n,1);
isKept(kept) = true;
fullRhs = zeros(n,size(rhs,2));
fullRhs(kept,:) = rhs;
fullSolution = zeros(size(fullRhs));
cursor = 1;
while cursor<=n
    if cursor<n && D(cursor+1,cursor)~=0
        indices = (cursor:cursor+1).';
    else
        indices = cursor;
    end
    if all(isKept(indices))
        if numel(indices)==1
            assert(abs(D(indices,indices))>0, ...
                "mixedDirection:KeptZeroPivot", ...
                "A numerical-zero singleton remained in the kept D block.");
            fullSolution(indices,:) = ...
                fullRhs(indices,:)./D(indices,indices);
        else
            fullSolution(indices,:) = full(D(indices,indices))\ ...
                fullRhs(indices,:);
        end
    else
        assert(all(~isKept(indices)), ...
            "mixedDirection:PartialDelayedBlock", ...
            "Only part of a 2-by-2 LDL block was delayed.");
    end
    cursor = indices(end)+1;
end
solution = fullSolution(kept,:);
assert(all(isfinite(solution),"all"), ...
    "mixedDirection:KeptDSolution", ...
    "The retained-D reduced solve is nonfinite.");
end

