function result = solve_stage_b2c_joint_microborder_direction( ...
        lin,candidate,options)
%SOLVE_STAGE_B2C_JOINT_MICROBORDER_DIRECTION Solve one confirmed joint mode.
%
% The ordinary days keep their one-factor affine responses.  The confirmed
% problem day is factorized once after an exact joint equality/inequality
% coordinate is moved into a scaled 17-D micro-border.  The model, residual
% equations, and acceptance thresholds are unchanged.

arguments
    lin (1,1) struct
    candidate (1,1) struct
    options.SymmetryTolerance (1,1) double = 1e-8
    options.LocalResidualTolerance (1,1) double = 1e-10
    options.ReconstructedKktResidualTolerance (1,1) double = 1e-8
    options.RefinementPasses (1,1) double ...
        {mustBeInteger,mustBeNonnegative} = 3
    options.ResponseRefinementMaximumPasses (1,1) double ...
        {mustBeInteger,mustBePositive} = 32
    options.VpaDigits (1,1) double {mustBeInteger,mustBePositive} = 50
    options.ReturnFailedDirectionForDiagnostics (1,1) logical = false
end
assert(candidate.used && candidate.detection_method=="active_set_joint_d", ...
    "stageB2C:jointMicroborder:Candidate", ...
    "The formal micro-border requires one preemptively confirmed joint mode.");
assert(options.ResponseRefinementMaximumPasses<=32 && ...
    options.VpaDigits>=34, ...
    "stageB2C:jointMicroborder:PrecisionContract", ...
    "The joint micro-border refinement or precision contract is invalid.");
config = struct( ...
    "reduced_symmetry_tolerance",options.SymmetryTolerance, ...
    "border_symmetry_tolerance",options.SymmetryTolerance, ...
    "recursive_refinement_max_passes",options.RefinementPasses);

totalTimer = tic;
[directionData,diagnostics,artifacts,payload] = ...
    solve_mixed_precision_direction( ...
        lin,lin.index,config,candidate.day_id,candidate.relation_hours, ...
        options.LocalResidualTolerance, ...
        options.ReconstructedKktResidualTolerance, ...
        options.ResponseRefinementMaximumPasses,options.VpaDigits, ...
        true,true,true,true,true,true);
kktBlocks = artifacts.kkt_block_table;
dualBlock = kktBlocks(kktBlocks.block=="dual",:);
equalityBlock = kktBlocks(kktBlocks.block=="equality",:);
inequalityBlock = kktBlocks(kktBlocks.block=="inequality",:);
complementarityBlock = kktBlocks(kktBlocks.block=="complementarity",:);
formalDirectionGatePass = diagnostics.complete_direction_formed && ...
    diagnostics.affine_gate_pass && ...
    diagnostics.maximum_daily_final_relative_residual<= ...
        options.LocalResidualTolerance && ...
    diagnostics.actual_recovered_core_relative_residual<= ...
        options.LocalResidualTolerance && ...
    diagnostics.rounded_core_algebraic_relative_residual<= ...
        options.LocalResidualTolerance && ...
    diagnostics.core_symmetry_relative<=options.SymmetryTolerance && ...
    diagnostics.pair_reconstructed_kkt_relative_residual<= ...
        options.ReconstructedKktResidualTolerance;
diagnostics.formal_direction_gate_pass = formalDirectionGatePass;
if ~formalDirectionGatePass && ~options.ReturnFailedDirectionForDiagnostics
    error("stageB2C:jointMicroborder:DirectionGate", ...
    "The confirmed joint micro-border direction failed a formal residual gate: "+ ...
    "complete=%d, affine=%d, affine_residual=%.17g, "+ ...
    "affine_first_pass=%.17g, daily=%.17g, actual_core=%.17g, "+ ...
    "rounded_core=%.17g, symmetry=%.17g, pair_kkt=%.17g, "+ ...
    "pivot=%.17g, zero_pivots=%d, promoted=%d, "+ ...
    "dual=(%.17g,%.17g), eq=(%.17g,%.17g), "+ ...
    "ineq=(%.17g,%.17g), comp=(%.17g,%.17g), "+ ...
    "physical_canonical=(%.17g,%.17g), border=%.17g, "+ ...
    "affine_stop=%s, "+ ...
    "affine_history=[%s].", ...
    diagnostics.complete_direction_formed,diagnostics.affine_gate_pass, ...
    diagnostics.problem_day_affine_relative_residual, ...
    diagnostics.affine_first_gate_pass, ...
    diagnostics.maximum_daily_final_relative_residual, ...
    diagnostics.actual_recovered_core_relative_residual, ...
    diagnostics.rounded_core_algebraic_relative_residual, ...
    diagnostics.core_symmetry_relative, ...
    diagnostics.reconstructed_kkt_relative_residual, ...
    diagnostics.problem_day_minimum_absolute_pivot, ...
    diagnostics.problem_day_numerical_zero_pivots, ...
    diagnostics.factor_coordinate_promotion_count, ...
    dualBlock.block_relative_residual, ...
    dualBlock.maximum_absolute_residual, ...
    equalityBlock.block_relative_residual, ...
    equalityBlock.maximum_absolute_residual, ...
    inequalityBlock.block_relative_residual, ...
    inequalityBlock.maximum_absolute_residual, ...
    complementarityBlock.block_relative_residual, ...
    complementarityBlock.maximum_absolute_residual, ...
    diagnostics.problem_physical_canonical_action_relative_difference, ...
    diagnostics.problem_physical_canonical_action_maximum_absolute_difference, ...
    diagnostics.problem_border_coordinate_magnitude, ...
    char(diagnostics.affine_stop_reason), ...
    char(affine_pass_history_text(artifacts.affine_history)));
end

componentsHigh = directionData.components_high;
componentsLow = directionData.components_low;
components = struct( ...
    "xi",componentsHigh.xi+componentsLow.xi, ...
    "y",componentsHigh.y+componentsLow.y, ...
    "l",componentsHigh.l+componentsLow.l, ...
    "z",componentsHigh.z+componentsLow.z);
contract = payload.partition.contract;
components.q = components.xi(contract.q_global);
components.rho = components.y(contract.y_duration);
components.q_day_by_day = cell(contract.n_days,1);
components.pi_by_day = cell(contract.n_days,1);
components.daily_joint_by_day = cell(contract.n_days,1);
components.eta_by_day = cell(contract.n_days,1);
for d = 1:contract.n_days
    local = directionData.daily_high_by_day{d}+ ...
        directionData.daily_low_by_day{d};
    components.daily_joint_by_day{d} = local;
    components.q_day_by_day{d} = ...
        local(payload.partition.day(d).q_day_local_positions);
    components.pi_by_day{d} = ...
        local(payload.partition.day(d).pi_day_local_positions);
end
fixed = rkkt.solver.stage_a_multiday_fixed_zero_evidence(lin.index);
recovery = struct( ...
    "stage_id","stage_B","milestone_id","B-2C", ...
    "linearization_identity",lin.identity, ...
    "direction",[components.xi;components.y;components.l;components.z], ...
    "direction_high",directionData.direction_high, ...
    "direction_low",directionData.direction_low, ...
    "canonical_reduced_direction",[components.xi;components.y], ...
    "components",components,"components_high",componentsHigh, ...
    "components_low",componentsLow, ...
    "daily_direct_backsolve",payload.daily_recovery_diagnostics, ...
    "fixed_zero",fixed,"no_full_direction_fallback",true, ...
    "full_direction_consumed",false,"state_update_executed",false, ...
    "diagnostics",struct( ...
        "all_daily_direct_factor_backsolve_used",false, ...
        "all_daily_affine_response_recovery_used",true, ...
        "daily_recovery_retained_factor_correction_count", ...
            sum([payload.daily_recovery_diagnostics.corrections_applied]), ...
        "additional_factorization_count",0, ...
        "maximum_daily_direct_relative_residual", ...
            diagnostics.maximum_daily_final_relative_residual, ...
        "extended_precision_components_retained",true, ...
        "high_low_state_update_required",true, ...
        "state_update_contract", ...
            "consume_components_high_low_before_final_state_rounding", ...
        "water_eta_dimension",0,"fixed_zero_exact",fixed.all_exact_zero));

coreSolution = payload.core_solution_high+payload.core_solution_low;
coreDimension = numel(coreSolution);
core = struct( ...
    "stage_id","stage_B","milestone_id","B-2C", ...
    "linearization_identity",lin.identity, ...
    "matrix",sparse(payload.core_matrix_high+payload.core_matrix_low), ...
    "matrix_high",sparse(payload.core_matrix_high), ...
    "matrix_low",sparse(payload.core_matrix_low), ...
    "rhs",payload.core_rhs_high+payload.core_rhs_low, ...
    "rhs_high",payload.core_rhs_high,"rhs_low",payload.core_rhs_low, ...
    "solution",coreSolution, ...
    "solution_high",payload.core_solution_high, ...
    "solution_low",payload.core_solution_low, ...
    "delta_q",coreSolution(1:14),"delta_rho",coreSolution(15:16), ...
    "border_alpha",coreSolution(17), ...
    "factor_promoted_coordinates",coreSolution(18:end), ...
    "dimension",coreDimension, ...
    "factor",struct( ...
        "object_type","joint_microborder_core_"+string(coreDimension), ...
        "method","vpa50_small_core_backslash", ...
        "dimension",coreDimension,"rhs_count",1,"factorization_count",1, ...
        "minimum_absolute_pivot_eigenvalue",NaN, ...
        "pivot_tolerance",NaN,"inertia_zero",0, ...
        "maximum_column_relative_residual", ...
            diagnostics.rounded_core_algebraic_relative_residual, ...
        "initial_maximum_column_relative_residual", ...
            diagnostics.rounded_core_algebraic_relative_residual, ...
        "refinement_enabled",false,"refinement_triggered",false, ...
        "refinement_maximum_passes",0,"refinement_passes_applied",0, ...
        "refinement_additional_factorization_count",0, ...
        "warning_present",false,"warning_continued",false, ...
        "blocking_warning_present",false, ...
        "solution_finite",all(isfinite(coreSolution)), ...
        "regularization_used",false,"pseudoinverse_used",false), ...
    "direct_daily_correction",struct( ...
        "enabled",true,"maximum_passes",0,"passes_attempted",0, ...
        "passes_applied",0,"initial_relative_residual", ...
            diagnostics.actual_recovered_core_relative_residual, ...
        "final_relative_residual", ...
            diagnostics.actual_recovered_core_relative_residual, ...
        "relative_residual_history", ...
            diagnostics.actual_recovered_core_relative_residual, ...
        "target_met",true,"global_kkt_gate_enabled",true, ...
        "global_kkt_correction_triggered",false, ...
        "initial_reconstructed_kkt_relative_residual", ...
            diagnostics.reconstructed_kkt_relative_residual, ...
        "final_reconstructed_kkt_relative_residual", ...
            diagnostics.reconstructed_kkt_relative_residual, ...
        "reconstructed_kkt_relative_residual_history", ...
            diagnostics.reconstructed_kkt_relative_residual, ...
        "combined_gate_history",diagnostics.direction_gate, ...
        "both_targets_met",true,"stop_reason","both_targets_met", ...
        "core_residual_tolerance",options.LocalResidualTolerance, ...
        "reconstructed_kkt_residual_tolerance", ...
            options.ReconstructedKktResidualTolerance, ...
        "compensated_accumulation_used",true, ...
        "daily_additional_factorization_count",0, ...
        "core_additional_factorization_count",0, ...
        "retained_core_factor_reused",true, ...
        "retained_daily_factors_reused",true, ...
        "complete_kkt_factorization_count",0, ...
        "complete_kkt_solved",false));

result = struct( ...
    "core",core,"recovery",recovery, ...
    "responses",payload.responses, ...
    "retained_factors",{payload.retained_factors}, ...
    "partition",payload.partition, ...
    "kkt_relative",diagnostics.pair_reconstructed_kkt_relative_residual, ...
    "kkt_maximum", ...
        diagnostics.pair_reconstructed_kkt_maximum_absolute_residual, ...
    "correction",core.direct_daily_correction, ...
    "timing",struct( ...
        "core_seconds",diagnostics.core_solve_seconds+ ...
            diagnostics.problem_schur_seconds, ...
        "recovery_seconds",sum( ...
            artifacts.recovery_timing.initial_response_combination_seconds)+ ...
            sum(artifacts.recovery_timing.double_double_refinement_seconds), ...
        "reconstructed_kkt_residual_seconds", ...
            diagnostics.complete_kkt_audit_seconds, ...
        "total_seconds",toc(totalTimer)), ...
    "diagnostics",diagnostics,"candidate",candidate, ...
    "artifacts",artifacts,"payload",payload);
end

function [direction,diagnostics,artifacts,payload] = ...
        solve_mixed_precision_direction( ...
        lin,index,config,problemDayId,relationHours,localTolerance, ...
        kktTolerance,maximumPasses,vpaDigits, ...
        problemRecoveryContinueAfterGate,problemTargetOperatorHighLow, ...
        problemPhysicalOperatorHighLow,problemScaledGammaCoordinate, ...
        globalPhysicalOperatorHighLow,problemAffineCombinationRecovery)
contract = rkkt.solver.stage_b2b_linearization_contract(lin);
reduced = rkkt.solver.eliminate_stage_b2c_all_inequality_directions(lin);
partition = rkkt.solver.partition_stage_b2c_daily_joint_system(lin,reduced);
globalTarget = build_global_base_high_low( ...
    lin,contract,partition,globalPhysicalOperatorHighLow,vpaDigits);
nDays = numel(partition.day);
problemPosition = find([partition.day.day_id]==problemDayId,1);
assert(isscalar(problemPosition),"mixedDirection:ProblemDay", ...
    "The requested problem day is absent from the partition.");

responseCells = repmat({struct("a",[],"U",[])},nDays,1);
retainedCells = cell(nDays,1);
ordinaryResponseTimer = tic;
for d = 1:nDays
    if d==problemPosition
        continue
    end
    [responseCells{d},retainedCells{d}] = ...
        rkkt.solver.solve_stage_b2c_daily_joint_day( ...
        partition.day(d), ...
        SymmetryTolerance=config.reduced_symmetry_tolerance, ...
        ResidualTolerance=localTolerance, ...
        RefinementPasses=config.recursive_refinement_max_passes);
end
ordinaryResponseSeconds = toc(ordinaryResponseTimer);
ordinaryMask = true(nDays,1);
ordinaryMask(problemPosition) = false;
ordinaryResponses = vertcat(responseCells{ordinaryMask});
ordinaryMaximum = max(arrayfun( ...
    @(value)value.factor.maximum_column_relative_residual, ...
    ordinaryResponses));

micro = build_joint_microborder_day( ...
    lin,index,contract,partition,problemPosition,problemDayId,relationHours, ...
    config.reduced_symmetry_tolerance,problemTargetOperatorHighLow, ...
    problemPhysicalOperatorHighLow,problemScaledGammaCoordinate,vpaDigits);
assert(~isempty(micro.inequality_rows) && ...
    nnz(micro.inequality_coefficients)>0, ...
    "mixedDirection:ProblemInequalityCoverage", ...
    "The confirmed problem day has no joint inequality support.");
assert(nnz(micro.coupling(:,15:16))==0, ...
    "mixedDirection:ProblemRhoCoupling", ...
    "The two omitted problem-day rho affine columns are no longer zero.");
borderLabel = conditional(problemScaledGammaCoordinate,"alpha","gamma");
rhsLabels = ["base";"QW1";"QW2";"QW3";"QW4";"QW5"; ...
    "QP1";"QP2";"QP3";"QP4";"QP5";"QS1";"QS2"; ...
    "ES1";"ES2";borderLabel];
if problemTargetOperatorHighLow
    affineRhsHigh = [micro.target_operator.rhs_high, ...
        micro.coupling(:,1:14),micro.target_operator.border_c_high];
    affineRhsLow = [micro.target_operator.rhs_low, ...
        sparse(micro.dimension,14),micro.target_operator.border_c_low];
else
    affineRhsHigh = [micro.safe_rhs,micro.coupling(:,1:14), ...
        micro.joint_column];
    affineRhsLow = zeros(size(affineRhsHigh));
end
affineRhsApproximation = affineRhsHigh+affineRhsLow;
[affineHigh,problemFactor,problemRetained] = ...
    rkkt.solver.solve_stage_b2c_daily_joint_block( ...
    micro.factor_matrix,affineRhsApproximation, ...
    "stageB2C_joint_microborder_day_"+string(problemDayId), ...
    SymmetryTolerance=config.reduced_symmetry_tolerance, ...
    ResidualTolerance=localTolerance,RefinementPasses=0, ...
    ContinueNumericalPivotWarning=true);
problemRetained.day_id = problemDayId;
problemRetained.linearization_identity = lin.identity;
retainedCells{problemPosition} = problemRetained;
factorPromotionEnabled = problemFactor.inertia_zero>0;
factorPromotion = struct("enabled",false,"count",0, ...
    "delayed_indices",zeros(0,1));
problemResponse = struct();
if factorPromotionEnabled
    [problemResponse,factorPromotion,affineHigh,affineLow, ...
        affineHistory,affineTiming,affineRefinement] = ...
        build_factor_promoted_problem_response( ...
            micro,problemRetained,localTolerance,maximumPasses, ...
            vpaDigits,problemDayId);
else
    [affineHigh,affineLow,affineHistory,affineTiming,affineRefinement] = ...
        refine_high_low_with_retained_factor( ...
        micro.factor_matrix,affineRhsHigh,affineRhsLow, ...
        affineHigh,zeros(size(affineHigh)),problemRetained,rhsLabels, ...
        localTolerance,maximumPasses,true, ...
        "stageB2C_joint_microborder_affine_day_"+string(problemDayId), ...
        micro.target_operator);
end
affineGatePass = isfinite(affineRefinement.first_gate_pass) && ...
    affineRefinement.selected_maximum_relative_residual<=localTolerance;

artifacts = empty_artifacts();
artifacts.affine_history = affineHistory;
artifacts.affine_timing = affineTiming;
artifacts.relation_table = micro.relation_table;
direction = struct("direction_high",[],"direction_low",[], ...
    "components_high",struct(),"components_low",struct());
payload = struct("safe_day_matrix",micro.safe_matrix, ...
    "factor_day_matrix",micro.factor_matrix, ...
    "safe_day_rhs",micro.safe_rhs,"joint_column",micro.joint_column);
payload.global_target_enabled = globalTarget.enabled;
payload.global_target_matrix_high = globalTarget.matrix_high;
payload.global_target_matrix_low = globalTarget.matrix_low;
payload.global_target_rhs_high = globalTarget.rhs_high;
payload.global_target_rhs_low = globalTarget.rhs_low;
if problemTargetOperatorHighLow
    payload.target_operator_physical = ...
        micro.target_operator.physical_operator;
    payload.target_operator_c_high = micro.target_operator.c_high;
    payload.target_operator_c_low = micro.target_operator.c_low;
    payload.target_operator_d_high = micro.target_operator.d_high;
    payload.target_operator_d_low = micro.target_operator.d_low;
    payload.target_operator_rho_high = micro.target_operator.rho_high;
    payload.target_operator_rho_low = micro.target_operator.rho_low;
    payload.target_operator_scaled_gamma_coordinate = ...
        micro.target_operator.scaled_gamma_coordinate;
    payload.target_operator_sqrt_d_high = ...
        micro.target_operator.sqrt_d_high;
    payload.target_operator_sqrt_d_low = ...
        micro.target_operator.sqrt_d_low;
    payload.target_operator_border_c_high = ...
        micro.target_operator.border_c_high;
    payload.target_operator_border_c_low = ...
        micro.target_operator.border_c_low;
    payload.target_operator_border_d_high = ...
        micro.target_operator.border_d_high;
    payload.target_operator_border_d_low = ...
        micro.target_operator.border_d_low;
    payload.target_operator_border_rhs_high = ...
        micro.target_operator.border_rhs_high;
    payload.target_operator_border_rhs_low = ...
        micro.target_operator.border_rhs_low;
    payload.target_operator_rhs_high = micro.target_operator.rhs_high;
    payload.target_operator_rhs_low = micro.target_operator.rhs_low;
    if problemPhysicalOperatorHighLow
        payload.target_operator_base_matrix = ...
            micro.target_operator.base_matrix;
        payload.target_operator_base_rhs = micro.target_operator.base_rhs;
        payload.target_operator_selected_jacobian = ...
            micro.target_operator.selected_jacobian;
        payload.target_operator_theta_high = ...
            micro.target_operator.theta_high;
        payload.target_operator_theta_low = ...
            micro.target_operator.theta_low;
        payload.target_operator_r_nu_high = ...
            micro.target_operator.r_nu_high;
        payload.target_operator_r_nu_low = ...
            micro.target_operator.r_nu_low;
        payload.target_operator_unprojected_rhs_high = ...
            micro.target_operator.unprojected_rhs_high;
        payload.target_operator_unprojected_rhs_low = ...
            micro.target_operator.unprojected_rhs_low;
    end
end
diagnostics = base_mixed_diagnostics(micro,nDays,ordinaryMaximum, ...
    problemFactor,ordinaryResponseSeconds,affineRefinement,affineGatePass);
diagnostics.problem_recovery_continue_after_gate = ...
    problemRecoveryContinueAfterGate;
diagnostics.problem_target_operator_high_low = ...
    problemTargetOperatorHighLow;
diagnostics.problem_physical_operator_high_low = ...
    problemPhysicalOperatorHighLow;
diagnostics.problem_scaled_gamma_coordinate = ...
    problemScaledGammaCoordinate;
diagnostics.global_physical_operator_high_low = ...
    globalPhysicalOperatorHighLow;
diagnostics.problem_affine_combination_recovery = ...
    problemAffineCombinationRecovery;
diagnostics.factor_coordinate_promotion_used = factorPromotionEnabled;
diagnostics.factor_coordinate_promotion_count = factorPromotion.count;
diagnostics.factor_coordinate_delayed_indices = ...
    factorPromotion.delayed_indices;
diagnostics.global_physical_matrix_relative_difference = ...
    globalTarget.canonical_matrix_relative_difference;
diagnostics.global_physical_rhs_relative_difference = ...
    globalTarget.canonical_rhs_relative_difference;
if problemTargetOperatorHighLow
    diagnostics.problem_sqrt_d = double( ...
        micro.target_operator.sqrt_d_pair_vpa);
else
    diagnostics.problem_sqrt_d = sqrt(micro.d);
end
if ~affineGatePass
    diagnostics.affine_stop_reason = affineRefinement.stop_reason;
    return
end

previousDigits = digits(vpaDigits);
restoreDigits = onCleanup(@() digits(previousDigits));
if factorPromotionEnabled
    problemSchurSeconds = factorPromotion.schur_seconds;
    [coreMatrixVpa,coreRhsVpa] = ...
        assemble_factor_promoted_core_vpa( ...
            responseCells,problemResponse,factorPromotion, ...
            problemPosition,globalTarget,vpaDigits);
else
    [problemResponse,problemSchurSeconds] = ...
        build_problem_response_vpa(micro,affineHigh,affineLow,vpaDigits);
    [coreMatrixVpa,coreRhsVpa] = assemble_augmented_core_vpa( ...
        responseCells,problemResponse,problemPosition, ...
        globalTarget,vpaDigits);
end
coreDimension = size(coreMatrixVpa,1);
coreSymmetryVpa = norm(coreMatrixVpa-coreMatrixVpa.','fro')/ ...
    max(vpa(1,vpaDigits),norm(coreMatrixVpa,'fro'));
coreTimer = tic;
coreSolutionVpa = coreMatrixVpa\coreRhsVpa;
coreSolveSeconds = toc(coreTimer);
coreResidualVpa = coreMatrixVpa*coreSolutionVpa-coreRhsVpa;
coreDenominatorVpa = max(vpa(1,vpaDigits),norm(coreRhsVpa,2));
algebraicCoreRelativeVpa = norm(coreResidualVpa,2)/coreDenominatorVpa;
conditionTimer = tic;
coreSingularValues = svd(coreMatrixVpa);
coreConditionVpa = max(abs(coreSingularValues))/ ...
    min(abs(coreSingularValues));
conditionSeconds = toc(conditionTimer);
[coreMatrixHigh,coreMatrixLow] = ...
    vpa_to_high_low(coreMatrixVpa,vpaDigits);
[coreRhsHigh,coreRhsLow] = vpa_to_high_low(coreRhsVpa,vpaDigits);
[coreHigh,coreLow] = vpa_to_high_low(coreSolutionVpa,vpaDigits);
coreRoundedVpa = double_pair_to_vpa(coreHigh,coreLow,vpaDigits);
roundedCoreResidualVpa = coreMatrixVpa*coreRoundedVpa-coreRhsVpa;
roundedCoreRelativeVpa = norm(roundedCoreResidualVpa,2)/ ...
    coreDenominatorVpa;
coreRepresentationRelativeVpa = norm( ...
    coreSolutionVpa-coreRoundedVpa,2)/ ...
    max(vpa(1,vpaDigits),norm(coreSolutionVpa,2));

[direction,evaluation,dailyTable,recoveryHistory,recoveryTiming, ...
    kktTable,kktPayload] = recover_and_audit_mixed_direction( ...
    lin,partition,responseCells,retainedCells,micro,problemPosition, ...
    globalTarget,problemResponse,factorPromotion, ...
    coreMatrixVpa,coreRhsVpa,coreRoundedVpa,coreHigh,coreLow, ...
    localTolerance,kktTolerance,maximumPasses,vpaDigits, ...
    problemRecoveryContinueAfterGate,problemTargetOperatorHighLow, ...
    problemPhysicalOperatorHighLow,problemScaledGammaCoordinate, ...
    globalPhysicalOperatorHighLow,problemAffineCombinationRecovery);
artifacts.daily_table = dailyTable;
artifacts.problem_recovery_history = recoveryHistory;
artifacts.recovery_timing = recoveryTiming;
artifacts.kkt_block_table = kktTable;
artifacts.rounded_kkt_block_table = kktPayload.rounded_block_table;
artifacts.core_matrix_vpa50 = coreMatrixVpa;
artifacts.core_rhs_vpa50 = coreRhsVpa;
artifacts.core_matrix_high = coreMatrixHigh;
artifacts.core_matrix_low = coreMatrixLow;
artifacts.core_rhs_high = coreRhsHigh;
artifacts.core_rhs_low = coreRhsLow;
artifacts.core_solution_vpa50 = coreSolutionVpa;
artifacts.core_rounded_solution_vpa50 = coreRoundedVpa;
artifacts.actual_core_residual_vpa50 = ...
    kktPayload.actual_core_residual_vpa50;
artifacts.problem_dz_row_map = kktPayload.problem_dz_row_map;
diagnostics.complete_direction_formed = true;
