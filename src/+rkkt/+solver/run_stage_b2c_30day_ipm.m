function paths = history_paths(root)
paths = struct("iteration",fullfile(root,"iteration_history.csv"), ...
    "timing",fullfile(root,"timing_history.csv"), ...
    "factorization",fullfile(root,"daily_joint_factorization_history.csv"), ...
    "water_correction",fullfile(root, ...
        "water_slack_second_order_correction_history.csv"));
end

function persist_histories(paths,iteration,timing,factorization,waterCorrection)
rkkt.artifacts.write_table_csv_17g_atomic(paths.iteration,iteration);
rkkt.artifacts.write_table_csv_17g_atomic(paths.timing,timing);
rkkt.artifacts.write_table_csv_17g_atomic(paths.factorization,factorization);
