end

function metadata = checkpoint_metadata(iteration,commit,configSha,inputHash,config)
metadata = struct("iteration",iteration,"git_commit",char(commit), ...
    "config_sha256",char(configSha), ...
    "input_hash_fingerprint",char(inputHash), ...
    "recursive_route",char(config.recursive_route), ...
    "local_linear_solve_residual_tolerance", ...
        config.local_linear_solve_residual_tolerance, ...
    "recursive_full_kkt_residual_tolerance", ...
        config.recursive_full_kkt_residual_tolerance, ...
    "reduced_symmetry_tolerance",config.reduced_symmetry_tolerance, ...
    "border_symmetry_tolerance",config.border_symmetry_tolerance, ...
    "lagrangian_hessian_symmetry_tolerance", ...
        config.lagrangian_hessian_symmetry_tolerance, ...
    "full_kkt_role",char(config.full_kkt_role), ...
    "full_kkt_audit_executed",false, ...
    "water_slack_second_order_correction_enabled",true, ...
    "water_slack_second_order_correction_scope_count", ...
        config.expected_water_inequality_count, ...
    "no_full_direction_fallback",true, ...
    "full_direction_consumed_by_recursive",false);
end

function ensure_directory(pathValue)
if isfolder(pathValue), return; end
[created,message] = mkdir(pathValue);
assert(created,"stageB2C:recursive:Directory","%s",message);
end

function value = hash_text(textValue)
engine = java.security.MessageDigest.getInstance("SHA-256");
engine.update(unicode2native(char(textValue),"UTF-8"));
bytes = mod(double(engine.digest()),256);
value = lower(string(reshape(dec2hex(bytes,2).',1,[])));
end
