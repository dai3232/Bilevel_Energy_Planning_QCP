
function contract = stage_a_multiday_linearization_contract(lin)
%STAGE_A_MULTIDAY_LINEARIZATION_CONTRACT Validate a formal seven-day object.

arguments
    lin (1,1) struct
end
required = ["H","A","G","r_dual","r_eq","r_ineq","r_comp", ...
    "l","z","state","identity","stage_id","index","maps","layout"];
for name = required
    assert(isfield(lin,name),"stageAMultiday:solver:MissingLinearizationField", ...
        "Shared formal multi-day linearization is missing field '%s'.",name);
end
assert(isfield(lin.state,"xi"),"stageAMultiday:solver:MissingStateXi", ...
    "Shared formal multi-day linearization must contain state.xi.");
assert(isfield(lin.layout,"days") && isfield(lin.layout,"hours"), ...
    "stageAMultiday:solver:MissingLayoutScope", ...
    "formal multi-day layout must contain days and hours.");

mapsRequired = ["q_global","q_day_by_day","x_by_day_hour", ...
    "y_duration","y_binding_by_day","y_by_day_hour", ...
    "ineq_global","ineq_by_day_hour"];
for name = mapsRequired
    assert(isfield(lin.maps,name),"stageAMultiday:solver:MissingMapField", ...
        "Shared formal multi-day maps are missing field '%s'.",name);
end

nx = size(lin.H,1);
neq = size(lin.A,1);
nineq = size(lin.G,1);
assert(size(lin.H,2)==nx && isequal(size(lin.A),[neq,nx]) && ...
    isequal(size(lin.G),[nineq,nx]),"stageAMultiday:solver:MatrixShape", ...
    "H, A, or G has an invalid shape.");

contract = struct();
contract.stage_id = string(lin.stage_id);
assert(isscalar(contract.stage_id) && ...
    ismember(contract.stage_id,["stage_A3","stage_A4"]), ...
    "stageAMultiday:solver:StageId", ...
    "Formal seven-day solver supports only stage_A3 and stage_A4 identities.");
contract.nx = nx;
contract.neq = neq;
contract.nineq = nineq;
contract.identity = lin.identity;
contract.days = normalize_index_vector(lin.layout.days,"layout.days").';
contract.hours = normalize_index_vector(lin.layout.hours,"layout.hours").';
contract.n_days = numel(contract.days);
contract.n_hours = numel(contract.hours);
assert(contract.n_days==7 && isequal(contract.days,14:20), ...
    "stageAMultiday:solver:DayScope", ...
    "formal multi-day must contain days 14 through 20 exactly.");
assert(contract.n_hours==24 && isequal(contract.hours,1:24), ...
    "stageAMultiday:solver:HourScope", ...
    "Every formal multi-day day must contain hours 1 through 24 exactly.");

contract.q_global = normalize_index_vector(lin.maps.q_global, ...
    "maps.q_global");
contract.q_day_by_day = normalize_day_slices(lin.maps.q_day_by_day, ...
    contract.n_days,"maps.q_day_by_day");
contract.y_duration = normalize_index_vector(lin.maps.y_duration, ...
    "maps.y_duration");
contract.y_binding_by_day = normalize_day_slices( ...
    lin.maps.y_binding_by_day,contract.n_days,"maps.y_binding_by_day");
contract.ineq_global = normalize_index_vector(lin.maps.ineq_global, ...
    "maps.ineq_global");
contract.x_by_day_hour = normalize_day_hour_slices( ...
    lin.maps.x_by_day_hour,contract.n_days,contract.n_hours, ...
    "maps.x_by_day_hour");
contract.y_by_day_hour = normalize_day_hour_slices( ...
    lin.maps.y_by_day_hour,contract.n_days,contract.n_hours, ...
    "maps.y_by_day_hour");
contract.ineq_by_day_hour = normalize_day_hour_slices( ...
    lin.maps.ineq_by_day_hour,contract.n_days,contract.n_hours, ...
    "maps.ineq_by_day_hour");

assert(numel(contract.q_global)==14, ...
    "stageAMultiday:solver:GlobalCapacityDimension", ...
    "The global capacity direction must be 14-dimensional.");
assert(numel(contract.y_duration)==2, ...
    "stageAMultiday:solver:DurationDimension", ...
    "The duration multiplier direction must be 2-dimensional.");
assert(numel(contract.ineq_global)==28, ...
    "stageAMultiday:solver:GlobalBoundDimension", ...
    "Only 28 global capacity-bound rows are permitted.");
for d = 1:contract.n_days
    assert(numel(contract.q_day_by_day{d})==14 && ...
        numel(contract.y_binding_by_day{d})==14, ...
        "stageAMultiday:solver:DailyCapacityDimension", ...
        "Day %d needs one 14-vector capacity copy and 14 bindings.", ...
        contract.days(d));
    for t = 1:contract.n_hours
        assert(numel(contract.ineq_by_day_hour{d,t}) == ...
            2*numel(contract.x_by_day_hour{d,t}), ...
            "stageAMultiday:solver:HourlyBoundDimension", ...
            "Day %d hour %d must have exactly two bounds per active variable.", ...
            contract.days(d),contract.hours(t));
    end
end

assert_partition([contract.q_global;vertcat(contract.q_day_by_day{:}); ...
    vertcat(contract.x_by_day_hour{:})],nx,"primal-variable");
assert_partition([contract.y_duration; ...
    vertcat(contract.y_binding_by_day{:}); ...
    vertcat(contract.y_by_day_hour{:})],neq,"equality");
assert_partition([contract.ineq_global; ...
    vertcat(contract.ineq_by_day_hour{:})],nineq,"inequality");

contract.r_dual = normalize_numeric_vector(lin.r_dual,nx,"r_dual");
contract.r_eq = normalize_numeric_vector(lin.r_eq,neq,"r_eq");
contract.r_ineq = normalize_numeric_vector(lin.r_ineq,nineq,"r_ineq");
contract.r_comp = normalize_numeric_vector(lin.r_comp,nineq,"r_comp");
contract.l = normalize_numeric_vector(lin.l,nineq,"l");
contract.z = normalize_numeric_vector(lin.z,nineq,"z");
contract.xi = normalize_numeric_vector(lin.state.xi,nx,"state.xi");
assert(isreal(lin.H) && isreal(lin.A) && isreal(lin.G) && ...
    all(isfinite(nonzeros(lin.H))) && ...
    all(isfinite(nonzeros(lin.A))) && ...
    all(isfinite(nonzeros(lin.G))), ...
    "stageAMultiday:solver:NonfiniteMatrix", ...
    "H, A, and G must be real and finite.");
end

function slices = normalize_day_slices(value,count,fieldName)
slices = cell(1,count);
if iscell(value)
    assert(numel(value)==count,"stageAMultiday:solver:DayMapCount", ...
        "%s must contain %d day slices.",fieldName,count);
    for d = 1:count
        slices{d} = normalize_index_vector(value{d}, ...
            sprintf("%s{%d}",fieldName,d));
    end
elseif isnumeric(value) && isequal(size(value),[14,count])
    for d = 1:count
        slices{d} = normalize_index_vector(value(:,d), ...
            sprintf("%s(:,%d)",fieldName,d));
    end
else
    error("stageAMultiday:solver:DayMapType", ...
        "%s must be a cell array or a 14-by-%d numeric matrix.", ...
        fieldName,count);
end
end

function slices = normalize_day_hour_slices(value,nDays,nHours,fieldName)
assert(iscell(value) && isequal(size(value),[nDays,nHours]), ...
    "stageAMultiday:solver:DayHourMapShape", ...
    "%s must be a %d-by-%d cell array.",fieldName,nDays,nHours);
slices = cell(nDays,nHours);
for d = 1:nDays
    for t = 1:nHours
        slices{d,t} = normalize_index_vector(value{d,t}, ...
            sprintf("%s{%d,%d}",fieldName,d,t));
    end
end
end

function indices = normalize_index_vector(value,fieldName)
assert(isnumeric(value) && isreal(value) && isvector(value), ...
    "stageAMultiday:solver:IndexVectorType", ...
    "%s must be a real numeric vector.",fieldName);
indices = double(value(:));
assert(~isempty(indices) && all(isfinite(indices)) && ...
    all(indices>=1) && all(indices==fix(indices)) && ...
    numel(unique(indices))==numel(indices), ...
    "stageAMultiday:solver:IndexVectorValue", ...
    "%s must contain unique positive integer indices.",fieldName);
end

function vector = normalize_numeric_vector(value,expectedLength,fieldName)
assert(isnumeric(value) && isreal(value) && isvector(value), ...
    "stageAMultiday:solver:VectorType", ...
    "%s must be a real numeric vector.",fieldName);
vector = double(value(:));
assert(numel(vector)==expectedLength && all(isfinite(vector)), ...
    "stageAMultiday:solver:VectorValue", ...
    "%s must contain %d finite entries.",fieldName,expectedLength);
end

function assert_partition(indices,expectedCount,label)
indices = double(indices(:));
assert(numel(indices)==expectedCount && ...
    isequal(sort(indices),(1:expectedCount).'), ...
    "stageAMultiday:solver:MapPartition", ...
    "The %s maps must partition 1:%d exactly.",label,expectedCount);
end
