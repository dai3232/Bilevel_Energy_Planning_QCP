end

function [candidate,recovery,timing] = evaluate_candidate( ...
        lin,partition,retainedFactors,problemPositions,layout, ...
        matrix,rhs,solution,residualTolerance,kktTolerance,refinementPasses)
contract = partition.contract;
expandedResidual = matrix*solution-rhs;
expandedRelative = norm(expandedResidual,2)/max(1,norm(rhs,2));
coreSolution = solution(layout.global_range);
recoveryTimer = tic;
reducedDirection = zeros(contract.nx+contract.neq,1);
written = false(size(reducedDirection));
globalIndices = partition.global.canonical_reduced_indices;
reducedDirection(globalIndices) = coreSolution;
written(globalIndices) = true;
dailySolutions = cell(contract.n_days,1);
deltaQDay = cell(contract.n_days,1);
deltaPi = cell(contract.n_days,1);
directDiagnostics = cell(contract.n_days,1);
for d = 1:contract.n_days
    day = partition.day(d);
    problemIndex = find(problemPositions==d,1);
    if isempty(problemIndex)
        finalRhs = day.rhs-day.coupling*coreSolution;
        [local,directDiagnostics{d}] = ...
            rkkt.solver.apply_stage_b2c_daily_joint_factor( ...
            retainedFactors{d},day.matrix,finalRhs, ...
            "stageB2C_delayed_recovery_day_"+string(day.day_id), ...
            ResidualTolerance=residualTolerance, ...
            RefinementPasses=refinementPasses, ...
            ContinueNumericalPivotWarning=true);
    else
        localRange = layout.local_ranges{problemIndex};
        local = solution(localRange);
        localResidual = expandedResidual(localRange);
        localRelative = norm(localResidual,2)/max(1,norm(rhs(localRange),2));
        directDiagnostics{d} = promoted_daily_diagnostic( ...
            day.day_id,localRelative,max(abs(localResidual)), ...
            residualTolerance,refinementPasses);
    end
    directDiagnostics{d}.day_id = day.day_id;
    indices = day.canonical_reduced_indices;
    assert(~any(written(indices)), ...
