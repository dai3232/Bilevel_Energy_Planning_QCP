factor.maximum_absolute_residual = solve.maximum_absolute_residual;
factor.warning_identifier = solve.warning_identifier;
factor.warning_message = solve.warning_message;
factor.warning_present = solve.warning_present;
factor.warning_continued = solve.warning_continued;
factor.blocking_warning_present = solve.blocking_warning_present;
factor.solution_finite = solve.solution_finite;
factor.local_residual_tolerance = solve.local_residual_tolerance;
factor.local_residual_target_met = solve.local_residual_target_met;
factor.acceptance_scope = "expanded_border_and_reconstructed_kkt";
factor.solve_seconds = solve.solve_seconds;
factor.refinement_enabled = solve.refinement_enabled;
factor.refinement_triggered = solve.refinement_triggered;
