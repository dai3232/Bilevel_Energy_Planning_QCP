function moduleResult = runEquivalence(options)
%RUNEQUIVALENCE Cross-check staged recursion and audit full equivalence.
%   This is the only PKG-6 validation entry that reads the full direction
%   and calls the authoritative recursive controller.

arguments
    options.LinearizationArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.modelArtifact( ...
        "统一线性化模块输出.mat")
    options.FullKKTArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.solverArtifact( ...
        "完整KKT模块输出.mat")
    options.ReducedKKTArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.solverArtifact( ...
        "既约KKT模块输出.mat")
    options.PartitionArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.solverArtifact( ...
        "递推分区模块输出.mat")
    options.DayChainArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.solverArtifact( ...
        "小时链求解模块输出.mat")
    options.DayResponseArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.solverArtifact( ...
        "日响应模块输出.mat")
    options.AggregationArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.solverArtifact( ...
        "七日响应汇总输出.mat")
    options.CoreArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.solverArtifact( ...
        "16维全局核心模块输出.mat")
    options.RecoveryArtifact (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.solverArtifact( ...
        "局部回代模块输出.mat")
    options.Interactive (1,1) logical = true
    options.WriteArtifacts (1,1) logical = true
    options.OutputDirectory (1,1) string = ...
        rkkt.solver.validation.ValidationSupport.outputDirectory()
end

support = rkkt.solver.validation.ValidationSupport;
support.requireOutputDirectory( ...
    options.OutputDirectory,options.WriteArtifacts);
[modules,objects] = load_staged_objects(support,options);
linearization = objects.linearization;
fullResult = objects.fullResult;
config = modules.linearization.input.config;
maximumPasses = 0;

recursiveResult = support.callProduction( ...
    "solve_stage_a_multiday_recursive_direction",linearization, ...
    "AssemblyTolerance",config.tolerances.symmetry_relative, ...
    "SymmetryTolerance",config.tolerances.symmetry_relative, ...
    "ResidualRefinementMaxPasses",maximumPasses);
comparisons = staged_authority_comparisons( ...
    objects,recursiveResult);
if ~all(structfun(@(value) logical(value),comparisons))
    error("rkkt:solver:validation:StagedAuthorityMismatch", ...
        "At least one staged result differs from the authority result.");
end

thresholds = equivalence_thresholds(config);
legacyAudit = support.callProduction( ...
    "verify_stage_a_multiday_direction_equivalence", ...
    fullResult,recursiveResult,linearization, ...
    "DirectionRelative",thresholds.DirectionRelative, ...
    "RecursiveResidual",thresholds.RecursiveResidual, ...
    "FullResidualPreferred",thresholds.FullResidualPreferred, ...
    "FullResidualMaximum",thresholds.FullResidualMaximum);
audit = rkkt.solver.verifyEquivalence( ...
    fullResult,recursiveResult,linearization, ...
    DirectionRelative=thresholds.DirectionRelative, ...
    RecursiveResidual=thresholds.RecursiveResidual, ...
    FullResidualPreferred=thresholds.FullResidualPreferred, ...
    FullResidualMaximum=thresholds.FullResidualMaximum);
legacyFacadeExact = isequaln(legacyAudit,audit);
facts = equivalence_facts( ...
    audit,recursiveResult,objects,comparisons,legacyFacadeExact);
if ~all(structfun(@(value) logical(value),facts))
    error("rkkt:solver:validation:EquivalenceFacts", ...
        "One or more objective direction-equivalence facts are false.");
end

directionSummary = direction_summary(audit,thresholds);
residualSummary = residual_summary( ...
    audit,recursiveResult,thresholds);
[outputFile,tableFiles,figureFiles,figureIndex] = ...
    support.outputPaths(options.OutputDirectory, ...
    "方向等价性模块输出.mat", ...
    ["方向等价误差.csv";"完整KKT回插残差.csv"], ...
    "方向等价性",options.WriteArtifacts);
metadata = support.metadata("rkkt.solver.verifyEquivalence", ...
    "verify_stage_a_multiday_direction_equivalence", ...
    options.RecoveryArtifact,outputFile,"方向等价性模块", ...
    linearization.state.iteration_index, ...
    linearization.state.state_revision, ...
    options.Interactive,options.WriteArtifacts);
moduleResult = rkkt.contracts.moduleResultTemplate(metadata);
moduleResult.input = input_references( ...
    support,options,modules,linearization.identity,thresholds);
moduleResult.output = struct("audit",audit);
moduleResult.intermediate = struct( ...
    "directionSummary",directionSummary, ...
    "residualSummary",residualSummary, ...
    "figureIndex",figureIndex);
moduleResult.diagnostics = struct( ...
    "legacy_facade_exact_equal",legacyFacadeExact, ...
    "staged_authority_exact",comparisons, ...
    "staged_authority_all_exact", ...
        all(structfun(@(value)logical(value),comparisons)), ...
    "linearization_identity",string(audit.linearization_identity), ...
    "direction_relative_error",audit.direction_relative_error, ...
    "component_relative_errors",audit.component_relative_errors, ...
    "recursive_kkt_relative_residual", ...
        audit.recursive_kkt_relative_residual, ...
    "full_kkt_relative_residual",audit.full_kkt_relative_residual, ...
    "fixed_zero_count",recursiveResult.fixed_zero.count, ...
    "no_full_direction_fallback", ...
        recursiveResult.no_full_direction_fallback, ...
    "full_direction_consumed",recursiveResult.full_direction_consumed, ...
    "parallel_executed",recursiveResult.parallel_executed, ...
    "residual_refinement_maximum_passes", ...
        recursiveResult.residual_refinement.maximum_passes, ...
    "all_blocking_pass",audit.all_blocking_pass, ...
    "objective_facts",facts, ...
    "artifacts_written",options.WriteArtifacts);
moduleResult.indexDescription = struct( ...
    "direction_order","[xi;y;l;z]", ...
    "staged_day_order",objects.aggregation.day_ids_sorted, ...
    "authority_response_input_order","默认正式顺序", ...
    "role","完整KKT方向仅在本入口用于最终审计");
moduleResult.tableFiles = tableFiles;
moduleResult.figureFiles = figureFiles;
rkkt.contracts.validateModuleResult(moduleResult);

if options.WriteArtifacts
    support.writeTable17(directionSummary,tableFiles(1));
    support.writeTable17(residualSummary,tableFiles(2));
    fig = equivalence_figure( ...
        directionSummary,residualSummary,options.Interactive);
    support.saveFigurePair( ...
        fig,figureIndex.figPath,figureIndex.pngPath);
    if ~options.Interactive
        close(fig);
    end
    support.saveResult(outputFile,moduleResult);
end

fprintf("当前模块：方向等价性模块\n");
fprintf("逐级结果与权威总控严格相同：%d\n", ...
    all(structfun(@(value)logical(value),comparisons)));
fprintf("新旧等价性审计严格相同：%d\n",legacyFacadeExact);
fprintf("总方向/递推回插相对误差：%.17g/%.17g\n", ...
    audit.direction_relative_error, ...
    audit.recursive_kkt_relative_residual);
if options.WriteArtifacts
    fprintf("固定人工验证输出：%s\n",outputFile);
end
end

function [modules,objects] = load_staged_objects(support,options)
modules = struct();
modules.linearization = support.loadResult( ...
    options.LinearizationArtifact,"runEquivalence linearization", ...
    "rkkt.model.linearize");
modules.fullKKT = support.loadResult( ...
    options.FullKKTArtifact,"runEquivalence full KKT", ...
    "rkkt.solver.solveFullKKT");
modules.reducedKKT = support.loadResult( ...
    options.ReducedKKTArtifact,"runEquivalence reduced KKT", ...
    "rkkt.solver.eliminateInequalities");
modules.partition = support.loadResult( ...
    options.PartitionArtifact,"runEquivalence partition", ...
    "rkkt.solver.partitionRecursiveSystem");
modules.dayChain = support.loadResult( ...
    options.DayChainArtifact,"runEquivalence day chain", ...
    "rkkt.solver.solveDayChain");
modules.dayResponse = support.loadResult( ...
    options.DayResponseArtifact,"runEquivalence day response", ...
    "rkkt.solver.buildDayResponse");
modules.aggregation = support.loadResult( ...
    options.AggregationArtifact,"runEquivalence aggregation", ...
    "rkkt.solver.aggregateDayResponses");
modules.core = support.loadResult( ...
    options.CoreArtifact,"runEquivalence global core", ...
    "rkkt.solver.solveGlobalCore");
modules.recovery = support.loadResult( ...
    options.RecoveryArtifact,"runEquivalence recovery", ...
    "rkkt.solver.recoverDirection");
rkkt.contracts.requireFields(modules.linearization.input,"config", ...
    "runEquivalence linearization input");
rkkt.contracts.requireFields(modules.linearization.output, ...
    "linearization","runEquivalence linearization output");
rkkt.contracts.requireFields(modules.fullKKT.output,"fullResult", ...
    "runEquivalence full-KKT output");
rkkt.contracts.requireFields(modules.reducedKKT.output,"reduced", ...
    "runEquivalence reduced-KKT output");
rkkt.contracts.requireFields(modules.partition.output,"partition", ...
    "runEquivalence partition output");
rkkt.contracts.requireFields(modules.dayChain.output,"dailyThomas", ...
    "runEquivalence day-chain output");
rkkt.contracts.requireFields(modules.dayResponse.output, ...
    "dailyResponses","runEquivalence day-response output");
rkkt.contracts.requireFields(modules.aggregation.output,"aggregation", ...
    "runEquivalence aggregation output");
rkkt.contracts.requireFields(modules.core.output,"core", ...
    "runEquivalence core output");
rkkt.contracts.requireFields(modules.recovery.output,"recovery", ...
    "runEquivalence recovery output");
objects = struct( ...
    "linearization",modules.linearization.output.linearization, ...
    "fullResult",modules.fullKKT.output.fullResult, ...
    "reduced",modules.reducedKKT.output.reduced, ...
    "partition",modules.partition.output.partition, ...
    "dailyThomas",modules.dayChain.output.dailyThomas, ...
    "dailyResponses",modules.dayResponse.output.dailyResponses, ...
    "aggregation",modules.aggregation.output.aggregation, ...
    "core",modules.core.output.core, ...
    "recovery",modules.recovery.output.recovery);
end

function value = staged_authority_comparisons(objects,authority)
value = struct( ...
    "reduced",isequaln(objects.reduced,authority.reduced), ...
    "partition",isequaln(objects.partition,authority.partition), ...
    "daily_thomas", ...
        isequaln(objects.dailyThomas,authority.daily_thomas), ...
    "daily_responses", ...
        isequaln(objects.dailyResponses,authority.daily_responses), ...
    "aggregation", ...
        isequaln(objects.aggregation,authority.aggregation), ...
    "core",isequaln(objects.core,authority.core), ...
    "recovery_direction", ...
        isequaln(objects.recovery.direction,authority.direction), ...
    "recovery_components", ...
        isequaln(objects.recovery.components,authority.components), ...
    "fixed_zero", ...
        isequaln(objects.recovery.fixed_zero,authority.fixed_zero), ...
    "recovery_diagnostics", ...
        isequaln(objects.recovery.diagnostics,authority.recovery));
end

function value = equivalence_thresholds(config)
value = struct( ...
    "DirectionRelative", ...
        config.tolerances.direction_relative_2norm, ...
    "RecursiveResidual", ...
        config.tolerances.recursive_full_kkt_relative_residual, ...
    "FullResidualPreferred",config.tolerances.direct_preferred, ...
    "FullResidualMaximum",config.tolerances.direct_maximum);
end

function facts = equivalence_facts( ...
        audit,authority,objects,comparisons,legacyFacadeExact)
errors = audit.component_relative_errors;
identities = [ ...
    string(objects.linearization.identity); ...
    string(objects.fullResult.linearization_identity); ...
    string(objects.reduced.linearization_identity); ...
    string(objects.partition.linearization_identity); ...
    string(objects.aggregation.linearization_identity); ...
    string(objects.core.linearization_identity); ...
    string(objects.recovery.linearization_identity); ...
    string(authority.linearization_identity)];
facts = struct( ...
    "legacy_facade_exact_equal",legacyFacadeExact, ...
    "staged_authority_all_exact", ...
        all(structfun(@(value)logical(value),comparisons)), ...
    "identity_shared",isscalar(unique(identities)), ...
    "overall_direction_within_threshold", ...
        audit.direction_relative_error<= ...
            audit.thresholds.DirectionRelative, ...
    "component_directions_within_threshold", ...
        all([errors.xi;errors.y;errors.l;errors.z]<= ...
            audit.thresholds.DirectionRelative), ...
    "recursive_reinsertion_within_threshold", ...
        audit.recursive_kkt_relative_residual<= ...
            audit.thresholds.RecursiveResidual && ...
        authority.full_kkt_reinsertion.relative_residual<= ...
            audit.thresholds.RecursiveResidual, ...
    "full_residual_preferred", ...
        audit.full_kkt_relative_residual<= ...
            audit.thresholds.FullResidualPreferred && ...
        audit.passed.full_residual_preferred, ...
    "full_residual_hard",audit.passed.full_residual_hard, ...
    "fixed_zero_exact", ...
        authority.fixed_zero.count==422 && ...
        authority.fixed_zero.all_exact_zero && ...
        all(authority.fixed_zero.value==0) && ...
        all(authority.fixed_zero.direction==0), ...
    "day_sort_invariant", ...
        authority.aggregation.order_invariant_passed && ...
        audit.passed.day_sort_invariant, ...
    "serial_execution_only",~authority.parallel_executed, ...
    "residual_refinement_disabled", ...
        authority.residual_refinement.maximum_passes==0 && ...
        all(arrayfun(@(item) ...
            item.maximum_passes==0, ...
            authority.residual_refinement.daily)) && ...
        authority.residual_refinement.core.maximum_passes==0, ...
    "no_full_direction_fallback", ...
        authority.no_full_direction_fallback && ...
        audit.passed.no_full_direction_fallback, ...
    "full_direction_not_consumed", ...
        ~authority.full_direction_consumed, ...
    "audit_all_blocking_pass",audit.all_blocking_pass);
end

