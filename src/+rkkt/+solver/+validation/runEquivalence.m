        options.PartitionArtifact,identity, ...
        modules.partition.meta.interface_name), ...
    "dayChainArtifact",support.artifactReference( ...
        options.DayChainArtifact,identity, ...
        modules.dayChain.meta.interface_name), ...
    "dayResponseArtifact",support.artifactReference( ...
        options.DayResponseArtifact,identity, ...
        modules.dayResponse.meta.interface_name), ...
    "aggregationArtifact",support.artifactReference( ...
        options.AggregationArtifact,identity, ...
        modules.aggregation.meta.interface_name), ...
    "coreArtifact",support.artifactReference( ...
        options.CoreArtifact,identity, ...
        modules.core.meta.interface_name), ...
    "recoveryArtifact",support.artifactReference( ...
        options.RecoveryArtifact,identity, ...
        modules.recovery.meta.interface_name), ...
    "linearizationIdentity",string(identity), ...
    "thresholds",thresholds, ...
    "assemblyTolerance", ...
        modules.linearization.input.config.tolerances.symmetry_relative, ...
    "symmetryTolerance", ...
        modules.linearization.input.config.tolerances.symmetry_relative, ...
