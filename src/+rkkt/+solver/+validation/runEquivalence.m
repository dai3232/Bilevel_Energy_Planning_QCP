    "revision", ...
        modules.linearization.output.linearization.state.state_revision);
end

function value = direction_summary(audit,thresholds)
metric = ["overall";"xi";"y";"l";"z"];
relativeError = [ ...
    audit.direction_relative_error; ...
    audit.component_relative_errors.xi; ...
    audit.component_relative_errors.y; ...
    audit.component_relative_errors.l; ...
    audit.component_relative_errors.z];
threshold = repmat(thresholds.DirectionRelative,5,1);
passed = relativeError<=threshold;
value = table(metric,relativeError,threshold,passed);
end

function value = residual_summary(audit,authority,thresholds)
metric = [ ...
    "authority_recursive_reinsertion"; ...
    "audit_recursive_reinsertion"; ...
    "audit_full_direct"];
relativeResidual = [ ...
    authority.full_kkt_reinsertion.relative_residual; ...
    audit.recursive_kkt_relative_residual; ...
    audit.full_kkt_relative_residual];
threshold = [ ...
    thresholds.RecursiveResidual; ...
    thresholds.RecursiveResidual; ...
    thresholds.FullResidualPreferred];
passed = relativeResidual<=threshold;
value = table(metric,relativeResidual,threshold,passed);
end

function fig = equivalence_figure( ...
        directionSummary,residualSummary,interactive)
fig = rkkt.solver.validation.ValidationSupport.newFigure( ...
    "方向等价性",interactive);
tiledlayout(fig,1,2,"TileSpacing","compact", ...
    "Padding","compact");
nexttile;
semilogy(1:height(directionSummary), ...
    max(directionSummary.relativeError,realmin), ...
    "-o","LineWidth",1.4);
hold on;
yline(directionSummary.threshold(1),"--");
hold off;
xticks(1:height(directionSummary));
xticklabels(directionSummary.metric);
ylabel("相对误差（对数轴）");
title("方向等价误差");
grid on;
nexttile;
semilogy(1:height(residualSummary), ...
    max(residualSummary.relativeResidual,realmin), ...
    "-o","LineWidth",1.4);
hold on;
semilogy(1:height(residualSummary), ...
    residualSummary.threshold,"--","LineWidth",1.0);
hold off;
xticks(1:height(residualSummary));
xticklabels(residualSummary.metric);
xtickangle(25);
ylabel("相对残差（对数轴）");
title("完整KKT回插残差");
grid on;
end
