function moduleResult = runReducedKKT(options)
%RUNREDUCEDKKT Validate exact inequality elimination without solving it.
%   The shared linearization and full audit direction are read from their
%   fixed upstream MAT files. No recursive partition is constructed.

arguments
    options.LinearizationArtifact (1,1) string = ...
        default_linearization_artifact()
    options.FullKKTArtifact (1,1) string = default_full_kkt_artifact()
    options.Interactive (1,1) logical = true
    options.WriteArtifacts (1,1) logical = true
    options.OutputDirectory (1,1) string = default_output_directory()
end

linearizationArtifact = string(options.LinearizationArtifact);
fullKktArtifact = string(options.FullKKTArtifact);
outputDirectory = string(options.OutputDirectory);
rkkt.model.validation.ValidationSupport.requireOutputDirectory( ...
    outputDirectory,options.WriteArtifacts);
linearizationUpstream = ...
    rkkt.model.validation.ValidationSupport.loadResult( ...
    linearizationArtifact,"runReducedKKT linearization");
fullKktUpstream = rkkt.model.validation.ValidationSupport.loadResult( ...
    fullKktArtifact,"runReducedKKT full KKT");
if string(linearizationUpstream.meta.interface_name) ~= ...
        "rkkt.model.linearize"
    error("rkkt:solver:validation:ReducedLinearizationInterface", ...
        "runReducedKKT requires the shared linearization artifact.");
end
if string(fullKktUpstream.meta.interface_name) ~= ...
        "rkkt.solver.solveFullKKT"
    error("rkkt:solver:validation:ReducedFullKktInterface", ...
        "runReducedKKT requires the complete-KKT module artifact.");
end
rkkt.contracts.requireFields(linearizationUpstream.input, ...
    ["projectData";"config"],"runReducedKKT linearization input");
rkkt.contracts.requireFields(linearizationUpstream.output, ...
    "linearization","runReducedKKT linearization output");
rkkt.contracts.requireFields(fullKktUpstream.output,"fullResult", ...
    "runReducedKKT full-KKT output");
linearization = linearizationUpstream.output.linearization;
config = linearizationUpstream.input.config;
projectRoot = string( ...
    linearizationUpstream.input.projectData.projectRoot);
fullResult = fullKktUpstream.output.fullResult;

legacyReduced = call_legacy_elimination(linearization);
reduced = rkkt.solver.eliminateInequalities(linearization);
legacyFacadeExact = isequaln(legacyReduced,reduced);
consistency = consistency_metrics( ...
    reduced,fullResult,linearization,config);
facts = inspect_reduced_kkt(reduced,fullResult,linearization, ...
    config,consistency,legacyFacadeExact);
if ~all(structfun(@(value) logical(value),facts))
    error("rkkt:solver:validation:ReducedKktFacts", ...
        "One or more objective reduced-KKT observations are false.");
end

dimensionSummary = dimension_summary(reduced);
coefficientSummary = coefficient_summary(reduced);
consistencySummary = consistency_summary(consistency);
[outputFile,tableFiles,figureFiles,figureIndex] = output_paths( ...
    outputDirectory,options.WriteArtifacts);
metadata = rkkt.model.validation.ValidationSupport.metadata( ...
    "rkkt.solver.eliminateInequalities", ...
    "eliminate_stage_a_multiday_inequality_directions", ...
    linearizationArtifact,projectRoot,outputFile,"既约KKT模块", ...
    linearization.state.iteration_index, ...
    linearization.state.state_revision, ...
    options.Interactive,options.WriteArtifacts);
metadata.full_kkt_input_artifact = fullKktArtifact;
metadata.full_kkt_input_sha256 = ...
    rkkt.model.validation.ValidationSupport.sha256( ...
    fullKktArtifact,projectRoot);
moduleResult = rkkt.contracts.moduleResultTemplate(metadata);
moduleResult.input = struct( ...
    "linearizationArtifact",linearizationArtifact, ...
    "linearizationSha256",metadata.input_sha256, ...
    "fullKktArtifact",fullKktArtifact, ...
    "fullKktSha256",metadata.full_kkt_input_sha256, ...
    "linearizationIdentity",string(linearization.identity), ...
    "fullKktLinearizationIdentity", ...
        string(fullResult.linearization_identity), ...
    "counts",linearization.counts, ...
    "symmetryThreshold",config.tolerances.symmetry_relative, ...
    "equationResidualThreshold", ...
        config.tolerances.recursive_full_kkt_relative_residual, ...
    "recoveryRelativeThreshold", ...
        config.tolerances.direction_relative_2norm);
moduleResult.output = struct("reduced",reduced);
moduleResult.intermediate = struct( ...
    "dimensionSummary",dimensionSummary, ...
    "coefficientSummary",coefficientSummary, ...
    "consistencySummary",consistencySummary, ...
    "figureIndex",figureIndex);
moduleResult.diagnostics = struct( ...
    "legacy_facade_exact_equal",legacyFacadeExact, ...
    "linearization_identity",string(reduced.linearization_identity), ...
    "symmetry_relative",reduced.symmetry_relative, ...
    "reduced_equation_relative_residual", ...
        consistency.reducedEquationRelative, ...
    "reduced_equation_max_absolute_residual", ...
        consistency.reducedEquationMaximumAbsolute, ...
    "dl_recovery_relative_error",consistency.dlRelative, ...
    "dl_recovery_max_absolute_error",consistency.dlMaximumAbsolute, ...
    "dz_recovery_relative_error",consistency.dzRelative, ...
    "dz_recovery_max_absolute_error",consistency.dzMaximumAbsolute, ...
    "objective_facts",facts, ...
    "artifacts_written",options.WriteArtifacts);
moduleResult.indexDescription = struct( ...
    "reduced_direction_order","[dxi;dy]", ...
    "formula","W=H+G'*diag(z./l)*G", ...
    "saddle_order","[W A'; A 0]", ...
    "recovery_contract",string(reduced.recovery_contract), ...
    "scope","仅不等式消元，不分区、不求解既约系统");
moduleResult.tableFiles = tableFiles;
moduleResult.figureFiles = figureFiles;
rkkt.contracts.validateModuleResult(moduleResult);

if options.WriteArtifacts
    rkkt.model.validation.ValidationSupport.writeTable17( ...
        dimensionSummary,tableFiles(1));
    rkkt.model.validation.ValidationSupport.writeTable17( ...
        coefficientSummary,tableFiles(2));
    rkkt.model.validation.ValidationSupport.writeTable17( ...
        consistencySummary,tableFiles(3));
    fig = reduced_kkt_figure(reduced,options.Interactive);
    rkkt.model.validation.ValidationSupport.saveFigurePair( ...
        fig,figureIndex.figPath,figureIndex.pngPath);
    if ~options.Interactive
        close(fig);
    end
    rkkt.model.validation.ValidationSupport.saveResult( ...
        outputFile,moduleResult);
end

fprintf("当前模块：既约KKT模块\n");
fprintf("公共接口：rkkt.solver.eliminateInequalities\n");
fprintf("新旧既约结果严格相同：%d\n",legacyFacadeExact);
fprintf("saddle维数/nnz/对称误差：%d/%d/%.17g\n", ...
    size(reduced.saddle,1),nnz(reduced.saddle), ...
    reduced.symmetry_relative);
fprintf("既约方程/dl/dz相对误差：%.17g/%.17g/%.17g\n", ...
    consistency.reducedEquationRelative, ...
    consistency.dlRelative,consistency.dzRelative);
if options.WriteArtifacts
    fprintf("固定人工验证输出：%s\n",outputFile);
end
end

function value = call_legacy_elimination(linearization)
[solverDirectory,productionFile] = production_location( ...
    "eliminate_stage_a_multiday_inequality_directions.m");
originalPath = path;
pathGuard = onCleanup(@() path(originalPath));
addpath(solverDirectory,"-begin");
resolved = string(which( ...
    "eliminate_stage_a_multiday_inequality_directions"));
if ~same_path(resolved,productionFile)
    error("rkkt:solver:validation:EliminationFunctionShadowed", ...
        "Expected elimination function at '%s'; resolved '%s'.", ...
        productionFile,resolved);
end
value = eliminate_stage_a_multiday_inequality_directions( ...
    linearization);
clear pathGuard
end

function value = consistency_metrics( ...
        reduced,fullResult,linearization,config)
reducedDirection = [fullResult.components.xi; ...
    fullResult.components.y];
equationResidual = reduced.saddle*reducedDirection-reduced.rhs;
dlRecovered = -linearization.r_ineq- ...
    linearization.G*fullResult.components.xi;
dzRecovered = (-linearization.r_comp+ ...
    linearization.z.*linearization.r_ineq+ ...
    linearization.z.*( ...
        linearization.G*fullResult.components.xi))./ ...
    linearization.l;
dlError = dlRecovered-fullResult.components.l;
dzError = dzRecovered-fullResult.components.z;
value = struct( ...
    "reducedEquationRelative", ...
        norm(equationResidual,2)/max(1,norm(reduced.rhs,2)), ...
    "reducedEquationMaximumAbsolute", ...
        norm(equationResidual,inf), ...
    "reducedEquationThreshold", ...
        config.tolerances.recursive_full_kkt_relative_residual, ...
    "dlRelative",norm(dlError,2)/ ...
        max(1,norm(fullResult.components.l,2)), ...
    "dlMaximumAbsolute",norm(dlError,inf), ...
    "dzRelative",norm(dzError,2)/ ...
        max(1,norm(fullResult.components.z,2)), ...
    "dzMaximumAbsolute",norm(dzError,inf), ...
    "recoveryRelativeThreshold", ...
        config.tolerances.direction_relative_2norm);
end

function facts = inspect_reduced_kkt(reduced,fullResult, ...
        linearization,config,consistency,legacyFacadeExact)
thetaExpected = linearization.z./linearization.l;
facts = struct( ...
    "legacy_facade_exact_equal",legacyFacadeExact, ...
    "stage_exact", ...
        string(linearization.stage_id) == "stage_A4" && ...
        string(reduced.stage_id) == "stage_A4" && ...
        string(fullResult.stage_id) == "stage_A4", ...
    "identities_exact", ...
        isequaln(reduced.linearization_identity, ...
            linearization.identity) && ...
        isequaln(fullResult.linearization_identity, ...
            linearization.identity), ...
    "controlled_dimensions", ...
        isequal(size(reduced.W),[3722,3722]) && ...
        isequal(size(reduced.A),[618,3722]) && ...
        isequal(size(reduced.saddle),[4340,4340]), ...
    "matrix_storage_sparse", ...
        issparse(reduced.W) && issparse(reduced.A) && ...
        issparse(reduced.saddle), ...
    "linearization_A_exact",isequaln(reduced.A,linearization.A), ...
    "reduced_rhs_exact", ...
        isequaln(reduced.rhs,[reduced.b_xi;-linearization.r_eq]), ...
    "theta_formula_exact",isequaln(reduced.theta,thetaExpected), ...
    "theta_finite_strictly_positive", ...
        all(isfinite(reduced.theta)) && all(reduced.theta > 0), ...
    "symmetry_within_threshold", ...
        reduced.symmetry_relative <= ...
            config.tolerances.symmetry_relative, ...
    "reduced_equation_within_threshold", ...
        consistency.reducedEquationRelative <= ...
            config.tolerances.recursive_full_kkt_relative_residual, ...
    "dl_recovery_within_threshold", ...
        consistency.dlRelative <= ...
            config.tolerances.direction_relative_2norm, ...
    "dz_recovery_within_threshold", ...
        consistency.dzRelative <= ...
            config.tolerances.direction_relative_2norm, ...
    "recovery_contract_exact", ...
        string(reduced.recovery_contract) == ...
        "dl=-r_ineq-G*dxi; dz=(-r_comp+z.*r_ineq+z.*(G*dxi))./l");
end

function value = dimension_summary(reduced)
matrixName = ["W";"A";"saddle"];
matrices = {reduced.W;reduced.A;reduced.saddle};
n = numel(matrices);
rowCount = zeros(n,1);
columnCount = zeros(n,1);
nonzeroCount = zeros(n,1);
density = zeros(n,1);
sparseStorage = false(n,1);
for k = 1:n
    matrix = matrices{k};
    rowCount(k) = size(matrix,1);
    columnCount(k) = size(matrix,2);
    nonzeroCount(k) = nnz(matrix);
    density(k) = nonzeroCount(k)/(rowCount(k)*columnCount(k));
    sparseStorage(k) = issparse(matrix);
end
value = table(matrixName,rowCount,columnCount,nonzeroCount, ...
    density,sparseStorage);
end

function value = coefficient_summary(reduced)
coefficient = ["theta";"phi"];
vectors = {reduced.theta;reduced.phi};
n = numel(vectors);
elementCount = zeros(n,1);
minimum = zeros(n,1);
maximum = zeros(n,1);
norm2 = zeros(n,1);
normInf = zeros(n,1);
finite = false(n,1);
strictlyPositive = false(n,1);
for k = 1:n
    vector = vectors{k};
    elementCount(k) = numel(vector);
    minimum(k) = min(vector,[],"all");
    maximum(k) = max(vector,[],"all");
    norm2(k) = norm(vector,2);
    normInf(k) = norm(vector,inf);
    finite(k) = all(isfinite(vector),"all");
    strictlyPositive(k) = all(vector > 0,"all");
end
value = table(coefficient,elementCount,minimum,maximum,norm2, ...
    normInf,finite,strictlyPositive);
end

function value = consistency_summary(consistency)
checkName = ["reduced_equation";"dl_recovery";"dz_recovery"];
relativeError = [consistency.reducedEquationRelative; ...
    consistency.dlRelative;consistency.dzRelative];
maximumAbsoluteError = [ ...
    consistency.reducedEquationMaximumAbsolute; ...
    consistency.dlMaximumAbsolute;consistency.dzMaximumAbsolute];
relativeThreshold = [consistency.reducedEquationThreshold; ...
    consistency.recoveryRelativeThreshold; ...
    consistency.recoveryRelativeThreshold];
value = table(checkName,relativeError,maximumAbsoluteError, ...
    relativeThreshold);
end

function fig = reduced_kkt_figure(reduced,interactive)
visibility = "off";
if interactive
    visibility = "on";
end
fig = figure("Name","既约KKT：稀疏结构", ...
    "NumberTitle","off","Color","w","Visible",visibility, ...
    "Position",[100,100,920,720]);
spy(reduced.saddle);
title(compose("既约鞍点矩阵：%d×%d，nnz=%d", ...
    size(reduced.saddle,1),size(reduced.saddle,2), ...
    nnz(reduced.saddle)));
end

function [outputFile,tableFiles,figureFiles,index] = ...
        output_paths(outputDirectory,writeArtifacts)
if writeArtifacts
    outputFile = fullfile(outputDirectory,"既约KKT模块输出.mat");
    tableFiles = [ ...
        fullfile(outputDirectory,"既约KKT维数与稀疏性.csv")
        fullfile(outputDirectory,"不等式消元系数摘要.csv")
        fullfile(outputDirectory,"既约方程与回代一致性.csv")];
    figPath = fullfile(outputDirectory,"既约KKT稀疏结构.fig");
    pngPath = fullfile(outputDirectory,"既约KKT稀疏结构.png");
    figureFiles = [figPath;pngPath];
else
    outputFile = "";
    tableFiles = strings(0,1);
    figPath = "";
    pngPath = "";
    figureFiles = strings(0,1);
end
tableFiles = reshape(string(tableFiles),[],1);
figureFiles = reshape(string(figureFiles),[],1);
index = struct("figPath",string(figPath),"pngPath",string(pngPath));
end

function [directory,file] = production_location(fileName)
validationDirectory = string(fileparts(mfilename("fullpath")));
packageDirectory = string(fileparts(validationDirectory));
rkktDirectory = string(fileparts(packageDirectory));
sourceDirectory = string(fileparts(rkktDirectory));
directory = fullfile(sourceDirectory,"solver");
file = fullfile(directory,fileName);
end

function value = default_linearization_artifact()
validationDirectory = string(fileparts(mfilename("fullpath")));
solverDirectory = string(fileparts(validationDirectory));
rkktDirectory = string(fileparts(solverDirectory));
value = fullfile(rkktDirectory,"+model","+validation", ...
    "统一线性化模块输出.mat");
end

function value = default_full_kkt_artifact()
value = fullfile(default_output_directory(),"完整KKT模块输出.mat");
end

function value = default_output_directory()
value = string(fileparts(mfilename("fullpath")));
end

function value = same_path(left,right)
left = replace(string(left),"/","\");
right = replace(string(right),"/","\");
if ispc
    value = strcmpi(left,right);
else
    value = strcmp(left,right);
end
end
