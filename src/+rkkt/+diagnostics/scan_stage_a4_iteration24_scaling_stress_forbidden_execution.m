function audit = ...
        scan_stage_a4_iteration24_scaling_stress_forbidden_execution( ...
        projectRoot,runtime)
%SCAN_STAGE_A4_ITERATION24_SCALING_STRESS_FORBIDDEN_EXECUTION Audit closure.
%
% This scanner follows the actual MATLAB dependency closures rooted at the
% stress computation and recursive direction.  It separates static source
% prohibitions from runtime booleans so no single no-fallback flag can
% masquerade as evidence for unrelated forbidden algorithms.

arguments
    projectRoot (1,1) string
    runtime (1,1) struct
end

stressEntry = fullfile(projectRoot,"src","+rkkt","+diagnostics", ...
    "run_stage_a4_iteration24_scaling_stress.m");
recursiveEntry = fullfile(projectRoot,"src","+rkkt","+solver", ...
    "solve_stage_a_multiday_recursive_direction.m");
fullAuditEntry = fullfile(projectRoot,"src","+rkkt","+solver", ...
    "solve_stage_a_multiday_full_kkt_direction.m");
stressFiles = project_m_files(dependency_files(stressEntry),projectRoot);
recursiveFiles = project_m_files( ...
    dependency_files(recursiveEntry),projectRoot);
allFiles = unique([stressFiles;recursiveFiles],"stable");
assert(~isempty(stressFiles)&&~isempty(recursiveFiles), ...
    "stageA4:scaleStress:ForbiddenClosureEmpty", ...
    "The scaling-stress dependency closure is empty.");

codeText = strings(numel(allFiles),1);
for k=1:numel(allFiles)
    codeText(k) = strip_matlab_noncode(fileread(allFiles(k)));
end
rules = [ ...
    make_rule("NO-INV","No inv call", ...
        "(?<![A-Za-z0-9_])inv\s*\(")
    make_rule("NO-PINV","No pinv call", ...
        "(?<![A-Za-z0-9_])pinv\s*\(")
    make_rule("NO-LSQMINNORM","No lsqminnorm call", ...
        "(?<![A-Za-z0-9_])lsqminnorm\s*\(")
    make_rule("NO-NEGATIVE-MATRIX-POWER", ...
        "No explicit negative-one matrix power", ...
        "\^\s*\(?\s*-1\s*\)?")
    make_rule("NO-RANDOM","No random-number call", ...
        "(?<![A-Za-z0-9_])(?:rand|randn|randi|randperm|rng)\s*\(")
    make_rule("NO-PARALLEL","No parallel execution call", ...
        "(?<![A-Za-z0-9_])(?:(?:parfor|spmd)(?![A-Za-z0-9_])|" + ...
        "(?:parpool|parfeval|parfevalOnAll|backgroundPool|gcp)" + ...
        "\s*\()")
    make_rule("NO-LINE-SEARCH","No line-search helper", ...
        "(?<![A-Za-z0-9_])(?:line_?search|backtrack(?:ing)?|" + ...
        "armijo|wolfe)\s*\(")
    make_rule("NO-REGULARIZATION","No regularization helper", ...
        "(?<![A-Za-z0-9_])(?:regulari[sz]e|add_?jitter|" + ...
        "diagonal_?shift)\s*\(")
    make_rule("NO-AUTOMATIC-SYMMETRIZATION", ...
        "No automatic symmetrization helper", ...
        "(?<![A-Za-z0-9_])(?:symmetri[sz]e|" + ...
        "make_?symmetric)\s*\(")
    make_rule("NO-PREDICTOR-CORRECTOR", ...
        "No predictor-corrector helper", ...
        "(?<![A-Za-z0-9_])(?:mehrotra|predictor_?corrector|" + ...
        "predictorcorrector)\s*\(")
    make_rule("NO-DIRECT-RAW-THOMAS-BACKSLASH", ...
        "No direct raw day-chain solve fallback", ...
        "(?:partition\s*\.\s*M|rawOperator)\s*\\")
    make_rule("NO-EXPLICIT-AVERAGE-SYMMETRIZATION", ...
        "No (M+M')/2 style matrix rewrite", ...
        "\(\s*[A-Za-z][A-Za-z0-9_\.]*\s*\+\s*" + ...
        "[A-Za-z][A-Za-z0-9_\.]*\s*\.\s*'\s*\)\s*/\s*2")];

checkId = strings(numel(rules)+11,1);
requirement = strings(numel(rules)+11,1);
matchCount = zeros(numel(rules)+11,1);
matchedFiles = strings(numel(rules)+11,1);
evidenceType = strings(numel(rules)+11,1);
status = repmat("PASS",numel(rules)+11,1);
row = 0;
for q=1:numel(rules)
    row=row+1;
    hits = strings(0,1);
    count = 0;
    for k=1:numel(allFiles)
        found = regexpi(char(codeText(k)),char(rules(q).pattern), ...
            "match");
        count = count+numel(found);
        if ~isempty(found)
            hits(end+1,1)=relative_path(allFiles(k),projectRoot); %#ok<AGROW>
        end
    end
    checkId(row)=rules(q).id;
    requirement(row)=rules(q).requirement;
    matchCount(row)=count;
    matchedFiles(row)=strjoin(unique(hits,"stable"),"; ");
    evidenceType(row)="dependency_closure_source_scan";
    if count~=0, status(row)="FAIL"; end
end

fullAuditCanonical = canonical_path(fullAuditEntry);
recursiveCanonical = arrayfun(@canonical_path,recursiveFiles);
row=row+1;
checkId(row)="NO-FULL-KKT-IN-RECURSIVE-CLOSURE";
requirement(row)="Recursive solver closure excludes complete-KKT solve";
matchCount(row)=nnz(lower(recursiveCanonical)==lower(fullAuditCanonical));
matchedFiles(row)=relative_path(fullAuditEntry,projectRoot);
evidenceType(row)="recursive_dependency_closure";
if matchCount(row)~=0, status(row)="FAIL"; end
if matchCount(row)==0
    matchedFiles(row)="";
end

runtimeIds = [ ...
    "RUNTIME-NO-FULL-DIRECTION-FALLBACK"; ...
    "RUNTIME-COMPLETE-KKT-AUDIT-ONLY"; ...
    "RUNTIME-NO-REGULARIZATION"; ...
    "RUNTIME-NO-AUTOMATIC-SYMMETRIZATION"; ...
    "RUNTIME-NO-PARALLEL"; ...
    "RUNTIME-NO-FULL-IPM"; ...
    "RUNTIME-NO-OPTIMIZATION"; ...
    "RUNTIME-NO-STATE-UPDATE"; ...
    "RUNTIME-SCALING-EXPLICITLY-ENABLED"; ...
    "RUNTIME-STRESS-ROUTE-EXPLICITLY-ENABLED"];
runtimeValues = [ ...
    logical(runtime.no_full_direction_fallback && ...
        runtime.execution_ledger.full_direction_fallback_calls==0); ...
    runtime.full_kkt_role=="independent_audit_only"; ...
    logical(~runtime.regularization_used && ...
        runtime.execution_ledger.regularization_calls==0); ...
    logical(~runtime.automatic_symmetrization_used && ...
        runtime.execution_ledger.automatic_symmetrization_calls==0); ...
    logical(~runtime.parallel_executed && ...
        runtime.execution_ledger.parallel_calls==0); ...
    logical(~runtime.full_ipm_executed && ...
        runtime.execution_ledger.full_ipm_calls==0); ...
    logical(~runtime.optimization_executed && ...
        runtime.execution_ledger.optimization_calls==0); ...
    logical(runtime.state_update_count==0 && ...
        runtime.execution_ledger.state_update_calls==0); ...
    logical(runtime.effective_config.use_congruence_scaling); ...
    logical(runtime.recursive.congruence_scaling.used)];
runtimeRequirements = [ ...
    "No complete-KKT direction fallback observed"; ...
    "Complete KKT used only for independent audit"; ...
    "No regularization observed"; ...
    "No automatic symmetrization observed"; ...
    "No parallel execution observed"; ...
    "No full IPM execution observed"; ...
    "No optimization execution observed"; ...
    "No primal-dual state update observed"; ...
    "Stress YAML explicitly enables congruence scaling"; ...
    "The recursive stress call explicitly enabled the optional route"];
for q=1:numel(runtimeIds)
    row=row+1;
    checkId(row)=runtimeIds(q);
    requirement(row)=runtimeRequirements(q);
    passed = logical(runtimeValues(q));
    matchCount(row)=double(~passed);
    evidenceType(row)="runtime_record";
    if ~passed, status(row)="FAIL"; end
end
assert(row==numel(checkId), ...
    "stageA4:scaleStress:ForbiddenRowCount", ...
    "The forbidden-execution audit row count changed.");
results = table(checkId,requirement,matchCount,matchedFiles, ...
    evidenceType,status, ...
    'VariableNames',{'check_id','requirement','match_count', ...
    'matched_files','evidence_type','status'});

relativePath = relative_paths(allFiles,projectRoot);
sha256 = strings(numel(allFiles),1);
inStressClosure = ismember(allFiles,stressFiles);
inRecursiveClosure = ismember(allFiles,recursiveFiles);
for k=1:numel(allFiles)
    sha256(k)=rkkt.data.compute_sha256_file(allFiles(k));
end
closure = table(relativePath,sha256,inStressClosure, ...
    inRecursiveClosure, ...
    'VariableNames',{'relative_path','sha256', ...
    'in_stress_closure','in_recursive_closure'});
audit = struct( ...
    "results",results, ...
    "dependency_closure",closure, ...
    "all_pass",all(results.status=="PASS"), ...
    "check_count",height(results), ...
    "dependency_file_count",height(closure), ...
    "independent_checks",true);
end

function files = dependency_files(entryPath)
[files,~] = matlab.codetools.requiredFilesAndProducts(char(entryPath));
files = unique([string(files(:));string(entryPath)],"stable");
end

function files = project_m_files(paths,root)
rootCanonical = canonical_path(root);
prefix = lower(rootCanonical+filesep);
canonical = arrayfun(@canonical_path,paths);
mask = startsWith(lower(canonical),prefix) & endsWith(canonical,".m");
files = unique(canonical(mask),"stable");
end

function rule = make_rule(id,requirement,pattern)
rule = struct("id",string(id),"requirement",string(requirement), ...
    "pattern",string(pattern));
end

function output = strip_matlab_noncode(textValue)
output = string(textValue);
output = regexprep(output,'"(?:""|[^"])*"'," ");
output = regexprep(output, ...
    "(?<![A-Za-z0-9_\)\]\}\.])'(?:''|[^'])*'"," ");
output = regexprep(output,"(?s)%\{.*?%\}"," ");
lines = splitlines(output);
for line = 1:numel(lines)
    position = regexp(char(lines(line)),"%", "once");
    if ~isempty(position)
        lines(line) = extractBefore(lines(line),position);
    end
end
output = strjoin(lines,newline);
end

function values = relative_paths(paths,root)
values = strings(numel(paths),1);
for k=1:numel(paths)
    values(k)=relative_path(paths(k),root);
end
end

function value = relative_path(pathValue,root)
pathValue=canonical_path(pathValue);
root=canonical_path(root);
value=replace(extractAfter(pathValue,strlength(root)+1),"\","/");
end

function value = canonical_path(pathValue)
value=string(char(java.io.File(char(pathValue)).getCanonicalPath()));
end
