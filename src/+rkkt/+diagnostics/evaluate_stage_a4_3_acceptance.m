function acceptance = evaluate_stage_a4_3_acceptance( ...
        projectRoot,runResult,physicalAudit,options)
%EVALUATE_STAGE_A4_3_ACCEPTANCE Evaluate the frozen seven A4 gates.

arguments
    projectRoot (1,1) string
    runResult (1,1) struct
    physicalAudit table
    options.ReportEvidence (1,1) struct = struct()
end
sourcePath = fullfile(projectRoot,"stages","stage_A4", ...
    "阶段A4_验收矩阵.csv");
config = rkkt.model.load_stage_a4_3_configuration(projectRoot);
a43 = config.a4_3;
acceptance = readtable(sourcePath,"TextType","string", ...
    "VariableNamingRule","preserve");
for name = ["test_id","category","requirement","command_or_method", ...
        "threshold","expected_evidence","status","actual_value"]
    acceptance.(name) = string(acceptance.(name));
end
assert(height(acceptance)==7 && ...
    isequal(acceptance.test_id,[ ...
        "SA4-CONV-001";"SA4-CONV-002";"SA4-CONV-003"; ...
        "SA4-CONV-004";"SA4-EQ-001";"SA4-PHY-001"; ...
        "SA4-RPT-001"]), ...
    "stageA4:a43:AcceptanceIdentity", ...
    "The controlled Stage A4 acceptance matrix changed.");
m = runResult.final_metrics;
direction = runResult.direction_audit;
if isempty(direction)
    worstDirection = Inf;
    directionEvidenceComplete = false;
else
    governedDirectionMetrics = [ ...
        direction.direction_relative_error
        direction.xi_relative_error
        direction.y_relative_error
        direction.l_relative_error
        direction.z_relative_error
        direction.recursive_full_kkt_relative_residual];
    worstDirection = max(governedDirectionMetrics,[],"all");
    count = runResult.iteration_count;
    directionNumericalPass = ...
        all(direction.direction_relative_error<= ...
            a43.direction_relative_tolerance) && ...
        all(direction.xi_relative_error<= ...
            a43.direction_relative_tolerance) && ...
        all(direction.y_relative_error<= ...
            a43.direction_relative_tolerance) && ...
        all(direction.l_relative_error<= ...
            a43.direction_relative_tolerance) && ...
        all(direction.z_relative_error<= ...
            a43.direction_relative_tolerance) && ...
        all(direction.recursive_full_kkt_relative_residual<= ...
            a43.recursive_full_kkt_residual_tolerance) && ...
        all(direction.full_kkt_relative_residual<= ...
            a43.full_kkt_residual_tolerance);
    directionEvidenceComplete = height(direction)==count && ...
        isequal(direction.iteration,(1:count).') && ...
        isequal(direction.state_revision_before,(0:count-1).') && ...
        isequal(direction.state_revision_after,(1:count).') && ...
        all(direction.no_full_direction_fallback) && ...
        all(direction.full_kkt_audit_only) && ...
        all(direction.recursive_direction_is_official) && ...
        runResult.full_kkt_audit_count==count && ...
        runResult.execution_audit.one_full_kkt_audit_per_accepted_iteration && ...
        runResult.execution_audit.direction_audits_pass && ...
        runResult.execution_audit.no_full_direction_fallback && ...
        runResult.execution_audit.forbidden_execution_pass && ...
        directionNumericalPass;
    if ~directionEvidenceComplete
        worstDirection = Inf;
    end
end
converged = runResult.run_terminal_state=="CONVERGED" && ...
    runResult.convergence_achieved;
expectedPhysicalIds = [ ...
    "A43-PHY-EQUALITY"
    "A43-PHY-POWER-BALANCE"
    "A43-PHY-SOC-CHAIN"
    "A43-PHY-SOC-TERMINAL"
    "A43-PHY-INEQUALITY"
    "A43-PHY-FIXED-ZERO-VALUE"
    "A43-PHY-FIXED-ZERO-DIRECTION"
    "A43-PHY-NO-INTERDAY-SOC"];
physicalEvidenceComplete = height(physicalAudit)==8 && ...
    all(ismember(["audit_id","status"], ...
    string(physicalAudit.Properties.VariableNames))) && ...
    isequal(string(physicalAudit.audit_id),expectedPhysicalIds) && ...
    numel(unique(string(physicalAudit.audit_id)))==8;
physicalPassed = physicalEvidenceComplete && ...
    all(string(physicalAudit.status)=="PASS");
[reportPassed,reportAttempted,reportReason] = ...
    validate_report_evidence(options.ReportEvidence);
actual = [m.r_eq_inf;m.r_ineq_inf;m.r_dual_scaled_inf; ...
    m.mean_lz_scaled;worstDirection; ...
    double(~physicalPassed);double(~reportPassed)];
thresholds = [a43.primal_equality_inf_tolerance; ...
    a43.primal_inequality_inf_tolerance; ...
    a43.dual_scaled_inf_tolerance; ...
    a43.mean_lz_scaled_tolerance; ...
    a43.direction_relative_tolerance;0;0];
for row = 1:height(acceptance)
    if row==7
        acceptance.actual_value(row) = reportReason;
    else
        acceptance.actual_value(row) = compose("%.17g",actual(row));
    end
    if row==7 && ~reportAttempted
        acceptance.status(row) = "NOT_RUN";
    elseif row==7 && ~reportPassed
        acceptance.status(row) = "FAIL";
    elseif row<=4 && ~(converged && actual(row)<=thresholds(row))
        acceptance.status(row) = "FAIL";
    elseif row==5 && ...
            ~(directionEvidenceComplete && actual(row)<=thresholds(row))
        acceptance.status(row) = "FAIL";
    elseif actual(row)<=thresholds(row)
        acceptance.status(row) = "PASS";
    else
        acceptance.status(row) = "FAIL";
    end
end
acceptance.expected_evidence = [ ...
    "iterations/iteration_summary.csv"
    "iterations/iteration_summary.csv"
    "iterations/iteration_summary.csv"
    "iterations/iteration_summary.csv"
    "iterations/direction_audit.csv"
    "acceptance/physical_audit.csv"
    "reports"];
end

function [passed,attempted,reason] = validate_report_evidence(evidence)
passed = false;
attempted = false;
reason = "report_evidence_not_provided";
if isempty(fieldnames(evidence))
    return
end
attempted = true;
reason = "report_evidence_schema_invalid";
required = ["run_root","report_paths","structure_validation", ...
    "visual_validation","hash_manifest"];
if ~all(isfield(evidence,cellstr(required))) || ...
        ~isstruct(evidence.report_paths) || ...
        ~istable(evidence.structure_validation) || ...
        ~istable(evidence.visual_validation) || ...
        ~istable(evidence.hash_manifest)
    return
end
reason = "report_path_identity_invalid";
pathNames = sort(string(fieldnames(evidence.report_paths)));
if ~isequal(pathNames,sort([ ...
        "model_report";"issue_report";"run_summary"]))
    return
end
paths = string(struct2cell(evidence.report_paths));
if numel(paths)~=3 || ~all(isfile(paths))
    return
end
reason = "report_validation_tables_invalid";
structure = evidence.structure_validation;
visual = evidence.visual_validation;
hashes = evidence.hash_manifest;
if ~all(ismember(["status","path"], ...
        string(structure.Properties.VariableNames))) || ...
        height(structure)~=3 || ...
        ~all(string(structure.status)=="PASS") || ...
        ~all(ismember(["status","report_path","page_number", ...
        "page_count","image_path","image_sha256"], ...
        string(visual.Properties.VariableNames))) || isempty(visual) || ...
        ~all(string(visual.status)=="PASS") || ...
        ~all(ismember(["relative_path","sha256","status"], ...
        string(hashes.Properties.VariableNames)))
    return
end
reason = "report_path_hash_or_visual_evidence_invalid";
root = string(evidence.run_root);
for k = 1:numel(paths)
    canonical = string(char(java.io.File(char(paths(k))).getCanonicalPath()));
    canonicalRoot = string(char(java.io.File(char(root)).getCanonicalPath()));
    if ~startsWith(lower(canonical),lower(canonicalRoot+filesep))
        return
    end
    relative = replace(extractAfter(canonical, ...
        strlength(canonicalRoot)+1),"\","/");
    row = hashes(string(hashes.relative_path)==relative,:);
    if height(row)~=1 || string(row.status)~="PASS" || ...
            lower(string(row.sha256))~= ...
            lower(string(rkkt.data.compute_sha256_file(canonical)))
        return
    end
    reportVisual = visual(string(visual.report_path)==canonical,:);
    pageNumbers = double(reportVisual.page_number);
    pageCounts = double(reportVisual.page_count);
    if nnz(string(structure.path)==canonical)~=1 || ...
            isempty(reportVisual) || ...
            ~isscalar(unique(pageCounts)) || ...
            unique(pageCounts)~=height(reportVisual) || ...
            ~isequal(sort(pageNumbers),(1:height(reportVisual)).')
        return
    end
    for page = 1:height(reportVisual)
        imagePath = string(reportVisual.image_path(page));
        if ~isfile(imagePath) || ...
                lower(string(rkkt.data.compute_sha256_file(imagePath)))~= ...
                lower(string(reportVisual.image_sha256(page)))
            return
        end
    end
end
passed = true;
reason = "three_reports_structure_visual_and_sha256_validated";
end
