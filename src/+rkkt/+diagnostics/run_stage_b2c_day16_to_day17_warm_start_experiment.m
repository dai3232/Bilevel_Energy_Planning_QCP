function value = acceptance_table(runId,mapping,reset,iterations,directions, ...
        terminalState,config,inputPass)
mappingPass = height(mapping)==516 && nnz(mapping.source_matched)==515 && ...
    nnz(~mapping.source_matched)==1 && ...
    all(mapping.warm_target_value(mapping.source_matched)== ...
        mapping.source_value(mapping.source_matched));
resetPass = reset.all_finite && reset.l_strictly_positive && ...
    reset.z_strictly_positive;
if isempty(directions)
    directionPass = false;
    maximumDirectionError = NaN;
    maximumRecursiveResidual = NaN;
else
    directionPass = all(directions.all_pass) && ...
        all(directions.no_full_direction_fallback) && ...
        all(directions.full_direction_not_consumed);
    maximumDirectionError = max(directions.direction_relative_error);
    maximumRecursiveResidual = max(directions.recursive_kkt_relative_residual);
end
outcomePass = terminalState=="CONVERGED";
check_id = ["WARM-INPUT-001";"WARM-MAP-001";"WARM-STATE-001"; ...
    "WARM-DIR-001";"WARM-OUTCOME-001"];
requirement = ["受控输入哈希保持通过"; ...
    "第16日至第17日物理原变量按规范标识映射"; ...
    "第17日y/l/z重新初始化且l/z严格为正"; ...
    "全部已接受实验方向通过独立完整KKT审计"; ...
    "Warm-start实验达到原冻结收敛阈值"];
actual_value = [string(inputPass); ...
    "matched="+nnz(mapping.source_matched)+", unmatched="+ ...
        nnz(~mapping.source_matched); ...
    "min_l="+compose("%.17g",reset.minimum_l)+", min_z="+ ...
        compose("%.17g",reset.minimum_z); ...
    "max_direction="+compose("%.17g",maximumDirectionError)+ ...
        ", max_recursive_residual="+ ...
        compose("%.17g",maximumRecursiveResidual); ...
    terminalState+", accepted="+height(iterations)];
threshold = ["true";"515 matched + 1 deterministic unmatched"; ...
    "finite and >0";"<= "+compose("%.17g", ...
        config.direction_relative_error_tolerance);"CONVERGED"];
passed = [inputPass;mappingPass;resetPass;directionPass;outcomePass];
status = repmat("PASS",5,1); status(~passed) = "FAIL";
value = table(repmat(string(runId),5,1),check_id,requirement, ...
    actual_value,threshold,true(5,1),status, ...
    ["input_hashes.csv"; ...
    "diagnostics/day16_to_day17_primal_mapping.csv"; ...
    "diagnostics/day17_dual_slack_reset.csv"; ...
    "diagnostics/direction_audit_history.csv"; ...
    "diagnostics/iteration_history.csv"], ...
    'VariableNames',{'run_id','check_id','requirement','actual_value', ...
    'threshold','blocking','status','evidence_path'});
end

function value = issue_table(runId,terminalState,identifier,message,accepted)
if terminalState=="CONVERGED"
    value = table(strings(0,1),strings(0,1),strings(0,1), ...
        strings(0,1),strings(0,1),strings(0,1), ...
        'VariableNames',{'run_id','issue_id','status','identifier', ...
        'message','evidence_path'});
    return
end
if strlength(identifier)==0
    identifier = "stageB2C:warmStart:MaxIterations";
    message = "Warm-start experiment reached the iteration limit after "+ ...
        accepted+" accepted updates.";
end
value = table(string(runId),"WARM-OUTCOME-001","FAIL_RETRYABLE", ...
    string(identifier),string(message),"diagnostics/iteration_history.csv", ...
    'VariableNames',{'run_id','issue_id','status','identifier', ...
    'message','evidence_path'});
end

function value = decision_table(runId,terminalState,accepted)
if terminalState=="CONVERGED"
    conclusion = "前一日物理原变量warm start在本受控检查点实验中收敛。";
    nextAction = "如需采用，另行决定是否从第0次状态做正式验证。";
else
    conclusion = "前一日物理原变量warm start未消除本次数值阻断。";
    nextAction = "保持正式求解器不变，返回中心参数或模型/分解决策。";
end
value = table(string(runId),"B-2C-WARM-START-EXPERIMENT", ...
    terminalState,string(conclusion),string(nextAction),accepted,false,false, ...
    'VariableNames',{'run_id','milestone','terminal_state','conclusion', ...
    'next_action','accepted_iterations','formal_solver_modified', ...
    'production_fallback_added'});
end

function value = run_code_analyzer(root)
relativeFiles = [ ...
    "src/+rkkt/+diagnostics/run_stage_b2c_day16_to_day17_warm_start_experiment.m"
    "src/+rkkt/+reporting/generate_stage_b2c_day16_to_day17_warm_start_report.m"];
findingCount = zeros(numel(relativeFiles),1);
status = strings(numel(relativeFiles),1);
for position = 1:numel(relativeFiles)
    findings = checkcode(fullfile(root,relativeFiles(position)),"-id");
    findingCount(position) = numel(findings);
    status(position) = conditional_status(isempty(findings));
end
value = table(relativeFiles,findingCount,status, ...
    'VariableNames',{'file','finding_count','status'});
end

