function result = run_stage_b2c_day16_to_day17_warm_start_experiment(options)
%RUN_STAGE_B2C_DAY16_TO_DAY17_WARM_START_EXPERIMENT Run one isolated restart.
%
% The experiment starts from an accepted B-2C checkpoint, copies only the
% day-16 hourly primal variables into the matching day-17 variables, uses
% the deterministic day-17 value for the one unmatched active variable,
% and rebuilds only day-17 y/l/z. The formal workflow and configuration are
% not modified.

arguments
    options.ProjectRoot (1,1) string = ""
    options.SourceRunId (1,1) string = ...
        "20260811_050742_stage_B_2C_4168a6e9"
    options.SourceRevision (1,1) double = 30
    options.MaximumIterations (1,1) double = 100
    options.RunId (1,1) string = ""
end

root = options.ProjectRoot;
if strlength(strip(root))==0
    root = rkkt.projectRoot();
end
root = string(java.io.File(char(root)).getCanonicalPath());
assert(options.SourceRevision>=0 && ...
    options.SourceRevision==fix(options.SourceRevision), ...
    "stageB2C:warmStart:SourceRevision", ...
    "SourceRevision must be a nonnegative integer.");
assert(options.MaximumIterations>=1 && ...
    options.MaximumIterations==fix(options.MaximumIterations), ...
    "stageB2C:warmStart:MaximumIterations", ...
    "MaximumIterations must be a positive integer.");

sourceRoot = fullfile(root,"runs",options.SourceRunId);
sourceManifestPath = fullfile(sourceRoot,"run_manifest.json");
assert(isfile(sourceManifestPath),"stageB2C:warmStart:SourceRun", ...
    "The source run manifest is missing: %s",sourceManifestPath);
sourceManifest = jsondecode(fileread(sourceManifestPath));
sourceContext = struct( ...
    "checkpoints_dir",fullfile(sourceRoot,"checkpoints"), ...
    "checkpoint_manifest_path", ...
        fullfile(sourceRoot,"checkpoints","checkpoint_manifest.csv"));
[sourceCheckpoint,sourceRecord] = rkkt.artifacts.load_stage_b2c_checkpoint( ...
    sourceContext,options.SourceRevision);

config = rkkt.model.load_stage_b2c_configuration(root);
assert(options.MaximumIterations<=config.max_iterations, ...
    "stageB2C:warmStart:MaximumIterations", ...
    "MaximumIterations cannot exceed the formal limit %d.", ...
    config.max_iterations);
[inputHashes,inputPass] = rkkt.data.verify_input_hashes(root);
assert(inputPass,"stageB2C:warmStart:InputHash", ...
    "The controlled input hashes did not pass.");

runId = options.RunId;
if strlength(strip(runId))==0
    stamp = string(datetime("now","TimeZone","UTC", ...
        "Format","yyyyMMdd_HHmmss"));
    runId = stamp+"_stage_B_WARM_"+ ...
        extractBefore(string(sourceManifest.git_commit),9);
end
metadata = struct( ...
    "run_purpose","stage_B_2C_day16_primal_to_day17_warm_start_experiment", ...
    "milestone","B-2C-WARM-START-EXPERIMENT", ...
    "source_run_id",char(options.SourceRunId), ...
    "source_checkpoint_revision",options.SourceRevision, ...
    "source_day",16,"target_day",17, ...
    "warm_start_scope","hourly_primal_only", ...
    "target_dual_slack_rule","day17_reinitialized", ...
    "formal_solver_modified",false,"formal_entry_modified",false, ...
    "model_modified",false,"production_fallback_added",false, ...
    "full_ipm_executed",false,"experimental_ipm_executed",true, ...
    "formal_convergence_claimed",false,"stage_c1_entered",false, ...
    "milestone_status","RUNNING");
context = rkkt.artifacts.create_run_context(root,"stage_B", ...
    "RunId",runId,"ModelContractVersion","v1.0", ...
    "InputHashes",input_hash_object(inputHashes), ...
    "EffectiveConfigPath",fullfile(root,"config","stage_B_2C.yaml"), ...
    "ManifestMetadata",metadata);

result = struct("run_id",string(context.run_id), ...
    "run_path",string(context.root),"status","RUNNING", ...
    "terminal_state","NOT_STARTED","accepted_iterations",0, ...
    "report_path","","failure_identifier","", ...
    "failure_message","");
runTimer = tic;
try
    environment = rkkt.diagnostics.inspect_stage_b2b_environment();
    environment = addvars(environment,repmat(string(context.run_id), ...
        height(environment),1),'Before',1,'NewVariableNames','run_id');
    write_new_table(context.environment_csv_path,environment);
    assert(all(environment.status(logical(environment.blocking))=="PASS"), ...
        "stageB2C:warmStart:Environment", ...
        "A blocking MATLAB environment check failed.");
    write_new_table(context.input_hashes_csv_path, ...
        input_hash_table(inputHashes,context.run_id));

    analyzer = run_code_analyzer(root);
    write_new_table(fullfile(context.tests_dir,"code_analyzer.csv"),analyzer);
    rkkt.artifacts.write_json_file(context.test_summary_path,struct( ...
        "test_total",0,"test_passed",0,"test_failed",0, ...
        "status","NOT_RUN_DIAGNOSTIC_EXPERIMENT", ...
        "reason","The numerical experiment is the targeted validation."));
    assert(all(analyzer.status=="PASS"), ...
        "stageB2C:warmStart:CodeAnalyzer", ...
        "The two experiment files must have zero Code Analyzer findings.");

    data = rkkt.data.load_project_data(root);
    index = rkkt.indexing.build_stage_b2c_index( ...
        data,config,"RunId",string(context.run_id));
    persist_index_artifacts(context,index);

    sourceRecord = addvars(sourceRecord,string(options.SourceRunId), ...
        'Before',1,'NewVariableNames','source_run_id');
    write_new_table(fullfile(context.root,"diagnostics", ...
        "source_checkpoint.csv"),sourceRecord);

    freshState = rkkt.model.initialize_stage_b2c_state(data,index,config);
    [warmState,mappingAudit,resetAudit] = build_warm_state( ...
        sourceCheckpoint.state,freshState,data,index,config);
    write_new_table(fullfile(context.root,"diagnostics", ...
        "day16_to_day17_primal_mapping.csv"),mappingAudit);
    write_new_table(fullfile(context.root,"diagnostics", ...
        "day17_dual_slack_reset.csv"),resetAudit);

    sourceLin = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
        sourceCheckpoint.state,data,index,config,"B-2C-WARM-SOURCE");
    warmLin = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
        warmState,data,index,config,"B-2C-WARM-INITIAL");
    sourceMetrics = rkkt.diagnostics.compute_stage_b2c_unitized_metrics(sourceLin);
    warmMetrics = rkkt.diagnostics.compute_stage_b2c_unitized_metrics(warmLin);
    initialComparison = metrics_table(context.run_id, ...
        sourceMetrics,warmMetrics);
    write_new_table(fullfile(context.root,"diagnostics", ...
        "warm_start_initial_metrics.csv"),initialComparison);

    reduced = rkkt.solver.eliminate_stage_b2c_all_inequality_directions(warmLin);
    partition = rkkt.solver.partition_stage_b2c_daily_joint_system(warmLin,reduced);
    dayPosition = find([partition.day.day_id]==17);
    assert(isscalar(dayPosition),"stageB2C:warmStart:Day17Partition", ...
        "The warm-start partition must contain exactly one day-17 block.");
    warmDay17 = partition.day(dayPosition);
    matrixPath = fullfile(context.matrices_dir, ...
        "warm_start_initial_day17_joint_block.mat");
    rkkt.artifacts.save_mat_artifact(matrixPath, ...
        "matrix",warmDay17.matrix,"rhs",warmDay17.rhs, ...
        "capacity_coupling",warmDay17.capacity_coupling);
    matrixManifest = table(string(context.run_id), ...
        "warm_start_initial_day17_joint_block",17, ...
        warmDay17.dimension,nnz(warmDay17.matrix), ...
        sprank(warmDay17.matrix),issparse(warmDay17.matrix), ...
        "matrices/warm_start_initial_day17_joint_block.mat", ...
        rkkt.data.compute_sha256_file(matrixPath), ...
        'VariableNames',{'run_id','matrix_name','day','dimension','nnz', ...
        'structural_rank','is_sparse','relative_path','sha256'});
    write_new_table(context.matrix_manifest_path,matrixManifest);
    clear reduced partition warmDay17

    checkpointBase = jsondecode(fileread(context.run_manifest_path));
    checkpointMetadata = struct( ...
        "iteration",0,"git_commit",checkpointBase.git_commit, ...
        "config_sha256",char(rkkt.data.compute_sha256_file( ...
            context.effective_config_path)), ...
        "input_hash_fingerprint",char(rkkt.data.compute_sha256_file( ...
            context.input_hashes_csv_path)), ...
        "experiment","day16_primal_to_day17_warm_start");
    rkkt.artifacts.write_stage_b2c_checkpoint( ...
        context,warmState,warmLin,checkpointMetadata);

    iterationHistory = empty_iteration_history();
    factorHistory = empty_factor_history();
    directionHistory = empty_direction_history();
    persist_histories(context.root,iterationHistory, ...
        factorHistory,directionHistory);
    terminalState = "MAX_ITERATIONS";
    failureIdentifier = "";
    failureMessage = "";
    state = warmState;
    previousIdentity = "";
    finalMetrics = warmMetrics;
    lastStep = struct();

    for iteration = 1:options.MaximumIterations
        try
            step = rkkt.diagnostics.execute_stage_b2c_iteration( ...
                state,data,index,config, ...
                PreviousLinearizationIdentity=previousIdentity);
            dayResponsePosition = find([step.recursive.responses.day_id]==17);
            assert(isscalar(dayResponsePosition), ...
                "stageB2C:warmStart:Day17Response", ...
                "The recursive result must contain one day-17 response.");
            dayFactor = step.recursive.responses(dayResponsePosition).factor;
            converged = rkkt.diagnostics.stage_b2c_convergence_passed( ...
                step.metrics_after,config);
            iterationHistory = [iterationHistory; ...
                make_iteration_row(context.run_id,iteration,step, ...
                    dayFactor,converged)]; %#ok<AGROW>
            factorHistory = [factorHistory; ...
                make_factor_row(context.run_id,iteration,dayFactor)]; %#ok<AGROW>
            directionHistory = [directionHistory; ...
                make_direction_row(context.run_id,iteration,step)]; %#ok<AGROW>
            persist_histories(context.root,iterationHistory, ...
                factorHistory,directionHistory);

            state = step.state_after;
            finalMetrics = step.metrics_after;
            previousIdentity = step.linearization_before.identity;
            lastStep = step;
            checkpointMetadata.iteration = iteration;
            rkkt.artifacts.write_stage_b2c_checkpoint( ...
                context,state,step.linearization_after,checkpointMetadata);
            rkkt.artifacts.update_running_run_manifest(context,struct( ...
                "experimental_solver_terminal_state","RUNNING", ...
                "accepted_iteration_count",iteration, ...
                "last_primal_inequality_inf", ...
                    finalMetrics.primal_inequality_inf, ...
                "last_mean_lz_scaled",finalMetrics.mean_lz_scaled, ...
                "last_day17_minimum_absolute_pivot", ...
                    dayFactor.minimum_absolute_pivot_eigenvalue, ...
                "last_day17_numerical_zero_pivot_count", ...
                    dayFactor.inertia_zero));
            if converged
                terminalState = "CONVERGED";
                break
            end
        catch cause
            terminalState = "NUMERICAL_FAILURE";
            failureIdentifier = string(cause.identifier);
            failureMessage = string(cause.message);
            break
        end
    end

    accepted = height(iterationHistory);
    if accepted==options.MaximumIterations && terminalState~="CONVERGED"
        terminalState = "MAX_ITERATIONS";
    end
    if terminalState=="CONVERGED"
        runStatus = "PASS";
    else
        runStatus = "FAIL_RETRYABLE";
    end

    resultPath = fullfile(context.root,"results", ...
        "day16_to_day17_warm_start_experiment.mat");
    rkkt.artifacts.save_mat_artifact(resultPath, ...
        "warm_initial_state",warmState,"final_state",state, ...
        "initial_metrics",warmMetrics,"final_metrics",finalMetrics, ...
        "terminal_state",terminalState,"failure_identifier",failureIdentifier, ...
        "failure_message",failureMessage);

    acceptance = acceptance_table(context.run_id,mappingAudit,resetAudit, ...
        iterationHistory,directionHistory,terminalState,config,inputPass);
    write_new_table(context.acceptance_results_path,acceptance);
    issues = issue_table(context.run_id,terminalState, ...
        failureIdentifier,failureMessage,accepted);
    write_new_table(context.issue_log_path,issues);
    decision = decision_table(context.run_id,terminalState,accepted);
    write_new_table(context.decision_log_path,decision);

    rkkt.artifacts.update_running_run_manifest(context,struct( ...
        "experimental_solver_terminal_state",char(terminalState), ...
        "accepted_iteration_count",accepted, ...
        "state_update_count",accepted, ...
        "convergence_evaluated",true, ...
        "experimental_convergence_achieved",terminalState=="CONVERGED", ...
        "formal_convergence_claimed",false, ...
        "final_primal_equality_inf",finalMetrics.primal_equality_inf, ...
        "final_primal_inequality_inf",finalMetrics.primal_inequality_inf, ...
        "final_dual_scaled_inf",finalMetrics.dual_scaled_inf, ...
        "final_mean_lz_scaled",finalMetrics.mean_lz_scaled, ...
        "final_maximum_water_violation", ...
            finalMetrics.maximum_water_violation, ...
        "mapping_target_count",height(mappingAudit), ...
        "mapping_matched_count",nnz(mappingAudit.source_matched), ...
        "mapping_unmatched_count",nnz(~mappingAudit.source_matched), ...
        "failure_identifier",char(failureIdentifier), ...
        "failure_message",char(failureMessage), ...
        "milestone_status",char(runStatus), ...
        "elapsed_seconds_before_report",toc(runTimer)));

    report = rkkt.reporting.generate_stage_b2c_day16_to_day17_warm_start_report( ...
        context.root);
    [reportValid,reportDetails] = rkkt.reporting.validate_docx_package(report.path);
    reportStructure = table(string(context.run_id),string(report.path), ...
        reportValid,conditional_status(reportValid), ...
        strjoin(string(reportDetails.errors),"; "), ...
        string(report.design_preset),string(report.header_pattern), ...
        'VariableNames',{'run_id','path','valid','status','details', ...
        'design_preset','header_pattern'});
    write_new_table(fullfile(context.reports_dir, ...
        "report_structure_validation.csv"),reportStructure);
    assert(reportValid,"stageB2C:warmStart:Report", ...
        "The Chinese warm-start report failed DOCX package validation.");
    visual = rkkt.reporting.render_stage_b2c_report_external( ...
        context.root,report.path);
    write_new_table(fullfile(context.reports_dir,"report_visual_qa.csv"),visual);
    reportHash = rkkt.data.compute_sha256_file(report.path);
    write_new_table(fullfile(context.reports_dir,"report_sha256.csv"), ...
        table(string(context.run_id), ...
        "reports/阶段B-2C_第16日原变量映射至第17日WarmStart实验报告.docx", ...
        string(reportHash),"PASS", ...
        'VariableNames',{'run_id','relative_path','sha256','status'}));

    manifest = rkkt.artifacts.finalize_run_manifest(context,runStatus,struct( ...
        "milestone_status",char(runStatus), ...
        "experimental_solver_terminal_state",char(terminalState), ...
        "experimental_convergence_achieved",terminalState=="CONVERGED", ...
        "formal_convergence_claimed",false, ...
        "formal_solver_modified",false,"formal_entry_modified",false, ...
        "model_modified",false,"production_fallback_added",false, ...
        "accepted_iteration_count",accepted, ...
        "reports_generated",true,"report_structure_validated",true, ...
        "report_visual_qa_status",char(string(visual.status)), ...
        "report_relative_path", ...
            "reports/阶段B-2C_第16日原变量映射至第17日WarmStart实验报告.docx", ...
        "report_sha256",char(reportHash), ...
        "failure_identifier",char(failureIdentifier), ...
        "failure_message",char(failureMessage), ...
        "elapsed_seconds",toc(runTimer)));
    rkkt.artifacts.update_run_index(context,manifest);

    result.status = string(manifest.status);
    result.terminal_state = terminalState;
    result.accepted_iterations = accepted;
    result.report_path = string(report.path);
    result.failure_identifier = failureIdentifier;
    result.failure_message = failureMessage;
    result.initial_metrics = warmMetrics;
    result.final_metrics = finalMetrics;
    result.iteration_history = iterationHistory;
    result.mapping_audit = mappingAudit;
    result.last_step = lastStep;
catch cause
    failureIdentifier = string(cause.identifier);
    failureMessage = string(cause.message);
    try
        if ~isfile(context.issue_log_path)
            write_new_table(context.issue_log_path,table( ...
                string(context.run_id),"WARM-SETUP-001","FAIL_RETRYABLE", ...
                failureIdentifier,failureMessage, ...
                'VariableNames',{'run_id','issue_id','status', ...
                'identifier','message'}));
        end
        manifest = jsondecode(fileread(context.run_manifest_path));
        if string(manifest.status)=="RUNNING"
            manifest = rkkt.artifacts.finalize_run_manifest( ...
                context,"FAIL_RETRYABLE",struct( ...
                "milestone_status","FAIL_RETRYABLE", ...
                "experimental_solver_terminal_state","SETUP_FAILURE", ...
                "formal_convergence_claimed",false, ...
                "formal_solver_modified",false, ...
                "formal_entry_modified",false,"model_modified",false, ...
                "production_fallback_added",false, ...
                "failure_identifier",char(failureIdentifier), ...
                "failure_message",char(failureMessage), ...
                "elapsed_seconds",toc(runTimer)));
            rkkt.artifacts.update_run_index(context,manifest);
        end
    catch
    end
    result.status = "FAIL_RETRYABLE";
    result.terminal_state = "SETUP_FAILURE";
    result.failure_identifier = failureIdentifier;
    result.failure_message = failureMessage;
end
end

function [state,mapping,reset] = build_warm_state( ...
        source,fresh,data,index,config)
variables = index.variable_index;
sourceRows = variables(variables.day==16 & variables.hour>0,:);
targetRows = variables(variables.day==17 & variables.hour>0,:);
state = source;
targetCount = height(targetRows);
sourceIndex = nan(targetCount,1);
sourceMatched = false(targetCount,1);
sourceValue = nan(targetCount,1);
previousTargetValue = zeros(targetCount,1);
warmTargetValue = zeros(targetCount,1);
deterministicInitialValue = zeros(targetCount,1);
for row = 1:targetCount
    target = targetRows(row,:);
    match = sourceRows.hour==target.hour & ...
        sourceRows.asset_id==target.asset_id & ...
        string(sourceRows.asset_type)==string(target.asset_type) & ...
        string(sourceRows.variable_name)==string(target.variable_name);
    targetIndex = target.global_index_start;
    previousTargetValue(row) = source.xi(targetIndex);
    deterministicInitialValue(row) = fresh.xi(targetIndex);
    if nnz(match)==1
        sourceIndex(row) = sourceRows.global_index_start(match);
        sourceValue(row) = source.xi(sourceIndex(row));
        state.xi(targetIndex) = sourceValue(row);
        sourceMatched(row) = true;
    else
        assert(nnz(match)==0,"stageB2C:warmStart:AmbiguousMap", ...
            "The day-16 to day-17 primal mapping is ambiguous.");
        state.xi(targetIndex) = fresh.xi(targetIndex);
    end
    warmTargetValue(row) = state.xi(targetIndex);
end
assert(targetCount==516 && nnz(sourceMatched)==515 && ...
    nnz(~sourceMatched)==1, ...
    "stageB2C:warmStart:MappingInventory", ...
    "Expected 515 matched and one unmatched day-17 hourly variable.");

constraints = index.constraint_index;
equalities = constraints(string(constraints.constraint_type)=="equality",:);
inequalities = constraints(string(constraints.constraint_type)=="inequality",:);
day17Equality = find(equalities.day==17);
day17Inequality = find(inequalities.day==17);
state.y(day17Equality) = fresh.y(day17Equality);
state.z(day17Inequality) = fresh.z(day17Inequality);

temporary = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
    state,data,index,config,"B-2C-WARM-SLACK-REBUILD");
day17ConstraintValue = temporary.constraints.ineq(day17Inequality);
state.l(day17Inequality) = max(1,-day17ConstraintValue);
state.mu = NaN;
state.iteration_index = 0;
state.state_revision = 0;
state.newton_direction_number = 0;
state.completed_newton_direction_count = 0;
state.initialization_version = ...
    "stage-B2C-day16-primal-to-day17-warm-start-experiment-v1.0";
state.water_slack_rule = "day17_max_1_minus_g_current";
state.water_multiplier_rule = "day17_deterministic_positive_reset";
state.nonzero_hessian_gate_state = false;
state.optimization_state = true;

mapping = table(repmat(16,targetCount,1),targetRows.day,targetRows.hour, ...
    string(targetRows.asset_type),targetRows.asset_id, ...
    string(targetRows.variable_name),targetRows.global_index_start, ...
    sourceIndex,sourceMatched,sourceValue,previousTargetValue, ...
    deterministicInitialValue,warmTargetValue, ...
    'VariableNames',{'source_day','target_day','hour','asset_type', ...
    'asset_id','variable_name','target_global_index','source_global_index', ...
    'source_matched','source_value','previous_target_value', ...
    'deterministic_initial_value','warm_target_value'});
reset = table(17,numel(day17Equality),numel(day17Inequality), ...
    min(state.l(day17Inequality)),max(state.l(day17Inequality)), ...
    min(state.z(day17Inequality)),max(state.z(day17Inequality)), ...
    all(isfinite([state.y(day17Equality);state.l(day17Inequality); ...
        state.z(day17Inequality)])),all(state.l(day17Inequality)>0), ...
    all(state.z(day17Inequality)>0), ...
    'VariableNames',{'day','equality_reset_count', ...
    'inequality_reset_count','minimum_l','maximum_l','minimum_z', ...
    'maximum_z','all_finite','l_strictly_positive','z_strictly_positive'});
end

function value = metrics_table(runId,source,warm)
point = ["source_checkpoint";"warm_start_initial"];
value = table(repmat(string(runId),2,1),point, ...
    [source.primal_equality_inf;warm.primal_equality_inf], ...
    [source.primal_inequality_inf;warm.primal_inequality_inf], ...
    [source.dual_scaled_inf;warm.dual_scaled_inf], ...
    [source.mean_lz_scaled;warm.mean_lz_scaled], ...
    [source.physical_inequality_violation; ...
        warm.physical_inequality_violation], ...
    [source.maximum_water_violation;warm.maximum_water_violation], ...
    [source.min_l;warm.min_l],[source.min_z;warm.min_z], ...
    'VariableNames',{'run_id','point','primal_equality_inf', ...
    'primal_inequality_inf','dual_scaled_inf','mean_lz_scaled', ...
    'physical_inequality_violation','maximum_water_violation', ...
    'minimum_l','minimum_z'});
end

function row = make_iteration_row(runId,iteration,step,factor,converged)
metrics = step.metrics_after;
row = table(string(runId),iteration,step.state_after.state_revision, ...
    metrics.primal_equality_inf,metrics.primal_inequality_inf, ...
    metrics.dual_scaled_inf,metrics.mean_lz_scaled, ...
    metrics.maximum_water_violation,step.primal_step.alpha, ...
    step.dual_step.alpha,factor.minimum_absolute_pivot_eigenvalue, ...
    factor.pivot_tolerance,factor.inertia_zero, ...
    factor.maximum_column_relative_residual, ...
    step.direction_audit.direction_relative_error, ...
    step.direction_audit.recursive_kkt_relative_residual, ...
    converged, ...
    'VariableNames',{'run_id','experiment_iteration','state_revision', ...
    'primal_equality_inf','primal_inequality_inf','dual_scaled_inf', ...
    'mean_lz_scaled','maximum_water_violation','alpha_primal', ...
    'alpha_dual','day17_minimum_absolute_pivot','day17_pivot_tolerance', ...
    'day17_numerical_zero_pivot_count', ...
    'day17_maximum_rhs_relative_residual', ...
    'direction_relative_error','recursive_kkt_relative_residual', ...
    'convergence_accepted'});
end

function row = make_factor_row(runId,iteration,factor)
row = table(string(runId),iteration,17,factor.dimension, ...
    factor.rhs_count,factor.factorization_count, ...
    factor.minimum_absolute_pivot_eigenvalue,factor.pivot_tolerance, ...
    factor.inertia_zero,factor.maximum_column_relative_residual, ...
    factor.local_residual_target_met,string(factor.warning_identifier), ...
    factor.warning_present,factor.warning_continued,factor.solution_finite, ...
    'VariableNames',{'run_id','experiment_iteration','day_id','dimension', ...
    'rhs_count','factorization_count','minimum_absolute_pivot', ...
    'pivot_tolerance','numerical_zero_pivot_count', ...
    'maximum_rhs_relative_residual','local_residual_target_met', ...
    'warning_identifier','warning_present','warning_continued', ...
    'solution_finite'});
end

function row = make_direction_row(runId,iteration,step)
audit = step.direction_audit;
