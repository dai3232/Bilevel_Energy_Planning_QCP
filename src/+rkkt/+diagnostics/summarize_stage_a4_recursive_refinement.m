function summary = summarize_stage_a4_recursive_refinement(recursive)
%SUMMARIZE_STAGE_A4_RECURSIVE_REFINEMENT Compact retained-factor evidence.
%
% One row is emitted for each of the seven day chains and one for the
% 16-dimensional global core.  The function is read-only and does not
% trigger a solve, factorization, or state update.

arguments
    recursive (1,1) struct
end

dayCount = numel(recursive.daily_thomas);
rowCount = dayCount+1;
objectType = [repmat("day_chain",dayCount,1);"global_core"];
dayId = nan(rowCount,1);
maximumPasses = zeros(rowCount,1);
selectedPass = zeros(rowCount,1);
passesAttempted = zeros(rowCount,1);
initialRelativeResidual = zeros(rowCount,1);
finalRelativeResidual = zeros(rowCount,1);
residualReductionRatio = zeros(rowCount,1);
stopReason = strings(rowCount,1);
rhsCount = zeros(rowCount,1);
factorizationCount = zeros(rowCount,1);
fullDirectionConsumed = false(rowCount,1);
operatorExact = false(rowCount,1);
factorContextUnchanged = false(rowCount,1);

for d = 1:dayCount
    diagnostic = recursive.daily_thomas(d).diagnostics. ...
        residual_refinement;
    dayId(d) = recursive.daily_responses(d).day_id;
    [maximumPasses(d),selectedPass(d),passesAttempted(d), ...
        initialRelativeResidual(d),finalRelativeResidual(d), ...
        residualReductionRatio(d),stopReason(d),rhsCount(d), ...
        factorizationCount(d),fullDirectionConsumed(d), ...
        operatorExact(d),factorContextUnchanged(d)] = ...
        unpack(diagnostic);
end

diagnostic = recursive.core.diagnostics.residual_refinement;
[maximumPasses(end),selectedPass(end),passesAttempted(end), ...
    initialRelativeResidual(end),finalRelativeResidual(end), ...
    residualReductionRatio(end),stopReason(end),rhsCount(end), ...
    factorizationCount(end),fullDirectionConsumed(end), ...
    operatorExact(end),factorContextUnchanged(end)] = ...
    unpack(diagnostic);

summary = table(objectType,dayId,maximumPasses,selectedPass, ...
    passesAttempted,initialRelativeResidual,finalRelativeResidual, ...
    residualReductionRatio,stopReason,rhsCount,factorizationCount, ...
    fullDirectionConsumed,operatorExact,factorContextUnchanged, ...
    'VariableNames',{'object_type','day_id','maximum_passes', ...
    'selected_pass','passes_attempted', ...
    'initial_maximum_column_relative', ...
    'final_maximum_column_relative','residual_reduction_ratio', ...
    'stop_reason','rhs_count','additional_factorization_count', ...
    'full_kkt_direction_consumed','residual_operator_exact_original', ...
    'factor_context_unchanged'});
assert(height(summary)==8 && ...
    isequal(summary.day_id(1:7),reshape(14:20,[],1)) && ...
    all(summary.maximum_passes>=0 & summary.maximum_passes<=3) && ...
    all(summary.selected_pass>=0 & ...
        summary.selected_pass<=summary.maximum_passes) && ...
    all(summary.passes_attempted>=summary.selected_pass & ...
        summary.passes_attempted<=summary.maximum_passes) && ...
    all(summary.additional_factorization_count==0) && ...
    ~any(summary.full_kkt_direction_consumed), ...
    "stageA4:r1:RefinementSummary", ...
    "The stable-v2 refinement summary violated its fixed evidence contract.");
end

function [maximumPasses,selectedPass,passesAttempted,initialResidual, ...
        finalResidual,reductionRatio,stopReason,rhsCount, ...
        factorizationCount,fullDirectionConsumed,operatorExact, ...
        factorContextUnchanged] = unpack(diagnostic)
maximumPasses = diagnostic.maximum_passes;
selectedPass = diagnostic.selected_pass;
passesAttempted = diagnostic.passes_attempted;
initialResidual = diagnostic.initial_maximum_column_relative;
finalResidual = diagnostic.final_maximum_column_relative;
reductionRatio = diagnostic.residual_reduction_ratio;
stopReason = string(diagnostic.stop_reason);
rhsCount = diagnostic.rhs_count;
factorizationCount = diagnostic.additional_factorization_count;
fullDirectionConsumed = diagnostic.full_kkt_direction_consumed;
operatorExact = diagnostic.residual_operator_exact_original;
factorContextUnchanged = diagnostic.factor_context_unchanged;
end
