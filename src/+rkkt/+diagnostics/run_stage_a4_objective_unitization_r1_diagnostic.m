function identifier = limiter_id(item,which)
if which=="primal"
    if isfield(item,"primal_limiter")
        identifier = string(item.primal_limiter);
    else
        identifier = string(item.primal_step.limiting_constraint_id);
    end
else
    if isfield(item,"dual_limiter")
        identifier = string(item.dual_limiter);
    else
        identifier = string(item.dual_step.limiting_constraint_id);
    end
end
end

function metric = metric_at_revision(chain,revision)
if revision==0
    metric = chain.iterations(1).metrics_before;
else
    metric = chain.iterations(revision).metrics_after;
end
end

function series = interval_metric_series(chain,startRevision,endRevision)
count = endRevision-startRevision+1;
gap = zeros(count,1);
dual = zeros(count,1);
equality = zeros(count,1);
for offset = 0:count-1
    metric = metric_at_revision(chain,startRevision+offset);
    gap(offset+1) = metric.mean_gap_scaled;
    dual(offset+1) = metric.dual_scaled_inf;
    equality(offset+1) = metric.equality_inf;
end
series = struct("gap",gap,"dual",dual,"equality",equality);
end

function [monotone,rebound] = trend_flags(values)
differences = diff(values);
monotone = all(differences<=0);
rebound = any(differences>0);
end

function value = safe_ratio(numerator,denominator)
if denominator==0
    if numerator==0
        value = 1;
    else
        value = Inf;
    end
else
    value = numerator/denominator;
end
end

function factor = geometric_factor(startValue,endValue,transitionCount)
if startValue>0 && endValue>=0 && transitionCount>0
    factor = (endValue/startValue)^(1/transitionCount);
else
    factor = Inf;
end
end

function value = project_metric(current,factor,remaining)
if remaining<=0
    value = current;
elseif isfinite(factor) && factor>=0
    value = current*factor^remaining;
else
    value = Inf;
end
end

function exact = canonical_state_equal(left,right)
names = ["xi","y","l","z","iteration_index","state_revision", ...
    "newton_direction_number","completed_newton_direction_count"];
exact = true;
for name = names
    exact = exact && isfield(left,name) && isfield(right,name) && ...
        isequaln(left.(name),right.(name));
end
end
