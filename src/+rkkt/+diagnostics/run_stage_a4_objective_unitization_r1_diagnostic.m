end

function tableValue = make_refinement_table(unscaled,five,twenty)
chains = {unscaled,five,twenty};
chainIds = ["unscaled_stable_5","scaled_stable_5","scaled_stable_20"];
tableValue = table();
for chainPosition = 1:numel(chains)
    chain = chains{chainPosition};
    for iteration = 1:chain.iteration_count
        item = chain.iterations(iteration);
        detail = item.recursive_refinement;
        prefix = table( ...
            repmat(chainIds(chainPosition),height(detail),1), ...
            repmat(iteration,height(detail),1), ...
            'VariableNames',{'chain_id','iteration'});
        rows = [prefix,detail];
        if isempty(tableValue)
            tableValue = rows;
        else
            tableValue = [tableValue;rows]; %#ok<AGROW>
        end
    end
end
assert(height(tableValue)==240 && ...
    all(tableValue.maximum_passes==3) && ...
    all(tableValue.selected_pass<=3) && ...
    all(tableValue.passes_attempted<=3) && ...
    all(tableValue.additional_factorization_count==0) && ...
    ~any(tableValue.full_kkt_direction_consumed), ...
    "stageA4:r1:RefinementTable", ...
    "The R1 refinement table must contain 30 times 8 bounded records.");
end

function analysis = analyze_convergence(chain,config)
assert(chain.iteration_count==20 && chain.all_pass, ...
    "stageA4:r1:ConvergenceInput", ...
    "Convergence analysis requires the completed scaled twenty-round chain.");
intervalStart = [0;5;18;19;0];
intervalEnd = [5;18;19;20;20];
intervalName = ["initial_to_5";"5_to_18";"18_to_19"; ...
    "19_to_20";"initial_to_20"];
rowCount = numel(intervalStart);
gapScaledStart = zeros(rowCount,1);
gapScaledEnd = zeros(rowCount,1);
gapScaledEndToStart = zeros(rowCount,1);
gapScaledReductionFraction = zeros(rowCount,1);
gapOriginalStart = zeros(rowCount,1);
gapOriginalEnd = zeros(rowCount,1);
etaGapStart = zeros(rowCount,1);
etaGapEnd = zeros(rowCount,1);
rDualScaledStart = zeros(rowCount,1);
rDualScaledEnd = zeros(rowCount,1);
rDualScaledEndToStart = zeros(rowCount,1);
rDualScaledReductionFraction = zeros(rowCount,1);
rDualOriginalStart = zeros(rowCount,1);
rDualOriginalEnd = zeros(rowCount,1);
etaDualStart = zeros(rowCount,1);
etaDualEnd = zeros(rowCount,1);
rEqStart = zeros(rowCount,1);
rEqEnd = zeros(rowCount,1);
rEqEndToStart = zeros(rowCount,1);
rEqReductionFraction = zeros(rowCount,1);
etaEqStart = zeros(rowCount,1);
etaEqEnd = zeros(rowCount,1);
alphaPrimalFirst = zeros(rowCount,1);
alphaPrimalLast = zeros(rowCount,1);
alphaDualFirst = zeros(rowCount,1);
alphaDualLast = zeros(rowCount,1);
gapMonotone = false(rowCount,1);
dualMonotone = false(rowCount,1);
equalityMonotone = false(rowCount,1);
gapRebound = false(rowCount,1);
dualRebound = false(rowCount,1);
equalityRebound = false(rowCount,1);
gapStagnation = false(rowCount,1);
dualStagnation = false(rowCount,1);
equalityStagnation = false(rowCount,1);
projectedGapAt100 = zeros(rowCount,1);
projectedDualAt100 = zeros(rowCount,1);
projectedEqualityAt100 = zeros(rowCount,1);
gapPossibleBy100 = false(rowCount,1);
dualPossibleBy100 = false(rowCount,1);
equalityPossibleBy100 = false(rowCount,1);
allPossibleBy100 = false(rowCount,1);
initialEqualityScale = max(1, ...
    chain.iterations(1).metrics_before.equality_inf);

for row = 1:rowCount
    startMetric = metric_at_revision(chain,intervalStart(row));
    endMetric = metric_at_revision(chain,intervalEnd(row));
    gapScaledStart(row) = startMetric.mean_gap_scaled;
    gapScaledEnd(row) = endMetric.mean_gap_scaled;
    gapScaledEndToStart(row) = safe_ratio( ...
        gapScaledEnd(row),gapScaledStart(row));
    gapScaledReductionFraction(row) = 1-gapScaledEndToStart(row);
    gapOriginalStart(row) = startMetric.mapped_mean_gap;
    gapOriginalEnd(row) = endMetric.mapped_mean_gap;
    etaGapStart(row) = startMetric.eta_gap_mapped;
    etaGapEnd(row) = endMetric.eta_gap_mapped;
    rDualScaledStart(row) = startMetric.dual_scaled_inf;
    rDualScaledEnd(row) = endMetric.dual_scaled_inf;
    rDualScaledEndToStart(row) = safe_ratio( ...
        rDualScaledEnd(row),rDualScaledStart(row));
    rDualScaledReductionFraction(row) = 1-rDualScaledEndToStart(row);
    rDualOriginalStart(row) = startMetric.mapped_r_dual_inf;
    rDualOriginalEnd(row) = endMetric.mapped_r_dual_inf;
    etaDualStart(row) = startMetric.eta_dual_mapped;
    etaDualEnd(row) = endMetric.eta_dual_mapped;
    rEqStart(row) = startMetric.equality_inf;
    rEqEnd(row) = endMetric.equality_inf;
    rEqEndToStart(row) = safe_ratio(rEqEnd(row),rEqStart(row));
    rEqReductionFraction(row) = 1-rEqEndToStart(row);
    etaEqStart(row) = rEqStart(row)/initialEqualityScale;
    etaEqEnd(row) = rEqEnd(row)/initialEqualityScale;
    firstTransition = intervalStart(row)+1;
    lastTransition = intervalEnd(row);
    alphaPrimalFirst(row) = ...
        chain.iterations(firstTransition).applied_alpha_primal;
    alphaPrimalLast(row) = ...
        chain.iterations(lastTransition).applied_alpha_primal;
    alphaDualFirst(row) = ...
        chain.iterations(firstTransition).applied_alpha_dual;
    alphaDualLast(row) = ...
        chain.iterations(lastTransition).applied_alpha_dual;
    metrics = interval_metric_series( ...
        chain,intervalStart(row),intervalEnd(row));
    [gapMonotone(row),gapRebound(row)] = ...
        trend_flags(metrics.gap);
    [dualMonotone(row),dualRebound(row)] = ...
        trend_flags(metrics.dual);
    [equalityMonotone(row),equalityRebound(row)] = ...
        trend_flags(metrics.equality);
    transitions = intervalEnd(row)-intervalStart(row);
    gapFactor = geometric_factor( ...
        gapScaledStart(row),gapScaledEnd(row),transitions);
    dualFactor = geometric_factor( ...
        rDualScaledStart(row),rDualScaledEnd(row),transitions);
    equalityFactor = geometric_factor( ...
        rEqStart(row),rEqEnd(row),transitions);
    gapStagnation(row) = gapFactor>=0.99;
    dualStagnation(row) = dualFactor>=0.99;
    equalityStagnation(row) = equalityFactor>=0.99;
    remaining = 100-intervalEnd(row);
    projectedGapAt100(row) = project_metric( ...
        gapScaledEnd(row),gapFactor,remaining);
    projectedDualAt100(row) = project_metric( ...
        rDualScaledEnd(row),dualFactor,remaining);
    projectedEqualityAt100(row) = project_metric( ...
        rEqEnd(row),equalityFactor,remaining);
    gapPossibleBy100(row) = ...
        projectedGapAt100(row)<= ...
            config.convergence.normalized_complementarity_gap;
    dualPossibleBy100(row) = ...
        projectedDualAt100(row)<=config.convergence.dual_inf;
    equalityPossibleBy100(row) = ...
        projectedEqualityAt100(row)<= ...
            config.convergence.primal_equality_inf;
    allPossibleBy100(row) = gapPossibleBy100(row) && ...
        dualPossibleBy100(row) && equalityPossibleBy100(row);
end

intervals = table(intervalName,intervalStart,intervalEnd, ...
    gapScaledStart,gapScaledEnd,gapScaledEndToStart, ...
    gapScaledReductionFraction,gapOriginalStart,gapOriginalEnd, ...
    etaGapStart,etaGapEnd,rDualScaledStart,rDualScaledEnd, ...
    rDualScaledEndToStart,rDualScaledReductionFraction, ...
    rDualOriginalStart,rDualOriginalEnd,etaDualStart,etaDualEnd, ...
    rEqStart,rEqEnd,rEqEndToStart,rEqReductionFraction, ...
    etaEqStart,etaEqEnd,alphaPrimalFirst,alphaPrimalLast, ...
    alphaDualFirst,alphaDualLast,gapMonotone,dualMonotone, ...
    equalityMonotone,gapRebound,dualRebound,equalityRebound, ...
    gapStagnation,dualStagnation,equalityStagnation, ...
    projectedGapAt100,projectedDualAt100,projectedEqualityAt100, ...
    gapPossibleBy100,dualPossibleBy100,equalityPossibleBy100, ...
    allPossibleBy100, ...
    'VariableNames',{'interval_name','start_iteration','end_iteration', ...
    'gap_scaled_start','gap_scaled_end','gap_scaled_end_to_start_ratio', ...
    'gap_scaled_reduction_fraction','gap_original_mapped_start', ...
    'gap_original_mapped_end','eta_gap_start','eta_gap_end', ...
    'r_dual_scaled_start','r_dual_scaled_end', ...
    'r_dual_scaled_end_to_start_ratio', ...
    'r_dual_scaled_reduction_fraction','r_dual_original_mapped_start', ...
    'r_dual_original_mapped_end','eta_dual_start','eta_dual_end', ...
    'r_eq_start','r_eq_end','r_eq_end_to_start_ratio', ...
    'r_eq_reduction_fraction','eta_eq_start','eta_eq_end', ...
    'alpha_primal_first_transition','alpha_primal_last_transition', ...
    'alpha_dual_first_transition','alpha_dual_last_transition', ...
    'gap_monotone_nonincreasing','r_dual_monotone_nonincreasing', ...
    'r_eq_monotone_nonincreasing','gap_rebound_detected', ...
    'r_dual_rebound_detected','r_eq_rebound_detected', ...
    'gap_stagnation_geometric_factor_ge_0_99', ...
    'r_dual_stagnation_geometric_factor_ge_0_99', ...
    'r_eq_stagnation_geometric_factor_ge_0_99', ...
    'projected_gap_scaled_at_iteration_100', ...
    'projected_r_dual_scaled_at_iteration_100', ...
    'projected_r_eq_at_iteration_100', ...
    'gap_possible_by_100_at_observed_log_rate', ...
    'r_dual_possible_by_100_at_observed_log_rate', ...
    'r_eq_possible_by_100_at_observed_log_rate', ...
    'all_three_possible_by_100_at_observed_log_rate'});

final = chain.final_metrics;
thresholds = struct( ...
    "r_eq",config.convergence.primal_equality_inf, ...
    "r_ineq",config.convergence.primal_inequality_inf, ...
    "r_dual_scaled",config.convergence.dual_inf, ...
    "gap_scaled",config.convergence.normalized_complementarity_gap);
achieved = final.equality_inf<=thresholds.r_eq && ...
    final.slack_equality_inf<=thresholds.r_ineq && ...
    final.dual_scaled_inf<=thresholds.r_dual_scaled && ...
    final.mean_gap_scaled<=thresholds.gap_scaled;
analysis = struct( ...
    "intervals",intervals, ...
    "final_metrics",final, ...
    "thresholds",thresholds, ...
    "convergence_achieved",achieved, ...
    "mean_lz_is_dimensionless",false, ...
    "dimensionless_metrics", ...
        ["eta_eq","eta_dual_mapped","eta_gap_mapped"], ...
    "stagnation_definition", ...
        "Diagnostic only: interval geometric end/start factor >= 0.99.", ...
    "projection_definition", ...
        "Diagnostic log-linear extrapolation of each interval's observed "+ ...
        "geometric rate to iteration 100; it is not a convergence claim.", ...
    "formal_convergence_claimed",false);
end

function [before,after] = native_metrics(item,mode)
if mode=="unscaled"
    before = convert_unscaled_metrics( ...
        item.residuals_before,item.objective_value_before);
    after = convert_unscaled_metrics( ...
        item.residuals_after,item.objective_value_after);
else
    before = convert_scaled_metrics(item.metrics_before);
    after = convert_scaled_metrics(item.metrics_after);
end
end

