function result = run_stage_a4_objective_unitization_r1_diagnostic( ...
        data,index,config,projectRoot)
%RUN_STAGE_A4_OBJECTIVE_UNITIZATION_R1_DIAGNOSTIC Execute stable-v2 5/20.
%
% Three chains start independently from the same deterministic A4 state:
% one unscaled five-round chain, one objective-unitized five-round chain,
% and one objective-unitized twenty-round chain.  Every round explicitly
% enables at most three retained-factor refinement passes.  This function
% has no filesystem side effects and creates no formal A4 run.

arguments
    data (1,1) struct
    index (1,1) struct
    config (1,1) struct
    projectRoot (1,1) string
end

assert(string(config.stage_id)=="stage_A4" && ...
    string(config.status)=="READY" && ...
    config.fraction_to_boundary==0.9995 && ...
    config.initialization.centering_sigma==0.1, ...
    "stageA4:r1:FrozenConfiguration", ...
    "A4-2D-2A-R1 requires stage_A4 / READY, sigma=0.1 and tau=0.9995.");
assert(isfolder(projectRoot) && ...
    isfile(fullfile(projectRoot,"CURRENT_STAGE.md")), ...
    "stageA4:r1:ProjectRoot", ...
    "A4-2D-2A-R1 requires the repository project root.");

maximumPasses = 3;
sequence = strings(0,1);
totalTimer = tic;

baselineFive = rkkt.diagnostics.run_stage_a4_five_iteration_diagnostic( ...
    data,index,config, ...
    "RetainCanonicalVectors",true, ...
    "RecursiveRefinementMaxPasses",maximumPasses);
baselineFive.milestone = "A4-2D-2A-R1_unscaled_stable_five";
sequence(end+1,1) = "unscaled_stable5_completed";

scaledFive = rkkt.diagnostics.run_stage_a4_scaled_objective_chain( ...
    data,index,config, ...
    "IterationCount",5, ...
    "RecursiveRefinementMaxPasses",maximumPasses, ...
    "DiagnosticChainId","A4-2D-2A-R1-SCALED-STABLE-V2");
scaledFive.r1_chain_id = "A4-2D-2A-R1-SCALED-5";
sequence(end+1,1) = "scaled_stable5_completed";

fiveRoundGate = rkkt.diagnostics.evaluate_stage_a4_scaled_five_round_gate(scaledFive);
assert(fiveRoundGate.passed && ...
    fiveRoundGate.permission_to_start_twenty_round_chain, ...
    "stageA4:r1:FiveRoundGate", ...
    "The stable-v2 scaled five-round gate did not authorize twenty rounds.");
sequence(end+1,1) = "scaled_stable5_gate_passed";

scaledTwenty = rkkt.diagnostics.run_stage_a4_scaled_objective_chain( ...
    data,index,config, ...
    "IterationCount",20, ...
    "RecursiveRefinementMaxPasses",maximumPasses, ...
    "DiagnosticChainId","A4-2D-2A-R1-SCALED-STABLE-V2");
scaledTwenty.r1_chain_id = "A4-2D-2A-R1-SCALED-20";
sequence(end+1,1) = "scaled_stable20_completed";

prefixAudit = compare_scaled_prefix(scaledFive,scaledTwenty);
initializationAudit = compare_initial_states( ...
    baselineFive,scaledFive,scaledTwenty);
structureAudit = compare_frozen_structure( ...
    scaledFive,scaledTwenty,index,config);

roundTable = make_round_table( ...
    baselineFive,scaledFive,scaledTwenty);
gapTables = struct( ...
    "unscaled_five",make_gap_table(baselineFive,"unscaled"), ...
    "scaled_five",make_gap_table(scaledFive,"scaled"), ...
    "scaled_twenty",make_gap_table(scaledTwenty,"scaled"));
residualTrajectory = make_residual_trajectory( ...
    baselineFive,scaledFive,scaledTwenty);
refinementTable = make_refinement_table( ...
    baselineFive,scaledFive,scaledTwenty);
convergence = analyze_convergence(scaledTwenty,config);
[forbiddenCodeAudit,dependencyClosure] = ...
    rkkt.diagnostics.scan_stage_a4_r1_forbidden_code(projectRoot);
[forbiddenExecutionAudit,execution] = ...
    rkkt.diagnostics.audit_stage_a4_r1_forbidden_execution( ...
        baselineFive,scaledFive,scaledTwenty,sequence,roundTable, ...
        refinementTable,config,forbiddenCodeAudit,dependencyClosure);
blocking = rkkt.diagnostics.make_stage_a4_r1_blocking_audit( ...
    baselineFive,scaledFive,scaledTwenty,prefixAudit, ...
    initializationAudit,structureAudit,roundTable,refinementTable, ...
    forbiddenExecutionAudit);
allBlockingPass = all(blocking.status=="PASS");
assert(allBlockingPass, ...
    "stageA4:r1:BlockingAudit", ...
    "A4-2D-2A-R1 failed one or more execution-correctness checks.");

result = struct();
result.stage_id = "stage_A4";
result.stage_status = "READY";
result.milestone = ...
    "A4-2D-2A-R1_stable_v2_objective_unitization_5_20";
result.milestone_status = "PASS";
result.pass_semantics = ...
    "All three stable-v2 controlled chains completed with frozen "+ ...
    "direction audits; this does not assert formal A4 convergence.";
result.stable_route = ...
    "retained_factor_bounded_residual_refinement_stable_v2";
result.recursive_refinement_max_passes = maximumPasses;
result.unscaled_five = baselineFive;
result.scaled_five = scaledFive;
result.scaled_twenty = scaledTwenty;
result.five_round_gate = fiveRoundGate;
result.scaled_prefix_audit = prefixAudit;
result.initialization_audit = initializationAudit;
result.structure_audit = structureAudit;
result.round_table = roundTable;
result.gap_tables = gapTables;
result.residual_trajectory = residualTrajectory;
result.refinement_table = refinementTable;
result.convergence_analysis = convergence;
result.r1_forbidden_code_audit = forbiddenCodeAudit;
result.r1_dependency_closure = dependencyClosure;
result.forbidden_execution_audit = forbiddenExecutionAudit;
result.forbidden_execution_pass = ...
    all(forbiddenExecutionAudit.status=="PASS");
result.blocking_audit = blocking;
result.all_blocking_pass = allBlockingPass;
result.all_pass = allBlockingPass;
result.execution_sequence = sequence;
result.convergence_achieved = convergence.convergence_achieved;
result.convergence_claimed = false;
result.stage_a4_pass_claimed = false;
result.formal_algorithm_replaced = false;
result.formal_acceptance_metric_changed = false;
result.execution = execution;
result.timing = struct( ...
    "unscaled_five_seconds",baselineFive.timing.total_seconds, ...
    "scaled_five_seconds",scaledFive.timing_total_seconds, ...
    "scaled_twenty_seconds",scaledTwenty.timing_total_seconds, ...
    "thirty_newton_seconds", ...
        baselineFive.timing.total_seconds+ ...
        scaledFive.timing_total_seconds+ ...
        scaledTwenty.timing_total_seconds, ...
    "total_seconds",toc(totalTimer));
end

function audit = compare_scaled_prefix(five,twenty)
assert(five.iteration_count==5 && twenty.iteration_count==20, ...
    "stageA4:r1:PrefixCount", ...
    "The scaled prefix audit requires complete five- and twenty-round chains.");
fieldNames = [ ...
    "state_before","state_after","recursive_direction", ...
    "chain_id","linearization_identity_before", ...
    "linearization_identity_after","recursive_linearization_identity", ...
    "full_kkt_linearization_identity", ...
    "direction_audit_linearization_identity", ...
    "candidate_alpha_primal","candidate_alpha_dual", ...
    "applied_alpha_primal","applied_alpha_dual", ...
    "primal_limiter","dual_limiter","metrics_before","metrics_after", ...
    "objective_scale_factor","delta_qp5","direction_relative_error", ...
    "component_relative_errors","recursive_kkt_relative_residual", ...
    "full_kkt_relative_residual","no_full_direction_fallback", ...
    "full_direction_consumed","state_update_consumed_recursive_only", ...
    "global_capacity_before","global_capacity_after", ...
    "state_fingerprint_before","state_fingerprint_after", ...
    "direction_fingerprint","recursive_refinement_max_passes", ...
    "recursive_refinement"];
perIteration = false(5,1);
perField = true(5,numel(fieldNames));
for iteration = 1:5
    left = five.iterations(iteration);
    right = twenty.iterations(iteration);
    for fieldIndex = 1:numel(fieldNames)
        name = fieldNames(fieldIndex);
        perField(iteration,fieldIndex) = ...
            isequaln(left.(name),right.(name));
    end
    perIteration(iteration) = all(perField(iteration,:));
end
audit = struct( ...
    "compared_field_names",fieldNames, ...
    "per_field_exact",perField, ...
    "per_iteration_exact",perIteration, ...
    "excluded_chain_specific_fields", ...
        ["r1_chain_id","timing","timing_total_seconds"], ...
    "exclusion_reason", ...
        "Only elapsed time and result-level requested count are excluded; "+ ...
        "both R1 scaled chains use one explicit identity, and every "+ ...
        "retained per-round field is compared at zero tolerance.", ...
    "fresh_initial_state_exact", ...
        canonical_state_equal(five.initial_state,twenty.initial_state), ...
    "all_pass",all(perIteration) && ...
        canonical_state_equal(five.initial_state,twenty.initial_state));
end

function audit = compare_initial_states(unscaled,scaledFive,scaledTwenty)
exact15 = canonical_state_equal( ...
    unscaled.initial_state,scaledFive.initial_state);
exact120 = canonical_state_equal( ...
    unscaled.initial_state,scaledTwenty.initial_state);
exact520 = canonical_state_equal( ...
    scaledFive.initial_state,scaledTwenty.initial_state);
fingerprints = [unscaled.initial_state_fingerprint; ...
    scaledFive.initial_state_fingerprint; ...
    scaledTwenty.initial_state_fingerprint];
audit = struct( ...
    "unscaled_vs_scaled_five_exact",exact15, ...
    "unscaled_vs_scaled_twenty_exact",exact120, ...
    "scaled_five_vs_twenty_exact",exact520, ...
    "initial_fingerprints",fingerprints, ...
    "fingerprints_exact",all(fingerprints==fingerprints(1)), ...
    "all_pass",exact15 && exact120 && exact520 && ...
        all(fingerprints==fingerprints(1)));
end

function audit = compare_frozen_structure(five,twenty,index,config)
baseFive = five.initial_unscaled_linearization;
scaledFive = five.initial_scaled_linearization;
baseTwenty = twenty.initial_unscaled_linearization;
scaledTwenty = twenty.initial_scaled_linearization;
matricesExact = isequal(baseFive.H,baseTwenty.H) && ...
    isequal(baseFive.A,baseTwenty.A) && ...
    isequal(baseFive.G,baseTwenty.G) && ...
    isequal(scaledFive.H,baseFive.H) && ...
    isequal(scaledFive.A,baseFive.A) && ...
    isequal(scaledFive.G,baseFive.G) && ...
    isequal(scaledTwenty.H,baseFive.H) && ...
    isequal(scaledTwenty.A,baseFive.A) && ...
    isequal(scaledTwenty.G,baseFive.G);
offsetsExact = isequal(baseFive.eq_offset,baseTwenty.eq_offset) && ...
    isequal(baseFive.ineq_offset,baseTwenty.ineq_offset) && ...
    isequal(scaledFive.eq_offset,baseFive.eq_offset) && ...
    isequal(scaledFive.ineq_offset,baseFive.ineq_offset) && ...
    isequal(scaledTwenty.eq_offset,baseFive.eq_offset) && ...
    isequal(scaledTwenty.ineq_offset,baseFive.ineq_offset);
mapsExact = isequal(baseFive.maps,baseTwenty.maps) && ...
    isequal(scaledFive.maps,baseFive.maps) && ...
    isequal(scaledTwenty.maps,baseFive.maps);
audit = struct( ...
    "H_A_G_exact",matricesExact, ...
    "offsets_exact",offsetsExact, ...
    "maps_exact",mapsExact, ...
    "index_stage_id",string(index.scope.stage_id), ...
    "index_variable_count",height(index.variable_index), ...
    "index_constraint_count",height(index.constraint_index), ...
    "nxi",size(baseFive.H,1), ...
    "neq",size(baseFive.A,1), ...
    "nineq",size(baseFive.G,1), ...
    "complete_kkt_dimension", ...
        size(baseFive.H,1)+size(baseFive.A,1)+2*size(baseFive.G,1), ...
    "fixed_zero_count",height(index.fixed_zero_map), ...
    "day_ids",config.days(:), ...
    "objective_scale_factor_exact", ...
        five.objective_scale.factor==twenty.objective_scale.factor, ...
    "all_pass",matricesExact && offsetsExact && mapsExact && ...
        string(index.scope.stage_id)=="stage_A4" && ...
        size(baseFive.H,1)==3722 && size(baseFive.A,1)==618 && ...
        size(baseFive.G,1)==7248 && ...
        size(baseFive.H,1)+size(baseFive.A,1)+ ...
            2*size(baseFive.G,1)==18836 && ...
        height(index.fixed_zero_map)==422 && ...
        isequal(config.days(:),(14:20).') && ...
        five.objective_scale.factor==twenty.objective_scale.factor);
end

