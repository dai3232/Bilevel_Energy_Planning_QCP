function tableValue = make_gap_table(chain,mode)
n = chain.iteration_count;
iteration = (1:n).';
gapBefore = zeros(n,1);
gapAfter = zeros(n,1);
rDualBefore = zeros(n,1);
rDualAfter = zeros(n,1);
alphaPrimal = zeros(n,1);
alphaDual = zeros(n,1);
minLAfter = zeros(n,1);
minZAfter = zeros(n,1);
for k = 1:n
    item = chain.iterations(k);
    [before,after] = native_metrics(item,mode);
    gapBefore(k) = before.gap;
    gapAfter(k) = after.gap;
    rDualBefore(k) = before.r_dual;
    rDualAfter(k) = after.r_dual;
    alphaPrimal(k) = item.applied_alpha_primal;
    alphaDual(k) = item.applied_alpha_dual;
    minLAfter(k) = after.min_l;
    minZAfter(k) = after.min_z;
end
gapReduction = gapBefore-gapAfter;
gapReductionRatio = gapReduction./gapBefore;
tableValue = table(iteration,gapBefore,gapAfter,gapReduction, ...
    gapReductionRatio,rDualBefore,rDualAfter,alphaPrimal,alphaDual, ...
    minLAfter,minZAfter, ...
    'VariableNames',{'iteration','gap_before','gap_after', ...
    'gap_reduction','gap_reduction_ratio','r_dual_before', ...
    'r_dual_after','alpha_primal','alpha_dual','min_l_after', ...
    'min_z_after'});
end

