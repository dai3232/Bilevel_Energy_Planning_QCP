function result = run_stage_b2c_30day_linearization_benchmark( ...
        projectRoot,options)
%RUN_STAGE_B2C_30DAY_LINEARIZATION_BENCHMARK Compare one old/new update.

arguments
    projectRoot (1,1) string = rkkt.projectRoot()
    options.OutputDirectory (1,1) string = ""
end
projectRoot = string(java.io.File(char(projectRoot)).getCanonicalPath());
settings = rkkt.config.build_stage_b2c_run_settings(projectRoot, ...
    DayStart=1,DayEnd=30,MaxIterations=1,RequireConvergence=false, ...
    AuditMode="recursive_only",CacheEnabled=true, ...
    ConfigPath=fullfile(projectRoot,"config", ...
        "stage_B_2C_30_day_experiment.yaml"));
[data,~] = rkkt.cache.load_or_build_project_data(projectRoot);
config = rkkt.model.build_stage_b2c_runtime_configuration( ...
    projectRoot,settings,data);
[index,~] = rkkt.cache.load_or_build_stage_b2c_index( ...
    projectRoot,data,config);
state = rkkt.model.initialize_stage_b2c_state(data,index,config);
initial = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
    state,data,index,config,"B-2C-FORMAL-IPM");
template = rkkt.model.build_stage_b2c_linearization_template( ...
    initial,data,index,config);

oldStep = rkkt.diagnostics.execute_stage_b2c_iteration( ...
    state,data,index,config,FullKktAuditEnabled=false, ...
    PrecomputedLinearization=initial, ...
    LinearizationUpdateMode="full_rebuild");
newStep = rkkt.diagnostics.execute_stage_b2c_iteration( ...
    state,data,index,config,FullKktAuditEnabled=false, ...
    PrecomputedLinearization=initial,LinearizationTemplate=template, ...
    LinearizationUpdateMode="cached_numeric");

directionRelative = relative_error(newStep.recursive.direction, ...
    oldStep.recursive.direction);
stateErrors = struct( ...
    "xi",relative_error(newStep.state_after.xi,oldStep.state_after.xi), ...
    "y",relative_error(newStep.state_after.y,oldStep.state_after.y), ...
    "l",relative_error(newStep.state_after.l,oldStep.state_after.l), ...
    "z",relative_error(newStep.state_after.z,oldStep.state_after.z));
matrixErrors = struct( ...
    "H",relative_error(newStep.linearization_after.H, ...
        oldStep.linearization_after.H), ...
    "A",relative_error(newStep.linearization_after.A, ...
        oldStep.linearization_after.A), ...
    "G",relative_error(newStep.linearization_after.G, ...
        oldStep.linearization_after.G));
residualErrors = struct( ...
    "r_eq",relative_error(newStep.linearization_after.r_eq, ...
        oldStep.linearization_after.r_eq), ...
    "r_ineq",relative_error(newStep.linearization_after.r_ineq, ...
        oldStep.linearization_after.r_ineq), ...
    "r_dual",relative_error(newStep.linearization_after.r_dual, ...
        oldStep.linearization_after.r_dual), ...
    "r_comp",relative_error(newStep.linearization_after.r_comp, ...
        oldStep.linearization_after.r_comp));
metricErrors = struct();
for name = ["primal_equality_inf","primal_inequality_inf", ...
        "dual_scaled_inf","mean_lz_scaled"]
    metricErrors.(name) = scalar_relative( ...
        newStep.metrics_after.(name),oldStep.metrics_after.(name));
end
maximumError = max([directionRelative,struct_values(stateErrors), ...
    struct_values(matrixErrors),struct_values(residualErrors), ...
    struct_values(metricErrors)]);
speedup = oldStep.timing.total_seconds/newStep.timing.total_seconds;
linearizationSpeedup = oldStep.timing.linearization_after_seconds/ ...
    newStep.timing.linearization_after_seconds;
passed = maximumError<=1e-12 && ...
    newStep.recursive.diagnostics.final_kkt_residual_gate_passed && ...
    oldStep.recursive.diagnostics.final_kkt_residual_gate_passed;

summary = table( ...
    ["full_rebuild";"cached_numeric"], ...
    [oldStep.timing.total_seconds;newStep.timing.total_seconds], ...
    [oldStep.timing.step_and_state_update_seconds; ...
        newStep.timing.step_and_state_update_seconds], ...
    [oldStep.timing.linearization_after_seconds; ...
        newStep.timing.linearization_after_seconds], ...
    [oldStep.timing.recursive_seconds;newStep.timing.recursive_seconds], ...
    'VariableNames',{'route','total_seconds','state_update_seconds', ...
        'linearization_after_seconds','recursive_seconds'});
equivalence = table(directionRelative,stateErrors.xi,stateErrors.y, ...
    stateErrors.l,stateErrors.z,matrixErrors.H,matrixErrors.A, ...
    matrixErrors.G,residualErrors.r_eq,residualErrors.r_ineq, ...
    residualErrors.r_dual,residualErrors.r_comp, ...
    metricErrors.primal_equality_inf, ...
    metricErrors.primal_inequality_inf,metricErrors.dual_scaled_inf, ...
    metricErrors.mean_lz_scaled,maximumError,passed, ...
    'VariableNames',{'direction_relative_error','state_xi_relative_error', ...
        'state_y_relative_error','state_l_relative_error', ...
        'state_z_relative_error','H_relative_error','A_relative_error', ...
        'G_relative_error','r_eq_relative_error','r_ineq_relative_error', ...
        'r_dual_relative_error','r_comp_relative_error', ...
        'primal_equality_metric_relative_error', ...
        'primal_inequality_metric_relative_error', ...
        'dual_metric_relative_error','gap_metric_relative_error', ...
        'maximum_relative_error','passed'});
result = struct("passed",passed,"summary",summary, ...
    "equivalence",equivalence,"overall_speedup",speedup, ...
    "linearization_speedup",linearizationSpeedup, ...
    "old_step",oldStep,"new_step",newStep);
if strlength(options.OutputDirectory)>0
    output = string(java.io.File(char(options.OutputDirectory)).getCanonicalPath());
    if ~isfolder(output), mkdir(output); end
    rkkt.artifacts.write_table_csv_17g_atomic( ...
        fullfile(output,"timing_comparison.csv"),summary);
    rkkt.artifacts.write_table_csv_17g_atomic( ...
        fullfile(output,"equivalence.csv"),equivalence);
    rkkt.artifacts.write_json_file(fullfile(output,"summary.json"), ...
        struct("passed",passed,"overall_speedup",speedup, ...
        "linearization_speedup",linearizationSpeedup, ...
        "maximum_relative_error",maximumError));
end
assert(passed,"stageB2C:benchmark:Equivalence", ...
    "The 30-day cached update differs from the full rebuild route.");
end

function value = relative_error(actual,expected)
value = norm(actual-expected,inf)/ ...
    max([1,norm(actual,inf),norm(expected,inf)]);
end

function value = scalar_relative(actual,expected)
value = abs(actual-expected)/max([1,abs(actual),abs(expected)]);
end

function value = struct_values(source)
value = struct2array(source);
end
