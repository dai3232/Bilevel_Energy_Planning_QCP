function result = run_stage_a1_direction_verification(data,index,config)
%RUN_STAGE_A1_DIRECTION_VERIFICATION Execute exactly one A1 Newton direction.
% No primal-dual state update, line search, IPM loop, parallel pool, or
% economic interpretation is performed by this function.

arguments
    data (1,1) struct
    index (1,1) struct
    config (1,1) struct
end
totalTimer = tic;

timer = tic;
state = rkkt.model.initialize_stage_a1_state(data,index,config);
linearization = rkkt.model.build_stage_a1_linearization(state,data,index,config);
timing.linearization_seconds = toc(timer);

timer = tic;
direct = rkkt.solver.solve_full_kkt_direction(linearization);
timing.full_kkt_direct_seconds = toc(timer);

timer = tic;
recursive = rkkt.solver.solve_recursive_direction(linearization, ...
    AssemblyTolerance=config.tolerances.symmetry_relative, ...
    SymmetryTolerance=config.tolerances.symmetry_relative);
timing.recursive_seconds = toc(timer);

timer = tic;
audit = rkkt.solver.verify_direction_equivalence(direct,recursive,linearization, ...
    DirectionRelative=config.tolerances.direction_relative_2norm, ...
    RecursiveResidual=config.tolerances.recursive_full_kkt_relative_residual, ...
    FullResidualPreferred=config.tolerances.direct_preferred, ...
    FullResidualMaximum=config.tolerances.direct_maximum);
physical = rkkt.model.recover_stage_a_physical_arrays(linearization.state.xi, ...
    recursive.components.xi,index,data);
timing.verification_seconds = toc(timer);
timing.total_seconds = toc(totalTimer);

assert(linearization.counts.full_kkt == ...
    config.expected_full_kkt_dimension, ...
    "stageA1:verification:FullKktDimension", ...
    "The complete KKT dimension changed from its frozen value.");
assert(isequal([recursive.partition.hour.dimension], ...
    config.expected_hourly_kkt_block_dimensions), ...
    "stageA1:verification:HourBlockDimension", ...
    "The three hourly KKT block dimensions changed.");
assert(isequal(size(recursive.core.matrix), ...
    [config.expected_global_core_dimension, ...
    config.expected_global_core_dimension]), ...
    "stageA1:verification:CoreDimension", ...
    "The global core is not 16-by-16.");
assert(recursive.no_full_direction_fallback, ...
    "stageA1:verification:RecursiveFallback", ...
    "Recursive output does not prove the no-fallback contract.");
assert(physical.fixed_zero_audit.values_exact_zero && ...
    physical.fixed_zero_audit.directions_exact_zero, ...
    "stageA1:verification:FixedZero", ...
    "A removed fixed-zero value or direction was not restored as exact zero.");

result = struct();
result.state = state;
result.linearization = linearization;
result.direct = direct;
result.recursive = recursive;
result.audit = audit;
result.physical = physical;
result.timing = timing;
result.execution = struct( ...
    "newton_direction_count",1, ...
    "full_ipm_executed",false, ...
    "parallel_executed",false, ...
    "optimization_executed",false, ...
    "a1_solver_executed",true, ...
    "physical_dispatch_interpretation",false);
end
