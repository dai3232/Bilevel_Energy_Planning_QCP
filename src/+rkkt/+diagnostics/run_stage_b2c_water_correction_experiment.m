function value = acceptance_table(runId,iterations,directions,corrections, ...
        terminalState,physical,config,inputPass,sourceRevision)
sourcePass = ~isempty(iterations) && ...
    iterations.source_equivalent_revision(1)==sourceRevision+1;
scopePass = ~isempty(iterations) && ...
    all(iterations.only_water_slacks_corrected);
correctionPass = ~isempty(corrections) && ...
    all(corrections.strictly_positive) && ...
    all(abs(corrections.closure_error)<=corrections.closure_tolerance);
directionPass = ~isempty(directions) && all(directions.all_pass) && ...
    all(directions.no_full_direction_fallback) && ...
    all(directions.full_direction_not_consumed);
convergencePass = terminalState=="CONVERGED" && ...
    iterations.primal_equality_inf(end)<= ...
        config.primal_equality_inf_tolerance && ...
    iterations.primal_inequality_inf(end)<= ...
        config.primal_inequality_inf_tolerance && ...
    iterations.dual_scaled_inf(end)<=config.dual_scaled_inf_tolerance && ...
    iterations.mean_lz_scaled(end)<=config.mean_lz_scaled_tolerance;
physicalPass = terminalState=="CONVERGED" && physical.passed;
maxClosure = NaN; minL = NaN; maxDirection = NaN;
if ~isempty(corrections)
    maxClosure = max(abs(corrections.closure_error));
    minL = min(corrections.l_corrected);
end
if ~isempty(directions)
    maxDirection = max(directions.direction_relative_error);
end
check = ["WATER2-INPUT-001";"WATER2-SOURCE-001"; ...
    "WATER2-SCOPE-001";"WATER2-CORRECTION-001"; ...
    "WATER2-DIRECTION-001";"WATER2-CONVERGENCE-001"; ...
    "WATER2-PHYSICAL-001"];
requirement = ["controlled input hashes"; ...
    "source checkpoint continues at the next source-equivalent revision"; ...
    "only 56 water slacks change after the formal update"; ...
    "exact closure and strict positive corrected water slacks"; ...
    "all directions pass independent full-KKT audit"; ...
    "all four frozen stopping metrics pass"; ...
    "final Stage-A and water physical audit passes"];
actual = [string(inputPass); ...
    "first_source_equivalent="+first_or_nan(iterations, ...
        "source_equivalent_revision"); ...
    "all_scope_assertions="+scopePass; ...
    "max_closure="+compose("%.17g",maxClosure)+ ...
        ", min_l="+compose("%.17g",minL); ...
    "max_direction="+compose("%.17g",maxDirection); ...
    terminalState+", final_ineq="+last_or_nan(iterations, ...
        "primal_inequality_inf"); ...
    "passed="+physical.passed+", max_water="+ ...
        compose("%.17g",physical.maximum_water_violation)];
threshold = ["true";string(sourceRevision+1);"true"; ...
    "abs(closure)<=row tolerance and l>0"; ...
    "<= "+compose("%.17g",config.direction_relative_error_tolerance); ...
    "four metrics <= 1e-6";"physical thresholds"];
passed = [inputPass;sourcePass;scopePass;correctionPass;directionPass; ...
    convergencePass;physicalPass];
status = repmat("PASS",numel(check),1); status(~passed) = "FAIL";
value = table(repmat(string(runId),numel(check),1),check,requirement, ...
    actual,threshold,true(numel(check),1),status,[ ...
    "input_hashes.csv";"diagnostics/source_checkpoint.csv"; ...
    "diagnostics/iteration_history.csv"; ...
    "diagnostics/water_correction_row_history.csv"; ...
    "diagnostics/direction_audit_history.csv"; ...
    "diagnostics/iteration_history.csv"; ...
    "diagnostics/final_water_physical_audit.csv"], ...
    'VariableNames',{'run_id','check_id','requirement','actual_value', ...
    'threshold','blocking','status','evidence_path'});
end

