function result = run_stage_b2c_water_correction_experiment(options)
%RUN_STAGE_B2C_WATER_CORRECTION_EXPERIMENT Continue one isolated B-2C run.
%
% The experiment resumes an accepted authoritative checkpoint and uses the
% unchanged formal direction and step calculation.  After every accepted
% update it applies the exact second-order correction only to the 56 daily
% water slacks.  No formal workflow entry or configuration is modified.

arguments
    options.ProjectRoot (1,1) string = ""
    options.SourceRunId (1,1) string = ...
        "20260811_050742_stage_B_2C_4168a6e9"
    options.SourceRevision (1,1) double = 27
    options.MaximumIterations (1,1) double = 20
    options.RunId (1,1) string = ""
end

root = options.ProjectRoot;
if strlength(strip(root))==0
    root = rkkt.projectRoot();
end
root = string(java.io.File(char(root)).getCanonicalPath());
assert(options.SourceRevision>=0 && ...
    options.SourceRevision==fix(options.SourceRevision), ...
    "stageB2C:waterCorrection:SourceRevision", ...
    "SourceRevision must be a nonnegative integer.");
assert(options.MaximumIterations>=1 && ...
    options.MaximumIterations==fix(options.MaximumIterations), ...
    "stageB2C:waterCorrection:MaximumIterations", ...
    "MaximumIterations must be a positive integer.");

sourceRoot = fullfile(root,"runs",options.SourceRunId);
sourceManifestPath = fullfile(sourceRoot,"run_manifest.json");
assert(isfile(sourceManifestPath),"stageB2C:waterCorrection:SourceRun", ...
    "The source run manifest is missing: %s",sourceManifestPath);
sourceManifest = jsondecode(fileread(sourceManifestPath));
sourceContext = struct( ...
    "checkpoints_dir",fullfile(sourceRoot,"checkpoints"), ...
    "checkpoint_manifest_path", ...
        fullfile(sourceRoot,"checkpoints","checkpoint_manifest.csv"));
[sourceCheckpoint,sourceRecord] = rkkt.artifacts.load_stage_b2c_checkpoint( ...
    sourceContext,options.SourceRevision);

config = rkkt.model.load_stage_b2c_configuration(root);
assert(options.SourceRevision+options.MaximumIterations<= ...
    config.max_iterations, ...
    "stageB2C:waterCorrection:MaximumIterations", ...
    "SourceRevision plus MaximumIterations cannot exceed %d.", ...
    config.max_iterations);
[inputHashes,inputPass] = rkkt.data.verify_input_hashes(root);
assert(inputPass,"stageB2C:waterCorrection:InputHash", ...
    "The controlled input hashes did not pass.");

runId = options.RunId;
if strlength(strip(runId))==0
    stamp = string(datetime("now","TimeZone","UTC", ...
        "Format","yyyyMMdd_HHmmss"));
    runId = stamp+"_stage_B_WATER2_"+ ...
        extractBefore(string(sourceManifest.git_commit),9);
end
metadata = struct( ...
    "run_purpose","stage_B_2C_exact_water_slack_second_order_experiment", ...
    "milestone","B-2C-WATER-SECOND-ORDER-EXPERIMENT", ...
    "source_run_id",char(options.SourceRunId), ...
    "source_checkpoint_revision",options.SourceRevision, ...
    "correction_scope","56_daily_water_inequality_slacks_only", ...
    "correction_formula", ...
        "l_corrected=l_trial-(g_after-g_before-alpha*G*dx)", ...
    "formal_solver_modified",false,"formal_entry_modified",false, ...
    "model_modified",false,"objective_modified",false, ...
    "step_length_modified",false,"production_fallback_added",false, ...
    "experimental_ipm_executed",true,"formal_convergence_claimed",false, ...
    "stage_c1_entered",false,"milestone_status","RUNNING");
context = rkkt.artifacts.create_run_context(root,"stage_B", ...
    "RunId",runId,"ModelContractVersion","v1.0", ...
    "InputHashes",input_hash_object(inputHashes), ...
    "EffectiveConfigPath",fullfile(root,"config","stage_B_2C.yaml"), ...
    "ManifestMetadata",metadata);

result = struct("run_id",string(context.run_id), ...
    "run_path",string(context.root),"status","RUNNING", ...
    "terminal_state","NOT_STARTED","accepted_iterations",0, ...
    "report_path","","failure_identifier","","failure_message","");
runTimer = tic;
try
    environment = experiment_environment(context.run_id);
    write_new_table(context.environment_csv_path,environment);
    assert(all(environment.status(logical(environment.blocking))=="PASS"), ...
        "stageB2C:waterCorrection:Environment", ...
        "A blocking MATLAB environment check failed.");
    write_new_table(context.input_hashes_csv_path, ...
        input_hash_table(inputHashes,context.run_id));

    analyzer = run_code_analyzer(root);
    write_new_table(fullfile(context.tests_dir,"code_analyzer.csv"),analyzer);
    rkkt.artifacts.write_json_file(context.test_summary_path,struct( ...
        "test_total",0,"test_passed",0,"test_failed",0, ...
        "status","NOT_RUN_INSIDE_NUMERICAL_EXPERIMENT", ...
        "reason","The caller runs the targeted unit test separately."));
    assert(all(analyzer.status=="PASS"), ...
        "stageB2C:waterCorrection:CodeAnalyzer", ...
        "The water-correction experiment files must have no findings.");

    data = rkkt.data.load_project_data(root);
    index = rkkt.indexing.build_stage_b2c_index( ...
        data,config,"RunId",string(context.run_id));
    persist_index_artifacts(context,index);
    sourceRecord = addvars(sourceRecord,string(options.SourceRunId), ...
        'Before',1,'NewVariableNames','source_run_id');
    write_new_table(fullfile(context.root,"diagnostics", ...
        "source_checkpoint.csv"),sourceRecord);

    initialState = sourceCheckpoint.state;
    initialState.iteration_index = 0;
    initialState.state_revision = 0;
    initialState.newton_direction_number = 0;
    initialState.completed_newton_direction_count = 0;
    initialState.initialization_version = ...
        "stage-B2C-water-second-order-checkpoint-continuation-v1.0";
    initialLin = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
        initialState,data,index,config,"B-2C-WATER-SECOND-ORDER-INITIAL");
    initialMetrics = rkkt.diagnostics.compute_stage_b2c_unitized_metrics( ...
        initialLin);
    sourceLin = rkkt.model.build_stage_b2c_scaled_objective_linearization( ...
        sourceCheckpoint.state,data,index,config,"B-2C-WATER-SOURCE-AUDIT");
    sourceMetrics = rkkt.diagnostics.compute_stage_b2c_unitized_metrics( ...
        sourceLin);
    assert(metrics_equal(initialMetrics,sourceMetrics), ...
        "stageB2C:waterCorrection:SourceState", ...
        "Resetting only experiment revision metadata changed a metric.");
    write_new_table(fullfile(context.root,"diagnostics", ...
        "initial_metrics.csv"),metrics_table(context.run_id, ...
        sourceMetrics,initialMetrics));
    persist_initial_day17_matrix(context,initialLin);

    checkpointBase = jsondecode(fileread(context.run_manifest_path));
    checkpointMetadata = struct( ...
        "iteration",0,"git_commit",checkpointBase.git_commit, ...
        "config_sha256",char(rkkt.data.compute_sha256_file( ...
            context.effective_config_path)), ...
        "input_hash_fingerprint",char(rkkt.data.compute_sha256_file( ...
            context.input_hashes_csv_path)), ...
        "experiment","exact_water_slack_second_order_correction", ...
        "source_run_id",char(options.SourceRunId), ...
        "source_checkpoint_revision",options.SourceRevision, ...
        "source_equivalent_revision",options.SourceRevision);
    rkkt.artifacts.write_stage_b2c_checkpoint( ...
        context,initialState,initialLin,checkpointMetadata);

    iterationHistory = empty_iteration_history();
    factorHistory = empty_factor_history();
    directionHistory = empty_direction_history();
    correctionHistory = empty_correction_history();
    persist_histories(context.root,iterationHistory,factorHistory, ...
        directionHistory,correctionHistory);

    terminalState = "MAX_ITERATIONS";
    failureIdentifier = "";
    failureMessage = "";
    state = initialState;
    finalLin = initialLin;
    finalMetrics = initialMetrics;
    previousIdentity = "";
    lastStep = struct();

    for iteration = 1:options.MaximumIterations
        try
            step = ...
                rkkt.diagnostics.execute_stage_b2c_water_corrected_iteration( ...
                state,data,index,config, ...
                PreviousLinearizationIdentity=previousIdentity);
            day17Position = find([step.recursive.responses.day_id]==17);
            assert(isscalar(day17Position), ...
                "stageB2C:waterCorrection:Day17Response", ...
                "The recursive result must contain one day-17 response.");
            day17Factor = step.recursive.responses(day17Position).factor;
            converged = rkkt.diagnostics.stage_b2c_convergence_passed( ...
                step.metrics_after,config);
            sourceEquivalent = options.SourceRevision+iteration;
            iterationHistory = [iterationHistory;make_iteration_row( ...
                context.run_id,iteration,sourceEquivalent,step, ...
                day17Factor,converged)]; %#ok<AGROW>
            factorHistory = [factorHistory;make_factor_rows( ...
                context.run_id,iteration,sourceEquivalent, ...
                step.recursive.responses)]; %#ok<AGROW>
            directionHistory = [directionHistory;make_direction_row( ...
                context.run_id,iteration,sourceEquivalent,step)]; %#ok<AGROW>
            correctionAudit = step.water_slack_second_order_correction.audit;
            correctionAudit = addvars(correctionAudit, ...
                repmat(string(context.run_id),height(correctionAudit),1), ...
                repmat(iteration,height(correctionAudit),1), ...
                repmat(sourceEquivalent,height(correctionAudit),1), ...
                'Before',1,'NewVariableNames', ...
                {'run_id','experiment_iteration','source_equivalent_revision'});
            correctionHistory = [correctionHistory;correctionAudit]; %#ok<AGROW>
            persist_histories(context.root,iterationHistory,factorHistory, ...
                directionHistory,correctionHistory);

            state = step.state_after;
            finalLin = step.linearization_after;
            finalMetrics = step.metrics_after;
            previousIdentity = step.linearization_before.identity;
            lastStep = step;
            checkpointMetadata.iteration = iteration;
            checkpointMetadata.source_equivalent_revision = sourceEquivalent;
            rkkt.artifacts.write_stage_b2c_checkpoint( ...
                context,state,finalLin,checkpointMetadata);
            rkkt.artifacts.update_running_run_manifest(context,struct( ...
                "experimental_solver_terminal_state","RUNNING", ...
                "accepted_iteration_count",iteration, ...
                "last_source_equivalent_revision",sourceEquivalent, ...
                "last_primal_inequality_inf", ...
                    finalMetrics.primal_inequality_inf, ...
                "last_mean_lz_scaled",finalMetrics.mean_lz_scaled, ...
                "last_day17_minimum_absolute_pivot", ...
                    day17Factor.minimum_absolute_pivot_eigenvalue, ...
                "last_day17_numerical_zero_pivot_count", ...
                    day17Factor.inertia_zero));
            if converged
                terminalState = "CONVERGED";
                break
            end
        catch cause
            terminalState = "NUMERICAL_FAILURE";
            failureIdentifier = string(cause.identifier);
            failureMessage = string(cause.message);
            break
        end
    end

    accepted = height(iterationHistory);
    if accepted==options.MaximumIterations && terminalState~="CONVERGED"
        terminalState = "MAX_ITERATIONS";
    end
    physicalAudit = struct("passed",false,"maximum_water_violation",NaN);
    if terminalState=="CONVERGED"
        auditInput = struct("convergence_achieved",true, ...
            "run_terminal_state","CONVERGED","final_state",state, ...
            "final_linearization",finalLin, ...
            "iteration_history",iterationHistory);
        physicalAudit = rkkt.diagnostics.evaluate_stage_b2c_physical_audit( ...
            auditInput,index,data,config);
        write_new_table(fullfile(context.root,"diagnostics", ...
            "final_water_physical_audit.csv"),physicalAudit.water);
        write_new_table(fullfile(context.root,"diagnostics", ...
            "final_stage_a_physical_audit.csv"),physicalAudit.stage_a);
        rkkt.artifacts.save_mat_artifact(fullfile(context.root,"results", ...
            "final_physical_arrays.mat"),"physical",physicalAudit.physical);
        if ~physicalAudit.passed
            terminalState = "PHYSICAL_AUDIT_FAILURE";
            failureIdentifier = "stageB2C:waterCorrection:PhysicalAudit";
            failureMessage = "The converged experiment failed physical audit.";
        end
    end
    if terminalState=="CONVERGED" && physicalAudit.passed
        runStatus = "PASS";
    else
        runStatus = "FAIL_RETRYABLE";
    end

    rkkt.artifacts.save_mat_artifact(fullfile(context.root,"results", ...
        "water_second_order_correction_experiment.mat"), ...
        "initial_state",initialState,"final_state",state, ...
        "initial_metrics",initialMetrics,"final_metrics",finalMetrics, ...
        "terminal_state",terminalState, ...
        "failure_identifier",failureIdentifier, ...
        "failure_message",failureMessage);
    acceptance = acceptance_table(context.run_id,iterationHistory, ...
        directionHistory,correctionHistory,terminalState,physicalAudit, ...
        config,inputPass,options.SourceRevision);
    write_new_table(context.acceptance_results_path,acceptance);
    write_new_table(context.issue_log_path,issue_table(context.run_id, ...
        terminalState,failureIdentifier,failureMessage,accepted));
    write_new_table(context.decision_log_path,decision_table( ...
        context.run_id,terminalState,accepted,options.SourceRevision));

    [day17Minimum,day17Zeros] = final_day17_values(iterationHistory);
    rkkt.artifacts.update_running_run_manifest(context,struct( ...
        "experimental_solver_terminal_state",char(terminalState), ...
        "accepted_iteration_count",accepted, ...
        "iteration_count",accepted, ...
        "state_update_count",accepted, ...
        "final_source_equivalent_revision", ...
            options.SourceRevision+accepted, ...
        "convergence_evaluated",true, ...
        "experimental_convergence_achieved",terminalState=="CONVERGED", ...
        "experimental_physical_audit_passed",physicalAudit.passed, ...
        "formal_convergence_claimed",false, ...
        "final_primal_equality_inf",finalMetrics.primal_equality_inf, ...
        "final_primal_inequality_inf",finalMetrics.primal_inequality_inf, ...
        "final_dual_scaled_inf",finalMetrics.dual_scaled_inf, ...
        "final_mean_lz_scaled",finalMetrics.mean_lz_scaled, ...
        "final_maximum_water_violation", ...
            finalMetrics.maximum_water_violation, ...
        "final_physical_water_violation", ...
            physicalAudit.maximum_water_violation, ...
        "final_day17_minimum_absolute_pivot",day17Minimum, ...
        "final_day17_numerical_zero_pivot_count",day17Zeros, ...
        "failure_identifier",char(failureIdentifier), ...
        "failure_message",char(failureMessage), ...
        "milestone_status",char(runStatus), ...
        "elapsed_seconds_before_report",toc(runTimer)));

    report = ...
        rkkt.reporting.generate_stage_b2c_water_correction_experiment_report( ...
        context.root);
    [reportValid,reportDetails] = ...
        rkkt.reporting.validate_stage_b2c_water_correction_report( ...
        context.root);
    reportStructure = table(string(context.run_id),string(report.path), ...
        reportValid,conditional_status(reportValid), ...
        strjoin(string(reportDetails.errors),"; "), ...
        string(report.design_preset),string(report.header_pattern), ...
        'VariableNames',{'run_id','path','valid','status','details', ...
        'design_preset','header_pattern'});
    write_new_table(fullfile(context.reports_dir, ...
        "report_structure_validation.csv"),reportStructure);
    assert(reportValid,"stageB2C:waterCorrection:Report", ...
        "The Chinese experiment report failed package validation.");
    visual = rkkt.reporting.render_stage_b2c_report_external( ...
        context.root,report.path);
    write_new_table(fullfile(context.reports_dir, ...
        "report_visual_qa.csv"),visual);
    reportHash = rkkt.data.compute_sha256_file(report.path);
    write_new_table(fullfile(context.reports_dir,"report_sha256.csv"), ...
        table(string(context.run_id), ...
        "reports/阶段B-2C_水量二阶松弛校正实验报告.docx", ...
        string(reportHash),"PASS", ...
        'VariableNames',{'run_id','relative_path','sha256','status'}));

    manifest = rkkt.artifacts.finalize_run_manifest(context,runStatus,struct( ...
        "milestone_status",char(runStatus), ...
        "experimental_solver_terminal_state",char(terminalState), ...
        "experimental_convergence_achieved",terminalState=="CONVERGED", ...
        "experimental_physical_audit_passed",physicalAudit.passed, ...
        "formal_convergence_claimed",false, ...
        "formal_solver_modified",false,"formal_entry_modified",false, ...
        "model_modified",false,"objective_modified",false, ...
        "step_length_modified",false,"production_fallback_added",false, ...
        "accepted_iteration_count",accepted,"iteration_count",accepted, ...
        "reports_generated",true,"report_structure_validated",true, ...
        "report_visual_qa_status",char(string(visual.status)), ...
        "report_relative_path", ...
            "reports/阶段B-2C_水量二阶松弛校正实验报告.docx", ...
        "report_sha256",char(reportHash), ...
        "failure_identifier",char(failureIdentifier), ...
        "failure_message",char(failureMessage), ...
        "elapsed_seconds",toc(runTimer)));
    rkkt.artifacts.update_run_index(context,manifest);

    result.status = string(manifest.status);
    result.terminal_state = terminalState;
    result.accepted_iterations = accepted;
    result.source_equivalent_revision = options.SourceRevision+accepted;
    result.report_path = string(report.path);
    result.failure_identifier = failureIdentifier;
    result.failure_message = failureMessage;
    result.initial_metrics = initialMetrics;
    result.final_metrics = finalMetrics;
    result.iteration_history = iterationHistory;
    result.factor_history = factorHistory;
    result.physical_audit = physicalAudit;
    result.last_step = lastStep;
catch cause
    failureIdentifier = string(cause.identifier);
    failureMessage = string(cause.message);
    try
        if ~isfile(context.issue_log_path)
            write_new_table(context.issue_log_path,table( ...
                string(context.run_id),"WATER2-SETUP-001","FAIL_RETRYABLE", ...
                failureIdentifier,failureMessage, ...
                'VariableNames',{'run_id','issue_id','status', ...
                'identifier','message'}));
        end
        manifest = jsondecode(fileread(context.run_manifest_path));
        if string(manifest.status)=="RUNNING"
            manifest = rkkt.artifacts.finalize_run_manifest( ...
                context,"FAIL_RETRYABLE",struct( ...
                "milestone_status","FAIL_RETRYABLE", ...
                "experimental_solver_terminal_state","SETUP_FAILURE", ...
                "experimental_convergence_achieved",false, ...
                "experimental_physical_audit_passed",false, ...
                "formal_convergence_claimed",false, ...
                "formal_solver_modified",false, ...
                "formal_entry_modified",false,"model_modified",false, ...
                "production_fallback_added",false, ...
                "failure_identifier",char(failureIdentifier), ...
                "failure_message",char(failureMessage), ...
                "elapsed_seconds",toc(runTimer)));
            rkkt.artifacts.update_run_index(context,manifest);
        end
    catch
    end
    result.status = "FAIL_RETRYABLE";
    result.terminal_state = "SETUP_FAILURE";
    result.failure_identifier = failureIdentifier;
    result.failure_message = failureMessage;
end
end

function value = experiment_environment(runId)
value = rkkt.diagnostics.inspect_stage_b2b_environment();
row = value.check_id=="IPM_OPTIMIZATION";
value.expected(row) = "isolated_continuation";
value.actual(row) = "isolated_continuation";
value.details(row) = ...
    "Formal direction and step plus experimental water slack correction";
value = addvars(value,repmat(string(runId),height(value),1), ...
    'Before',1,'NewVariableNames','run_id');
end

function persist_initial_day17_matrix(context,lin)
reduced = rkkt.solver.eliminate_stage_b2c_all_inequality_directions(lin);
partition = rkkt.solver.partition_stage_b2c_daily_joint_system(lin,reduced);
position = find([partition.day.day_id]==17);
assert(isscalar(position),"stageB2C:waterCorrection:InitialDay17", ...
    "The initial partition must contain one day-17 block.");
block = partition.day(position);
pathValue = fullfile(context.matrices_dir, ...
    "initial_day17_joint_block.mat");
rkkt.artifacts.save_mat_artifact(pathValue,"matrix",block.matrix, ...
    "rhs",block.rhs,"capacity_coupling",block.capacity_coupling);
manifest = table(string(context.run_id),"initial_day17_joint_block",17, ...
    block.dimension,nnz(block.matrix),sprank(block.matrix), ...
    issparse(block.matrix),"matrices/initial_day17_joint_block.mat", ...
    rkkt.data.compute_sha256_file(pathValue), ...
    'VariableNames',{'run_id','matrix_name','day','dimension','nnz', ...
    'structural_rank','is_sparse','relative_path','sha256'});
write_new_table(context.matrix_manifest_path,manifest);
end

function row = make_iteration_row(runId,iteration,sourceEquivalent, ...
        step,factor,converged)
m = step.metrics_after; u = step.uncorrected_metrics_after;
c = step.water_slack_second_order_correction;
row = table(string(runId),iteration,sourceEquivalent, ...
    step.state_after.state_revision,m.primal_equality_inf, ...
    m.primal_inequality_inf,u.primal_inequality_inf,m.dual_scaled_inf, ...
    m.mean_lz_scaled,m.maximum_water_violation,step.primal_step.alpha, ...
    step.dual_step.alpha,c.maximum_absolute_remainder, ...
    c.maximum_trial_residual,c.maximum_corrected_residual, ...
    c.maximum_closure_error,c.minimum_corrected_l, ...
    factor.minimum_absolute_pivot_eigenvalue,factor.pivot_tolerance, ...
    factor.inertia_zero,step.direction_audit.direction_relative_error, ...
    step.direction_audit.recursive_kkt_relative_residual, ...
    step.fixed_zero.maximum_absolute_direction, ...
    step.only_water_slacks_corrected,converged, ...
    'VariableNames',{'run_id','experiment_iteration', ...
    'source_equivalent_revision','state_revision', ...
    'primal_equality_inf','primal_inequality_inf', ...
    'uncorrected_primal_inequality_inf','dual_scaled_inf', ...
    'mean_lz_scaled','maximum_water_violation','alpha_primal', ...
    'alpha_dual','maximum_absolute_water_remainder', ...
    'maximum_trial_water_residual','maximum_corrected_water_residual', ...
    'maximum_water_closure_error','minimum_corrected_water_l', ...
    'day17_minimum_absolute_pivot','day17_pivot_tolerance', ...
    'day17_numerical_zero_pivot_count','direction_relative_error', ...
    'recursive_kkt_relative_residual', ...
    'fixed_zero_maximum_absolute_direction', ...
    'only_water_slacks_corrected','convergence_accepted'});
end

function rows = make_factor_rows(runId,iteration,sourceEquivalent,responses)
n = numel(responses);
rows = empty_factor_history();
for position = 1:n
    f = responses(position).factor;
    rows = [rows;table(string(runId),iteration,sourceEquivalent, ...
        responses(position).day_id,f.dimension,f.rhs_count, ...
        f.factorization_count,f.minimum_absolute_pivot_eigenvalue, ...
        f.pivot_tolerance,f.inertia_zero, ...
        f.maximum_column_relative_residual,f.local_residual_target_met, ...
        string(f.warning_identifier),f.warning_present, ...
        f.warning_continued,f.solution_finite, ...
        'VariableNames',rows.Properties.VariableNames)]; %#ok<AGROW>
end
end

function row = make_direction_row(runId,iteration,sourceEquivalent,step)
a = step.direction_audit;
row = table(string(runId),iteration,sourceEquivalent, ...
    a.direction_relative_error,a.component_relative_errors.xi, ...
    a.component_relative_errors.y,a.component_relative_errors.l, ...
    a.component_relative_errors.z,a.recursive_kkt_relative_residual, ...
    a.full_kkt_relative_residual,a.all_pass, ...
    step.recursive.no_full_direction_fallback, ...
    ~step.recursive.full_direction_consumed, ...
    'VariableNames',{'run_id','experiment_iteration', ...
    'source_equivalent_revision','direction_relative_error', ...
    'xi_relative_error','y_relative_error','l_relative_error', ...
    'z_relative_error','recursive_kkt_relative_residual', ...
    'full_kkt_relative_residual','all_pass','no_full_direction_fallback', ...
    'full_direction_not_consumed'});
end

function value = empty_iteration_history()
value = table('Size',[0,25], ...
    'VariableTypes',[repmat("double",1,23),"logical","logical"], ...
    'VariableNames',{'run_id_numeric_placeholder','experiment_iteration', ...
    'source_equivalent_revision','state_revision','primal_equality_inf', ...
    'primal_inequality_inf','uncorrected_primal_inequality_inf', ...
    'dual_scaled_inf','mean_lz_scaled','maximum_water_violation', ...
    'alpha_primal','alpha_dual','maximum_absolute_water_remainder', ...
    'maximum_trial_water_residual','maximum_corrected_water_residual', ...
    'maximum_water_closure_error','minimum_corrected_water_l', ...
