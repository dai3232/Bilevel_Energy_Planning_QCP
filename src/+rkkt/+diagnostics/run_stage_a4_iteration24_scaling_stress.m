row = struct( ...
    "day",0,"hour",0,"dimension",0, ...
    "original_numeric_rank",0,"scaled_numeric_rank",0, ...
    "original_condition_2",NaN,"scaled_condition_2",NaN, ...
    "condition_reduction_factor",NaN, ...
    "original_smin",NaN,"scaled_smin",NaN, ...
    "symmetry_relative_original",NaN, ...
    "symmetry_relative_scaled",NaN, ...
    "scaling_used",false,"equilibration_passes",0, ...
    "scale_min",NaN,"scale_max",NaN,"scale_ratio",NaN, ...
    "factor_relative_residual",NaN, ...
    "solve_original_operator_relative_residual",NaN, ...
    "solve_factorized_operator_relative_residual",NaN, ...
    "chain_relative_residual",NaN);
end

function audit = build_core_audit(recursive)
factor = recursive.core.factor;
trace = factor.scaling_trace;
audit = struct( ...
    "dimension",factor.dimension, ...
    "scaling_used",factor.scaling_used, ...
    "equilibration_passes",factor.equilibration_passes, ...
    "original_numeric_rank",factor.original_numeric_rank, ...
    "scaled_numeric_rank",factor.numeric_rank, ...
    "original_condition_2",factor.original_condition_2, ...
    "scaled_condition_2",factor.condition_2, ...
    "condition_reduction_factor", ...
        factor.original_condition_2/factor.condition_2, ...
    "original_smin",factor.original_smin, ...
    "scaled_smin",trace.smin(end), ...
    "symmetry_relative_original",factor.symmetry_relative, ...
    "symmetry_relative_scaled", ...
        factor.factorization_matrix_symmetry_relative, ...
    "relative_residual",recursive.core.diagnostics.relative_residual, ...
    "refinement_correction_count", ...
        recursive.core.diagnostics.residual_refinement.correction_count, ...
    "refinement_stop_reason", ...
        recursive.core.diagnostics.residual_refinement.stop_reason);
end

function tableValue = build_refinement_audit(recursive)
nDays = numel(recursive.daily_thomas);
component = strings(nDays+1,1);
day = nan(nDays+1,1);
maximumPasses = zeros(nDays+1,1);
passesAttempted = zeros(nDays+1,1);
correctionCount = zeros(nDays+1,1);
initialResidual = nan(nDays+1,1);
finalResidual = nan(nDays+1,1);
stopReason = strings(nDays+1,1);
for d = 1:nDays
    item = recursive.daily_thomas(d).diagnostics.residual_refinement;
    component(d) = "day_chain";
    day(d) = recursive.daily_partitions(d).day_id;
    maximumPasses(d) = item.maximum_passes;
    passesAttempted(d) = item.passes_attempted;
    correctionCount(d) = item.correction_count;
    initialResidual(d) = item.initial_maximum_column_relative;
    finalResidual(d) = item.final_maximum_column_relative;
    stopReason(d) = item.stop_reason;
end
item = recursive.core.diagnostics.residual_refinement;
component(end) = "global_core_16";
maximumPasses(end) = item.maximum_passes;
passesAttempted(end) = item.passes_attempted;
correctionCount(end) = item.correction_count;
initialResidual(end) = item.initial_maximum_column_relative;
finalResidual(end) = item.final_maximum_column_relative;
stopReason(end) = item.stop_reason;
tableValue = table(component,day,maximumPasses,passesAttempted, ...
    correctionCount,initialResidual,finalResidual,stopReason, ...
    'VariableNames',{'component','day','maximum_passes', ...
    'passes_attempted','correction_count', ...
    'initial_maximum_column_relative', ...
    'final_maximum_column_relative','stop_reason'});
end

function audit = audit_factor_operator_contract(recursive)
factorCount = 0;
allScaled = true;
allOriginalRetained = true;
maximumCongruenceRelative = 0;
maximumFactorResidual = 0;
maximumOriginalOperatorMismatch = 0;
for d = 1:numel(recursive.daily_thomas)
    for t = 1:numel(recursive.daily_thomas(d).factors)
        factor = recursive.daily_thomas(d).factors{t};
        [allScaled,allOriginalRetained,maximumCongruenceRelative, ...
            maximumFactorResidual,maximumOriginalOperatorMismatch, ...
            factorCount] = accumulate_factor( ...
            factor,allScaled,allOriginalRetained, ...
            maximumCongruenceRelative,maximumFactorResidual, ...
            maximumOriginalOperatorMismatch,factorCount);
    end
end
[allScaled,allOriginalRetained,maximumCongruenceRelative, ...
    maximumFactorResidual,maximumOriginalOperatorMismatch,factorCount] = ...
    accumulate_factor( ...
    recursive.core.factor,allScaled,allOriginalRetained, ...
    maximumCongruenceRelative,maximumFactorResidual, ...
    maximumOriginalOperatorMismatch,factorCount);
audit = struct( ...
    "factor_count",factorCount, ...
    "all_scaled",allScaled, ...
    "all_original_operators_retained",allOriginalRetained, ...
    "maximum_congruence_reconstruction_relative", ...
        maximumCongruenceRelative, ...
    "maximum_factor_reconstruction_relative", ...
        maximumFactorResidual, ...
    "maximum_original_factorized_operator_relative", ...
        maximumOriginalOperatorMismatch, ...
    "automatic_symmetrization_used",false, ...
    "regularization_used",false, ...
    "full_kkt_direction_consumed",false, ...
    "all_pass",allScaled && allOriginalRetained && ...
        maximumCongruenceRelative<=64*eps && ...
        maximumFactorResidual<=1e-12 && ...
        maximumOriginalOperatorMismatch<=1e-12);
end

function [allScaled,allOriginalRetained,maxCongruence,maxFactor, ...
        maxOriginalMismatch,count] = ...
        accumulate_factor(factor,allScaled,allOriginalRetained, ...
        maxCongruence,maxFactor,maxOriginalMismatch,count)
count = count+1;
allScaled = allScaled && factor.scaling_used;
scale = spdiags(factor.congruence_scale,0, ...
    factor.dimension,factor.dimension);
rebuilt = scale*factor.matrix*scale;
relative = norm(rebuilt-factor.factorization_matrix,"fro") / ...
    max(1,norm(factor.factorization_matrix,"fro"));
allOriginalRetained = allOriginalRetained && ...
    isequal(size(factor.matrix),size(factor.factorization_matrix)) && ...
    isfinite(relative);
maxCongruence = max(maxCongruence,relative);
maxFactor = max(maxFactor,factor.factor_relative_residual);
maxOriginalMismatch = max(maxOriginalMismatch, ...
    factor.raw_to_factorized_operator_relative);
end

function digest = numeric_fingerprint(value)
messageDigest = java.security.MessageDigest.getInstance("SHA-256");
shape = uint64(size(value));
messageDigest.update(typecast(shape(:),"int8"));
bytes = typecast(double(value(:)),"uint8");
messageDigest.update(typecast(bytes(:),"int8"));
digestBytes = mod(double(messageDigest.digest()),256);
digest = lower(join(compose("%02x",digestBytes),""));
digest = reshape(digest,1,1);
end

function git = capture_git(root)
[headStatus,headText] = git_command(root,"rev-parse HEAD");
[branchStatus,branchText] = git_command(root,"branch --show-current");
[statusCode,statusText] = git_command( ...
    root,"status --porcelain --untracked-files=normal");
git = struct( ...
    "commit",lower(strip(string(headText))), ...
    "branch",strip(string(branchText)), ...
    "status_text",string(statusText), ...
    "head_resolved",headStatus==0, ...
    "branch_resolved",branchStatus==0, ...
    "status_resolved",statusCode==0);
end

function [status,output] = git_command(root,argumentsValue)
safe = replace(string(root),"\","/");
quotedSafe = '"'+replace(safe,'"','\"')+'"';
quotedRoot = '"'+replace(string(root),'"','\"')+'"';
command = "git -c safe.directory="+quotedSafe+" -C "+quotedRoot+" "+ ...
    argumentsValue;
[status,output] = system(char(command));
end

function root = canonical_root(value)
root = string(java.io.File(value).getCanonicalPath());
assert(isfolder(root),"stageA4:scaleStress:ProjectRoot", ...
    "Project root does not exist: %s",root);
end

