write_new_table(fullfile(context.indices_dir,"variable_index.csv"), ...
    index.variable_index);
write_new_table(fullfile(context.indices_dir,"constraint_index.csv"), ...
    index.constraint_index);
write_new_table(fullfile(context.indices_dir,"block_index.csv"), ...
    index.block_index);
write_new_table(fullfile(context.indices_dir,"fixed_zero_map.csv"), ...
    index.fixed_zero_map);
write_new_table(fullfile(context.indices_dir,"permutation_map.csv"), ...
    index.permutation_map);
write_new_table(fullfile(context.indices_dir,"soc_link_map.csv"), ...
    index.soc_link_map);
write_new_table(fullfile(context.indices_dir,"water_constraint_index.csv"), ...
    index.water_constraint_index);
end

function persist_final_matrix_artifacts(context,ipm)
lin=ipm.final_linearization; step=ipm.last_step;
linPath=fullfile(context.matrices_dir,"final_linearization.mat");
auditPath=fullfile(context.matrices_dir,"final_direction_audit.mat");
rkkt.artifacts.save_mat_artifact(linPath,"linearization",lin);
rkkt.artifacts.save_mat_artifact(auditPath, ...
    "full_kkt_matrix",step.full_audit.kkt.matrix, ...
    "full_kkt_rhs",step.full_audit.kkt.rhs, ...
    "recursive_direction",step.recursive.direction, ...
    "full_kkt_audit_direction",step.full_audit.direction, ...
    "direction_audit",step.direction_audit);
matrix_name=["H_L";"A";"G";"full_KKT_audit";"global_core_16"];
matrices={lin.H;lin.A;lin.G;step.full_audit.kkt.matrix; ...
    step.recursive.core.matrix};
row_count=zeros(5,1); column_count=zeros(5,1); nonzero_count=zeros(5,1);
for k=1:5
    [row_count(k),column_count(k)]=size(matrices{k});
    nonzero_count(k)=nnz(matrices{k});
end
artifact_path=[repmat("matrices/final_linearization.mat",3,1); ...
    repmat("matrices/final_direction_audit.mat",2,1)];
sha256=[repmat(rkkt.data.compute_sha256_file(linPath),3,1); ...
    repmat(rkkt.data.compute_sha256_file(auditPath),2,1)];
role=["shared_lagrangian_hessian";"shared_equality_jacobian"; ...
    "shared_inequality_jacobian";"independent_audit_only"; ...
    "recursive_formal"];
manifest=table(repmat(string(context.run_id),5,1),matrix_name,role, ...
    row_count,column_count,nonzero_count,true(5,1),artifact_path,sha256, ...
    repmat(string(lin.identity),5,1),repmat("PASS",5,1), ...
    'VariableNames',{'run_id','matrix_name','role','row_count', ...
    'column_count','nonzero_count','is_sparse','artifact_path','sha256', ...
    'linearization_identity','status'});
write_new_table(context.matrix_manifest_path,manifest);
end

function [capacity,hourly]=build_physical_results( ...
        context,ipm,index,data,physical)
names=string(ipm.final_linearization.capacity_parameters.names(:));
values=ipm.final_state.xi(ipm.final_linearization.maps.q_global);
capacity=table(repmat(string(context.run_id),14,1),(1:14).', ...
    names,values,'VariableNames',{'run_id','capacity_index', ...
    'capacity_name','value'});
n=7*24; day=zeros(n,1); hour=zeros(n,1); row=0;
arrays=cell(1,24);
for k=1:24, arrays{k}=zeros(n,1); end
for d=1:7
    for t=1:24
        row=row+1; day(row)=physical.days(d); hour(row)=physical.hours(t);
        valuesAtHour=[reshape(physical.value.wind(d,t,:),1,[]), ...
            reshape(physical.value.solar(d,t,:),1,[]), ...
            reshape(physical.value.hydro(d,t,:),1,[]), ...
            reshape(physical.value.thermal(d,t,:),1,[]), ...
            reshape(physical.value.charge(d,t,:),1,[]), ...
            reshape(physical.value.discharge(d,t,:),1,[]), ...
            reshape(physical.value.soc(d,t,:),1,[])];
        for k=1:24, arrays{k}(row)=valuesAtHour(k); end
    end
end
variableNames=["PW_1","PW_2","PW_3","PW_4","PW_5", ...
    "PP_1","PP_2","PP_3","PP_4","PP_5", ...
    "PH_1","PH_2","PH_3","PH_4", ...
    "PF_1","PF_2","PF_3","PF_4", ...
    "Pch_1","Pch_2","Pdis_1","Pdis_2","SOC_1","SOC_2"];
hourly=table(repmat(string(context.run_id),n,1),day,hour, ...
    'VariableNames',{'run_id','day','hour'});
for k=1:numel(variableNames), hourly.(variableNames(k))=arrays{k}; end
assert(height(hourly)==168 && width(hourly)==27 && ...
    isscalar(data.meta.nHydro) && height(index.variable_index)==3722, ...
    "stageB2C:Results","The canonical physical result table is incomplete.");
end

function value=make_acceptance(context,ipm,physical,waterInput,config)
directions=ipm.direction_audit_history;
test_id=["SB-DATA-001";"SB-DER-001";"SB-EQ-001";"SB-PHY-001"];
category=["数据";"导数";"方向等价";"物理"];
requirement=["第14—20日28组水量上下限数据有效"; ...
    "非零水量Hessian及56行精确余项中心性限幅校正通过"; ...
    "每轮递推与完整KKT方向及残差<=1e-10"; ...
    "最终28项水量与Stage-A物理审计通过"];
status=repmat("PASS",4,1);
actual_value=["28/28 input rows PASS"; ...
    compose("H_water nnz=672; min_beta=%.17g; final_beta=%.17g; max_closure=%.17g; min_l=%.17g", ...
        ipm.execution_audit.minimum_water_slack_correction_fraction, ...
        ipm.execution_audit.final_water_slack_correction_fraction, ...
        ipm.execution_audit. ...
            maximum_water_slack_correction_closure_error, ...
        ipm.execution_audit.minimum_corrected_water_slack); ...
    compose("worst_direction=%.17g; worst_recursive_residual=%.17g", ...
        max(directions.direction_relative_error), ...
        max(directions.recursive_full_kkt_relative_residual)); ...
    compose("28/28; maximum_violation=%.17g", ...
        physical.maximum_water_violation)];
evidence_path=["diagnostics/water_input_audit.csv"; ...
    "diagnostics/nonzero_water_hessian_gate.csv"; ...
    "diagnostics/direction_audit_history.csv"; ...
    "diagnostics/final_daily_water_constraint_audit.csv"];
passed=[height(waterInput)==28&&all(waterInput.status=="PASS"); ...
    ipm.execution_audit.water_slack_second_order_correction_pass; ...
    all(directions.direction_relative_error<= ...
        config.direction_relative_error_tolerance) && ...
    all(directions.recursive_full_kkt_relative_residual<= ...
        config.recursive_full_kkt_residual_tolerance) && ...
    all(directions.full_kkt_relative_residual<= ...
        config.full_kkt_residual_tolerance);physical.passed];
status(~passed)="FAIL";
value=table(repmat(string(context.run_id),4,1),test_id,category, ...
    requirement,true(4,1),status,actual_value,evidence_path, ...
    repmat("B-2C",4,1),'VariableNames',{'run_id','test_id','category', ...
    'requirement','blocking','status','actual_value','evidence_path', ...
    'milestone'});
end

function suites=run_test_and_static_evidence(context,root)
b2c=run_stage_B_2C_tests("EvidenceDirectory",string(context.tests_dir), ...
    "CommandText","run_stage_B_2C_tests() [formal B-2C evidence]");
b2b=run_stage_B_2B_tests("EvidenceDirectory", ...
    string(fullfile(context.tests_dir,"b2b_regression")), ...
    "CommandText","run_stage_B_2B_tests() [B-2C regression]");
b2a=run_stage_B_2A_tests("EvidenceDirectory", ...
    string(fullfile(context.tests_dir,"b2a_regression")), ...
    "CommandText","run_stage_B_2A_tests() [B-2C regression]");
b1=run_stage_B_1_tests("EvidenceDirectory", ...
    string(fullfile(context.tests_dir,"b1_regression")), ...
    "CommandText","run_stage_B_1_tests() [B-2C regression]");
b1Affected=run_stage_B_1_affected_regressions("EvidenceDirectory", ...
    string(fullfile(context.tests_dir,"b1_affected")), ...
    "CommandText","run_stage_B_1_affected_regressions() [B-2C]");
stageA=run_stage_B_2A_stage_A_regressions("EvidenceDirectory", ...
    string(fullfile(context.tests_dir,"stage_a_structure")), ...
    "CommandText","run_stage_B_2A_stage_A_regressions() [B-2C]");
a43=run_stage_B_2C_A4_3_affected_regressions("EvidenceDirectory", ...
    string(fullfile(context.tests_dir,"a4_3_affected")), ...
    "CommandText", ...
    "run_stage_B_2C_A4_3_affected_regressions() [B-2C]");
allPass=b2c.all_pass&&b2b.all_pass&&b2a.all_pass&&b1.all_pass&& ...
    b1Affected.all_pass&&stageA.all_pass&&a43.all_pass;
counts=[b2c.summary.test_total,b2b.summary.test_total, ...
    b2a.summary.test_total,b1.summary.test_total, ...
    b1Affected.summary.test_total,stageA.summary.test_total, ...
    a43.summary.test_total];
passedCounts=[b2c.summary.test_passed,b2b.summary.test_passed, ...
    b2a.summary.test_passed,b1.summary.test_passed, ...
    b1Affected.summary.test_passed,stageA.summary.test_passed, ...
    a43.summary.test_passed];
static=rkkt.diagnostics.run_stage_b2c_static_checks(root);
write_new_table(fullfile(context.tests_dir,"static_check_summary.csv"), ...
    static.code_analyzer);
write_new_table(fullfile(context.tests_dir,"forbidden_code_audit.csv"), ...
    static.forbidden_execution);
write_new_table(fullfile(context.tests_dir, ...
    "dependency_closure_audit.csv"),static.dependency_closure);
write_new_table(fullfile(context.tests_dir, ...
    "forbidden_execution_audit.csv"),static.runtime_boundary);
diffScope=[ ...
    "src/+rkkt/+workflows/stageB2C.m"; ...
    "src/+rkkt/+solver/compute_stage_b2c_water_slack_second_order_correction.m"; ...
    "src/+rkkt/+solver/run_stage_b2c_full_ipm.m"; ...
    "src/+rkkt/+diagnostics/execute_stage_b2c_iteration.m"; ...
    "src/+rkkt/+diagnostics/execute_stage_b2c_water_corrected_iteration.m"; ...
    "src/+rkkt/+diagnostics/run_stage_b2c_static_checks.m"; ...
    "src/+rkkt/+reporting/generate_stage_b2c_report.m"; ...
    "src/+rkkt/+reporting/validate_stage_b2c_report.m"; ...
    "tests/integration/test_stage_b2c_formal_ipm.m"; ...
    "tests/unit/test_stage_b2c_water_slack_second_order_correction.m"];
diffCommand="diff --check -- "+strjoin(diffScope," ");
[diffCode,diffOutput]=system(git_command(root,diffCommand));
rkkt.artifacts.write_text_utf8(fullfile(context.tests_dir,"git_diff_check.txt"), ...
    "scope="+strjoin(diffScope,"|")+newline+ ...
    "exit_code="+string(diffCode)+newline+string(diffOutput));
suites=struct("b2c",b2c.summary,"b2b",b2b.summary, ...
    "b2a",b2a.summary,"b1",b1.summary, ...
    "b1_affected",b1Affected.summary,"stage_a",stageA.summary, ...
    "a4_3",a43.summary,"static",static, ...
    "total",sum(counts),"passed",sum(passedCounts), ...
    "all_pass",allPass&&static.all_pass&&diffCode==0);
end

function value=empty_issue_log()
