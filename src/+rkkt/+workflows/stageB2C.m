function result = stageB2C(options)
%STAGEB2C Run the formal seven-day daily-joint recursive Stage B IPM.

arguments
    options.ProjectRoot (1,1) string = ""
    options.RunId (1,1) string = ""
end
root=options.ProjectRoot;
if strlength(strip(root))==0
    root=rkkt.projectRoot();
end
root=string(java.io.File(char(root)).getCanonicalPath());
addpath(fullfile(root,"tests"));
config=rkkt.model.load_stage_b2c_configuration(root);
[inputHashes,inputPass]=rkkt.data.verify_input_hashes(root);
assert(inputPass,"stageB2C:InputHashMismatch", ...
    "Controlled input SHA256 verification failed.");
commit=git_commit(root); shortCommit=extractBefore(commit,9);
runId=choose_run_id(root,options.RunId,shortCommit);
actualCommand="RUN_PROJECT.m";
metadata=struct("run_purpose",char(config.run_purpose), ...
    "milestone","B-2C","implementation_commit",char(commit), ...
    "parent_run_id",char(config.parent_run_id), ...
    "historical_baseline_commit", ...
        "90bf33cca0611154231588ac5d7ee09fd0e9c089", ...
    "actual_test_command",char(actualCommand), ...
    "optimization_executed",true,"a1_solver_executed",false, ...
    "full_ipm_executed",false,"convergence_evaluated",false, ...
    "convergence_achieved",false,"full_kkt_role","audit_only", ...
    "recursive_direction_executed",false, ...
    "recursive_direction_is_formal",true, ...
    "water_slack_second_order_correction_enabled",true, ...
    "water_slack_second_order_correction_scope_count",56, ...
    "water_slack_second_order_correction_formula", ...
        "l_corrected=l_trial-beta*(g_after-g_before-alpha*G*dx)", ...
    "water_correction_fraction_rule", ...
        "beta=1_if_l_exact_ge_sigma_l_trial_else_tau_times_centrality_boundary", ...
    "no_full_direction_fallback",true, ...
    "full_direction_consumed_by_recursive",false, ...
    "parallel_executed",false,"annual_scope_executed",false, ...
    "thermal_second_pass_executed",false, ...
    "stage_c1_implemented",false,"stage_c1_entered",false, ...
    "water_constraints_enabled",true,"milestone_status","RUNNING");
context=rkkt.artifacts.create_run_context(root,"stage_B","RunId",runId, ...
    "ModelContractVersion","v1.0", ...
    "InputHashes",input_hash_object(inputHashes), ...
    "EffectiveConfigPath",fullfile(root,"config","stage_B_2C.yaml"), ...
    "ManifestMetadata",metadata);
diagnosticsDir=fullfile(context.root,"diagnostics");
resultsDir=fullfile(context.root,"results");
ensure_directory(diagnosticsDir); ensure_directory(resultsDir);
result=struct("run_id",string(context.run_id), ...
    "run_path",string(context.root),"status","RUNNING", ...
    "manifest",struct(),"report_path","","error_identifier","", ...
    "error_message","");
try
    environment=rkkt.diagnostics.inspect_stage_b2b_environment();
    environment=addvars(environment,repmat(string(context.run_id), ...
        height(environment),1),'Before',1,'NewVariableNames','run_id');
    write_new_table(context.environment_csv_path,environment);
    assert(all(environment.status(logical(environment.blocking))=="PASS"), ...
        "stageB2C:Environment", ...
        "A blocking MATLAB environment check failed.");
    write_new_table(context.input_hashes_csv_path, ...
        input_hash_table(inputHashes,context.run_id));

    data=rkkt.data.load_project_data(root);
    waterInput=rkkt.diagnostics.build_stage_b1_water_input_audit(data,context.run_id);
    write_new_table(fullfile(diagnosticsDir,"water_input_audit.csv"), ...
        waterInput);
    assert(height(waterInput)==28 && all(waterInput.status=="PASS"), ...
        "stageB2C:WaterInput", ...
        "The controlled 28-row water-input audit failed.");
    index=rkkt.indexing.build_stage_b2c_index(data,config,"RunId",string(context.run_id));
    persist_index_artifacts(context,index);

    gate=rkkt.diagnostics.run_stage_b2c_nonzero_hessian_gate(data,index,config, ...
        DiagnosticsDirectory=string(diagnosticsDir));
    assert(gate.passed,"stageB2C:NonzeroHessianGate", ...
        "The mandatory nonzero-water-Hessian gate failed.");
    rkkt.artifacts.update_running_run_manifest(context,struct( ...
        "nonzero_water_hessian_gate_passed",true, ...
        "nonzero_water_hessian_nnz",gate.water_hessian_nnz, ...
        "nonzero_water_hessian_fro_norm",gate.water_hessian_fro_norm, ...
        "nonzero_water_hessian_direction_relative_error", ...
            gate.comparison.direction_relative_error, ...
        "nonzero_water_hessian_recursive_kkt_residual", ...
            gate.comparison.recursive_kkt_relative_residual, ...
        "nonzero_water_hessian_full_kkt_residual", ...
            gate.comparison.full_kkt_relative_residual));
    clear gate

    ipm=rkkt.solver.run_stage_b2c_full_ipm(data,index,config,context);
    if ~(ipm.convergence_achieved && ...
            string(ipm.run_terminal_state)=="CONVERGED")
        if ipm.failure.present
            throw(MException(char(ipm.failure.identifier), ...
                "%s",char(ipm.failure.message)));
        end
        error("stageB2C:Convergence", ...
            "The formal seven-day B-2C IPM did not converge within 100 iterations.");
    end
    assert(ipm.execution_audit.water_slack_second_order_correction_pass, ...
        "stageB2C:WaterCorrection", ...
        "The formal 56-row water-slack correction audit failed.");
    physical=rkkt.diagnostics.evaluate_stage_b2c_physical_audit(ipm,index,data,config);
    write_new_table(fullfile(diagnosticsDir, ...
        "final_daily_water_constraint_audit.csv"),physical.water);
    write_new_table(fullfile(context.acceptance_dir,"physical_audit.csv"), ...
        physical.stage_a);
    assert(physical.passed,"stageB2C:PhysicalAcceptance", ...
        "SB-PHY-001 or a Stage-A physical regression failed.");

    [capacityResults,hourlyResults]=build_physical_results( ...
        context,ipm,index,data,physical.physical);
    write_new_table(fullfile(resultsDir,"capacity_results.csv"), ...
        capacityResults);
    write_new_table(fullfile(resultsDir,"hourly_dispatch_results.csv"), ...
        hourlyResults);
    rkkt.artifacts.save_mat_artifact(fullfile(resultsDir,"final_state_and_physical.mat"), ...
        "final_state",ipm.final_state,"physical",physical.physical, ...
        "final_metrics",ipm.final_metrics);
    persist_final_matrix_artifacts(context,ipm);

    acceptance=make_acceptance(context,ipm,physical,waterInput,config);
    write_new_table(context.acceptance_results_path,acceptance);
    assert(all(acceptance.status=="PASS"), ...
        "stageB2C:Acceptance","A blocking Stage-B acceptance item failed.");
    issues=empty_issue_log(); write_new_table(context.issue_log_path,issues);
    decision=table(string(context.run_id),"B-2C","PASS", ...
        "Nonzero Hessian gate, formal water-slack correction, seven-day convergence, direction audits, and 28 water rows passed.", ...
        "Stage B may close; switch only the stage gate to Stage C1 / READY without implementing C1.", ...
        'VariableNames',{'run_id','milestone','status','conclusion','next_action'});
    write_new_table(context.decision_log_path,decision);

    suites=run_test_and_static_evidence(context,root);
    assert(suites.all_pass,"stageB2C:Tests", ...
        "A B-2C, regression, static, or forbidden-item suite failed.");
    rkkt.artifacts.update_running_run_manifest(context,struct( ...
        "tests_executed",true,"test_total",suites.total, ...
        "test_passed",suites.passed,"test_failed",0, ...
        "test_incomplete",0, ...
        "code_analyzer_blocking_findings",0, ...
        "forbidden_execution_audit","PASS", ...
        "SB_DATA_001_status","PASS","SB_DER_001_status","PASS", ...
        "SB_EQ_001_status","PASS","SB_PHY_001_status","PASS", ...
        "fixed_zero_count",422,"final_maximum_water_violation", ...
            physical.maximum_water_violation,"stage_b_complete",true, ...
        "water_slack_second_order_correction_enabled",true, ...
        "water_slack_second_order_correction_passed",true, ...
        "minimum_water_slack_correction_fraction", ...
            ipm.execution_audit.minimum_water_slack_correction_fraction, ...
        "final_water_slack_correction_fraction", ...
            ipm.execution_audit.final_water_slack_correction_fraction, ...
        "centrality_limited_water_correction_iteration_count", ...
            ipm.execution_audit. ...
            centrality_limited_water_correction_iteration_count, ...
        "maximum_water_slack_correction_closure_error", ...
            ipm.execution_audit. ...
            maximum_water_slack_correction_closure_error, ...
        "minimum_corrected_water_slack", ...
            ipm.execution_audit.minimum_corrected_water_slack, ...
        "milestone_status","PASS"));

    report=rkkt.reporting.generate_stage_b2c_report(context.root);
    [reportValid,reportDetails]=rkkt.reporting.validate_stage_b2c_report(context.root);
    structure=table(string(context.run_id), ...
        "stage_B_2C_formal_convergence_and_water_physical_acceptance", ...
        string(report.path),reportValid,conditional_status(reportValid), ...
        string(reportDetails.message),string(report.design_preset), ...
        string(report.header_pattern), ...
        'VariableNames',{'run_id','report_id','path','valid','status', ...
        'details','design_preset','header_pattern'});
    write_new_table(fullfile(context.reports_dir, ...
        "report_structure_validation.csv"),structure);
    assert(reportValid,"stageB2C:Report", ...
        "The B-2C Chinese report failed OOXML validation: %s", ...
        reportDetails.message);
    visual=rkkt.reporting.render_stage_b2c_report_external(context.root,report.path);
    write_new_table(fullfile(context.reports_dir,"report_visual_qa.csv"), ...
        visual);
    assert(visual.status=="PASS" || startsWith(visual.status,"NOT_RUN"), ...
        "stageB2C:ReportRender", ...
        "The available DOCX render engine failed for a non-availability reason.");
    reportHash=table( ...
        "reports/阶段B-2C_七日递推IPM收敛与水量物理验收报告.docx", ...
        rkkt.data.compute_sha256_file(report.path),string(context.run_id),"PASS", ...
        'VariableNames',{'relative_path','sha256','run_id','status'});
    write_new_table(fullfile(context.reports_dir,"report_sha256.csv"), ...
        reportHash);

    evidence=write_evidence_hashes(context.root, ...
        fullfile(context.acceptance_dir,"evidence_hashes.csv"));
    manifest=rkkt.artifacts.finalize_run_manifest(context,"PASS",struct( ...
        "milestone_status","PASS","stage_b_complete",true, ...
        "stage_c1_implemented",false,"stage_c1_entered",false, ...
        "reports_generated",true,"report_structure_validated",true, ...
        "report_visual_qa_status",char(visual.status), ...
        "report_relative_path",char(reportHash.relative_path), ...
        "report_sha256",char(reportHash.sha256), ...
        "evidence_hashes","acceptance/evidence_hashes.csv", ...
        "evidence_hashes_sha256",char(rkkt.data.compute_sha256_file( ...
            fullfile(context.acceptance_dir,"evidence_hashes.csv"))), ...
        "evidence_file_count",height(evidence)));
    result.status=string(manifest.status); result.manifest=manifest;
    result.report_path=string(report.path); result.acceptance=acceptance;
    result.ipm=ipm; result.physical=physical; result.tests=suites;
catch cause
    try
        if ~isfile(context.issue_log_path)
            rkkt.artifacts.write_table_csv_17g_atomic(string(context.issue_log_path), ...
                failure_issue(context,cause));
        end
    catch
    end
    finalStatus="FAIL_RETRYABLE";
    if contains(string(cause.identifier),["Environment","InputHash"])
        finalStatus="BLOCKED_EXTERNAL";
    elseif contains(string(cause.identifier),"ModelDecision")
        finalStatus="NEEDS_MODEL_DECISION";
    end
    try
        manifest=jsondecode(fileread(context.run_manifest_path));
        if string(manifest.status)=="RUNNING"
            manifest=rkkt.artifacts.finalize_run_manifest(context,finalStatus,struct( ...
                "milestone_status",char(finalStatus), ...
                "stage_b_complete",false,"stage_c1_implemented",false, ...
                "stage_c1_entered",false, ...
                "failure_identifier",char(string(cause.identifier)), ...
                "failure_message",char(string(cause.message))));
        end
    catch
        manifest=struct();
    end
    result.status=finalStatus; result.manifest=manifest;
    result.error_identifier=string(cause.identifier);
    result.error_message=string(cause.message);
end
end

