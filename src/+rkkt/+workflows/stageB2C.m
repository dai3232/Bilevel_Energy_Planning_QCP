end
function runId=choose_run_id(root,requested,shortCommit)
if strlength(strip(requested))>0
    runId=requested;
    assert(~contains(runId,["/","\"]),"stageB2C:RunId", ...
        "Run id must be a leaf name.");
else
    timestamp=string(datetime("now","TimeZone","UTC", ...
        "Format","yyyyMMdd_HHmmss"));
    runId=timestamp+"_stage_B_2C_"+shortCommit;
end
assert(~isfile(fullfile(root,"runs",runId))&& ...
    ~isfolder(fullfile(root,"runs",runId)),"stageB2C:RunExists", ...
    "Run path already exists: %s",runId);
end
