function counts = model_counts(modelIndex)
if isfield(modelIndex,"version") && ismember(string(modelIndex.version),[ ...
        "stage-B2C-recursive-runtime-package-v1.0", ...
        "stage-B2C-recursive-numerical-payload-v1.0"])
    counts = modelIndex.counts;
else
    counts = modelIndex.counts;
    counts.fixed_zero = height(modelIndex.fixed_zero_map);
    if ~isfield(counts,"base_inequalities")
        counts.base_inequalities = counts.inequalities-counts.water_inequalities;
    end
end
end

function value = make_acceptance(context,ipm,physical,waterInput,index, ...
        config,settings)
counts = model_counts(index);
accepted = ipm.accepted_iteration_count;
recursiveResidual = worst_recursive_residual(ipm,settings.audit_mode);
routePass = accepted>0 && recursiveResidual<= ...
    config.recursive_full_kkt_residual_tolerance;
if settings.audit_mode=="full_kkt"
    routePass = routePass && ipm.execution_audit.direction_audits_pass && ...
        ipm.execution_audit.one_full_kkt_audit_per_accepted_iteration;
    factors = ipm.daily_joint_factorization_history;
    correction = ipm.water_slack_second_order_correction_history;
    correctionPass = height(correction)== ...
        accepted*config.expected_water_inequality_count && ...
        all(correction.strictly_positive);
    fixedPass = all(ipm.iteration_history.fixed_zero_count== ...
        config.expected_stage_a_fixed_zero_count) && ...
        all(ipm.iteration_history.fixed_zero_exact);
else
    routePass = routePass && isfield(ipm,"parallel_executed") && ...
        logical(ipm.parallel_executed)==logical(settings.parallel_enabled);
    factors = ipm.factorization_history;
    correction = ipm.water_correction_history;
    correctionPass = height(correction)== ...
        accepted*config.expected_water_inequality_count && ...
        all(correction.strictly_positive);
    fixedPass = all(ipm.iteration_history.fixed_zero_count== ...
        config.expected_stage_a_fixed_zero_count) && ...
        all(ipm.iteration_history.fixed_zero_exact);
end

factorPass = height(factors)==accepted*(numel(config.days)+1) && ...
    all(factors.factorization_count==1) && ...
    all(~factors.blocking_warning_present) && all(factors.solution_finite);
convergencePass = ~settings.require_convergence || ipm.convergence_achieved;
physicalPass = ~ipm.convergence_achieved || physical.passed;
test_id = ["RUN-DATA";"RUN-INDEX";"RUN-ROUTE";"RUN-FACTORS"; ...
    "RUN-WATER-CORRECTION";"RUN-FIXED-ZERO";"RUN-CONVERGENCE"; ...
    "RUN-PHYSICAL"];
requirement = [compose("%d water-input rows pass", ...
        config.expected_final_water_audit_rows); ...
        "dimensions match the selected day set"; ...
    "configured audit/parallel route and reconstructed KKT residual pass"; ...
    compose("%d daily factors plus one 16-D base or confirmed 17-D micro-border core per iteration", ...
        numel(config.days)); ...
    compose("%d exact water-slack corrections per iteration", ...
        config.expected_water_inequality_count); ...
    compose("%d removed renewable entries remain exact zero", ...
        config.expected_stage_a_fixed_zero_count); ...
    conditional_text(settings.require_convergence, ...
        "four stopping metrics <= 1e-6","bounded run completed"); ...
    "if converged, final water and Stage-A physical audit passes"];
    actual_value = [string(height(waterInput))+" rows"; ...
    compose("%d/%d/%d; reconstructed=%d",counts.variables, ...
        counts.equalities,counts.inequalities, ...
        counts.full_kkt_dimension); ...
    compose("mode=%s; parallel=%s; worst residual=%.17g", ...
        settings.audit_mode,string(settings.parallel_enabled), ...
        recursiveResidual); ...
    string(height(factors))+" factor records; cores="+ ...
        strjoin(unique(factors.object_type( ...
        factors.object_type~="daily_joint")),"|"); ...
    string(height(correction))+" correction records"; ...
    string(config.expected_stage_a_fixed_zero_count)+" exact zeros"; ...
    compose("converged=%s; iterations=%d", ...
        string(ipm.convergence_achieved),accepted); ...
    conditional_text(ipm.convergence_achieved, ...
        compose("passed=%s; max water violation=%.17g", ...
            string(physical.passed),physical.maximum_water_violation), ...
        "not executed before convergence")];
dimensionPass = counts.variables== ...
    config.expected_stage_a_primal_dimension && ...
    counts.equalities==config.expected_stage_a_equality_dimension && ...
    counts.inequalities==config.expected_stage_a_inequality_dimension+ ...
        config.expected_water_inequality_count && ...
    counts.full_kkt_dimension==config.expected_full_kkt_dimension;
passed = [height(waterInput)==config.expected_final_water_audit_rows && ...
        all(waterInput.status=="PASS");dimensionPass;routePass;factorPass; ...
        correctionPass;fixedPass;convergencePass;physicalPass];
status = repmat("FAIL",numel(test_id),1); status(passed) = "PASS";
value = table(repmat(string(context.run_id),numel(test_id),1), ...
    test_id,requirement,actual_value,true(numel(test_id),1),status, ...
    'VariableNames',{'run_id','test_id','requirement','actual_value', ...
    'blocking','status'});
end

function value = make_lightweight_acceptance( ...
        context,ipm,physical,config,settings)
recursiveResidual = worst_recursive_residual(ipm,settings.audit_mode);
convergencePass = ~settings.require_convergence || ipm.convergence_achieved;
kktPass = isfinite(recursiveResidual) && recursiveResidual<= ...
    config.recursive_full_kkt_residual_tolerance;
physicalPass = ipm.convergence_achieved && physical.passed;
test_id = ["LIGHT-CONVERGENCE";"LIGHT-RECONSTRUCTED-KKT"; ...
    "LIGHT-FINAL-PHYSICAL"];
requirement = ["configured stopping metrics pass"; ...
    compose("all reconstructed KKT relative residuals <= %.17g", ...
        config.recursive_full_kkt_residual_tolerance); ...
    "final Stage-A and daily water physical audit passes"];
actual_value = [compose("converged=%s; iterations=%d", ...
        string(ipm.convergence_achieved),ipm.accepted_iteration_count); ...
    compose("worst residual=%.17g",recursiveResidual); ...
    compose("passed=%s; max water violation=%.17g", ...
        string(physicalPass),physical.maximum_water_violation)];
passed = [convergencePass;kktPass;physicalPass];
status = repmat("FAIL",numel(test_id),1);
status(passed) = "PASS";
value = table(repmat(string(context.run_id),numel(test_id),1), ...
    test_id,requirement,actual_value,true(numel(test_id),1),status, ...
    'VariableNames',{'run_id','test_id','requirement','actual_value', ...
    'blocking','status'});
end

function value = worst_recursive_residual(ipm,auditMode)
value = NaN;
if auditMode=="full_kkt" && ~isempty(ipm.direction_audit_history)
    value = max(ipm.direction_audit_history. ...
        recursive_full_kkt_relative_residual);
elseif auditMode=="recursive_only" && ~isempty(ipm.iteration_history)
    value = max(ipm.iteration_history. ...
        recursive_final_kkt_relative_residual);
end
end

function value = solver_wall_seconds(ipm)
if isfield(ipm,"elapsed_seconds"), value = ipm.elapsed_seconds;
else, value = ipm.solver_seconds; end
end

function value = make_issue_log(context,status,ipm,settings)
if status=="PASS"
    value = table(strings(0,1),strings(0,1),strings(0,1), ...
        strings(0,1),strings(0,1),strings(0,1), ...
        'VariableNames',{'run_id','issue_id','severity','status', ...
        'description','next_action'});
    return
end
description = "The configured day-set run did not pass all checks.";
if settings.require_convergence && ~ipm.convergence_achieved
    description = "The four stopping metrics did not all pass within the iteration limit.";
end
value = table(string(context.run_id),"CONFIGURED_RANGE","BLOCKING", ...
    status,description,"Inspect iteration and factor histories.", ...
    'VariableNames',{'run_id','issue_id','severity','status', ...
    'description','next_action'});
end

