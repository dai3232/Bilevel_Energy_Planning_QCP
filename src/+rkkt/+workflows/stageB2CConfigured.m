    dataCache.load_seconds+dataCache.build_seconds+dataCache.write_seconds; ...
    indexCache.load_seconds+indexCache.build_seconds+indexCache.write_seconds; ...
    structureCache.load_seconds+structureCache.build_seconds+ ...
        structureCache.write_seconds; ...
