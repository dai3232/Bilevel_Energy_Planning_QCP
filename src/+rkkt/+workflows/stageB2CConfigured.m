    conclusion,"Review configured run artifacts.", ...
    settings.audit_mode=="full_kkt",false,false, ...
    'VariableNames',{'run_id','milestone','status','conclusion', ...
    'next_action','full_kkt_audit_executed','formal_stage_changed', ...
    'stage_c1_entered'});
end

function persist_runtime_test_evidence(context,acceptance)
inventory = table("B2C-CONFIGURED-RUNTIME", ...
    "src/+rkkt/+workflows/stageB2CConfigured.m", ...
    "configured range, cache, route, water correction and convergence", ...
    'VariableNames',{'test_id','test_file','purpose'});
write_replace_table(context.test_inventory_path,inventory);
results = acceptance(:,["run_id","test_id","status"]);
results.passed = results.status=="PASS";
write_replace_table(context.test_results_csv_path,results);
summary = struct("test_total",height(results), ...
    "test_passed",nnz(results.passed),"test_failed",nnz(~results.passed), ...
    "all_pass",all(results.passed));
rkkt.artifacts.write_json_file(context.test_summary_path,summary);
rkkt.artifacts.write_text_utf8(context.test_command_path, ...
    "RUN_PROJECT.m (configured runtime evidence)");
end

function preserve_failure_artifacts(context,cause,status)
if ~isfile(context.issue_log_path)
    issue = table(string(context.run_id),"WORKFLOW_FAILURE","BLOCKING", ...
        status,string(cause.identifier)+": "+string(cause.message), ...
        "Repair the first failed layer and create a new unique run.", ...
        'VariableNames',{'run_id','issue_id','severity','status', ...
        'description','next_action'});
    rkkt.artifacts.write_table_csv_17g_atomic(context.issue_log_path,issue);
end
if ~isfile(context.acceptance_results_path)
    acceptance = table(string(context.run_id),"workflow_completed", ...
        "no exception",string(cause.identifier),"FAIL", ...
        'VariableNames',{'run_id','test_id','requirement', ...
        'actual_value','status'});
    rkkt.artifacts.write_table_csv_17g_atomic( ...
        context.acceptance_results_path,acceptance);
end
end

