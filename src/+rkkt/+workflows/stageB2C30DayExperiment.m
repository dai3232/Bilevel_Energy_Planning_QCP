function result = stageB2C30DayExperiment(options)
%STAGEB2C30DAYEXPERIMENT Run the day-1-to-30 recursive-only IPM experiment.

arguments
    options.ProjectRoot (1,1) string = ""
    options.RunId (1,1) string = ""
    options.MaxIterations (1,1) double {mustBeInteger,mustBePositive} = 100
    options.RequireConvergence (1,1) logical = true
end

root = options.ProjectRoot;
if strlength(strip(root))==0
    root = rkkt.projectRoot();
end
root = string(java.io.File(char(root)).getCanonicalPath());
config = rkkt.model.load_stage_b2c_configuration( ...
    root,Profile="experimental_30_day");
[inputHashes,inputPass] = rkkt.data.verify_input_hashes(root);
assert(inputPass,"stageB2C:30day:InputHash", ...
    "Controlled input hashes do not match their authority values.");

mode = "convergence_run";
if ~options.RequireConvergence
    mode = "bounded_smoke_run";
end
metadata = struct( ...
    "run_purpose",char(config.run_purpose), ...
    "milestone","B-2C-30-DAY-EXPERIMENT", ...
    "parent_run_id",char(config.parent_run_id), ...
    "actual_test_command","rkkt.workflows.stageB2C30DayExperiment", ...
    "experiment_mode",char(mode), ...
    "optimization_executed",true,"a1_solver_executed",false, ...
    "full_ipm_executed",true,"convergence_evaluated",true, ...
    "convergence_required",options.RequireConvergence, ...
    "convergence_achieved",false, ...
    "time_scope","days_1_to_30_full_24_hours", ...
    "full_kkt_role",char(config.full_kkt_role), ...
    "full_kkt_assembled",false,"full_kkt_solved",false, ...
    "full_kkt_audit_executed",false, ...
    "recursive_direction_executed",true, ...
    "recursive_direction_is_formal_for_experiment",true, ...
    "reconstructed_kkt_residual_gate_enabled",true, ...
    "recursive_refinement_max_passes", ...
        config.recursive_refinement_max_passes, ...
    "water_slack_second_order_correction_enabled",true, ...
    "water_slack_second_order_correction_scope_count", ...
        config.expected_water_inequality_count, ...
    "no_full_direction_fallback",true, ...
    "parallel_executed",false,"annual_scope_executed",false, ...
    "thermal_second_pass_executed",false, ...
    "stage_c1_implemented",false,"stage_c1_entered",false, ...
    "formal_stage_b_acceptance_unchanged",true, ...
    "expected_primal_dimension",config.expected_stage_a_primal_dimension, ...
    "expected_equality_dimension", ...
        config.expected_stage_a_equality_dimension, ...
    "expected_inequality_dimension", ...
        config.expected_stage_a_inequality_dimension+ ...
        config.expected_water_inequality_count, ...
    "expected_reconstructed_full_kkt_dimension", ...
        config.expected_full_kkt_dimension, ...
    "milestone_status","RUNNING");
context = rkkt.artifacts.create_run_context(root,"stage_B", ...
    "RunId",options.RunId,"ModelContractVersion","v1.0", ...
    "InputHashes",input_hash_object(inputHashes), ...
    "EffectiveConfigPath",fullfile(root,"config", ...
        "stage_B_2C_30_day_experiment.yaml"), ...
    "ManifestMetadata",metadata);
diagnosticsDir = fullfile(context.root,"diagnostics");
resultsDir = fullfile(context.root,"results");
ensure_directory(diagnosticsDir);
ensure_directory(resultsDir);

result = struct("run_id",string(context.run_id), ...
    "run_path",string(context.root),"status","RUNNING", ...
    "convergence_achieved",false,"accepted_iteration_count",0, ...
    "recursive_ipm_seconds",NaN,"report_path","", ...
    "error_identifier","","error_message","");

try
    preparationTimer = tic;
    environment = rkkt.diagnostics.inspect_stage_b2b_environment();
    environment = addvars(environment,repmat(string(context.run_id), ...
        height(environment),1),'Before',1,'NewVariableNames','run_id');
    write_new_table(context.environment_csv_path,environment);
    assert(all(environment.status(logical(environment.blocking))=="PASS"), ...
        "stageB2C:30day:Environment", ...
        "A blocking MATLAB environment check failed.");
    write_new_table(context.input_hashes_csv_path, ...
        input_hash_table(inputHashes,context.run_id));

    data = rkkt.data.load_project_data(root);
    waterInput = build_water_input_audit(data,config,context.run_id);
    write_new_table(fullfile(diagnosticsDir,"water_input_audit.csv"), ...
        waterInput);
    assert(height(waterInput)==config.expected_final_water_audit_rows && ...
        all(waterInput.status=="PASS"), ...
        "stageB2C:30day:WaterInput", ...
        "The configured 30-day water-input audit failed.");

    indexTimer = tic;
    index = rkkt.indexing.build_stage_b2c_index( ...
        data,config,"RunId",string(context.run_id));
    indexSeconds = toc(indexTimer);
    persist_index_artifacts(context,index);
    preparationSeconds = toc(preparationTimer);
    dimensionSummary = build_dimension_summary( ...
        context,index,config,indexSeconds,preparationSeconds);
    write_new_table(fullfile(diagnosticsDir,"dimension_summary.csv"), ...
        dimensionSummary);

    ipm = rkkt.solver.run_stage_b2c_30day_ipm( ...
        data,index,config,context,MaxIterations=options.MaxIterations);
    pureIpmComputeSeconds = sum(ipm.timing_history.total_seconds);
    iterationEvidenceSeconds = ipm.elapsed_seconds-pureIpmComputeSeconds;
    rkkt.artifacts.write_json_file(fullfile(diagnosticsDir, ...
        "final_metrics.json"),ipm.final_metrics);

    physicalArrays = rkkt.model.recover_stage_a_physical_arrays( ...
        ipm.final_state.xi,zeros(size(ipm.final_state.xi)),index,data);
    [capacityResults,hourlyResults,dailyResults] = ...
        build_physical_results(context,ipm,index,physicalArrays);
    write_new_table(fullfile(resultsDir,"capacity_results.csv"), ...
        capacityResults);
    write_new_table(fullfile(resultsDir,"hourly_dispatch_results.csv"), ...
        hourlyResults);
    write_new_table(fullfile(resultsDir,"daily_generation_summary.csv"), ...
        dailyResults);
    rkkt.artifacts.save_mat_artifact(fullfile(resultsDir, ...
        "final_state_and_physical.mat"), ...
        "final_state",ipm.final_state,"physical",physicalArrays, ...
        "final_metrics",ipm.final_metrics);
    persist_final_matrix_artifacts(context,ipm);

    physical = struct("passed",false,"maximum_water_violation",NaN);
    if ipm.convergence_achieved
        physical = rkkt.diagnostics.evaluate_stage_b2c_physical_audit( ...
            ipm,index,data,config);
        write_new_table(fullfile(diagnosticsDir, ...
            "final_daily_water_constraint_audit.csv"),physical.water);
        write_new_table(fullfile(context.acceptance_dir, ...
            "physical_audit.csv"),physical.stage_a);
    end

    acceptance = make_acceptance(context,ipm,physical,waterInput, ...
        index,config,options.RequireConvergence);
    write_new_table(context.acceptance_results_path,acceptance);
    experimentPassed = all(acceptance.status=="PASS");
    terminalStatus = "FAIL_RETRYABLE";
    if experimentPassed
        terminalStatus = "PASS";
    end
    issues = make_issue_log(context,terminalStatus,ipm, ...
        options.RequireConvergence);
    write_new_table(context.issue_log_path,issues);
    decision = make_decision(context,terminalStatus,ipm, ...
        options.RequireConvergence);
    write_new_table(context.decision_log_path,decision);
    persist_runtime_test_evidence(context,acceptance);

    rkkt.artifacts.update_running_run_manifest(context,struct( ...
        "milestone_status",char(terminalStatus), ...
        "experiment_completed",true, ...
        "experiment_passed",experimentPassed, ...
        "convergence_achieved",ipm.convergence_achieved, ...
        "accepted_iteration_count",ipm.accepted_iteration_count, ...
        "recursive_ipm_seconds",pureIpmComputeSeconds, ...
        "recursive_ipm_compute_seconds",pureIpmComputeSeconds, ...
        "iteration_loop_wall_seconds",ipm.elapsed_seconds, ...
        "iteration_evidence_io_seconds",iterationEvidenceSeconds, ...
        "index_build_seconds",indexSeconds, ...
        "preparation_seconds",preparationSeconds, ...
        "full_kkt_assembled",false,"full_kkt_solved",false, ...
        "full_kkt_audit_executed",false, ...
        "recursive_final_kkt_relative_residual", ...
            max(ipm.iteration_history. ...
                recursive_final_kkt_relative_residual), ...
        "final_primal_equality_inf", ...
            ipm.final_metrics.primal_equality_inf, ...
        "final_primal_inequality_inf", ...
            ipm.final_metrics.primal_inequality_inf, ...
        "final_dual_scaled_inf",ipm.final_metrics.dual_scaled_inf, ...
        "final_mean_lz_scaled",ipm.final_metrics.mean_lz_scaled, ...
        "final_physical_audit_executed",ipm.convergence_achieved, ...
        "final_physical_audit_passed", ...
            ipm.convergence_achieved && physical.passed));

    report = rkkt.reporting.generate_stage_b2c_30day_experiment_report( ...
        context.root);
    [reportValid,reportDetails] = ...
        rkkt.reporting.validate_docx_package(report.path);
    reportValidation = table(string(context.run_id),string(report.path), ...
        reportValid,conditional_status(reportValid), ...
        strjoin(string(reportDetails.errors)," | "), ...
        'VariableNames',{'run_id','path','package_valid','status','details'});
    write_new_table(fullfile(context.reports_dir, ...
        "report_structure_validation.csv"),reportValidation);
    assert(reportValid,"stageB2C:30day:Report", ...
        "The Chinese experiment report failed DOCX package validation.");

    manifest = rkkt.artifacts.finalize_run_manifest( ...
        context,terminalStatus,struct( ...
        "reports_generated",true,"report_structure_validated",true, ...
        "report_relative_path",char(erase(string(report.path), ...
            string(context.root)+filesep)), ...
        "report_sha256",char(rkkt.data.compute_sha256_file(report.path))));
    result.status = string(manifest.status);
    result.convergence_achieved = ipm.convergence_achieved;
    result.accepted_iteration_count = ipm.accepted_iteration_count;
    result.recursive_ipm_seconds = pureIpmComputeSeconds;
    result.report_path = string(report.path);
catch cause
    finalStatus = "FAIL_RETRYABLE";
    if contains(string(cause.identifier),["Environment","InputHash"])
        finalStatus = "BLOCKED_EXTERNAL";
    elseif contains(string(cause.identifier),"ModelDecision")
        finalStatus = "NEEDS_MODEL_DECISION";
    end
    preserve_failure_artifacts(context,cause,finalStatus);
    try
        manifest = jsondecode(fileread(context.run_manifest_path));
        if string(manifest.status)=="RUNNING"
            rkkt.artifacts.finalize_run_manifest(context,finalStatus,struct( ...
                "milestone_status",char(finalStatus), ...
                "experiment_completed",false, ...
                "experiment_passed",false, ...
                "failure_identifier",char(string(cause.identifier)), ...
                "failure_message",char(string(cause.message))));
        end
    catch
    end
    result.status = finalStatus;
    result.error_identifier = string(cause.identifier);
    result.error_message = string(cause.message);
end
end

function value = build_water_input_audit(data,config,runId)
n = numel(config.days)*numel(config.hydro_ids);
run_id = repmat(string(runId),n,1);
day = repelem(config.days(:),numel(config.hydro_ids));
hydro_id = repmat(config.hydro_ids(:),numel(config.days),1);
water_a = zeros(n,1); water_b = zeros(n,1); water_c = zeros(n,1);
water_min_m3 = zeros(n,1); water_max_m3 = zeros(n,1);
max_output_mw = zeros(n,1); all_finite = false(n,1);
min_not_above_max = false(n,1); nonnegative_bounds = false(n,1);
status = repmat("FAIL",n,1);
for row = 1:n
    h = hydro_id(row); d = day(row);
    water_a(row) = data.base.hydro.waterA(h);
    water_b(row) = data.base.hydro.waterB(h);
    water_c(row) = data.base.hydro.waterC(h);
    max_output_mw(row) = data.base.hydro.maxOutputMW(h);
    water_min_m3(row) = data.timeseries.hydroWaterMin(d,h);
    water_max_m3(row) = data.timeseries.hydroWaterMax(d,h);
    all_finite(row) = all(isfinite([water_a(row),water_b(row), ...
        water_c(row),max_output_mw(row),water_min_m3(row), ...
        water_max_m3(row)]));
    min_not_above_max(row) = water_min_m3(row)<=water_max_m3(row);
    nonnegative_bounds(row) = water_min_m3(row)>=0 && ...
        water_max_m3(row)>=0 && max_output_mw(row)>0;
    if all_finite(row) && min_not_above_max(row) && ...
            nonnegative_bounds(row)
        status(row) = "PASS";
    end
end
value = table(run_id,day,hydro_id,water_a,water_b,water_c, ...
    water_min_m3,water_max_m3,max_output_mw,all_finite, ...
    min_not_above_max,nonnegative_bounds,status);
end

function value = build_dimension_summary(context,index,config,indexSeconds,prepSeconds)
metric = ["days";"hours_per_day";"primal_variables";"equalities"; ...
    "base_inequalities";"water_inequalities";"total_inequalities"; ...
    "reconstructed_full_kkt_dimension";"daily_joint_block_count"; ...
    "global_core_dimension";"fixed_zero_count";"index_build_seconds"; ...
    "preparation_seconds"];
actual_value = [numel(config.days);numel(config.hours); ...
    index.counts.variables;index.counts.equalities; ...
    config.expected_stage_a_inequality_dimension; ...
    index.counts.water_inequalities;index.counts.inequalities; ...
    index.counts.full_kkt_dimension;numel(config.days); ...
    config.expected_global_core_dimension;height(index.fixed_zero_map); ...
    indexSeconds;prepSeconds];
value = table(repmat(string(context.run_id),numel(metric),1), ...
    metric,actual_value,'VariableNames',{'run_id','metric','actual_value'});
end

