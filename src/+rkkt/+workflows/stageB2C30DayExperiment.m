function preserve_failure_artifacts(context,cause,status)
if ~isfile(context.issue_log_path)
    issue = table(string(context.run_id),"WORKFLOW_FAILURE","BLOCKING", ...
        status,string(cause.identifier)+": "+string(cause.message), ...
        "Repair the first failed layer and create a new unique run.", ...
        'VariableNames',{'run_id','issue_id','severity','status', ...
        'description','next_action'});
    rkkt.artifacts.write_table_csv_17g_atomic(context.issue_log_path,issue);
end
if ~isfile(context.acceptance_results_path)
    acceptance = table(string(context.run_id),"workflow_completed", ...
        "no exception",string(cause.identifier),"FAIL", ...
        'VariableNames',{'run_id','test_id','requirement', ...
        'actual_value','status'});
    rkkt.artifacts.write_table_csv_17g_atomic( ...
        context.acceptance_results_path,acceptance);
end
end

function value = input_hash_object(hashes)
base = hashes.fileName=="基础参数.xlsx";
series = hashes.fileName=="输入数据.xlsx";
assert(nnz(base)==1 && nnz(series)==1,"stageB2C:30day:InputHashRows", ...
    "Both controlled input rows are required.");
value = struct("base_parameters",char(hashes.actualSHA256(base)), ...
    "timeseries",char(hashes.actualSHA256(series)));
end

function value = input_hash_table(hashes,runId)
n = height(hashes);
value = table(repmat(string(runId),n,1),string(hashes.fileName), ...
    "inputs/raw/"+string(hashes.fileName),double(hashes.expectedBytes), ...
    double(hashes.actualBytes),string(hashes.expectedSHA256), ...
    string(hashes.actualSHA256),string(hashes.status), ...
    'VariableNames',{'run_id','file_name','relative_path','expected_bytes', ...
    'actual_bytes','expectedSHA256','actualSHA256','status'});
end

function ensure_directory(pathValue)
if isfolder(pathValue), return; end
[created,message] = mkdir(pathValue);
assert(created,"stageB2C:30day:Directory","%s",message);
end

function write_new_table(pathValue,value)
assert(~isfile(pathValue) && ~isfolder(pathValue), ...
    "stageB2C:30day:ArtifactExists","Refusing to overwrite %s.",pathValue);
rkkt.artifacts.write_table_csv_17g(pathValue,value);
end

function value = conditional_status(passed)
if passed, value = "PASS"; else, value = "FAIL"; end
end

function value = conditional_text(condition,whenTrue,whenFalse)
if condition, value = string(whenTrue); else, value = string(whenFalse); end
end
