function [capacity,hourly,daily] = build_physical_results( ...
        context,ipm,index,physical)
names = string(ipm.final_linearization.capacity_parameters.names(:));
values = ipm.final_state.xi(ipm.final_linearization.maps.q_global);
capacity = table(repmat(string(context.run_id),14,1),(1:14).', ...
    names,values,'VariableNames',{'run_id','capacity_index', ...
    'capacity_name','value'});

nDays = numel(physical.days); nHours = numel(physical.hours);
n = nDays*nHours; day = zeros(n,1); hour = zeros(n,1);
arrays = cell(1,24);
for k = 1:24
    arrays{k} = zeros(n,1);
end
row = 0;
for d = 1:nDays
    for t = 1:nHours
        row = row+1; day(row) = physical.days(d); hour(row) = physical.hours(t);
        atHour = [reshape(physical.value.wind(d,t,:),1,[]), ...
            reshape(physical.value.solar(d,t,:),1,[]), ...
            reshape(physical.value.hydro(d,t,:),1,[]), ...
            reshape(physical.value.thermal(d,t,:),1,[]), ...
            reshape(physical.value.charge(d,t,:),1,[]), ...
            reshape(physical.value.discharge(d,t,:),1,[]), ...
            reshape(physical.value.soc(d,t,:),1,[])];
        for k = 1:24
            arrays{k}(row) = atHour(k);
        end
    end
end
variableNames = ["PW_1","PW_2","PW_3","PW_4","PW_5", ...
    "PP_1","PP_2","PP_3","PP_4","PP_5", ...
    "PH_1","PH_2","PH_3","PH_4", ...
    "PF_1","PF_2","PF_3","PF_4", ...
    "Pch_1","Pch_2","Pdis_1","Pdis_2","SOC_1","SOC_2"];
hourly = table(repmat(string(context.run_id),n,1),day,hour, ...
    'VariableNames',{'run_id','day','hour'});
for k = 1:numel(variableNames)
    hourly.(variableNames(k)) = arrays{k};
end
assert(height(hourly)==n && width(hourly)==27 && ...
    height(index.variable_index)==ipm.final_linearization.counts.primal, ...
    "stageB2C:30day:Results", ...
    "The configured physical result table is incomplete.");

wind_mwh = squeeze(sum(physical.value.wind,[2,3]));
solar_mwh = squeeze(sum(physical.value.solar,[2,3]));
hydro_mwh = squeeze(sum(physical.value.hydro,[2,3]));
thermal_mwh = squeeze(sum(physical.value.thermal,[2,3]));
charge_mwh = squeeze(sum(physical.value.charge,[2,3]));
discharge_mwh = squeeze(sum(physical.value.discharge,[2,3]));
total_generation_mwh = wind_mwh+solar_mwh+hydro_mwh+thermal_mwh;
net_storage_supply_mwh = discharge_mwh-charge_mwh;
daily = table(repmat(string(context.run_id),nDays,1), ...
    physical.days(:),wind_mwh,solar_mwh,hydro_mwh,thermal_mwh, ...
    charge_mwh,discharge_mwh,net_storage_supply_mwh, ...
    total_generation_mwh, ...
    'VariableNames',{'run_id','day','wind_mwh','solar_mwh', ...
    'hydro_mwh','thermal_mwh','storage_charge_mwh', ...
    'storage_discharge_mwh','net_storage_supply_mwh', ...
    'total_generation_mwh'});
end

function persist_final_matrix_artifacts(context,ipm)
pathValue = fullfile(context.matrices_dir,"final_recursive_operators.mat");
lin = ipm.final_linearization;
core = ipm.last_core;
rkkt.artifacts.save_mat_artifact(pathValue,"H",lin.H,"A",lin.A, ...
    "G",lin.G,"global_core_matrix",core.matrix, ...
    "global_core_rhs",core.rhs,"global_core_solution",core.solution, ...
    "linearization_identity",lin.identity);
matrix_name = ["H_L";"A";"G";"global_core_16"];
matrices = {lin.H;lin.A;lin.G;core.matrix};
row_count = zeros(4,1); column_count = zeros(4,1);
nonzero_count = zeros(4,1);
for k = 1:4
    [row_count(k),column_count(k)] = size(matrices{k});
    nonzero_count(k) = nnz(matrices{k});
end
manifest = table(repmat(string(context.run_id),4,1),matrix_name, ...
    ["recursive_shared";"recursive_shared";"recursive_shared"; ...
    "recursive_formal"],row_count,column_count,nonzero_count, ...
    true(4,1),repmat("matrices/final_recursive_operators.mat",4,1), ...
    repmat(rkkt.data.compute_sha256_file(pathValue),4,1), ...
    repmat(string(lin.identity),4,1),repmat("PASS",4,1), ...
    'VariableNames',{'run_id','matrix_name','role','row_count', ...
    'column_count','nonzero_count','is_sparse','artifact_path','sha256', ...
    'linearization_identity','status'});
write_new_table(context.matrix_manifest_path,manifest);
end

function value = make_acceptance(context,ipm,physical,waterInput,index, ...
        config,requireConvergence)
iterations = ipm.iteration_history;
factors = ipm.factorization_history;
correction = ipm.water_correction_history;
accepted = ipm.accepted_iteration_count;
routePass = accepted>0 && all(~iterations.full_kkt_audit_executed) && ...
    all(iterations.recursive_final_kkt_relative_residual<= ...
        config.recursive_full_kkt_residual_tolerance);
factorPass = height(factors)==accepted*(numel(config.days)+1) && ...
    all(factors.factorization_count==1) && ...
    all(factors.refinement_additional_factorization_count==0) && ...
    all(~factors.blocking_warning_present) && all(factors.solution_finite);
correctionPass = height(correction)== ...
    accepted*config.expected_water_inequality_count && ...
    all(correction.strictly_positive);
fixedPass = all(iterations.fixed_zero_count== ...
    config.expected_stage_a_fixed_zero_count) && ...
    all(iterations.fixed_zero_exact);
convergencePass = ~requireConvergence || ipm.convergence_achieved;
physicalPass = ~ipm.convergence_achieved || physical.passed;
test_id = ["EXP-DATA";"EXP-INDEX";"EXP-ROUTE";"EXP-FACTORS"; ...
    "EXP-WATER-CORRECTION";"EXP-FIXED-ZERO";"EXP-CONVERGENCE"; ...
    "EXP-PHYSICAL"];
requirement = ["120 water-input rows pass"; ...
    "15910/2642/31220 and reconstructed dimension 80992"; ...
    "recursive direction only; reconstructed KKT residual <= 1e-10"; ...
    "30 daily LDL solves plus one 16-D core solve per iteration; no refactorization during residual correction"; ...
    "240 exact second-order water-slack corrections per iteration"; ...
    "1804 removed renewable entries remain exact zero"; ...
    conditional_text(requireConvergence, ...
        "four stopping metrics <= 1e-6","bounded smoke update completed"); ...
    "if converged, final water and Stage-A physical audit passes"];
actual_value = [string(height(waterInput))+" rows"; ...
    compose("%d/%d/%d; reconstructed=%d",index.counts.variables, ...
        index.counts.equalities,index.counts.inequalities, ...
        index.counts.full_kkt_dimension); ...
    compose("audit=false; worst residual=%.17g", ...
        max(iterations.recursive_final_kkt_relative_residual)); ...
    string(height(factors))+" factor records; refinement triggers="+ ...
        string(nnz(factors.refinement_triggered)); ...
    string(height(correction))+" correction records"; ...
    string(max(iterations.fixed_zero_count))+" exact zeros"; ...
    compose("converged=%s; iterations=%d", ...
        string(ipm.convergence_achieved),accepted); ...
    conditional_text(ipm.convergence_achieved, ...
        compose("passed=%s; max water violation=%.17g", ...
            string(physical.passed),physical.maximum_water_violation), ...
        "not executed before convergence")];
passed = [height(waterInput)==config.expected_final_water_audit_rows && ...
        all(waterInput.status=="PASS"); ...
    index.counts.variables==config.expected_stage_a_primal_dimension && ...
        index.counts.equalities==config.expected_stage_a_equality_dimension && ...
        index.counts.inequalities==config.expected_stage_a_inequality_dimension+ ...
            config.expected_water_inequality_count && ...
        index.counts.full_kkt_dimension==config.expected_full_kkt_dimension; ...
    routePass;factorPass;correctionPass;fixedPass; ...
    convergencePass;physicalPass];
status = repmat("FAIL",numel(test_id),1); status(passed) = "PASS";
value = table(repmat(string(context.run_id),numel(test_id),1), ...
    test_id,requirement,actual_value,true(numel(test_id),1),status, ...
    'VariableNames',{'run_id','test_id','requirement','actual_value', ...
    'blocking','status'});
end

function value = make_issue_log(context,status,ipm,requireConvergence)
if status=="PASS"
    value = table(strings(0,1),strings(0,1),strings(0,1), ...
        strings(0,1),strings(0,1),strings(0,1), ...
        'VariableNames',{'run_id','issue_id','severity','status', ...
        'description','next_action'});
    return
end
description = "30-day recursive experiment did not satisfy all checks.";
if requireConvergence && ~ipm.convergence_achieved
    description = "The four stopping metrics did not all pass within the iteration limit.";
end
value = table(string(context.run_id),"30DAY_EXPERIMENT", ...
    "BLOCKING",status,description,"Inspect iteration and factor histories.", ...
    'VariableNames',{'run_id','issue_id','severity','status', ...
    'description','next_action'});
end

function value = make_decision(context,status,ipm,requireConvergence)
conclusion = "The bounded 30-day recursive smoke update completed.";
nextAction = "Run the convergence experiment without changing the formal seven-day flow.";
if requireConvergence
    conclusion = "The 30-day recursive IPM experiment completed; convergence="+ ...
        string(ipm.convergence_achieved)+".";
    nextAction = "Review capacities and daily dispatch; formal Stage-B acceptance remains unchanged.";
end
