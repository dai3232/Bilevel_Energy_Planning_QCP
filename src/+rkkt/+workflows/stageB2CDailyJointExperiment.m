function value = direction_audit_table(context,oldControl,newControl, ...
        oldStress,newStress)
audits = {oldControl;newControl;oldStress;newStress};
point = ["control";"control";"stress";"stress"];
route = ["existing_recursive_border";"daily_joint_full_elimination"; ...
    "existing_recursive_border";"daily_joint_full_elimination"];
