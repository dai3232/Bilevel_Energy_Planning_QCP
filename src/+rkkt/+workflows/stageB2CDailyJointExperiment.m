tests = rkkt.testing.run_fixed_test_inventory_with_evidence( ...
    root,"tests/unit/test_stage_b2c_daily_joint_block.m", ...
    fullfile(root,"tests", ...
        "stage_B_2C_daily_joint_experiment_inventory.csv"), ...
    EvidenceDirectory=string(context.tests_dir), ...
    CommandText="runtests tests/unit/test_stage_b2c_daily_joint_block.m", ...
    SuiteLabel="stage_B_2C_daily_joint_experiment");
end

function tableValue = run_code_analyzer(root)
relativeFiles = [ ...
    "src/+rkkt/+solver/eliminate_stage_b2c_all_inequality_directions.m"
    "src/+rkkt/+solver/partition_stage_b2c_daily_joint_system.m"
    "src/+rkkt/+solver/solve_stage_b2c_daily_joint_block.m"
    "src/+rkkt/+solver/solve_stage_b2c_daily_joint_day.m"
    "src/+rkkt/+solver/recover_stage_b2c_daily_joint_direction.m"
    "src/+rkkt/+solver/solve_stage_b2c_daily_joint_direction.m"
    "src/+rkkt/+diagnostics/load_stage_b2c_daily_joint_frozen_points.m"
    "src/+rkkt/+reporting/generate_stage_b2c_daily_joint_experiment_report.m"
    "src/+rkkt/+workflows/stageB2CDailyJointExperiment.m"
    "tests/unit/test_stage_b2c_daily_joint_block.m"];
findingCount = zeros(numel(relativeFiles),1);
status = strings(numel(relativeFiles),1);
for k = 1:numel(relativeFiles)
    findings = checkcode(fullfile(root,relativeFiles(k)),"-id");
    findingCount(k) = numel(findings);
    status(k) = conditional_status(isempty(findings));
end
tableValue = table(relativeFiles,findingCount,status, ...
    'VariableNames',{'file','finding_count','status'});
end

