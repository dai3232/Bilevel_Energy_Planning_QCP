function value = write_evidence_hashes(runRoot,pathValue)
files = dir(fullfile(runRoot,"**","*"));
files = files(~[files.isdir]);
absolute = strings(0,1);
relative = strings(0,1);
for k = 1:numel(files)
    current = string(fullfile(files(k).folder,files(k).name));
    currentRelative = replace(current,string(runRoot)+filesep,"");
    if current==string(pathValue) || currentRelative=="run_manifest.json"
        continue
    end
    absolute(end+1,1) = current; %#ok<AGROW>
    relative(end+1,1) = currentRelative; %#ok<AGROW>
end
[relative,order] = sort(relative);
absolute = absolute(order);
sha256 = strings(numel(absolute),1);
for k = 1:numel(absolute)
    sha256(k) = rkkt.data.compute_sha256_file(absolute(k));
end
value = table(relative,sha256, ...
    'VariableNames',{'relative_path','sha256'});
rkkt.artifacts.write_table_csv_17g(pathValue,value);
end

