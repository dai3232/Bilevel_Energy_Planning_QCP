function value = single_day_gate_table(context,day,response,status,message)
if status=="PASS"
    factor = response.factor;
    structuralRank = factor.structural_rank;
    maximumResidual = factor.maximum_column_relative_residual;
    minimumPivot = factor.minimum_absolute_pivot_eigenvalue;
    pivotDynamicRange = factor.pivot_dynamic_range;
    rhsCount = response.rhs_count;
else
    structuralRank = sprank(day.matrix);
    maximumResidual = NaN;
    minimumPivot = NaN;
    pivotDynamicRange = NaN;
    rhsCount = 15;
end
value = table(string(context.run_id),"stress",day.day_id, ...
    day.dimension,day.nnz,structuralRank,rhsCount,maximumResidual, ...
    minimumPivot,pivotDynamicRange,day.maximum_water_l_over_z, ...
    day.water_eta_dimension,string(status),string(message), ...
    'VariableNames',{'run_id','point','day_id','dimension','nnz', ...
    'structural_rank','rhs_count','maximum_rhs_relative_residual', ...
    'minimum_absolute_pivot','pivot_dynamic_range', ...
    'maximum_water_l_over_z','water_eta_dimension','status','message'});
end

