function result = stageB2CDailyJointExperiment(options)
%STAGEB2CDAILYJOINTEXPERIMENT Run the approved frozen-direction experiment.

arguments
    options.ProjectRoot (1,1) string = ""
    options.RunId (1,1) string = ""
end

root = options.ProjectRoot;
if strlength(strip(root))==0
    root = rkkt.projectRoot();
end
root = string(java.io.File(char(root)).getCanonicalPath());
sourceRunId = "20260807_145804_stage_B_2C_4168a6e9";
sourceRoot = fullfile(root,"runs",sourceRunId);
sourceManifest = jsondecode(fileread(fullfile(sourceRoot,"run_manifest.json")));
[inputHashes,inputPass] = rkkt.data.verify_input_hashes(root);
assert(inputPass,"stageB2C:dailyJoint:InputHash", ...
    "Controlled input hashes do not match their authority values.");

metadata = struct( ...
    "run_purpose","stage_B_2C_frozen_daily_joint_direction_experiment", ...
    "milestone","B-2C-DAILY-JOINT-EXPERIMENT", ...
    "parent_run_id",char(sourceRunId), ...
    "historical_source_commit",char(string(sourceManifest.git_commit)), ...
    "actual_test_command", ...
        "rkkt.workflows.stageB2CDailyJointExperiment", ...
    "optimization_executed",false,"a1_solver_executed",false, ...
    "full_ipm_executed",false,"state_update_executed",false, ...
    "convergence_evaluated",false,"convergence_claimed",false, ...
    "full_kkt_role","audit_only_outside_timing", ...
    "recursive_direction_executed",true, ...
    "daily_joint_direction_executed",false, ...
    "no_full_direction_fallback",true, ...
    "full_direction_consumed_by_daily_joint",false, ...
    "parallel_executed",false,"annual_scope_executed",false, ...
    "thermal_second_pass_executed",false, ...
    "stage_c1_implemented",false,"stage_c1_entered",false, ...
    "warmup_count_per_route_and_point",1, ...
    "timed_count_per_route_and_point",1, ...
    "milestone_status","RUNNING");
context = rkkt.artifacts.create_run_context(root,"stage_B", ...
    "RunId",options.RunId,"ModelContractVersion","v1.0", ...
    "InputHashes",input_hash_object(inputHashes), ...
    "EffectiveConfigPath",fullfile(root,"config", ...
        "stage_B_2C_daily_joint_experiment.yaml"), ...
    "ManifestMetadata",metadata);
diagnosticsDir = fullfile(context.root,"diagnostics");
resultsDir = fullfile(context.root,"results");
ensure_directory(diagnosticsDir);
ensure_directory(resultsDir);

result = struct("run_id",string(context.run_id), ...
    "run_path",string(context.root),"status","RUNNING", ...
    "manifest",struct(),"report_path","", ...
    "error_identifier","","error_message","");
try
    environment = rkkt.diagnostics.inspect_stage_b2b_environment();
    environment = addvars(environment,repmat(string(context.run_id), ...
        height(environment),1),'Before',1,'NewVariableNames','run_id');
    write_new_table(context.environment_csv_path,environment);
    assert(all(environment.status(logical(environment.blocking))=="PASS"), ...
        "stageB2C:dailyJoint:Environment", ...
        "A blocking MATLAB environment check failed.");
    write_new_table(context.input_hashes_csv_path, ...
        input_hash_table(inputHashes,context.run_id));

    tests = run_targeted_tests(root,context);
    analyzer = run_code_analyzer(root);
    write_new_table(fullfile(context.tests_dir,"code_analyzer.csv"),analyzer);
    assert(tests.all_pass && all(analyzer.status=="PASS"), ...
        "stageB2C:dailyJoint:DevelopmentChecks", ...
        "A targeted test or Code Analyzer check failed.");

    frozen = rkkt.diagnostics.load_stage_b2c_daily_joint_frozen_points( ...
        root,sourceRunId);
    identityTable = checkpoint_identity_table(context,frozen);
    write_new_table(fullfile(diagnosticsDir,"checkpoint_identity.csv"), ...
        identityTable);
    sourceTable = source_artifact_table(context,frozen);
    write_new_table(fullfile(diagnosticsDir,"source_artifacts.csv"), ...
        sourceTable);
    persist_index_artifacts(context,frozen.index);
    write_checkpoint_references(context,frozen);

    stressReduced = ...
        rkkt.solver.eliminate_stage_b2c_all_inequality_directions( ...
            frozen.stress.linearization);
    stressPartition = ...
        rkkt.solver.partition_stage_b2c_daily_joint_system( ...
            frozen.stress.linearization,stressReduced);
    [~,worstPosition] = max( ...
        [stressPartition.day.maximum_water_l_over_z]);
    worstDay = stressPartition.day(worstPosition);
    stressBlockPath = fullfile(context.matrices_dir, ...
        "stress_worst_daily_joint_block.mat");
    rkkt.artifacts.save_mat_artifact(stressBlockPath, ...
        "matrix",worstDay.matrix,"rhs",worstDay.rhs, ...
        "capacity_coupling",worstDay.capacity_coupling, ...
        "day_id",worstDay.day_id, ...
        "linearization_identity",worstDay.linearization_identity);
    try
        worstResponse = rkkt.solver.solve_stage_b2c_daily_joint_day( ...
            worstDay, ...
            SymmetryTolerance=frozen.config.reduced_symmetry_tolerance, ...
            ResidualTolerance= ...
                frozen.config.recursive_full_kkt_residual_tolerance);
        gateTable = single_day_gate_table(context,worstDay,worstResponse, ...
            "PASS","");
    catch gateCause
        gateTable = single_day_gate_table(context,worstDay,struct(), ...
            "FAIL",string(gateCause.identifier)+": "+ ...
                string(gateCause.message));
        write_new_table(fullfile(diagnosticsDir,"single_day_gate.csv"), ...
            gateTable);
        if contains(string(gateCause.identifier),"ModelDecision")
            throw(MException( ...
                "stageB2C:dailyJoint:ModelDecisionDailyBlock", ...
                "%s",char(gateCause.message)));
        end
        rethrow(gateCause)
    end
    write_new_table(fullfile(diagnosticsDir,"single_day_gate.csv"), ...
        gateTable);

    [oldControl,oldControlSeconds] = warm_and_time(@() ...
        solve_existing(frozen.control.linearization,frozen.config));
    [newControl,newControlSeconds] = warm_and_time(@() ...
        solve_daily_joint(frozen.control.linearization,frozen.config));
    [oldStress,oldStressSeconds] = warm_and_time(@() ...
        solve_existing(frozen.stress.linearization,frozen.config));
    [newStress,newStressSeconds] = warm_and_time(@() ...
        solve_daily_joint(frozen.stress.linearization,frozen.config));

    fullControl = rkkt.solver.solve_stage_b2b_full_kkt_direction( ...
        frozen.control.linearization);
    fullStress = rkkt.solver.solve_stage_b2b_full_kkt_direction( ...
        frozen.stress.linearization);
    oldControlAudit = direction_audit( ...
        fullControl,oldControl,frozen.control.linearization,frozen.config);
    newControlAudit = direction_audit( ...
        fullControl,newControl,frozen.control.linearization,frozen.config);
    oldStressAudit = direction_audit( ...
        fullStress,oldStress,frozen.stress.linearization,frozen.config);
    newStressAudit = direction_audit( ...
        fullStress,newStress,frozen.stress.linearization,frozen.config);

    directionTable = direction_audit_table(context, ...
        oldControlAudit,newControlAudit,oldStressAudit,newStressAudit);
    write_new_table(fullfile(diagnosticsDir,"direction_equivalence.csv"), ...
        directionTable);
    timingTable = solver_timing_table(context, ...
        oldControlSeconds,newControlSeconds,oldStressSeconds, ...
        newStressSeconds,oldControlAudit,newControlAudit, ...
        oldStressAudit,newStressAudit);
    write_new_table(fullfile(diagnosticsDir,"solver_timing.csv"), ...
        timingTable);
    dayTable = daily_diagnostics_table(context,newControl,newStress);
    write_new_table(fullfile(diagnosticsDir, ...
        "daily_joint_block_diagnostics.csv"),dayTable);

    controlCorePath = fullfile(context.matrices_dir,"control_core16.mat");
    stressCorePath = fullfile(context.matrices_dir,"stress_core16.mat");
    rkkt.artifacts.save_mat_artifact(controlCorePath, ...
        "matrix",newControl.core.matrix,"rhs",newControl.core.rhs, ...
        "solution",newControl.core.solution);
    rkkt.artifacts.save_mat_artifact(stressCorePath, ...
        "matrix",newStress.core.matrix,"rhs",newStress.core.rhs, ...
        "solution",newStress.core.solution);
    directionsPath = fullfile(resultsDir,"frozen_direction_results.mat");
    directionResults = compact_direction_results( ...
        oldControl,newControl,fullControl,oldStress,newStress,fullStress, ...
        oldControlAudit,newControlAudit,oldStressAudit,newStressAudit);
    rkkt.artifacts.save_mat_artifact(directionsPath, ...
        "directionResults",directionResults,"timing",timingTable, ...
        "checkpointIdentity",identityTable);
    matrixManifest = matrix_manifest(context,stressBlockPath, ...
        controlCorePath,stressCorePath,worstDay,newControl,newStress);
    write_new_table(context.matrix_manifest_path,matrixManifest);

    acceptance = acceptance_table(context,frozen,gateTable, ...
        newControl,newStress,oldControlAudit,newControlAudit, ...
        oldStressAudit,newStressAudit,tests,analyzer);
    write_new_table(context.acceptance_results_path,acceptance);
    assert(all(acceptance.status=="PASS"), ...
        "stageB2C:dailyJoint:Acceptance", ...
        "A blocking daily-joint experiment acceptance item failed.");
    write_new_table(context.issue_log_path,empty_issue_log());
    decision = table(string(context.run_id), ...
        "B-2C-DAILY-JOINT-EXPERIMENT","PASS", ...
        "Frozen directions 34 and 35 passed the fully eliminated daily-joint route.", ...
        "USER_REVIEW_BEFORE_PRODUCTION_ROUTE_MIGRATION", ...
        false,false, ...
        'VariableNames',{'run_id','milestone','status','conclusion', ...
        'next_action','full_ipm_executed','stage_c1_entered'});
    write_new_table(context.decision_log_path,decision);

    rkkt.artifacts.update_running_run_manifest(context,struct( ...
        "tests_executed",true,"test_total",tests.summary.test_total, ...
        "test_passed",tests.summary.test_passed,"test_failed",0, ...
        "code_analyzer_findings",sum(analyzer.finding_count), ...
        "daily_joint_direction_executed",true, ...
        "single_day_gate_passed",true,"seven_day_response_count",7, ...
        "global_core_dimension",16, ...
        "control_daily_joint_direction_passed",newControlAudit.all_pass, ...
        "stress_daily_joint_direction_passed",newStressAudit.all_pass, ...
        "control_existing_recursive_passed",oldControlAudit.all_pass, ...
        "stress_existing_recursive_passed",oldStressAudit.all_pass, ...
        "control_existing_recursive_seconds",oldControlSeconds, ...
        "control_daily_joint_seconds",newControlSeconds, ...
        "stress_existing_recursive_seconds",oldStressSeconds, ...
        "stress_daily_joint_seconds",newStressSeconds, ...
        "milestone_status","PASS","stage_b_complete",false));

    report = rkkt.reporting.generate_stage_b2c_daily_joint_experiment_report( ...
        context.root);
    [reportValid,reportValidation] = ...
        rkkt.reporting.validate_docx_package(report.path);
    reportStructure = table(string(context.run_id),string(report.path), ...
        reportValid,conditional_status(reportValid), ...
        strjoin(string(reportValidation.errors),"; "), ...
        'VariableNames',{'run_id','path','valid','status','details'});
    write_new_table(fullfile(context.reports_dir, ...
        "report_structure_validation.csv"),reportStructure);
    assert(reportValid,"stageB2C:dailyJoint:Report", ...
        "The Chinese experiment report failed DOCX validation.");
    visual = rkkt.reporting.render_stage_b2c_report_external( ...
        context.root,report.path);
    write_new_table(fullfile(context.reports_dir,"report_visual_qa.csv"), ...
        visual);
    reportHash = rkkt.data.compute_sha256_file(report.path);
    write_new_table(fullfile(context.reports_dir,"report_sha256.csv"), ...
        table(string(context.run_id), ...
        "reports/阶段B-2C_日内联合方向冻结点实验报告.docx", ...
        string(reportHash),"PASS", ...
        'VariableNames',{'run_id','relative_path','sha256','status'}));

    evidence = write_evidence_hashes(context.root,fullfile( ...
        context.acceptance_dir,"evidence_hashes.csv"));
    manifest = rkkt.artifacts.finalize_run_manifest(context,"PASS",struct( ...
        "milestone_status","PASS","stage_b_complete",false, ...
        "full_ipm_executed",false,"state_update_executed",false, ...
        "convergence_evaluated",false,"convergence_claimed",false, ...
        "stage_c1_implemented",false,"stage_c1_entered",false, ...
        "reports_generated",true,"report_structure_validated",true, ...
        "report_visual_qa_status",char(string(visual.status)), ...
        "report_relative_path", ...
            "reports/阶段B-2C_日内联合方向冻结点实验报告.docx", ...
        "report_sha256",char(reportHash), ...
        "evidence_file_count",height(evidence)));
    rkkt.artifacts.update_run_index(context,manifest);
    result.status = "PASS";
    result.manifest = manifest;
    result.report_path = string(report.path);
    result.acceptance = acceptance;
    result.timing = timingTable;
    result.direction_equivalence = directionTable;
catch cause
    finalStatus = "FAIL_RETRYABLE";
    if contains(string(cause.identifier),"ModelDecision")
        finalStatus = "NEEDS_MODEL_DECISION";
    elseif contains(string(cause.identifier),["Environment","InputHash"])
        finalStatus = "BLOCKED_EXTERNAL";
    end
    ensure_failure_artifacts(context,cause,finalStatus);
    try
        report = ...
            rkkt.reporting.generate_stage_b2c_daily_joint_experiment_report( ...
                context.root);
        result.report_path = string(report.path);
    catch
    end
    manifest = jsondecode(fileread(context.run_manifest_path));
    if string(manifest.status)=="RUNNING"
        manifest = rkkt.artifacts.finalize_run_manifest( ...
            context,finalStatus,struct( ...
            "milestone_status",char(finalStatus), ...
            "stage_b_complete",false,"full_ipm_executed",false, ...
            "state_update_executed",false,"convergence_evaluated",false, ...
            "convergence_claimed",false,"stage_c1_entered",false, ...
            "failure_identifier",char(string(cause.identifier)), ...
            "failure_message",char(string(cause.message))));
        rkkt.artifacts.update_run_index(context,manifest);
    end
    result.status = finalStatus;
    result.manifest = manifest;
    result.error_identifier = string(cause.identifier);
    result.error_message = string(cause.message);
end
end

function value = solve_existing(lin,config)
value = rkkt.solver.solve_stage_b2b_recursive_direction(lin, ...
    SymmetryTolerance=config.reduced_symmetry_tolerance, ...
    ResidualRefinementMaxPasses=config.recursive_refinement_max_passes, ...
    UseCongruenceScaling=config.recursive_congruence_scaling_enabled, ...
    EquilibrationPasses=config.equilibration_passes);
end

function value = solve_daily_joint(lin,config)
value = rkkt.solver.solve_stage_b2c_daily_joint_direction(lin, ...
    SymmetryTolerance=config.reduced_symmetry_tolerance, ...
    ResidualTolerance=config.recursive_full_kkt_residual_tolerance);
end

function [value,seconds] = warm_and_time(callback)
warmup = callback(); %#ok<NASGU>
clear warmup
timer = tic;
value = callback();
seconds = toc(timer);
end

function audit = direction_audit(fullResult,candidate,lin,config)
audit = rkkt.solver.verify_stage_b2b_direction_equivalence( ...
    fullResult,candidate,lin, ...
    DirectionRelative=config.direction_relative_error_tolerance, ...
    RecursiveResidual=config.recursive_full_kkt_residual_tolerance, ...
    FullResidual=config.full_kkt_residual_tolerance);
end

