function exported = export_stage_a4_result_artifacts( ...
        runContext,data,index,finalState,physicalAudit,options)
%EXPORT_STAGE_A4_RESULT_ARTIFACTS Persist final A4 capacity/hourly results.
%
% This function does not solve or advance the primal-dual iteration.  It
% only expands the caller-provided final state through the canonical index,
% writes user-auditable result tables, and preserves the supplied physical
% audit.  Existing targets are never overwritten.

arguments
    runContext (1,1) struct
    data (1,1) struct
    index (1,1) struct
    finalState (1,1) struct
    physicalAudit table
    options.SolvePass (1,1) string = "pass_1"
    options.PhysicalTolerance (1,1) double ...
        {mustBeFinite,mustBeNonnegative} = 1.0e-8
end

validate_inputs(runContext,index,finalState,physicalAudit,options.SolvePass);

resultsDirectory = fullfile(runContext.root,"results");
ensure_directory(resultsDirectory);
paths = struct( ...
    "capacity_results",fullfile(resultsDirectory,"capacity_results.csv"), ...
    "hourly_dispatch_results", ...
        fullfile(resultsDirectory,"hourly_dispatch_results.csv"), ...
    "physical_results_mat",fullfile(resultsDirectory,"physical_results.mat"), ...
    "physical_audit",fullfile(runContext.acceptance_dir,"physical_audit.csv"), ...
    "result_artifact_hashes", ...
        fullfile(resultsDirectory,"result_artifact_hashes.csv"));
targets = string(struct2cell(paths));
assert_targets_absent(targets);

zeroDirection = zeros(size(finalState.xi));
physical = rkkt.model.recover_stage_a_physical_arrays( ...
    finalState.xi,zeroDirection,index,data);
capacityResults = make_capacity_results( ...
    runContext,data,physical,options.SolvePass,options.PhysicalTolerance);
hourlyResults = make_hourly_results( ...
    runContext,data,index,physical,options.SolvePass, ...
    options.PhysicalTolerance);
physicalAudit = normalize_physical_audit( ...
    physicalAudit,runContext,options.SolvePass);

assert(height(capacityResults)==14, ...
    "stageA4:artifacts:CapacityRowCount", ...
    "capacity_results.csv must contain the canonical 14 capacities.");
expectedHourlyRows = numel(physical.days)*numel(physical.hours)*( ...
    data.meta.nWind+data.meta.nSolar+data.meta.nHydro+ ...
    data.meta.nThermal+3*data.meta.nStorage);
assert(height(hourlyResults)==expectedHourlyRows, ...
    "stageA4:artifacts:HourlyRowCount", ...
    "hourly_dispatch_results.csv has %d rows; expected %d.", ...
    height(hourlyResults),expectedHourlyRows);
fixedRows = hourlyResults.fixed_zero;
assert(all(hourlyResults.value(fixedRows)==0), ...
    "stageA4:artifacts:FixedZeroRecovery", ...
    "Every fixed-zero hourly result must be exact numeric zero.");

rkkt.artifacts.write_table_csv_17g(paths.capacity_results,capacityResults);
rkkt.artifacts.write_table_csv_17g(paths.hourly_dispatch_results,hourlyResults);
rkkt.artifacts.write_table_csv_17g(paths.physical_audit,physicalAudit);
rkkt.artifacts.save_mat_artifact(paths.physical_results_mat, ...
    "final_state",finalState,"physical",physical, ...
    "capacity_results",capacityResults, ...
    "hourly_dispatch_results",hourlyResults, ...
    "physical_audit",physicalAudit);

hashTargets = [string(paths.capacity_results); ...
    string(paths.hourly_dispatch_results); ...
    string(paths.physical_results_mat);string(paths.physical_audit)];
artifactHashes = make_artifact_hashes(runContext.root,hashTargets);
rkkt.artifacts.write_table_csv_17g(paths.result_artifact_hashes,artifactHashes);

exported = struct( ...
    "paths",paths, ...
    "capacity_results",capacityResults, ...
    "hourly_dispatch_results",hourlyResults, ...
    "physical_audit",physicalAudit, ...
    "physical",physical, ...
    "artifact_hashes",artifactHashes);
end

function validate_inputs(context,index,state,audit,solvePass)
requiredContext = ["root","run_id","stage_id","acceptance_dir", ...
    "run_manifest_path"];
assert(all(isfield(context,cellstr(requiredContext)))&& ...
    isfolder(context.root), ...
    "stageA4:artifacts:InvalidRunContext", ...
    "A matching A4 run context is required.");
assert(string(context.stage_id)=="stage_A4"&& ...
    strlength(strip(solvePass))>0, ...
    "stageA4:artifacts:StageIdentity", ...
    "The result exporter requires stage_A4 and a nonempty solve pass.");
manifest = jsondecode(fileread(context.run_manifest_path));
assert(string(manifest.run_id)==string(context.run_id)&& ...
    string(manifest.stage_id)=="stage_A4"&& ...
    string(manifest.status)=="RUNNING", ...
    "stageA4:artifacts:ManifestIdentity", ...
    "A4 result export requires the matching RUNNING manifest.");
assert(isfield(index,"variable_index")&& ...
    isfield(index,"fixed_zero_map")&& ...
    istable(index.variable_index)&&istable(index.fixed_zero_map), ...
    "stageA4:artifacts:IndexContract", ...
    "variable_index and fixed_zero_map are required.");
assert(isfield(state,"xi")&&isnumeric(state.xi)&&iscolumn(state.xi)&& ...
    numel(state.xi)==height(index.variable_index)&& ...
    isreal(state.xi)&&all(isfinite(state.xi)), ...
    "stageA4:artifacts:FinalState", ...
    "finalState.xi must be a finite canonical compact state.");
requiredAudit = ["audit_id","requirement","actual_value", ...
    "threshold","status","evidence_path"];
assert(height(audit)>0&& ...
    all(ismember(requiredAudit,string(audit.Properties.VariableNames))), ...
    "stageA4:artifacts:PhysicalAuditSchema", ...
    "physicalAudit must contain %s.",strjoin(requiredAudit,", "));
status = upper(strip(string(audit.status)));
assert(all(ismember(status,["PASS","FAIL","NOT_APPLICABLE"])), ...
    "stageA4:artifacts:PhysicalAuditStatus", ...
    "physicalAudit contains an unsupported status.");
end

function output = make_capacity_results( ...
        context,data,physical,solvePass,tolerance)
parameters = rkkt.model.stage_a_capacity_parameters(data);
n = 14;
run_id = repmat(string(context.run_id),n,1);
stage_id = repmat("stage_A4",n,1);
solve_pass = repmat(solvePass,n,1);
capacity_index = (1:n).';
capacity_name = reshape(string(parameters.names),[],1);
asset_type = [repmat("wind",5,1);repmat("solar",5,1); ...
    repmat("storage_power",2,1);repmat("storage_energy",2,1)];
asset_id = [(1:5).';(1:5).';(1:2).';(1:2).'];
unit = [repmat("MW",12,1);repmat("MWh",2,1)];
value = reshape(double(physical.value.global_capacity),[],1);
lower_bound = reshape(double(parameters.lower),[],1);
upper_bound = reshape(double(parameters.upper),[],1);
unit_investment_cost = reshape(double(parameters.cost),[],1);
unit_cost_unit = [repmat("yuan_per_MW",12,1); ...
    repmat("yuan_per_MWh",2,1)];
investment_cost_yuan = value.*unit_investment_cost;
lower_margin = value-lower_bound;
upper_margin = upper_bound-value;
bound_violation = max([lower_bound-value,value-upper_bound,zeros(n,1)],[],2);
dailyCopy = double(physical.value.daily_capacity);
maximum_daily_copy_absolute_difference = ...
    max(abs(dailyCopy-value.'),[],1).';
fixed_tolerance = repmat(tolerance,n,1);
status = repmat("PASS",n,1);
passed = isfinite(value)&isfinite(investment_cost_yuan)& ...
    bound_violation<=tolerance& ...
    maximum_daily_copy_absolute_difference<=tolerance;
status(~passed) = "FAIL";
value_source = repmat( ...
    "final_state.xi/canonical variable_index",n,1);
output = table(run_id,stage_id,solve_pass,capacity_index,capacity_name, ...
    asset_type,asset_id,unit,value,lower_bound,upper_bound, ...
    unit_investment_cost,unit_cost_unit,investment_cost_yuan, ...
    lower_margin,upper_margin,bound_violation, ...
    maximum_daily_copy_absolute_difference,fixed_tolerance,status, ...
    value_source);
end

function output = make_hourly_results( ...
        context,data,index,physical,solvePass,tolerance)
fields = ["wind","solar","hydro","thermal","charge","discharge","soc"];
assetTypes = ["wind","solar","hydro","thermal", ...
    "storage","storage","storage"];
variableNames = ["PW","PP","PH","PF","Pch","Pdis","SOC"];
units = ["MW","MW","MW","MW","MW","MW","MWh"];
counts = [data.meta.nWind,data.meta.nSolar,data.meta.nHydro, ...
    data.meta.nThermal,data.meta.nStorage,data.meta.nStorage, ...
    data.meta.nStorage];
n = numel(physical.days)*numel(physical.hours)*sum(counts);

run_id = repmat(string(context.run_id),n,1);
stage_id = repmat("stage_A4",n,1);
solve_pass = repmat(solvePass,n,1);
day = zeros(n,1); hour = zeros(n,1); asset_type = strings(n,1);
asset_id = zeros(n,1); variable_name = strings(n,1);
unit = strings(n,1); value = zeros(n,1);
lower_bound = zeros(n,1); upper_bound = zeros(n,1);
availability_factor = NaN(n,1); fixed_zero = false(n,1);
energy_mwh = zeros(n,1); power_balance_coefficient = zeros(n,1);
power_balance_contribution_mw = zeros(n,1);
bound_violation = zeros(n,1); fixed_zero_exact = true(n,1);
fixed_tolerance = repmat(tolerance,n,1); status = strings(n,1);
value_source = strings(n,1);
parameters = rkkt.model.stage_a_capacity_parameters(data);
q = reshape(double(physical.value.global_capacity),[],1);
row = 0;
for d = 1:numel(physical.days)
    dayId = double(physical.days(d));
    for h = 1:numel(physical.hours)
        hourId = double(physical.hours(h));
        for group = 1:numel(fields)
            for asset = 1:counts(group)
                row = row+1;
                day(row) = dayId; hour(row) = hourId;
                asset_type(row) = assetTypes(group);
                asset_id(row) = asset;
                variable_name(row) = variableNames(group);
                unit(row) = units(group);
                value(row) = physical.value.(fields(group))(d,h,asset);
                [lower_bound(row),upper_bound(row), ...
                    availability_factor(row)] = result_bounds( ...
                    fields(group),asset,dayId,hourId,q,data,parameters);
                fixed_zero(row) = is_fixed_zero( ...
                    index.fixed_zero_map,dayId,hourId, ...
                    assetTypes(group),asset,variableNames(group));
                fixed_zero_exact(row) = ~fixed_zero(row)||value(row)==0;
                if units(group)=="MW"
                    energy_mwh(row) = value(row)*double(data.meta.dtHours);
                end
                power_balance_coefficient(row) = ...
                    balance_coefficient(variableNames(group));
                power_balance_contribution_mw(row) = ...
                    power_balance_coefficient(row)*value(row);
                bound_violation(row) = max([ ...
                    lower_bound(row)-value(row), ...
                    value(row)-upper_bound(row),0]);
                passed = isfinite(value(row))&& ...
                    isfinite(lower_bound(row))&& ...
                    isfinite(upper_bound(row))&& ...
                    bound_violation(row)<=tolerance&& ...
                    fixed_zero_exact(row);
                if passed, status(row)="PASS"; else, status(row)="FAIL"; end
                if fixed_zero(row)
                    value_source(row) = ...
                        "fixed_zero_map/exact physical recovery";
                else
                    value_source(row) = ...
                        "final_state.xi/canonical variable_index";
                end
            end
        end
    end
end
assert(row==n,"stageA4:artifacts:HourlyAllocation", ...
    "Hourly result preallocation and populated rows differ.");
output = table(run_id,stage_id,solve_pass,day,hour,asset_type, ...
    asset_id,variable_name,unit,value,lower_bound,upper_bound, ...
    availability_factor,fixed_zero,fixed_zero_exact,energy_mwh, ...
    power_balance_coefficient,power_balance_contribution_mw, ...
    bound_violation,fixed_tolerance,status,value_source);
end

function [lower,upper,availability] = result_bounds( ...
        field,asset,day,hour,q,data,parameters)
lower = 0; availability = NaN;
switch field
    case "wind"
        availability = data.timeseries.windAvailability(day,hour,asset);
        upper = availability*q(asset);
    case "solar"
        availability = data.timeseries.solarAvailability(day,hour,asset);
        upper = availability*q(5+asset);
    case "hydro"
        upper = data.base.hydro.maxOutputMW(asset);
    case "thermal"
        upper = data.base.thermal.maxOutputMW(asset);
    case {"charge","discharge"}
        upper = q(10+asset);
    case "soc"
        lower = parameters.soc_lower_fraction(asset)*q(12+asset);
        upper = parameters.soc_upper_fraction(asset)*q(12+asset);
    otherwise
        error("stageA4:artifacts:UnknownPhysicalField", ...
            "Unknown physical result field %s.",field);
end
end

function present = is_fixed_zero( ...
        map,day,hour,assetType,assetId,variableName)
if isempty(map)
    present = false;
    return
end
mask = map.day==day&map.hour==hour& ...
    string(map.asset_type)==assetType&map.asset_id==assetId& ...
    string(map.variable_name)==variableName;
present = nnz(mask)==1;
assert(nnz(mask)<=1,"stageA4:artifacts:DuplicateFixedZero", ...
    "Duplicate fixed-zero result mapping for day %d hour %d.",day,hour);
end

function coefficient = balance_coefficient(variableName)
if ismember(variableName,["PW","PP","PH","PF","Pdis"])
    coefficient = 1;
elseif variableName=="Pch"
    coefficient = -1;
else
    coefficient = 0;
end
end

function output = normalize_physical_audit( ...
        input,context,solvePass)
output = input;
names = string(output.Properties.VariableNames);
if ~ismember("run_id",names)
    output = addvars(output,repmat(string(context.run_id),height(output),1), ...
        'Before',1,'NewVariableNames','run_id');
end
names = string(output.Properties.VariableNames);
if ~ismember("stage_id",names)
    output = addvars(output,repmat("stage_A4",height(output),1), ...
        'After','run_id','NewVariableNames','stage_id');
end
names = string(output.Properties.VariableNames);
if ~ismember("solve_pass",names)
    output = addvars(output,repmat(solvePass,height(output),1), ...
        'After','stage_id','NewVariableNames','solve_pass');
end
assert(all(string(output.run_id)==string(context.run_id))&& ...
    all(string(output.stage_id)=="stage_A4")&& ...
    all(string(output.solve_pass)==solvePass), ...
    "stageA4:artifacts:PhysicalAuditIdentity", ...
    "physicalAudit run/stage/solve-pass identity is inconsistent.");
end

function hashes = make_artifact_hashes(runRoot,targets)
n = numel(targets);
relative_path = strings(n,1); sha256 = strings(n,1);
bytes = zeros(n,1); artifact_type = strings(n,1);
for k = 1:n
    assert(isfile(targets(k)), ...
        "stageA4:artifacts:MissingWrittenTarget", ...
        "Expected A4 result artifact was not written: %s",targets(k));
    relative_path(k) = relative_run_path(runRoot,targets(k));
    sha256(k) = rkkt.data.compute_sha256_file(targets(k));
    information = dir(targets(k)); bytes(k) = information.bytes;
    [~,~,extension] = fileparts(targets(k));
    artifact_type(k) = erase(lower(string(extension)),".");
end
scope = repmat("stage_A4_final_results",n,1);
status = repmat("PASS",n,1);
hashes = table(relative_path,sha256,bytes,artifact_type,scope,status);
end

function value = relative_run_path(runRoot,pathValue)
runRoot = string(char(java.io.File(char(runRoot)).getCanonicalPath()));
pathValue = string(char(java.io.File(char(pathValue)).getCanonicalPath()));
prefix = runRoot+filesep;
assert(startsWith(lower(pathValue),lower(prefix)), ...
    "stageA4:artifacts:PathOutsideRun", ...
    "Result artifact is outside the current run.");
value = replace(extractAfter(pathValue,strlength(prefix)), ...
    string(filesep),"/");
end

function ensure_directory(pathValue)
if isfolder(pathValue), return; end
if isfile(pathValue)
    error("stageA4:artifacts:PathConflict", ...
        "A file exists where results/ is required: %s",pathValue);
end
[created,message] = mkdir(pathValue);
assert(created,"stageA4:artifacts:CreateDirectoryFailed","%s",message);
end

function assert_targets_absent(targets)
for target = targets.'
    if isfile(target)||isfolder(target)
        error("stageA4:artifacts:TargetExists", ...
            "Refusing to overwrite A4 result artifact: %s",target);
    end
end
end
