function value = format_number(number)
value = string(sprintf("%.17g",number));
end

function assert_targets_absent(paths)
for k=1:numel(paths)
    assert(~isfile(paths(k)) && ~isfolder(paths(k)), ...
        "stageA4:iter24:ArtifactExists", ...
        "Refusing to overwrite diagnostic artifact %s.",paths(k));
end
end

function ensure_directory(pathValue)
if isfolder(pathValue), return; end
[created,message]=mkdir(pathValue);
assert(created,"stageA4:iter24:DirectoryCreate", ...
    "Could not create %s: %s",pathValue,message);
end

function write_text(pathValue,textValue)
fid=fopen(pathValue,"wb");
assert(fid>=0,"stageA4:iter24:TextOpen", ...
    "Could not open %s for writing.",pathValue);
guard=onCleanup(@()close_if_open(fid));
bytes=unicode2native(char(string(textValue)),"UTF-8");
count=fwrite(fid,bytes,"uint8");
assert(count==numel(bytes),"stageA4:iter24:TextWrite", ...
    "Incomplete write to %s.",pathValue);
clear guard;
end

function close_if_open(fid)
fclose(fid);
end
