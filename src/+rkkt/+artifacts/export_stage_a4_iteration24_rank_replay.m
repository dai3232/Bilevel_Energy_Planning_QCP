function exported = export_stage_a4_iteration24_rank_replay( ...
        runContext,result,options)
%EXPORT_STAGE_A4_ITERATION24_RANK_REPLAY Persist diagnostic-only evidence.
%
% All numerical values are taken from RESULT, which is rebuilt from the
% immutable revision-23 failure state.  This exporter does not update a
% solver state, overwrite a historical run, or create a Stage-A4 PASS
% claim.

arguments
    runContext (1,1) struct
    result (1,1) struct
    options.CommandText (1,1) string = ...
        "matlab -batch ""result="+ ...
        "main_stage_A4_iteration24_rank_replay();"""
end

assert(result.pass && result.no_state_update && ...
    result.no_stage_a4_pass_claim, ...
    "stageA4:iter24:ExportGate", ...
    "Only a completed diagnostic replay may be exported.");
diagnosticsDirectory = fullfile(runContext.root,"diagnostics");
ensure_directory(diagnosticsDirectory);

paths = struct();
paths.command = fullfile(diagnosticsDirectory,"replay_command.txt");
paths.identity = fullfile(diagnosticsDirectory,"replay_identity.json");
paths.summary = fullfile(diagnosticsDirectory,"diagnostic_summary.json");
paths.block_summary = fullfile(diagnosticsDirectory,"block_summary.csv");
paths.singular_values = fullfile(diagnosticsDirectory,"singular_values.csv");
paths.near_null = fullfile(diagnosticsDirectory,"near_null_components.csv");
paths.curvature = fullfile(diagnosticsDirectory,"curvature_sources.csv");
paths.scaling_trace = fullfile(diagnosticsDirectory,"scaling_trace.csv");
paths.coordinate_scaling = fullfile(diagnosticsDirectory, ...
    "diagnostic_coordinate_scaling.csv");
paths.factor_comparison = fullfile(diagnosticsDirectory, ...
    "factor_solve_comparison.csv");
paths.protected = fullfile(diagnosticsDirectory, ...
    "protected_file_audit.csv");
paths.result_mat = fullfile(diagnosticsDirectory, ...
    "iteration24_rank_replay_result.mat");
paths.matrix_mat = fullfile(runContext.matrices_dir, ...
    "iteration24_local_pivots_and_full_audit.mat");
paths.matrix_manifest = runContext.matrix_manifest_path;
paths.acceptance = runContext.acceptance_results_path;
paths.issue_log = runContext.issue_log_path;

assert_targets_absent(string(struct2cell(paths)));
write_text(paths.command,options.CommandText+newline);
rkkt.artifacts.write_table_csv_17g_atomic(paths.block_summary,result.block_summary);
rkkt.artifacts.write_table_csv_17g_atomic(paths.singular_values,result.singular_values);
rkkt.artifacts.write_table_csv_17g_atomic(paths.near_null,result.near_null_components);
rkkt.artifacts.write_table_csv_17g_atomic(paths.curvature,result.curvature_sources);
rkkt.artifacts.write_table_csv_17g_atomic(paths.scaling_trace,result.scaling_trace);
rkkt.artifacts.write_table_csv_17g_atomic(paths.coordinate_scaling, ...
    result.coordinate_scaling);
rkkt.artifacts.write_table_csv_17g_atomic(paths.factor_comparison, ...
    result.factor_solve_comparison);
rkkt.artifacts.write_table_csv_17g_atomic(paths.protected, ...
    result.protected_file_audit.table);

identity = make_identity(result,runContext);
summary = make_summary(result,runContext);
rkkt.artifacts.write_json_file(paths.identity,identity);
rkkt.artifacts.write_json_file(paths.summary,summary);

persisted = result;
matrixData = persisted.matrix_data;
persisted = rmfield(persisted,"matrix_data");
if isfield(persisted.high_precision,"solution_double")
    persisted.high_precision = rmfield( ...
        persisted.high_precision,"solution_double");
end
save(paths.result_mat,"persisted","-v7.3");
save(paths.matrix_mat,"matrixData","-v7.3");

matrixManifest = make_matrix_manifest( ...
    runContext.root,paths.matrix_mat,matrixData);
rkkt.artifacts.write_table_csv_17g_atomic(paths.matrix_manifest,matrixManifest);
acceptance = make_acceptance(result,runContext);
rkkt.artifacts.write_table_csv_17g_atomic(paths.acceptance,acceptance);
issues = make_issue_log(result,runContext);
rkkt.artifacts.write_table_csv_17g_atomic(paths.issue_log,issues);

exported = struct("paths",paths,"identity",identity, ...
    "summary",summary,"matrix_manifest",matrixManifest, ...
    "acceptance",acceptance,"issues",issues);
end

