function manifest = make_matrix_manifest(root,pathValue,matrixData)
names = string(fieldnames(matrixData));
sha = string(rkkt.data.compute_sha256_file(pathValue));
rows = zeros(numel(names),1);
columns = zeros(numel(names),1);
nonzeros = zeros(numel(names),1);
for k=1:numel(names)
    value = matrixData.(names(k));
    rows(k)=size(value,1);
    columns(k)=size(value,2);
    nonzeros(k)=nnz(value);
end
relative = replace(string(pathValue),string(root)+filesep,"");
manifest = table(names,repmat(relative,numel(names),1), ...
    rows,columns,nonzeros,repmat(sha,numel(names),1), ...
    repmat("diagnostic_only_not_consumed_by_formal_solver", ...
        numel(names),1), ...
    'VariableNames',{'matrix_name','relative_path','rows','columns', ...
        'nnz','sha256','role'});
end

function acceptance = make_acceptance(result,context)
h3 = result.block_summary(result.block_summary.hour==3,:);
scaled = result.scaling_trace(end,:);
ids = [ ...
    "A4-I24-ID-001"; ...
    "A4-I24-REPLAY-001"; ...
    "A4-I24-RANK-001"; ...
    "A4-I24-SCALE-001"; ...
    "A4-I24-GOV-001"];
names = [ ...
    "权威状态和线性化指纹复现"; ...
    "第24轮day14/hour3生产失败复现"; ...
    "80位重算排除冻结系数上的结构真奇异"; ...
    "只读合同尺度反事实恢复22维数值秩"; ...
    "无状态更新、无回退且冻结资料不变"];
actual = [ ...
    result.state_fingerprint+" / "+result.linearization_fingerprint; ...
    result.replay_failure.layer+" rank="+result.replay_failure.rank; ...
    "smin="+format_number(result.high_precision.s3_smin); ...
    "rank="+scaled.numeric_rank+" cond2="+ ...
        format_number(scaled.condition_2); ...
    "state_update_count=0; protected="+ ...
        string(result.protected_file_audit.all_pass)];
contracts = [ ...
    "逐位等于权威checkpoint"; ...
    "layer=day_14_block_ldl_thomas, rank=17"; ...
    "80位最小绝对特征值明确非零"; ...
    "rank=22，且只读诊断不进入正式方向"; ...
    "CURRENT_STAGE=stage_A4/READY，无正式A4 run"];
status = repmat("PASS",5,1);
blocking = true(5,1);
evidence = [ ...
    "diagnostics/replay_identity.json"; ...
    "diagnostics/block_summary.csv"; ...
    "diagnostics/diagnostic_summary.json"; ...
    "diagnostics/scaling_trace.csv"; ...
    "diagnostics/protected_file_audit.csv"];
acceptance = table( ...
    repmat(string(context.run_id),5,1),ids,names,blocking, ...
    status,actual,contracts,evidence, ...
    'VariableNames',{'run_id','test_id','test_name','blocking', ...
        'status','actual','contract','evidence'});
assert(all(acceptance.status=="PASS") && height(acceptance)==5 && ...
    h3.schur_rank==17, ...
    "stageA4:iter24:AcceptanceConstruction", ...
    "The diagnostic acceptance facts are inconsistent.");
end

