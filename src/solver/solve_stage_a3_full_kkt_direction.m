function result = solve_stage_a3_full_kkt_direction(lin)
%SOLVE_STAGE_A3_FULL_KKT_DIRECTION Solve the sparse 7-day audit system.

arguments
    lin (1,1) struct
end

assembly = assemble_stage_a3_full_kkt(lin);
lastwarn("");
direction = assembly.matrix\assembly.rhs;
[warningMessage,warningId] = lastwarn;
if strlength(string(warningId))>0 || strlength(string(warningMessage))>0
    error("stageA3:solver:FullKktSolveWarning", ...
        "A3 sparse audit solve emitted warning %s: %s", ...
        string(warningId),string(warningMessage));
end
assert(all(isfinite(direction)),"stageA3:solver:FullDirectionNonfinite", ...
    "A3 sparse audit direction contains NaN or Inf.");
residual = assembly.matrix*direction-assembly.rhs;

result = struct();
result.method = "sparse_backslash_audit";
result.linearization_identity = assembly.linearization_identity;
result.direction = direction;
result.components = struct( ...
    "xi",direction(assembly.slices.xi), ...
    "y",direction(assembly.slices.y), ...
    "l",direction(assembly.slices.l), ...
    "z",direction(assembly.slices.z));
result.kkt = assembly;
result.diagnostics = struct( ...
    "relative_residual",norm(residual,2)/max(1,norm(assembly.rhs,2)), ...
    "max_absolute_residual",max(abs(residual)), ...
    "max_residual_row",find(abs(residual)==max(abs(residual)),1,"first"), ...
    "warning_id",string(warningId), ...
    "warning_message",string(warningMessage), ...
    "warning_present",false);
end
