
function core = solve_stage_a_multiday_core16_ldl(partition,aggregation,options)
%SOLVE_STAGE_A_MULTIDAY_CORE16_LDL Solve the sorted seven-day 16-D core.

arguments
    partition (1,1) struct
    aggregation (1,1) struct
    options.SymmetryTolerance (1,1) double {mustBeNonnegative,mustBeFinite} = 1e-12
end
assert(isequal(partition.linearization_identity, ...
    aggregation.linearization_identity), ...
    "stageAMultiday:solver:LinearizationIdentityMismatch", ...
    "formal multi-day partition and aggregation identities differ.");
assert(aggregation.order_invariant_passed, ...
    "stageAMultiday:solver:DayAggregationOrder", ...
    "Sorted day-response aggregation is not order invariant.");
globalPart = partition.global;
assert(isfield(partition,"stage_id") && ...
    isfield(aggregation,"stage_id") && ...
    string(partition.stage_id)==string(aggregation.stage_id), ...
    "stageAMultiday:solver:StageIdentityMismatch", ...
    "Partition and aggregation must share one stage identity.");
stageId = string(partition.stage_id);
matrix = [globalPart.Q+aggregation.S_sum,globalPart.R.'; ...
    globalPart.R,sparse(2,2)];
rhs = [globalPart.b_q+aggregation.gamma_sum;-globalPart.r_duration];
assert(isequal(size(matrix),[16,16]) && numel(rhs)==16, ...
    "stageAMultiday:solver:CoreDimension", ...
    "The formal multi-day global core must be exactly 16-by-16.");
try
    factor = factor_symmetric_ldl(matrix,stageId+"_global_core_16", ...
        options.SymmetryTolerance);
    [solution,solveDiagnostics] = solve_with_ldl_factor( ...
        factor,rhs,stageId+"_global_core_rhs");
catch cause
    wrapped = MException("stageAMultiday:solver:Core16Failure", ...
        "formal multi-day 16-by-16 global core failed: %s",cause.message);
    wrapped = addCause(wrapped,cause);
    throw(wrapped);
end
residual = matrix*solution-rhs;

core = struct();
core.stage_id = stageId;
core.linearization_identity = partition.linearization_identity;
core.matrix = sparse(matrix);
core.rhs = rhs;
core.solution = solution;
core.delta_q = solution(1:14);
core.delta_rho = solution(15:16);
core.factor = factor;
core.diagnostics = struct( ...
    "factor",rmfield(factor,["matrix","L","D"]), ...
    "solve",solveDiagnostics, ...
    "relative_residual",norm(residual,2)/max(1,norm(rhs,2)), ...
    "max_absolute_residual",max(abs(residual)), ...
    "day_ids_accumulated",aggregation.day_ids_sorted);
end
