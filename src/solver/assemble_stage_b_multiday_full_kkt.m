function assembly = assemble_stage_b_multiday_full_kkt(linearization,config)
%ASSEMBLE_STAGE_B_MULTIDAY_FULL_KKT Assemble, but never solve, B-2A KKT.
%
% The block signs follow docs/08 exactly:
% [ H A' 0 G'; A 0 0 0; G 0 I 0; 0 0 Z L ].  The raw primal-dual
% operator is contractually nonsymmetric because its complementarity rows
% contain Z while its slack rows contain I.  Symmetry is audited on H and
% on the explicit transpose block placements, never forced on the raw KKT.

arguments
    linearization (1,1) struct
    config (1,1) struct
end

nx = numel(linearization.state.xi);
neq = numel(linearization.state.y);
ni = numel(linearization.state.l);
assert(nx==3722 && neq==618 && ni==7304, ...
    "stageB2A:kkt:Dimensions", ...
    "B-2A KKT dimensions must be 3722/618/7304.");
assert(string(linearization.milestone_id)=="B-2A" && ...
    ~linearization.execution.full_kkt_solved && ...
    ~linearization.execution.recursive_direction_executed, ...
    "stageB2A:kkt:ExecutionBoundary", ...
    "The B-2A assembler is assemble-only and cannot consume a direction.");

H = sparse(linearization.H);
A = sparse(linearization.A);
G = sparse(linearization.G);
Z = spdiags(linearization.state.z,0,ni,ni);
L = spdiags(linearization.state.l,0,ni,ni);
I = speye(ni);
zeroNxNi = sparse(nx,ni);
zeroEqNi = sparse(neq,ni);
zeroNiEq = sparse(ni,neq);
zeroNiNx = sparse(ni,nx);
zeroNiNi = sparse(ni,ni);
matrix = [H,A.',zeroNxNi,G.'; ...
    A,sparse(neq,neq),zeroEqNi,zeroEqNi; ...
    G,zeroNiEq,I,zeroNiNi; ...
    zeroNiNx,zeroNiEq,Z,L];
rhs = [-linearization.r_dual; -linearization.r_eq; ...
    -linearization.r_ineq; -linearization.r_comp];
dimension = nx+neq+2*ni;
assert(isequal(size(matrix),[dimension,dimension]) && ...
    numel(rhs)==dimension && issparse(matrix) && ...
    all(isfinite(nonzeros(matrix))) && all(isfinite(rhs)), ...
    "stageB2A:kkt:Assembly", ...
    "The assembled sparse KKT shape or finite-value contract failed.");

blockRows = build_block_audit(H,A,G,I,Z,L,matrix,nx,neq,ni);
assembly = struct();
assembly.stage_id = "stage_B";
assembly.milestone_id = "B-2A";
assembly.linearization_identity = linearization.identity;
assembly.matrix = matrix;
assembly.rhs = rhs;
assembly.dimension = dimension;
assembly.nnz = nnz(matrix);
assembly.expected_nnz = 54664;
assembly.slices = struct( ...
    "xi",(1:nx).', ...
    "y",(nx+(1:neq)).', ...
    "l",(nx+neq+(1:ni)).', ...
    "z",(nx+neq+ni+(1:ni)).', ...
    "stationarity_rows",(1:nx).', ...
    "equality_rows",(nx+(1:neq)).', ...
    "slack_rows",(nx+neq+(1:ni)).', ...
    "complementarity_rows",(nx+neq+ni+(1:ni)).');
assembly.blocks = blockRows;
assembly.symmetry = struct( ...
    "raw_full_kkt_relative",relative_symmetry_error(matrix), ...
    "raw_full_kkt_status", ...
        "NOT_APPLICABLE_CONTRACTUALLY_NONSYMMETRIC", ...
    "hessian_relative",relative_symmetry_error(H), ...
    "hessian_threshold",config.lagrangian_hessian_symmetry_tolerance, ...
    "a_transpose_relative",relative_block_error( ...
        A.',matrix(1:nx,nx+(1:neq))), ...
    "g_transpose_relative",relative_block_error( ...
        G.',matrix(1:nx, nx+neq+ni+(1:ni))), ...
    "identity_block_relative",relative_block_error( ...
        I,matrix(nx+neq+(1:ni),nx+neq+(1:ni))), ...
    "z_block_relative",relative_block_error( ...
        Z,matrix(nx+neq+ni+(1:ni),nx+neq+(1:ni))), ...
    "l_block_relative",relative_block_error( ...
        L,matrix(nx+neq+ni+(1:ni),nx+neq+ni+(1:ni))));
assert(assembly.nnz==assembly.expected_nnz && ...
    assembly.symmetry.hessian_relative<= ...
        config.lagrangian_hessian_symmetry_tolerance && ...
    assembly.symmetry.a_transpose_relative==0 && ...
    assembly.symmetry.g_transpose_relative==0 && ...
    assembly.symmetry.identity_block_relative==0 && ...
    assembly.symmetry.z_block_relative==0 && ...
    assembly.symmetry.l_block_relative==0, ...
    "stageB2A:kkt:StructureAudit", ...
    "One or more sparse KKT block placement audits failed.");
assembly.execution = struct("assembled",true,"solved",false, ...
    "recursive_direction_executed",false,"newton_direction_count",0, ...
    "full_ipm_executed",false,"optimization_executed",false, ...
    "parallel_executed",false,"fallback_used",false);
end

function blocks = build_block_audit(H,A,G,I,Z,L,K,nx,neq,ni)
names = ["H";"A_transpose";"G_transpose";"A";"G";"I_slack"; ...
    "Z_complementarity";"L_complementarity"];
rowStart = [1;1;1;nx+1;nx+neq+1;nx+neq+1; ...
    nx+neq+ni+1;nx+neq+ni+1];
rowEnd = [nx;nx;nx;nx+neq;nx+neq+ni;nx+neq+ni; ...
    nx+neq+2*ni;nx+neq+2*ni];
colStart = [1;nx+1;nx+neq+ni+1;1;1;nx+neq+1; ...
    nx+neq+1;nx+neq+ni+1];
colEnd = [nx;nx+neq;nx+neq+2*ni;nx;nx;nx+neq+ni; ...
    nx+neq+ni;nx+neq+2*ni];
expectedNnz = [nnz(H);nnz(A);nnz(G);nnz(A);nnz(G);nnz(I);nnz(Z);nnz(L)];
actualNnz = zeros(8,1);
for k = 1:8
    actualNnz(k) = nnz(K(rowStart(k):rowEnd(k),colStart(k):colEnd(k)));
end
rows = [nx;nx;nx;neq;ni;ni;ni;ni];
cols = [nx;neq;ni;nx;nx;ni;ni;ni];
role = ["stationarity_hessian";"stationarity_eq_transpose"; ...
    "stationarity_ineq_transpose";"equality_jacobian"; ...
    "inequality_jacobian";"slack_identity"; ...
    "complementarity_z";"complementarity_l"];
status = repmat("PASS",8,1);
status(actualNnz~=expectedNnz) = "FAIL";
blocks = table(names,role,rowStart,rowEnd,colStart,colEnd,rows,cols, ...
    expectedNnz,actualNnz,status, ...
    'VariableNames',{'block_name','role','row_start','row_end', ...
    'column_start','column_end','row_count','column_count', ...
    'expected_nnz','actual_nnz','status'});
assert(all(status=="PASS"),"stageB2A:kkt:BlockNnz", ...
    "Sparse KKT block nnz inventory failed.");
end

function value = relative_symmetry_error(matrix)
value = norm(matrix-matrix.',"fro")/max(1,norm(matrix,"fro"));
end

function value = relative_block_error(expected,actual)
delta = expected-actual;
value = norm(delta,"fro")/max(1,norm(expected,"fro"));
end
