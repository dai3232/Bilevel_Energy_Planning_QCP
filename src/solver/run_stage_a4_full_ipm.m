function recover_initial_checkpoint_transaction(context,state,metrics, ...
        linearization,gitCommit,inputHashes,configSha,initialFingerprint, ...
        capacityNames,maxPasses)
if isfile(context.checkpoint_manifest_path)
    return
end
iterations = empty_iteration_table(capacityNames);
directions = empty_direction_table();
refinement = empty_refinement_table();
iterationPath = fullfile(context.iterations_dir,"iteration_summary.csv");
directionPath = fullfile(context.iterations_dir,"direction_audit.csv");
refinementPath = fullfile(context.iterations_dir,"recursive_refinement.csv");
metricsPath = fullfile(context.iterations_dir,"initial_metrics.json");
archiveRoot = fullfile(context.iterations_dir, ...
    "orphaned_initial_transaction", ...
    string(datetime("now","TimeZone","UTC", ...
    "Format","yyyyMMdd_HHmmss_SSS")));
ensure_exact_or_archive_table(iterationPath,iterations,archiveRoot);
ensure_exact_or_archive_table(directionPath,directions,archiveRoot);
ensure_exact_or_archive_table(refinementPath,refinement,archiveRoot);
revisionRoot = fullfile(context.iterations_dir,"revisions","revision_000");
snapshotPassed = false;
snapshot = struct();
if isfolder(revisionRoot)
    try
        snapshot = load_validated_revision_snapshot(context,0);
        snapshotPassed = true;
    catch
        snapshotPassed = false;
    end
    if ~snapshotPassed
        ensure_directory(archiveRoot);
        target = fullfile(archiveRoot,"revision_000_incomplete");
        [moved,message] = movefile(revisionRoot,target);
        assert(moved,"stageA4:a43:InitialTransactionArchive","%s",message);
    end
end
if ~snapshotPassed
    snapshot = write_revision_snapshot( ...
        context,0,iterations,directions,refinement);
end
if isfile(metricsPath)
    persistedMetrics = jsondecode(fileread(metricsPath));
    metricsPassed = string(persistedMetrics.convergence_coordinate)== ...
        string(metrics.convergence_coordinate) && ...
        double(persistedMetrics.objective_scale_factor)== ...
        double(metrics.objective_scale_factor);
    if ~metricsPassed
        ensure_directory(archiveRoot);
        [moved,message] = movefile(metricsPath, ...
            fullfile(archiveRoot,"initial_metrics_inconsistent.json"));
        assert(moved,"stageA4:a43:InitialTransactionArchive","%s",message);
    end
end
if ~isfile(metricsPath)
    write_json_file(metricsPath,metrics);
end
metadata = checkpoint_metadata(0,gitCommit,inputHashes,configSha, ...
    initialFingerprint,compute_stage_a4_rns1_fingerprint( ...
    linearization,"linearization"), ...
    snapshot.iteration_summary_sha256, ...
    snapshot.direction_audit_sha256, ...
    snapshot.recursive_refinement_sha256,maxPasses);
metadata.state_fingerprint = initialFingerprint;
write_stage_a4_checkpoint(context,state,metadata);
end

function ensure_exact_or_archive_table(pathValue,expected,archiveRoot)
temporary = string(tempname(tempdir))+".csv";
guard = onCleanup(@()delete_if_present(temporary));
write_table_csv_17g(temporary,expected);
expectedHash = compute_sha256_file(temporary);
if isfile(pathValue)
    if lower(string(compute_sha256_file(pathValue)))==lower(string(expectedHash))
        clear guard
        return
    end
    ensure_directory(archiveRoot);
    [~,base,extension] = fileparts(pathValue);
    target = fullfile(archiveRoot,string(base)+string(extension));
    [moved,message] = movefile(pathValue,target);
    assert(moved,"stageA4:a43:InitialTransactionArchive","%s",message);
end
write_table_csv_17g_atomic(pathValue,expected);
clear guard
end

