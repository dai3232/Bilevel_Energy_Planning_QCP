failure.state_fingerprint = ...
    compute_stage_a4_checkpoint_state_fingerprint(state);
save_mat_artifact(pathValue,"state_before_failure",state, ...
    "failure",failure);
sha256 = compute_sha256_file(pathValue);
ledgerPath = fullfile(context.checkpoints_dir,"failure_ledger.csv");
if isfile(ledgerPath)
    checkpointAudit = validate_stage_a4_checkpoint(context);
    assert(checkpointAudit.failure_ledger_audit.passed, ...
        "stageA4:a43:FailureLedgerPriorAudit", ...
        "Existing failure ledger did not pass independent validation.");
    ledger = checkpointAudit.failure_ledger_audit.ledger;
else
    ledger = empty_failure_ledger();
end
sequence = height(ledger)+1;
row = table(sequence,string(context.run_id),invocation, ...
    double(failure.iteration),double(failure.state_revision),string(kind), ...
    string(failure.identifier),string(failure.message), ...
    string(failure.state_fingerprint),relativePath,string(sha256),timestamp, ...
    'VariableNames',{'failure_sequence','run_id','solver_invocation', ...
    'iteration','state_revision','terminal_state','identifier','message', ...
    'state_fingerprint','relative_path','sha256','recorded_at_utc'});
ledger = [ledger;row];
write_table_csv_17g_atomic(ledgerPath,ledger);
checkpointAudit = validate_stage_a4_checkpoint(context);
assert(checkpointAudit.failure_ledger_audit.passed && ...
    checkpointAudit.failure_ledger_audit.failure_count==sequence, ...
    "stageA4:a43:FailureLedgerPostWriteAudit", ...
    "New failure evidence did not pass independent ledger validation.");
end

function value = empty_failure_ledger()
value = table(zeros(0,1),strings(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),strings(0,1),strings(0,1),strings(0,1), ...
    strings(0,1),strings(0,1),strings(0,1),strings(0,1), ...
    'VariableNames',{'failure_sequence','run_id','solver_invocation', ...
    'iteration','state_revision','terminal_state','identifier','message', ...
    'state_fingerprint','relative_path','sha256','recorded_at_utc'});
end

function require_run_context(context)
required = ["root","run_id","run_manifest_path","effective_config_path", ...
    "iterations_dir","checkpoints_dir"];
assert(all(isfield(context,required)) && isfolder(context.root) && ...
    isfile(context.run_manifest_path), ...
    "stageA4:a43:RunContext","A valid unique run context is required.");
manifest = jsondecode(fileread(context.run_manifest_path));
assert(string(manifest.stage_id)=="stage_A4" && ...
    string(manifest.status)=="RUNNING", ...
    "stageA4:a43:RunManifest", ...
    "A4-3 requires a RUNNING stage_A4 manifest.");
end
