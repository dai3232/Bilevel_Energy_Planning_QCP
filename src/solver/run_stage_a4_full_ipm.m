function publish_csv(source,target)
source = char(string(source));
target = char(string(target));
ensure_parent_directory(target);
temporary = [tempname(fileparts(target)),'.csv.pending'];
cleanup = onCleanup(@()delete_if_present(temporary));
[copied,message] = copyfile(source,temporary);
assert(copied,"stageA4:a43:RevisionSnapshotPublish","%s",message);
[moved,message] = movefile(temporary,target,"f");
assert(moved,"stageA4:a43:RevisionSnapshotPublish","%s",message);
clear cleanup
assert(lower(string(compute_sha256_file(target)))== ...
    lower(string(compute_sha256_file(source))), ...
    "stageA4:a43:RevisionSnapshotPublish", ...
    "Published cumulative CSV differs from its immutable snapshot.");
end

function snapshot = load_validated_revision_snapshot(context,revision)
revisionRoot = fullfile(context.iterations_dir,"revisions", ...
    "revision_"+compose("%03d",revision));
manifestPath = fullfile(revisionRoot,"snapshot_manifest.json");
assert(isfolder(revisionRoot) && isfile(manifestPath), ...
    "stageA4:a43:RevisionSnapshotMissing", ...
    "Revision %d snapshot or manifest is missing.",revision);
snapshot = jsondecode(fileread(manifestPath));
required = ["revision","root","iteration_summary_path", ...
    "direction_audit_path","recursive_refinement_path", ...
    "iteration_summary_sha256","direction_audit_sha256", ...
    "recursive_refinement_sha256"];
assert(isstruct(snapshot)&&isscalar(snapshot) && ...
    all(isfield(snapshot,cellstr(required))) && ...
    double(snapshot.revision)==revision, ...
    "stageA4:a43:RevisionSnapshotSchema", ...
    "Revision %d snapshot manifest is invalid.",revision);

expectedPaths = [ ...
    string(revisionRoot)
    fullfile(revisionRoot,"iteration_summary.csv")
    fullfile(revisionRoot,"direction_audit.csv")
    fullfile(revisionRoot,"recursive_refinement.csv")];
recordedPaths = [string(snapshot.root)
    string(snapshot.iteration_summary_path)
    string(snapshot.direction_audit_path)
    string(snapshot.recursive_refinement_path)];
for k = 1:numel(expectedPaths)
    assert(same_canonical_path(recordedPaths(k),expectedPaths(k)), ...
        "stageA4:a43:RevisionSnapshotPath", ...
        "Revision %d snapshot path %d is not canonical.",revision,k);
end

hashFields = ["iteration_summary_sha256","direction_audit_sha256", ...
    "recursive_refinement_sha256"];
for k = 1:numel(hashFields)
    recordedHash = lower(strip(string(snapshot.(hashFields(k)))));
    assert(is_sha256_text(recordedHash) && ...
        isfile(expectedPaths(k+1)) && ...
        lower(string(compute_sha256_file(expectedPaths(k+1))))== ...
            recordedHash, ...
        "stageA4:a43:RevisionSnapshotHash", ...
        "Revision %d %s hash is invalid.",revision,hashFields(k));
    snapshot.(hashFields(k)) = recordedHash;
end
snapshot.root = expectedPaths(1);
snapshot.iteration_summary_path = expectedPaths(2);
snapshot.direction_audit_path = expectedPaths(3);
snapshot.recursive_refinement_path = expectedPaths(4);
end

function passed = same_canonical_path(left,right)
left = string(char(java.io.File( ...
    char(string(left))).getCanonicalPath()));
right = string(char(java.io.File( ...
    char(string(right))).getCanonicalPath()));
if ispc
    passed = strcmpi(left,right);
else
    passed = left==right;
end
end

function passed = is_sha256_text(value)
passed = isscalar(value) && ...
    ~isempty(regexp(char(value),"^[0-9a-f]{64}$","once"));
end

function repair_cumulative_evidence_from_snapshot(context,revision, ...
        checkpointRecord,iterationTarget,directionTarget,refinementTarget)
snapshot = load_validated_revision_snapshot(context,revision);
iterationSnapshotHash = lower(string(snapshot.iteration_summary_sha256));
checkpointIterationHashPassed = iterationSnapshotHash== ...
    lower(string(checkpointRecord.iteration_csv_sha256));
assert(double(snapshot.revision)==revision && ...
    checkpointIterationHashPassed && ...
        lower(string(checkpointRecord.direction_csv_sha256))== ...
        lower(string(snapshot.direction_audit_sha256)) && ...
        lower(string(checkpointRecord.refinement_csv_sha256))== ...
        lower(string(snapshot.recursive_refinement_sha256)) && ...
    iterationSnapshotHash== ...
        lower(string(snapshot.iteration_summary_sha256)) && ...
    lower(string(compute_sha256_file( ...
        snapshot.direction_audit_path)))== ...
        lower(string(snapshot.direction_audit_sha256)) && ...
    lower(string(compute_sha256_file( ...
        snapshot.recursive_refinement_path)))== ...
        lower(string(snapshot.recursive_refinement_sha256)), ...
    "stageA4:a43:ResumeSnapshotHash", ...
    "The selected checkpoint revision snapshot failed SHA256 validation.");
if ~isfile(iterationTarget) || ...
        lower(string(compute_sha256_file(iterationTarget)))~= ...
        lower(string(snapshot.iteration_summary_sha256)) || ...
        ~isfile(directionTarget) || ...
        lower(string(compute_sha256_file(directionTarget)))~= ...
        lower(string(snapshot.direction_audit_sha256)) || ...
        ~isfile(refinementTarget) || ...
        lower(string(compute_sha256_file(refinementTarget)))~= ...
        lower(string(snapshot.recursive_refinement_sha256))
    publish_revision_snapshot(snapshot,iterationTarget, ...
        directionTarget,refinementTarget);
end
end

