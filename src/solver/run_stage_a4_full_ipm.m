function audit = replay_last_accepted_iteration(runContext,state,data,index, ...
        config,chainId,eqScale,dualScale,iterationTable,directionTable,expected)
revision = state.state_revision;
if revision==0
    audit = struct("performed",false,"passed",true, ...
        "reason","initial_checkpoint", ...
        "full_kkt_audit_performed",false, ...
        "full_kkt_direction_solve_count",0);
    return
end
[previous,~,previousAudit] = load_stage_a4_checkpoint(runContext, ...
    "Revision",revision-1,"ExpectedMetadata",expected);
replayed = execute_stage_a4_iteration(previous.state,data,index,config, ...
    "StepStrategy","independent", ...
    "ObjectiveScaleMode","positive_scalar_unitization", ...
    "DiagnosticObjectiveChainId",chainId, ...
    "RecursiveRefinementMaxPasses",3, ...
    "EqualityResidualReferenceScale",eqScale, ...
    "DualResidualReferenceScale",dualScale);
stateExact = canonical_state_equal(replayed.state_after,state);
row = directionTable(revision,:);
directionExact = ...
    replayed.direction_audit.direction_relative_error== ...
        row.direction_relative_error && ...
    replayed.direction_audit.recursive_kkt_relative_residual== ...
        row.recursive_full_kkt_relative_residual && ...
    replayed.direction_audit.full_kkt_relative_residual== ...
        row.full_kkt_relative_residual;
iterationExact = iterationTable.iteration(revision)==revision && ...
    iterationTable.state_revision(revision)==revision;
audit = struct( ...
    "performed",true, ...
    "revision",revision, ...
    "previous_checkpoint_passed",previousAudit.passed, ...
    "state_exact",stateExact, ...
    "direction_audit_exact",directionExact, ...
    "iteration_identity_exact",iterationExact, ...
    "full_kkt_audit_performed",true, ...
    "full_kkt_direction_solve_count",1, ...
    "passed",previousAudit.passed && stateExact && ...
        directionExact && iterationExact);
assert(audit.passed,"stageA4:a43:ResumeReplay", ...
    "The last accepted A4-3 transition did not replay exactly.");
end

