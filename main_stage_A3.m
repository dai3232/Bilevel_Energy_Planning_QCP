    [~,base,extension]=fileparts(paths.(names{k}));
    value.(names{k})=char("reports/"+string(base)+string(extension));
end
end
function write_new_table(pathValue,value)
assert(~isfile(pathValue)&&~isfolder(pathValue), ...
    "stageA3:artifacts:TargetExists","Refusing to overwrite %s.",pathValue);
write_table_csv_17g(pathValue,value);
end
function passed=all_required_test_evidence_exists(paths)
values=string(struct2cell(paths)); passed=numel(values)==6&&all(isfile(values));
end

function preserve_stage_a3_failure(context,acceptance,issues,exception)
hashPath=fullfile(context.acceptance_dir,"evidence_hashes.csv");
preserve_candidate_file(context.acceptance_results_path, ...
    fullfile(context.acceptance_dir,"acceptance_results.pre_failure_candidate.csv"));
preserve_candidate_file(context.issue_log_path, ...
    fullfile(context.issues_dir,"issue_log.pre_failure_candidate.csv"));
try
    if isempty(acceptance)
        acceptance=initialize_stage_a3_acceptance(string(context.project_root));
    end
    failureId=first_failure_test_id(exception);
    if nnz(acceptance.test_id==failureId)==1
        acceptance=set_stage_a3_acceptance_result(acceptance,failureId,"FAIL", ...
            exception.message,"first failing A3 acceptance fact","run_manifest.json");
    end
    for row=1:height(acceptance)
        if acceptance.status(row)=="NOT_RUN"
            acceptance=set_stage_a3_acceptance_result(acceptance, ...
                acceptance.test_id(row),"BLOCKED", ...
                "not completed after "+failureId, ...
                "dependency blocked by first failure","run_manifest.json");
        end
    end
    write_table_csv_17g(context.acceptance_results_path,acceptance);
catch
end
try
    issues=append_stage_a3_issue(issues,context,failureId, ...
        first_failure_layer(exception),first_failure_object(exception), ...
        "Stage A3 formal run failed",exception.message, ...
        "See exception and persisted evidence", ...
        "Fix the first failing layer and create a new unique run", ...
        "OPEN","run_manifest.json");
    write_table_csv_17g(context.issue_log_path,issues);
catch
end
try
    generate_stage_a3_failure_report(context,exception,issues,acceptance);
catch
end
latestHashPath=hashPath; latestHashRelative="acceptance/evidence_hashes.csv";
try
    if ~isfile(hashPath)
        write_stage_a3_evidence_hashes(context);
    else
        write_stage_a3_failure_evidence_addendum(context);
        latestHashPath=fullfile(context.acceptance_dir, ...
            "evidence_hashes_failure_addendum.csv");
        latestHashRelative="acceptance/evidence_hashes_failure_addendum.csv";
    end
catch
end
try
    manifest=jsondecode(fileread(context.run_manifest_path));
    if string(manifest.status)=="RUNNING"
        updates=struct("fatal_error_identifier",exception.identifier, ...
            "fatal_error_message",exception.message, ...
            "first_failed_layer",first_failure_layer(exception), ...
            "first_failed_object",first_failure_object(exception));
        if isfile(latestHashPath)
            updates.evidence_hashes=char(latestHashRelative);
            updates.evidence_hashes_sha256=compute_sha256_file(latestHashPath);
            if ~strcmp(char(latestHashPath),char(hashPath))
                updates.prior_evidence_hashes="acceptance/evidence_hashes.csv";
                updates.prior_evidence_hashes_sha256=compute_sha256_file(hashPath);
            end
        end
        report=fullfile(context.reports_dir,"阶段A3_失败与首层定位报告.docx");
        if isfile(report)
            updates.reports=struct("failure",relative_run_path(report,context.root));
        end
        finalize_run_manifest(context,"FAIL_RETRYABLE",updates);
    end
catch
end
end
function value=first_failure_test_id(exception)
message=string(exception.message);
token=regexp(message,"test_id '([^']+)'",'tokens','once');
if ~isempty(token)
    value=string(token{1});
elseif contains(exception.identifier,"tests")
    value="SA3-TESTS";
elseif contains(exception.identifier,"artifacts")
    value="SA3-ARTIFACTS";
elseif contains(exception.identifier,"report")
    value="SA3-REPORT";
elseif contains(exception.identifier,"numeric")
    value="SA3-EQ-002";
else
    value="SA3-RUN";
end
end
function value=first_failure_layer(exception)
message=string(exception.message);
token=regexp(message,"layer '([^']+)'",'tokens','once');
if ~isempty(token)
    value=string(token{1});
elseif contains(exception.identifier,"tests")
    value="automated_tests";
elseif contains(exception.identifier,"artifacts")
    value="artifact_persistence";
elseif contains(exception.identifier,"report")
    value="report_generation";
else
    value="formal_run_orchestration";
end
end
function value=first_failure_object(exception)
message=string(exception.message);
token=regexp(message,"object '([^']+)'",'tokens','once');
if ~isempty(token)
    value=string(token{1});
else
    value=exception.identifier;
end
end
function value=relative_run_path(pathValue,runRoot)
pathValue=string(char(java.io.File(char(pathValue)).getCanonicalPath()));
runRoot=string(char(java.io.File(char(runRoot)).getCanonicalPath()));
value=replace(extractAfter(pathValue,strlength(runRoot)+1),'\','/');
end
function cleanup_staging(pathValue)
if strlength(string(pathValue))>0&&isfolder(pathValue)
    try
        rmdir(pathValue,'s');
    catch
    end
end
end
function preserve_candidate_file(source,target)
try
    if isfile(source)&&~isfile(target)&&~isfolder(target)
        movefile(source,target);
    end
catch
end
