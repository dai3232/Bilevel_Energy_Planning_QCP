function result = main_stage_A4_iteration24_scaling_stress()
%MAIN_STAGE_A4_ITERATION24_SCALING_STRESS Run the independent stress test.
%
% This entry creates one unique, non-overwriting diagnostic run.  PASS
% means only that the frozen iteration-24 direction is stabilized by local
% symmetric diagonal congruence scaling plus stable-v2 retained-factor
% refinement.  It does not update an IPM state or mark Stage A4 as passed.

projectRoot = string(fileparts(mfilename("fullpath")));
addpath(projectRoot);
addpath(genpath(fullfile(projectRoot,"src")));
addpath(fullfile(projectRoot,"tests"));

preflight = assert_stage_a4_3_preflight(projectRoot);
assert(preflight.passed && preflight.stage_id=="stage_A4" && ...
    preflight.stage_status=="READY", ...
    "stageA4:scaleStress:Preflight", ...
    "The scaling stress preflight did not pass.");
[inputHashes,inputPass] = verify_input_hashes(projectRoot);
stressConfig = ...
    load_stage_a4_iteration24_scaling_stress_configuration(projectRoot);
environment = inspect_stage_a4_environment();
blocking = logical(environment.blocking);
environmentPass = all(string(environment.status(blocking))=="PASS");
assert(inputPass && environmentPass, ...
    "stageA4:scaleStress:BlockedExternal", ...
    "The stress test requires controlled inputs and MATLAB.");

historicalBefore = snapshot_stage_a4_historical_runs(projectRoot);
commandText = ...
    "matlab -batch ""result="+ ...
    "main_stage_A4_iteration24_scaling_stress(); "+ ...
    "assert(strcmp(result.stress_status,'PASS'));""";
metadata = struct( ...
    "run_purpose", ...
        "iteration24_local_congruence_scaling_numerical_stability_stress_test", ...
    "milestone","A4-ITER24-SCALE-STRESS", ...
    "parent_run_id","20260728_112548_stage_A4_1f3836ca", ...
    "authority_revision",23, ...
    "attempted_iteration",24, ...
    "actual_execution_command",char(commandText), ...
    "recursive_route", ...
        "stable_v2_with_local_symmetric_diagonal_congruence", ...
    "equilibration_passes",8, ...
    "recursive_refinement_max_passes",3, ...
    "primary_recursive_direction_solve_count",2, ...
    "primary_complete_kkt_audit_solve_count",1, ...
    "state_update_count",0, ...
    "formal_a4_run",false, ...
    "full_ipm_executed",false, ...
    "optimization_executed",false, ...
    "parallel_executed",false, ...
    "stage_b_entered",false, ...
    "complete_kkt_role","independent_audit_only", ...
    "automatic_symmetrization_used",false, ...
    "regularization_used",false, ...
    "full_kkt_direction_fallback_used",false, ...
    "a4_pass_claimed",false);
runId = make_run_id(projectRoot,preflight.git_commit);
context = create_run_context(projectRoot,"stage_A4", ...
    "RunId",runId, ...
    "ModelContractVersion","v1.0", ...
    "InputHashes",input_hash_object(inputHashes), ...
    "EffectiveConfigPath",fullfile(projectRoot,"config", ...
        "stage_A4_iteration24_scaling_stress.yaml"), ...
    "ManifestMetadata",metadata);
assert(string(compute_sha256_file(context.effective_config_path))== ...
    stressConfig.sha256, ...
    "stageA4:scaleStress:EffectiveConfigHash", ...
    "The run-local effective_config.yaml does not match the executed YAML.");

write_table_csv_17g_atomic(context.input_hashes_csv_path,inputHashes);
environment = addvars(environment, ...
    repmat(string(context.run_id),height(environment),1), ...
    'Before',1,'NewVariableNames','run_id');
write_table_csv_17g_atomic(context.environment_csv_path,environment);
write_table_csv_17g_atomic( ...
    fullfile(context.root,"historical_runs_before.csv"),historicalBefore);
diagnosticsDirectory = fullfile(context.root,"diagnostics");
ensure_directory(diagnosticsDirectory);
consolePath = fullfile(diagnosticsDirectory,"matlab_console.log");
diary(consolePath);
diaryGuard = onCleanup(@()diary("off"));

try
    fprintf("PRIMARY_STRESS_BEGIN run_id=%s\n",context.run_id);
    stress = run_stage_a4_iteration24_scaling_stress(projectRoot, ...
        AuthorityRunId=stressConfig.authority_run_id, ...
        ExpectedStateRevision= ...
            stressConfig.authority_state_revision, ...
        EquilibrationPasses=stressConfig.equilibration_passes, ...
        ResidualRefinementMaxPasses= ...
            stressConfig.recursive_refinement_max_passes, ...
        DirectionTolerance= ...
            stressConfig.direction_relative_engineering_tolerance, ...
        RecursiveResidualTolerance= ...
            stressConfig. ...
            recursive_full_kkt_residual_engineering_tolerance, ...
        FullResidualTolerance= ...
            stressConfig.full_kkt_audit_residual_tolerance, ...
        SymmetryTolerance= ...
            stressConfig.symmetry_relative_tolerance);
    assert(stress.pass && stress.status=="PASS", ...
        "stageA4:scaleStress:StressFailed", ...
        "The numerical-stability stress result did not pass.");
    exported = export_stage_a4_iteration24_scaling_stress( ...
        context,stress,CommandText=commandText);
    assert(exported.all_blocking_pass, ...
        "stageA4:scaleStress:AcceptanceFailed", ...
        "One or more stress acceptance rows failed.");

    fprintf("PRIMARY_STRESS_COMPLETE_BEFORE_TESTS\n");
    % The fixed-suite helper owns its own diary and closes it reliably on
    % both success and failure.  Close the primary diary before entering it,
    % then explicitly resume the primary log for finalization markers.
    diary("off");
    clear diaryGuard
    testCommand = ...
        "in_process: run_stage_A4_ITER24_scaling_stress_tests("+ ...
        "EvidenceDirectory="""+string(context.tests_dir)+""", "+ ...
        "CommandText=<this invocation>)";
    testReproductionCommand = ...
        "matlab -batch ""addpath('tests'); evidence="+ ...
        "run_stage_A4_ITER24_scaling_stress_tests("+ ...
        "EvidenceDirectory='"+ ...
        replace(string(context.tests_dir),"'","''")+"',"+ ...
        "CommandText='"+testCommand+"'); "+ ...
        "assert(evidence.all_pass);""";
    write_text(fullfile(context.tests_dir,"reproduction_command.txt"), ...
        testReproductionCommand);
    testEvidence = run_stage_A4_ITER24_scaling_stress_tests( ...
        EvidenceDirectory=string(context.tests_dir), ...
        CommandText=testCommand);
    diary(consolePath);
    diaryGuard = onCleanup(@()diary("off"));
    fprintf("POST_TEST_FINALIZATION_RESUMED\n");
    historicalAudit = compare_stage_a4_historical_runs( ...
        projectRoot,historicalBefore,string(context.run_id));
    write_json_file(fullfile(context.root, ...
        "historical_runs_audit.json"),historicalAudit);
    [reportPath,reportValidation] = ...
        generate_stage_a4_iteration24_scaling_stress_report(context);

    clear diaryGuard
    hashes = write_evidence_hash_manifest(context);
    tests = testEvidence.summary;
    hour3 = stress.hourly_factor_audit( ...
        stress.hourly_factor_audit.day==14 & ...
        stress.hourly_factor_audit.hour==3,:);
    updates = struct( ...
        "stress_status","PASS", ...
        "stage_a4_status","READY", ...
        "a4_pass_claimed",false, ...
        "state_update_count_observed",0, ...
        "unscaled_failure_reproduced",true, ...
        "hour3_original_numeric_rank", ...
            double(hour3.original_numeric_rank), ...
        "hour3_scaled_numeric_rank", ...
            double(hour3.scaled_numeric_rank), ...
        "hour3_dimension",double(hour3.dimension), ...
        "hour3_original_condition_2", ...
            double(hour3.original_condition_2), ...
        "hour3_scaled_condition_2", ...
            double(hour3.scaled_condition_2), ...
        "direction_relative_error", ...
            stress.equivalence.direction_relative_error, ...
        "xi_direction_relative_error", ...
            stress.equivalence.component_relative_errors.xi, ...
        "y_direction_relative_error", ...
            stress.equivalence.component_relative_errors.y, ...
        "l_direction_relative_error", ...
            stress.equivalence.component_relative_errors.l, ...
        "z_direction_relative_error", ...
            stress.equivalence.component_relative_errors.z, ...
        "recursive_full_kkt_relative_residual", ...
            stress.equivalence.recursive_kkt_relative_residual, ...
        "full_kkt_audit_relative_residual", ...
            stress.equivalence.full_kkt_relative_residual, ...
        "maximum_day_response_symmetry_relative", ...
            stress.maximum_day_response_symmetry_relative, ...
        "deterministic_repeat_exact", ...
            stress.determinism.direction_exact, ...
        "no_full_direction_fallback", ...
            stress.no_full_direction_fallback, ...
        "test_total",double(tests.test_total), ...
        "test_passed",double(tests.test_passed), ...
        "test_failed",double(tests.test_failed), ...
        "test_incomplete",double(tests.test_incomplete), ...
        "report_path",relative_path(context.root,reportPath), ...
        "report_structure_validated",isempty(reportValidation.errors), ...
        "historical_runs_unchanged",historicalAudit.passed, ...
        "evidence_sha256_manifest", ...
            "acceptance/evidence_sha256.csv", ...
        "evidence_sha256_manifest_sha256", ...
            char(compute_sha256_file(hashes.path)), ...
        "evidence_file_count",height(hashes.table), ...
        "next_action", ...
            "user review; do not automatically resume formal A4");
    finalManifest = finalize_run_manifest(context,"PASS",updates);
    result = struct( ...
        "run_id",string(context.run_id), ...
        "run_path",string(context.root), ...
        "stress_status","PASS", ...
        "manifest_status",string(finalManifest.status), ...
        "summary",exported.summary, ...
        "test_summary",tests, ...
        "report_path",string(reportPath), ...
        "evidence_sha256_path",string(hashes.path), ...
        "stage_status","READY", ...
        "stage_a4_pass_claimed",false, ...
        "state_update_count",0);
    print_summary(result);
catch cause
    clear diaryGuard
    preserve_failure(context,cause);
    rethrow(cause)
end
end

function hashes = write_evidence_hash_manifest(context)
target = fullfile(context.acceptance_dir,"evidence_sha256.csv");
assert(~isfile(target)&&~isfolder(target), ...
    "stageA4:scaleStress:EvidenceHashExists", ...
    "Refusing to overwrite %s.",target);
entries = dir(fullfile(context.root,"**","*"));
entries = entries(~[entries.isdir]);
absolute = strings(0,1);
relative = strings(0,1);
for k=1:numel(entries)
    pathValue = string(fullfile(entries(k).folder,entries(k).name));
    rel = relative_path(context.root,pathValue);
    if rel=="run_manifest.json" || ...
            rel=="acceptance/evidence_sha256.csv"
        continue
    end
    absolute(end+1,1)=pathValue; %#ok<AGROW>
    relative(end+1,1)=rel; %#ok<AGROW>
end
[relative,order]=sort(relative);
absolute=absolute(order);
sha256=strings(numel(absolute),1);
bytes=zeros(numel(absolute),1);
for k=1:numel(absolute)
    sha256(k)=compute_sha256_file(absolute(k));
    info=dir(absolute(k)); bytes(k)=info.bytes;
end
tableValue=table(relative,bytes,sha256, ...
    'VariableNames',{'relative_path','bytes','sha256'});
write_table_csv_17g_atomic(target,tableValue);
hashes=struct("path",string(target),"table",tableValue);
end

function preserve_failure(context,cause)
try
    failurePath=fullfile(context.issues_dir,"stress_failure.json");
    if ~isfile(failurePath)&&~isfolder(failurePath)
        value=struct("identifier",cause.identifier, ...
            "message",cause.message, ...
            "report",getReport(cause,"extended","hyperlinks","off"));
        write_json_file(failurePath,value);
    end
    manifest=jsondecode(fileread(context.run_manifest_path));
    if string(manifest.status)=="RUNNING"
        finalize_run_manifest(context,"FAIL_RETRYABLE",struct( ...
            "stress_status","FAIL_RETRYABLE", ...
            "stage_a4_status","READY", ...
            "a4_pass_claimed",false, ...
            "failure_identifier",cause.identifier, ...
            "failure_message",cause.message, ...
            "state_update_count_observed",0));
    end
catch
    % Preserve the original exception and every partial artifact.
end
end

function print_summary(result)
s=result.summary;
fprintf("A4 iteration-24 scaling stress run_id=%s status=%s\n", ...
    result.run_id,result.stress_status);
fprintf("hour3 rank=%d -> %d/%d cond2=%.17g -> %.17g\n", ...
    s.hour3_original_rank,s.hour3_scaled_rank,s.hour3_dimension, ...
    s.hour3_original_condition_2,s.hour3_scaled_condition_2);
fprintf("direction=%.17g recursive_kkt=%.17g full_kkt=%.17g\n", ...
    s.direction_relative_error, ...
    s.recursive_full_kkt_relative_residual, ...
    s.full_kkt_audit_relative_residual);
fprintf("Stage A4 remains READY; state updates=0; formal A4 not run.\n");
end

function value=input_hash_object(inputHashes)
names = string(inputHashes.fileName);
baseMask = names=="基础参数.xlsx";
timeMask = names=="输入数据.xlsx";
assert(nnz(baseMask)==1 && nnz(timeMask)==1, ...
    "stageA4:scaleStress:InputHashName", ...
    "Controlled input hashes must be selected by file name.");
value=struct( ...
    "base_parameters",char(string(inputHashes.actualSHA256(baseMask))), ...
    "timeseries",char(string(inputHashes.actualSHA256(timeMask))));
end

function value=relative_path(root,pathValue)
value=replace(erase(string(pathValue),string(root)+filesep),"\","/");
end

function ensure_directory(pathValue)
if isfolder(pathValue), return; end
[created,message]=mkdir(pathValue);
assert(created,"stageA4:scaleStress:DirectoryCreate", ...
    "Could not create %s: %s",pathValue,message);
end

function runId=make_run_id(root,commit)
stamp=string(datetime("now","TimeZone","Asia/Shanghai", ...
    "Format","yyyyMMdd_HHmmss"));
base=stamp+"_stage_A4_ITER24_SCALE_STRESS_"+extractBefore(commit,9);
runId=base;
suffix=1;
while isfolder(fullfile(root,"runs",runId)) || ...
        isfile(fullfile(root,"runs",runId))
    suffix=suffix+1;
    runId=base+"_"+compose("%03d",suffix);
end
end
