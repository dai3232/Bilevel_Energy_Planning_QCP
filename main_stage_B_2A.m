    "index",fullfile(context.matrices_dir,"stage_b2a_index.mat"), ...
    "linearization",fullfile(context.matrices_dir, ...
        "stage_b2a_linearization.mat"), ...
    "kkt",fullfile(context.matrices_dir,"stage_b2a_full_kkt.mat"));
for pathValue = string(struct2cell(paths)).'
    assert(~isfile(pathValue)&&~isfolder(pathValue), ...
        "stageB2A:ArtifactExists","Refusing to overwrite %s.",pathValue);
end
save_mat_artifact(paths.index,"index",index,"state",state);
save_mat_artifact(paths.linearization,"linearization",lin);
save_mat_artifact(paths.kkt,"matrix",kkt.matrix,"rhs",kkt.rhs, ...
    "linearization_identity",kkt.linearization_identity, ...
    "slices",kkt.slices,"blocks",kkt.blocks,"symmetry",kkt.symmetry, ...
    "execution",kkt.execution);
end

function value = build_matrix_manifest(context,lin,kkt,paths)
matrix_name = ["objective_H";"lagrangian_H";"A";"G";"full_KKT"];
row_count = [size(lin.objective.hessian,1);size(lin.H,1); ...
    size(lin.A,1);size(lin.G,1);size(kkt.matrix,1)];
column_count = [size(lin.objective.hessian,2);size(lin.H,2); ...
    size(lin.A,2);size(lin.G,2);size(kkt.matrix,2)];
nonzero_count = [nnz(lin.objective.hessian);nnz(lin.H); ...
    nnz(lin.A);nnz(lin.G);nnz(kkt.matrix)];
is_sparse = true(5,1);
artifact_path = ["matrices/stage_b2a_linearization.mat"; ...
    "matrices/stage_b2a_linearization.mat"; ...
    "matrices/stage_b2a_linearization.mat"; ...
    "matrices/stage_b2a_linearization.mat"; ...
    "matrices/stage_b2a_full_kkt.mat"];
sha256 = [repmat(compute_sha256_file(paths.linearization),4,1); ...
    compute_sha256_file(paths.kkt)];
linearization_identity = repmat(string(lin.identity),5,1);
assembled = true(5,1);
solved = false(5,1);
status = repmat("PASS",5,1);
run_id = repmat(string(context.run_id),5,1);
value = table(run_id,matrix_name,row_count,column_count,nonzero_count, ...
    is_sparse,artifact_path,sha256,linearization_identity,assembled, ...
    solved,status);
end

