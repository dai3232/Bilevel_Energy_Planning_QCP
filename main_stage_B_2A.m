function result = main_stage_B_2A(options)
%MAIN_STAGE_B_2A Run the assemble-only Stage B-2A structure audit.
%
% The entry point appends 56 daily hydro-water inequalities, builds one
% shared nonlinear linearization, and assembles the full sparse KKT.  It
% deliberately performs no KKT solve, recursive direction, Newton step,
% IPM iteration, optimization, state update, or parallel execution.

arguments
    options.ProjectRoot (1,1) string = ""
    options.RunId (1,1) string = ""
end

projectRoot = options.ProjectRoot;
if strlength(strtrim(projectRoot))==0
    projectRoot = string(fileparts(mfilename("fullpath")));
end
projectRoot = string(java.io.File(char(projectRoot)).getCanonicalPath());
addpath(genpath(fullfile(projectRoot,"src")));
addpath(fullfile(projectRoot,"tests"));

config = load_stage_b2a_configuration(projectRoot);
assert_clean_implementation_commit(projectRoot);
[inputHashes,inputHashesPass] = verify_input_hashes(projectRoot);
assert(inputHashesPass,"stageB2A:InputHashMismatch", ...
    "Controlled input SHA256 verification failed.");
implementationCommit = git_commit(projectRoot);
shortCommit = extractBefore(implementationCommit,9);
runId = choose_run_id(projectRoot,options.RunId,shortCommit);
actualCommand = "matlab -batch ""result=main_stage_B_2A(); " + ...
    "disp(result.run_id); assert(strcmp(char(result.status),'PASS'));""";
metadata = struct( ...
    "run_purpose",char(config.run_purpose), ...
    "milestone","B-2A", ...
    "implementation_commit",char(implementationCommit), ...
    "parent_run_id","20260803_123004_stage_B_1_fcccf11d", ...
    "historical_baseline_commit", ...
        "952feb4599a433947811d8837da8aea9e3fbd41a", ...
    "actual_test_command",char(actualCommand), ...
    "data_window_days",config.days, ...
    "data_window_hours",config.hours, ...
    "hydro_ids",config.hydro_ids, ...
    "water_bound_order",char(config.water_bound_order), ...
    "optimization_executed",false, ...
    "a1_solver_executed",false, ...
    "full_kkt_assembled",false, ...
    "full_kkt_solved",false, ...
    "recursive_direction_executed",false, ...
    "newton_direction_count",0, ...
    "full_ipm_executed",false, ...
    "state_update_executed",false, ...
    "parallel_executed",false, ...
    "stage_b_complete",false, ...
    "stage_c1_entered",false, ...
    "annual_scope_executed",false, ...
    "thermal_second_pass_enabled",false, ...
    "water_constraints_connected_to_linearization",false, ...
    "water_constraints_connected_to_full_kkt",false, ...
    "milestone_status","RUNNING");
context = create_run_context(projectRoot,"stage_B", ...
    "RunId",runId,"ModelContractVersion","v1.0", ...
    "InputHashes",input_hash_object(inputHashes), ...
    "EffectiveConfigPath",fullfile(projectRoot,"config","stage_B.yaml"), ...
    "ManifestMetadata",metadata);
diagnosticsDir = fullfile(context.root,"diagnostics");
ensure_directory(diagnosticsDir);

result = struct("run_id",string(context.run_id), ...
    "run_path",string(context.root),"status","RUNNING", ...
    "manifest",struct(),"report_path","","error_identifier","");
try
    environment = inspect_stage_b2a_environment();
    environment = addvars(environment,repmat(string(context.run_id), ...
        height(environment),1),'Before',1,'NewVariableNames','run_id');
    write_new_table(context.environment_csv_path,environment);
    assert(all(string(environment.status(logical(environment.blocking)))=="PASS"), ...
        "stageB2A:Environment","A blocking environment audit failed.");
    write_new_table(context.input_hashes_csv_path, ...
        input_hash_table(inputHashes,context.run_id));

    data = load_project_data(projectRoot);
    waterInput = build_stage_b1_water_input_audit(data,context.run_id);
    assert(height(waterInput)==28 && all(waterInput.status=="PASS"), ...
        "stageB2A:WaterInput","The 28-row water input baseline failed.");
    write_new_table(fullfile(diagnosticsDir,"water_input_audit.csv"),waterInput);

    index = build_stage_b_index(data,config,"RunId",string(context.run_id));
    state = initialize_stage_b2a_state(data,index,config);
    linearization = build_stage_b_multiday_linearization( ...
        state,data,index,config);
    fullKkt = assemble_stage_b_multiday_full_kkt(linearization,config);
    audits = build_stage_b2a_audits( ...
        data,index,linearization,fullKkt,config);
    assert(all(audits.water_constraint_index.status=="PASS") && ...
        all(audits.water_constraint_derivative.status=="PASS") && ...
        all(audits.linearization_identity.status=="PASS") && ...
        all(audits.lagrangian_hessian.status=="PASS") && ...
        all(audits.full_kkt_structure.status=="PASS"), ...
        "stageB2A:Audits","One or more B-2A structure audits failed.");

    persist_index_artifacts(context,index);
    write_new_table(fullfile(diagnosticsDir, ...
        "water_constraint_index_audit.csv"), ...
        audits.water_constraint_index);
    write_new_table(fullfile(diagnosticsDir, ...
        "water_constraint_derivative_audit.csv"), ...
        audits.water_constraint_derivative);
    write_new_table(fullfile(diagnosticsDir,"full_kkt_structure.csv"), ...
        audits.full_kkt_structure);
    write_new_table(fullfile(diagnosticsDir,"linearization_identity.csv"), ...
        audits.linearization_identity);
    write_new_table(fullfile(diagnosticsDir, ...
        "lagrangian_hessian_audit.csv"),audits.lagrangian_hessian);
    write_new_table(fullfile(diagnosticsDir, ...
        "water_constraint_hessian_triplets.csv"), ...
        linearization.constraints.water.hessian_triplets);

    matPaths = persist_mat_artifacts(context,index,state,linearization,fullKkt);
    matrixManifest = build_matrix_manifest(context,linearization,fullKkt,matPaths);
    write_new_table(context.matrix_manifest_path,matrixManifest);

    acceptance = make_acceptance(context,audits,fullKkt,config);
    write_new_table(context.acceptance_results_path,acceptance);
    physicalAudit = make_physical_audit(context);
    write_new_table(fullfile(context.acceptance_dir,"physical_audit.csv"), ...
        physicalAudit);
    issues = empty_issue_log();
    write_new_table(context.issue_log_path,issues);
    decision = table(string(context.run_id),"B-2A", ...
        "READY_FOR_REVIEW", ...
        "56 water inequalities, unified linearization, and full sparse KKT structure passed.", ...
        "Stage B remains READY; direction equivalence and physical optimization remain NOT_RUN.", ...
        'VariableNames',{'run_id','milestone','status','conclusion','next_action'});
    write_new_table(context.decision_log_path,decision);

    update_running_run_manifest(context,struct( ...
        "water_constraints_connected_to_linearization",true, ...
        "water_constraints_connected_to_full_kkt",true, ...
        "full_kkt_assembled",true, ...
        "water_inequality_count",height(index.water_constraint_index), ...
        "primal_dimension",linearization.counts.primal, ...
        "equality_dimension",linearization.counts.equalities, ...
        "inequality_dimension",linearization.counts.inequalities, ...
        "full_kkt_dimension",fullKkt.dimension, ...
        "full_kkt_nnz",fullKkt.nnz, ...
        "hessian_nnz",nnz(linearization.H), ...
        "hessian_symmetry_relative", ...
            linearization.lagrangian_hessian_symmetry_relative, ...
        "linearization_identity_error", ...
            linearization.linearization_identity_error, ...
        "linearization_identity",char(linearization.identity), ...
        "raw_full_kkt_symmetry_status", ...
            char(fullKkt.symmetry.raw_full_kkt_status), ...
        "raw_full_kkt_symmetry_relative", ...
            fullKkt.symmetry.raw_full_kkt_relative, ...
        "blocking_acceptance_total",6, ...
        "blocking_acceptance_pass",6, ...
        "not_run_acceptance_ids",["SB-EQ-001","SB-PHY-001"]));

    b2aCommand = "run_stage_B_2A_tests(""EvidenceDirectory"","""+ ...
        replace(string(context.tests_dir),'"','""')+""")";
    b2aTests = run_stage_B_2A_tests( ...
        "EvidenceDirectory",string(context.tests_dir), ...
        "CommandText",b2aCommand);
    b1FixedDir = fullfile(context.tests_dir,"b1_fixed");
    b1Fixed = run_stage_B_1_tests( ...
        "EvidenceDirectory",string(b1FixedDir), ...
        "CommandText","run_stage_B_1_tests() [B-2A regression]");
    b1AffectedDir = fullfile(context.tests_dir,"b1_affected");
    b1Affected = run_stage_B_1_affected_regressions( ...
        "EvidenceDirectory",string(b1AffectedDir), ...
        "CommandText","run_stage_B_1_affected_regressions() [B-2A regression]");
    a4StructureDir = fullfile(context.tests_dir,"a4_structure");
    a4Structure = run_stage_B_2A_stage_A_regressions( ...
        "EvidenceDirectory",string(a4StructureDir), ...
        "CommandText","run_stage_B_2A_stage_A_regressions()");
    assert(b2aTests.all_pass && b1Fixed.all_pass && ...
        b1Affected.all_pass && a4Structure.all_pass, ...
        "stageB2A:Tests","A fixed or regression suite failed.");

    static = run_stage_b2a_static_checks(projectRoot);
    write_new_table(fullfile(context.tests_dir,"static_check_summary.csv"), ...
        static.code_analyzer);
    write_new_table(fullfile(context.tests_dir, ...
        "forbidden_execution_audit.csv"),static.forbidden_execution);
    assert(static.all_pass,"stageB2A:Static", ...
        "Code Analyzer or forbidden-execution audit failed.");
    update_running_run_manifest(context,struct( ...
        "tests_executed",true, ...
        "b2a_test_total",b2aTests.summary.test_total, ...
        "b2a_test_passed",b2aTests.summary.test_passed, ...
        "b1_fixed_test_total",b1Fixed.summary.test_total, ...
        "b1_fixed_test_passed",b1Fixed.summary.test_passed, ...
        "b1_affected_test_total",b1Affected.summary.test_total, ...
        "b1_affected_test_passed",b1Affected.summary.test_passed, ...
        "stage_a_structure_regression_total", ...
            a4Structure.summary.test_total, ...
        "stage_a_structure_regression_passed", ...
            a4Structure.summary.test_passed, ...
        "test_total",b2aTests.summary.test_total+ ...
            b1Fixed.summary.test_total+b1Affected.summary.test_total+ ...
            a4Structure.summary.test_total, ...
        "test_failed",0,"test_incomplete",0, ...
        "code_analyzer_blocking_findings",static.blocking_findings, ...
        "forbidden_execution_pass",true));

    report = generate_stage_b2a_report(context.root);
    [reportValid,reportDetails] = validate_stage_b2a_report(context.root);
    validation = table(string(context.run_id), ...
        "stage_B_2A_water_constraint_linearization_full_kkt", ...
        string(report.path),reportValid, ...
        conditional_status(reportValid),string(reportDetails.message), ...
        'VariableNames',{'run_id','report_id','path','valid','status','details'});
    write_new_table(fullfile(context.reports_dir, ...
        "report_structure_validation.csv"),validation);
    assert(reportValid,"stageB2A:Report", ...
        "The Chinese B-2A report failed structural validation: %s", ...
        reportDetails.message);
    reportHash = table("reports/阶段B-2A_水量约束线性化与完整KKT结构报告.docx", ...
        compute_sha256_file(report.path),string(context.run_id),"PASS", ...
        'VariableNames',{'relative_path','sha256','run_id','status'});
    write_new_table(fullfile(context.reports_dir,"report_sha256.csv"),reportHash);
    update_running_run_manifest(context,struct( ...
        "reports_generated",true,"report_structure_validated",true, ...
        "report_relative_path", ...
            "reports/阶段B-2A_水量约束线性化与完整KKT结构报告.docx", ...
        "report_sha256",char(reportHash.sha256), ...
        "milestone_status","READY_FOR_REVIEW"));

    evidence = write_evidence_hashes(context.root, ...
        fullfile(context.acceptance_dir,"evidence_hashes.csv"));
    manifest = finalize_run_manifest(context,"PASS",struct( ...
        "milestone_status","READY_FOR_REVIEW", ...
        "stage_b_complete",false,"stage_c1_entered",false, ...
        "evidence_hashes","acceptance/evidence_hashes.csv", ...
        "evidence_hashes_sha256",char(compute_sha256_file( ...
            fullfile(context.acceptance_dir,"evidence_hashes.csv"))), ...
        "evidence_file_count",height(evidence)));
    result.status = string(manifest.status);
    result.manifest = manifest;
    result.report_path = string(report.path);
    result.acceptance = acceptance;
catch cause
    issue = failure_issue(context,cause);
    try
        write_table_csv_17g_atomic(string(context.issue_log_path),issue);
    catch
    end
    finalStatus = "FAIL_RETRYABLE";
    if contains(string(cause.identifier),["Environment","InputHash"])
        finalStatus = "BLOCKED_EXTERNAL";
    elseif contains(string(cause.identifier),"ModelDecision")
        finalStatus = "NEEDS_MODEL_DECISION";
    end
    try
        manifest = jsondecode(fileread(context.run_manifest_path));
        if string(manifest.status)=="RUNNING"
            manifest = finalize_run_manifest(context,finalStatus,struct( ...
                "milestone_status",char(finalStatus), ...
                "stage_b_complete",false,"stage_c1_entered",false, ...
                "failure_identifier",char(string(cause.identifier)), ...
                "failure_message",char(string(cause.message))));
        end
    catch
        manifest = struct();
    end
    result.status = finalStatus;
    result.manifest = manifest;
    result.error_identifier = string(cause.identifier);
    result.error_message = string(cause.message);
end
end

