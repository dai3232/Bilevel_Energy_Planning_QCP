function value = write_evidence_hashes(runRoot,pathValue)
assert(~isfile(pathValue)&&~isfolder(pathValue), ...
    "stageB2A:EvidenceHashExists","Refusing to overwrite hash evidence.");
listing = dir(fullfile(runRoot,"**","*"));
listing = listing(~[listing.isdir]);
relative_path = strings(0,1); sha256 = strings(0,1); bytes = zeros(0,1);
for k = 1:numel(listing)
    absolute = string(fullfile(listing(k).folder,listing(k).name));
    relative = replace(extractAfter(absolute,string(runRoot)+filesep),filesep,"/");
    if relative=="acceptance/evidence_hashes.csv" || relative=="run_manifest.json"
        continue
    end
    relative_path(end+1,1) = relative; %#ok<AGROW>
    sha256(end+1,1) = compute_sha256_file(absolute); %#ok<AGROW>
    bytes(end+1,1) = listing(k).bytes; %#ok<AGROW>
end
[relative_path,order] = sort(relative_path);
sha256 = sha256(order); bytes = bytes(order);
status = repmat("PASS",numel(relative_path),1);
value = table(relative_path,sha256,bytes,status);
write_new_table(pathValue,value);
end

function value = input_hash_object(hashes)
base = hashes.fileName=="基础参数.xlsx";
series = hashes.fileName=="输入数据.xlsx";
assert(nnz(base)==1&&nnz(series)==1,"stageB2A:InputHashRows", ...
    "Both controlled input rows are required.");
value = struct("base_parameters",char(hashes.actualSHA256(base)), ...
    "timeseries",char(hashes.actualSHA256(series)));
end

function value = input_hash_table(hashes,runId)
n = height(hashes);
value = table(repmat(string(runId),n,1),string(hashes.fileName), ...
    "inputs/raw/"+string(hashes.fileName),double(hashes.expectedBytes), ...
    double(hashes.actualBytes),string(hashes.expectedSHA256), ...
    string(hashes.actualSHA256),string(hashes.status), ...
    'VariableNames',{'run_id','file_name','relative_path', ...
    'expected_bytes','actual_bytes','expectedSHA256','actualSHA256','status'});
end

function assert_clean_implementation_commit(root)
[status,branch] = system(git_command(root,"rev-parse --abbrev-ref HEAD"));
assert(status==0 && strip(string(branch))=="stage_B", ...
    "stageB2A:GitBranch","Formal B-2A must run from branch stage_B.");
[status,changes] = system(git_command(root, ...
    "status --porcelain --untracked-files=no"));
assert(status==0 && strlength(strip(string(changes)))==0, ...
    "stageB2A:GitDirty", ...
    "Formal B-2A run requires a clean tracked worktree.");
end

function value = git_commit(root)
[status,output] = system(git_command(root,"rev-parse HEAD"));
value = lower(strip(string(output)));
assert(status==0 && ~isempty(regexp(value,"^[0-9a-f]{40}$","once")), ...
    "stageB2A:GitCommit","Could not resolve the implementation commit.");
end

function value = git_command(root,arguments)
safe = replace(char(root),'"','\"');
value = string(sprintf('git -c safe.directory="%s" %s', ...
    safe,char(arguments)));
end

function runId = choose_run_id(root,requested,shortCommit)
if strlength(strtrim(requested))>0
    runId = requested;
    assert(~contains(runId,["/","\"]),"stageB2A:RunId", ...
        "Run id must be a leaf name.");
else
    timestamp = string(datetime("now","TimeZone","UTC", ...
        "Format","yyyyMMdd_HHmmss"));
    runId = timestamp+"_stage_B_2A_"+shortCommit;
end
assert(~isfile(fullfile(root,"runs",runId)) && ...
    ~isfolder(fullfile(root,"runs",runId)), ...
    "stageB2A:RunExists","Run path already exists: %s",runId);
end

function ensure_directory(pathValue)
if isfolder(pathValue), return; end
assert(~isfile(pathValue),"stageB2A:DirectoryConflict", ...
    "A file occupies required directory %s.",pathValue);
[created,message] = mkdir(pathValue);
assert(created,"stageB2A:Directory","%s",message);
end

function write_new_table(pathValue,value)
assert(~isfile(pathValue)&&~isfolder(pathValue), ...
    "stageB2A:ArtifactExists","Refusing to overwrite %s.",pathValue);
